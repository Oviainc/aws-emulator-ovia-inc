/// The tag set the rule says the resource `logical_id` of this row ends up carrying, in the
/// stack `stack_name` whose id is `stack_id`.
fn expected_tags(row: &Row, logical_id: &str, stack_name: &str, stack_id: &str) -> BTreeMap<String, String> {
    let mut expected: BTreeMap<String, String> = BTreeMap::new();
    for resource in row.resources {
        if resource.logical_id == logical_id {
            for (key, value) in resource.declared {
                expected.insert((*key).to_string(), (*value).to_string());
            }
        }
    }
    // A stack tag whose key the declaration already states does not displace it.
    for (key, value) in row.stack_tags {
        expected
            .entry((*key).to_string())
            .or_insert_with(|| (*value).to_string());
    }
    // The three CloudFormation records itself, which nothing displaces.
    expected.insert(STACK_NAME_TAG.to_string(), stack_name.to_string());
    expected.insert(STACK_ID_TAG.to_string(), stack_id.to_string());
    expected.insert(LOGICAL_ID_TAG.to_string(), logical_id.to_string());
    expected
}

/// The `Tags.member.N.Key`/`Value` request members a stack-level tag list is.
fn tag_members(tags: &[(&str, &str)]) -> Vec<(String, String)> {
    let mut members = Vec::new();
    for (index, (key, value)) in tags.iter().enumerate() {
        let position = index + 1;
        members.push((format!("Tags.member.{position}.Key"), (*key).to_string()));
        members.push((
            format!("Tags.member.{position}.Value"),
            (*value).to_string(),
        ));
    }
    members
}

/// Every row: `s3vectors ListTagsForResource` on the handle the stack published for each of
/// its S3 Vectors resources answers with the stack's own tags, the declaration's own tags
/// and the three tags CloudFormation records — so the resource names the stack and its place
/// in that stack's template.
#[tokio::test]
async fn a_stack_stamps_its_provenance_onto_the_s3vectors_resources_it_creates() {
    let router = build_router();

    for (index, row) in ROWS.iter().enumerate() {
        let case = row.case;
        let region = row.region;
        let stack_name = format!("s3vectors-provenance-{index}");
        let template = (row.template)();

        let mut members: Vec<(String, String)> = vec![
            ("StackName".to_string(), stack_name.clone()),
            ("TemplateBody".to_string(), template),
        ];
        members.extend(tag_members(row.stack_tags));
        let borrowed: Vec<(&str, &str)> = members
            .iter()
            .map(|(name, value)| (name.as_str(), value.as_str()))
            .collect();
        let (status, body) = cloudformation(&router, region, "CreateStack", &borrowed).await;
        assert_eq!(
            status, 200,
            "case {case:?}: expected HTTP 200 from CreateStack, got {status} with body {body}"
        );

        tokio::time::sleep(PAST_STACK_SPAN).await;
        let (status, described) =
            cloudformation(&router, region, "DescribeStacks", &[("StackName", &stack_name)]).await;
        assert_eq!(
            status, 200,
            "case {case:?}: expected HTTP 200 from DescribeStacks, got {status} with body \
             {described}"
        );
        assert_eq!(
            opt_element(&described, "StackStatus").as_deref(),
            Some("CREATE_COMPLETE"),
            "case {case:?}: expected the stack to reach CREATE_COMPLETE, got {described}"
        );
        let stack_id = opt_element(&described, "StackId").unwrap_or_default();
        assert!(
            stack_id.contains(&stack_name),
            "case {case:?}: expected the reported stack id to name the stack, got \
             {stack_id:?}"
        );

        let (status, resources) = cloudformation(
            &router,
            region,
            "DescribeStackResources",
            &[("StackName", &stack_name)],
        )
        .await;
        assert_eq!(
            status, 200,
            "case {case:?}: expected HTTP 200 from DescribeStackResources, got {status} with \
             body {resources}"
        );
        let reported = physical_ids_of(&resources);

        for resource in row.resources {
            let logical_id = resource.logical_id;
            // The handle the stack publishes for the resource, which for both S3 Vectors
            // types is that resource's own ARN.
            let arn = reported.get(logical_id).cloned().unwrap_or_else(|| {
                panic!("case {case:?}: no physical id for {logical_id:?} in {resources}")
            });

            let (status, held) = vector_resource_tags(&router, region, &arn).await;
            assert_eq!(
                status, 200,
                "case {case:?}: expected HTTP 200 from ListTagsForResource({arn}), got \
                 {status} with {held:?}"
            );
            let expected = expected_tags(row, logical_id, &stack_name, &stack_id);
            assert_eq!(
                held, expected,
                "case {case:?}: expected {logical_id} to carry {expected:?}, got {held:?}"
            );
        }
    }
}

/// The three keys are the resource-to-stack REVERSE LOOKUP: the stack id they carry is the
/// one `DescribeStacks` reports, so a client holding only a vector bucket ARN reaches that
/// stack's own record — and its resources — from the tag read alone.
#[tokio::test]
async fn the_stamped_stack_id_resolves_back_to_the_stack_that_created_the_bucket() {
    let router = build_router();
    let region = "us-east-2";
    let stack_name = "s3vectors-reverse-lookup";
    let template = json!({
        "Resources": {
            "Vectors": {
                "Type": "AWS::S3Vectors::VectorBucket",
                "Properties": { "VectorBucketName": "reverse-lookup-vec" }
            }
        }
    })
    .to_string();

    let (status, body) = cloudformation(
        &router,
        region,
        "CreateStack",
        &[("StackName", stack_name), ("TemplateBody", &template)],
    )
    .await;
    assert_eq!(
        status, 200,
        "expected HTTP 200 from CreateStack, got {status} with body {body}"
    );
    tokio::time::sleep(PAST_STACK_SPAN).await;

    let (_, resources) = cloudformation(
        &router,
        region,
        "DescribeStackResources",
        &[("StackName", stack_name)],
    )
    .await;
    let arn = physical_ids_of(&resources)
        .get("Vectors")
        .cloned()
        .unwrap_or_else(|| panic!("no physical id for \"Vectors\" in {resources}"));

    // Everything the client knows from here on is what the tag read answered.
    let (status, held) = vector_resource_tags(&router, region, &arn).await;
    assert_eq!(
        status, 200,
        "expected HTTP 200 from ListTagsForResource({arn}), got {status} with {held:?}"
    );
    let stamped_id = held.get(STACK_ID_TAG).cloned().unwrap_or_default();
    let stamped_name = held.get(STACK_NAME_TAG).cloned().unwrap_or_default();
    let stamped_logical_id = held.get(LOGICAL_ID_TAG).cloned().unwrap_or_default();

    // The stack id is a handle `DescribeStacks` resolves, and the stack it resolves to is
    // the one the resource belongs to: its name is the stamped name, and the resource it
    // reports under the stamped logical id is the bucket the tag read was made on.
    let (status, described) =
        cloudformation(&router, region, "DescribeStacks", &[("StackName", &stamped_id)]).await;
    assert_eq!(
        status, 200,
        "expected the stamped stack id {stamped_id:?} to resolve, got {status} with body \
         {described}"
    );
    assert_eq!(
        opt_element(&described, "StackName"),
        Some(stamped_name.clone()),
        "expected the stack the stamped id resolves to be {stamped_name:?}, got {described}"
    );
    let (status, resources) = cloudformation(
        &router,
        region,
        "DescribeStackResources",
        &[("StackName", &stamped_id)],
    )
    .await;
    assert_eq!(
        status, 200,
        "expected the stamped stack id to resolve for its resources, got {status} with body \
         {resources}"
    );
    assert_eq!(
        physical_ids_of(&resources).get(&stamped_logical_id),
        Some(&arn),
        "expected the resource at the stamped logical id {stamped_logical_id:?} to be the \
         bucket {arn}, got {resources}"
    );
}
