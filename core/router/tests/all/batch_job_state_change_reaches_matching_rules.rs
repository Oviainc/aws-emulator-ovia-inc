//! A Batch job's state changes reach the EventBridge rules that match them, and no others.
//!
//! The RULE under test: **every status an AWS Batch job MOVES INTO is published once onto
//! the account's DEFAULT EventBridge bus as `source` `aws.batch` / `detail-type`
//! `Batch Job State Change`, carrying that job's own description as the event `detail`
//! and the job's ARN in `resources`; EventBridge then routes it by its CONTENT, so each
//! rule whose `EventPattern` matches the envelope delivers it to that rule's targets and a
//! rule whose pattern does not match receives none of them.** The status the submit itself
//! stored is not a move, so no envelope carries it ("events aren't created for the initial
//! job submission" — the Batch User Guide's "Job state change events"). Source: the
//! EventBridge
//! reference page "AWS Batch events" (`events-ref-batch.html`), which names the source,
//! the detail type and the default bus, and
//! `smithy_query(query="shape", shape="com.amazonaws.batch#JobStatus")` for the statuses a
//! job can take.
//!
//! This runs the path a client runs it over: three services (Batch publishes, EventBridge
//! routes, SQS holds what arrived) reached through the WHOLE emulator — the same
//! `build_router` service set the binary serves — so the in-process publication is claimed
//! and routed by whichever mounted model a client's `events`-scoped call would reach, not
//! by a hand-picked pair of services.
//!
//! The rows differ along what the rule generalises over: WHICH dimension of the envelope
//! the matching rule filters on (the source and detail type alone, the job's queue inside
//! `detail`, the status inside `detail`), WHICH statuses the job therefore takes (left to
//! the clock, or ended by a caller), and whether the target queue carries a resource policy
//! admitting EventBridge. Every row also carries a rule whose pattern names ANOTHER job
//! queue, whose own queue must stay empty — the negative half of the same rule.
//!
//! What is NOT asserted here, because it is asserted elsewhere:
//! `services/service-com-amazonaws-batch-awsbatchv20160810/tests/all/job_state_change_events.rs`
//! pins the same rule over a table of job LIFECYCLES (left to the clock, terminated,
//! cancelled, waiting on a dependency) and pins each published `detail` against what
//! `DescribeJobs` reports for the same job,
//! `services/service-com-amazonaws-batch-awsbatchv20160810/tests/all/job_submission_publishes_no_event.rs`
//! pins the exclusion of the submitted status over a table of first moves, and
//! `core/router/tests/all/events_fan_out_to_each_matched_target.rs` pins the fan-out to
//! several targets of several services. What only this suite can reach is the pair those
//! two leave out: routing a Batch event by its CONTENT (a pattern reaching into `detail`)
//! over the WHOLE mounted service set, where three models resolve to the `events` key and
//! the publication has to be claimed by the one a client's own call reaches.

use std::sync::Arc;
use std::time::Duration;

use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

/// The Region every request below is signed for.
const REGION: &str = "us-west-2";

/// The `source` and `detail-type` AWS Batch publishes a job's state changes under, spelled
/// out here rather than imported from the service crate, so a wrong constant in the
/// implementation cannot make this suite pass. Source: "AWS Batch events".
const BATCH_SOURCE: &str = "aws.batch";
const JOB_STATE_CHANGE: &str = "Batch Job State Change";

/// The bus an Amazon Web Services service's own events go to: "events generated by Amazon
/// Web Services services go to your account's default event bus".
const DEFAULT_BUS: &str = "default";

/// The service principal EventBridge delivers to an SQS target as, which is what a queue's
/// resource policy admits ("for Amazon SQS queues, EventBridge relies on resource-based
/// policies").
const EVENTS_PRINCIPAL: &str = "events.amazonaws.com";

/// How long a row waits for the transitions the clock owes to arrive on a queue before it
/// gives up: far above the span one transition takes, and driven off the messages that have
/// ARRIVED rather than off a fixed sleep, so a slow machine delays a row instead of
/// breaking it.
const DELIVERY_DEADLINE: Duration = Duration::from_secs(20);

/// One poll of a queue inside [`DELIVERY_DEADLINE`].
const POLL_INTERVAL: Duration = Duration::from_millis(25);

/// How long a row leaves the non-matching rule's queue alone before it reads it: longer
/// than the span one transition of this job took to reach the matching rule's queue, so an
/// empty read is evidence the rule was not a delivery target rather than evidence of having
/// looked too early.
const QUIET_SPAN: Duration = Duration::from_millis(750);

/// The whole emulator over one engine, exactly as `core/router/src/lib.rs` assembles it for
/// the binary: Batch publishes through the in-process callback, so WHICH mounted model
/// claims that `events`-scoped call has to be the one a client reaches too.
fn router() -> MultiServiceRouter {
    let engine = aws_emulator_router::new_engine();
    let mut router = aws_emulator_router::build_router(Arc::clone(&engine));
    router.set_request_authentication(false);
    router
}

/// A SigV4 `Authorization` whose credential scope names `service`, which is what routes the
/// request. The signature is never checked: the router above runs with request
/// authentication off.
fn authorization(service: &str) -> String {
    format!(
        "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20260101/{REGION}/{service}/aws4_request, \
         SignedHeaders=host, Signature=0000"
    )
}

/// The status and parsed body of one response.
fn answered(response: &http::Response<Bytes>) -> (u16, Value) {
    let status = response.status().as_u16();
    let parsed = if response.body().is_empty() {
        Value::Null
    } else {
        serde_json::from_slice(response.body()).unwrap_or(Value::Null)
    };
    (status, parsed)
}

/// One `X-Amz-Target` RPC call against the service whose signing name is `signing_name`,
/// which must answer 200.
async fn rpc(
    router: &MultiServiceRouter,
    case: &str,
    signing_name: &str,
    target_prefix: &str,
    json_version: &str,
    operation: &str,
    body: &Value,
) -> Value {
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("{signing_name}.{REGION}.amazonaws.com"))
        .header("authorization", authorization(signing_name))
        .header("content-type", format!("application/x-amz-json-{json_version}"))
        .header("x-amz-target", format!("{target_prefix}.{operation}"))
        .body(Bytes::from(body.to_string()))
        .expect("the test request is well formed");
    let (status, parsed) = answered(&router.dispatch(request).await);
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from {signing_name} {operation}, got {status} with \
         {parsed}"
    );
    parsed
}

/// One EventBridge call (`awsJson1_1`, `AWSEvents.<Operation>`).
async fn events(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    rpc(router, case, "events", "AWSEvents", "1.1", operation, body).await
}

/// One Amazon SQS call (`awsJson1_0`, `AmazonSQS.<Operation>`).
async fn sqs(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    rpc(router, case, "sqs", "AmazonSQS", "1.0", operation, body).await
}

/// One AWS Batch call: a `restJson1` service, so `POST <uri>` with a JSON body.
async fn batch(router: &MultiServiceRouter, case: &str, uri: &str, body: &Value) -> Value {
    let request = http::Request::builder()
        .method("POST")
        .uri(format!("https://batch.{REGION}.amazonaws.com{uri}"))
        .header("host", format!("batch.{REGION}.amazonaws.com"))
        .header("authorization", authorization("batch"))
        .header("content-type", "application/json")
        .body(Bytes::from(body.to_string()))
        .expect("the test request is well formed");
    let (status, parsed) = answered(&router.dispatch(request).await);
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from Batch {uri}, got {status} with {parsed}"
    );
    parsed
}

/// A string member of a response, or a panic naming the case and what came back.
fn member(case: &str, body: &Value, pointer: &str) -> String {
    body.pointer(pointer)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("case {case:?}: expected {pointer} in {body}"))
        .to_string()
}

/// An SQS queue called `name`, created through SQS itself; answers its url and the ARN a
/// rule names it by.
async fn queue(router: &MultiServiceRouter, case: &str, name: &str) -> (String, String) {
    let created = sqs(router, case, "CreateQueue", &json!({"QueueName": name})).await;
    let url = member(case, &created, "/QueueUrl");
    let attributes = sqs(
        router,
        case,
        "GetQueueAttributes",
        &json!({"QueueUrl": &url, "AttributeNames": ["QueueArn"]}),
    )
    .await;
    let arn = member(case, &attributes, "/Attributes/QueueArn");
    (url, arn)
}

/// Let EventBridge send to the queue at `url` on behalf of the rule `rule_arn`, the way a
/// client admits a rule to its queue: a resource policy naming EventBridge's service
/// principal, scoped to that rule.
async fn admit_events(
    router: &MultiServiceRouter,
    case: &str,
    url: &str,
    queue_arn: &str,
    rule_arn: &str,
) {
    let policy = json!({
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "AllowEventBridge",
            "Effect": "Allow",
            "Principal": {"Service": EVENTS_PRINCIPAL},
            "Action": "sqs:SendMessage",
            "Resource": queue_arn,
            "Condition": {"ArnEquals": {"aws:SourceArn": rule_arn}},
        }],
    })
    .to_string();
    sqs(
        router,
        case,
        "SetQueueAttributes",
        &json!({"QueueUrl": url, "Attributes": {"Policy": policy}}),
    )
    .await;
}

/// An ENABLED rule called `name` on the default bus carrying `pattern`, with the queue
/// `queue_arn` as its one target; answers the rule's ARN.
async fn rule(
    router: &MultiServiceRouter,
    case: &str,
    name: &str,
    pattern: &Value,
    queue_arn: &str,
) -> String {
    let put = events(
        router,
        case,
        "PutRule",
        &json!({
            "Name": name,
            "EventBusName": DEFAULT_BUS,
            "EventPattern": pattern.to_string(),
            "State": "ENABLED",
        }),
    )
    .await;
    let rule_arn = member(case, &put, "/RuleArn");
    let targeted = events(
        router,
        case,
        "PutTargets",
        &json!({
            "Rule": name,
            "EventBusName": DEFAULT_BUS,
            "Targets": [{"Id": "t1", "Arn": queue_arn}],
        }),
    )
    .await;
    assert_eq!(
        targeted["FailedEntryCount"],
        json!(0),
        "case {case:?}: every target must be accepted, got {targeted}"
    );
    rule_arn
}

/// Every message now waiting on the queue at `url`, as the parsed event envelopes their
/// bodies carry.
async fn drain(router: &MultiServiceRouter, case: &str, url: &str) -> Vec<Value> {
    let received = sqs(
        router,
        case,
        "ReceiveMessage",
        &json!({"QueueUrl": url, "MaxNumberOfMessages": 10}),
    )
    .await;
    received["Messages"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|message| {
            let raw = message["Body"].as_str().unwrap_or_default();
            serde_json::from_str::<Value>(raw).unwrap_or(Value::Null)
        })
        .collect()
}

/// Collect envelopes off the queue at `url` until `wanted` of them have arrived or
/// [`DELIVERY_DEADLINE`] passes; answers everything that did arrive.
async fn collect(
    router: &MultiServiceRouter,
    case: &str,
    url: &str,
    wanted: usize,
) -> Vec<Value> {
    let started = std::time::Instant::now();
    let mut arrived: Vec<Value> = Vec::new();
    while arrived.len() < wanted && started.elapsed() < DELIVERY_DEADLINE {
        arrived.extend(drain(router, case, url).await);
        if arrived.len() < wanted {
            tokio::time::sleep(POLL_INTERVAL).await;
        }
    }
    arrived
}

/// The `detail.status` of each envelope, sorted: an SQS standard queue makes "a best-effort
/// to preserve order" and nothing here depends on the order, so what is asserted is WHICH
/// transitions arrived, once each.
fn statuses(envelopes: &[Value]) -> Vec<String> {
    let mut found: Vec<String> = envelopes
        .iter()
        .map(|envelope| {
            envelope["detail"]["status"]
                .as_str()
                .unwrap_or_default()
                .to_string()
        })
        .collect();
    found.sort();
    found
}

/// What one row filters on, does to the job, and must therefore see.
struct Row {
    case: &'static str,
    /// The `detail` clause the matching rule's pattern carries beyond the source and the
    /// detail type, built over the submitted job's queue ARN. `None` filters on the source
    /// and detail type alone.
    detail: Option<fn(&str) -> Value>,
    /// Whether the caller ends the job once it has come to rest.
    terminate: bool,
    /// The statuses the matching rule's queue must receive, sorted.
    expected: &'static [&'static str],
}

/// The statuses a job MOVES INTO here: `RUNNABLE` when the clock releases it, and the
/// terminal `FAILED` a caller's `TerminateJob` writes. The status the submit stored is not
/// one of them — no event is created for the submission itself — so a job's stream begins
/// at `RUNNABLE`. Nothing in this emulator places a job on compute capacity, so a job left
/// alone rests in `RUNNABLE`.
const RESTING: &[&str] = &["RUNNABLE"];
const TERMINATED: &[&str] = &["FAILED", "RUNNABLE"];
const RUNNABLE_ONLY: &[&str] = &["RUNNABLE"];

/// RULE: each status a Batch job moves into is published to the default bus and delivered
/// to every rule whose pattern matches the envelope — and to no rule whose pattern does
/// not.
#[tokio::test]
async fn every_job_state_change_reaches_the_rules_that_match_it_and_no_others() {
    let rows = [
        Row {
            case: "the source and detail type alone",
            detail: None,
            terminate: false,
            expected: RESTING,
        },
        Row {
            case: "the job's queue inside the detail, behind a queue policy",
            detail: Some(|queue_arn| json!({"jobQueue": [queue_arn]})),
            terminate: false,
            expected: RESTING,
        },
        Row {
            case: "one status inside the detail",
            detail: Some(|_| json!({"status": ["RUNNABLE"]})),
            terminate: false,
            expected: RUNNABLE_ONLY,
        },
        Row {
            case: "a job the caller terminates",
            detail: Some(|queue_arn| json!({"jobQueue": [queue_arn]})),
            terminate: true,
            expected: TERMINATED,
        },
    ];

    for (index, row) in rows.iter().enumerate() {
        let case = row.case;
        let router = router();

        // The two queues: the one the matching rule targets, and the one only a rule that
        // cannot match targets.
        let (matching_url, matching_arn) = queue(&router, case, &format!("q-match-{index}")).await;
        let (other_url, other_arn) = queue(&router, case, &format!("q-other-{index}")).await;

        // The compute environment, queue and definition a job is submitted against.
        let environment = batch(
            &router,
            case,
            "/v1/createcomputeenvironment",
            &json!({
                "computeEnvironmentName": format!("ce-{index}"),
                "type": "UNMANAGED",
                "state": "ENABLED",
            }),
        )
        .await;
        let environment_arn = member(case, &environment, "/computeEnvironmentArn");
        let job_queue = batch(
            &router,
            case,
            "/v1/createjobqueue",
            &json!({
                "jobQueueName": format!("jq-{index}"),
                "priority": 1,
                "computeEnvironmentOrder": [{"order": 1, "computeEnvironment": environment_arn}],
            }),
        )
        .await;
        let job_queue_arn = member(case, &job_queue, "/jobQueueArn");
        let definition = batch(
            &router,
            case,
            "/v1/registerjobdefinition",
            &json!({
                "jobDefinitionName": format!("jd-{index}"),
                "type": "container",
                "containerProperties": {
                    "image": "busybox",
                    "command": ["echo", "hello"],
                    "resourceRequirements": [
                        {"type": "VCPU", "value": "1"},
                        {"type": "MEMORY", "value": "512"},
                    ],
                },
            }),
        )
        .await;
        let definition_arn = member(case, &definition, "/jobDefinitionArn");

        // The matching rule filters on this row's own dimension; the other rule names a job
        // queue no event of this job can carry, so nothing it targets may be delivered to.
        let mut matching_pattern = json!({
            "source": [BATCH_SOURCE],
            "detail-type": [JOB_STATE_CHANGE],
        });
        if let Some(clause) = row.detail {
            matching_pattern["detail"] = clause(&job_queue_arn);
        }
        let unrelated_queue = format!(
            "arn:aws:batch:{REGION}:{}:job-queue/no-such-queue",
            engine::EMULATOR_ACCOUNT_ID
        );
        let other_pattern = json!({
            "source": [BATCH_SOURCE],
            "detail-type": [JOB_STATE_CHANGE],
            "detail": {"jobQueue": [unrelated_queue]},
        });
        let matching_rule = rule(
            &router,
            case,
            &format!("r-match-{index}"),
            &matching_pattern,
            &matching_arn,
        )
        .await;
        let other_rule = rule(
            &router,
            case,
            &format!("r-other-{index}"),
            &other_pattern,
            &other_arn,
        )
        .await;
        // The grant a rule's queue target needs: EventBridge makes that target's
        // `sqs:SendMessage` as its own service principal and "relies on resource-based
        // policies" for a queue (`PutTargets`), so a queue that has granted it nothing
        // receives nothing. What a document WITHHOLDING it does is asserted where that
        // rule lives, in
        // `services/service-com-amazonaws-eventbridge-awsevents/tests/all/queue_target_policy_authorization.rs`;
        // here it is a prerequisite, so every row admits EventBridge and what a row
        // varies is the PATTERN alone.
        admit_events(&router, case, &matching_url, &matching_arn, &matching_rule).await;
        admit_events(&router, case, &other_url, &other_arn, &other_rule).await;
        let job_name = format!("job-{index}");
        let submitted = batch(
            &router,
            case,
            "/v1/submitjob",
            &json!({
                "jobName": &job_name,
                "jobQueue": &job_queue_arn,
                "jobDefinition": &definition_arn,
            }),
        )
        .await;
        let job_id = member(case, &submitted, "/jobId");
        let job_arn = member(case, &submitted, "/jobArn");

        // Everything the clock owes a resting job arrives with no further Batch call: the
        // publication is the service's own, not a side effect of being read.
        let resting = row.expected.len() - usize::from(row.terminate);
        let mut arrived = collect(&router, case, &matching_url, resting).await;
        if row.terminate {
            batch(
                &router,
                case,
                "/v1/terminatejob",
                &json!({"jobId": &job_id, "reason": "ended by this suite"}),
            )
            .await;
            arrived.extend(collect(&router, case, &matching_url, 1).await);
        }

        let found = statuses(&arrived);
        assert_eq!(
            found,
            row.expected,
            "case {case:?}: expected the matching rule's queue to receive one event per \
             status in {:?}, got {found:?} from {arrived:?}",
            row.expected
        );

        // Each delivered message is the WHOLE envelope AWS hands a target, and its detail
        // is this job's own description.
        for envelope in &arrived {
            for (pointer, expected) in [
                ("/source", json!(BATCH_SOURCE)),
                ("/detail-type", json!(JOB_STATE_CHANGE)),
                ("/account", json!(engine::EMULATOR_ACCOUNT_ID)),
                ("/region", json!(REGION)),
                ("/resources", json!([&job_arn])),
                ("/detail/jobId", json!(&job_id)),
                ("/detail/jobName", json!(&job_name)),
                ("/detail/jobArn", json!(&job_arn)),
                ("/detail/jobQueue", json!(&job_queue_arn)),
                ("/detail/jobDefinition", json!(&definition_arn)),
            ] {
                let actual = envelope.pointer(pointer).cloned().unwrap_or(Value::Null);
                assert_eq!(
                    actual, expected,
                    "case {case:?}: expected {pointer} to be {expected}, got {actual} in \
                     {envelope}"
                );
            }
            assert!(
                envelope["id"].as_str().is_some_and(|id| !id.is_empty()),
                "case {case:?}: expected the envelope to carry an event id, got {envelope}"
            );
            assert!(
                envelope["time"].as_str().is_some_and(|at| at.ends_with('Z')),
                "case {case:?}: expected the envelope to state when the job moved, got \
                 {envelope}"
            );
        }

        // The negative half: the rule naming another job queue matched nothing, so its own
        // queue is still empty — and stays empty over a further span of the clock, which is
        // longer than any transition of this job took to arrive above.
        tokio::time::sleep(QUIET_SPAN).await;
        let withheld = drain(&router, case, &other_url).await;
        assert!(
            withheld.is_empty(),
            "case {case:?}: a rule whose pattern names another job queue must receive \
             nothing, got {withheld:?}"
        );
    }
}
