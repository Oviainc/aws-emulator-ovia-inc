//! A Batch job's state changes reach the rule pinned to ITS job queue, and only that one.
//!
//! The RULE under test: **every status an AWS Batch job MOVES INTO is published once onto
//! the account's default EventBridge bus as `source` `aws.batch` / `detail-type`
//! `Batch Job State Change`, carrying the job's own stored record as the `detail` — so
//! `detail.jobQueue` is the ARN of the queue the job was placed on, whichever way the submit
//! NAMED that queue, and `detail.statusReason` is the reason the call that ended the job
//! gave — and EventBridge routes each envelope by that content: a rule whose pattern pins one
//! job queue's ARN receives the envelopes of the jobs on THAT queue and none of another
//! queue's, until a job is submitted to the other queue, whose own transitions then reach the
//! rule pinned to it.** The status the submit itself stored is not a move, so no envelope
//! carries it ("events aren't created for the initial job submission" — the Batch User
//! Guide's "Job state change events"). Sources: the EventBridge reference page "AWS Batch
//! events" (`events-ref-batch.html`) for the source, the detail type and the default bus;
//! `smithy_query(query="operation",operation="DescribeJobs")` for the `JobDetail` members the
//! `detail` is a projection of (`jobQueue` — "The Amazon Resource Name (ARN) of the job queue
//! that the job is associated with", `statusReason`, `jobName`, `createdAt`); and
//! `smithy_query(query="doc",shape="TerminateJobRequest",member="reason")` — "A message to
//! attach to the job that explains the reason for terminating it. This message is returned by
//! future DescribeJobs operations on the job" — for the text a terminate attaches, and
//! `smithy_query(query="doc",shape="SubmitJobRequest",member="jobQueue")` for the two ways a
//! submit may name its queue.
//!
//! The rows differ along what the rule generalises over: WHICH of two sibling queues on one
//! compute environment the first job is submitted to, and HOW each submit names its queue
//! (by name or by ARN) — neither may change the ARN the envelope reports or which rule
//! receives it. Every row runs the whole sequence a client runs: it first proves the
//! EventBridge -> SQS wiring delivers at all (a rule on a source of the client's own), then
//! reads the job's `RUNNABLE` envelope off the watched queue, checks the sibling queue is
//! observably empty (nothing visible, nothing in flight), terminates the job and reads the
//! `FAILED` envelope carrying the terminate's reason, and finally submits to the sibling
//! queue and reads its own `RUNNABLE` envelope there.
//!
//! What is NOT asserted here, because it is asserted elsewhere:
//! `core/router/tests/all/batch_job_state_change_reaches_matching_rules.rs` pins which
//! dimension of the envelope a rule may filter on and the envelope members that are the
//! BUS's rather than the job's (`account`, `region`, `id`, `time`);
//! `services/service-com-amazonaws-batch-awsbatchv20160810/tests/all/job_state_change_events.rs`
//! pins the same rule over a table of job lifecycles; and
//! `.../tests/all/job_submission_publishes_no_event.rs` pins the submitted-status exclusion
//! over a table of first moves. What only this suite reaches is the pair those leave out: the
//! ARN a submit BY NAME has to publish, and two real sibling queues whose rules must each see
//! only their own queue's jobs.

use std::sync::Arc;
use std::time::{Duration, Instant};

use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

/// The Region every request below is signed for.
const REGION: &str = "us-west-2";

/// The `source` and `detail-type` AWS Batch publishes a job's state changes under, spelled
/// out here rather than imported from the service crate, so a wrong constant in the
/// implementation cannot make this suite pass. Source: "AWS Batch events".
const BATCH_SOURCE: &str = "aws.batch";
const JOB_STATE_CHANGE: &str = "Batch Job State Change";

/// The bus an Amazon Web Services service's own events go to: "events generated by Amazon
/// Web Services services go to your account's default event bus".
const DEFAULT_BUS: &str = "default";

/// The service principal EventBridge delivers to an SQS target as, which is what a queue's
/// resource policy admits ("for Amazon SQS queues, EventBridge relies on resource-based
/// policies").
const EVENTS_PRINCIPAL: &str = "events.amazonaws.com";

/// The namespace a client of its own publishes the warm-up event under, which proves the
/// EventBridge -> SQS wiring delivers before any Batch event is expected on it. It is the
/// client's own namespace, not the `aws.` one AWS reserves for its services; each warm-up
/// gets its own source below, so one queue's warm-up cannot reach another's rule.
const WARM_UP_NAMESPACE: &str = "com.example.wiring-check";

/// The source the warm-up for the rule called `name` publishes under.
fn warm_up_source(name: &str) -> String {
    format!("{WARM_UP_NAMESPACE}.{name}")
}

/// The statuses a job takes here: `RUNNABLE` when the clock releases it (nothing in this
/// emulator places a job on compute capacity, so it rests there) and the terminal `FAILED`
/// a `TerminateJob` writes. Source: `smithy_query(query="shape", shape="JobStatus")`.
const RUNNABLE: &str = "RUNNABLE";
const FAILED: &str = "FAILED";

/// The status a submit stores, which no envelope may ever report.
const SUBMITTED: &str = "SUBMITTED";

/// The status a compute environment and a job queue come to rest in. Source:
/// `smithy_query(query="shape", shape="CEStatus")` / `JQStatus`.
const VALID: &str = "VALID";

/// How long this suite waits for something the clock owes — a compute environment or job
/// queue reaching `VALID`, an envelope reaching a queue — before giving up. Far above the
/// span one transition takes, and driven off what has ARRIVED rather than off a fixed sleep,
/// so a slow machine delays a row instead of breaking it.
const DEADLINE: Duration = Duration::from_secs(30);

/// One poll inside [`DEADLINE`].
const POLL_INTERVAL: Duration = Duration::from_millis(25);

/// How long a row leaves the sibling queue alone before reading it: longer than the span the
/// watched queue's own envelope took to arrive, so an empty read is evidence the sibling's
/// rule was not a delivery target rather than evidence of having looked too early.
const QUIET_SPAN: Duration = Duration::from_millis(750);

/// The whole emulator over one engine, exactly as `core/router/src/lib.rs` assembles it for
/// the binary: Batch publishes through the in-process callback, so WHICH mounted model claims
/// that `events`-scoped call has to be the one a client reaches too.
fn router() -> MultiServiceRouter {
    let engine = aws_emulator_router::new_engine();
    let mut router = aws_emulator_router::build_router(Arc::clone(&engine));
    router.set_request_authentication(false);
    router
}

/// A SigV4 `Authorization` whose credential scope names `service`, which is what routes the
/// request. The signature is never checked: the router above runs with request
/// authentication off.
fn authorization(service: &str) -> String {
    format!(
        "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20260101/{REGION}/{service}/aws4_request, \
         SignedHeaders=host, Signature=0000"
    )
}

/// The status and parsed body of one response.
fn answered(response: &http::Response<Bytes>) -> (u16, Value) {
    let status = response.status().as_u16();
    let parsed = if response.body().is_empty() {
        Value::Null
    } else {
        serde_json::from_slice(response.body()).unwrap_or(Value::Null)
    };
    (status, parsed)
}

/// One `X-Amz-Target` RPC call against the service whose signing name is `signing_name`,
/// which must answer 200.
async fn rpc(
    router: &MultiServiceRouter,
    case: &str,
    signing_name: &str,
    target_prefix: &str,
    json_version: &str,
    operation: &str,
    body: &Value,
) -> Value {
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("{signing_name}.{REGION}.amazonaws.com"))
        .header("authorization", authorization(signing_name))
        .header("content-type", format!("application/x-amz-json-{json_version}"))
        .header("x-amz-target", format!("{target_prefix}.{operation}"))
        .body(Bytes::from(body.to_string()))
        .expect("the test request is well formed");
    let (status, parsed) = answered(&router.dispatch(request).await);
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from {signing_name} {operation}, got {status} with \
         {parsed}"
    );
    parsed
}

/// One EventBridge call (`awsJson1_1`, `AWSEvents.<Operation>`).
async fn events(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    rpc(router, case, "events", "AWSEvents", "1.1", operation, body).await
}

/// One Amazon SQS call (`awsJson1_0`, `AmazonSQS.<Operation>`).
async fn sqs(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    rpc(router, case, "sqs", "AmazonSQS", "1.0", operation, body).await
}

/// One AWS Batch call: a `restJson1` service, so `POST <uri>` with a JSON body.
async fn batch(router: &MultiServiceRouter, case: &str, uri: &str, body: &Value) -> Value {
    let request = http::Request::builder()
        .method("POST")
        .uri(format!("https://batch.{REGION}.amazonaws.com{uri}"))
        .header("host", format!("batch.{REGION}.amazonaws.com"))
        .header("authorization", authorization("batch"))
        .header("content-type", "application/json")
        .body(Bytes::from(body.to_string()))
        .expect("the test request is well formed");
    let (status, parsed) = answered(&router.dispatch(request).await);
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from Batch {uri}, got {status} with {parsed}"
    );
    parsed
}

/// A string member of a response, or a panic naming the case and what came back.
fn member(case: &str, body: &Value, pointer: &str) -> String {
    body.pointer(pointer)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("case {case:?}: expected {pointer} in {body}"))
        .to_string()
}

/// An SQS queue called `name` whose resource policy admits EventBridge, created the way a
/// client creates one; answers its url and the ARN a rule names it by.
async fn queue(router: &MultiServiceRouter, case: &str, name: &str) -> (String, String) {
    let created = sqs(router, case, "CreateQueue", &json!({"QueueName": name})).await;
    let url = member(case, &created, "/QueueUrl");
    let attributes = sqs(
        router,
        case,
        "GetQueueAttributes",
        &json!({"QueueUrl": &url, "AttributeNames": ["QueueArn"]}),
    )
    .await;
    let arn = member(case, &attributes, "/Attributes/QueueArn");
    let policy = json!({
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "AllowEventBridge",
            "Effect": "Allow",
            "Principal": {"Service": EVENTS_PRINCIPAL},
            "Action": "sqs:SendMessage",
            "Resource": &arn,
        }],
    })
    .to_string();
    sqs(
        router,
        case,
        "SetQueueAttributes",
        &json!({"QueueUrl": &url, "Attributes": {"Policy": policy}}),
    )
    .await;
    (url, arn)
}

/// An ENABLED rule called `name` on the default bus carrying `pattern`, with the queue
/// `queue_arn` as its one target.
async fn rule(
    router: &MultiServiceRouter,
    case: &str,
    name: &str,
    pattern: &Value,
    queue_arn: &str,
) {
    events(
        router,
        case,
        "PutRule",
        &json!({
            "Name": name,
            "EventBusName": DEFAULT_BUS,
            "EventPattern": pattern.to_string(),
            "State": "ENABLED",
        }),
    )
    .await;
    let targeted = events(
        router,
        case,
        "PutTargets",
        &json!({
            "Rule": name,
            "EventBusName": DEFAULT_BUS,
            "Targets": [{"Id": "t1", "Arn": queue_arn}],
        }),
    )
    .await;
    assert_eq!(
        targeted["FailedEntryCount"],
        json!(0),
        "case {case:?}: every target must be accepted, got {targeted}"
    );
}

/// Receive everything waiting on the queue at `url` and DELETE it, so what a later read
/// reports — and what the queue counts as in flight — is only what arrived after this call.
/// Answers the parsed envelopes the message bodies carried.
async fn drain(router: &MultiServiceRouter, case: &str, url: &str) -> Vec<Value> {
    let received = sqs(
        router,
        case,
        "ReceiveMessage",
        &json!({"QueueUrl": url, "MaxNumberOfMessages": 10}),
    )
    .await;
    let messages = received["Messages"].as_array().cloned().unwrap_or_default();
    let mut envelopes = Vec::new();
    for message in &messages {
        if let Some(handle) = message["ReceiptHandle"].as_str() {
            sqs(
                router,
                case,
                "DeleteMessage",
                &json!({"QueueUrl": url, "ReceiptHandle": handle}),
            )
            .await;
        }
        let raw = message["Body"].as_str().unwrap_or_default();
        envelopes.push(serde_json::from_str::<Value>(raw).unwrap_or(Value::Null));
    }
    envelopes
}

/// Collect envelopes off the queue at `url` until `wanted` of them have arrived or
/// [`DEADLINE`] passes; answers everything that did arrive.
async fn collect(router: &MultiServiceRouter, case: &str, url: &str, wanted: usize) -> Vec<Value> {
    let started = Instant::now();
    let mut arrived: Vec<Value> = Vec::new();
    while arrived.len() < wanted && started.elapsed() < DEADLINE {
        arrived.extend(drain(router, case, url).await);
        if arrived.len() < wanted {
            tokio::time::sleep(POLL_INTERVAL).await;
        }
    }
    arrived
}

/// What the queue at `url` reports waiting on it and in flight, the two counters a consumer
/// reads an absence off.
async fn counters(router: &MultiServiceRouter, case: &str, url: &str) -> (String, String) {
    let attributes = sqs(
        router,
        case,
        "GetQueueAttributes",
        &json!({
            "QueueUrl": url,
            "AttributeNames": [
                "ApproximateNumberOfMessages",
                "ApproximateNumberOfMessagesNotVisible",
            ],
        }),
    )
    .await;
    (
        member(case, &attributes, "/Attributes/ApproximateNumberOfMessages"),
        member(
            case,
            &attributes,
            "/Attributes/ApproximateNumberOfMessagesNotVisible",
        ),
    )
}

/// Prove the wiring from EventBridge to the queue at `url` delivers at all, the way a client
/// proves it: a rule on a source of the client's OWN, one event published under it, and the
/// envelope read back off the queue. Leaves the queue empty again.
async fn prove_wiring(router: &MultiServiceRouter, case: &str, name: &str, url: &str, arn: &str) {
    let source = warm_up_source(name);
    rule(router, case, name, &json!({"source": [&source]}), arn).await;
    let published = events(
        router,
        case,
        "PutEvents",
        &json!({
            "Entries": [{
                "EventBusName": DEFAULT_BUS,
                "Source": &source,
                "DetailType": "wiring check",
                "Detail": json!({"check": name}).to_string(),
            }],
        }),
    )
    .await;
    assert_eq!(
        published["FailedEntryCount"],
        json!(0),
        "case {case:?}: the warm-up publication must be accepted, got {published}"
    );
    let arrived = collect(router, case, url, 1).await;
    let sources: Vec<&str> = arrived
        .iter()
        .map(|envelope| envelope["source"].as_str().unwrap_or_default())
        .collect();
    assert_eq!(
        sources,
        vec![source.as_str()],
        "case {case:?}: the wiring to {url} must deliver the client's own event before any \
         Batch event is expected on it, got {arrived:?}"
    );
}

/// Poll the body `uri` answers for `body` until its `pointer` reads `wanted`, or [`DEADLINE`]
/// passes; answers what it last read.
async fn await_status(
    router: &MultiServiceRouter,
    case: &str,
    uri: &str,
    body: &Value,
    pointer: &str,
    wanted: &str,
) -> String {
    let started = Instant::now();
    let mut last = String::new();
    while started.elapsed() < DEADLINE {
        let described = batch(router, case, uri, body).await;
        last = described
            .pointer(pointer)
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string();
        if last == wanted {
            return last;
        }
        tokio::time::sleep(POLL_INTERVAL).await;
    }
    last
}

/// The `detail.status` of each envelope, sorted: an SQS standard queue makes "a best-effort
/// to preserve order", so what is asserted is WHICH transitions arrived.
fn statuses(envelopes: &[Value]) -> Vec<String> {
    let mut found: Vec<String> = envelopes
        .iter()
        .map(|envelope| {
            envelope["detail"]["status"]
                .as_str()
                .unwrap_or_default()
                .to_string()
        })
        .collect();
    found.sort();
    found
}

/// How a submit NAMES the job queue it places a job on. Either spelling places the job on the
/// same queue, so either has to publish that queue's ARN in `detail.jobQueue`.
#[derive(Debug, Clone, Copy)]
enum Named {
    /// `SubmitJob$jobQueue`: "The job queue where the job is submitted. You can specify either
    /// the name or the Amazon Resource Name (ARN) of the queue."
    ByName,
    ByArn,
}

impl Named {
    /// The reference a submit carries for the queue called `name` whose ARN is `arn`.
    fn reference(self, name: &str, arn: &str) -> String {
        match self {
            Named::ByName => name.to_string(),
            Named::ByArn => arn.to_string(),
        }
    }
}

/// One row: which of the two sibling queues the first job goes to, and how each submit names
/// its queue.
struct Row {
    case: &'static str,
    /// The index (0 or 1) of the queue the first job is submitted to; the other is the
    /// sibling whose rule must see nothing until its own job is submitted.
    watched: usize,
    /// How the first job's submit names its queue.
    first: Named,
    /// How the sibling's submit names its queue.
    second: Named,
}

/// RULE: a job's transitions reach the rule pinned to the ARN of the queue it was submitted
/// to — whichever way the submit named that queue — and reach no rule pinned to another
/// queue, whose own jobs reach it instead.
#[tokio::test]
async fn a_job_state_change_reaches_only_the_rule_pinned_to_its_own_job_queue() {
    let rows = [
        Row {
            case: "the first queue watched, submitted by name",
            watched: 0,
            first: Named::ByName,
            second: Named::ByArn,
        },
        Row {
            case: "the second queue watched, submitted by ARN",
            watched: 1,
            first: Named::ByArn,
            second: Named::ByName,
        },
    ];

    for (index, row) in rows.iter().enumerate() {
        let case = row.case;
        let router = router();

        // One SQS queue per job queue, each admitting EventBridge, each proven to be
        // reachable from the bus before any Batch event is expected on it.
        let mut consumers = Vec::new();
        for slot in 0..2 {
            let (url, arn) = queue(&router, case, &format!("events-{index}-{slot}")).await;
            prove_wiring(
                &router,
                case,
                &format!("wiring-{index}-{slot}"),
                &url,
                &arn,
            )
            .await;
            consumers.push((url, arn));
        }

        // An UNMANAGED compute environment carrying a service role of the account's own, and
        // two sibling job queues on it: nothing places a job, so a job rests in RUNNABLE.
        let environment = batch(
            &router,
            case,
            "/v1/createcomputeenvironment",
            &json!({
                "computeEnvironmentName": format!("ce-{index}"),
                "type": "UNMANAGED",
                "state": "ENABLED",
                "serviceRole": format!(
                    "arn:aws:iam::{}:role/service-role/BatchServiceRole",
                    engine::EMULATOR_ACCOUNT_ID,
                ),
            }),
        )
        .await;
        let environment_arn = member(case, &environment, "/computeEnvironmentArn");
        let reached = await_status(
            &router,
            case,
            "/v1/describecomputeenvironments",
            &json!({"computeEnvironments": [&environment_arn]}),
            "/computeEnvironments/0/status",
            VALID,
        )
        .await;
        assert_eq!(
            reached, VALID,
            "case {case:?}: the compute environment must reach {VALID}, got {reached:?}"
        );

        let mut job_queues = Vec::new();
        for slot in 0..2 {
            let name = format!("jq-{index}-{slot}");
            let created = batch(
                &router,
                case,
                "/v1/createjobqueue",
                &json!({
                    "jobQueueName": &name,
                    "state": "ENABLED",
                    "priority": 1,
                    "computeEnvironmentOrder": [
                        {"order": 1, "computeEnvironment": &environment_arn},
                    ],
                }),
            )
            .await;
            job_queues.push((name, member(case, &created, "/jobQueueArn")));
        }
        for (name, arn) in &job_queues {
            let reached = await_status(
                &router,
                case,
                "/v1/describejobqueues",
                &json!({"jobQueues": [arn]}),
                "/jobQueues/0/status",
                VALID,
            )
            .await;
            assert_eq!(
                reached, VALID,
                "case {case:?}: the job queue {name} must reach {VALID}, got {reached:?}"
            );
        }

        let definition = batch(
            &router,
            case,
            "/v1/registerjobdefinition",
            &json!({
                "jobDefinitionName": format!("jd-{index}"),
                "type": "container",
                "containerProperties": {
                    "image": "busybox",
                    "command": ["echo", "hello"],
                    "resourceRequirements": [
                        {"type": "VCPU", "value": "1"},
                        {"type": "MEMORY", "value": "512"},
                    ],
                },
            }),
        )
        .await;
        let definition_arn = member(case, &definition, "/jobDefinitionArn");

        // One rule per job queue, each pinning its OWN queue's ARN inside the detail and
        // delivering to that queue's consumer.
        for (slot, (_, queue_arn)) in job_queues.iter().enumerate() {
            rule(
                &router,
                case,
                &format!("batch-{index}-{slot}"),
                &json!({
                    "source": [BATCH_SOURCE],
                    "detail-type": [JOB_STATE_CHANGE],
                    "detail": {"jobQueue": [queue_arn]},
                }),
                &consumers[slot].1,
            )
            .await;
        }

        let sibling = 1 - row.watched;
        let (watched_name, watched_arn) = &job_queues[row.watched];
        let (sibling_name, sibling_arn) = &job_queues[sibling];
        let watched_url = consumers[row.watched].0.clone();
        let sibling_url = consumers[sibling].0.clone();

        // The job, submitted to the watched queue by this row's spelling of it.
        let job_name = format!("job-{index}");
        let submitted = batch(
            &router,
            case,
            "/v1/submitjob",
            &json!({
                "jobName": &job_name,
                "jobQueue": row.first.reference(watched_name, watched_arn),
                "jobDefinition": &definition_arn,
            }),
        )
        .await;
        let job_id = member(case, &submitted, "/jobId");
        let job_arn = member(case, &submitted, "/jobArn");

        // The first transition arrives with no further Batch call, and it is the move OUT of
        // the submitted status: the submit's own status is never published.
        let resting = collect(&router, case, &watched_url, 1).await;
        assert_eq!(
            statuses(&resting),
            vec![RUNNABLE.to_string()],
            "case {case:?}: expected the watched rule's queue to receive the job's move into \
             {RUNNABLE}, got {resting:?}"
        );

        // The envelope is the one AWS Batch publishes, naming the job it is about.
        for (pointer, expected) in [
            ("/source", json!(BATCH_SOURCE)),
            ("/detail-type", json!(JOB_STATE_CHANGE)),
            ("/resources", json!([&job_arn])),
        ] {
            let actual = resting[0].pointer(pointer).cloned().unwrap_or(Value::Null);
            assert_eq!(
                actual, expected,
                "case {case:?}: expected {pointer} to be {expected}, got {actual} in {}",
                resting[0]
            );
        }

        // The detail is the job's own record, as DescribeJobs reports it — the two views
        // cannot disagree — and it names the queue by ARN whichever way the submit named it.
        let described = batch(
            &router,
            case,
            "/v1/describejobs",
            &json!({"jobs": [&job_id]}),
        )
        .await;
        let detail = &resting[0]["detail"];
        for (pointer, expected) in [
            ("/jobId", json!(&job_id)),
            ("/jobArn", json!(&job_arn)),
            ("/jobQueue", json!(watched_arn)),
            ("/jobDefinition", json!(&definition_arn)),
            ("/jobName", described.pointer("/jobs/0/jobName").cloned().unwrap_or(Value::Null)),
            ("/createdAt", described.pointer("/jobs/0/createdAt").cloned().unwrap_or(Value::Null)),
        ] {
            let actual = detail.pointer(pointer).cloned().unwrap_or(Value::Null);
            assert_eq!(
                actual, expected,
                "case {case:?}: expected detail{pointer} to be {expected}, got {actual} in \
                 {detail}"
            );
        }
        assert!(
            detail["jobDefinition"]
                .as_str()
                .is_some_and(|arn| arn.starts_with("arn:")),
            "case {case:?}: the detail must name the job definition by ARN, got {detail}"
        );

        // The sibling queue's rule pins ANOTHER job queue, so nothing has been delivered to
        // it: it holds no message and has none in flight.
        tokio::time::sleep(QUIET_SPAN).await;
        let (visible, in_flight) = counters(&router, case, &sibling_url).await;
        assert_eq!(
            (visible.as_str(), in_flight.as_str()),
            ("0", "0"),
            "case {case:?}: the sibling queue {sibling_name} must report nothing waiting and \
             nothing in flight, got {visible} waiting and {in_flight} in flight"
        );

        // The terminate's reason is the job's `statusReason`, so the FAILED envelope carries
        // it — read from the same record, so DescribeJobs reports it too.
        let reason = format!("ended by case {index}");
        batch(
            &router,
            case,
            "/v1/terminatejob",
            &json!({"jobId": &job_id, "reason": &reason}),
        )
        .await;
        let ended = collect(&router, case, &watched_url, 1).await;
        assert_eq!(
            statuses(&ended),
            vec![FAILED.to_string()],
            "case {case:?}: expected the terminate's move into {FAILED} on the watched \
             queue, got {ended:?}"
        );
        assert_eq!(
            ended[0]["detail"]["statusReason"],
            json!(&reason),
            "case {case:?}: expected the {FAILED} envelope to carry the terminate's reason, \
             got {}",
            ended[0]["detail"]
        );
        let described = batch(
            &router,
            case,
            "/v1/describejobs",
            &json!({"jobs": [&job_id]}),
        )
        .await;
        assert_eq!(
            described.pointer("/jobs/0/statusReason").cloned().unwrap_or(Value::Null),
            json!(&reason),
            "case {case:?}: the reason the envelope carried must be the one DescribeJobs \
             reports, got {described}"
        );

        // No envelope for this job ever reported the status the submit stored.
        let delivered = [resting, ended].concat();
        assert!(
            !statuses(&delivered).iter().any(|status| status == SUBMITTED),
            "case {case:?}: no event is created for the initial job submission, got \
             {delivered:?}"
        );

        // The repair: a job on the SIBLING queue reaches the rule pinned to that queue, and
        // the watched queue receives none of it.
        let sibling_job = batch(
            &router,
            case,
            "/v1/submitjob",
            &json!({
                "jobName": format!("sibling-job-{index}"),
                "jobQueue": row.second.reference(sibling_name, sibling_arn),
                "jobDefinition": &definition_arn,
            }),
        )
        .await;
        let sibling_id = member(case, &sibling_job, "/jobId");
        let arrived = collect(&router, case, &sibling_url, 1).await;
        assert_eq!(
            statuses(&arrived),
            vec![RUNNABLE.to_string()],
            "case {case:?}: expected the sibling queue to receive its own job's move into \
             {RUNNABLE} once one is submitted to it, got {arrived:?}"
        );
        for (pointer, expected) in [
            ("/jobId", json!(&sibling_id)),
            ("/jobQueue", json!(sibling_arn)),
        ] {
            let actual = arrived[0]["detail"]
                .pointer(pointer)
                .cloned()
                .unwrap_or(Value::Null);
            assert_eq!(
                actual, expected,
                "case {case:?}: expected the sibling's envelope detail{pointer} to be \
                 {expected}, got {actual} in {}",
                arrived[0]
            );
        }
        tokio::time::sleep(QUIET_SPAN).await;
        let crossed = drain(&router, case, &watched_url).await;
        assert!(
            crossed.is_empty(),
            "case {case:?}: the watched queue must receive none of the sibling queue's \
             events, got {crossed:?}"
        );
    }
}
