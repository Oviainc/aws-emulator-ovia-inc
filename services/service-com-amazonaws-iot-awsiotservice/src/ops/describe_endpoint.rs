impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeEndpoint<Eng>
{
    type Input = DescribeEndpointInput;
    type Output = DescribeEndpointOutput;
    type Error = DescribeEndpointError;

    const NAME: &'static str = "DescribeEndpoint";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_ENDPOINT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_ENDPOINT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // Which endpoint the caller asked for. `endpointType` is optional, so a
        // request that names none asks for the default data endpoint; one that names
        // a token outside the documented catalog is refused with the operation's own
        // modelled client error rather than served some other endpoint.
        let endpoint_type = match input.endpoint_type.as_deref() {
            None => EndpointType::DEFAULT,
            Some(requested) => match EndpointType::parse(requested) {
                Some(endpoint_type) => endpoint_type,
                None => {
                    audit(ctx, "validation-refused", input.endpoint_type.as_deref());
                    let valid = EndpointType::ALL
                        .iter()
                        .map(|candidate| candidate.token())
                        .collect::<Vec<_>>()
                        .join(", ");
                    return Err(DescribeEndpointErrorModeled::InvalidRequestException(
                        InvalidRequestException {
                            message: Some(format!(
                                "endpointType must be one of [{valid}], got '{requested}'"
                            )),
                        },
                    )
                    .into());
                }
            },
        };

        let Some(state) = crate::state::service_state(&*self.engine) else {
            audit(ctx, "store-unavailable", Some(endpoint_type.token()));
            return Err(DescribeEndpointErrorModeled::InternalFailureException(
                InternalFailureException {
                    message: Some(
                        "the IoT endpoint store is unavailable in this emulator".to_string(),
                    ),
                },
            )
            .into());
        };

        // The region is read from the request's credential scope, so the endpoint
        // resolved is the one of the Region the caller addressed; the account is the
        // emulator's own.
        let region = endpoint_region(ctx.parts());
        let account_id = ::engine::emulator_account_id();

        // "Returns or creates": the first call in a region creates the account's
        // endpoint there and records its identifier, every later call reads that record,
        // so this account has ONE endpoint per region and repeating the call returns
        // the same endpoint.
        //
        // The region is read from the caller's credential scope, so the set of keys the
        // record store is grown by is client-influenced, and that store is BOUNDED:
        // `endpoint_identifier_or_create` records at most
        // `crate::state::MAX_ENDPOINT_REGIONS` regions and records nothing past that
        // cap, so no sequence of requests can grow this service's state without limit by
        // varying the signed region. Answering past the cap costs nothing observable:
        // the identifier a record holds is a pure function of the account and the region
        // (`crate::state::derive_endpoint_identifier`).
        let created = {
            let mut store = state.lock();
            let already_created = store.endpoint_identifier(&region).is_some();
            store.endpoint_identifier_or_create(account_id, &region);
            !already_created
        };

        // WHERE that endpoint answers, which is what the caller is told: this emulator's
        // own endpoint, the one address its IoT planes are served at.
        let endpoint_address = published_endpoint_address(ctx);

        audit(
            ctx,
            if created {
                "endpoint-created"
            } else {
                "endpoint-returned"
            },
            Some(endpoint_type.token()),
        );

        Ok(DescribeEndpointOutput {
            endpoint_address: Some(endpoint_address),
        })
    }
}
