//! @op GetJobDocument
//!
//! A pure read of the job this account registered under that `jobId`
//! ([`crate::state::ComAmazonawsIotAwsiotserviceState::jobs`]): it reports the document
//! the job was created with, and a `jobId` the store does not hold is the modelled 404
//! rather than a hollow 200.
//!
