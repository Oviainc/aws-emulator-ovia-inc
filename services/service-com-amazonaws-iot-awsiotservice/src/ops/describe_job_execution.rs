impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeJobExecution<Eng>
{
    type Input = DescribeJobExecutionInput;
    type Output = DescribeJobExecutionOutput;
    type Error = DescribeJobExecutionError;

    const NAME: &'static str = "DescribeJobExecution";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_JOB_EXECUTION_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_JOB_EXECUTION_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let unavailable = || -> DescribeJobExecutionError {
            DescribeJobExecutionErrorModeled::ServiceUnavailableException(
                ServiceUnavailableException {
                    message: Some("the IoT emulator has no state store attached".to_string()),
                },
            )
            .into()
        };
        // The job the execution belongs to lives in the SHARED jobs store every creator
        // of an IoT job records one in.
        let Some(jobs) = crate::state::job_store(&*self.engine) else {
            return Err(unavailable());
        };
        // The executions live in the SHARED store the IoT Jobs data plane serves, so
        // this read answers from the very record the device polls, starts and updates.
        let Some(executions) = crate::state::job_execution_store(&*self.engine) else {
            return Err(unavailable());
        };

        // The two conditions this read can fail on are DISTINGUISHABLE, so each is
        // worded for the resource it is about: a `jobId` no creator recorded has no
        // execution anywhere and the refusal names that missing JOB
        // ([`crate::state::missing_job_execution_job_message`]), while a job that does
        // exist and has no execution on this thing names the pair it found none for.
        let missing_execution = || -> DescribeJobExecutionError {
            DescribeJobExecutionErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(crate::state::missing_job_execution_message(
                        &input.thing_name,
                        &input.job_id,
                    )),
                },
            )
            .into()
        };

        let region = crate::state::request_region(ctx.parts());
        let now = ::service_common::iot_job_executions::now_epoch_seconds();

        // LOCK ORDER: the shared jobs store first, the shared execution store second,
        // as `crate::state::job_store` documents. A job execution belongs to a job of
        // this account's jobs store (`CreateJob$jobId` is "A job identifier which must
        // be unique for your account"), so a `jobId` that store does not hold has no
        // job execution to report — which is also what keeps a COMMAND execution, keyed
        // in the shared execution store by its own minted `executionId` and read through
        // `GetCommandExecution`, from being reported here as a job execution.
        if !jobs.lock().contains(&input.job_id) {
            return Err(DescribeJobExecutionErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(crate::state::missing_job_execution_job_message(
                        &input.job_id,
                    )),
                },
            )
            .into());
        }

        let mut store = executions.lock();
        // A timer the job or the device armed moves an execution to `TIMED_OUT` by
        // itself, so the transitions the clock has already made due are recorded
        // before anything is read: each was owed at its own deadline whether or not
        // this call happened, and the status a later reader of the shared store sees
        // must be the same one.
        store.time_out_due_executions(&input.thing_name, now);

        // ONE lookup, so a pair the store holds no execution for has exactly one
        // answer: without `executionNumber` it is the LATEST execution of that job on
        // that thing, which is what the member documents as the default.
        let Some(record) = store
            .execution_index(&input.thing_name, &input.job_id, input.execution_number)
            .and_then(|index| store.record(&input.thing_name, index))
        else {
            return Err(missing_execution());
        };

        Ok(DescribeJobExecutionOutput {
            execution: Some(crate::state::to_job_execution(record, &region, now)),
        })
    }
}
