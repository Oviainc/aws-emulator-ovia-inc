//! @op UntagResource
//!
//! Removes the named keys from the tag set stored on the Braket resource `resourceArn`
//! names, and touches nothing else: a key the resource carries is dropped with its
//! value, a key it does not carry is already absent and so is left alone, and every key
//! the request does not name stays. That is what makes the call `@idempotent` by its own
//! effect — repeating it leaves the same set — and `ListTagsForResource` reads back what
//! this leaves, through the one lookup both doors share
//! (`crate::state::ComAmazonawsBraketBraketState::tags_of`).
//!
