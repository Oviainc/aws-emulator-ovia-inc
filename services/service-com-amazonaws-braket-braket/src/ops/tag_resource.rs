//! @op TagResource
//!
//! Merges the submitted tags into the tag set stored on the Braket resource
//! `resourceArn` names: a key the resource does not carry is added, a key it does carry
//! takes the submitted value, and every key the request does not name is left exactly as
//! it was. So tagging is additive and repeatable — the same call twice leaves the same
//! set — and `ListTagsForResource` reads back what this writes, through the one lookup
//! both doors share (`crate::state::ComAmazonawsBraketBraketState::tags_of`).
//!
//! The set one resource carries is bounded by COUNT at
//! [`crate::state::MAX_TAGS_PER_RESOURCE`]: a call that would take the resource past the
//! number of tags AWS allows on one resource is refused as invalid input and writes
//! nothing, so repeated tagging cannot grow a stored record without end. A key already
//! on the resource does not grow the set, so overwriting a value is served at the limit.
//!
//! `resourceArn` is the only thing that resolves the resource. A value that is not a
//! Braket resource ARN names no resource to tag and is refused as invalid input before
//! the store is touched; a well-formed ARN that no stored resource carries — one never
//! minted, one already gone, or an ARN of a resource that holds no tag set at all, such
//! as a device AWS publishes rather than this API creates — is answered HTTP 404 with
//! the error code the tagging doors answer that class with ([`RESOURCE_NOT_FOUND`]), and
//! neither refusal writes anything.
