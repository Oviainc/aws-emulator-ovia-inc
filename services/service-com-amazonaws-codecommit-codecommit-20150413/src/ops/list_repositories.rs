        let repositories: Vec<RepositoryNameIdPair> = ordered[start..end]
            .iter()
            .map(|repository| RepositoryNameIdPair {
                repository_name: Some(repository.name.clone()),
                repository_id: Some(repository.repository_id.clone()),
            })
            .collect();

