/// Either selector names the same group — the name, or either ARN form of it — and the
/// pair is refused when it names both or neither; a selector naming no group answers an
/// empty field list rather than a refusal.
#[tokio::test]
async fn the_log_group_is_named_by_either_selector_and_the_pair_is_checked() {
    let logs = Logs::new();
    group_with_stream(&logs, "selected", "stream-1", None).await;
    put_recent(&logs, "selected", "stream-1", &[r#"{"level":"INFO"}"#]).await;
    // `logGroupIdentifier`'s own pattern (`^[\w#+=/:,.@-]*$`) admits no `*`, so the
    // group's `arn` member — which carries the trailing `:*` — cannot be passed through
    // this member at all; the ARN form a client selects a group by is `logGroupArn`.
    let (_wildcard_arn, plain_arn) = logs.group_arns("selected").await;

    for (case, request) in [
        ("by name", json!({"logGroupName": "selected"})),
        (
            "by identifier naming the name",
            json!({"logGroupIdentifier": "selected"}),
        ),
        (
            "by the ARN without a trailing wildcard",
            json!({"logGroupIdentifier": plain_arn}),
        ),
    ] {
        let reported = group_fields(&logs, case, &request).await;
        assert_eq!(
            reported,
            expected_fields(&[("level", 100)]),
            "case {case:?}: every selector naming one group answers the same fields, got {reported:?}"
        );
    }

    // (case, request, the error code, the message the service words the refusal with)
    let refusals = [
        (
            "both selectors",
            json!({"logGroupName": "selected", "logGroupIdentifier": "selected"}),
            "ValidationException",
            "LogGroup name and LogGroup ARN are mutually exclusive parameters.",
        ),
        (
            "neither selector",
            json!({}),
            "ValidationException",
            "Either LogGroupName or LogGroupArn must be provided.",
        ),
    ];
    for (case, request, expected_code, expected_message) in refusals {
        let (code, message) = logs.refusal("GetLogGroupFields", &request).await;
        assert_eq!(
            code, expected_code,
            "case {case:?}: expected {expected_code}, got {code} / {message}"
        );
        assert_eq!(
            message, expected_message,
            "case {case:?}: expected {expected_message:?}, got {message:?}"
        );
    }

    // A selector naming no log group is NOT a missing resource here: the operation reports
    // the fields its index holds for the name it was given, and an index holding nothing
    // names no field.
    for (case, request) in [
        ("a name no group carries", json!({"logGroupName": "absent"})),
        (
            "an ARN no group carries",
            json!({"logGroupIdentifier": format!(
                "arn:aws:logs:{REGION}:{}:log-group:absent",
                engine::emulator_account_id()
            )}),
        ),
    ] {
        let reported = group_fields(&logs, case, &request).await;
        assert!(
            reported.is_empty(),
            "case {case:?}: expected 200 with no field at all, got {reported:?}"
        );
    }
}

/// The operation only reports: two identical calls answer identically, and nothing a later
/// caller reads changes because the fields were read.
#[tokio::test]
async fn reporting_the_fields_changes_nothing_a_later_caller_sees() {
    let logs = Logs::new();
    group_with_stream(&logs, "read-only", "stream-1", None).await;
    put_recent(
        &logs,
        "read-only",
        "stream-1",
        &[r#"{"level":"INFO"}"#, r#"{"level":"WARN","latency":3}"#],
    )
    .await;

    let request = json!({"logGroupName": "read-only"});
    let before = logs.ok("GetLogEvents", &json!({
        "logGroupName": "read-only",
        "logStreamName": "stream-1",
        "startFromHead": true,
    }))
    .await;
    let first = group_fields(&logs, "first call", &request).await;
    let second = group_fields(&logs, "second call", &request).await;
    let after = logs.ok("GetLogEvents", &json!({
        "logGroupName": "read-only",
        "logStreamName": "stream-1",
        "startFromHead": true,
    }))
    .await;

    assert_eq!(
        first,
        expected_fields(&[("level", 100), ("latency", 50)]),
        "case first call: expected the stored events' fields, got {first:?}"
    );
    assert_eq!(
        second, first,
        "case second call: a report is repeatable, got {second:?} after {first:?}"
    );
    assert_eq!(
        after["events"], before["events"],
        "case the events after the report: reporting the fields must not change them, got {after} after {before}"
    );
    let group = logs
        .describe_group("read-only")
        .await
        .expect("case the group after the report: the group is still there");
    assert!(
        group.get("storedBytes").and_then(Value::as_i64).unwrap_or(0) > 0,
        "case the group after the report: its stored bytes are unchanged by a read, got {group}"
    );
}

/// The ceilings the search applies are applied, and they cut the documented side: one
/// event contributes at most `MAX_FIELDS_PER_EVENT` names (the generated five included),
/// the response carries at most `MAX_REPORTED_FIELDS` of them, and flattening stops
/// descending at `MAX_FIELD_DEPTH`, reporting the member under the path reached there.
#[tokio::test]
async fn one_search_is_bounded_by_the_handlers_own_field_ceilings() {
    // A message naming far more keys than one event may contribute.
    let wide: String = {
        let keys: Vec<String> = (0..500).map(|index| format!(r#""k{index:04}":{index}"#)).collect();
        format!("{{{}}}", keys.join(","))
    };
    // A message nested far deeper than the flattening descends.
    let deep: String = {
        let mut message = "1".to_string();
        for level in (0..12).rev() {
            message = format!(r#"{{"n{level}":{message}}}"#);
        }
        message
    };
    let deepest_path: String = (0..MAX_FIELD_DEPTH)
        .map(|level| format!("n{level}"))
        .collect::<Vec<_>>()
        .join(".");

    let logs = Logs::new();
    group_with_stream(&logs, "wide", "stream-1", None).await;
    put_recent(&logs, "wide", "stream-1", &[wide.as_str()]).await;
    let reported = group_fields(&logs, "one event naming 500 keys", &json!({"logGroupName": "wide"})).await;
    assert_eq!(
        reported.len(),
        MAX_FIELDS_PER_EVENT,
        "case one event naming 500 keys: one event contributes at most {MAX_FIELDS_PER_EVENT} fields, got {}",
        reported.len()
    );
    for name in GENERATED_FIELDS {
        assert_eq!(
            reported.get(name),
            Some(&100),
            "case one event naming 500 keys: the generated field {name} survives the cut, got {reported:?}"
        );
    }

    group_with_stream(&logs, "deep", "stream-1", None).await;
    put_recent(&logs, "deep", "stream-1", &[deep.as_str()]).await;
    let reported = group_fields(&logs, "one event nested 12 deep", &json!({"logGroupName": "deep"})).await;
    assert_eq!(
        reported,
        expected_fields(&[(deepest_path.as_str(), 100)]),
        "case one event nested 12 deep: the member is reported under the path reached at depth {MAX_FIELD_DEPTH}, got {reported:?}"
    );

    // 12 events naming 100 distinct keys each: more distinct names than one response
    // reports, so the response is capped and the generated fields — the highest
    // percentages — are the ones kept.
    group_with_stream(&logs, "many-names", "stream-1", None).await;
    let messages: Vec<String> = (0..12)
        .map(|event| {
            let keys: Vec<String> = (0..100)
                .map(|key| format!(r#""e{event:02}k{key:03}":1"#))
                .collect();
            format!("{{{}}}", keys.join(","))
        })
        .collect();
    let borrowed: Vec<&str> = messages.iter().map(String::as_str).collect();
    put_recent(&logs, "many-names", "stream-1", &borrowed).await;
    let reported = group_fields(
        &logs,
        "1200 distinct names over 12 events",
        &json!({"logGroupName": "many-names"}),
    )
    .await;
    assert_eq!(
        reported.len(),
        MAX_REPORTED_FIELDS,
        "case 1200 distinct names over 12 events: at most {MAX_REPORTED_FIELDS} fields are reported, got {}",
        reported.len()
    );
    for name in GENERATED_FIELDS {
        assert_eq!(
            reported.get(name),
            Some(&100),
            "case 1200 distinct names over 12 events: the generated field {name} is kept, got its entry {:?}",
            reported.get(name)
        );
    }
}

/// The search is bounded by how many events it walks, too: past that ceiling the NEWEST
/// events of the window are the ones searched, so a field only the oldest events carried
/// is not reported and the percentages are over the events actually searched.
#[tokio::test]
async fn the_newest_events_of_the_window_are_the_ones_searched() {
    // `MAX_SEARCHED_EVENTS` as the handler states it, plus a tail of older events that
    // must fall outside the search.
    const MAX_SEARCHED_EVENTS: usize = 10_000;
    const OLDER: usize = 100;

    let logs = Logs::new();
    group_with_stream(&logs, "capped-scan", "stream-1", None).await;
    let total = MAX_SEARCHED_EVENTS + OLDER;
    let base = now_ms() - i64::try_from(total).expect("the count fits in an i64") - MINUTE_MS;
    let events: Vec<(i64, &str)> = (0..total)
        .map(|index| {
            (
                base + i64::try_from(index).expect("the index fits in an i64"),
                if index < OLDER {
                    r#"{"only_on_the_oldest":1}"#
                } else {
                    r#"{"on_the_newest":1}"#
                },
            )
        })
        .collect();
    // `logEvents` is modelled with a maximum length of 10000, so the events go in in
    // chunks; each chunk starts after the previous one, keeping the writes chronological.
    for chunk in events.chunks(5_000) {
        logs.ok(
            "PutLogEvents",
            &json!({
                "logGroupName": "capped-scan",
                "logStreamName": "stream-1",
                "logEvents": batch(chunk),
            }),
        )
        .await;
    }

    let reported = group_fields(
        &logs,
        "more events in the window than one search walks",
        &json!({"logGroupName": "capped-scan"}),
    )
    .await;
    assert_eq!(
        reported,
        expected_fields(&[("on_the_newest", 100)]),
        "case more events in the window than one search walks: only the newest {MAX_SEARCHED_EVENTS} events are searched, got {reported:?}"
    );
}
