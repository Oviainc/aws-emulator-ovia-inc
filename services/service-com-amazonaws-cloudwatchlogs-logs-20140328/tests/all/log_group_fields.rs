//! End-to-end tests for `GetLogGroupFields`: which fields a log group's stored events are
//! reported to carry, at which percentage, over which time window.
//!
//! Every case drives the service the way a client does — `POST /` with
//! `X-Amz-Target: Logs_20140328.GetLogGroupFields` through the router that mounts it — so a
//! response that is not computed from the shared store cannot pass.
//!
//! The tables below span the classes the rules generalise over (message form — text, JSON
//! object, JSON scalar, nested object, list —, how many of the searched events carry a
//! field, which stream carried them, where an event sits relative to each published window
//! bound, and which selector named the group); the values any one issue happens to mention
//! are single rows.

use std::collections::BTreeMap;

use serde_json::{json, Value};

use crate::harness::{batch, group_with_stream, now_ms, Logs, REGION};

/// The fields CloudWatch Logs generates for every log event, so every one of them is
/// reported at 100% whenever the searched window holds an event. Source: the operation's
/// own documentation — "fields that start with @ are fields generated by CloudWatch Logs.
/// For example, @timestamp is the timestamp of each log event" — and the crate's
/// `GENERATED_FIELDS`.
const GENERATED_FIELDS: [&str; 5] = [
    "@ingestionTime",
    "@log",
    "@logStream",
    "@message",
    "@timestamp",
];

/// One minute, in the milliseconds every stored event timestamp carries.
const MINUTE_MS: i64 = 60 * 1_000;

/// The ceilings the handler applies to one search, as its own constants state them:
/// `MAX_REPORTED_FIELDS` (how many fields one response reports), `MAX_FIELDS_PER_EVENT`
/// (how many are taken from one event, the generated five included) and `MAX_FIELD_DEPTH`
/// (how deep the JSON flattening descends).
const MAX_REPORTED_FIELDS: usize = 1_000;
const MAX_FIELDS_PER_EVENT: usize = 200;
const MAX_FIELD_DEPTH: usize = 8;

/// Write `messages` into one stream, stamped a minute apart ending just before now, so the
/// whole batch sits inside the default searched window (the most recent 15 minutes) and
/// inside `PutLogEvents`' own ingestion window.
async fn put_recent(logs: &Logs, group: &str, stream: &str, messages: &[&str]) {
    let count = i64::try_from(messages.len()).expect("the batch size fits in an i64");
    let base = now_ms() - count * MINUTE_MS;
    let events: Vec<(i64, &str)> = messages
        .iter()
        .enumerate()
        .map(|(index, message)| {
            (
                base + i64::try_from(index).expect("the index fits in an i64") * MINUTE_MS,
                *message,
            )
        })
        .collect();
    logs.ok(
        "PutLogEvents",
        &json!({
            "logGroupName": group,
            "logStreamName": stream,
            "logEvents": batch(&events),
        }),
    )
    .await;
}

/// The fields one `GetLogGroupFields` call reports, keyed by name, having checked the
/// ordering the operation documents ("The response results are sorted by the frequency
/// percentage, starting with the highest percentage").
async fn group_fields(logs: &Logs, case: &str, request: &Value) -> BTreeMap<String, i64> {
    let response = logs.ok("GetLogGroupFields", request).await;
    let listed = response
        .get("logGroupFields")
        .and_then(Value::as_array)
        .unwrap_or_else(|| {
            panic!("case {case:?}: GetLogGroupFields must return logGroupFields, got {response}")
        });
    let reported: Vec<(String, i64)> = listed
        .iter()
        .map(|field| {
            let name = field
                .get("name")
                .and_then(Value::as_str)
                .unwrap_or_else(|| {
                    panic!("case {case:?}: every reported field carries a name, got {field}")
                })
                .to_string();
            // `LogGroupField$percent` is modelled with `default: 0`, so the wire may omit
            // it for a field that rounds to no whole percent.
            let percent = field.get("percent").and_then(Value::as_i64).unwrap_or(0);
            (name, percent)
        })
        .collect();
    for pair in reported.windows(2) {
        assert!(
            pair[0].1 >= pair[1].1,
            "case {case:?}: fields are ordered by descending percent, got {reported:?}"
        );
    }
    let fields: BTreeMap<String, i64> = reported.iter().cloned().collect();
    assert_eq!(
        fields.len(),
        reported.len(),
        "case {case:?}: a field is reported at most once, got {reported:?}"
    );
    fields
}

/// The whole set of fields a window of events must report: the generated five at 100%,
/// plus the discovered fields the case expects.
fn expected_fields(discovered: &[(&str, i64)]) -> BTreeMap<String, i64> {
    let mut expected: BTreeMap<String, i64> = GENERATED_FIELDS
        .iter()
        .map(|name| ((*name).to_string(), 100))
        .collect();
    for (name, percent) in discovered {
        expected.insert((*name).to_string(), *percent);
    }
    expected
}

/// One row of the discovery table: the case's name, the messages written into the group,
/// and the non-generated fields the response must report with their percentages.
type DiscoveryCase<'a> = (&'a str, Vec<&'a str>, Vec<(&'a str, i64)>);

/// A field is reported with the percentage of the SEARCHED events that carried it: the
/// five generated fields on every event, and the keys of a JSON-object message on the
/// events that carried them. The rows differ along message form, nesting, and the fraction
/// of events a field appears in.
#[tokio::test]
async fn reported_fields_are_the_percentage_of_searched_events_that_carried_them() {
    // (case, the messages written, the non-generated fields expected, with percentages)
    let cases: Vec<DiscoveryCase<'_>> = vec![
        (
            "plain text messages name no field but the generated ones",
            vec!["boot ok", "still ok"],
            vec![],
        ),
        (
            "one JSON key carried by every event",
            vec![r#"{"level":"INFO"}"#, r#"{"level":"WARN"}"#],
            vec![("level", 100)],
        ),
        (
            "a key carried by half the events",
            vec![
                r#"{"level":"INFO","latency":12}"#,
                r#"{"level":"INFO","latency":15}"#,
                r#"{"level":"WARN"}"#,
                r#"{"level":"ERROR"}"#,
            ],
            vec![("level", 100), ("latency", 50)],
        ),
        (
            "a key carried by one of three events rounds to the nearest whole percent",
            vec![
                r#"{"level":"INFO"}"#,
                r#"{"level":"INFO","trace":"abc"}"#,
                r#"{"level":"INFO"}"#,
            ],
            vec![("level", 100), ("trace", 33)],
        ),
        (
            "a nested object and a list are flattened into their members",
            vec![r#"{"user":{"id":7,"name":"ada"},"tags":["x","y"]}"#],
            vec![
                ("user.id", 100),
                ("user.name", 100),
                ("tags.0", 100),
                ("tags.1", 100),
            ],
        ),
        (
            "an empty object and an empty list name no field of their own",
            vec![r#"{"meta":{},"items":[],"ok":true}"#],
            vec![("ok", 100)],
        ),
        (
            "a null-valued key is still a field",
            vec![r#"{"error":null}"#],
            vec![("error", 100)],
        ),
        (
            "a JSON scalar or array message names no key",
            vec!["42", "[1,2]", "\"text\"", "true"],
            vec![],
        ),
        (
            "JSON and text messages mixed: the key is carried by a quarter of them",
            vec!["plain", "also plain", "still plain", r#"{"structured":1}"#],
            vec![("structured", 25)],
        ),
    ];

    for (case, messages, discovered) in &cases {
        let logs = Logs::new();
        group_with_stream(&logs, "/aws/emulator/fields", "stream-1", None).await;
        put_recent(&logs, "/aws/emulator/fields", "stream-1", messages).await;

        let reported = group_fields(
            &logs,
            case,
            &json!({"logGroupName": "/aws/emulator/fields"}),
        )
        .await;
        assert_eq!(
            reported,
            expected_fields(discovered),
            "case {case:?}: expected the generated fields at 100% plus {discovered:?}, got {reported:?}"
        );
    }
}

/// The fields are the LOG GROUP's: every stream of the group is searched, so a key written
/// into one stream is reported at its share of the group's events, not of that stream's.
#[tokio::test]
async fn fields_are_discovered_across_every_stream_of_the_group() {
    let logs = Logs::new();
    group_with_stream(&logs, "many-streams", "stream-a", None).await;
    logs.ok(
        "CreateLogStream",
        &json!({"logGroupName": "many-streams", "logStreamName": "stream-b"}),
    )
    .await;
    put_recent(&logs, "many-streams", "stream-a", &[r#"{"from_a":1}"#]).await;
    put_recent(&logs, "many-streams", "stream-b", &[r#"{"from_b":2}"#]).await;

    let reported = group_fields(
        &logs,
        "two streams, one key each",
        &json!({"logGroupName": "many-streams"}),
    )
    .await;
    assert_eq!(
        reported,
        expected_fields(&[("from_a", 50), ("from_b", 50)]),
        "case two streams, one key each: each key is carried by half the group's events, got {reported:?}"
    );
}

/// `time` centres the search: "If you specify time, the 8 minutes before and 8 minutes
/// after this time are searched." The rows sit on each published bound of that window and
/// one minute past each, so an event outside it contributes no field and is not counted in
/// the percentages of the fields inside it.
#[tokio::test]
async fn a_named_time_searches_the_eight_minutes_either_side_of_it() {
    let logs = Logs::new();
    group_with_stream(&logs, "centred-window", "stream-1", None).await;

    // (offset from the centre in minutes, the key only that event carries, searched?)
    let rows: [(i64, &str, bool); 6] = [
        (-9, "before_the_window", false),
        (-8, "on_the_lower_bound", true),
        (-1, "inside_the_window", true),
        (0, "at_the_centre", true),
        (8, "on_the_upper_bound", true),
        (9, "after_the_window", false),
    ];
    // The centre is now, so the rows either side of it stay inside `PutLogEvents`'
    // ingestion window (14 days back to 2 hours ahead). `time` carries SECONDS, so the
    // centre is taken on a whole second and the offsets are exact against the window the
    // service computes from it.
    let centre_seconds = now_ms() / 1_000;
    let centre_ms = centre_seconds * 1_000;
    let events: Vec<(i64, String)> = rows
        .iter()
        .map(|(offset, key, _)| (centre_ms + offset * MINUTE_MS, format!(r#"{{"{key}":1}}"#)))
        .collect();
    let batched: Vec<(i64, &str)> = events
        .iter()
        .map(|(timestamp, message)| (*timestamp, message.as_str()))
        .collect();
    logs.ok(
        "PutLogEvents",
        &json!({
            "logGroupName": "centred-window",
            "logStreamName": "stream-1",
            "logEvents": batch(&batched),
        }),
    )
    .await;

    // `time` is this operation's one timestamp member in SECONDS: "The time value is
    // specified as epoch time, which is the number of seconds since January 1, 1970,
    // 00:00:00 UTC."
    let searched_count = rows.iter().filter(|(_, _, searched)| *searched).count();
    let share = i64::try_from(100 / searched_count).expect("the share fits in an i64");
    let discovered: Vec<(&str, i64)> = rows
        .iter()
        .filter(|(_, _, searched)| *searched)
        .map(|(_, key, _)| (*key, share))
        .collect();

    let reported = group_fields(
        &logs,
        "eight minutes either side of a named time",
        &json!({"logGroupName": "centred-window", "time": centre_seconds}),
    )
    .await;
    assert_eq!(
        reported,
        expected_fields(&discovered),
        "case eight minutes either side of a named time: expected only the in-window keys at {share}%, got {reported:?}"
    );
}

