//! End-to-end tests for `GetLogFields`: which fields the log events ingested through one
//! data source are reported to carry, with which data type, and how the owning log groups'
//! transformer pipelines modify that set.
//!
//! Every case drives the service the way a client does — `POST /` with
//! `X-Amz-Target: Logs_20140328.GetLogFields` through the router that mounts it — so a
//! response that is not computed from the shared store cannot pass.
//!
//! The tables below span the classes the rules generalise over (the form a stored value
//! takes — text, whole number, fractional number, boolean, null, nested object, list of
//! scalars, list of objects, empty list —, which events of which group carried it, whether
//! a group's data sources name the requested name AND type, and which processor a pipeline
//! applies); the data source an issue happens to cite is a single row.
//!
//! A data source is put in the store through [`DataSourceRecord`] — the record
//! `ListLogGroups` filters on and `ListAggregateLogGroupSummaries` counts by — because no
//! operation associates a data source with a log group yet, so no wire call can store one.
//! Everything these cases assert is read back over the wire.

use std::collections::BTreeMap;

use serde_json::{json, Value};

use service_com_amazonaws_cloudwatchlogs_logs_20140328::ops::types::TYPE_VALUES;

use crate::harness::{batch, group_with_stream, now_ms, Logs};
use crate::index_policies::seed_data_sources;

/// The operation every case calls.
const OP: &str = "GetLogFields";

/// The data source every case asks about. Source: the `GroupingIdentifier` docs, whose
/// examples of a data source's name, type and format are `amazon_vpc`, `flow` and `OCSF`.
const DATA_SOURCE_NAME: &str = "amazon_vpc";
const DATA_SOURCE_TYPE: &str = "flow";

/// One minute, in the milliseconds every stored event timestamp carries.
const MINUTE_MS: i64 = 60 * 1_000;

/// The ceilings the handler applies to one request, as its own constants state them:
/// `MAX_FIELDS_PER_EVENT` (how many names are taken from one event) and `MAX_FIELD_DEPTH`
/// (how deep the type discovery descends).
const MAX_FIELDS_PER_EVENT: usize = 200;
const MAX_FIELD_DEPTH: usize = 8;

/// The fields CloudWatch Logs generates on every stored log event, with the type the
/// handler reports for each. Source: the generated-field sentence `GetLogGroupFields`
/// documents — "fields that start with @ are fields generated by CloudWatch Logs. For
/// example, @timestamp is the timestamp of each log event" — and the two timestamps and
/// three names a stored event carries.
const GENERATED_FIELDS: [(&str, &str); 5] = [
    ("@ingestionTime", "integer"),
    ("@log", "string"),
    ("@logStream", "string"),
    ("@message", "string"),
    ("@timestamp", "integer"),
];

/// Write `messages` into one stream, stamped a minute apart ending just before now, so the
/// whole batch sits inside `PutLogEvents`' ingestion window. The LAST message is the most
/// recently ingested one, which is what decides a field's type where events disagree.
async fn put_events(logs: &Logs, group: &str, stream: &str, messages: &[&str]) {
    let count = i64::try_from(messages.len()).expect("the batch size fits in an i64");
    let base = now_ms() - count * MINUTE_MS;
    let events: Vec<(i64, &str)> = messages
        .iter()
        .enumerate()
        .map(|(index, message)| {
            (
                base + i64::try_from(index).expect("the index fits in an i64") * MINUTE_MS,
                *message,
            )
        })
        .collect();
    logs.ok(
        "PutLogEvents",
        &json!({
            "logGroupName": group,
            "logStreamName": stream,
            "logEvents": batch(&events),
        }),
    )
    .await;
}

/// A log group and stream that the data source `(name, type)` feeds, holding `messages`.
async fn group_fed_by(
    logs: &Logs,
    group: &str,
    sources: &[(&str, &str)],
    messages: &[&str],
) {
    group_with_stream(logs, group, "stream-1", None).await;
    seed_data_sources(logs, group, sources);
    if !messages.is_empty() {
        put_events(logs, group, "stream-1", messages).await;
    }
}

/// The fields one `GetLogFields` call reports, keyed by name, with each field's reported
/// type as the wire carries it (`Value::Null` for a field that carries none). Checks what
/// holds of every response on the way: a name on every field, each name reported once, and
/// the names ASCII-sorted so one store answers one request the same way every time.
async fn reported(logs: &Logs, case: &str, name: &str, source_type: &str) -> BTreeMap<String, Value> {
    let response = logs
        .ok(OP, &json!({"dataSourceName": name, "dataSourceType": source_type}))
        .await;
    let listed = response
        .get("logFields")
        .and_then(Value::as_array)
        .unwrap_or_else(|| panic!("case {case:?}: {OP} must return logFields, got {response}"))
        .clone();
    let names: Vec<String> = listed
        .iter()
        .map(|field| {
            field
                .get("logFieldName")
                .and_then(Value::as_str)
                .unwrap_or_else(|| {
                    panic!("case {case:?}: every reported field carries a logFieldName, got {field}")
                })
                .to_string()
        })
        .collect();
    let mut sorted = names.clone();
    sorted.sort();
    assert_eq!(
        names, sorted,
        "case {case:?}: fields are reported ASCII-sorted by name, got {names:?}"
    );
    let fields: BTreeMap<String, Value> = names
        .iter()
        .cloned()
        .zip(
            listed
                .iter()
                .map(|field| field.get("logFieldType").cloned().unwrap_or(Value::Null)),
        )
        .collect();
    assert_eq!(
        fields.len(),
        names.len(),
        "case {case:?}: a field is reported at most once, got {names:?}"
    );
    fields
}

/// The whole set of fields a data source holding events must report: the generated five
/// with their types, plus the fields the case discovered.
fn expected(discovered: &[(&str, Value)]) -> BTreeMap<String, Value> {
    let mut all: BTreeMap<String, Value> = GENERATED_FIELDS
        .iter()
        .map(|(name, type_name)| ((*name).to_string(), json!({"type": type_name})))
        .collect();
    for (name, field_type) in discovered {
        all.insert((*name).to_string(), field_type.clone());
    }
    all
}

/// One nested field, as `LogFieldType$fields` carries its members.
fn nested(members: &[(&str, Value)]) -> Value {
    Value::Array(
        members
            .iter()
            .map(|(name, field_type)| {
                if field_type.is_null() {
                    json!({"logFieldName": name})
                } else {
                    json!({"logFieldName": name, "logFieldType": field_type})
                }
            })
            .collect(),
    )
}

/// Every name one response reports, nested members and list element types included: what
/// the handler's `MAX_DISCOVERED_FIELDS` ceiling bounds.
fn count_reported_names(fields: &Value) -> usize {
    fields
        .as_array()
        .map(|listed| {
            listed
                .iter()
                .map(|field| {
                    let field_type = field.get("logFieldType");
                    let members = field_type
                        .and_then(|value| value.get("fields"))
                        .map(count_reported_names)
                        .unwrap_or_default();
                    let element = field_type
                        .and_then(|value| value.get("element"))
                        .map_or(0, |_| 1);
                    1 + members + element
                })
                .sum()
        })
        .unwrap_or_default()
}

/// Every scalar type name this operation reports is one of the type names the SERVICE
/// declares — the `Type` enum `TypeConverterEntry$type` targets, whose values the crate
/// exposes as `TYPE_VALUES` — because the model constrains `DataType` to no value set of
/// its own.
#[tokio::test]
async fn every_reported_scalar_type_is_one_the_service_declares() {
    let logs = Logs::new();
    group_fed_by(
        &logs,
        "typed",
        &[(DATA_SOURCE_NAME, DATA_SOURCE_TYPE)],
        &[r#"{"text":"t","whole":1,"fraction":1.5,"flag":false}"#],
    )
    .await;

    let fields = reported(&logs, "every scalar form", DATA_SOURCE_NAME, DATA_SOURCE_TYPE).await;
    for (name, field_type) in &fields {
        if let Some(type_name) = field_type.get("type").and_then(Value::as_str) {
            assert!(
                TYPE_VALUES.contains(&type_name),
                "case every scalar form: {name} is reported as type {type_name:?}, which is not one of {TYPE_VALUES:?}"
            );
        }
    }
    assert_eq!(
        fields,
        expected(&[
            ("flag", json!({"type": "boolean"})),
            ("fraction", json!({"type": "double"})),
            ("text", json!({"type": "string"})),
            ("whole", json!({"type": "integer"})),
        ]),
        "case every scalar form: expected one type per stored value form, got {fields:?}"
    );
}

/// One row of the discovery table: the case's name, the messages written into the group,
/// and the non-generated fields the response must report with their types.
type DiscoveryCase<'a> = (&'a str, Vec<&'a str>, Vec<(&'a str, Value)>);

/// A field is reported with the type its stored values have, in each form a JSON value
/// takes: a scalar names its type, a list names its element type, a nested structure names
/// its members, and a value nothing types names none. Where two events type a field
/// differently, the most recently ingested one decides it.
#[tokio::test]
async fn a_field_is_reported_with_the_type_its_stored_values_have() {
    let cases: Vec<DiscoveryCase<'_>> = vec![
        (
            "a plain text message names no field but the generated ones",
            vec!["boot ok", "still ok"],
            vec![],
        ),
        (
            "a JSON scalar or array message names no key",
            vec!["42", "[1,2]", "\"text\"", "true"],
            vec![],
        ),
        (
            "text and number keys",
            vec![r#"{"level":"INFO","latency":12}"#],
            vec![
                ("latency", json!({"type": "integer"})),
                ("level", json!({"type": "string"})),
            ],
        ),
        (
            "a null-valued key is a field with no type",
            vec![r#"{"error":null}"#],
            vec![("error", Value::Null)],
        ),
        (
            "a nested object names its members",
            vec![r#"{"user":{"id":7,"name":"ada"}}"#],
            vec![(
                "user",
                json!({"fields": nested(&[
                    ("id", json!({"type": "integer"})),
                    ("name", json!({"type": "string"})),
                ])}),
            )],
        ),
        (
            "a list of text names its element type",
            vec![r#"{"tags":["x","y"]}"#],
            vec![("tags", json!({"element": {"type": "string"}}))],
        ),
        (
            "a list of objects names the members its items name",
            vec![r#"{"rows":[{"a":1},{"b":"t"}]}"#],
            vec![(
                "rows",
                json!({"element": {"fields": nested(&[
                    ("a", json!({"type": "integer"})),
                    ("b", json!({"type": "string"})),
                ])}}),
            )],
        ),
        (
            "an empty list names no element type",
            vec![r#"{"items":[]}"#],
            vec![("items", json!({"element": {}}))],
        ),
        (
            "a key only an older event carried is still reported",
            vec![r#"{"only_old":1}"#, r#"{"only_new":"t"}"#],
            vec![
                ("only_new", json!({"type": "string"})),
                ("only_old", json!({"type": "integer"})),
            ],
        ),
        (
            "the most recent value decides a field's type",
            vec![r#"{"flips":"text"}"#, r#"{"flips":5}"#],
            vec![("flips", json!({"type": "integer"}))],
        ),
        (
            "a newer null keeps the type an older value named",
            vec![r#"{"maybe":true}"#, r#"{"maybe":null}"#],
            vec![("maybe", json!({"type": "boolean"}))],
        ),
        (
            "a key that is a scalar in one event and a structure in the newest is a structure",
            vec![r#"{"detail":"text"}"#, r#"{"detail":{"code":5}}"#],
            vec![(
                "detail",
                json!({"fields": nested(&[("code", json!({"type": "integer"}))])}),
            )],
        ),
    ];

    for (case, messages, discovered) in &cases {
        let logs = Logs::new();
        group_fed_by(
            &logs,
            "/aws/emulator/fields",
            &[(DATA_SOURCE_NAME, DATA_SOURCE_TYPE)],
            messages,
        )
        .await;

        let fields = reported(&logs, case, DATA_SOURCE_NAME, DATA_SOURCE_TYPE).await;
        assert_eq!(
            fields,
            expected(discovered),
            "case {case:?}: expected the generated fields plus {discovered:?}, got {fields:?}"
        );
    }
}

/// The fields are the DATA SOURCE's: every log group one of whose data sources is that
/// exact name AND type contributes its events' fields, and a group whose data sources name
/// another name, another type, or no type at all contributes none.
#[tokio::test]
async fn the_fields_are_those_of_every_group_the_named_data_source_feeds() {
    let logs = Logs::new();
    group_fed_by(
        &logs,
        "fed-one",
        &[(DATA_SOURCE_NAME, DATA_SOURCE_TYPE)],
        &[r#"{"from_one":1}"#],
    )
    .await;
    group_fed_by(
        &logs,
        "fed-two",
        &[("other_source", "other_type"), (DATA_SOURCE_NAME, DATA_SOURCE_TYPE)],
        &[r#"{"from_two":"t"}"#],
    )
    .await;
    group_fed_by(
        &logs,
        "other-type",
        &[(DATA_SOURCE_NAME, "other_type")],
        &[r#"{"from_other_type":1}"#],
    )
    .await;
    group_fed_by(
        &logs,
        "other-name",
        &[("other_source", DATA_SOURCE_TYPE)],
        &[r#"{"from_other_name":1}"#],
    )
    .await;
    // A group no data source feeds at all: created and written to through the wire, with
    // nothing seeded on it.
    group_with_stream(&logs, "unfed", "stream-1", None).await;
    put_events(&logs, "unfed", "stream-1", &[r#"{"from_unfed":1}"#]).await;

    let fields = reported(
        &logs,
        "two groups of the data source, three groups outside it",
        DATA_SOURCE_NAME,
        DATA_SOURCE_TYPE,
    )
    .await;
    assert_eq!(
        fields,
        expected(&[
            ("from_one", json!({"type": "integer"})),
            ("from_two", json!({"type": "string"})),
        ]),
        "case two groups of the data source, three groups outside it: expected only the fed groups' keys, got {fields:?}"
    );

    // The same store answers each other data source with its own groups' fields, so the
    // selection is the pair and not one half of it.
    let other_type = reported(&logs, "the same name, another type", DATA_SOURCE_NAME, "other_type").await;
    assert_eq!(
        other_type,
        expected(&[("from_other_type", json!({"type": "integer"}))]),
        "case the same name, another type: expected that type's group's keys, got {other_type:?}"
    );
    let other_name = reported(&logs, "another name, the same type", "other_source", DATA_SOURCE_TYPE).await;
    assert_eq!(
        other_name,
        expected(&[("from_other_name", json!({"type": "integer"}))]),
        "case another name, the same type: expected that name's group's keys, got {other_name:?}"
    );
}

/// Discovery over a data source nothing has ingested for still answers the fields every log
/// event carries — the schema available for any data source — rather than a refusal or an
/// empty list: a data source categorizes ingested logs rather than naming a resource a
/// caller created. The rows span a name and type no stored data source carries (including
/// one that names a log group instead), a stored pair whose type differs, and a fed group
/// holding no event.
#[tokio::test]
async fn a_data_source_nothing_has_ingested_for_reports_the_generated_fields() {
    let logs = Logs::new();
    group_fed_by(
        &logs,
        "fed-but-empty",
        &[(DATA_SOURCE_NAME, DATA_SOURCE_TYPE)],
        &[],
    )
    .await;
    logs.ok("CreateLogGroup", &json!({"logGroupName": "a-group"}))
        .await;

    for (case, name, source_type) in [
        (
            "a name and type no data source carries",
            "no_such_source",
            "no_such_type",
        ),
        ("a name that is a log group's", "a-group", DATA_SOURCE_TYPE),
        (
            "a stored name under another type",
            DATA_SOURCE_NAME,
            "no_such_type",
        ),
        (
            "a fed group holding no event",
            DATA_SOURCE_NAME,
            DATA_SOURCE_TYPE,
        ),
    ] {
        let fields = reported(&logs, case, name, source_type).await;
        assert_eq!(
            fields,
            expected(&[]),
            "case {case:?}: expected the fields every log event carries and nothing else, got {fields:?}"
        );
    }
}

/// One row of the pipeline table: the case, the `transformerConfig` put on the group, and
/// the non-generated fields the response must report once that pipeline is applied.
type PipelineCase<'a> = (&'a str, Value, Vec<(&'a str, Value)>);

/// "The response includes any field modifications introduced through pipelines, such as new
/// fields or changed field types": the processors that name key paths and types in their own
/// configuration are applied, in the order the pipeline lists them, to the fields the
/// group's events named. The rows span one row per such processor, a pipeline of two, a
/// write the configuration refuses to overwrite, and a processor whose output depends on the
/// event content rather than on its configuration.
#[tokio::test]
async fn the_pipeline_a_group_carries_modifies_the_reported_fields() {
    // The fields the group's events name before any pipeline runs.
    let stored = [
        ("count", json!({"type": "integer"})),
        ("level", json!({"type": "string"})),
        ("path", json!({"type": "string"})),
    ];
    let without = |dropped: &[&str]| -> Vec<(&str, Value)> {
        stored
            .iter()
            .filter(|(name, _)| !dropped.contains(name))
            .map(|(name, field_type)| (*name, field_type.clone()))
            .collect()
    };
    let with = |dropped: &[&str], added: &[(&'static str, Value)]| -> Vec<(&'static str, Value)> {
        let mut fields = without(dropped);
        fields.extend(added.iter().cloned());
        fields
    };

    let cases: Vec<PipelineCase<'_>> = vec![
        (
            "addKeys adds a field carrying the literal text it names",
            json!([{"addKeys": {"entries": [{"key": "env", "value": "prod"}]}}]),
            with(&[], &[("env", json!({"type": "string"}))]),
        ),
        (
            "deleteKeys removes the field it names",
            json!([{"deleteKeys": {"withKeys": ["count"]}}]),
            without(&["count"]),
        ),
        (
            "renameKeys reports the field under its new name",
            json!([{"renameKeys": {"entries": [{"key": "level", "renameTo": "severity"}]}}]),
            with(&["level"], &[("severity", json!({"type": "string"}))]),
        ),
        (
            "renameKeys onto an occupied key moves nothing unless it overwrites",
            json!([{"renameKeys": {"entries": [{"key": "level", "renameTo": "count"}]}}]),
            without(&[]),
        ),
        (
            "renameKeys onto an occupied key overwrites it when told to",
            json!([{"renameKeys": {"entries": [
                {"key": "level", "renameTo": "count", "overwriteIfExists": true}
            ]}}]),
            with(&["count", "level"], &[("count", json!({"type": "string"}))]),
        ),
        (
            "moveKeys reports the field under a nested key",
            json!([{"moveKeys": {"entries": [{"source": "count", "target": "metrics.count"}]}}]),
            with(
                &["count"],
                &[(
                    "metrics",
                    json!({"fields": nested(&[("count", json!({"type": "integer"}))])}),
                )],
            ),
        ),
        (
            "copyValue reports the source's type under the target too",
            json!([{"copyValue": {"entries": [{"source": "level", "target": "level_copy"}]}}]),
            with(&[], &[("level_copy", json!({"type": "string"}))]),
        ),
        (
            "typeConverter reports the converted type",
            json!([{"typeConverter": {"entries": [{"key": "count", "type": "string"}]}}]),
            with(&["count"], &[("count", json!({"type": "string"}))]),
        ),
        (
            "splitString makes a text field a list of text",
            json!([{"splitString": {"entries": [{"source": "path", "delimiter": "/"}]}}]),
            with(
                &["path"],
                &[("path", json!({"element": {"type": "string"}}))],
            ),
        ),
        (
            "dateTimeConverter adds its formatted target",
            json!([{"dateTimeConverter": {
                "source": "count",
                "target": "stamped",
                "matchPatterns": ["yyyy-MM-dd"],
            }}]),
            with(&[], &[("stamped", json!({"type": "string"}))]),
        ),
        (
            "csv reports the columns it names, under the destination it names",
            json!([{"csv": {
                "source": "path",
                "destination": "parsed",
                "columns": ["left", "right"],
            }}]),
            with(
                &[],
                &[(
                    "parsed",
                    json!({"fields": nested(&[
                        ("left", json!({"type": "string"})),
                        ("right", json!({"type": "string"})),
                    ])}),
                )],
            ),
        ),
        (
            "csv naming no column adds no field, because the data would name them",
            json!([{"csv": {"source": "path", "delimiter": ","}}]),
            without(&[]),
        ),
        (
            "a key path deeper than the discovery descends writes nothing",
            json!([{"moveKeys": {"entries": [
                {"source": "count", "target": "a.b.c.d.e.f.g.h.i.j"}
            ]}}]),
            without(&[]),
        ),
        (
            "two processors work one after another, in the order they are listed",
            json!([
                {"addKeys": {"entries": [{"key": "env", "value": "prod"}]}},
                {"deleteKeys": {"withKeys": ["env", "level"]}},
            ]),
            without(&["level"]),
        ),
        (
            "a processor that only rewrites a value changes no field",
            json!([{"upperCaseString": {"withKeys": ["level"]}}]),
            without(&[]),
        ),
        (
            "a processor whose output depends on the event content adds no field of its own",
            json!([{"parseVPC": {"source": "level"}}]),
            without(&[]),
        ),
    ];

    for (case, transformer_config, fields_expected) in &cases {
        let logs = Logs::new();
        group_fed_by(
            &logs,
            "piped",
            &[(DATA_SOURCE_NAME, DATA_SOURCE_TYPE)],
            &[r#"{"level":"INFO","count":3,"path":"a/b"}"#],
        )
        .await;
        logs.ok(
            "PutTransformer",
            &json!({"logGroupIdentifier": "piped", "transformerConfig": transformer_config}),
        )
        .await;

        let fields = reported(&logs, case, DATA_SOURCE_NAME, DATA_SOURCE_TYPE).await;
        assert_eq!(
            fields,
            expected(fields_expected),
            "case {case:?}: expected {fields_expected:?} beside the generated fields, got {fields:?}"
        );
    }
}

/// A pipeline cannot grow one response past the discovery ceiling: a `copyValue` that clones
/// a wide subtree over a target INSIDE that same subtree doubles what the tree holds per
/// entry, so the names a write adds are charged and the names it replaces refunded, and a
/// write the ceiling cannot pay for does not happen.
#[tokio::test]
async fn a_pipeline_cannot_grow_one_response_past_the_discovery_ceiling() {
    /// `MAX_DISCOVERED_FIELDS` as the handler states it: how many names one response reports.
    const MAX_DISCOVERED_FIELDS: usize = 1_000;

    // One event naming a wide nested object, so a clone of it is a large subtree.
    let wide: String = {
        let keys: Vec<String> = (0..100)
            .map(|index| format!(r#""k{index:03}":{index}"#))
            .collect();
        format!(r#"{{"a":{{{}}}}}"#, keys.join(","))
    };
    // `CopyValueEntries` is modelled with a maximum length of 5, so the clones go in as
    // several processors of five entries each; each entry overwrites a target under `a`, so
    // every one of them copies whatever the previous entries left there.
    let processors: Vec<Value> = (0..8)
        .map(|processor| {
            let entries: Vec<Value> = (0..5)
                .map(|entry| {
                    json!({
                        "source": "a",
                        "target": format!("a.c{processor}{entry}"),
                        "overwriteIfExists": true,
                    })
                })
                .collect();
            json!({"copyValue": {"entries": entries}})
        })
        .collect();

    let logs = Logs::new();
    group_fed_by(
        &logs,
        "amplified",
        &[(DATA_SOURCE_NAME, DATA_SOURCE_TYPE)],
        &[wide.as_str()],
    )
    .await;
    logs.ok(
        "PutTransformer",
        &json!({"logGroupIdentifier": "amplified", "transformerConfig": processors}),
    )
    .await;

    let response = logs
        .ok(
            OP,
            &json!({"dataSourceName": DATA_SOURCE_NAME, "dataSourceType": DATA_SOURCE_TYPE}),
        )
        .await;
    let names = count_reported_names(&response["logFields"]);
    assert!(
        names <= MAX_DISCOVERED_FIELDS + GENERATED_FIELDS.len(),
        "case 40 subtree clones over nested targets: expected at most {} names, got {names}",
        MAX_DISCOVERED_FIELDS + GENERATED_FIELDS.len()
    );
    // The response is still an answer about the data source, not a truncation to nothing:
    // the fields the event named survive the ceiling.
    let fields = reported(
        &logs,
        "40 subtree clones over nested targets",
        DATA_SOURCE_NAME,
        DATA_SOURCE_TYPE,
    )
    .await;
    for (name, type_name) in GENERATED_FIELDS {
        assert_eq!(
            fields.get(name),
            Some(&json!({"type": type_name})),
            "case 40 subtree clones over nested targets: the generated field {name} is still reported, got {:?}",
            fields.get(name)
        );
    }
    assert!(
        fields.contains_key("a"),
        "case 40 subtree clones over nested targets: the event's own field is still reported, got {:?}",
        fields.keys().collect::<Vec<_>>()
    );
}

