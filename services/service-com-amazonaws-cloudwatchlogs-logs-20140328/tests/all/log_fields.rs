/// The operation only reports: two identical calls answer identically, and nothing a later
/// caller reads — the events, the group, its transformer — changes because the fields were
/// read.
#[tokio::test]
async fn reporting_the_fields_changes_nothing_a_later_caller_sees() {
    let logs = Logs::new();
    group_fed_by(
        &logs,
        "read-only",
        &[(DATA_SOURCE_NAME, DATA_SOURCE_TYPE)],
        &[r#"{"level":"INFO"}"#, r#"{"level":"WARN","latency":3}"#],
    )
    .await;
    logs.ok(
        "PutTransformer",
        &json!({
            "logGroupIdentifier": "read-only",
            "transformerConfig": [{"addKeys": {"entries": [{"key": "env", "value": "prod"}]}}],
        }),
    )
    .await;

    let events_before = logs
        .ok(
            "GetLogEvents",
            &json!({
                "logGroupName": "read-only",
                "logStreamName": "stream-1",
                "startFromHead": true,
            }),
        )
        .await;
    let first = reported(&logs, "first call", DATA_SOURCE_NAME, DATA_SOURCE_TYPE).await;
    let second = reported(&logs, "second call", DATA_SOURCE_NAME, DATA_SOURCE_TYPE).await;
    let events_after = logs
        .ok(
            "GetLogEvents",
            &json!({
                "logGroupName": "read-only",
                "logStreamName": "stream-1",
                "startFromHead": true,
            }),
        )
        .await;

    assert_eq!(
        first,
        expected(&[
            ("env", json!({"type": "string"})),
            ("latency", json!({"type": "integer"})),
            ("level", json!({"type": "string"})),
        ]),
        "case first call: expected the stored events' fields and the pipeline's, got {first:?}"
    );
    assert_eq!(
        second, first,
        "case second call: a report is repeatable, got {second:?} after {first:?}"
    );
    assert_eq!(
        events_after["events"], events_before["events"],
        "case the events after the report: reporting the fields must not change them, got {events_after} after {events_before}"
    );
    let transformer = logs
        .ok("GetTransformer", &json!({"logGroupIdentifier": "read-only"}))
        .await;
    assert_eq!(
        transformer["transformerConfig"],
        json!([{"addKeys": {"entries": [{"key": "env", "value": "prod", "overwriteIfExists": false}]}}]),
        "case the transformer after the report: the pipeline is unchanged by a read, got {transformer}"
    );
}

/// One response is bounded by the handler's own ceilings, and they cut the documented side:
/// one event contributes at most `MAX_FIELDS_PER_EVENT` names, and the type discovery stops
/// descending at `MAX_FIELD_DEPTH`, where the value is reported as a field with no type.
#[tokio::test]
async fn one_response_is_bounded_by_the_handlers_own_ceilings() {
    // A message naming far more keys than one event may contribute.
    let wide: String = {
        let keys: Vec<String> = (0..500)
            .map(|index| format!(r#""k{index:04}":{index}"#))
            .collect();
        format!("{{{}}}", keys.join(","))
    };
    let logs = Logs::new();
    group_fed_by(
        &logs,
        "wide",
        &[(DATA_SOURCE_NAME, DATA_SOURCE_TYPE)],
        &[wide.as_str()],
    )
    .await;
    let fields = reported(&logs, "one event naming 500 keys", DATA_SOURCE_NAME, DATA_SOURCE_TYPE).await;
    assert_eq!(
        fields.len(),
        MAX_FIELDS_PER_EVENT + GENERATED_FIELDS.len(),
        "case one event naming 500 keys: one event contributes at most {MAX_FIELDS_PER_EVENT} names beside the generated ones, got {}",
        fields.len()
    );
    for (name, type_name) in GENERATED_FIELDS {
        assert_eq!(
            fields.get(name),
            Some(&json!({"type": type_name})),
            "case one event naming 500 keys: the generated field {name} survives the cut, got {:?}",
            fields.get(name)
        );
    }

    // A message nested far deeper than the discovery descends: the walk reports the value it
    // stops at as a field with no type, so the reported nesting is exactly the ceiling.
    let deep: String = {
        let mut message = "1".to_string();
        for level in (0..12).rev() {
            message = format!(r#"{{"n{level}":{message}}}"#);
        }
        message
    };
    let logs = Logs::new();
    group_fed_by(
        &logs,
        "deep",
        &[(DATA_SOURCE_NAME, DATA_SOURCE_TYPE)],
        &[deep.as_str()],
    )
    .await;
    let fields = reported(&logs, "one event nested 12 deep", DATA_SOURCE_NAME, DATA_SOURCE_TYPE).await;
    let mut node = fields
        .get("n0")
        .cloned()
        .unwrap_or_else(|| panic!("case one event nested 12 deep: n0 is reported, got {fields:?}"));
    let mut depth = 1usize;
    while let Some(members) = node.get("fields").and_then(Value::as_array).cloned() {
        assert_eq!(
            members.len(),
            1,
            "case one event nested 12 deep: each level names one member, got {members:?}"
        );
        node = members[0]
            .get("logFieldType")
            .cloned()
            .unwrap_or(Value::Null);
        depth += 1;
    }
    assert_eq!(
        depth, MAX_FIELD_DEPTH,
        "case one event nested 12 deep: the discovery descends {MAX_FIELD_DEPTH} levels, got {depth}"
    );
    assert_eq!(
        node,
        Value::Null,
        "case one event nested 12 deep: the value the walk stops at is reported with no type, got {node}"
    );
}
