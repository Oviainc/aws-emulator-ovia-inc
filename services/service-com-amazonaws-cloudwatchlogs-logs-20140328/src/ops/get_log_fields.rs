/// The type names a reported scalar field carries.
///
/// `DataType` — what `LogFieldType$type` targets — is an unconstrained string in the
/// model, so the names come from the one type vocabulary this service does declare:
/// `Type`, the enum `TypeConverterEntry$type` targets, whose values
/// `super::types::TYPE_VALUES` lists as `boolean`, `double`, `integer` and `string`.
/// A composite value names no type of its own: a list is identified by the
/// `LogFieldType$element` the model gives it, and a nested structure by
/// `LogFieldType$fields`.
const TYPE_BOOLEAN: &str = "boolean";
const TYPE_DOUBLE: &str = "double";
const TYPE_INTEGER: &str = "integer";
const TYPE_STRING: &str = "string";

