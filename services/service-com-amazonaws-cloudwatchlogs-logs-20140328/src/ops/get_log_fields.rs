/// THE EMULATOR'S OWN CEILING on how many stored events one request reads, over every log
/// group the data source feeds: the groups' streams would otherwise multiply out to
/// everything ever ingested. The NEWEST events of a stream are the ones read, so the cut
/// falls on the oldest.
const MAX_SEARCHED_EVENTS: usize = 10_000;

/// THE EMULATOR'S OWN CEILING on how many message BYTES one request reads, the second
/// factor of the same product: one stream may hold megabytes of messages and a group many
/// streams.
const MAX_SEARCHED_BYTES: usize = 4 * 1024 * 1024;

/// THE EMULATOR'S OWN CEILING on how many field names are taken from ONE event: a single
/// JSON message can name arbitrarily many keys, and each name costs an allocation.
const MAX_FIELDS_PER_EVENT: usize = 200;

/// THE EMULATOR'S OWN CEILING on how deep the type discovery descends, so a reported
/// field's nesting is bounded here rather than inherited from whatever the JSON parser
/// admits. A value nested deeper than this is reported as a field with no type.
const MAX_FIELD_DEPTH: usize = 8;

/// THE EMULATOR'S OWN CEILING on how many fields one response reports, nested members
/// included. Once this many are discovered a further NEW name is not added; the names
/// already discovered keep merging, so what one request allocates is bounded by this
/// constant rather than by how much log data the data source holds.
const MAX_DISCOVERED_FIELDS: usize = 1_000;

/// THE EMULATOR'S OWN CEILING on how many dot-separated segments of a processor's key path
/// are followed. A path longer than the discovery descends names a field the response could
/// not report anyway, so it is not followed at all rather than walked to whatever depth the
/// stored configuration happens to name.
const MAX_PATH_SEGMENTS: usize = MAX_FIELD_DEPTH;

/// THE EMULATOR'S OWN CEILING on how deep a reported field tree nests: a value discovered
/// from a message is at most [`MAX_FIELD_DEPTH`] deep and a processor writes it at most
/// [`MAX_PATH_SEGMENTS`] deep, so no pipeline — however many processors it chains — can
/// build a tree past this, and every walk over a tree ([`count_names`], [`merge`],
/// [`log_field_type`]) descends at most this far.
const MAX_TREE_DEPTH: usize = MAX_FIELD_DEPTH + MAX_PATH_SEGMENTS;

/// How many events the read walks between yields, so a cancelled or timed-out request has
/// somewhere to land instead of walking every message first.
const SEARCH_YIELD_INTERVAL: usize = 256;

/// The type one discovered field has, in the three shapes `LogFieldType` can report:
/// a type name, a list with an element type, or a nested structure with its own fields.
#[derive(Debug, Clone, PartialEq, Eq)]
enum FieldSchema {
    /// A scalar value, named by the type it has, or unnamed when nothing stored for the
    /// field names one (a JSON `null`, or a value past [`MAX_FIELD_DEPTH`]).
    Scalar(Option<String>),
    /// A list, whose element type is the one its items have.
    List(Box<FieldSchema>),
    /// A nested structure, whose members are fields in their own right.
    Fields(BTreeMap<String, FieldSchema>),
}

/// How many names a schema holds, itself included: what adding it to a response costs
/// against [`MAX_DISCOVERED_FIELDS`]. Descends at most [`MAX_TREE_DEPTH`], the depth every
/// stored tree is bounded to.
fn count_names(schema: &FieldSchema) -> usize {
    match schema {
        FieldSchema::Scalar(_) => 1,
        FieldSchema::List(element) => 1 + count_names(element),
        FieldSchema::Fields(members) => 1 + members.values().map(count_names).sum::<usize>(),
    }
}

/// How deep a schema nests, itself counted as one level: what a write at a given path adds
/// to the depth of the tree it lands in, which [`write_path`] holds to [`MAX_TREE_DEPTH`].
fn depth_of(schema: &FieldSchema) -> usize {
    match schema {
        FieldSchema::Scalar(_) => 1,
        FieldSchema::List(element) => 1 + depth_of(element),
        FieldSchema::Fields(members) => {
            1 + members.values().map(depth_of).max().unwrap_or_default()
        }
    }
}

/// The schema one stored JSON value has. `budget` bounds how many names this one value may
/// contribute ([`MAX_FIELDS_PER_EVENT`]) and `depth` how far the walk descends
/// ([`MAX_FIELD_DEPTH`]); a value the walk stops at is reported as a field with no type,
/// rather than as a name whose length and count the message decides.
fn schema_of(value: &::serde_json::Value, depth: usize, budget: &mut usize) -> FieldSchema {
    if depth >= MAX_FIELD_DEPTH {
        return FieldSchema::Scalar(None);
    }
    match value {
        // A `null` value names no type: the field is there, its type is not known.
        ::serde_json::Value::Null => FieldSchema::Scalar(None),
        ::serde_json::Value::Bool(_) => FieldSchema::Scalar(Some(TYPE_BOOLEAN.to_string())),
        // A JSON number is `integer` when it is whole and `double` when it is not, which
        // is the distinction this service's own type vocabulary draws.
        ::serde_json::Value::Number(number) => FieldSchema::Scalar(Some(
            if number.is_f64() {
                TYPE_DOUBLE
            } else {
                TYPE_INTEGER
            }
            .to_string(),
        )),
        ::serde_json::Value::String(_) => FieldSchema::Scalar(Some(TYPE_STRING.to_string())),
        // Every item of a list contributes to ONE element type, so a list of objects
        // reports the union of the members its items name.
        ::serde_json::Value::Array(items) => {
            let mut element: Option<FieldSchema> = None;
            for item in items {
                let item_schema = schema_of(item, depth + 1, budget);
                element = Some(match element.take() {
                    Some(discovered) => merge(item_schema, discovered, budget),
                    None => item_schema,
                });
            }
            FieldSchema::List(Box::new(element.unwrap_or(FieldSchema::Scalar(None))))
        }
        ::serde_json::Value::Object(members) => {
            let mut fields: BTreeMap<String, FieldSchema> = BTreeMap::new();
            for (key, member) in members {
                if *budget == 0 {
                    break;
                }
                *budget -= 1;
                fields.insert(key.clone(), schema_of(member, depth + 1, budget));
            }
            FieldSchema::Fields(fields)
        }
    }
}

/// Merge the schema an older value gave a field into the one a newer value gave it.
///
/// The newer value wins where the two disagree — a field's reported type is the one its
/// most recent value has, which is what makes a type change observable — while names only
/// the older value carried are kept, so the response reports every field the data source's
/// events name. `budget` bounds how many names the merge may add
/// ([`MAX_DISCOVERED_FIELDS`]), and the walk descends at most [`MAX_TREE_DEPTH`], the depth
/// every stored tree is bounded to.
fn merge(newer: FieldSchema, older: FieldSchema, budget: &mut usize) -> FieldSchema {
    match (newer, older) {
        (FieldSchema::Fields(mut newer_members), FieldSchema::Fields(older_members)) => {
            merge_fields(&mut newer_members, older_members, budget);
            FieldSchema::Fields(newer_members)
        }
        (FieldSchema::List(newer_element), FieldSchema::List(older_element)) => {
            FieldSchema::List(Box::new(merge(*newer_element, *older_element, budget)))
        }
        // The newer value named no type at all, so whatever an older one named stands.
        (FieldSchema::Scalar(None), older) => {
            let cost = count_names(&older).saturating_sub(1);
            if cost <= *budget {
                *budget -= cost;
                older
            } else {
                FieldSchema::Scalar(None)
            }
        }
        (newer, _) => newer,
    }
}

/// Merge the fields an older set of values named into the ones a newer set named, member by
/// member: [`merge`] over two field trees, which is how one event's fields join the ones
/// already discovered and how one log group's join the response's.
fn merge_fields(
    newer: &mut BTreeMap<String, FieldSchema>,
    older: BTreeMap<String, FieldSchema>,
    budget: &mut usize,
) {
    for (name, older_member) in older {
        match newer.remove(&name) {
            Some(newer_member) => {
                newer.insert(name, merge(newer_member, older_member, budget));
            }
            None => {
                let cost = count_names(&older_member);
                if cost <= *budget {
                    *budget -= cost;
                    newer.insert(name, older_member);
                }
            }
        }
    }
}

/// The node `path` — a dot-separated key path, the notation a transformer's processors name
/// a nested key by — reaches, removed from the tree it was in.
///
/// Walked ITERATIVELY and only as far as [`MAX_PATH_SEGMENTS`], so how deep a stored
/// processor's key path is cannot set how deep this descends.
fn take_path(fields: &mut BTreeMap<String, FieldSchema>, path: &str) -> Option<FieldSchema> {
    if path.split('.').count() > MAX_PATH_SEGMENTS {
        return None;
    }
    let mut segments = path.split('.').peekable();
    let mut current = fields;
    loop {
        let segment = segments.next()?;
        if segments.peek().is_none() {
            return current.remove(segment);
        }
        match current.get_mut(segment) {
            Some(FieldSchema::Fields(members)) => current = members,
            _ => return None,
        }
    }
}

/// The node `path` reaches, left where it is. Bounded like [`take_path`].
fn read_path(fields: &BTreeMap<String, FieldSchema>, path: &str) -> Option<FieldSchema> {
    if path.split('.').count() > MAX_PATH_SEGMENTS {
        return None;
    }
    let mut segments = path.split('.').peekable();
    let mut current = fields;
    loop {
        let segment = segments.next()?;
        let node = current.get(segment)?;
        if segments.peek().is_none() {
            return Some(node.clone());
        }
        match node {
            FieldSchema::Fields(members) => current = members,
            _ => return None,
        }
    }
}

/// Write `schema` at `path`, answering whether the write happened: a path a field already
/// occupies is written only when the processor says to overwrite it. Missing parents along
/// the path are created as nested structures, which is what writing a nested key does.
///
/// Walked ITERATIVELY, and three ceilings decide what may be written at all: the path is
/// followed at most [`MAX_PATH_SEGMENTS`] segments, the tree it lands in stays within
/// [`MAX_TREE_DEPTH`], and `budget` — the names this tree may still hold — is charged for
/// everything the write adds, each created parent included, and refunded for whatever the
/// write replaces, so a write it cannot pay for does not happen. So neither the key paths a
/// stored pipeline names, nor how many processors chain, nor what they copy over what
/// decides how much one request allocates or how deep anything reading the tree back
/// descends.
fn write_path(
    fields: &mut BTreeMap<String, FieldSchema>,
    path: &str,
    schema: FieldSchema,
    overwrite: bool,
    budget: &mut usize,
) -> bool {
    let segment_count = path.split('.').count();
    if segment_count > MAX_PATH_SEGMENTS || segment_count + depth_of(&schema) > MAX_TREE_DEPTH {
        return false;
    }
    let mut segments = path.split('.').peekable();
    let mut current = fields;
    loop {
        let Some(segment) = segments.next() else {
            return false;
        };
        if segments.peek().is_none() {
            let replaced = current.get(segment);
            if replaced.is_some() && !overwrite {
                return false;
            }
            // The budget is the names this tree may still hold, so a write accounts for
            // BOTH sides of it: what it replaces is refunded and what it writes is charged,
            // and a write it cannot pay for does not happen. An overwrite that skipped the
            // charge would let a pipeline copying a subtree over a node inside that same
            // subtree grow the tree without bound.
            let refund = replaced.map(count_names).unwrap_or_default();
            let cost = count_names(&schema);
            let available = budget.saturating_add(refund);
            if cost > available {
                return false;
            }
            *budget = available - cost;
            current.insert(segment.to_string(), schema);
            return true;
        }
        // An intermediate parent: created when the path names one the tree does not hold,
        // and charged against the budget like any other name it adds. A parent that is not
        // a nested structure becomes one, which is what writing a key underneath it does.
        if !current.contains_key(segment) {
            if *budget == 0 {
                return false;
            }
            *budget -= 1;
        }
        let parent = current
            .entry(segment.to_string())
            .or_insert_with(|| FieldSchema::Fields(BTreeMap::new()));
        if !matches!(parent, FieldSchema::Fields(_)) {
            *parent = FieldSchema::Fields(BTreeMap::new());
        }
        let FieldSchema::Fields(members) = parent else {
            return false;
        };
        current = members;
    }
}

/// Apply one processor of a log group's transformer to the fields discovered for that
/// group, so the response "includes any field modifications introduced through pipelines,
/// such as new fields or changed field types".
///
/// Only the processors whose effect on the FIELD SET is fixed by their own configuration
/// are applied here — the ones that name key paths, column names or types. A processor whose
/// output fields depend on the content of each event (a grok match, a parser, a list keyed
/// by the data, a `csv` that lists no column names) leaves the field set as the stored
/// events name it, and one that only rewrites a value in place (case, trimming,
/// substitution) changes neither a field's name nor its type.
///
/// Destructured EXHAUSTIVELY — no `..` — so a processor kind the model gains is a COMPILE
/// error here rather than a transformation this function silently cannot see.
fn apply_processor(
    fields: &mut BTreeMap<String, FieldSchema>,
    processor: &Processor,
    budget: &mut usize,
) {
    let Processor {
        add_keys,
        copy_value,
        csv,
        date_time_converter,
        delete_keys,
        grok: _,
        list_to_map: _,
        lower_case_string: _,
        move_keys,
        parse_cloudfront: _,
        parse_json: _,
        parse_key_value: _,
        parse_route53: _,
        parse_to_ocsf: _,
        parse_postgres: _,
        parse_vpc: _,
        parse_waf: _,
        rename_keys,
        split_string,
        substitute_string: _,
        trim_string: _,
        type_converter,
        upper_case_string: _,
    } = processor;

    // `addKeys` adds a key carrying the literal text the entry names, so the new field is
    // text.
    if let Some(add_keys) = add_keys {
        for entry in &add_keys.entries {
            write_path(
                fields,
                &entry.key,
                FieldSchema::Scalar(Some(TYPE_STRING.to_string())),
                entry.overwrite_if_exists,
                budget,
            );
        }
    }

    // `copyValue` copies a field's value to a second key, so the target carries the
    // source's type and the source stays.
    if let Some(copy_value) = copy_value {
        for entry in &copy_value.entries {
            if let Some(schema) = read_path(fields, &entry.source) {
                write_path(
                    fields,
                    &entry.target,
                    schema,
                    entry.overwrite_if_exists,
                    budget,
                );
            }
        }
    }

    // `csv` splits a source field into one field per column. Its column NAMES are fixed by
    // the configuration only when the processor lists them — the names to use for the
    // columns of the transformed event — and they carry the text each column holds, under
    // the destination the processor names when it names one. A `csv` listing no column names
    // names them after how many columns the data has, so it adds no field here.
    if let Some(csv) = csv {
        if let Some(columns) = &csv.columns {
            for column in columns {
                let target = match &csv.destination {
                    Some(destination) => format!("{destination}.{column}"),
                    None => column.clone(),
                };
                write_path(
                    fields,
                    &target,
                    FieldSchema::Scalar(Some(TYPE_STRING.to_string())),
                    false,
                    budget,
                );
            }
        }
    }

    // `dateTimeConverter` writes the converted date to its target key as formatted text.
    if let Some(converter) = date_time_converter {
        write_path(
            fields,
            &converter.target,
            FieldSchema::Scalar(Some(TYPE_STRING.to_string())),
            true,
            budget,
        );
    }

    // `deleteKeys` removes the keys it names, so those fields are no longer available.
    if let Some(delete_keys) = delete_keys {
        for key in &delete_keys.with_keys {
            take_path(fields, key);
        }
    }

    // `moveKeys` moves a field to a second key: the target takes the source's type and the
    // source is gone — unless the target is occupied and the entry does not overwrite it,
    // in which case nothing moves.
    if let Some(move_keys) = move_keys {
        for entry in &move_keys.entries {
            if let Some(schema) = read_path(fields, &entry.source) {
                if write_path(
                    fields,
                    &entry.target,
                    schema,
                    entry.overwrite_if_exists,
                    budget,
                ) {
                    take_path(fields, &entry.source);
                }
            }
        }
    }

    // `renameKeys` is the same move under a new name.
    if let Some(rename_keys) = rename_keys {
        for entry in &rename_keys.entries {
            if let Some(schema) = read_path(fields, &entry.key) {
                if write_path(
                    fields,
                    &entry.rename_to,
                    schema,
                    entry.overwrite_if_exists,
                    budget,
                ) {
                    take_path(fields, &entry.key);
                }
            }
        }
    }

    // `splitString` splits a field's text on a delimiter, so that field becomes a list of
    // text rather than text.
    if let Some(split_string) = split_string {
        for entry in &split_string.entries {
            if read_path(fields, &entry.source).is_some() {
                write_path(
                    fields,
                    &entry.source,
                    FieldSchema::List(Box::new(FieldSchema::Scalar(Some(
                        TYPE_STRING.to_string(),
                    )))),
                    true,
                    budget,
                );
            }
        }
    }

    // `typeConverter` converts a field's value to the type the entry names, which is the
    // changed field type the operation reports. A key the events do not carry is not
    // converted into existence.
    if let Some(type_converter) = type_converter {
        for entry in &type_converter.entries {
            if read_path(fields, &entry.key).is_some() {
                write_path(
                    fields,
                    &entry.key,
                    FieldSchema::Scalar(Some(entry.r#type.clone())),
                    true,
                    budget,
                );
            }
        }
    }
}

/// One `LogFieldsListItem` per discovered field, ASCII-sorted by name at every level: the
/// model documents no order for `logFields`, so one store answers one request the same way
/// every time.
fn log_fields(fields: &BTreeMap<String, FieldSchema>) -> Vec<LogFieldsListItem> {
    fields
        .iter()
        .map(|(name, schema)| LogFieldsListItem {
            log_field_name: Some(name.clone()),
            log_field_type: log_field_type(schema),
        })
        .collect()
}

/// One field's type as `LogFieldType` carries it: a type name for a scalar, an `element`
/// for a list, `fields` for a nested structure — and nothing at all for a field whose
/// stored values name no type.
fn log_field_type(schema: &FieldSchema) -> Option<LogFieldType> {
    match schema {
        FieldSchema::Scalar(None) => None,
        FieldSchema::Scalar(Some(name)) => Some(LogFieldType {
            r#type: Some(name.clone()),
            element: None,
            fields: None,
        }),
        FieldSchema::List(element) => Some(LogFieldType {
            r#type: None,
            element: Some(Box::new(log_field_type(element).unwrap_or_default())),
            fields: None,
        }),
        FieldSchema::Fields(members) => Some(LogFieldType {
            r#type: None,
            element: None,
            fields: Some(log_fields(members)),
        }),
    }
}

/// The messages one log group contributes, newest first, and the transformer pipeline that
/// group's events go through.
struct SelectedGroup {
    messages: Vec<String>,
    processors: Vec<Processor>,
}

/// The `GetLogFields` operation.
///
/// Owns the shared engine (the constructor seam) and implements
/// [`smithy_server_runtime::Operation`]. Generic over the engine type `Eng`, so this
/// crate names no concrete engine type: a migrated service that needs state picks a
/// concrete engine where it mounts the service, not here.
pub struct GetLogFields<Eng> {
    engine: ::std::sync::Arc<Eng>,
}

impl<Eng> GetLogFields<Eng> {
    /// Construct the operation from the shared engine. INFALLIBLE — the engine is a
    /// construction-time dependency, so engine access is guaranteed by the time any
    /// request runs. Called by the generated `EmulatedService::new(engine)` constructor.
    pub fn new(engine: ::std::sync::Arc<Eng>) -> Self {
        Self { engine }
    }
}

impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for GetLogFields<Eng>
{
    type Input = GetLogFieldsInput;
    type Output = GetLogFieldsOutput;
    type Error = GetLogFieldsError;

    const NAME: &'static str = "GetLogFields";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_LOG_FIELDS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_LOG_FIELDS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `ctx` carries only request metadata; this operation answers from the store.
        let _ = ctx;

        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            GetLogFieldsError::from(GetLogFieldsErrorModeled::ServiceUnavailableException(
                ServiceUnavailableException {
                    message: Some("the log store is unavailable".to_string()),
                },
            ))
        })?;

        // A data source "categorizes logs by originating service and log type" and the
        // request names ONE of them, so a log group names fields for it only when one of the
        // data sources that ingest into it is that exact name AND type. Discovery over a
        // categorization this account holds no logs for is still an answer rather than a
        // missing resource — the fields every log event carries are available for it — so no
        // matching group is not a refusal.
        //
        // Only the messages are taken while the store is locked, and only as many as
        // [`MAX_SEARCHED_EVENTS`] and [`MAX_SEARCHED_BYTES`] admit; the parsing and type
        // discovery then run with the lock released, so one request neither grows with
        // everything ever ingested nor serialises every other caller.
        let selected: Vec<SelectedGroup> = {
            let store = state.lock();
            let mut selected: Vec<SelectedGroup> = Vec::new();
            let mut events_read = 0usize;
            let mut bytes_read = 0usize;
            for group in store.log_groups.values() {
                let feeds_group = group.data_sources.iter().any(|source| {
                    source.name == input.data_source_name
                        && source.source_type.as_deref() == Some(input.data_source_type.as_str())
                });
                if !feeds_group {
                    continue;
                }
                if events_read >= MAX_SEARCHED_EVENTS || bytes_read >= MAX_SEARCHED_BYTES {
                    break;
                }
                // A stream's events are kept sorted by `(timestamp, ingestion_seq)`
                // (`crate::state::LogStreamRecord::events`), so taking them in reverse
                // takes the newest first and the ceilings cut the oldest. The group's
                // streams are then merged back into one newest-first run, because a
                // field's type is the one its most recent value in the GROUP has.
                let mut taken: Vec<(crate::state::EventKey, String)> = Vec::new();
                for stream in group.streams.values() {
                    for event in stream.events.iter().rev() {
                        if events_read >= MAX_SEARCHED_EVENTS || bytes_read >= MAX_SEARCHED_BYTES {
                            break;
                        }
                        events_read += 1;
                        bytes_read = bytes_read.saturating_add(event.message.len());
                        taken.push((event.key(), event.message.clone()));
                    }
                }
                taken.sort_by_key(|(key, _)| ::std::cmp::Reverse(*key));
                selected.push(SelectedGroup {
                    messages: taken.into_iter().map(|(_, message)| message).collect(),
                    processors: group
                        .transformer
                        .as_ref()
                        .map(|transformer| transformer.processors.clone())
                        .unwrap_or_default(),
                });
            }
            selected
        };

        // One budget bounds the names the RESPONSE holds, and a fresh one bounds the names
        // discovered for each group, so neither how many groups a data source feeds nor how
        // much each holds decides what one request allocates.
        let mut response_budget = MAX_DISCOVERED_FIELDS;
        let mut discovered: BTreeMap<String, FieldSchema> = BTreeMap::new();
        let mut walked = 0usize;
        for group in &selected {
            let mut group_budget = MAX_DISCOVERED_FIELDS;
            let mut group_fields: BTreeMap<String, FieldSchema> = BTreeMap::new();
            for message in &group.messages {
                // A yield every `SEARCH_YIELD_INTERVAL` events, so a cancelled or
                // timed-out request has somewhere to land mid-read.
                if walked > 0 && walked.is_multiple_of(SEARCH_YIELD_INTERVAL) {
                    ::tokio::task::yield_now().await;
                }
                walked += 1;
                // Only a JSON OBJECT is a structured log event: a message that is bare
                // text (or a bare JSON scalar or array, which names no keys) names no
                // field of its own.
                let Ok(value) = ::serde_json::from_str::<::serde_json::Value>(message) else {
                    continue;
                };
                if !value.is_object() {
                    continue;
                }
                let mut per_event = MAX_FIELDS_PER_EVENT;
                if let FieldSchema::Fields(event_fields) = schema_of(&value, 0, &mut per_event) {
                    merge_fields(&mut group_fields, event_fields, &mut group_budget);
                }
            }
            // The fields CloudWatch Logs generates are carried by every log event the group
            // holds — and by every one it will hold, so a group the data source feeds names
            // them whether or not an event has been ingested into it yet. They are
            // GENERATED, so a message key of the same name does not redefine them, and they
            // go in before the pipeline runs, because a pipeline that drops or retypes one of
            // them modifies what this group's logs carry like any other field.
            for (name, type_name) in GENERATED_FIELDS {
                group_fields.insert(
                    name.to_string(),
                    FieldSchema::Scalar(Some(type_name.to_string())),
                );
            }
            // "The processors work one after another, in the order that you list them,
            // like a pipeline", so the group's processors are applied in that order to the
            // fields its events named — which is also how a pipeline that DECLARES a field
            // names one for a group nothing has been written to yet.
            for processor in &group.processors {
                apply_processor(&mut group_fields, processor, &mut group_budget);
            }
            merge_fields(&mut discovered, group_fields, &mut response_budget);
        }

        // The fields CloudWatch Logs generates on every log event are available for any
        // data source, whatever has been ingested through it, so they are the schema
        // reported when no log group names that data source at all: discovery over a
        // categorization this account holds no logs for answers what every log event
        // carries, not nothing at all.
        if selected.is_empty() {
            for (name, type_name) in GENERATED_FIELDS {
                discovered.insert(
                    name.to_string(),
                    FieldSchema::Scalar(Some(type_name.to_string())),
                );
            }
        }

        Ok(GetLogFieldsOutput {
            log_fields: Some(log_fields(&discovered)),
        })
    }
}
