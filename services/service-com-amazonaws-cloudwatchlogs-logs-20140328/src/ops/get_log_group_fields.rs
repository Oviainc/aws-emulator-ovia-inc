/// The fields CloudWatch Logs generates for every log event it stores, which is why the
/// operation documents that "fields that start with @ are fields generated by CloudWatch
/// Logs. For example, @timestamp is the timestamp of each log event": the event's raw text
/// (`@message`), the two timestamps this store keeps for it (`@timestamp`,
/// `@ingestionTime`) and the two names it was ingested under (`@log`, the log group, and
/// `@logStream`). Every event in the window carries all five, so each is reported at the
/// percentage of events that exist — 100 whenever the window holds any.
///
/// `@ptr` is NOT here: it is the pointer `GetQueryResults` mints for one row of a query's
/// results (`GetLogRecord$logRecordPointer`: "You get this from the response of a
/// GetQueryResults operation"), not a field discovered in a stored log event.
const GENERATED_FIELDS: [&str; 5] = [
    "@ingestionTime",
    "@log",
    "@logStream",
    "@message",
    "@timestamp",
];

/// Half the width of the window a request that names `time` searches: "If you specify
/// time, the 8 minutes before and 8 minutes after this time are searched."
const CENTERED_WINDOW_HALF_WIDTH_MS: i64 = 8 * 60 * 1_000;

/// The window a request that omits `time` searches: "If you omit time, the most recent 15
/// minutes up to the current time are searched."
const DEFAULT_WINDOW_MS: i64 = 15 * 60 * 1_000;

/// `time` is the one timestamp member of this service expressed in SECONDS rather than in
/// milliseconds — "The time value is specified as epoch time, which is the number of
/// seconds since January 1, 1970, 00:00:00 UTC." — so it is scaled by this to reach the
/// milliseconds every stored event's timestamp is in.
const MILLIS_PER_SECOND: i64 = 1_000;

/// THE EMULATOR'S OWN CEILING on how many fields one response reports, not an AWS quota:
/// a single JSON log event can name arbitrarily many keys, and this keeps the response
/// bounded. The fields that survive are the ones the response is ordered by — the highest
/// percentages — so the cut falls on the rarest fields.
const MAX_REPORTED_FIELDS: usize = 1_000;

/// THE EMULATOR'S OWN CEILING on how many DISTINCT field names one request ACCUMULATES
/// while counting — a small multiple of what it reports. Once this many names are tracked,
/// a further name is not added (the names already tracked keep counting), so the map is
/// clamped WHILE it grows rather than after it has been built: what one request allocates
/// is bounded by this constant and not by how much log data the group holds.
const MAX_TRACKED_FIELDS: usize = 4 * MAX_REPORTED_FIELDS;

/// THE EMULATOR'S OWN CEILING on how many fields are taken from ONE event, the generated
/// five included: one JSON message can name arbitrarily many keys, and each name costs an
/// allocation carrying its whole dotted path.
const MAX_FIELDS_PER_EVENT: usize = 200;

/// THE EMULATOR'S OWN CEILING on how deep the flattening descends, so a field name's
/// length is bounded here rather than inherited from whatever nesting the JSON parser
/// happens to admit. A member nested deeper than this is reported under the path reached at
/// the limit.
const MAX_FIELD_DEPTH: usize = 8;

/// THE EMULATOR'S OWN CEILING on how many events one request searches: the group's streams
/// and their windows would otherwise multiply out to everything ever ingested. The NEWEST
/// events of the window are the ones searched, so the cut falls on the oldest, and the
/// percentages are reported over the events actually searched.
const MAX_SEARCHED_EVENTS: usize = 10_000;

/// THE EMULATOR'S OWN CEILING on how many message BYTES one request searches, the second
/// factor of the same product: one stream may hold megabytes of messages and a group many
/// streams.
const MAX_SEARCHED_BYTES: usize = 4 * 1024 * 1024;

/// How many events the search walks between yields, so a cancelled or timed-out request has
/// somewhere to land instead of running the whole window first.
const SEARCH_YIELD_INTERVAL: usize = 256;

/// The fields one stored log event carries: the generated five, plus — when the event's
/// message is a JSON object — the keys CloudWatch Logs discovers in it, up to
/// [`MAX_FIELDS_PER_EVENT`] names in all.
fn fields_of(message: &str) -> BTreeSet<String> {
    let mut fields: BTreeSet<String> = GENERATED_FIELDS
        .iter()
        .map(|name| (*name).to_string())
        .collect();
    // Only a JSON OBJECT is a structured log event: a message that is bare text (or a
    // bare JSON scalar or array, which names no keys) is discoverable as `@message`
    // alone.
    if let Ok(::serde_json::Value::Object(members)) =
        ::serde_json::from_str::<::serde_json::Value>(message)
    {
        for (key, value) in &members {
            if fields.len() >= MAX_FIELDS_PER_EVENT {
                break;
            }
            collect_json_fields(key, value, 1, &mut fields);
        }
    }
    fields
}

/// Flatten one JSON member into the field names it contributes, under the name `path` it
/// is reached by: a nested object contributes `parent.child`, a list contributes
/// `parent.0`, and a scalar (or `null`) contributes its own path. A container contributes
/// no name of its own, so an empty object or list adds nothing.
///
/// Both ceilings are applied BEFORE a name is allocated: the walk stops descending at
/// [`MAX_FIELD_DEPTH`] — where the container is reported under the path reached there,
/// which bounds a name's length — and stops emitting at [`MAX_FIELDS_PER_EVENT`] names.
fn collect_json_fields(
    path: &str,
    value: &::serde_json::Value,
    depth: usize,
    into: &mut BTreeSet<String>,
) {
    if into.len() >= MAX_FIELDS_PER_EVENT {
        return;
    }
    match value {
        ::serde_json::Value::Object(members) if depth < MAX_FIELD_DEPTH => {
            for (key, member) in members {
                if into.len() >= MAX_FIELDS_PER_EVENT {
                    break;
                }
                collect_json_fields(&format!("{path}.{key}"), member, depth + 1, into);
            }
        }
        ::serde_json::Value::Array(items) if depth < MAX_FIELD_DEPTH => {
            for (index, item) in items.iter().enumerate() {
                if into.len() >= MAX_FIELDS_PER_EVENT {
                    break;
                }
                collect_json_fields(&format!("{path}.{index}"), item, depth + 1, into);
            }
        }
        _ => {
            into.insert(path.to_string());
        }
    }
}

/// "The percentage of log events queried that contained the field", as the `Percentage`
/// shape carries it: an integer in `0..=100`, rounded to the nearest whole percent.
///
/// `total` is the number of events searched and is never zero here: a window holding no
/// event reports no field at all, rather than every field at an undefined percentage.
fn percent_of(count: usize, total: usize) -> i32 {
    let rounded = count
        .saturating_mul(100)
        .saturating_add(total / 2)
        .checked_div(total)
        .unwrap_or(0);
    i32::try_from(rounded).unwrap_or(100).clamp(0, 100)
}

