        if identifiers.len() > crate::state::MAX_QUERY_LOG_GROUPS {
            return Err(invalid_parameter(format!(
                "A query can include up to {} log groups.",
                crate::state::MAX_QUERY_LOG_GROUPS
            )));
        }
