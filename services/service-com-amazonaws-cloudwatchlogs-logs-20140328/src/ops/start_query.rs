        // keys them by: an identifier may be a name or either ARN form of one group.
        let identifiers: Vec<String> = input
            .log_group_name
            .clone()
            .map(|name| vec![name])
            .or_else(|| input.log_group_names.clone())
            .or_else(|| input.log_group_identifiers.clone())
            .unwrap_or_default();
