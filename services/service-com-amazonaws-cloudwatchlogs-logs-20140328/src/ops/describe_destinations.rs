/// The kind tag this operation's pagination cursor carries, so a token minted by another
/// paginated operation is refused rather than misread.
const CURSOR_KIND: &str = "DescribeDestinations";

/// Where the next page resumes: the `destinationName` of the last destination returned, plus
/// the prefix filter of the enumeration it belongs to. A continuation that changes the filter
/// is refused, because the token is only a position within one filtered enumeration.
#[derive(Debug, Clone)]
struct Cursor {
    destination_name_prefix: Option<String>,
    after: String,
}

impl Cursor {
    fn encode(&self) -> String {
        crate::state::encode_token(&::serde_json::json!({
            "kind": CURSOR_KIND,
            "destinationNamePrefix": self.destination_name_prefix,
            "after": self.after,
        }))
    }

    fn decode(token: &str) -> Option<Self> {
        let value = crate::state::decode_token(token)?;
        if value.get("kind")?.as_str()? != CURSOR_KIND {
            return None;
        }
        let destination_name_prefix = match value.get("destinationNamePrefix") {
            None | Some(::serde_json::Value::Null) => None,
            Some(prefix) => Some(prefix.as_str()?.to_string()),
        };
        Some(Self {
            destination_name_prefix,
            after: value.get("after")?.as_str()?.to_string(),
        })
    }
}

