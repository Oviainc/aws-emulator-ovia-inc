        let now = crate::state::now_millis();
        let mut store = state.lock();
        store.purge_permanently_deleted(now);

        let fingerprint = crate::state::create_archive_fingerprint(
            &input.archive_name,
            input.retention.as_ref(),
            input.kms_key_arn.as_deref(),
            input.tags.as_deref(),
        );

