        if application.status != crate::state::STATUS_READY {
            return Err(StartApplicationErrorModeled::ResourceInUseException(
                ResourceInUseException {
                    message: Some(format!(
                        "Application {name} cannot be started while it is in the {} state",
                        application.status
                    )),
                },
            )
            .into());
        }

