        let not_found = || {
            PutGroupConfigurationError::from(PutGroupConfigurationErrorModeled::NotFoundException(
                NotFoundException {
                    message: Some(crate::state::GROUP_NOT_FOUND_MESSAGE.to_string()),
                },
            ))
        };
