/// [`crate::state::MAX_ATTRIBUTE_DEFINITIONS`] attribute definitions.
fn clamped_lists(input: &CreateTableInput) -> Result<(), crate::state::RequestError> {
    let definitions = input.attribute_definitions.as_ref().map_or(0, Vec::len);
    if definitions > crate::state::MAX_ATTRIBUTE_DEFINITIONS {
        return Err(crate::state::RequestError::Validation(format!(
            "Invalid AttributeDefinitions: a table may declare at most {} attribute \
             definitions, got {definitions}",
            crate::state::MAX_ATTRIBUTE_DEFINITIONS
        )));
    }
    let indexes = input.global_secondary_indexes.as_ref().map_or(0, Vec::len);
    if indexes > crate::state::MAX_GLOBAL_SECONDARY_INDEXES {
        return Err(crate::state::RequestError::Validation(format!(
            "Invalid GlobalSecondaryIndexes: a table may carry at most {} global secondary \
             indexes, got {indexes}",
            crate::state::MAX_GLOBAL_SECONDARY_INDEXES
        )));
    }
    for index in input.global_secondary_indexes.iter().flatten() {
        if index.key_schema.len() > crate::state::MAX_INDEX_KEY_ELEMENTS {
            return Err(crate::state::RequestError::Validation(format!(
                "Invalid KeySchema for index {}: an index key may carry at most {} elements, \
                 got {}",
                index.index_name,
                crate::state::MAX_INDEX_KEY_ELEMENTS,
                index.key_schema.len()
            )));
        }
    }
    let local_indexes = input.local_secondary_indexes.as_ref().map_or(0, Vec::len);
    if local_indexes > crate::state::MAX_LOCAL_SECONDARY_INDEXES {
        return Err(crate::state::RequestError::Validation(format!(
            "Invalid LocalSecondaryIndexes: a table may carry at most {} local secondary \
             indexes, got {local_indexes}",
            crate::state::MAX_LOCAL_SECONDARY_INDEXES
        )));
    }
    for index in input.local_secondary_indexes.iter().flatten() {
        if index.key_schema.len() > crate::state::MAX_INDEX_KEY_ELEMENTS {
            return Err(crate::state::RequestError::Validation(format!(
                "Invalid KeySchema for index {}: an index key may carry at most {} elements, \
                 got {}",
                index.index_name,
                crate::state::MAX_INDEX_KEY_ELEMENTS,
                index.key_schema.len()
            )));
        }
    }
    Ok(())
}

/// The English ordinal DynamoDB names a `KeySchemaElement` by, for every position a key
/// schema can hold — [`crate::state::MAX_INDEX_KEY_ELEMENTS`] is the widest key schema
/// this service accepts, and a table's primary key is narrower still.
const ELEMENT_ORDINALS: [&str; crate::state::MAX_INDEX_KEY_ELEMENTS] = [
    "first", "second", "third", "fourth", "fifth", "sixth", "seventh", "eighth",
];

/// How DynamoDB refers to the element at `position` (0-based) of a key schema.
///
/// Every position a key schema can hold has a word: [`clamped_lists`] bounds an index
/// key to [`crate::state::MAX_INDEX_KEY_ELEMENTS`] elements and a table's primary key is
/// narrower still, so the bare position past the table above is unreachable and is there
/// only so this never has to panic.
fn element_ordinal(position: usize) -> String {
    ELEMENT_ORDINALS
        .get(position)
        .map_or_else(|| (position + 1).to_string(), |word| (*word).to_string())
}

/// Refuse a key schema whose element at some position does not carry the key type that
/// position requires, naming that element the way DynamoDB does.
///
/// A key schema is validated element by element, in the order the request lists it: the
/// partition keys lead and the sort keys follow, so the first element is always a `HASH`
/// element, a `HASH` is in place only while the leading run of at most `partition_keys`
/// partition keys is still open, and every other position must be `RANGE`. The first
/// element that breaks that is refused with its ordinal position and the key type its
/// position required — `Invalid KeySchema: The second KeySchemaElement is not a RANGE key
/// type` — so a caller is told WHICH element to fix rather than the whole rule.
///
/// `index_name` is `None` for a table's own primary key and the index's name for an
/// index key, which DynamoDB scopes its refusal to.
fn validated_key_type_order(
    index_name: Option<&str>,
    key_schema: &[KeySchemaElement],
    partition_keys: usize,
) -> Result<(), crate::state::RequestError> {
    let mut hash_keys = 0usize;
    let mut saw_sort_key = false;
    for (position, element) in key_schema.iter().enumerate() {
        let hash_allowed = !saw_sort_key && hash_keys < partition_keys;
        match element.key_type.as_str() {
            "HASH" if hash_allowed => hash_keys += 1,
            // Only partition keys may lead a key schema, so the first element is never a
            // sort key.
            "RANGE" if position > 0 => saw_sort_key = true,
            _ => {
                let expected = if hash_allowed { "HASH" } else { "RANGE" };
                let scope =
                    index_name.map_or_else(String::new, |name| format!(" for index {name}"));
                return Err(crate::state::RequestError::Validation(format!(
                    "Invalid KeySchema{scope}: The {} KeySchemaElement is not a {expected} key \
                     type",
                    element_ordinal(position)
                )));
            }
        }
    }
    Ok(())
}

/// The table's key schema, refused unless it is one `HASH` attribute optionally
/// followed by one `RANGE` attribute, each defined in `AttributeDefinitions` as a
/// scalar type — "The attributes in KeySchema must also be defined in the
/// AttributeDefinitions array" (`CreateTable$KeySchema`).
///
/// [`clamped_lists`] has already bounded every list this walks.
fn validated_key_schema(
    input: &CreateTableInput,
) -> Result<Vec<KeySchemaElement>, crate::state::RequestError> {
    let key_schema = input.key_schema.clone().unwrap_or_default();
    if key_schema.is_empty() {
        return Err(crate::state::RequestError::Validation(
            "KeySchema is required and must declare a HASH key attribute".to_string(),
        ));
    }
    let definitions = input.attribute_definitions.clone().unwrap_or_default();
    if key_schema.len() > crate::state::MAX_TABLE_KEY_ELEMENTS {
        return Err(crate::state::RequestError::Validation(format!(
            "Invalid KeySchema: a table's primary key may declare at most {} \
             KeySchemaElement(s), got {}",
            crate::state::MAX_TABLE_KEY_ELEMENTS,
            key_schema.len()
        )));
    }
    // A table's primary key is "one KeySchemaElement (for the partition key)" and, when
    // composite, "another KeySchemaElement for the sort key": position 1 holds the only
    // HASH element and position 2, when present, the only RANGE one.
    validated_key_type_order(None, &key_schema, crate::state::MAX_TABLE_PARTITION_KEYS)?;
    for element in &key_schema {
        let name = element.attribute_name.as_str();
        let Some(definition) = definitions
            .iter()
            .find(|definition| definition.attribute_name == name)
        else {
            return Err(crate::state::RequestError::Validation(format!(
                "Invalid KeySchema: no AttributeDefinition was provided for key attribute {name}"
            )));
        };
        if !matches!(definition.attribute_type.as_str(), "S" | "N" | "B") {
            return Err(crate::state::RequestError::Validation(format!(
                "Invalid AttributeDefinition: {name} must have AttributeType S, N or B, got {}",
                definition.attribute_type
            )));
        }
    }
    // The key attributes of every requested index, collected ONCE: the loop below asks
    // whether each definition is used, and a per-definition scan of every index's key
    // schema would be the product of two request-chosen counts. Both index kinds declare
    // their key attributes in the same array, so both are collected here.
    let index_key_attributes: ::std::collections::HashSet<&str> = input
        .global_secondary_indexes
        .iter()
        .flatten()
        .flat_map(|index| index.key_schema.iter())
        .chain(
            input
                .local_secondary_indexes
                .iter()
                .flatten()
                .flat_map(|index| index.key_schema.iter()),
        )
        .map(|element| element.attribute_name.as_str())
        .collect();
    for definition in &definitions {
        // "Some AttributeDefinitions are not used in any KeySchema": every defined
        // attribute must be a key of the table or of one of its secondary indexes,
        // whose key attributes are declared in the same array.
        let used_by_table = key_schema
            .iter()
            .any(|element| element.attribute_name == definition.attribute_name);
        let used_by_index = index_key_attributes.contains(definition.attribute_name.as_str());
        if !used_by_table && !used_by_index {
            return Err(crate::state::RequestError::Validation(format!(
                "Some AttributeDefinitions are not used in any KeySchema: {}",
                definition.attribute_name
            )));
        }
    }
    Ok(key_schema)
}

/// The global secondary indexes to store with the table.
///
/// Each one is refused unless its name is unique on the table, its key schema names
/// attributes `AttributeDefinitions` declares with a scalar type, its `Projection` is
/// one the model's `ProjectionType` enum names, and its throughput matches the table's
/// billing mode — "You must use either OnDemandThroughput or ProvisionedThroughput
/// based on your table's capacity mode" (`GlobalSecondaryIndex$ProvisionedThroughput`).
/// An index created with the table is reported `CREATING` and becomes `ACTIVE` on the
/// same clock-owed transition as the table.
fn validated_indexes(
    input: &CreateTableInput,
    billing_mode: &str,
    region: &str,
    table: &str,
    now: ::std::time::SystemTime,
) -> Result<Vec<crate::state::GlobalSecondaryIndex>, crate::state::RequestError> {
    let requested = input.global_secondary_indexes.clone().unwrap_or_default();
    let definitions = input.attribute_definitions.clone().unwrap_or_default();
    let mut indexes: Vec<crate::state::GlobalSecondaryIndex> = Vec::new();
    for index in &requested {
        if indexes.iter().any(|stored| stored.name == index.index_name) {
            return Err(crate::state::RequestError::Validation(format!(
                "Invalid GlobalSecondaryIndex: duplicate index name {}",
                index.index_name
            )));
        }
        validated_index_key_schema(&index.index_name, &index.key_schema, &definitions)?;
        validated_projection(&index.index_name, &index.projection)?;
        let throughput = validated_index_throughput(
            &index.index_name,
            billing_mode,
            index.provisioned_throughput.clone(),
        )?;
        // No request may name a warm throughput per index (that member is refused with
        // the scaffold's 501), so a new index keeps warm the capacity it is provisioned
        // for.
        let warm_throughput = crate::state::WarmThroughputSettings::tracking(throughput.as_ref(), now);
        indexes.push(crate::state::GlobalSecondaryIndex {
            arn: crate::state::index_arn(region, table, &index.index_name),
            name: index.index_name.clone(),
            key_schema: index.key_schema.clone(),
            projection: index.projection.clone(),
            provisioned_throughput: throughput,
            transient_status: crate::state::IndexStatus::Creating,
            active_at: now + crate::state::STATUS_TRANSITION,
            throughput_history: crate::state::ThroughputHistory::default(),
            warm_throughput,
            reported_counters: crate::state::MeteredCounters::new(now),
        });
    }
    Ok(indexes)
}

/// The local secondary indexes to store with the table.
///
/// A local secondary index is "an index that has the same partition key as the table,
/// but a different sort key" (the `LocalSecondaryIndex` doc and the Developer Guide), so
/// each one is refused unless its `HASH` key is the table's own partition key. Beyond
/// that it is held to the same rules as a global index: a name unique "among all other
/// indexes on this table" (`LocalSecondaryIndex$IndexName`), key attributes declared in
/// `AttributeDefinitions` with a scalar type, and a `Projection` the model's
/// `ProjectionType` enum names. A local index carries no throughput of its own and no
/// status: it exists from the moment the table does.
///
/// [`clamped_lists`] has already bounded every list this walks.
fn validated_local_indexes(
    input: &CreateTableInput,
    table_key_schema: &[KeySchemaElement],
    global_secondary_indexes: &[crate::state::GlobalSecondaryIndex],
    region: &str,
    table: &str,
    now: ::std::time::SystemTime,
) -> Result<Vec<crate::state::LocalSecondaryIndex>, crate::state::RequestError> {
    let requested = input.local_secondary_indexes.clone().unwrap_or_default();
    let definitions = input.attribute_definitions.clone().unwrap_or_default();
    let partition_key = table_key_schema
        .iter()
        .find(|element| element.key_type == "HASH")
        .map_or("", |element| element.attribute_name.as_str());
    let mut indexes: Vec<crate::state::LocalSecondaryIndex> = Vec::new();
    for index in &requested {
        if indexes.iter().any(|stored| stored.name == index.index_name)
            || global_secondary_indexes
                .iter()
                .any(|stored| stored.name == index.index_name)
        {
            return Err(crate::state::RequestError::Validation(format!(
                "Invalid LocalSecondaryIndex: duplicate index name {}",
                index.index_name
            )));
        }
        validated_index_key_schema(&index.index_name, &index.key_schema, &definitions)?;
        validated_projection(&index.index_name, &index.projection)?;
        let hash_key = index
            .key_schema
            .iter()
            .find(|element| element.key_type == "HASH")
            .map_or("", |element| element.attribute_name.as_str());
        if hash_key != partition_key {
            return Err(crate::state::RequestError::Validation(format!(
                "Invalid KeySchema for index {}: a local secondary index must have the table's \
                 partition key {partition_key} as its HASH key, got {hash_key}",
                index.index_name
            )));
        }
        indexes.push(crate::state::LocalSecondaryIndex {
            arn: crate::state::index_arn(region, table, &index.index_name),
            name: index.index_name.clone(),
            key_schema: index.key_schema.clone(),
            projection: index.projection.clone(),
            reported_counters: crate::state::MeteredCounters::new(now),
        });
    }
    Ok(indexes)
}

/// One index's key schema: at least one `HASH` element, within the documented key
/// counts, with every attribute declared in `AttributeDefinitions` as a scalar type.
///
/// An index key is validated by position like a table's: "Each global secondary index
/// supports up to 4 partition keys and up to 4 sort keys"
/// (`CreateTable$GlobalSecondaryIndexes`), so the leading positions hold the partition
/// keys and the sort keys follow, and an element out of place is named by its ordinal.
pub(crate) fn validated_index_key_schema(
    index_name: &str,
    key_schema: &[KeySchemaElement],
    definitions: &[AttributeDefinition],
) -> Result<(), crate::state::RequestError> {
    if key_schema.is_empty() {
        return Err(crate::state::RequestError::Validation(format!(
            "Invalid KeySchema for index {index_name}: an index key must declare a HASH key \
             attribute"
        )));
    }
    validated_key_type_order(
        Some(index_name),
        key_schema,
        crate::state::MAX_INDEX_PARTITION_KEYS,
    )?;
    let range_keys = key_schema
        .iter()
        .filter(|element| element.key_type == "RANGE")
        .count();
    if range_keys > crate::state::MAX_INDEX_SORT_KEYS {
        return Err(crate::state::RequestError::Validation(format!(
            "Invalid KeySchema for index {index_name}: an index key may declare at most {} RANGE \
             attribute(s), got {range_keys}",
            crate::state::MAX_INDEX_SORT_KEYS
        )));
    }
    for element in key_schema {
        let name = element.attribute_name.as_str();
        let Some(definition) = definitions
            .iter()
            .find(|definition| definition.attribute_name == name)
        else {
            return Err(crate::state::RequestError::Validation(format!(
                "Invalid KeySchema for index {index_name}: no AttributeDefinition was provided \
                 for key attribute {name}"
            )));
        };
        if !matches!(definition.attribute_type.as_str(), "S" | "N" | "B") {
            return Err(crate::state::RequestError::Validation(format!(
                "Invalid AttributeDefinition: {name} must have AttributeType S, N or B, got {}",
                definition.attribute_type
            )));
        }
    }
    Ok(())
}

/// One index's projection: `ProjectionType` must be a value the model's enum names,
/// and `NonKeyAttributes` belongs to `INCLUDE` alone — "This limit only applies when
/// you specify the ProjectionType of INCLUDE" (`Projection$NonKeyAttributes`).
pub(crate) fn validated_projection(
    index_name: &str,
    projection: &Projection,
) -> Result<(), crate::state::RequestError> {
    let projection_type = projection.projection_type.as_deref().unwrap_or("ALL");
    if !matches!(projection_type, "ALL" | "KEYS_ONLY" | "INCLUDE") {
        return Err(crate::state::RequestError::Validation(format!(
            "Invalid Projection for index {index_name}: ProjectionType {projection_type} must be \
             ALL, KEYS_ONLY or INCLUDE"
        )));
    }
    let non_key = projection
        .non_key_attributes
        .as_ref()
        .is_some_and(|attributes| !attributes.is_empty());
    if non_key && projection_type != "INCLUDE" {
        return Err(crate::state::RequestError::Validation(format!(
            "Invalid Projection for index {index_name}: NonKeyAttributes can only be specified \
             with a ProjectionType of INCLUDE"
        )));
    }
    Ok(())
}

/// One index's provisioned throughput, held to the table's billing mode: a
/// `PROVISIONED` table's index must carry one (with both dimensions at least 1), and a
/// `PAY_PER_REQUEST` table's index must not.
pub(crate) fn validated_index_throughput(
    index_name: &str,
    billing_mode: &str,
    throughput: Option<ProvisionedThroughput>,
) -> Result<Option<ProvisionedThroughput>, crate::state::RequestError> {
    match (billing_mode, throughput) {
        ("PAY_PER_REQUEST", None) => Ok(None),
        ("PAY_PER_REQUEST", Some(_)) => Err(crate::state::RequestError::Validation(format!(
            "ProvisionedThroughput cannot be specified for index {index_name} when BillingMode \
             is PAY_PER_REQUEST"
        ))),
        (_, Some(throughput)) => {
            if throughput.read_capacity_units < 1 || throughput.write_capacity_units < 1 {
                return Err(crate::state::RequestError::Validation(format!(
                    "Invalid ProvisionedThroughput for index {index_name}: ReadCapacityUnits and \
                     WriteCapacityUnits must be at least 1, got {} and {}",
                    throughput.read_capacity_units, throughput.write_capacity_units
                )));
            }
            Ok(Some(throughput))
        }
        (_, None) => Err(crate::state::RequestError::Validation(format!(
            "ProvisionedThroughput must be specified for index {index_name} when BillingMode is \
             PROVISIONED"
        ))),
    }
}

/// The billing mode and the provisioned throughput to store: "If you set BillingMode
/// as PROVISIONED, you must specify this property. If you set BillingMode as
/// PAY_PER_REQUEST, you cannot specify this property"
/// (`CreateTable$ProvisionedThroughput`). `BillingMode` defaults to `PROVISIONED`.
fn validated_throughput(
    input: &CreateTableInput,
) -> Result<(String, Option<ProvisionedThroughput>), crate::state::RequestError> {
    let billing_mode = input
        .billing_mode
        .clone()
        .unwrap_or_else(|| "PROVISIONED".to_string());
    match (billing_mode.as_str(), input.provisioned_throughput.clone()) {
        ("PAY_PER_REQUEST", None) => Ok((billing_mode, None)),
        ("PAY_PER_REQUEST", Some(_)) => Err(crate::state::RequestError::Validation(
            "ProvisionedThroughput cannot be specified when BillingMode is PAY_PER_REQUEST"
                .to_string(),
        )),
        ("PROVISIONED", Some(throughput)) => {
            if throughput.read_capacity_units < 1 || throughput.write_capacity_units < 1 {
                return Err(crate::state::RequestError::Validation(format!(
                    "Invalid ProvisionedThroughput: ReadCapacityUnits and WriteCapacityUnits \
                     must be at least 1, got {} and {}",
                    throughput.read_capacity_units, throughput.write_capacity_units
                )));
            }
            Ok((billing_mode, Some(throughput)))
        }
        ("PROVISIONED", None) => Err(crate::state::RequestError::Validation(
            "ProvisionedThroughput must be specified when BillingMode is PROVISIONED".to_string(),
        )),
        (other, _) => Err(crate::state::RequestError::Validation(format!(
            "Invalid BillingMode: {other} must be PROVISIONED or PAY_PER_REQUEST"
        ))),
    }
}
