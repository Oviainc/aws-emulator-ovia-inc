            return Err(refuse(FieldFault::new(
                framings[1],
                "FieldValidationFailed",
                format!(
                    "a static map is framed by exactly one of BoundingBox, BoundedPositions or Center, got {}",
                    framings.join(" and ")
                ),
            )));
