impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ListStacks<Eng>
{
    type Input = ListStacksInput;
    type Output = ListStacksOutput;
    type Error = ListStacksError;

    const NAME: &'static str = "ListStacks";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_STACKS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_STACKS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            // Not the shared in-memory engine: there is no stack store to list, so this
            // answers 501 rather than an empty, truthful-looking list.
            return Err(crate::scaffolded::Scaffolded::not_implemented("ListStacks"));
        };

        // A resource of a stack of this Region whose owning service had not reported it
        // ready when the create answered holds that stack's operation open, so the summary
        // status it reports is still `*_IN_PROGRESS`: those services are asked, before the
        // store is locked, what they report now
        // ([`crate::state::provisioning::advance_stabilisations`]).
        crate::state::provisioning::advance_stabilisations(ctx, &state).await;
        // The summary status a stack rolling back reports is the one that rollback reaches:
        // a rollback the failure of an update already made due is carried out here, before
        // the summaries are read, since it was owed at the instant that update failed
        // whether or not anybody called (`crate::state::settle_due_rollbacks`).
        crate::state::settle_due_rollbacks(ctx, &*self.engine).await;

        let mut store = state.lock();
        // Reporting operation: the only write is materialising a status transition the
        // clock had already made due.
        store.settle(::std::time::SystemTime::now());

        // "Returns the summary information for stacks whose status matches the specified
        // StackStatusFilter … If no StackStatusFilter is specified, summary information
        // for all stacks is returned (including existing stacks and stacks that have
        // been deleted)" — all the stacks OF THIS REGION, since CloudFormation lists the
        // stacks of the Region the request was signed for.
        let region = crate::state::request_region(ctx.parts());
        let filter = input.stack_status_filter.as_deref().unwrap_or_default();
        // The store is read through ONE shared borrow, and the nesting relation every
        // summary's `ParentId`/`RootId` is derived from is built once for the whole read:
        // the relation is a function of the other stacks' resource records, not of the stack
        // the summary is about.
        let view = &*store;
        let nesting = view.nesting_in(&region);
        let matching: Vec<StackSummary> = view
            .stacks_in(&region)
            .filter(|stack| filter.is_empty() || filter.contains(&stack.status))
            .map(|stack| stack_summary(&nesting, stack))
            .collect();
        // `@paginated(inputToken: NextToken, outputToken: NextToken,
        // items: StackSummaries)`: one response carries one bounded page.
        let (stack_summaries, next_token) = crate::state::paginate(
            crate::state::PageOf::StackSummaries,
            matching,
            input.next_token.as_deref(),
        )
        .map_err(crate::scaffolded::Scaffolded::validation_error)?;

        Ok(ListStacksOutput {
            stack_summaries: Some(stack_summaries),
            next_token,
        })
    }
}
