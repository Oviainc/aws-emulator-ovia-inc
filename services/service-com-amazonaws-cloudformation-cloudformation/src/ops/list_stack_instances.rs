/// WHICH of a StackSet's instances the request selects.
///
/// The three narrowing members are independent and apply TOGETHER: "You can filter for stack
/// instances that are associated with a specific Amazon Web Services account name or Region,
/// or that have a specific status", so an instance is reported only when it satisfies every
/// one the request named. A request that names none selects the StackSet's whole set.
#[derive(Debug, Default)]
struct Selection {
    /// `StackInstanceAccount`: "the name of the Amazon Web Services account that you want to
    /// list stack instances for".
    account: Option<String>,
    /// `StackInstanceRegion`: "the name of the Region where you want to list stack
    /// instances".
    region: Option<String>,
    /// `Filters`: up to three `StackInstanceFilter`s (`@length(0..3)`), each a modelled
    /// filter name with the single value to filter by. A filter that names no `Name` or no
    /// `Values` narrows nothing: both members are optional in the model and it declares no
    /// refusal for an incomplete filter, so there is no status to compare against.
    filters: Vec<(String, String)>,
}

impl Selection {
    /// The narrowing the request asks for.
    fn of(input: &ListStackInstancesInput) -> Self {
        Self {
            account: input.stack_instance_account.clone(),
            region: input.stack_instance_region.clone(),
            filters: input
                .filters
                .iter()
                .flatten()
                .filter_map(|filter| match (&filter.name, &filter.values) {
                    (Some(name), Some(values)) => Some((name.clone(), values.clone())),
                    _ => None,
                })
                .collect(),
        }
    }

    /// Whether this selection covers `instance`.
    fn selects(&self, instance: &StoredStackInstance) -> bool {
        self.account
            .as_ref()
            .is_none_or(|account| &instance.account == account)
            && self
                .region
                .as_ref()
                .is_none_or(|region| &instance.region == region)
            && self
                .filters
                .iter()
                .all(|(name, value)| instance.matches_filter(name, value))
    }
}

/// One stored stack instance as the modelled `StackInstanceSummary`.
///
/// Every member is read off the instance record, and `StackSetId` off the StackSet that
/// holds it, so this read and `DescribeStackInstance` cannot disagree about an instance's
/// account, Region, stack, statuses, drift or last operation. A member the instance does not
/// carry — the stack of a deployment that has not produced one, a status with no reason, the
/// organizational unit of a self-managed StackSet, the drift-check instant of an instance no
/// detection has run against — is absent rather than reported empty.
fn stack_instance_summary(
    stack_set_id: &str,
    stored: &StoredStackInstance,
) -> StackInstanceSummary {
    StackInstanceSummary {
        stack_set_id: Some(stack_set_id.to_string()),
        region: Some(stored.region.clone()),
        account: Some(stored.account.clone()),
        stack_id: stored.stack_id.clone(),
        status: Some(stored.status.clone()),
        status_reason: stored.status_reason.clone(),
        stack_instance_status: Some(StackInstanceComprehensiveStatus {
            detailed_status: Some(stored.detailed_status.clone()),
        }),
        organizational_unit_id: stored.organizational_unit_id.clone(),
        drift_status: Some(stored.drift_status.clone()),
        last_drift_check_timestamp: stored.last_drift_check.map(crate::state::timestamp),
        last_operation_id: Some(stored.last_operation_id.clone()),
    }
}

