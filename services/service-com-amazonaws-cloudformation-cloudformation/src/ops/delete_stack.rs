    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DELETE_STACK_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = DELETE_STACK_OUTPUT_SCHEMA;
