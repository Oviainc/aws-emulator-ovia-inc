/// One stored stack as the modelled `Stack` shape.
///
/// Every member is read back from what `CreateStack`/`UpdateStack`/`DeleteStack`/
/// `UpdateTerminationProtection` or `CreateChangeSet`/`ExecuteChangeSet` persisted.
///
/// The members CloudFormation reports on EVERY stack are always present, as an empty
/// element where the stack carries nothing: `NotificationARNs`, `Tags`,
/// `RollbackConfiguration`, `DeploymentConfig` (with its documented defaults filled in)
/// and `LastOperations`. The members that report a stack's OWN declarations —
/// `Parameters`, `Outputs`, `Capabilities` — appear only when the stack has some, since a
/// stack that declares none has no list to report.
///
/// `ChangeSetId` is the change set that last acted on the stack: the one that created it in
/// `REVIEW_IN_PROGRESS`, or the one `ExecuteChangeSet` applied. `LastOperations` is the
/// operation that last acted on the stack — the create, update or delete it ran, or the
/// change-set creation that brought the stack into existence.
///
/// The members this emulator has nothing to report for are absent rather than invented:
///
/// * `DetailedStatus` — nothing in this slice produces one.
///
/// `ParentId` and `RootId` are the stack this one is NESTED IN and the top of that chain,
/// derived from the resource record that created it ([`crate::state::stack_nesting`]) — both
/// absent for a top-level stack, which is nested in nothing.
///
/// `Outputs` is the stack's evaluated outputs: one entry per output the template declares,
/// as of the create or update that COMPLETED (see `crate::state::StoredStack`) — so a
/// stack whose create failed reports none.
///
/// `DriftInformation` is the result of the last drift detection that COMPLETED against the
/// stack, with the instant the most recent detection was initiated on it: `NOT_CHECKED`
/// with no timestamp until `DetectStackDrift` has run one.
fn stack_view(nesting: &crate::state::Nesting, stored: &StoredStack) -> Stack {
    Stack {
        stack_id: Some(stored.stack_id.clone()),
        stack_name: stored.stack_name.clone(),
        change_set_id: stored.change_set_id.clone(),
        description: stored.description(),
        parameters: crate::state::parameter_views(&stored.parameters),
        creation_time: crate::state::timestamp(stored.creation_time),
        deletion_time: stored.deletion_time.map(crate::state::timestamp),
        last_updated_time: stored.last_updated_time.map(crate::state::timestamp),
        rollback_configuration: crate::state::rollback_configuration_in_force(
            stored.rollback_configuration.as_ref(),
        ),
        stack_status: stored.status.clone(),
        stack_status_reason: stored.status_reason.clone(),
        disable_rollback: Some(stored.disable_rollback),
        deployment_config: crate::state::deployment_config_view(
            stored.deployment_config.as_ref(),
            stored.disable_rollback,
        ),
        notification_ar_ns: Some(stored.notification_arns.clone()),
        timeout_in_minutes: stored.timeout_in_minutes,
        capabilities: crate::state::non_empty(stored.capabilities.clone()),
        outputs: crate::state::output_views(&stored.outputs),
        role_arn: stored.role_arn.clone(),
        tags: crate::state::tag_views(&stored.tags),
        enable_termination_protection: Some(stored.enable_termination_protection),
        parent_id: nesting.parent_id_of(stored),
        root_id: nesting.root_id_of(stored),
        drift_information: crate::state::stack_drift_information(stored),
        retain_except_on_create: stored.retain_except_on_create,
        deletion_mode: stored.deletion_mode.clone(),
        detailed_status: None,
        last_operations: crate::state::last_operation_views(stored.last_operation()),
    }
}

