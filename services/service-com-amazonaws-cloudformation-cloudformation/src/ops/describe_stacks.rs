impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeStacks<Eng>
{
    type Input = DescribeStacksInput;
    type Output = DescribeStacksOutput;
    type Error = DescribeStacksError;

    const NAME: &'static str = "DescribeStacks";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_STACKS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_STACKS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            // Not the shared in-memory engine: there is no stack store to read, so this
            // answers 501 rather than an empty, truthful-looking list.
            return Err(crate::scaffolded::Scaffolded::not_implemented(
                "DescribeStacks",
            ));
        };

        // A resource of a stack of this Region whose owning service had not reported it
        // ready when the create answered holds that stack's operation open, so the stack is
        // still `*_IN_PROGRESS`: those services are asked, before the store is locked, what
        // they report now ([`crate::state::provisioning::advance_stabilisations`]).
        crate::state::provisioning::advance_stabilisations(ctx, &state).await;
        // A rollback the failure of an update already made due owes work in the services
        // that own the stack's resources, and the status this read reports is the one that
        // rollback reaches: it is carried out here, before the store is read, since it was
        // owed at the instant that update failed whether or not anybody called
        // (`crate::state::settle_due_rollbacks`).
        crate::state::settle_due_rollbacks(ctx, &*self.engine).await;

        let mut store = state.lock();
        // Reporting operation: the only write is materialising a status transition the
        // clock had already made due, which was owed whether or not anyone called.
        store.settle(::std::time::SystemTime::now());
        // CloudFormation is Regional: this read answers from the stacks of the Region the
        // request was signed for, and a name or id of another Region's stack names nothing
        // here.
        let region = crate::state::request_region(ctx.parts());
        let matching: Vec<&StoredStack> = match &input.stack_name {
            // "The name or the unique stack ID that's associated with the stack …
            // Running stacks: either. Deleted stacks: you must specify the unique stack
            // ID." A name that resolves to nothing is a `ValidationError`, not an empty
            // list: "If the stack doesn't exist, a ValidationError is returned."
            Some(name_or_id) => {
                let stack = store.resolve(&region, name_or_id).ok_or_else(|| {
                    crate::scaffolded::Scaffolded::validation_error(
                        crate::state::stack_does_not_exist(name_or_id),
                    )
                })?;
                vec![stack]
            }
            // "Deleted stacks don't show up in the DescribeStacks operation if the
            // deletion has been completed successfully."
            None => store.live_stacks(&region).collect(),
        };
        // `@paginated(inputToken: NextToken, outputToken: NextToken, items: Stacks)`: one
        // response carries one bounded page, and the token resumes just past it. The page
        // is taken over the STORED stacks and only its members are projected onto the wire
        // shape, so the work one request costs is bounded by the page and not by how many
        // stacks the store holds.
        let (page, next_token) = crate::state::paginate(
            crate::state::PageOf::Stacks,
            matching,
            input.next_token.as_deref(),
        )
        .map_err(crate::scaffolded::Scaffolded::validation_error)?;
        // The nesting relation the two members below are derived from, built once for this
        // read: it is a function of the other stacks' resource records rather than of the
        // stack each view is about.
        let nesting = store.nesting_in(&region);
        let stacks: Vec<Stack> = page
            .into_iter()
            .map(|stored| stack_view(&nesting, stored))
            .collect();

        Ok(DescribeStacksOutput {
            stacks: Some(stacks),
            next_token,
        })
    }
}
