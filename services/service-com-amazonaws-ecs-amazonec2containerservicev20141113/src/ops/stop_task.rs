            task.stopped_reason = Some(
                input
                    .reason
                    .clone()
                    .unwrap_or_else(|| crate::state::DEFAULT_STOPPED_REASON.to_string()),
            );
            task.stop_code = Some(crate::state::STOP_CODE_USER_INITIATED.to_string());
