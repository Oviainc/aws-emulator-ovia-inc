impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for GetBlueprint<Eng>
{
    type Input = GetBlueprintInput;
    type Output = GetBlueprintOutput;
    type Error = GetBlueprintError;

    const NAME: &'static str = "GetBlueprint";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_BLUEPRINT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_BLUEPRINT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            GetBlueprintError::Modeled(GetBlueprintErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("the Bedrock Data Automation store is unavailable".to_string()),
                },
            ))
        })?;
        // A read: it only projects what is already stored.
        let store = state.lock();

        // The refusal for a blueprint lookup that resolves to nothing is the service's
        // FIXED sentence, single-homed in `crate::state`, with nothing taken from the
        // request: the ARN one for an unscoped lookup, the ARN-or-version one when the
        // request scoped the lookup to a version.
        let not_found = || {
            GetBlueprintError::Modeled(GetBlueprintErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(
                        crate::state::blueprint_not_found_message(
                            input.blueprint_version.as_deref(),
                        )
                        .to_string(),
                    ),
                },
            ))
        };

        let record = store.blueprints.get(&input.blueprint_arn).ok_or_else(not_found)?;

        // `blueprintStage` selects a stage; a blueprint that is not at the stage
        // asked for is not the resource the caller named.
        if let Some(stage) = input.blueprint_stage.as_deref() {
            if stage != record.blueprint_stage {
                return Err(not_found());
            }
        }

        // `blueprintVersion` is modeled `^[0-9]*$`, so a value that reaches this
        // handler is digits — but a version nothing ever cut does not exist.
        let blueprint = match input.blueprint_version.as_deref() {
            None => record.to_blueprint(),
            Some(raw) => {
                let version = raw.parse::<u64>().map_err(|_| not_found())?;
                record
                    .to_blueprint_version(version)
                    .ok_or_else(not_found)?
            }
        };
        Ok(GetBlueprintOutput { blueprint })
    }
}
