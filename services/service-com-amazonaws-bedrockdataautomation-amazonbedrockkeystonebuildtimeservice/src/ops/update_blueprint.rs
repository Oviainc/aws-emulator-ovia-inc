impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateBlueprint<Eng>
{
    type Input = UpdateBlueprintInput;
    type Output = UpdateBlueprintOutput;
    type Error = UpdateBlueprintError;

    const NAME: &'static str = "UpdateBlueprint";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_BLUEPRINT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_BLUEPRINT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            UpdateBlueprintError::Modeled(UpdateBlueprintErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("the Bedrock Data Automation store is unavailable".to_string()),
                },
            ))
        })?;
        let mut store = state.lock();

        let Some(record) = store.blueprints.get_mut(&input.blueprint_arn) else {
            return Err(UpdateBlueprintErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(crate::state::BLUEPRINT_ARN_NOT_FOUND_MESSAGE.to_string()),
                },
            )
            .into());
        };

        // `schema` is @required, so it always replaces the stored one; every other
        // member replaces only what the request names. `creationTime` never moves.
        // The write lands AT A STAGE — the one the request names, or the stage the
        // blueprint already stands at — and leaves every other stage holding the
        // content it has.
        let stage = input
            .blueprint_stage
            .unwrap_or_else(|| record.blueprint_stage.clone());
        record.write_stage(&stage, input.schema, crate::state::now());
        if let Some(config) = input.encryption_configuration {
            record.kms_key_id = Some(config.kms_key_id);
            record.kms_encryption_context = config.kms_encryption_context;
        }

        Ok(UpdateBlueprintOutput {
            blueprint: record.to_blueprint(),
        })
    }
}
