/// The wording GuardDuty answers a `findingTypes` entry that is not a finding type
/// with. The HTTP status (400) and the error class are the requirement; the text
/// states the rule and names no value from the request, as the service's own does.
const INVALID_FINDING_TYPE_MESSAGE: &str =
    "The request is rejected because of invalid finding type is specified.";

/// Refuse the request the way GuardDuty does: HTTP 400 under the
/// `InvalidInputException` class, in both the body's `__type` and its `type` member.
fn invalid_input(message: impl Into<String>) -> CreateSampleFindingsError {
    crate::scaffolded::Scaffolded::invalid_input(message)
}

/// The first segment of a finding type: everything before the `:`.
fn threat_purpose(finding_type: &str) -> &str {
    finding_type.split(':').next().unwrap_or(finding_type)
}

/// The `Resource.ResourceType` a finding of this type is about.
///
/// The finding type's second segment names the AFFECTED RESOURCE TYPE in
/// GuardDuty's own abbreviations (read through the shared parser in
/// `crate::state`, which every operation that reads the convention uses); this
/// maps each one onto the value the `Resource` shape reports. An abbreviation this
/// emulator does not know is reported verbatim rather than guessed at.
fn resource_type_for(finding_type: &str) -> String {
    match crate::state::finding_type_affected_resource(finding_type) {
        "EC2" | "Runtime" => "Instance",
        // An IAM principal is reported through its credential, which is the
        // `AccessKey` resource.
        "IAMUser" | "IAM" => "AccessKey",
        "S3" => "S3Bucket",
        "Kubernetes" | "EKS" => "EKSCluster",
        "ECS" => "ECSCluster",
        "RDS" => "RDSDBInstance",
        "Lambda" => "Lambda",
        "Container" => "Container",
        other => other,
    }
    .to_string()
}

/// The `Description` a sample finding carries, stated from the two parts of the
/// finding type that are documented to mean something.
fn describe(finding_type: &str) -> String {
    format!(
        "[SAMPLE] GuardDuty sample finding of type {finding_type}: a {} observation affecting a {} resource.",
        threat_purpose(finding_type),
        resource_type_for(finding_type)
    )
}
