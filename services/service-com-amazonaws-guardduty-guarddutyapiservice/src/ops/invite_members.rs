impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for InviteMembers<Eng>
{
    type Input = InviteMembersInput;
    type Output = InviteMembersOutput;
    type Error = InviteMembersError;

    const NAME: &'static str = "InviteMembers";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::INVITE_MEMBERS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::INVITE_MEMBERS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(InviteMembersErrorModeled::InternalServerErrorException(
                crate::state::state_unavailable(),
            )
            .into());
        };
        let region = crate::state::request_region(ctx);
        let administrator = crate::state::administrator_account_id();

        // Parameter failures first, before anything is looked up or written: a value
        // that cannot be a value of its member at all is refused whatever the store
        // holds. `UnprocessedAccounts` reports accounts that were not PROCESSED,
        // never a request that was not understood, so a malformed account id refuses
        // the whole call rather than landing in that list.
        if !crate::state::is_detector_id(&input.detector_id) {
            return Err(crate::scaffolded::Scaffolded::invalid_input(
                crate::state::invalid_parameter_message(crate::state::DETECTOR_ID_MEMBER),
            ));
        }
        if let Some(message) = crate::state::account_ids_rejection(
            crate::state::ACCOUNT_IDS_MEMBER,
            &input.account_ids,
        ) {
            return Err(crate::scaffolded::Scaffolded::invalid_input(message));
        }

        let mut state = state.lock();
        // Members hang off the detector that administers them, so only the
        // account/Region that owns it can invite them.
        if state.detector_in(&region, &input.detector_id).is_none() {
            return Err(not_owned(&input.detector_id));
        }
        // The instant an invitation this call sends is sent at, read WITHOUT being
        // taken off the clock: whether anything is written at all is answered only
        // by the loop below and the delivery after it, because an account this
        // administrator holds no member record for is reported and an account whose
        // invitation is still pending keeps the one it has. One instant for the whole
        // call, so every member it invites carries the same `InvitedAt` and the same
        // `UpdatedAt`.
        let now = state.pending_millis();
        // Is the invitation this administrator sent through this Region's endpoint
        // still pending? Both halves of a send are decided by this one answer, read
        // from the inbox an acceptance, a decline and a delete each take an
        // invitation out of: while it is pending a re-send re-sends that same
        // invitation and moves neither half, and once it has been answered or
        // deleted nothing of that send is pending any more, so a later send is a
        // fresh invitation on BOTH halves. Read before anything is written, because
        // the delivery below is what changes it.
        let invitation_pending = state.invitation_pending_in(&region, &administrator);
        let Some(detector) = state.detector_in_mut(&region, &input.detector_id) else {
            // Unreachable: the detector was resolved above and the lock has not been
            // released since. Answered rather than panicked, because a handler owes
            // the caller a modelled response on every path.
            return Err(not_owned(&input.detector_id));
        };

        let mut unprocessed = Vec::new();
        let mut sent = false;
        let mut wrote = false;
        let mut seen = ::std::collections::BTreeSet::new();
        for account_id in &input.account_ids {
            // `AccountIds` names a SET of accounts: a repeated id is invited once, so
            // it cannot be reported twice either.
            if !seen.insert(account_id.as_str()) {
                continue;
            }
            match detector.members.get_mut(account_id) {
                // The condition is the member RECORD, not the association: the
                // records of disassociated members are retained precisely so they can
                // be invited again, so an invitation re-associates one rather than
                // needing a second `CreateMembers`.
                Some(member) => {
                    sent = true;
                    // What this send leaves the member in: an invitation is
                    // announced to the address `CreateMembers` recorded, and
                    // GuardDuty resolves that address's domain as it sends, so an
                    // address no mail can reach fails verification there and then
                    // rather than waiting for an answer that can never arrive
                    // ([`crate::state::invitation_outcome`]).
                    let outcome = crate::state::invitation_outcome(&member.email);
                    // One invitation is pending per administrator/member pair, so
                    // inviting an account whose invitation is still pending re-sends
                    // that same invitation rather than issuing a second one: nothing
                    // about the member moves, `InvitedAt` and `UpdatedAt` included.
                    // "Still pending" is the inbox's answer, not the stored status's:
                    // a member left by a send whose invitation has since been
                    // accepted, declined or deleted has none pending, so the instant
                    // this send is made at is what its record carries — a member's
                    // `InvitedAt` names the instant an invitation this store holds
                    // was sent at, never one that was answered. The stored status is
                    // compared against the OUTCOME of a send to this member, so a
                    // re-send changes nothing whichever outcome the first one had.
                    if invitation_pending && member.relationship_status == outcome {
                        continue;
                    }
                    member.relationship_status = outcome.to_string();
                    member.invited_at_millis = Some(now);
                    member.updated_at_millis = now;
                    wrote = true;
                }
                // An account this administrator holds no member record for cannot be
                // invited — GuardDuty has to be enabled in the account and the
                // account recorded first — so it is reported rather than refused, and
                // nothing is persisted for it. The administrator's own account is one
                // of these: it is never one of its own members.
                None => unprocessed.push(UnprocessedAccount {
                    account_id: account_id.clone(),
                    result: crate::state::NOT_AN_ASSOCIATED_MEMBER_MESSAGE.to_string(),
                }),
            }
        }

        // An invitation that was sent is pending for the account it was delivered to
        // until that account answers it, so the send writes the MEMBER side of the
        // relationship too: it delivers the invitation to the inbox the Region's
        // endpoint serves, which is what the inbox reads report and what an
        // acceptance, a decline and a delete each act on. A call that invited nobody
        // sent nothing, so it delivers nothing.
        //
        // Nothing is reported from the delivery, because every outcome it can have is
        // already the outcome this call owes its caller: it answers `false` for an
        // inviting account whose invitation is still pending, which is the re-send
        // that must change nothing at all, and the inbox ceiling it also guards is not
        // reachable through a request — the inbox is keyed by the SENDING account and
        // every account this emulator presents carries the one canonical account id,
        // so a Region's inbox holds at most that single key.
        if sent {
            wrote |= state.deliver_invitation_in(&region, &administrator, now);
        }

        // The instant is taken off the clock only now that one of the two sides of
        // the relationship has really been written: a call that invited nobody, and
        // one that only re-sent invitations already pending, left the store exactly
        // as it found it, so neither consumes an instant.
        if wrote {
            state.commit_millis(now);
        }

        // `Message` and `DisableEmailNotification` govern the EMAIL the invitation is
        // announced by, which is not something this emulator sends and not something
        // any read reports — the `Invitation` shape carries no message
        // (`smithy_query(shape="Invitation")`) — so neither member is persisted.
        Ok(InviteMembersOutput {
            unprocessed_accounts: unprocessed,
        })
    }
}

