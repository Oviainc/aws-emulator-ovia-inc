    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // Tagging is identified by the resource's ARN alone; nothing else about the
        // request takes part in it.
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(TagResourceErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the AWS Control Tower emulator is mounted on an engine that \
                              holds no state"
                        .to_string(),
                },
            )
            .into());
        };

        let mut store = state.lock();
        // Only materialises transitions the clock already owed, so a resource whose
        // teardown has become due is already gone and cannot be tagged.
        store.settle(::std::time::SystemTime::now());

        // `resourceArn` is modelled as an `Arn`, so the only value the front door lets
        // through is an ARN — and the ARNs this service mints are the keys of its
        // resource stores.
        if !store.taggable_resource_exists(&input.resource_arn) {
            return Err(TagResourceErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: format!("no resource matches resourceArn {}", input.resource_arn),
                },
            )
            .into());
        }

        // The single merge site for the tag store: past the cap nothing is written and
        // the request is refused with the error the model declares for this operation.
        if store.merge_tags(&input.resource_arn, input.tags).is_none() {
            return Err(TagResourceErrorModeled::ValidationException(
                ValidationException {
                    message: format!(
                        "a resource carries at most {} tags; remove tags from {} before \
                         applying more",
                        crate::state::MAX_TAGS_PER_RESOURCE, input.resource_arn
                    ),
                },
            )
            .into());
        }

        Ok(TagResourceOutput {})
    }
