//! @op UpdateChannel
//! IMPLEMENTED. Updates one channel's editable members and reports the channel as it is
//! now stored, so a later `GetChannel` returns the same bytes.
//!
//! The switching and CMSD-header blocks the SERVICE applies are re-materialised exactly
//! as the create materialises them; every member the model restricts to particular input
//! types is refused on the channel's STORED (immutable) input type through the same rule
//! table `CreateChannel` uses; and the multiview configuration — which the model says
//! can be changed but neither added nor removed — is preserved when the request omits it,
//! and, when it carries one, is held to the same contents rules the create holds it to:
//! neither of its lists may repeat an entry, and each available source must name a
//! channel of the same group whose input type and output locking mode a tile source may
//! have.
//! The read-only `AttachedMultiviewChannels` member is DERIVED from the group after the
//! write, as on every other channel reader, since an update neither adds nor removes an
//! attachment.
//!
//! ## The conditional-update contract
//!
//! `ETag` arrives in the `x-amzn-update-if-match` header. When it is present it is a
//! PRECONDITION: the update commits only if the entity tag it carries is still the
//! committed one, and is refused `ConflictException` (409,
//! `ConflictExceptionType` `CONFLICTING_OPERATION`) otherwise. The comparison and the
//! write happen under ONE hold of the store lock, which is the serialization point that
//! makes N concurrent racers reading one entity tag resolve to exactly ONE winner —
//! never zero, because the winner's read-compare-write cannot be interleaved. Each
//! commit bumps the resource's version, so the tag the losers hold is necessarily stale
//! even when they were writing the same values.
//!
//! An absent `ETag` is an unconditional update, which is what the model's optional
//! member means.
//!
//! A commit is what rotates the tag, and only a write that CHANGED the channel commits:
//! an update that stored exactly the content the channel already held leaves `ModifiedAt`
//! and the ETag alone, so the tag the caller just read stays usable as the precondition of
//! its next update.
//!
