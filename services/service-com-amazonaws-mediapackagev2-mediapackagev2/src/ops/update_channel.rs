        // held to the rules the create holds them to: neither list may repeat an entry
        // (decided above, without the store), and every available source has to be a
        // channel of this same group whose input type and output locking mode a tile
        // source may have. The
        // required-member direction is not an update's: an absent configuration leaves the
        // stored one in place (below), so the channel still has the one its input type
        // requires.
        if let Some(violation) = input
            .multiview_configuration
            .as_ref()
            .and_then(|multiview| crate::state::multiview_source_violation(group, multiview))
        {
            return Err(UpdateChannelErrorModeled::ValidationException(violation).into());
        }

        // Only the members `UpdateChannelRequest` binds are editable; everything else
        // (the name, the ARN, the ingest endpoints, `CreatedAt`, the output-locking mode,
        // the attached policy and the tags) is immutable or not this operation's input,
        // so the update leaves it exactly as the store holds it. A bound member the
        // request omits is cleared, except the ones the model documents otherwise, each
        // handled on its own here. The switching and CMSD-header blocks are
        // MATERIALISED, not echoed, by the same functions the create uses, so an update
        // that omits them leaves the channel with the state the service reports rather
        // than with nothing.
        // Every refusal is behind us, so the channel can be taken mutably for the write.
        // The group holds it under the name the request addressed, which the read above
        // already resolved, so the lookup cannot miss: ONE hold of the store's lock
        // covers both.
        let Some(channel) = group.channels.get_mut(&input.channel_name) else {
            return Err(UpdateChannelErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("the MediaPackageV2 store is unavailable".to_string()),
                },
            )
            .into());
        };
        // What the channel was before this request wrote anything, so the commit below
        // can tell a real change from an update that stored what was already there.
        let before = channel.configuration_fingerprint();
