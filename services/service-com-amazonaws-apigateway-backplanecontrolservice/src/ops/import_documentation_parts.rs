/// The `ImportDocumentationParts` operation.
///
/// Owns the shared engine (the constructor seam) and implements
/// [`smithy_server_runtime::Operation`]. Generic over the engine type `Eng`, so this
/// crate names no concrete engine type: a migrated service that needs state picks a
/// concrete engine where it mounts the service, not here.
pub struct ImportDocumentationParts<Eng> {
    engine: ::std::sync::Arc<Eng>,
}

impl<Eng> ImportDocumentationParts<Eng> {
    /// Construct the operation from the shared engine. INFALLIBLE — the engine is a
    /// construction-time dependency, so engine access is guaranteed by the time any
    /// request runs. Called by the generated `EmulatedService::new(engine)` constructor.
    pub fn new(engine: ::std::sync::Arc<Eng>) -> Self {
        Self { engine }
    }
}

impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ImportDocumentationParts<Eng>
{
    type Input = ImportDocumentationPartsInput;
    type Output = ImportDocumentationPartsOutput;
    type Error = ImportDocumentationPartsError;

    const NAME: &'static str = "ImportDocumentationParts";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::IMPORT_DOCUMENTATION_PARTS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::IMPORT_DOCUMENTATION_PARTS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine)
            .ok_or_else(crate::state::state_unavailable)?;

        // Every refusal below is the modelled 400: the request's body or mode is wrong,
        // and the message names what to fix.
        fn bad_request(message: String) -> ImportDocumentationPartsError {
            ImportDocumentationPartsErrorModeled::BadRequestException(BadRequestException {
                message: Some(message),
            })
            .into()
        }

        // The body is read and bounded BEFORE the store lock is taken, so a malformed or
        // over-sized import never reaches the records at all — and so does the rule that
        // every entry be storable, which is what makes the import all-or-nothing.
        let mode = put_mode(input.mode.as_deref()).map_err(bad_request)?;
        let ImportedParts { parts } = parse_import(&input.body).map_err(bad_request)?;

        // `failOnWarnings` is "a query parameter to specify whether to rollback the
        // documentation importation (true) or not (false) when a warning is encountered":
        // the warnings are what the document earns ([`import_warnings`]), and the rollback
        // is decided BEFORE the store is touched, so a refused import leaves the API's
        // documentation set exactly as it was. With the flag off the same body is imported
        // and the warnings are reported instead ([`ImportDocumentationPartsOutput`]'s
        // `warnings`).
        let warnings = import_warnings(&input.body);
        if input.fail_on_warnings && !warnings.is_empty() {
            return Err(bad_request(warnings_refusal(&warnings)));
        }

        // `failOnWarnings` is "a query parameter to specify whether to rollback the
        // documentation importation (true) or not (false) when a warning is encountered":
        // an import this service carries out applies every entry its body declares, and
        // the warnings the document earns were decided above — before the store was
        // touched, which is what makes the rollback "nothing was applied" rather than an
        // undo.

        let mut store = state.lock();

        // The entities the body documents: what an `overwrite` import leaves documented,
        // however many entries name each of them.
        let imported_entities: BTreeSet<[String; 5]> =
            parts.iter().map(|part| location_key(&part.location)).collect();

        // How many documentation parts this import CREATES: one per entry whose entity the
        // API does not already document. An entry for an entity it DOES document lands on
        // that part, keeping its identifier, whichever mode the import runs in.
        let minted_count = {
            let api = store.rest_apis.get(&input.rest_api_id).ok_or_else(|| {
                ImportDocumentationPartsErrorModeled::NotFoundException(NotFoundException {
                    message: Some(crate::state::no_such_rest_api(&input.rest_api_id)),
                })
            })?;
            // The parts that survive this import: all of them in `merge`, and in
            // `overwrite` — which replaces "any existing DocumentationParts definition" —
            // only those documenting an entity the body documents.
            let kept: Vec<[String; 5]> = api
                .documentation_parts
                .values()
                .map(|part| location_key(&part.location))
                .filter(|key| mode == PutModeKind::Merge || imported_entities.contains(key))
                .collect();
            let landed: BTreeSet<&[String; 5]> = kept.iter().collect();
            let minted = parts
                .iter()
                .filter(|part| !landed.contains(&location_key(&part.location)))
                .count();
            if kept.len() + minted > crate::state::MAX_DOCUMENTATION_PARTS_PER_API {
                return Err(ImportDocumentationPartsErrorModeled::LimitExceededException(
                    LimitExceededException {
                        retry_after_seconds: None,
                        message: Some(crate::state::quota_reached(
                            "Documentation Parts",
                            "API",
                        )),
                    },
                )
                .into());
            }
            minted
        };
        // One id and one creation rank per part this import CREATES: an entry that lands
        // on the part already documenting its entity keeps that part's id and rank
        // instead.
        let ids = store.reserve_ids(minted_count);
        let sequences: Vec<u64> = (0..minted_count).map(|_| store.next_sequence()).collect();

        let api = store.rest_apis.get_mut(&input.rest_api_id).ok_or_else(|| {
            ImportDocumentationPartsErrorModeled::NotFoundException(NotFoundException {
                message: Some(crate::state::no_such_rest_api(&input.rest_api_id)),
            })
        })?;
        if mode == PutModeKind::Overwrite {
            // `overwrite` replaces "any existing DocumentationParts definition": the
            // imported set becomes the API's documentation, so an entity the body does
            // not document is no longer documented. An entity it DOES document keeps the
            // part documenting it — the entry lands on that record, under its identifier,
            // rather than on a second part for one entity — so a client holding that id
            // still reads, patches and deletes the entity's documentation after the
            // import.
            api.documentation_parts
                .retain(|_, part| imported_entities.contains(&location_key(&part.location)));
        }

        // The entity-to-part index this import writes through, built ONCE from the
        // documentation set the import LANDS ON — the one that was already there: an entry
        // lands on the part documenting its entity with a lookup, so the work under the
        // lock is one lookup per entry rather than a scan of the API's whole documentation
        // set.
        let documented: BTreeMap<[String; 5], (String, u64)> = api
            .documentation_parts
            .values()
            .map(|part| {
                (
                    location_key(&part.location),
                    (part.id.clone(), part.sequence),
                )
            })
            .collect();

        let mut minted = 0usize;
        // One identifier per ENTITY the body documents, in the order it documents them:
        // the read already landed every entry on the entity it documents
        // ([`parse_import`]), so an entity several entries name is one part here.
        let mut imported: Vec<String> = Vec::with_capacity(parts.len());
        for part in parts {
            // `merge` merges "the new definition into the existing one": an entry for an
            // entity the API already documents replaces that part's content map under its
            // own identifier, so a re-import does not double the documentation set.
            let key = location_key(&part.location);
            let (id, sequence) = match documented.get(&key) {
                Some(existing) => existing.clone(),
                None => {
                    let id = ids
                        .get(minted)
                        .cloned()
                        .ok_or_else(crate::state::state_unavailable)?;
                    let sequence = sequences
                        .get(minted)
                        .copied()
                        .ok_or_else(crate::state::state_unavailable)?;
                    minted += 1;
                    (id, sequence)
                }
            };
            api.documentation_parts.insert(
                id.clone(),
                DocumentationPartEntry {
                    id: id.clone(),
                    location: part.location,
                    properties: part.properties,
                    sequence,
                },
            );
            imported.push(id);
        }

        // Everything below is owned, so the store lock is released before the response is
        // formatted: the critical section covers the state change only.
        drop(store);
        // The access record for a state-changing operation: who, what, and the outcome.
        // Metadata only — never the imported content maps.
        ::tracing::info!(
            target: crate::state::AUDIT_TARGET,
            operation = Self::NAME,
            caller = ?crate::state::request_caller(ctx.parts()),
            rest_api = ?input.rest_api_id,
            mode = ?mode,
            documentation_parts = imported.len(),
            outcome = "imported",
            "documentation parts imported",
        );
        Ok(ImportDocumentationPartsOutput {
            ids: Some(imported),
            // "A list of warning messages reported during import of documentation parts":
            // what the document earned, which an import carried out reports rather than
            // refuses. A document that earns none reports none at all, exactly as the
            // sibling definition import reports none.
            warnings: (!warnings.is_empty()).then_some(warnings),
        })
    }
}
