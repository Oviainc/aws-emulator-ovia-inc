/// The paths an `Authorizer` publishes, per `op`, in the order API Gateway enumerates them
/// when it refuses one it cannot apply.
///
/// A `replace` names one of the authorizer's updateable SINGLE-VALUED members, in the
/// `Authorizer` shape's own member order
/// (`smithy_query(query="shape", shape="com.amazonaws.apigateway#Authorizer")`: id, name,
/// type, providerARNs, authType, authorizerUri, authorizerCredentials, identitySource,
/// identityValidationExpression, authorizerResultTtlInSeconds), with `id` dropped — it is
/// the URI label addressing this very record.
///
/// An `add` names a MULTI-VALUED member instead — the pool ARNs of a user-pool authorizer
/// and the identity sources it reads, each of which an element is added to — so that op
/// enumerates its own set, as a recorded refusal of a path under an `add` shows. A
/// `remove` publishes no path: nothing records a set for it, and the two ops' sets need not
/// coincide, so an unapplicable path under a `remove` is answered as an op the resource
/// publishes no path for.
const PATCH_PATHS: SupportedPatchPaths = SupportedPatchPaths {
    add: &["/providerARNs", "/identitySource"],
    remove: &[],
    replace: &[
        "/name",
        "/type",
        "/authType",
        "/authorizerUri",
        "/authorizerCredentials",
        "/identitySource",
        "/identityValidationExpression",
        "/authorizerResultTtlInSeconds",
    ],
};

/// How this operation words a refusal of a patch `path` it cannot apply: the path quoted,
/// the `op` that named it and the paths this resource publishes. Reaches every path
/// refusal the request goes on to produce, so one unapplicable pointer reads the same
/// whether it names no member of the authorizer, reaches into one of its single-valued
/// members, or is no JSON Pointer at all.
const INVALID_PATH: InvalidPathRefusal = InvalidPathRefusal::PathOpAndSupported(PATCH_PATHS);

// The `path` values `UpdateAuthorizer` accepts are the ones `apply_patch` below has an arm
// for: one per updateable member of the `Authorizer` shape. `id` is the authorizer's
// identity — the URI label that addresses this very record — so it is reported but not
// patchable, exactly as `UpdateApiKey` treats a key's `id`.
//
// `authorizerResultTtlInSeconds` is checked through the SAME checker `CreateAuthorizer`
// runs ([`authorizer_result_ttl`]), so one TTL is refused with one sentence whichever
// operation set it.

/// Apply one patch to a COPY of a stored authorizer.
fn apply_patch(entry: &mut AuthorizerEntry, patch: &Patch) -> Result<(), PatchFailure> {
    match patch.member() {
        // An authorizer always reports a name and a type, so each can be set but not
        // cleared; a patch `value` is a bare string on the wire, so the `type`'s value set
        // is checked here rather than by the boundary validator.
        "name" => patch_required_string(&mut entry.name, patch, MAX_STRING_CHARS),
        "type" => {
            if matches!(patch.op, PatchOpKind::Add | PatchOpKind::Replace) {
                patch.require_single_valued()?;
                let value = patch.require_value()?;
                if !AUTHORIZER_TYPE_VALUES.contains(&value) {
                    // The sentence belongs to the MEMBER, not to the call that wrote it:
                    // a value outside `AuthorizerType` reads the same here as it does on
                    // the create.
                    return Err(PatchFailure::BadRequest(
                        crate::ops::create_authorizer::INVALID_AUTHORIZER_TYPE.to_string(),
                    ));
                }
            }
            patch_required_string(&mut entry.r#type, patch, MAX_STRING_CHARS)
        }
        "authType" => patch_optional_string(&mut entry.auth_type, patch, MAX_STRING_CHARS),
        "authorizerUri" => {
            patch_optional_string(&mut entry.authorizer_uri, patch, MAX_STRING_CHARS)
        }
        // "To use resource-based permissions on the Lambda function, specify null"
        // (`Authorizer$authorizerCredentials`), so this member can be cleared.
        "authorizerCredentials" => {
            patch_optional_string(&mut entry.authorizer_credentials, patch, MAX_STRING_CHARS)
        }
        "identitySource" => {
            patch_optional_string(&mut entry.identity_source, patch, MAX_STRING_CHARS)
        }
        "identityValidationExpression" => patch_optional_string(
            &mut entry.identity_validation_expression,
            patch,
            MAX_STRING_CHARS,
        ),
        // A stored authorizer always carries a TTL — the member documents the value the
        // service picks for a request that sets none — so it is replaced inside its
        // published window and never cleared.
        "authorizerResultTtlInSeconds" => patch_i32_checked(
            &mut entry.authorizer_result_ttl_in_seconds,
            patch,
            |requested| authorizer_result_ttl(Some(requested)),
        ),
        // The path names ONE pool ARN of the list, or the op's own `value` does: a
        // collection member has elements added and removed rather than being replaced
        // whole.
        "providerARNs" => {
            let arn = patch.collection_entry(1)?;
            crate::state::bound_chars(&patch.path, &arn, MAX_STRING_CHARS)
                .map_err(PatchFailure::BadRequest)?;
            patch_string_set(&mut entry.provider_arns, patch, &arn, MAX_COLLECTION_ENTRIES)
        }
        _ => Err(patch.unsupported_path()),
    }
}

