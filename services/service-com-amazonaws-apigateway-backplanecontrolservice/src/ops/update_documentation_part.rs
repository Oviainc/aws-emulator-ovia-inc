// The `path` values `UpdateDocumentationPart` accepts are the ones `apply_patch` below
// has an arm for.
//
// The `DocumentationPart` shape declares exactly three members — `id`, `location` and
// `properties` — and only the content map is an updateable one: `id` is "generated by API
// Gateway when the DocumentationPart is created" (`DocumentationPart$id`), and `location`
// is "the location of the API entity to which the documentation applies", which is this
// record's identity — it is what makes a second part at one location the
// `ConflictException` `CreateDocumentationPart` answers, so documenting another entity is
// a create, not a patch. The same rule `UpdateMethodResponse` applies to a response's
// `statusCode` and `UpdateRestApi` to an API's `id`.

/// Apply one patch to a COPY of a stored documentation part.
fn apply_patch(entry: &mut DocumentationPartEntry, patch: &Patch) -> Result<(), PatchFailure> {
    match patch.member() {
        // A stored part always has a content map (`properties` is required on
        // `CreateDocumentationPartRequest`), so the member is set by an `add` or a
        // `replace` and cannot be removed. The patched text must still be what the member
        // documents — "a content map ... encoded as a JSON string"
        // (`DocumentationPart$properties`) — so it is read by the same function the create
        // and the import read it with, and the store never holds a `properties` that is
        // not a content map.
        "properties" => {
            patch_required_string(&mut entry.properties, patch, MAX_PROPERTIES_CHARS)?;
            entry.properties =
                validated_properties(&entry.properties).map_err(PatchFailure::BadRequest)?;
            Ok(())
        }
        _ => Err(patch.unsupported_path()),
    }
}

