// The `path` values `UpdateGatewayResponse` accepts are the ones `apply_patch` below has
// an arm for: the two MAP members of the `GatewayResponse` shape, and its `statusCode`
// under a `replace`. `responseType` is the response's identity — it is the URI label that
// addresses this very record — so it is reported but not patchable, the way
// `UpdateMethodResponse` treats a method response's `statusCode`; `defaultResponse` is the
// service's own report of whether the response is generated or customized, not a member a
// caller sets.
//
// Which ops one pointer takes is part of that table: a recorded refusal of `/statusCode`
// under an op other than `replace` names the PATH and nothing of the op, so this operation
// keys every unapplicable entry on its pointer (`UnsupportedOpRefusal::Path`, passed where
// the request's list is read).

/// Apply one patch to a COPY of the gateway response `response_type` reports.
///
/// Two of the three patchable pointers are MAPS, so a path addressing one of them names
/// ONE entry (`/responseTemplates/application~1json`), and the edit is the service's
/// shared map-patch semantics ([`patch_string_map`]): `add` and `replace` set the entry,
/// `remove` drops it, and `move`/`copy`/`test` name nothing on such a member. The status
/// code is single-valued and takes a `replace` only.
fn apply_patch(entry: &mut GetGatewayResponseOutput, patch: &Patch) -> Result<(), PatchFailure> {
    match patch.member() {
        // "The HTTP status code for this GatewayResponse"
        // (`GatewayResponse$statusCode`), typed `StatusCode` and so constrained to
        // `^[1-5]\d\d$` — a constraint a patch `value` reaches the handler unvalidated
        // against, since it is a bare string on the wire.
        "statusCode" => {
            patch.require_single_valued()?;
            match patch.op {
                PatchOpKind::Replace => {
                    let value = patch.require_value()?;
                    if !crate::state::is_status_code(value) {
                        return Err(PatchFailure::BadRequest(format!(
                            "{} must satisfy the pattern ^[1-5]\\d\\d$, got {value:?}",
                            patch.path
                        )));
                    }
                    entry.status_code = Some(value.to_string());
                }
                // Every other op: the member is SET by a `replace` and by
                // `PutGatewayResponse`, and by nothing else — an `add` puts no entry
                // anywhere and a `remove` would leave the response with no code to answer
                // with. The recorded evidence is an `add` of this pointer, answered with
                // the PATH refusal while a `replace` of it is served; the op set the
                // pointer takes is read from that pair rather than per op, so a recording
                // of a `remove` of it would be what narrows this arm again.
                _ => return Err(patch.unsupported_op()),
            }
            Ok(())
        }
        // "Response parameters (paths, query strings and headers) of the GatewayResponse
        // as a string-to-string map of key-value pairs"
        // (`GatewayResponse$responseParameters`). The key is a mapping expression, so a
        // patch that SETS an entry is refused when the key it names is not one — the same
        // rule `PutGatewayResponse` stores a key by, so a mapping this service refuses on
        // one path cannot be written through the other. A `remove` names an entry already
        // stored, so it is not checked against the form again.
        "responseParameters" => {
            let name = crate::state::bounded_map_key(patch, 1)?;
            if matches!(patch.op, PatchOpKind::Add | PatchOpKind::Replace)
                && !super::put_gateway_response::is_gateway_response_parameter(&name)
            {
                return Err(PatchFailure::BadRequest(
                    super::put_gateway_response::invalid_response_parameter(&name),
                ));
            }
            // A `remove` names ONE parameter the response HAS. A name it carries no
            // parameter under removes nothing, so the request is refused rather than
            // answered with the unchanged record: a client told its removal succeeded
            // would believe a parameter gone that was never configured.
            if matches!(patch.op, PatchOpKind::Remove)
                && entry
                    .response_parameters
                    .as_ref()
                    .is_none_or(|parameters| !parameters.contains_key(&name))
            {
                return Err(PatchFailure::NotFound(
                    crate::state::INVALID_RESPONSE_PARAMETER_NAME.to_string(),
                ));
            }
            let mut parameters = crate::state::ordered_map(entry.response_parameters.take());
            patch_string_map(
                &mut parameters,
                patch,
                name,
                MAX_COLLECTION_ENTRIES,
                MAX_STRING_CHARS,
            )?;
            entry.response_parameters = crate::state::stored_map(parameters);
            Ok(())
        }
        // "Response templates of the GatewayResponse as a string-to-string map of
        // key-value pairs" (`GatewayResponse$responseTemplates`), keyed by the content
        // type the template renders; a `/` in that content type is escaped `~1` the way a
        // JSON Pointer requires.
        "responseTemplates" => {
            let content_type = crate::state::bounded_map_key(patch, 1)?;
            let mut templates = crate::state::ordered_map(entry.response_templates.take());
            patch_string_map(
                &mut templates,
                patch,
                content_type,
                MAX_COLLECTION_ENTRIES,
                MAX_STRING_CHARS,
            )?;
            entry.response_templates = crate::state::stored_map(templates);
            Ok(())
        }
        _ => Err(patch.unsupported_path()),
    }
}

