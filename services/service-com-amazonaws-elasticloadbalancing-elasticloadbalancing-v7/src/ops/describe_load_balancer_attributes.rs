/// Project the stored attributes onto the modelled `LoadBalancerAttributes`.
///
/// EVERY member is reported, for a load balancer nobody has modified as much as for one
/// that has been: AWS answers this operation with the full attribute set, so a client
/// reading `ConnectionSettings.IdleTimeout` or the `elb.http.desyncmitigationmode`
/// additional attribute off a freshly created load balancer finds it. The values are the
/// record's own — the service defaults are seeded into the record at create, not
/// synthesized here.
fn reported(attributes: &crate::state::AttributeConfig) -> LoadBalancerAttributes {
    LoadBalancerAttributes {
        cross_zone_load_balancing: Some(CrossZoneLoadBalancing {
            enabled: attributes.cross_zone_load_balancing_enabled,
        }),
        access_log: Some(AccessLog {
            enabled: attributes.access_log.enabled,
            s3_bucket_name: attributes.access_log.s3_bucket_name.clone(),
            emit_interval: Some(attributes.access_log.emit_interval_minutes),
            s3_bucket_prefix: attributes.access_log.s3_bucket_prefix.clone(),
        }),
        connection_draining: Some(ConnectionDraining {
            enabled: attributes.connection_draining.enabled,
            timeout: Some(attributes.connection_draining.timeout_seconds),
        }),
        connection_settings: Some(ConnectionSettings {
            idle_timeout: attributes.idle_timeout_seconds,
        }),
        additional_attributes: Some(
            attributes
                .additional
                .iter()
                .map(|(key, value)| AdditionalAttribute {
                    key: Some(key.clone()),
                    value: Some(value.clone()),
                })
                .collect(),
        ),
    }
}
