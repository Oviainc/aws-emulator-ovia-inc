//! @op Encrypt
//! IMPLEMENTED: seals a plaintext under the key material of the KMS key a `KeyId`
//! names. This is the ONLY file to touch for this operation.
//!
//! For a symmetric encryption key the returned `CiphertextBlob` is an AES-256-GCM
//! envelope built by [`crate::state::seal`]: it names the key that sealed it,
//! authenticates the encryption context, and is the exact input `Decrypt` inverts. For an
//! asymmetric encryption key it is the plaintext sealed to the PUBLIC half of the key's
//! key pair under the declared algorithm ([`crate::state::encrypt_asymmetric`]), which
//! only the private half held here opens and which carries no encryption context. Either
//! way it is opaque — the plaintext does not appear in it — and a blob sealed by one key
//! cannot be opened by another.
//!
//! Permission is the service's one authorization decision
//! ([`crate::state::authorization`]): a request that presents NO `GrantTokens` is judged
//! against the key's own key policy, the calling principal's identity-based policies and
//! the grants on this key issued to that principal, and is refused when none of them
//! allows it.
//!
//! One deliberate divergence, which [`crate::state::authorization::authorize`] states
//! once for every handler that shares it: a request that DOES present a grant token is
//! treated as drawing its permission from the grants those tokens name, so the grant must
//! be on this key, permit this operation and have its encryption-context constraints met.
//! In the real service a grant token is ADDITIVE — a caller the key policy already
//! permits succeeds even when the token it presents grants nothing relevant — so the
//! effect here is narrower than AWS: an otherwise-permitted call that carries an
//! unrelated or stale grant token is refused.
//!
//! A request that presents NO grant token draws its permission from the key's own policy,
//! and the one thing that policy decides without a caller identity is judged:
//! [`crate::state::authorization`] refuses the request when every statement granting this
//! action is gated on a condition the request does not satisfy.
//!
