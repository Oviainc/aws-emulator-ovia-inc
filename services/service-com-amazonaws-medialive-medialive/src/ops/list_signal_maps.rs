        // A template group belongs to the region it was created in, so a group
        // identifier this request filters by resolves in the region the request
        // was signed for.
        let region = crate::state::request_region(ctx.parts());

        // The page size this listing cuts at is the service's shared page-size
        // rule ([`crate::state::list_page_size`]), whose refusal this operation
