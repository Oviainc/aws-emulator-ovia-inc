impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for BatchStop<Eng>
{
    type Input = BatchStopInput;
    type Output = BatchStopOutput;
    type Error = BatchStopError;

    const NAME: &'static str = "BatchStop";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::BATCH_STOP_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::BATCH_STOP_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;

        // The request's two id lists carry no modelled length constraint, and
        // each id costs a lookup and a projection plus one result entry, so the
        // batch is bounded BEFORE the state guard is taken: the guard is never
        // held for an amount of work the caller chose. The shared bound answers
        // the message; this operation lifts it into the modelled client error IT
        // declares.
        within_id_cap(
            Self::NAME,
            crate::state::MAX_BATCH_STOP_IDS,
            &[&input.channel_ids, &input.multiplex_ids],
        )
        .map_err(|message| {
            BatchStopErrorModeled::BadRequestException(BadRequestException {
                message: Some(message),
            })
        })?;

        let state = crate::state::service_state(&*self.engine, ctx.parts()).ok_or_else(unavailable)?;
        let now = ::std::time::SystemTime::now();

        let mut state = state.lock();
        // Transitions the clock had already made due were owed whether or not
        // this call ran, so they are materialised before anything is read: a
        // channel whose `STARTING` span has passed is `RUNNING`, and that is the
        // state this stop acts on.
        state.settle(now);

        // "Stops running resources": each named resource is attempted on its own
        // and reported on its own, so the call itself answers 200 even when
        // every resource named in it was refused.
        let mut results = Results::default();
        for id in input.channel_ids.unwrap_or_default() {
            results.push(stop_channel(&mut state, &id, now)?);
        }
        for id in input.multiplex_ids.unwrap_or_default() {
            results.push(stop_multiplex(&mut state, &id, now)?);
        }

        Ok(BatchStopOutput {
            failed: Some(results.failed),
            successful: Some(results.successful),
        })
    }
}

/// One channel's stop, under exactly `StopChannel`'s rule: an id whose delete
/// has been accepted names no channel to stop and is reported NOT FOUND, and a
/// channel that still exists stops from `RUNNING` only — every other state
/// (still creating, still starting, already stopping, idle) is a conflict —
/// while an accepted stop puts it in `STOPPING`, owing the stopped `IDLE` the
/// clock then makes due.
fn stop_channel(
    state: &mut State,
    id: &str,
    now: ::std::time::SystemTime,
) -> Result<Outcome, BatchStopError> {
    // The id is resolved through the shared channel guard FIRST, so a channel
    // whose delete has been accepted is reported with the NOT-FOUND code
    // `StopChannel` answers for it rather than with a state conflict. The guard
    // hands back the tombstone's own ARN for the entry to name.
    let channel = match state.mutable_channel(id) {
        Ok(channel) => channel,
        Err(dead) => {
            return Ok(refused(id, dead.arn, failure_code::NOT_FOUND, dead.message));
        }
    };
    if channel.state != crate::state::channel_state::RUNNING {
        return Ok(refused(
            id,
            Some(channel.arn.clone()),
            failure_code::CONFLICT,
            crate::state::channel_not_running_message(id, &channel.state),
        ));
    }
    crate::state::begin_stop(channel, now);

    // Read the result back out of the store, so the entry reports what was
    // written rather than what this handler meant to write. A description that
    // is suddenly missing is a server fault, not an accepted stop with empty
    // members — the same `unavailable()` `StopChannel` answers for it.
    accepted(
        id,
        state
            .channel_description(id)
            .map(|channel| (channel.arn, channel.state)),
    )
    .ok_or_else(unavailable)
}

/// One multiplex's stop, under exactly `StopMultiplex`'s rule: a running
/// multiplex moves into `STOPPING`, owing the stopped `IDLE` the clock then
/// makes due, and a multiplex that is not running is left exactly as it is —
/// "If the multiplex isn't running, this action has no effect" — so it is
/// reported in the state it already stands in rather than refused. The one
/// refusal is an id the account does not hold.
fn stop_multiplex(
    state: &mut State,
    id: &str,
    now: ::std::time::SystemTime,
) -> Result<Outcome, BatchStopError> {
    match state.stop_multiplex(id, now) {
        Ok(()) => accepted(
            id,
            state
                .multiplex_description(id)
                .map(|multiplex| (multiplex.arn, multiplex.state)),
        )
        .ok_or_else(unavailable),
        Err(crate::state::MultiplexStopRefusal::NotFound) => Ok(not_found("Multiplex", id)),
    }
}

