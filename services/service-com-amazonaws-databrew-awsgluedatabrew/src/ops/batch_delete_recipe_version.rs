                return Err(refused_as_invalid(format!(
                    "RecipeVersions must name numeric versions X.Y or {}: {} is not \
                     supported by this operation",
                    crate::state::LATEST_WORKING,
                    crate::state::LATEST_PUBLISHED
                )));
