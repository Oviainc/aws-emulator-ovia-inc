        let steps = steps.unwrap_or_default();

        let now = ::std::time::SystemTime::now();
        let principal = crate::state::request_principal();

        let mut store = state.lock();
        // `Name` addresses the recipe to UPDATE rather than a name this operation mints,
        // so the documented character set is `CreateRecipe`'s rule and a name this
        // account holds no recipe under is answered by the lookup with the modelled 404.
        // Every recipe has a working version from the moment it is created, so the
        // recipe itself is the only half this operation can miss.
