impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CreateDataset<Eng>
{
    type Input = CreateDatasetInput;
    type Output = CreateDatasetOutput;
    type Error = CreateDatasetError;

    const NAME: &'static str = "CreateDataset";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_DATASET_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_DATASET_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        _ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        use crate::state::{
            active_at, canonical_dataset_type, creation_status, dataset_arn, is_dataset_type,
            mint_tracking_id, DatasetRecord, DATASET_TYPE_VALUES, DATASET_TYPE_WITH_TRACKING_ID,
            MAX_DATASETS, STATUS_ACTIVE,
        };
        use std::time::SystemTime;

        // See `create_schema.rs`: this operation models no server-side error, so a
        // stateless mount is reported through the scaffold channel.
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(crate::scaffolded::Scaffolded::not_implemented(
                "CreateDataset",
            ));
        };

        // `DatasetType` is a plain string shape, so the boundary validator only checks
        // its pattern. The permitted set is the model's own documented one, matched
        // "case insensitive" as that documentation says. The canonical spelling is what
        // the value IDENTIFIES — the dataset's ARN segment, the type a group holds at
        // most one of, and the one type that carries a tracking id — so the casing the
        // request happened to write is not part of the dataset (see the state write).
        let Some(dataset_type) = canonical_dataset_type(&input.dataset_type) else {
            return Err(invalid_input(format!(
                "Value '{}' at 'datasetType' failed to satisfy constraint: Member must be one of \
                 [{}]",
                input.dataset_type,
                DATASET_TYPE_VALUES.join(", ")
            )));
        };

        let mut state = state.lock();

        let Some(group) = state.dataset_groups.get(&input.dataset_group_arn) else {
            return Err(not_found(
                crate::state::MissingResource::DatasetGroup,
                &input.dataset_group_arn,
            ));
        };
        // "You must wait until the status of the dataset group is ACTIVE before adding a
        // dataset to the group": a group whose create is still pending is in use by that
        // create, not available to hold a dataset.
        let group_status = creation_status(group.active_at);
        if group_status != STATUS_ACTIVE {
            return Err(CreateDatasetErrorModeled::ResourceInUseException(
                ResourceInUseException {
                    message: Some(format!(
                        "Dataset group {arn} is in status {group_status}; wait until it is \
                         {STATUS_ACTIVE} before adding a dataset.",
                        arn = input.dataset_group_arn
                    )),
                },
            )
            .into());
        }
        let arn = dataset_arn(&group.region, &group.name, dataset_type);

        if !state.schemas.contains_key(&input.schema_arn) {
            return Err(not_found(
                crate::state::MissingResource::Schema,
                &input.schema_arn,
            ));
        }

        // A dataset's identity inside its group is its TYPE — "a dataset group can
        // contain at most three datasets, one for each type of dataset" — so the clash is
        // looked up by (group, type) rather than by the minted ARN alone.
        if let Some(existing) = state.datasets.values().find(|record| {
            record.dataset_group_arn == input.dataset_group_arn
                && is_dataset_type(record, dataset_type)
        }) {
            return Err(CreateDatasetErrorModeled::ResourceAlreadyExistsException(
                ResourceAlreadyExistsException {
                    message: Some(format!(
                        "Dataset {existing_arn} of type {dataset_type} already exists in dataset \
                         group {group_arn}.",
                        existing_arn = existing.dataset_arn,
                        group_arn = input.dataset_group_arn
                    )),
                },
            )
            .into());
        }
        if state.datasets.len() >= MAX_DATASETS {
            return Err(CreateDatasetErrorModeled::LimitExceededException(
                LimitExceededException {
                    message: Some(format!(
                        "This emulator holds at most {MAX_DATASETS} datasets; delete one before \
                         creating another."
                    )),
                },
            )
            .into());
        }

        let now = SystemTime::now();

        // An ACTION INTERACTIONS dataset is addressed on the data plane by a TRACKING ID,
        // which Amazon Personalize provides with the dataset ("The ID of the event tracker
        // for an Action interactions dataset. You specify the tracker's ID in the
        // PutActionInteractions API operation"); every other type is addressed by its ARN
        // alone, so only this type is given one.
        let tracking_id = (dataset_type == DATASET_TYPE_WITH_TRACKING_ID).then(mint_tracking_id);

        // The dataset is minted here but INGESTED INTO by Amazon Personalize Events, a
        // different service whose API carries no dataset definition, so each target this
        // create mints — the ARN, and the tracking id when there is one — is recorded in
        // the registry that service reads before the record is kept here: a target the
        // control plane reports is a target the data plane can serve. Registering is
        // idempotent and never discards what was already ingested.
        //
        // The target is recorded as soon as its identifier EXISTS, not when the create's
        // clock completes: the ingestion API models no error for a dataset whose create is
        // still in progress, and whether a dataset is ready is what this service's own
        // `DescribeDataset` reports, so ingestion is not refused for a status the data
        // plane cannot express.
        if let Some(registry) = crate::state::ingestion_registry(&*self.engine) {
            let mut registry = registry.lock();
            // Registering is idempotent, so an ARN the registry already holds keeps
            // everything ingested into it — and only a registration THIS create added is
            // withdrawn again when the next one cannot be made.
            let was_registered = registry.dataset_mut(&arn).is_some();
            if registry.register_dataset(&arn).is_none() {
                return Err(ingestion_capacity_reached(
                    "datasets",
                    ::service_com_amazonaws_personalizeevents_amazonpersonalizeevents::state::MAX_DATASETS,
                ));
            }
            if let Some(tracking_id) = &tracking_id {
                if registry
                    .register_event_tracker(tracking_id, Some(input.dataset_group_arn.clone()))
                    .is_none()
                {
                    if !was_registered {
                        registry.forget_dataset(&arn);
                    }
                    return Err(ingestion_capacity_reached(
                        "event trackers",
                        ::service_com_amazonaws_personalizeevents_amazonpersonalizeevents::state::MAX_EVENT_TRACKERS,
                    ));
                }
            }
        }
        state.datasets.insert(
            arn.clone(),
            DatasetRecord {
                name: input.name.clone(),
                dataset_arn: arn.clone(),
                dataset_group_arn: input.dataset_group_arn.clone(),
                // The type is identified by its UPPER-CASE name, the same spelling the
                // ARN's trailing segment above carries, so that is the one every read
                // reports whatever casing this request wrote.
                dataset_type: dataset_type.to_ascii_uppercase(),
                schema_arn: input.schema_arn.clone(),
                tracking_id,
                creation_date_time: now,
                last_updated_date_time: now,
                // Like its group, a dataset is not created ready: "CREATE PENDING >
                // CREATE IN_PROGRESS > ACTIVE".
                active_at: active_at(now),
                tags: input.tags.clone().unwrap_or_default(),
            },
        );

        Ok(CreateDatasetOutput {
            dataset_arn: Some(arn),
        })
    }
}

