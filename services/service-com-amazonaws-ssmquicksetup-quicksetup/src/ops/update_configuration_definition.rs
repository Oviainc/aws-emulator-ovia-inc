/// Why this update cannot be served, or `None` when it can.
///
/// `TypeVersion`'s `^\d{1,3}(\.\d{1,3})?$|^LATEST$` pattern,
/// `LocalDeploymentExecutionRoleName`'s `^[\w+=,.@-]{1,64}$` pattern, both
