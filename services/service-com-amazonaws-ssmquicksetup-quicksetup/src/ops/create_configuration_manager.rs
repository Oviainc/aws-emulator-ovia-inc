/// Why this create's configuration definitions are unacceptable, or `None` when the
/// store can take them.
///
/// `ConfigurationDefinitionsInputList` is `@required` but carries no modelled length,
/// so an EMPTY list reaches the handler: a configuration manager is the deployment of
/// its definitions, so one with none to deploy is refused. Each definition's `Type`
/// must name a configuration type this service offers, because that is what selects
/// the service-owned template the definition deploys
/// (`crate::state::quick_setup_type_rejection`); its `TypeVersion` is resolved against
/// that same catalog in the handler, once the type is known to be published
/// (`crate::state::resolve_type_version`). The deployment targets a definition's
/// parameters name must be servable, because each targeted account and Region pair
/// becomes a stored configuration (`crate::state::deployment_targets_rejection`). The
/// remaining checks are
/// the store's own bounds on collections the model gives no length (see
/// `crate::state`'s `MAX_*` constants), the provider-reserved tag-key namespace a
/// caller may not assign into (`crate::state::reserved_tag_key_rejection`), and the
/// `IAMRoleArn` form of
/// `LocalDeploymentAdministrationRoleArn`, which the model states as an
/// `@arnReference` rather than as a `@pattern` the boundary could enforce.
fn definitions_rejection(input: &CreateConfigurationManagerInput) -> Option<String> {
    if input.configuration_definitions.is_empty() {
        return Some(
            "ConfigurationDefinitions must carry at least one configuration definition"
                .to_string(),
        );
    }
    let too_many = |member: &str, actual: usize, cap: usize| {
        (actual > cap).then(|| {
            format!("{member} carries {actual} entries, more than the {cap} this service accepts")
        })
    };
    too_many(
        "ConfigurationDefinitions",
        input.configuration_definitions.len(),
        crate::state::MAX_CONFIGURATION_DEFINITIONS,
    )
    .or_else(|| {
        input
            .configuration_definitions
            .iter()
            .find_map(|definition| {
                too_many(
                    "ConfigurationDefinitions.Parameters",
                    definition.parameters.len(),
                    crate::state::MAX_PARAMETERS,
                )
            })
    })
    .or_else(|| {
        // `Type` resolves a service-owned template, so only a type this service
        // publishes can be deployed; the catalog `ListQuickSetupTypes` answers is the
        // accepted set, and `crate::state` is the one place that rule lives.
        input
            .configuration_definitions
            .iter()
            .find_map(|definition| {
                crate::state::quick_setup_type_rejection(
                    "ConfigurationDefinitions.Type",
                    &definition.r#type,
                )
            })
    })
    .or_else(|| {
        // A definition's parameters name where it is deployed, and the service
        // deploys one configuration per targeted account and Region, so the targets
        // are checked before anything is stored; `crate::state` is the one place that
        // rule lives, shared with `UpdateConfigurationDefinition`.
        input
            .configuration_definitions
            .iter()
            .find_map(|definition| {
                crate::state::deployment_targets_rejection(
                    "ConfigurationDefinitions.Parameters",
                    &definition.parameters,
                )
            })
    })
    .or_else(|| {
        too_many(
            "Tags",
            input.tags.as_ref().map_or(0, std::collections::HashMap::len),
            crate::state::MAX_TAGS,
        )
    })
    .or_else(|| {
        // `TagsMap`'s key pattern admits `:`, so it admits a key under the
        // AWS-reserved prefix as well — a tag that is not the caller's to assign.
        // `crate::state::reserved_tag_key_rejection` is the one place that rule
        // lives, shared with every other member of this service that takes tag keys
        // from the caller.
        crate::state::reserved_tag_key_rejection(
            "Tags",
            input
                .tags
                .iter()
                .flat_map(std::collections::HashMap::keys)
                .map(String::as_str),
        )
    })
    .or_else(|| {
        // `LocalDeploymentAdministrationRoleArn` is an `IAMRoleArn`, whose
        // `@arnReference` to `AWS::IAM::Role` the model states with no `@pattern` to
        // enforce it; `crate::state::iam_role_arn_rejection` is the one place that
        // rule lives, shared with every other `IAMRoleArn` member of this service.
        input
            .configuration_definitions
            .iter()
            .filter_map(|definition| {
                definition.local_deployment_administration_role_arn.as_deref()
            })
            .find_map(|arn| {
                crate::state::iam_role_arn_rejection(
                    "ConfigurationDefinitions.LocalDeploymentAdministrationRoleArn",
                    arn,
                )
            })
    })
}

