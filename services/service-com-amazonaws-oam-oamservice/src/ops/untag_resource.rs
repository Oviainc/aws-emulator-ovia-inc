        // `ResourceArn`'s presence and its `^arn:(\w|-)+:oam:.+:.+:.+` pattern, and
        // every `TagKeys` entry's own `@length(1..128)`, are modelled constraints: the
        // centralized walk has already refused anything outside them before this body
