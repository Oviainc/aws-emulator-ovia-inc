    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_SCALING_POLICIES_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        use crate::state::{
            check_dimension_namespace, check_enum, decode_next_token, encode_next_token, page_size,
            scaling_policy_of, take_page, PolicyKey, TargetKey,
        };

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(DescribeScalingPoliciesErrorModeled::InternalServiceException(
                InternalServiceException {
                    message: Some(
                        "this service is mounted on an engine that holds no state".to_string(),
                    ),
                },
            )
            .into());
        };

        check_enum(
            "serviceNamespace",
            &input.service_namespace,
            SERVICE_NAMESPACE_VALUES,
        )
        .map_err(validation)?;
        if let Some(dimension) = input.scalable_dimension.as_deref() {
            check_enum("scalableDimension", dimension, SCALABLE_DIMENSION_VALUES)
                .map_err(validation)?;
            check_dimension_namespace(&input.service_namespace, dimension).map_err(validation)?;
        }
        // "If you specify a scalable dimension, you must also specify a resource ID": a
        // dimension names a capacity property of ONE resource, so a dimension filter sent
        // with no resource id is a filter with no subject — the same rule, and the same
        // sentence, every `Describe` of this service answers it with
        // ([`crate::state::check_dimension_requires_resource_id`]).
        crate::state::check_dimension_requires_resource_id(
            input.resource_id.as_deref(),
            input.scalable_dimension.as_deref(),
        )
        .map_err(validation)?;
        let page_size = page_size(input.max_results).map_err(validation)?;

        // Only the policies of THIS Region's scalable targets: the service is regional, so
        // the endpoint a request was sent to is what it reports over.
        let region = crate::state::request_region(ctx.parts());

        // The token carries the full identity of the last policy the previous page
        // emitted — its target plus its name — so this page resumes at the next key.
        let resume_after = match input.next_token.as_deref() {
            None => None,
            Some(token) => {
                let Some(fields) = decode_next_token(token, &region, 4) else {
                    return Err(
                        DescribeScalingPoliciesErrorModeled::InvalidNextTokenException(
                            InvalidNextTokenException {
                                message: Some(crate::state::INVALID_NEXT_TOKEN.to_string()),
                            },
                        )
                        .into(),
                    );
                };
                Some(PolicyKey {
                    target: TargetKey {
                        region: region.clone(),
                        service_namespace: fields[0].clone(),
                        resource_id: fields[1].clone(),
                        scalable_dimension: fields[2].clone(),
                    },
                    policy_name: fields[3].clone(),
                })
            }
        };

        let (scaling_policies, next_token) = {
            let state = state.lock();
            let matching: Vec<ScalingPolicy> = state
                .policies
                .iter()
                .filter(|(key, _)| key.target.region == region)
                .filter(|(key, _)| key.target.service_namespace == input.service_namespace)
                .filter(|(key, _)| {
                    input
                        .resource_id
                        .as_ref()
                        .is_none_or(|resource_id| &key.target.resource_id == resource_id)
                })
                .filter(|(key, _)| {
                    input
                        .scalable_dimension
                        .as_ref()
                        .is_none_or(|dimension| &key.target.scalable_dimension == dimension)
                })
                .filter(|(key, _)| match input.policy_names.as_deref() {
                    // The model bounds `PolicyNames` at 0..50, so an empty list is legal and
                    // narrows nothing.
                    None | Some([]) => true,
                    Some(names) => names.contains(&key.policy_name),
                })
                .filter(|(key, _)| resume_after.as_ref().is_none_or(|after| *key > after))
                .map(|(key, record)| scaling_policy_of(key, record))
                .collect();

            take_page(matching, page_size, |policy| {
                encode_next_token(
                    &region,
                    &[
                        &policy.service_namespace,
                        &policy.resource_id,
                        &policy.scalable_dimension,
                        &policy.policy_name,
                    ],
                )
            })
        };

        // A policy's `Alarms` are "the CloudWatch alarms associated with the scaling policy",
        // and what associates one is the alarm's own action list — so they are derived from
        // CloudWatch's state rather than from what was sent to this service: a policy that
        // minted its own alarms reports those, and one a client wired its OWN alarm to reports
        // that alarm. Read with this service's lock RELEASED, so no request holds two service
        // stores at once, and in one read however many policies this page carries.
        let invoking = crate::state::alarms_invoking_policies(&*self.engine, &region);
        let scaling_policies: Vec<ScalingPolicy> = scaling_policies
            .into_iter()
            .map(|mut policy| {
                policy.alarms = Some(
                    invoking
                        .get(&policy.policy_arn)
                        .cloned()
                        .unwrap_or_default(),
                );
                policy
            })
            .collect();

        Ok(DescribeScalingPoliciesOutput {
            scaling_policies: Some(scaling_policies),
            next_token,
        })
    }
