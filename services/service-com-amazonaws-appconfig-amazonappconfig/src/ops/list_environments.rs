        // order — which is what a pagination cursor needs to resume exactly once.
        ordered.sort_by(|(left, _), (right, _)| left.cmp(right));

        let Some(page) = crate::state::paginate(
            ordered,
            crate::state::LISTING_ENVIRONMENTS,
            input.next_token.as_deref(),
            input.max_results,
        ) else {
            return Err(ListEnvironmentsErrorModeled::BadRequestException(
                BadRequestException {
                    message: Some(
                        "NextToken is not a pagination token this operation issued.".to_string(),
                    ),
                    reason: None,
                    details: None,
                },
            )
            .into());
        };

