        // `DEPLOYING` exactly while one of its deployments is still rolling out or baking,
        // and both of those end at instants the clock fixed when the deployment started.
        // `GetEnvironment` materialises the same records the same way.
        for environment in application.environments.values_mut() {
            environment.materialize(now);
        }

        let mut ordered: Vec<(String, CreateEnvironmentOutput)> = application
            .environments
            .values()
            .map(|environment| (environment.id.clone(), reported(environment)))
            .collect();
