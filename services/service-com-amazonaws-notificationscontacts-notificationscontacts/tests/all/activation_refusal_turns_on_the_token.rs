//! Which refusal `ActivateEmailContact` answers for a code that disagrees with the
//! token the contact holds.
//!
//! RULE: the refusal a well-formed activation code that disagrees with the stored token
//! earns turns on the TOKEN alone — the modelled `ResourceNotFoundException` (HTTP 404)
//! naming the absent activation-token resource whenever the contact holds no
//! OUTSTANDING token (none was ever sent, or the one that was has run past its
//! documented lifetime or spent its documented attempt budget), and the modelled
//! `ValidationException` (HTTP 400) blaming `code` only while a token IS outstanding —
//! and never on the contact's own status; a call compared against an outstanding token
//! spends one of its attempts whatever that status is, while re-submitting the code that
//! DID activate the contact activates nothing, so it answers 200 and moves nothing.
//!
//! The two bounds are the ones the model documents:
//! `smithy_query(query="doc",shape="ActivateEmailContactRequest",member="code")` reads
//! "An email contact has a maximum of five activation attempts. Activation codes expire
//! after 12 hours and are generated by the SendActivationCode API action."
//!
//! Every case drives the harness `email_contacts.rs` builds (the production
//! `MultiServiceRouter`, restJson1 serialization and the modelled-constraint walk), and
//! reuses the token helpers `activation_code_bounds.rs` already owns, rather than
//! growing a second copy of either. The clock is never slept on: a token is aged by
//! moving the issue instant the store holds for it backwards, which is the same state
//! the service would be in after that much real time.

use serde_json::Value;
use service_com_amazonaws_notificationscontacts_notificationscontacts::state::{
    ACTIVATION_CODE_LIFETIME_MILLIS, MAX_ACTIVATION_ATTEMPTS, STATUS_ACTIVE, STATUS_INACTIVE,
};

use crate::activation_code_bounds::{
    age_token, assert_token_missing, status_of, token_attempts, wrong_codes,
};
use crate::email_contacts::{
    activate, create_ok, emulator, error_code, issued_code, send_code, Emulator,
};

/// Thirty days in milliseconds — only a row size for the table below.
const THIRTY_DAYS_MILLIS: i64 = 30 * 24 * 60 * 60 * 1_000;

/// How the token stands when the code under test arrives.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum TokenState {
    /// Freshly minted: inside both documented bounds, so a submitted code is compared
    /// against it.
    Outstanding,
    /// Aged by this many milliseconds since it was issued, which is past the documented
    /// lifetime for every row that uses it.
    AgedBy(i64),
    /// Every one of the documented attempts the token admits is spent.
    BudgetSpent,
}

impl TokenState {
    /// Whether a token in this state is still the one a submitted code is compared
    /// against.
    fn is_outstanding(self) -> bool {
        match self {
            Self::Outstanding => true,
            Self::AgedBy(age) => age < ACTIVATION_CODE_LIFETIME_MILLIS,
            Self::BudgetSpent => false,
        }
    }
}

/// The rows the table tests span: one outstanding token, the two documented ways a token
/// stops being outstanding, and the lifetime bound pinned from both the instant it is
/// reached and well past it.
const TOKEN_STATES: [(&str, TokenState); 5] = [
    ("outstanding", TokenState::Outstanding),
    (
        "aged-to-exactly-the-lifetime",
        TokenState::AgedBy(ACTIVATION_CODE_LIFETIME_MILLIS),
    ),
    (
        "aged-one-millisecond-past-the-lifetime",
        TokenState::AgedBy(ACTIVATION_CODE_LIFETIME_MILLIS + 1),
    ),
    ("aged-thirty-days", TokenState::AgedBy(THIRTY_DAYS_MILLIS)),
    ("budget-spent", TokenState::BudgetSpent),
];

/// A contact holding a token in `state`, ACTIVE when `active`, plus the code that token
/// holds.
///
/// The name is `[\w-.~]+` (the modelled `EmailContactName` pattern), so every label fed
/// in here is hyphenated.
async fn contact_with_token(
    em: &Emulator,
    label: &str,
    active: bool,
    state: TokenState,
) -> (String, String) {
    let name = format!("{label}-{}", if active { "active" } else { "inactive" });
    let arn = create_ok(em, &name, &format!("{name}@example.com")).await;
    assert_eq!(
        send_code(em, &arn).await.0,
        200,
        "case {name:?}: the send must mint an activation token"
    );
    let code = issued_code(em, &arn).expect("the send must persist a code");

    if active {
        let (status, body) = activate(em, &arn, &code).await;
        assert_eq!(
            status, 200,
            "case {name:?}: the issued code must activate the contact, got {status} / {body:?}"
        );
    }

    match state {
        TokenState::Outstanding => {}
        TokenState::AgedBy(age) => age_token(em, &arn, age),
        TokenState::BudgetSpent => {
            // Spending the budget is itself the documented rule at work: every call
            // against an outstanding token takes one of its attempts, whether this
            // contact is active or not.
            let taken = token_attempts(em, &arn).unwrap_or_else(|| {
                panic!("case {name:?}: the contact must hold a token to spend")
            });
            let left = MAX_ACTIVATION_ATTEMPTS.saturating_sub(taken) as usize;
            for (index, wrong) in wrong_codes(&code, left).iter().enumerate() {
                let (status, body) = activate(em, &arn, wrong).await;
                assert_eq!(
                    status, 400,
                    "case {name:?}: wrong code {} of {left}, still inside the budget, must \
                     be the modelled 400, got {status} / {body:?}",
                    index + 1
                );
            }
            assert_eq!(
                token_attempts(em, &arn),
                Some(MAX_ACTIVATION_ATTEMPTS),
                "case {name:?}: every attempt the token admits must now be spent"
            );
        }
    }

    (arn, code)
}

/// Assert `body` is the modelled 400 blaming the submitted `code` member, and that it
/// carries none of the 404 shape's members.
fn assert_wrong_code_400(case: &str, status: u16, body: &Value) {
    assert_eq!(
        status, 400,
        "case {case:?}: the token is outstanding, so a disagreeing code must be the \
         modelled 400, got {status} / {body:?}"
    );
    assert_eq!(
        error_code(body),
        "ValidationException",
        "case {case:?}: expected ValidationException, got {body:?}"
    );
    let blamed: Vec<&str> = body
        .get("fieldList")
        .and_then(Value::as_array)
        .map(|fields| {
            fields
                .iter()
                .filter_map(|field| field.get("name").and_then(Value::as_str))
                .collect()
        })
        .unwrap_or_default();
    assert_eq!(
        blamed,
        vec!["code"],
        "case {case:?}: the 400 must blame the submitted field, got {body:?}"
    );
    assert!(
        body.get("resourceId").is_none() && body.get("resourceType").is_none(),
        "case {case:?}: a ValidationException carries no resourceId/resourceType, got {body:?}"
    );
}

#[tokio::test]
async fn a_disagreeing_code_is_refused_by_the_token_state_whatever_the_contacts_status() {
    let em = emulator();

    // Rows differ along the two things the rule generalises over: the state of the TOKEN
    // (outstanding, past its lifetime at three ages, budget spent) and the state of the
    // CONTACT (inactive, active). The expected answer is read off the token column
    // alone, which is exactly what the rule says.
    for (label, state) in TOKEN_STATES {
        let mut answers = Vec::new();
        for active in [false, true] {
            let case = format!(
                "{label} token on a{} contact",
                if active { "n active" } else { "n inactive" }
            );
            let (arn, code) = contact_with_token(&em, label, active, state).await;
            let expected_status = if active { STATUS_ACTIVE } else { STATUS_INACTIVE };
            let attempts_before = token_attempts(&em, &arn);

            let wrong = wrong_codes(&code, 1).remove(0);
            let (status, body) = activate(&em, &arn, &wrong).await;
            if state.is_outstanding() {
                assert_wrong_code_400(&case, status, &body);
                // The call was compared against an outstanding token, so it took one of
                // that token's attempts — on an active contact just as on an inactive
                // one.
                assert_eq!(
                    token_attempts(&em, &arn),
                    attempts_before.map(|taken| taken + 1),
                    "case {case:?}: a call compared against an outstanding token must \
                     spend one of its attempts (was {attempts_before:?})"
                );
            } else {
                assert_token_missing(&case, status, &body);
                assert_eq!(
                    token_attempts(&em, &arn),
                    attempts_before,
                    "case {case:?}: there is no outstanding token to spend an attempt of"
                );
            }

            assert_eq!(
                status_of(&em, &arn).await,
                expected_status,
                "case {case:?}: a refused activation must leave the contact {expected_status}"
            );
            answers.push((case, status, error_code(&body)));
        }

        // The whole point: for ONE token state the two contact statuses answer alike.
        let (inactive_case, inactive_status, inactive_code) = &answers[0];
        let (active_case, active_status, active_code) = &answers[1];
        assert_eq!(
            (inactive_status, inactive_code),
            (active_status, active_code),
            "case {inactive_case:?} vs {active_case:?}: the refusal turns on the token, \
             so both must answer alike, got {inactive_status}/{inactive_code} and \
             {active_status}/{active_code}"
        );
    }
}

#[tokio::test]
async fn re_submitting_the_code_that_activated_the_contact_stays_200_in_every_token_state() {
    let em = emulator();

    // The idempotent arm, over the same token column: an active contact has nothing left
    // to activate, so its own code answers 200 however the token has since stood — and
    // the no-op activates nothing, so it spends no attempt and moves no timestamp.
    for (label, state) in TOKEN_STATES {
        let case = format!("{label} token, its own code re-submitted");
        let (arn, code) = contact_with_token(&em, &format!("repeat-{label}"), true, state).await;
        let attempts_before = token_attempts(&em, &arn);

        let (status, body) = activate(&em, &arn, &code).await;
        assert_eq!(
            status, 200,
            "case {case:?}: re-activating an active contact with its own code must stay \
             200, got {status} / {body:?}"
        );
        assert_eq!(
            status_of(&em, &arn).await,
            STATUS_ACTIVE,
            "case {case:?}: the contact must still read back {STATUS_ACTIVE}"
        );
        assert_eq!(
            token_attempts(&em, &arn),
            attempts_before,
            "case {case:?}: the no-op activates nothing, so it spends no attempt"
        );
    }
}

#[tokio::test]
async fn an_active_contact_whose_budget_is_spent_cannot_be_resent_and_still_answers_the_404() {
    let em = emulator();

    // The reachable, permanent state: four wrong codes and then the right one spend
    // every attempt WHILE activating the contact, and an active contact is refused a new
    // send — so from then on the contact permanently holds no outstanding token, and a
    // disagreeing code must keep answering the missing-resource 404 rather than drifting
    // to a bad-field 400.
    let arn = create_ok(&em, "spent-while-activating", "spent@example.com").await;
    assert_eq!(send_code(&em, &arn).await.0, 200, "the send must succeed");
    let code = issued_code(&em, &arn).expect("the send must persist a code");

    let budget = MAX_ACTIVATION_ATTEMPTS as usize;
    for (index, wrong) in wrong_codes(&code, budget - 1).iter().enumerate() {
        let (status, body) = activate(&em, &arn, wrong).await;
        assert_eq!(
            status, 400,
            "attempt {}: a wrong code inside the budget is the modelled 400, got \
             {status} / {body:?}",
            index + 1
        );
    }
    let (status, body) = activate(&em, &arn, &code).await;
    assert_eq!(
        status, 200,
        "the issued code's last admitted attempt must activate the contact, got \
         {status} / {body:?}"
    );
    assert_eq!(
        token_attempts(&em, &arn),
        Some(MAX_ACTIVATION_ATTEMPTS),
        "the activating call is an attempt too, so the budget is now spent"
    );

    // No new token can ever supersede the spent one.
    let (status, body) = send_code(&em, &arn).await;
    assert_eq!(
        (status, error_code(&body).as_str()),
        (409, "ConflictException"),
        "an active contact is refused a new send, got {status} / {body:?}"
    );

    // Rows differ only in which well-formed code is submitted and how often: the answer
    // is a property of the absent token, so it never drifts.
    for (round, wrong) in wrong_codes(&code, 3).iter().enumerate() {
        let case = format!("spent budget, wrong code {wrong:?} in round {}", round + 1);
        let (status, body) = activate(&em, &arn, wrong).await;
        assert_token_missing(&case, status, &body);
        assert_eq!(
            status_of(&em, &arn).await,
            STATUS_ACTIVE,
            "case {case:?}: a refusal must leave the activated contact {STATUS_ACTIVE}"
        );
    }

    // ... and the contact's own code still answers the idempotent 200 throughout.
    let (status, body) = activate(&em, &arn, &code).await;
    assert_eq!(
        status, 200,
        "the code that activated the contact must still answer 200, got {status} / {body:?}"
    );
}
