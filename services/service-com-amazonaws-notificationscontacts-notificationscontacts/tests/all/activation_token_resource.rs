//! The activation token an email contact is activated against, as a RESOURCE.
//!
//! RULE: a request whose outcome turns on a stored resource that another operation
//! mints is refused with the modelled `ResourceNotFoundException` (HTTP 404), naming
//! the ABSENT resource in `resourceId`/`resourceType`, whenever that resource does not
//! exist; the modelled `ValidationException` (HTTP 400) is only for a well-formed
//! request whose submitted value disagrees with a resource that DOES exist.
//!
//! In this service the resource is the activation token:
//! `smithy_query(query="operation",operation="ActivateEmailContact")` reports
//! `ActivateEmailContactRequest$code` as "generated by the SendActivationCode API
//! action" and declares BOTH `ResourceNotFoundException` (404) and
//! `ValidationException` (400) for the operation, so until a send has issued one there
//! is no token resource for a code to be compared against.
//!
//! The suite drives the harness `email_contacts.rs` builds (the production
//! `MultiServiceRouter`, restJson1 serialization and the modelled-constraint walk)
//! rather than growing a second copy of it.

use serde_json::Value;
use service_com_amazonaws_notificationscontacts_notificationscontacts::state::{
    ACTIVATION_CODE_LEN, CONTACT_RESOURCE_TYPE, STATUS_ACTIVE, STATUS_INACTIVE,
};

use crate::email_contacts::{
    activate, as_millis, create_ok, emulator, error_code, get_ok, issued_code, send_code,
    unknown_arn, Emulator,
};

/// Well-formed activation codes: every one satisfies the modelled `Token`
/// (`len 7..7`, `^[a-z0-9]{7}$`, from
/// `smithy_query(query="operation",operation="ActivateEmailContact")`), so the
/// constraint walk admits all of them and only stored state can tell them apart.
/// Rows span the alphabet's ends and both of its classes, including values the issue
/// did not cite.
const WELL_FORMED_CODES: [&str; 5] = ["0000000", "zzzzzzz", "abc1234", "a1b2c3d", "9z8y7x6"];

/// The `resourceId`/`resourceType` pair a 404 body reported, with the assertion that
/// both `@required` members are present.
fn not_found_resource(case: &str, body: &Value) -> (String, String) {
    let resource_id = body
        .get("resourceId")
        .and_then(Value::as_str)
        .unwrap_or_else(|| {
            panic!("case {case:?}: ResourceNotFoundException$resourceId is @required, got {body:?}")
        })
        .to_string();
    let resource_type = body
        .get("resourceType")
        .and_then(Value::as_str)
        .unwrap_or_else(|| {
            panic!(
                "case {case:?}: ResourceNotFoundException$resourceType is @required, got {body:?}"
            )
        })
        .to_string();
    (resource_id, resource_type)
}

/// Status, `updateTime` of the contact `arn` names, so a refusal can be shown to have
/// changed nothing.
async fn snapshot(em: &Emulator, arn: &str) -> (String, i64) {
    let contact = get_ok(em, arn).await;
    let status = contact
        .get("status")
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("EmailContact$status is @required, got {contact:?}"))
        .to_string();
    (status, as_millis(&contact, "updateTime"))
}

#[tokio::test]
async fn activating_a_contact_that_holds_no_token_is_the_modelled_404() {
    let em = emulator();

    // Rows differ along the two things the rule generalises over: WHICH contact (so
    // the answer is not a property of one record) and WHICH well-formed code was
    // submitted (so it is not a property of one value).
    for (index, code) in WELL_FORMED_CODES.iter().enumerate() {
        let name = format!("fresh-{index}");
        let arn = create_ok(&em, &name, &format!("{name}@example.com")).await;
        let case = format!("{name} activated with {code:?} before any send");
        assert!(
            issued_code(&em, &arn).is_none(),
            "case {case:?}: a contact that was never sent a code must hold none"
        );
        let before = snapshot(&em, &arn).await;

        let (status, body) = activate(&em, &arn, code).await;
        assert_eq!(
            status, 404,
            "case {case:?}: no activation token exists, so the refusal must be the \
             modelled 404, got {status} / {body:?}"
        );
        assert_eq!(
            error_code(&body),
            "ResourceNotFoundException",
            "case {case:?}: expected ResourceNotFoundException, got {body:?}"
        );
        let (resource_id, resource_type) = not_found_resource(&case, &body);
        assert_eq!(
            resource_id, arn,
            "case {case:?}: resourceId must name the resource the request referenced, got {body:?}"
        );
        assert!(
            !resource_type.is_empty() && resource_type != CONTACT_RESOURCE_TYPE,
            "case {case:?}: the missing resource is the activation token, not the \
             contact (which exists), so resourceType must name the token and not \
             {CONTACT_RESOURCE_TYPE:?}, got {resource_type:?}"
        );
        // The 404 shape carries resourceId/resourceType, never the ValidationException
        // members.
        assert!(
            body.get("fieldList").is_none() && body.get("reason").is_none(),
            "case {case:?}: a ResourceNotFoundException carries no fieldList/reason, got {body:?}"
        );

        // A refusal is not a mutation: nothing about the contact moved, and no token
        // was minted by the attempt.
        assert_eq!(
            snapshot(&em, &arn).await,
            before,
            "case {case:?}: a refused activation must leave the contact exactly as it was"
        );
        assert!(
            issued_code(&em, &arn).is_none(),
            "case {case:?}: a refused activation must not mint an activation token"
        );
    }
}

#[tokio::test]
async fn the_refusal_turns_on_whether_the_token_resource_exists() {
    let em = emulator();

    // Rows: the three states one contact can be in when a code arrives — no token at
    // all, a token that disagrees with the submitted code, and a token that agrees —
    // plus the control row where the CONTACT itself is what is missing.
    let arn = create_ok(&em, "token-states", "token-states@example.com").await;

    let (status, body) = activate(&em, &arn, WELL_FORMED_CODES[0]).await;
    assert_eq!(
        (status, error_code(&body).as_str()),
        (404, "ResourceNotFoundException"),
        "case \"no token issued\": got {status} / {body:?}"
    );
    let token_404_type = not_found_resource("no token issued", &body).1;

    // The control row: the same operation, same well-formed code, but an ARN the store
    // does not hold. Also a 404 — and the two are told apart by resourceType, which is
    // what says WHICH resource was not found.
    let missing = unknown_arn('q');
    let (status, body) = activate(&em, &missing, WELL_FORMED_CODES[0]).await;
    assert_eq!(
        (status, error_code(&body).as_str()),
        (404, "ResourceNotFoundException"),
        "case \"unknown contact arn\": got {status} / {body:?}"
    );
    let (resource_id, contact_404_type) = not_found_resource("unknown contact arn", &body);
    assert_eq!(
        resource_id, missing,
        "case \"unknown contact arn\": resourceId must name the arn the request carried, got {body:?}"
    );
    assert_eq!(
        contact_404_type, CONTACT_RESOURCE_TYPE,
        "case \"unknown contact arn\": the missing resource is the contact, got {contact_404_type:?}"
    );
    assert_ne!(
        token_404_type, contact_404_type,
        "the two 404s name different missing resources, so resourceType must differ: \
         token {token_404_type:?} vs contact {contact_404_type:?}"
    );

    // Once a send has issued a token, a code that disagrees with it is a bad FIELD:
    // the modelled 400, carrying reason/fieldList and naming `code`.
    assert_eq!(
        send_code(&em, &arn).await.0,
        200,
        "SendActivationCode must mint the activation token"
    );
    let issued = issued_code(&em, &arn).expect("the send must persist a token");
    assert_eq!(
        issued.len(),
        ACTIVATION_CODE_LEN,
        "the issued token must be {ACTIVATION_CODE_LEN} characters, got {issued:?}"
    );
    for wrong in WELL_FORMED_CODES.iter().filter(|c| **c != issued) {
        let case = format!("token outstanding, {wrong:?} submitted");
        let (status, body) = activate(&em, &arn, wrong).await;
        assert_eq!(
            status, 400,
            "case {case:?}: a token exists and the code disagrees with it, so the \
             refusal must be the modelled 400, got {status} / {body:?}"
        );
        assert_eq!(
            error_code(&body),
            "ValidationException",
            "case {case:?}: expected ValidationException, got {body:?}"
        );
        let blamed: Vec<&str> = body
            .get("fieldList")
            .and_then(Value::as_array)
            .map(|fields| {
                fields
                    .iter()
                    .filter_map(|f| f.get("name").and_then(Value::as_str))
                    .collect()
            })
            .unwrap_or_default();
        assert_eq!(
            blamed,
            vec!["code"],
            "case {case:?}: the 400 must blame the submitted field, got {body:?}"
        );
        assert!(
            body.get("resourceId").is_none() && body.get("resourceType").is_none(),
            "case {case:?}: a ValidationException carries no resourceId/resourceType, got {body:?}"
        );
        assert_eq!(
            snapshot(&em, &arn).await.0,
            STATUS_INACTIVE,
            "case {case:?}: a refused activation must leave the contact {STATUS_INACTIVE}"
        );
    }

    // And the token that does exist activates the contact: the 404 above was about the
    // missing token, not about this contact being unactivatable.
    let (status, body) = activate(&em, &arn, &issued).await;
    assert_eq!(
        status, 200,
        "case \"token outstanding, the issued code submitted\": got {status} / {body:?}"
    );
    assert_eq!(
        snapshot(&em, &arn).await.0,
        STATUS_ACTIVE,
        "the activated contact must read back {STATUS_ACTIVE}"
    );
}

#[tokio::test]
async fn a_missing_token_stays_missing_until_a_send_mints_one() {
    let em = emulator();
    let arn = create_ok(&em, "late-sender", "late-sender@example.com").await;

    // Repeating the refused call changes nothing: rows differ only in the attempt
    // count, which is what an idempotent refusal must not be sensitive to.
    for attempt in 1..=WELL_FORMED_CODES.len() {
        let code = WELL_FORMED_CODES[attempt - 1];
        let (status, body) = activate(&em, &arn, code).await;
        assert_eq!(
            (status, error_code(&body).as_str()),
            (404, "ResourceNotFoundException"),
            "case \"attempt {attempt} with {code:?}\": every attempt before a send must \
             answer the same 404, got {status} / {body:?}"
        );
    }

    // The send is what creates the token resource, and from then on the same operation
    // answers from it.
    assert_eq!(send_code(&em, &arn).await.0, 200, "the send must succeed");
    let issued = issued_code(&em, &arn).expect("the send must persist a token");
    assert_eq!(
        activate(&em, &arn, &issued).await.0,
        200,
        "the refused attempts must not have consumed anything: the issued token still \
         activates the contact"
    );
    assert_eq!(
        snapshot(&em, &arn).await.0,
        STATUS_ACTIVE,
        "the contact must read back {STATUS_ACTIVE}"
    );
}
