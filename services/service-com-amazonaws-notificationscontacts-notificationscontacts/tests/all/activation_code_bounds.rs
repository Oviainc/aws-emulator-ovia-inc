//! The two bounds an activation code carries, end to end over the wire.
//!
//! RULE: a submitted activation code is honoured only while the token it belongs to is
//! still outstanding — inside both of the bounds its own documentation states, the
//! lifetime from the instant the send minted it and the attempt budget every call
//! against it spends one of — and once either bound is past, the contact holds no
//! activation token at all, so the attempt is refused as a missing activation-token
//! resource, changes nothing, and the contact stays inactive until a new send mints a
//! fresh code.
//!
//! The bounds come from the model:
//! `smithy_query(query="doc",shape="ActivateEmailContactRequest",member="code")` reads
//! "An email contact has a maximum of five activation attempts. Activation codes expire
//! after 12 hours and are generated by the SendActivationCode API action."
//!
//! Every case drives the harness `email_contacts.rs` builds (the production
//! `MultiServiceRouter`, restJson1 serialization and the modelled-constraint walk)
//! rather than growing a second copy of it. The clock is never slept on: the test ages
//! a token by moving the issue instant the store holds for it backwards, which is the
//! same state the service would be in after that much real time.

use serde_json::Value;
use service_com_amazonaws_notificationscontacts_notificationscontacts::state::{
    self, ACTIVATION_CODE_LIFETIME_MILLIS, ACTIVATION_TOKEN_RESOURCE_TYPE, CONTACT_RESOURCE_TYPE,
    MAX_ACTIVATION_ATTEMPTS, STATUS_ACTIVE, STATUS_INACTIVE,
};

use crate::email_contacts::{
    activate, create_ok, emulator, error_code, get_ok, issued_code, send_code, Emulator,
};

/// One hour in milliseconds — only a row size for the lifetime table below.
const HOUR_MILLIS: i64 = 60 * 60 * 1_000;

/// The slack a row that must stay INSIDE the lifetime leaves itself.
///
/// A row ages the token by `ACTIVATION_CODE_LIFETIME_MILLIS - SLACK_MILLIS`, so the
/// code is still live as long as the rest of the case takes less than this; the bound
/// itself is pinned exactly from the other side, by the row aged by exactly the
/// lifetime.
const SLACK_MILLIS: i64 = 5_000;

/// The status the contact `arn` names currently reports.
async fn status_of(em: &Emulator, arn: &str) -> String {
    let contact = get_ok(em, arn).await;
    contact
        .get("status")
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("EmailContact$status is @required, got {contact:?}"))
        .to_string()
}

/// Move the issue instant of the token `arn` holds `by_millis` into the past, so the
/// code reads as that much older without the test waiting for it.
fn age_token(em: &Emulator, arn: &str, by_millis: i64) {
    let store = state::service_state(&*em.engine)
        .expect("the emulator's own engine must expose this service's store");
    let mut store = store.lock();
    let token = store
        .contact_mut(arn)
        .and_then(|contact| contact.activation_token.as_mut())
        .unwrap_or_else(|| panic!("{arn} must hold an activation token to age"));
    token.issued_at_millis -= by_millis;
}

/// How many attempts the token `arn` holds has already taken, or `None` when it holds
/// no token.
fn token_attempts(em: &Emulator, arn: &str) -> Option<u32> {
    state::service_state(&*em.engine)
        .expect("the emulator's own engine must expose this service's store")
        .lock()
        .contact(arn)
        .and_then(|contact| contact.activation_token.as_ref())
        .map(|token| token.attempts)
}

/// `count` well-formed codes none of which is `issued`.
///
/// Every one is seven ASCII digits, so each satisfies the modelled `Token`
/// (`len 7..7`, `^[a-z0-9]{7}$`) and only stored state can tell it from the real one.
fn wrong_codes(issued: &str, count: usize) -> Vec<String> {
    let codes: Vec<String> = (0..=count)
        .map(|n| format!("{n:07}"))
        .filter(|code| code != issued)
        .take(count)
        .collect();
    assert_eq!(
        codes.len(),
        count,
        "the wrong-code table must carry {count} rows that differ from the issued code, got {codes:?}"
    );
    codes
}

/// Assert that `body` is the modelled 404 naming the ABSENT activation token rather
/// than the contact, which exists throughout.
fn assert_token_missing(case: &str, status: u16, body: &Value) {
    assert_eq!(
        status, 404,
        "case {case:?}: the contact holds no outstanding activation token, so the \
         refusal must be the modelled 404, got {status} / {body:?}"
    );
    assert_eq!(
        error_code(body),
        "ResourceNotFoundException",
        "case {case:?}: expected ResourceNotFoundException, got {body:?}"
    );
    let resource_type = body
        .get("resourceType")
        .and_then(Value::as_str)
        .unwrap_or_else(|| {
            panic!("case {case:?}: ResourceNotFoundException$resourceType is @required, got {body:?}")
        });
    assert_eq!(
        resource_type, ACTIVATION_TOKEN_RESOURCE_TYPE,
        "case {case:?}: the missing resource is the activation token, not {CONTACT_RESOURCE_TYPE:?} \
         (the contact exists), got {resource_type:?}"
    );
}

/// The two bounds this suite is about are the ones the model documents, each pinned at
/// its published value: five attempts, and a 12-hour lifetime.
#[test]
fn the_bounds_are_the_documented_ones() {
    assert_eq!(
        MAX_ACTIVATION_ATTEMPTS, 5,
        "the documented budget is five activation attempts, got {MAX_ACTIVATION_ATTEMPTS}"
    );
    assert_eq!(
        ACTIVATION_CODE_LIFETIME_MILLIS,
        12 * HOUR_MILLIS,
        "the documented lifetime is 12 hours, got {ACTIVATION_CODE_LIFETIME_MILLIS} ms"
    );
}

#[tokio::test]
async fn a_code_is_honoured_only_inside_its_documented_lifetime() {
    let em = emulator();

    // Rows differ along the one thing the lifetime generalises over: how old the code
    // is when it is submitted. They span both sides of the published bound — including
    // the bound itself, one millisecond past it, and ages far past it — and each row
    // uses its own contact, so the answer is a property of the code's age and not of
    // one record.
    let lifetime = ACTIVATION_CODE_LIFETIME_MILLIS;
    for (label, age, usable) in [
        ("just issued", 0, true),
        ("one millisecond old", 1, true),
        ("one hour old", HOUR_MILLIS, true),
        ("half the lifetime old", lifetime / 2, true),
        ("just inside the lifetime", lifetime - SLACK_MILLIS, true),
        ("exactly the lifetime old", lifetime, false),
        ("one millisecond past the lifetime", lifetime + 1, false),
        ("twice the lifetime old", 2 * lifetime, false),
        ("thirty days old", 30 * 24 * HOUR_MILLIS, false),
    ] {
        let name = format!("aged-{}", label.replace(' ', "-"));
        let arn = create_ok(&em, &name, &format!("{name}@example.com")).await;
        assert_eq!(
            send_code(&em, &arn).await.0,
            200,
            "case {label:?}: the send must mint an activation token"
        );
        let code = issued_code(&em, &arn).expect("the send must persist a code");
        age_token(&em, &arn, age);

        let (status, body) = activate(&em, &arn, &code).await;
        if usable {
            assert_eq!(
                status, 200,
                "case {label:?}: a code inside its lifetime must still activate the \
                 contact, got {status} / {body:?}"
            );
            assert_eq!(
                status_of(&em, &arn).await,
                STATUS_ACTIVE,
                "case {label:?}: the activated contact must read back {STATUS_ACTIVE}"
            );
            continue;
        }

        assert_token_missing(label, status, &body);
        assert_eq!(
            status_of(&em, &arn).await,
            STATUS_INACTIVE,
            "case {label:?}: an expired code must leave the contact {STATUS_INACTIVE}"
        );

        // ... until a new code is sent: the send mints a token with its own lifetime,
        // and that one activates the contact.
        assert_eq!(
            send_code(&em, &arn).await.0,
            200,
            "case {label:?}: a contact whose code expired must still be sendable"
        );
        let fresh = issued_code(&em, &arn).expect("the second send must persist a code");
        let (status, body) = activate(&em, &arn, &fresh).await;
        assert_eq!(
            status, 200,
            "case {label:?}: the freshly issued code must activate the contact, got \
             {status} / {body:?}"
        );
        assert_eq!(
            status_of(&em, &arn).await,
            STATUS_ACTIVE,
            "case {label:?}: the contact must read back {STATUS_ACTIVE} after the new code"
        );
    }
}

#[tokio::test]
async fn a_code_is_honoured_only_inside_its_documented_attempt_budget() {
    let em = emulator();

    // Rows differ along the one thing the budget generalises over: how many attempts
    // the code has already taken when the real one is submitted. They span both sides
    // of the published bound — every count up to it, the bound itself, and counts past
    // it.
    let budget = MAX_ACTIVATION_ATTEMPTS as usize;
    for spent in [0usize, 1, 2, 3, budget - 1, budget, budget + 1, 2 * budget] {
        let name = format!("budget-{spent}");
        let arn = create_ok(&em, &name, &format!("{name}@example.com")).await;
        assert_eq!(
            send_code(&em, &arn).await.0,
            200,
            "case {spent}: the send must mint an activation token"
        );
        let code = issued_code(&em, &arn).expect("the send must persist a code");
        assert_eq!(
            token_attempts(&em, &arn),
            Some(0),
            "case {spent}: a freshly issued code must have taken no attempt yet"
        );

        for (index, wrong) in wrong_codes(&code, spent).iter().enumerate() {
            let case = format!("{spent} spent: wrong code {wrong:?} as attempt {}", index + 1);
            let (status, body) = activate(&em, &arn, wrong).await;
            if index < budget {
                // The token is still outstanding, so a code that disagrees with it is
                // a bad field: the modelled 400.
                assert_eq!(
                    status, 400,
                    "case {case:?}: a wrong code inside the budget must be the modelled \
                     400, got {status} / {body:?}"
                );
                assert_eq!(
                    error_code(&body),
                    "ValidationException",
                    "case {case:?}: expected ValidationException, got {body:?}"
                );
            } else {
                assert_token_missing(&case, status, &body);
            }
            assert_eq!(
                status_of(&em, &arn).await,
                STATUS_INACTIVE,
                "case {case:?}: a refused activation must leave the contact {STATUS_INACTIVE}"
            );
        }

        // Every attempt against an outstanding token spends one of its budget, and a
        // token whose budget is spent takes no more.
        assert_eq!(
            token_attempts(&em, &arn),
            Some(spent.min(budget) as u32),
            "case {spent}: the token must have taken {} of its {budget} attempts",
            spent.min(budget)
        );

        let (status, body) = activate(&em, &arn, &code).await;
        if spent < budget {
            assert_eq!(
                status, 200,
                "case {spent}: the issued code must still activate the contact on \
                 attempt {}, got {status} / {body:?}",
                spent + 1
            );
            assert_eq!(
                status_of(&em, &arn).await,
                STATUS_ACTIVE,
                "case {spent}: the activated contact must read back {STATUS_ACTIVE}"
            );
            assert_eq!(
                token_attempts(&em, &arn),
                Some(spent as u32 + 1),
                "case {spent}: the activating call is an attempt too"
            );
            continue;
        }

        assert_token_missing(&format!("{spent} spent, issued code"), status, &body);
        assert_eq!(
            status_of(&em, &arn).await,
            STATUS_INACTIVE,
            "case {spent}: a code whose budget is spent must leave the contact \
             {STATUS_INACTIVE}"
        );

        // ... until a new code is sent: the send hands out a fresh budget with the new
        // code, and the superseded one stays unusable.
        assert_eq!(
            send_code(&em, &arn).await.0,
            200,
            "case {spent}: a contact whose budget is spent must still be sendable"
        );
        let fresh = issued_code(&em, &arn).expect("the second send must persist a code");
        assert_eq!(
            token_attempts(&em, &arn),
            Some(0),
            "case {spent}: the new code must carry a full budget"
        );
        if fresh != code {
            let (status, body) = activate(&em, &arn, &code).await;
            assert_eq!(
                status, 400,
                "case {spent}: the superseded code must be refused as a bad field, got \
                 {status} / {body:?}"
            );
        }
        let (status, body) = activate(&em, &arn, &fresh).await;
        assert_eq!(
            status, 200,
            "case {spent}: the freshly issued code must activate the contact, got \
             {status} / {body:?}"
        );
        assert_eq!(
            status_of(&em, &arn).await,
            STATUS_ACTIVE,
            "case {spent}: the contact must read back {STATUS_ACTIVE} after the new code"
        );
    }
}

#[tokio::test]
async fn the_bounds_belong_to_the_code_and_a_send_restarts_both() {
    let em = emulator();

    // Rows: the two ways a code stops being outstanding, each followed by a send. What
    // is asserted is that the send restarts the bound the row exhausted — the lifetime
    // runs from the new code's own issue instant, and the attempt budget from zero.
    for (case, spend) in [("expired", false), ("budget spent", true)] {
        let name = format!("restart-{}", case.replace(' ', "-"));
        let arn = create_ok(&em, &name, &format!("{name}@example.com")).await;
        assert_eq!(send_code(&em, &arn).await.0, 200, "case {case:?}: the send must succeed");
        let code = issued_code(&em, &arn).expect("the send must persist a code");

        if spend {
            for wrong in wrong_codes(&code, MAX_ACTIVATION_ATTEMPTS as usize) {
                assert_eq!(
                    activate(&em, &arn, &wrong).await.0,
                    400,
                    "case {case:?}: a wrong code inside the budget is the modelled 400"
                );
            }
        } else {
            age_token(&em, &arn, ACTIVATION_CODE_LIFETIME_MILLIS);
        }

        let (status, body) = activate(&em, &arn, &code).await;
        assert_token_missing(case, status, &body);

        // The send restarts the bounds: the new code is live, with a full budget, and
        // it still has to survive a wrong attempt before it is used.
        assert_eq!(
            send_code(&em, &arn).await.0,
            200,
            "case {case:?}: the second send must succeed"
        );
        let fresh = issued_code(&em, &arn).expect("the second send must persist a code");
        let wrong = wrong_codes(&fresh, 1).remove(0);
        assert_eq!(
            activate(&em, &arn, &wrong).await.0,
            400,
            "case {case:?}: the new code is outstanding, so a disagreeing code is the \
             modelled 400"
        );
        assert_eq!(
            token_attempts(&em, &arn),
            Some(1),
            "case {case:?}: the new code must have taken exactly the one attempt made \
             against it"
        );
        let (status, body) = activate(&em, &arn, &fresh).await;
        assert_eq!(
            status, 200,
            "case {case:?}: the new code must activate the contact, got {status} / {body:?}"
        );
        assert_eq!(
            status_of(&em, &arn).await,
            STATUS_ACTIVE,
            "case {case:?}: the contact must read back {STATUS_ACTIVE}"
        );

        // Idempotent: repeating the call that activated the contact still answers 200,
        // and that is so however old the code has become, because an active contact has
        // nothing left to activate.
        age_token(&em, &arn, 2 * ACTIVATION_CODE_LIFETIME_MILLIS);
        let (status, body) = activate(&em, &arn, &fresh).await;
        assert_eq!(
            status, 200,
            "case {case:?}: re-activating an active contact with its own code must stay \
             200, got {status} / {body:?}"
        );
        assert_eq!(
            status_of(&em, &arn).await,
            STATUS_ACTIVE,
            "case {case:?}: the contact must still read back {STATUS_ACTIVE}"
        );
    }
}
