    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // The store is unreachable only when this service was mounted on a foreign
        // engine — a fault on this service's side, not a property of the request — so it
        // is reported through the server-side shape this service models, built in the one
        // place every handler builds it.
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(TagResourceErrorModeled::InternalServerException(
                crate::state::store_unreachable(Self::NAME),
            )
            .into());
        };
        // This service's endpoint is regional: the ARN has to name a resource of the
        // Region the request was signed for.
        let region = crate::state::region_of(ctx);
        let now = ::std::time::SystemTime::now();

        // The model bounds a tag key at 1..128 characters and a value at 0..256
        // (`smithy_query(query="shape",shape="TagMap")`) and the service reserves a key
        // namespace of its own; checked here as well because a constraint on a MAP's key
        // or value is not one the boundary walk can refuse through the member it was bound
        // to, and a rule the model does not state is not one it knows at all. The SAME
        // check `CreateDomain` applies to the tags a create carries, in the same place:
        // it is decided from the request alone, so it is decided before any state is read
        // — before the ARN below is resolved and before the merge is bounded — which is
        // where the boundary would have decided it. So neither operation enforces half
        // the rule, and neither answers a different refusal for one map. Nothing is
        // written: the store has not even been looked at yet.
        let requested_tags = crate::service::tag_bounds::accepted_entries(input.tags).map_err(
            |detail| {
                TagResourceErrorModeled::ValidationException(crate::state::invalid_request(detail))
            },
        )?;

        let mut store = state.lock();
        // The preamble every handler shares materialises what the CLOCK already made due
        // first, so the ARN of a resource whose deletion has fallen due no longer
        // resolves here.
        store.materialise_due(now);

        // The ARN has to name a resource this service HOLDS, in THIS REGION: tags live
        // beside the resource, so there is nothing to attach them to otherwise, and a
        // resource of another Region is not this endpoint's to tag. The same resolution
        // `ListTagsForResource` reads through, so the write and the read never disagree
        // about whether the ARN names a resource.
        if !store.holds_resource_arn(&region, &input.resource_arn) {
            return Err(TagResourceErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(crate::service::error_detail::resource_not_found_message(
                        &input.resource_arn,
                    )),
                },
            )
            .into());
        }

        // The limit is on the resource's tag SET, so it is the merged set that is
        // bounded: re-tagging keys the resource already carries is always accepted,
        // while new keys that would carry it past the cap are refused. The merge and the
        // bound are the ONE shared path `CreateDomain` bounds its create's set through,
        // so the two cannot drift apart in what they count; a refusal writes nothing,
        // because the set is only computed here.
        let merged = crate::service::tag_bounds::merged_within_cap(
            store.tags_for(&input.resource_arn),
            requested_tags,
        )
        .map_err(|count| {
            TagResourceErrorModeled::ServiceQuotaExceededException(
                ServiceQuotaExceededException {
                    message: Some(format!(
                        "resource {} would carry {count} tags, more than the maximum of {}",
                        input.resource_arn,
                        crate::state::MAX_TAGS_PER_RESOURCE
                    )),
                },
            )
        })?;

        // `@idempotent`: the merged set is what is stored, so repeating the call writes
        // the same set again and changes nothing.
        store.set_tags(&input.resource_arn, merged);
        Ok(TagResourceOutput)
    }
