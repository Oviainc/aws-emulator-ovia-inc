/// one `ReceiveRequestAttemptId` already served — project the wire message from the
/// stored one here, so the two cannot drift on what a receive reports.
fn wire_message(
    message: &sqs::StoredMessage,
    receipt_handle: String,
    system_requested: &[String],
    attribute_requested: &[String],
) -> Message {
    let attributes = system_attributes(message, system_requested);
    // The digest covers the attributes this answer RETURNS, which is what an SDK
    // verifies it against; a request that selects a subset therefore gets the digest of
    // that subset, not of the stored set.
    let message_attributes: BTreeMap<String, MessageAttributeValue> = message
        .message_attributes
        .iter()
        .filter(|(name, _)| selects(attribute_requested, name))
        .map(|(name, value)| (name.clone(), value.clone()))
        .collect();
    Message {
        message_id: Some(message.message_id.clone()),
        receipt_handle: Some(receipt_handle),
        md5_of_body: Some(message.md5_of_body.clone()),
        body: Some(message.body.clone()),
        attributes: (!attributes.is_empty()).then(|| attributes.into_iter().collect()),
        md5_of_message_attributes: sqs::md5_of_message_attributes(&message_attributes),
        message_attributes: (!message_attributes.is_empty())
            .then(|| message_attributes.into_iter().collect()),
    }
}

/// The message system attributes this emulator holds, filtered to the ones `requested`
/// selects.
///
/// Only the attributes the emulator genuinely records are reported: `SentTimestamp`,
/// `ApproximateReceiveCount`, `ApproximateFirstReceiveTimestamp`, the `AWSTraceHeader` a
/// send carried in `MessageSystemAttributes` and, for a message that carries them,
/// `MessageGroupId`, `MessageDeduplicationId` and `SequenceNumber`. The rest of the
/// `MessageSystemAttributeName` set belongs to behaviour that is not implemented
/// (dead-letter redrive, caller principals), so it is omitted rather than invented.
fn system_attributes(
    message: &sqs::StoredMessage,
    requested: &[String],
) -> BTreeMap<String, String> {
    let mut attributes = BTreeMap::new();
    let mut offer = |name: &str, value: String| {
        if selects(requested, name) {
            attributes.insert(name.to_string(), value);
        }
    };
    offer("SentTimestamp", sqs::epoch_millis(message.sent_at));
    offer(
        "ApproximateReceiveCount",
        message.receive_count.to_string(),
    );
    if let Some(first) = message.first_received_at {
        offer("ApproximateFirstReceiveTimestamp", sqs::epoch_millis(first));
    }
    // What the send stored in `MessageSystemAttributes`: "AWSTraceHeader - Returns the
    // X-Ray trace header string", reported under the name it was sent under and only
    // for a message whose send carried it.
    for (name, value) in &message.message_system_attributes {
        if let Some(string_value) = &value.string_value {
            offer(name, string_value.clone());
        }
    }
    // The three a FIFO send records. "The MessageDeduplicationId is available to the
    // consumer of the message", and a consumer of several interleaved streams needs the
    // group each message belongs to.
    if let Some(group_id) = &message.message_group_id {
        offer("MessageGroupId", group_id.clone());
    }
    if let Some(deduplication_id) = &message.message_deduplication_id {
        offer("MessageDeduplicationId", deduplication_id.clone());
    }
    if let Some(sequence_number) = &message.sequence_number {
        offer("SequenceNumber", sequence_number.clone());
    }
    attributes
}
