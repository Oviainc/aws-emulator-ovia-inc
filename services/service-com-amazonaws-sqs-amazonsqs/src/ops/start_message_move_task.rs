        // left blank, the messages will be redriven back to their respective original
        // source queues."
        let named_destination = match input
            .destination_arn
            .as_deref()
            .map(str::trim)
            .filter(|arn| !arn.is_empty())
            .map(|arn| sqs::parse_queue_arn(arn, &region))
        {
            Some(sqs::QueueArn::OfThisRegion(name)) => Some(name.to_string()),
            Some(sqs::QueueArn::OfAnotherRegion { .. }) | Some(sqs::QueueArn::Elsewhere) => {
                return Err(StartMessageMoveTaskErrorModeled::ResourceNotFoundException(
                    sqs::resource_not_found("DestinationArn"),
                )
                .into())
            }
            Some(sqs::QueueArn::Malformed) => {
                return Err(StartMessageMoveTaskErrorModeled::InvalidAddress(
                    sqs::invalid_address("DestinationArn"),
                )
                .into())
            }
            None => None,
        };

        // "Source queue arn and destination queue arn cannot be the same": a task whose
        // destination IS its source would move a queue's messages onto itself, so the pair
        // is refused before any task state is allocated. The two are compared as the queues
        // they RESOLVE to, so a second spelling of the one queue is the same queue here.
        if named_destination
            .as_deref()
            .is_some_and(|name| name == source_name)
        {
            return Err(Scaffolded::invalid_parameter_value(
                sqs::SAME_SOURCE_AND_DESTINATION,
            ));
        }

        let store = sqs::service_state(&*self.engine).ok_or_else(|| {
            StartMessageMoveTaskErrorModeled::UnsupportedOperation(sqs::store_unavailable())
        })?;
        let mut state = store.lock();

        let now = SystemTime::now();
        // Retention lapses and visibility timeouts are owed by the clock, not by this
        // call: what the task may take is what the source queue can hand out once
        // everything already due has been applied.
        state.materialise_due(now);

        if !state.holds_queue(&region, &source_name) {
            return Err(StartMessageMoveTaskErrorModeled::ResourceNotFoundException(
                sqs::resource_not_found("SourceArn"),
            )
            .into());
        }

