                return Err(SendMessageBatchErrorModeled::InvalidBatchEntryId(
                    InvalidBatchEntryId {
                        message: Some(format!(
                            "A batch entry id can only contain alphanumeric characters, hyphens \
                             and underscores. It can be at most {} letters long.",
                            sqs::MAX_BATCH_ENTRY_ID_LEN
                        )),
                    },
                )
                .into());
