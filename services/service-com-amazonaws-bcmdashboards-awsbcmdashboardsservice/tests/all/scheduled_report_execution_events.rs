//! The notification an execution of a scheduled report delivers, end to end over the
//! wire.
//!
//! The RULE under test: an execution of a scheduled report IS a delivery of one
//! notification to the account's default Amazon EventBridge event bus, and the health the
//! execution establishes reports whether that delivery succeeded. Source:
//! `smithy_query(query="shape",shape="HealthStatus")`, whose `statusCode` documents
//! `UNHEALTHY` as "the scheduled report is unable to deliver the notification to the
//! default Amazon EventBridge EventBus in your account", so a healthy execution does
//! deliver it; `smithy_query(query="doc",shape="ExecuteScheduledReport")` — "Triggers an
//! immediate execution of a scheduled report, outside of its regular schedule".
//!
//! So three things are asserted, each over a set of inputs rather than one request:
//!
//! * a triggered execution puts exactly one event on the `default` bus, naming the report
//!   and the dashboard it renders, over a table of reports differing in schedule state,
//!   widget-id count and client token;
//! * a call that triggers NO execution delivers nothing — the dry run, the refused
//!   `DISABLED` report, the report whose dashboard is gone, the ARN that resolves to
//!   nothing, and the idempotent retry that replays an earlier execution;
//! * a client that wires an EventBridge rule to the notification sees it routed, and a
//!   rule on another source does not;
//! * an execution whose notification nothing accepted answers `UNHEALTHY` with the reason
//!   the model has for a delivery failure, and both views of the record read that back.

use std::sync::Arc;
use std::time::{SystemTime, UNIX_EPOCH};

use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

use super::dashboard_lifecycle::{
    call, emulator, ok_call, router_without_event_bus, timestamp,
};
use super::scheduled_report_execution::{
    create_report, listed_summary, stored_report, HEALTHY, UNHEALTHY,
};
use super::scheduled_report_lifecycle::{error_code, source_dashboard};

/// The envelope values the notification must carry, spelled out here rather than imported
/// from the implementation, so a wrong constant in the handler cannot make a test pass.
///
/// `source`: EventBridge names the publishing service as `aws.<service>`, and this
/// service's namespace is its `aws.api#service$arnNamespace`, `bcm-dashboards`.
/// `detail-type`: the type this emulator publishes an execution's notification under.
/// `default`: "Events generated by Amazon Web Services services go to your account's
/// default event bus" (EventBridge's event-bus reference), which the model names for this
/// notification too.
pub(crate) const EVENT_SOURCE: &str = "aws.bcm-dashboards";
pub(crate) const EXECUTION_DETAIL_TYPE: &str = "BCM Dashboards Scheduled Report Execution";
pub(crate) const DEFAULT_BUS: &str = "default";

/// The `StatusReason` a delivery failure carries. Source:
/// `smithy_query(query="shape",shape="StatusReason")` — the value that names a failure of
/// neither the dashboard nor a widget.
pub(crate) const INTERNAL_FAILURE: &str = "INTERNAL_FAILURE";

/// A well-formed `ScheduledReportArn` no report in a fresh store is keyed by.
const MISSING_REPORT_ARN: &str =
    "arn:aws:bcm-dashboards::123456789012:scheduled-report/never-delivered";

/// One event EventBridge took, projected onto what this suite asserts. Shared with the
/// sibling concurrency suite, which reads the same bus.
#[derive(Debug, Clone)]
pub(crate) struct Published {
    pub(crate) bus: String,
    pub(crate) source: String,
    pub(crate) detail_type: String,
    pub(crate) resources: Vec<String>,
    pub(crate) detail: Value,
    /// The names of the rules on the bus whose `EventPattern` matched it.
    pub(crate) matched_rules: Vec<String>,
    /// The event's own time, in epoch seconds.
    pub(crate) time: f64,
}

/// `at` as epoch seconds, the unit this service's timestamp members carry on the wire.
fn epoch_seconds(at: SystemTime) -> f64 {
    at.duration_since(UNIX_EPOCH)
        .map(|since| since.as_secs_f64())
        .unwrap_or_default()
}

/// Every event the mounted EventBridge has taken, oldest first — the bus a client reads
/// the delivery on, reached through the same shared engine the handlers use.
pub(crate) fn published(engine: &Arc<engine::InMemoryEngine>) -> Vec<Published> {
    let store: engine::ServiceState<
        service_com_amazonaws_eventbridge_awsevents::state::ComAmazonawsEventbridgeAwseventsState,
    > = engine.state();
    let events: Vec<Published> = store
        .lock()
        .delivered
        .iter()
        .map(|event| Published {
            bus: event.bus.clone(),
            source: event.source.clone().unwrap_or_default(),
            detail_type: event.detail_type.clone().unwrap_or_default(),
            resources: event.resources.clone(),
            detail: event
                .detail
                .as_deref()
                .and_then(|raw| serde_json::from_str::<Value>(raw).ok())
                .unwrap_or(Value::Null),
            matched_rules: event.matched_rules.clone(),
            time: epoch_seconds(event.time),
        })
        .collect();
    events
}

/// Call one EventBridge operation the way a client does: `awsJson1_1`, `POST /` with
/// `X-Amz-Target: AWSEvents.<Operation>` and an `events`-scoped credential.
async fn events(router: &MultiServiceRouter, operation: &str, body: &Value) -> (u16, Value) {
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", "events.us-east-1.amazonaws.com")
        .header("content-type", "application/x-amz-json-1.1")
        .header("x-amz-target", format!("AWSEvents.{operation}"))
        .header(
            "authorization",
            "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20250818/us-east-1/events/aws4_request, \
             SignedHeaders=host, Signature=0000",
        )
        .body(Bytes::from(body.to_string()))
        .expect("a well-formed request");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let bytes = response.into_body();
    let parsed = if bytes.is_empty() {
        Value::Null
    } else {
        serde_json::from_slice(&bytes).unwrap_or(Value::Null)
    };
    (status, parsed)
}

/// One row of the delivery table.
struct DeliveryCase {
    label: &'static str,
    name: &'static str,
    /// `None` leaves `scheduleConfig.state` out of the create request.
    schedule_state: Option<&'static str>,
    /// `None` leaves `widgetIds` out; `Some(true)` names the dashboard's real widget.
    names_widget: Option<bool>,
    /// Whether the execution request presents a `clientToken`.
    client_token: Option<&'static str>,
}

/// A triggered execution delivers exactly ONE notification onto the account's default
/// event bus, naming the report it ran and the dashboard that report renders — over a
/// table differing in schedule state, widget-id count and client token.
#[tokio::test]
async fn a_triggered_execution_delivers_one_notification_to_the_default_bus() {
    let cases = [
        DeliveryCase {
            label: "state omitted, no widgetIds, no token",
            name: "Delivered Default",
            schedule_state: None,
            names_widget: None,
            client_token: None,
        },
        DeliveryCase {
            label: "state ENABLED explicitly, empty widgetIds, no token",
            name: "Delivered Empty Widgets",
            schedule_state: Some("ENABLED"),
            names_widget: Some(false),
            client_token: None,
        },
        DeliveryCase {
            label: "state ENABLED, one real widget id, with token",
            name: "Delivered One Widget",
            schedule_state: Some("ENABLED"),
            names_widget: Some(true),
            client_token: Some("delivery-token-0001"),
        },
    ];

    for case in cases {
        let label = case.label;
        // A fresh emulator per row, so one row's delivery cannot be read as another's.
        let (router, engine) = emulator();
        let (dashboard_arn, widget_id) = source_dashboard(&router, "DeliverySource").await;
        let widget_ids = case.names_widget.map(|names| {
            if names {
                vec![widget_id.clone()]
            } else {
                Vec::new()
            }
        });
        let arn = create_report(
            &router,
            &dashboard_arn,
            case.name,
            case.schedule_state,
            widget_ids.clone(),
        )
        .await;
        assert!(
            published(&engine).is_empty(),
            "case {label}: creating a report delivers nothing: {:?}",
            published(&engine)
        );

        let mut request = json!({"arn": arn});
        if let Some(token) = case.client_token {
            request["clientToken"] = json!(token);
        }
        let answered = ok_call(&router, "ExecuteScheduledReport", &request).await;
        assert_eq!(
            answered.get("executionTriggered").and_then(Value::as_bool),
            Some(true),
            "case {label}: the execution is triggered, got {answered}"
        );
        assert_eq!(
            answered.pointer("/healthStatus/statusCode").and_then(Value::as_str),
            Some(HEALTHY),
            "case {label}: a delivered notification leaves the report healthy, got {answered}"
        );

        let delivered = published(&engine);
        assert_eq!(
            delivered.len(),
            1,
            "case {label}: expected exactly one notification, got {delivered:?}"
        );
        let event = delivered
            .first()
            .unwrap_or_else(|| panic!("case {label}: the one notification"));
        assert_eq!(
            event.bus, DEFAULT_BUS,
            "case {label}: expected the notification on the {DEFAULT_BUS} bus, got {event:?}"
        );
        assert_eq!(
            event.source, EVENT_SOURCE,
            "case {label}: expected source {EVENT_SOURCE}, got {event:?}"
        );
        assert_eq!(
            event.detail_type, EXECUTION_DETAIL_TYPE,
            "case {label}: expected detail-type {EXECUTION_DETAIL_TYPE}, got {event:?}"
        );
        assert_eq!(
            event.resources,
            vec![arn.clone(), dashboard_arn.clone()],
            "case {label}: the notification names the report and its dashboard, got {event:?}"
        );

        // The `detail` is the STORED record, not a second copy of it: every member is
        // what `GetScheduledReport` reports for the same report.
        let stored = stored_report(&router, &arn).await;
        for member in ["arn", "name", "dashboardArn"] {
            assert_eq!(
                event.detail.get(member),
                stored.get(member),
                "case {label}: detail.{member} must be the stored record's, got {event:?}"
            );
        }
        assert_eq!(
            event.detail.get("widgetIds").cloned(),
            widget_ids.map(|ids| json!(ids)),
            "case {label}: detail.widgetIds must report exactly what the record holds, got {event:?}"
        );
        let execution_time = event
            .detail
            .get("executionTime")
            .and_then(Value::as_str)
            .unwrap_or_else(|| panic!("case {label}: no detail.executionTime in {event:?}"));
        assert!(
            execution_time.ends_with('Z') && execution_time.contains('T'),
            "case {label}: expected an RFC3339 executionTime, got {execution_time:?}"
        );

        // The event is stamped with the instant the execution ran — the same instant the
        // record reports as its last execution, not the instant anything was drained.
        let last_execution_at = timestamp(&stored, "lastExecutionAt", label);
        assert!(
            (event.time - last_execution_at).abs() < 1.0,
            "case {label}: the notification's time {} is not the execution instant {last_execution_at}",
            event.time
        );
    }
}

/// What a row of the no-delivery table does before the bus is inspected.
enum Attempt {
    /// A dry run of an enabled report whose resources resolve.
    DryRun,
    /// A real execution of a `DISABLED` report, which is refused.
    Disabled,
    /// A real execution of a report whose dashboard was deleted, which triggers nothing.
    DashboardDeleted,
    /// A real execution of an ARN no report is stored under.
    NeverCreated,
    /// A real execution, then the same request again under the same client token.
    RetryUnderTheSameToken,
}

/// Nothing is delivered without a triggered execution: a dry run, a refusal and a report
/// whose dashboard is gone each put NOTHING on the bus, and an idempotent retry — which
/// replays an earlier execution rather than running one — adds no second notification.
#[tokio::test]
async fn nothing_is_delivered_without_a_triggered_execution() {
    // (label, what the row attempts, how many notifications the bus must hold after it)
    let cases: [(&str, Attempt, usize); 5] = [
        ("a dry run", Attempt::DryRun, 0),
        ("a DISABLED report", Attempt::Disabled, 0),
        (
            "a report whose dashboard was deleted",
            Attempt::DashboardDeleted,
            0,
        ),
        ("an arn no report is stored under", Attempt::NeverCreated, 0),
        (
            "a retry under the same client token",
            Attempt::RetryUnderTheSameToken,
            1,
        ),
    ];

    for (label, attempt, expected) in cases {
        let (router, engine) = emulator();
        let (dashboard_arn, _) = source_dashboard(&router, "NoDeliverySource").await;

        match attempt {
            Attempt::DryRun => {
                let arn =
                    create_report(&router, &dashboard_arn, "Dry Run Delivery", None, None).await;
                let answered = ok_call(
                    &router,
                    "ExecuteScheduledReport",
                    &json!({"arn": arn, "dryRun": true}),
                )
                .await;
                assert_eq!(
                    answered.get("executionTriggered").and_then(Value::as_bool),
                    Some(false),
                    "case {label}: a dry run triggers nothing, got {answered}"
                );
            }
            Attempt::Disabled => {
                let arn = create_report(
                    &router,
                    &dashboard_arn,
                    "Paused Delivery",
                    Some("DISABLED"),
                    None,
                )
                .await;
                let (status, body) =
                    call(&router, "ExecuteScheduledReport", &json!({"arn": arn})).await;
                assert_eq!(
                    status, 400,
                    "case {label}: a DISABLED report is refused with 400, got {status}: {body}"
                );
                assert!(
                    error_code(&body).ends_with("ValidationException"),
                    "case {label}: expected ValidationException, got {body}"
                );
            }
            Attempt::DashboardDeleted => {
                let arn =
                    create_report(&router, &dashboard_arn, "Orphaned Delivery", None, None).await;
                ok_call(&router, "DeleteDashboard", &json!({"arn": dashboard_arn})).await;
                let answered =
                    ok_call(&router, "ExecuteScheduledReport", &json!({"arn": arn})).await;
                assert_eq!(
                    answered.get("executionTriggered").and_then(Value::as_bool),
                    Some(false),
                    "case {label}: a report with nothing to render triggers nothing, got {answered}"
                );
            }
            Attempt::NeverCreated => {
                let (status, body) = call(
                    &router,
                    "ExecuteScheduledReport",
                    &json!({"arn": MISSING_REPORT_ARN}),
                )
                .await;
                assert_eq!(
                    status, 400,
                    "case {label}: an unknown report arn answers 400, got {status}: {body}"
                );
            }
            Attempt::RetryUnderTheSameToken => {
                let arn =
                    create_report(&router, &dashboard_arn, "Retried Delivery", None, None).await;
                let request = json!({"arn": arn, "clientToken": "retried-delivery-0001"});
                let first = ok_call(&router, "ExecuteScheduledReport", &request).await;
                let retried = ok_call(&router, "ExecuteScheduledReport", &request).await;
                assert_eq!(
                    retried, first,
                    "case {label}: a retry answers the first call's outcome"
                );
            }
        }

        let delivered = published(&engine);
        assert_eq!(
            delivered.len(),
            expected,
            "case {label}: expected {expected} notification(s) on the bus, got {delivered:?}"
        );
    }
}

/// A rule on the default bus matching this service's notification receives it, and a rule
/// written for another source does not: the delivery is observable exactly where a client
/// wires itself to it.
#[tokio::test]
async fn a_rule_on_the_default_bus_matches_the_execution_notification() {
    let (router, engine) = emulator();

    // (rule name, the EventPattern it carries, whether it must match)
    let rules: [(&str, Value, bool); 3] = [
        (
            "bcm-dashboards-executions",
            json!({"source": [EVENT_SOURCE], "detail-type": [EXECUTION_DETAIL_TYPE]}),
            true,
        ),
        (
            "bcm-dashboards-any-source-event",
            json!({"source": [EVENT_SOURCE]}),
            true,
        ),
        ("another-services-events", json!({"source": ["aws.batch"]}), false),
    ];
    for (name, pattern, _) in &rules {
        let (status, body) = events(
            &router,
            "PutRule",
            &json!({"Name": name, "EventPattern": pattern.to_string()}),
        )
        .await;
        assert_eq!(
            status, 200,
            "case {name}: PutRule answered {status}: {body}"
        );
    }

    let (dashboard_arn, widget_id) = source_dashboard(&router, "RuleSource").await;
    let arn = create_report(
        &router,
        &dashboard_arn,
        "Routed Report",
        None,
        Some(vec![widget_id]),
    )
    .await;
    ok_call(&router, "ExecuteScheduledReport", &json!({"arn": arn})).await;

    let delivered = published(&engine);
    assert_eq!(
        delivered.len(),
        1,
        "expected one notification, got {delivered:?}"
    );
    let event = delivered.first().expect("the one notification");
    for (name, pattern, must_match) in rules {
        assert_eq!(
            event.matched_rules.iter().any(|matched| matched == name),
            must_match,
            "case {name} ({pattern}): expected matched={must_match}, got {:?}",
            event.matched_rules
        );
    }
}

/// One row of the undeliverable table.
struct UndeliverableCase {
    label: &'static str,
    name: &'static str,
    /// `None` leaves `widgetIds` out of the create request.
    names_widget: Option<bool>,
    client_token: Option<&'static str>,
}

/// An execution whose notification the account's default event bus did not take answers
/// UNHEALTHY with the reason the model has for a delivery failure — the state it
/// documents as the report being unable to deliver its notification — and both views of
/// the record read that health back. The execution was still triggered, so the record's
/// `lastExecutionAt` moves.
#[tokio::test]
async fn an_execution_whose_notification_is_not_delivered_reports_unhealthy() {
    let cases = [
        UndeliverableCase {
            label: "no widgetIds, no token",
            name: "Undelivered Plain",
            names_widget: None,
            client_token: None,
        },
        UndeliverableCase {
            label: "one real widget id, with token",
            name: "Undelivered One Widget",
            names_widget: Some(true),
            client_token: Some("undelivered-token-0001"),
        },
    ];

    for case in cases {
        let label = case.label;
        // No EventBridge in this emulator, so the notification an execution owes has
        // nowhere to land.
        let router = router_without_event_bus();
        let (dashboard_arn, widget_id) = source_dashboard(&router, "UndeliveredSource").await;
        let widget_ids = case
            .names_widget
            .map(|names| if names { vec![widget_id] } else { Vec::new() });
        let arn = create_report(&router, &dashboard_arn, case.name, None, widget_ids).await;

        let mut request = json!({"arn": arn});
        if let Some(token) = case.client_token {
            request["clientToken"] = json!(token);
        }
        let answered = ok_call(&router, "ExecuteScheduledReport", &request).await;
        assert_eq!(
            answered.get("executionTriggered").and_then(Value::as_bool),
            Some(true),
            "case {label}: the execution was triggered even though its delivery failed, got {answered}"
        );
        let health = answered
            .get("healthStatus")
            .unwrap_or_else(|| panic!("case {label}: no healthStatus in {answered}"));
        assert_eq!(
            health.get("statusCode").and_then(Value::as_str),
            Some(UNHEALTHY),
            "case {label}: an undelivered notification is reported as unhealthy, got {health}"
        );
        assert_eq!(
            health.get("statusReasons"),
            Some(&json!([INTERNAL_FAILURE])),
            "case {label}: expected statusReasons [{INTERNAL_FAILURE}], got {health}"
        );
        let refreshed = timestamp(health, "lastRefreshedAt", label);
        assert!(
            refreshed > 1_700_000_000.0,
            "case {label}: lastRefreshedAt {refreshed} is not a plausible epoch-seconds instant"
        );

        // Both views of the record project the health the execution established, and the
        // execution instant is on the record.
        let stored = stored_report(&router, &arn).await;
        assert_eq!(
            stored.pointer("/healthStatus/statusCode").and_then(Value::as_str),
            Some(UNHEALTHY),
            "case {label}: the record keeps the health the execution established: {stored}"
        );
        assert_eq!(
            stored.pointer("/healthStatus/statusReasons"),
            Some(&json!([INTERNAL_FAILURE])),
            "case {label}: the record keeps the reason the delivery failed: {stored}"
        );
        assert!(
            stored.get("lastExecutionAt").is_some(),
            "case {label}: a triggered execution records its instant: {stored}"
        );
        let summary = listed_summary(&router, &arn).await;
        assert_eq!(
            summary.pointer("/healthStatus/statusCode").and_then(Value::as_str),
            Some(UNHEALTHY),
            "case {label}: the listing reports the same health: {summary}"
        );

        // A retry under the same token replays that outcome rather than attempting a
        // second delivery.
        if case.client_token.is_some() {
            let retried = ok_call(&router, "ExecuteScheduledReport", &request).await;
            assert_eq!(
                retried, answered,
                "case {label}: a retry under the same token answers the first outcome"
            );
        }
    }
}
