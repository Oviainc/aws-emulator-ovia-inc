impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ListSchemas<Eng>
{
    type Input = ListSchemasInput;
    type Output = ListSchemasOutput;
    type Error = ListSchemasError;

    const NAME: &'static str = "ListSchemas";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_SCHEMAS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_SCHEMAS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // A schema a caller created reports the ARN that create stored; one in a
        // service-owned registry was created by no request, so its ARN names the
        // region THIS request is signed for.
        let region = crate::state::request_region(ctx.parts());
        // The model gives `Limit` no range: fewer than one item is not a page, and
        // more than `MAX_PAGE_SIZE` would materialise the whole selected store into
        // one response, so the handler owns both bounds.
        let page_size = crate::state::requested_page_size(input.limit).map_err(|refusal| {
            ListSchemasError::from(ListSchemasErrorModeled::BadRequestException(refusal))
        })?;

        let store = crate::state::service_state(&*self.engine).ok_or_else(|| {
            ListSchemasError::from(ListSchemasErrorModeled::InternalServerErrorException(
                crate::state::internal_error(),
            ))
        })?;
        let state = store.lock();

        let registry = state.registries.get(&input.registry_name).ok_or_else(|| {
            ListSchemasError::from(ListSchemasErrorModeled::NotFoundException(
                crate::state::registry_not_found(&input.registry_name),
            ))
        })?;

        // The members that decide WHICH schemas this listing contains. Bound into the
        // `NextToken`, so a token cannot resume a differently-selected listing.
        let selection = format!(
            "registryName={};schemaNamePrefix={}",
            input.registry_name,
            input.schema_name_prefix.as_deref().unwrap_or_default()
        );

        // Selected first (a prefix is a test on the name alone), then COLLATED: the
        // order a registry's schemas come back in is the collation
        // `crate::state::schema_name_order_key` defines, not the byte order the store
        // keys them by, and `Limit`/`NextToken` page over that order — so the page a
        // token resumes is a page of the order the caller was served.
        let matching = crate::state::in_schema_name_order(registry.schemas.iter().filter(
            |(name, _)| {
                input
                    .schema_name_prefix
                    .as_deref()
                    .is_none_or(|prefix| name.starts_with(prefix))
            },
        ));
        let page = crate::state::page_by_key(
            matching.into_iter(),
            &selection,
            input.next_token.as_deref(),
            page_size,
        )
        .map_err(|_| {
            ListSchemasError::from(ListSchemasErrorModeled::BadRequestException(
                crate::state::invalid_next_token(),
            ))
        })?;

        Ok(ListSchemasOutput {
            next_token: page.next_token,
            schemas: Some(
                page.items
                    .into_iter()
                    .map(|schema| SchemaSummary {
                        last_modified: Some(schema.last_modified.into()),
                        // A summary carries only the members the schema HAS: a schema
                        // of a service-owned registry is not a customer resource and
                        // has no ARN, so the member is left out for one.
                        schema_arn: registry.schema_arn_in(&region, schema),
                        schema_name: Some(schema.name.clone()),
                        tags: crate::state::tags_to_output(&schema.tags),
                        // "The number of versions available for the schema" —
                        // counted from the versions actually stored, not from the
                        // latest version number, which a DeleteSchemaVersion would
                        // outrun.
                        version_count: Some(
                            i64::try_from(schema.versions.len()).unwrap_or(i64::MAX),
                        ),
                    })
                    .collect(),
            ),
        })
    }
}
