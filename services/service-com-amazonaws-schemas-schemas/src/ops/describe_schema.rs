impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeSchema<Eng>
{
    type Input = DescribeSchemaInput;
    type Output = DescribeSchemaOutput;
    type Error = DescribeSchemaError;

    const NAME: &'static str = "DescribeSchema";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_SCHEMA_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_SCHEMA_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // A schema a caller created reports the ARN that create stored; one in a
        // service-owned registry was created by no request, so its ARN names the
        // region THIS request is signed for.
        let region = crate::state::request_region(ctx.parts());
        let store = crate::state::service_state(&*self.engine).ok_or_else(|| {
            DescribeSchemaError::from(DescribeSchemaErrorModeled::InternalServerErrorException(
                crate::state::internal_error(),
            ))
        })?;
        let state = store.lock();

        let registry = state.registries.get(&input.registry_name).ok_or_else(|| {
            DescribeSchemaError::from(DescribeSchemaErrorModeled::NotFoundException(
                crate::state::registry_not_found(&input.registry_name),
            ))
        })?;
        let schema = registry.schemas.get(&input.schema_name).ok_or_else(|| {
            DescribeSchemaError::from(DescribeSchemaErrorModeled::NotFoundException(
                crate::state::schema_not_found(&input.schema_name),
            ))
        })?;
        // `SchemaVersion` "limits the results to only this schema version"; absent, the
        // latest stored version answers. A version this schema does not hold is as
        // absent as a schema that was never created.
        let version = schema
            .version_for(input.schema_version.as_deref())
            .ok_or_else(|| {
                DescribeSchemaError::from(DescribeSchemaErrorModeled::NotFoundException(
                    crate::state::schema_version_not_found(
                        &input.registry_name,
                        &input.schema_name,
                        input.schema_version.as_deref(),
                    ),
                ))
            })?;

        Ok(DescribeSchemaOutput {
            // Verbatim: the bytes the create/update call stored for this version.
            content: Some(version.content.clone()),
            // `Description` is the SCHEMA's metadata, not a property of one
            // definition, so a read of ANY version reports the schema's current
            // description — the one the last `UpdateSchema` that sent one stored.
            description: schema.description.clone(),
            last_modified: Some(schema.last_modified.into()),
            schema_arn: Some(registry.schema_arn_in(&region, schema)),
            schema_name: Some(schema.name.clone()),
            schema_version: Some(version.version.to_string()),
            tags: crate::state::tags_to_output(&schema.tags),
            r#type: Some(version.r#type.clone()),
            version_created_date: Some(version.created_date.into()),
        })
    }
}
