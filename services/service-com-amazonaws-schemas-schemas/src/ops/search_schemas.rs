impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for SearchSchemas<Eng>
{
    type Input = SearchSchemasInput;
    type Output = SearchSchemasOutput;
    type Error = SearchSchemasError;

    const NAME: &'static str = "SearchSchemas";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::SEARCH_SCHEMAS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::SEARCH_SCHEMAS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // A schema a caller created reports the ARN that create stored; one in a
        // service-owned registry was created by no request, so its ARN names the
        // region THIS request is signed for.
        let region = crate::state::request_region(ctx.parts());
        // The model gives `Limit` no range: fewer than one item is not a page, and
        // more than `MAX_PAGE_SIZE` would materialise the whole selected store into
        // one response, so the handler owns both bounds — the same bounds every
        // listing in this service serves.
        let page_size = crate::state::requested_page_size(input.limit).map_err(|refusal| {
            SearchSchemasError::from(SearchSchemasErrorModeled::BadRequestException(refusal))
        })?;

        // A search costs one pass over the matched text PER KEYWORD, so the number of
        // keywords one request may name is capped and checked here — before the store
        // is touched, so an over-long request is refused rather than scanned. See
        // `crate::state::MAX_KEYWORDS_PER_SEARCH`.
        let keywords = keywords_of(&input.keywords);
        if keywords.len() > crate::state::MAX_KEYWORDS_PER_SEARCH {
            return Err(SearchSchemasErrorModeled::BadRequestException(
                crate::state::too_many_keywords(keywords.len()),
            )
            .into());
        }

        let store = crate::state::service_state(&*self.engine).ok_or_else(|| {
            SearchSchemasError::from(SearchSchemasErrorModeled::InternalServerErrorException(
                crate::state::internal_error(),
            ))
        })?;
        let state = store.lock();

        let registry = state.registries.get(&input.registry_name).ok_or_else(|| {
            SearchSchemasError::from(SearchSchemasErrorModeled::NotFoundException(
                crate::state::registry_not_found(&input.registry_name),
            ))
        })?;

        // The members that decide WHICH schemas this search contains. Bound into the
        // `NextToken`, so a token cannot resume a differently-selected search.
        let selection = format!(
            "registryName={};keywords={}",
            input.registry_name, input.keywords
        );

        // The schemas are COLLATED first — a search of a registry reports its matches
        // in the same order a listing of it does, the collation
        // `crate::state::schema_name_order_key` defines — and the keyword match runs
        // LAZILY over that order: `page_by_key` pulls from this filter only until the
        // page is full plus one, so a search that finds its page early stops there and
        // reads no further schema's documents.
        let collated = crate::state::in_schema_name_order(registry.schemas.iter());
        let matching = collated
            .into_iter()
            .filter(|(_, schema)| matches_every_keyword(schema, &keywords));
        let page = crate::state::page_by_key(
            matching,
            &selection,
            input.next_token.as_deref(),
            page_size,
        )
        .map_err(|_| {
            SearchSchemasError::from(SearchSchemasErrorModeled::BadRequestException(
                crate::state::invalid_next_token(),
            ))
        })?;

        Ok(SearchSchemasOutput {
            next_token: page.next_token,
            schemas: Some(
                page.items
                    .into_iter()
                    .map(|schema| SearchSchemaSummary {
                        registry_name: Some(input.registry_name.clone()),
                        // A summary carries only the members the schema HAS — see
                        // `Registry::schema_arn_in`.
                        schema_arn: registry.schema_arn_in(&region, schema),
                        schema_name: Some(schema.name.clone()),
                        // "An array of schema version summaries": one entry per
                        // version this service holds for the schema, in version
                        // order — the version map's keys are the numbers.
                        schema_versions: Some(
                            schema
                                .versions
                                .values()
                                .map(|version| SearchSchemaVersionSummary {
                                    created_date: Some(version.created_date.into()),
                                    schema_version: Some(version.version.to_string()),
                                    r#type: Some(version.r#type.clone()),
                                })
                                .collect(),
                        ),
                    })
                    .collect(),
            ),
        })
    }
}

/// The keywords one `Keywords` value carries, folded to lower case.
///
/// `Keywords` is a single `__string`, but the member is plural — "limits the results
/// to only schemas that include the provided keywords" — so one value carries a LIST
/// of keywords, separated by commas or whitespace; empty pieces are dropped. A value
/// that carries no keyword at all (empty, or separators only) therefore limits
/// nothing, which is all "specifying this limits the results" can mean for a value
/// that specifies none.
fn keywords_of(raw: &str) -> Vec<String> {
    raw.split(|c: char| c == ',' || c.is_whitespace())
        .filter(|keyword| !keyword.is_empty())
        .map(str::to_lowercase)
        .collect()
}

/// Whether `keywords` match a schema.
///
/// A schema is selected when EVERY requested keyword occurs in one of the event
/// keywords the schema declares ([`declared_event_keywords`]), matched
/// case-insensitively as a substring — a search is not a lookup by exact value, and
/// adding a keyword only ever narrows the result. A schema that declares no event
/// keyword at all is indexed under nothing, so a search never selects it, whatever (or
/// nothing) the request asks for.
fn matches_every_keyword(schema: &crate::state::Schema, keywords: &[String]) -> bool {
    let declared = declared_event_keywords(schema);
    if declared.is_empty() {
        return false;
    }
    keywords
        .iter()
        .all(|keyword| declared.iter().any(|value| value.contains(keyword.as_str())))
}

/// The event keywords a schema declares, folded to lower case: the event `source` and
/// `detail-type` its document records, which is what the registry indexes a schema
/// under.
///
/// EventBridge records them as the `x-amazon-events-source` and
/// `x-amazon-events-detail-type` extensions of the document's event component. They are
/// read from the stored document of EVERY version this service holds for the schema and
/// wherever in the document they sit — the extensions are a property of a component, and
/// which component is the event one differs between a discovered document and a
/// converted one — so a schema whose later version declares another source is found
/// under both. Folded ONCE per schema here rather than once per keyword at the match.
/// A document that is not JSON declares nothing: the content of a stored version is
/// whatever `CreateSchema` accepted for the type it was created as.
fn declared_event_keywords(schema: &crate::state::Schema) -> Vec<String> {
    let mut declared: Vec<String> = Vec::new();
    for version in schema.versions.values() {
        let Ok(document) = ::serde_json::from_str::<::serde_json::Value>(&version.content) else {
            continue;
        };
        collect_event_keywords(&document, &mut declared);
    }
    declared
}

/// Collect every event keyword `document` declares, at any depth, folded to lower case.
///
/// Depth is bounded by `serde_json`'s own nesting limit, which refused the document
/// before `CreateSchema` stored it, and breadth by
/// [`crate::state::MAX_STORED_CONTENT_BYTES`].
fn collect_event_keywords(document: &::serde_json::Value, declared: &mut Vec<String>) {
    match document {
        ::serde_json::Value::Object(members) => {
            for (name, value) in members {
                if EVENT_KEYWORD_EXTENSIONS.contains(&name.as_str()) {
                    if let Some(value) = value.as_str() {
                        declared.push(value.to_lowercase());
                    }
                }
                collect_event_keywords(value, declared);
            }
        }
        ::serde_json::Value::Array(items) => {
            for item in items {
                collect_event_keywords(item, declared);
            }
        }
        _ => {}
    }
}

/// The document members that carry a schema's event keywords: the EventBridge
/// extensions naming the event's source and detail type.
const EVENT_KEYWORD_EXTENSIONS: &[&str] = &[
    "x-amazon-events-source",
    "x-amazon-events-detail-type",
];

#[cfg(test)]
mod tests {
    use super::*;

    /// One `Keywords` value is a list: commas and whitespace separate its keywords,
    /// case is folded, and a value that names none limits nothing.
    #[test]
    fn a_keywords_value_is_a_case_folded_list() {
        for (raw, expected) in [
            ("order", vec!["order"]),
            ("Order", vec!["order"]),
            ("order placed", vec!["order", "placed"]),
            ("order,placed", vec!["order", "placed"]),
            ("order, placed\tv1\n", vec!["order", "placed", "v1"]),
            (",,  ,", vec![]),
            ("", vec![]),
        ] {
            let parsed = keywords_of(raw);
            assert_eq!(
                parsed, expected,
                "case {raw:?}: expected {expected:?}, got {parsed:?}"
            );
        }
    }

    /// Every schema AWS publishes declares the event it describes, so a search of the
    /// published registry has something to select on — and what it declares is the
    /// event's source and detail type, not the schema's own name.
    #[test]
    fn a_published_schema_declares_the_event_it_describes() {
        let state = crate::state::ComAmazonawsSchemasSchemasState::default();
        let registry = &state.registries[crate::state::AWS_MANAGED_REGISTRY];
        assert!(
            !registry.schemas.is_empty(),
            "the published registry must hold schemas to search over"
        );
        for (schema_name, schema) in &registry.schemas {
            // A document records the event on every component that is ABOUT the event
            // (its envelope and the component the envelope's `detail` references), and
            // the keywords are read from every version, so what a schema is indexed
            // under is the SET of values declared: the event's source and its detail
            // type, twice.
            let declared: ::std::collections::BTreeSet<String> =
                declared_event_keywords(schema).into_iter().collect();
            assert_eq!(
                declared.len(),
                2,
                "case {schema_name:?}: a published schema declares its event's source \
                 and detail type, got {declared:?}"
            );
            assert!(
                declared.iter().all(|value| value != schema_name),
                "case {schema_name:?}: the schema's name is not what it is indexed \
                 under, got {declared:?}"
            );
            // Every published source is under the `aws.` prefix, so this one keyword
            // selects each of them.
            assert!(
                matches_every_keyword(schema, &keywords_of("AWS.")),
                "case {schema_name:?}: a keyword of its source must select it, \
                 declared {declared:?}"
            );
            assert!(
                !matches_every_keyword(schema, &keywords_of("no-event-says-this")),
                "case {schema_name:?}: a keyword nothing declares must not select it"
            );
        }
    }
}
