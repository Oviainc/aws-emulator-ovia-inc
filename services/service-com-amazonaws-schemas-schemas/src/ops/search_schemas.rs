impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for SearchSchemas<Eng>
{
    type Input = SearchSchemasInput;
    type Output = SearchSchemasOutput;
    type Error = SearchSchemasError;

    const NAME: &'static str = "SearchSchemas";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::SEARCH_SCHEMAS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::SEARCH_SCHEMAS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // A schema a caller created reports the ARN that create stored; one in a
        // service-owned registry was created by no request, so its ARN names the
        // region THIS request is signed for.
        let region = crate::state::request_region(ctx.parts());
        // The model gives `Limit` no range: fewer than one item is not a page, and
        // more than `MAX_PAGE_SIZE` would materialise the whole selected store into
        // one response, so the handler owns both bounds — the same bounds every
        // listing in this service serves.
        let page_size = crate::state::requested_page_size(input.limit).map_err(|refusal| {
            SearchSchemasError::from(SearchSchemasErrorModeled::BadRequestException(refusal))
        })?;

        // A search costs one pass over the matched text PER KEYWORD, so the number of
        // keywords one request may name is capped and checked here — before the store
        // is touched, so an over-long request is refused rather than scanned. See
        // `crate::state::MAX_KEYWORDS_PER_SEARCH`.
        let keywords = keywords_of(&input.keywords);
        if keywords.len() > crate::state::MAX_KEYWORDS_PER_SEARCH {
            return Err(SearchSchemasErrorModeled::BadRequestException(
                crate::state::too_many_keywords(keywords.len()),
            )
            .into());
        }

        // The names this request supplies are checked against the service's own
        // constraints for them before the store is reached: a name outside one names no
        // resource anywhere, so the request is refused on its form rather than answered
        // as if the name merely named nothing yet. See `crate::state::validate_names`.
        crate::state::validate_names(Some(&input.registry_name), None).map_err(|refusal| {
            SearchSchemasError::from(SearchSchemasErrorModeled::BadRequestException(refusal))
        })?;

        let store = crate::state::service_state(&*self.engine).ok_or_else(|| {
            SearchSchemasError::from(SearchSchemasErrorModeled::InternalServerErrorException(
                crate::state::internal_error(),
            ))
        })?;
        let state = store.lock();

        // The registry step of the one read resolution — the whole of it for a search
        // that names no schema. See `crate::state::readable_registry`.
        let registry = state
            .readable_registry(&input.registry_name)
            .map_err(|refusal| {
                SearchSchemasError::from(SearchSchemasErrorModeled::NotFoundException(
                    refusal.not_found(),
                ))
            })?;

        // The members that decide WHICH schemas this search contains, with the search
        // itself. Bound into the `NextToken`, so a token cannot resume a
        // differently-selected search: `Keywords` is a free-form string, so the
        // fingerprint is rendered by `crate::state::selection_fingerprint`, which no
        // value a caller can send renders ambiguously.
        //
        // What is fingerprinted is the selection as THIS handler resolved it, not the
        // bytes the caller typed: `Keywords` decides nothing until `keywords_of` has
        // normalised it and `matches_every_keyword` has folded the result, so the
        // canonical form of the member is the keyword SET
        // ([`canonical_keywords`]) — every spelling of one selection therefore walks one
        // listing and shares its tokens, which is what
        // `crate::state::selection_fingerprint` requires of a value that selects the
        // same items.
        let selection = crate::state::selection_fingerprint(
            Self::NAME,
            &[
                ("registryName", input.registry_name.as_str()),
                ("keywords", canonical_keywords(&keywords).as_str()),
            ],
        );

        // ONE clock reading for the whole call: the instant this search is served, so
        // the token this page mints says when it was issued, the one this request
        // presented is aged against the same instant, and every schema's index entries
        // are decided as of one moment.
        let now = ::std::time::SystemTime::now();

        // The schemas are COLLATED first — a search of a registry reports its matches
        // in the same order a listing of it does, the codepoint order of their names
        // (`crate::state::in_schema_name_order`) — and the keyword match runs
        // LAZILY over that order: `page_by_key` pulls from this filter only until the
        // page is full plus one, so a search that finds its page early stops there and
        // reads no further schema's documents.
        let collated = crate::state::in_schema_name_order(registry.schemas.iter());
        let matching = collated
            .into_iter()
            .filter(|(_, schema)| matches_every_keyword(schema, &keywords, now));
        let page = crate::state::page_by_key(
            matching,
            &selection,
            input.next_token.as_deref(),
            page_size,
            now,
        )
        .map_err(|_| {
            SearchSchemasError::from(SearchSchemasErrorModeled::BadRequestException(
                crate::state::invalid_next_token(),
            ))
        })?;

        Ok(SearchSchemasOutput {
            next_token: page.next_token,
            schemas: Some(
                page.items
                    .into_iter()
                    .map(|schema| SearchSchemaSummary {
                        registry_name: Some(input.registry_name.clone()),
                        // A summary carries only the members the schema HAS — see
                        // `Registry::schema_arn_in`.
                        schema_arn: registry.schema_arn_in(&region, schema),
                        schema_name: Some(schema.name.clone()),
                        // "An array of schema version summaries": one entry per
                        // version this service holds for the schema, in version
                        // order — the version map's keys are the numbers.
                        schema_versions: Some(
                            schema
                                .versions
                                .values()
                                .map(|version| SearchSchemaVersionSummary {
                                    created_date: Some(version.created_date.into()),
                                    schema_version: Some(version.version.to_string()),
                                    r#type: Some(version.r#type.clone()),
                                })
                                .collect(),
                        ),
                    })
                    .collect(),
            ),
        })
    }
}

/// The keywords one `Keywords` value carries, folded to lower case.
///
/// `Keywords` is a single `__string`, but the member is plural — "limits the results
/// to only schemas that include the provided keywords" — so one value carries a LIST
/// of keywords, separated by commas or whitespace; empty pieces are dropped. A value
/// that carries no keyword at all (empty, or separators only) therefore limits
/// nothing, which is all "specifying this limits the results" can mean for a value
/// that specifies none.
fn keywords_of(raw: &str) -> Vec<String> {
    raw.split(|c: char| c == ',' || c.is_whitespace())
        .filter(|keyword| !keyword.is_empty())
        .map(str::to_lowercase)
        .collect()
}

/// The canonical rendering of what a `Keywords` value SELECTS, as one value a
/// selection fingerprint can carry.
///
/// Two searches select the same schemas exactly when their keyword SETS agree:
/// [`keywords_of`] has already dropped the separators and folded the case, and
/// [`matches_every_keyword`] folds the result with `all`, so neither the order the
/// keywords arrived in nor a keyword repeated in the value changes which schemas match.
/// Sorting and de-duplicating turns the list into that set, and joining with a comma is
/// unambiguous because a keyword can hold no comma — commas are what `keywords_of` split
/// on.
fn canonical_keywords(keywords: &[String]) -> String {
    let mut canonical: Vec<&str> = keywords.iter().map(String::as_str).collect();
    canonical.sort_unstable();
    canonical.dedup();
    canonical.join(",")
}

/// Whether `keywords` match a schema as of `now`.
///
/// A schema is selected when EVERY requested keyword occurs in one of the values the
/// schema is INDEXED under as of that instant ([`indexed_values`]), matched
/// case-insensitively as a substring, because a search is not a lookup by exact value and
/// adding a keyword only ever narrows the result. A request that names NO keyword limits
/// nothing, so it selects every schema, which is also what folding over an empty keyword
/// list says.
fn matches_every_keyword(
    schema: &crate::state::Schema,
    keywords: &[String],
    now: ::std::time::SystemTime,
) -> bool {
    // Answering "no keyword narrows nothing" before the index is built keeps an
    // unlimited search from reading any stored document — and such a search consults no
    // index, so it does not wait for one either.
    if keywords.is_empty() {
        return true;
    }
    let indexed = indexed_values(schema, now);
    keywords
        .iter()
        .all(|keyword| indexed.iter().any(|value| value.contains(keyword.as_str())))
}

/// The values a keyword can occur in for a schema to match as of `now`, folded to lower
/// case: what the registry indexes the schema under.
///
/// * the TEXT of every definition the index has caught up with
///   ([`crate::state::is_keyword_indexed`], read from the instant that definition was
///   written), so a keyword naming anything the document states — the event source and
///   detail type an EventBridge document records in its `x-amazon-events-*` extensions, a
///   title, a component, a property — finds it, and a schema whose later version states
///   something new is found under that too once that version is indexed;
/// * the schema's NAME — the text a caller knows it by, so a keyword drawn from it finds
///   the schema it names;
/// * the event identity of a PUBLISHED schema, which its document's text does not state
///   (the catalogue publishes the event's `detail` and nothing about the envelope it
///   arrives in), read from where the store holds it:
///   [`crate::state::Schema::published_event`].
///
/// EMPTY until the index has caught up with a definition of this schema: the schema's own
/// name and identity are index entries of the same index, so a schema nothing of which is
/// indexed yet is selected by no keyword at all. Folded ONCE per schema here rather than
/// once per keyword at the match.
fn indexed_values(
    schema: &crate::state::Schema,
    now: ::std::time::SystemTime,
) -> Vec<String> {
    let documents: Vec<&String> = schema
        .versions
        .values()
        .filter(|version| crate::state::is_keyword_indexed(version.created_date, now))
        .map(|version| &version.content)
        .collect();
    if documents.is_empty() {
        return Vec::new();
    }
    let mut indexed: Vec<String> = Vec::with_capacity(documents.len() + 3);
    indexed.push(schema.name.to_lowercase());
    if let Some(published) = &schema.published_event {
        indexed.push(published.source.to_lowercase());
        indexed.push(published.detail_type.to_lowercase());
    }
    for document in documents {
        indexed.push(document.to_lowercase());
    }
    indexed
}

#[cfg(test)]
mod tests {
    use super::*;

    /// One `Keywords` value is a list: commas and whitespace separate its keywords,
    /// case is folded, and a value that names none limits nothing.
    #[test]
    fn a_keywords_value_is_a_case_folded_list() {
        for (raw, expected) in [
            ("order", vec!["order"]),
            ("Order", vec!["order"]),
            ("order placed", vec!["order", "placed"]),
            ("order,placed", vec!["order", "placed"]),
            ("order, placed\tv1\n", vec!["order", "placed", "v1"]),
            (",,  ,", vec![]),
            ("", vec![]),
        ] {
            let parsed = keywords_of(raw);
            assert_eq!(
                parsed, expected,
                "case {raw:?}: expected {expected:?}, got {parsed:?}"
            );
        }
    }

    /// Two `Keywords` values select the same schemas exactly when their keyword SETS
    /// agree, so that set — not the bytes the caller typed — is what the fingerprint a
    /// `NextToken` carries is rendered from.
    #[test]
    fn the_canonical_keywords_are_the_selecting_set() {
        // Spellings of one selection, and the one value they all render as.
        for (spellings, canonical) in [
            (vec!["orders", "ORDERS", "orders,", " orders ", "orders,orders"], "orders"),
            (
                vec!["order placed", "placed,order", "ORDER,PLACED", " placed  order "],
                "order,placed",
            ),
            (vec!["", " ", ",", ",,  ,"], ""),
        ] {
            for spelling in spellings {
                let rendered = canonical_keywords(&keywords_of(spelling));
                assert_eq!(
                    rendered, canonical,
                    "case {spelling:?}: expected {canonical:?}, got {rendered:?}"
                );
            }
        }
        // And a selection that is NOT the same one renders differently.
        for (left, right) in [("orders", "order"), ("order placed", "orders"), ("orders", "")] {
            let (rendered_left, rendered_right) = (
                canonical_keywords(&keywords_of(left)),
                canonical_keywords(&keywords_of(right)),
            );
            assert_ne!(
                rendered_left, rendered_right,
                "case {left:?} vs {right:?}: different selections must render differently, \
                 got {rendered_left:?}"
            );
        }
    }

    /// Every schema AWS publishes carries the event it describes, and a keyword of that
    /// event's source or detail type selects it — as does one of its own name, which a
    /// caller knows it by. The catalogue was published before any request, so the index
    /// has long since caught up with it.
    #[test]
    fn a_published_schema_is_indexed_under_its_event_and_its_name() {
        let state = crate::state::ComAmazonawsSchemasSchemasState::default();
        let now = ::std::time::SystemTime::now();
        let registry = &state.registries[crate::state::AWS_MANAGED_REGISTRY];
        assert!(
            !registry.schemas.is_empty(),
            "the published registry must hold schemas to search over"
        );
        for (schema_name, schema) in &registry.schemas {
            let indexed = indexed_values(schema, now);
            // The catalogue holds the event identity its document does not state.
            let published = schema
                .published_event
                .as_ref()
                .unwrap_or_else(|| panic!("case {schema_name:?}: a published schema carries its event"));
            for declared in [&published.source, &published.detail_type] {
                assert!(
                    matches_every_keyword(schema, &keywords_of(declared), now),
                    "case {schema_name:?}: a keyword of its event {declared:?} must select it, \
                     indexed under {indexed:?}"
                );
            }
            // Its name is what a caller knows it by, so a keyword of it selects it too.
            assert!(
                matches_every_keyword(schema, &keywords_of(schema_name), now),
                "case {schema_name:?}: its own name must select it"
            );
            // Every published source is under the `aws.` prefix, so this one keyword
            // selects each of them.
            assert!(
                matches_every_keyword(schema, &keywords_of("AWS."), now),
                "case {schema_name:?}: a keyword of its source must select it, \
                 indexed under {indexed:?}"
            );
            assert!(
                !matches_every_keyword(schema, &keywords_of("no-event-says-this"), now),
                "case {schema_name:?}: a keyword nothing about it carries must not select it"
            );
            // A value carrying no keyword limits nothing, so it selects every schema.
            assert!(
                matches_every_keyword(schema, &keywords_of(" , "), now),
                "case {schema_name:?}: a value carrying no keyword must limit nothing"
            );
        }
    }

    /// RULE (the index's catch-up, as a property of the stored instants): nothing of a
    /// schema is reachable by keyword until the index has caught up with a definition of
    /// it, and from that instant on its name, its identity and that definition's text all
    /// are — while a value carrying no keyword consults no index and reports the schema
    /// throughout.
    #[test]
    fn no_keyword_reaches_a_schema_before_the_index_catches_up() {
        let state = crate::state::ComAmazonawsSchemasSchemasState::default();
        let registry = &state.registries[crate::state::AWS_MANAGED_REGISTRY];
        let (schema_name, schema) = registry
            .schemas
            .iter()
            .next()
            .expect("the published registry holds a schema");
        let written = schema
            .versions
            .values()
            .next_back()
            .expect("a published schema holds a definition")
            .created_date;
        let delay = crate::state::SCHEMA_INDEXING_DELAY;
        // Rows: instants either side of the catch-up for the NEWEST definition, named
        // relative to when it was written rather than as a wall-clock value.
        for (case, at, indexed) in [
            ("the instant it was written", written, false),
            (
                "a moment after it was written",
                written + delay / 2,
                false,
            ),
            ("one span after it was written", written + delay, true),
            ("long after it was written", written + delay * 100, true),
        ] {
            assert_eq!(
                matches_every_keyword(schema, &keywords_of(schema_name), at),
                indexed,
                "case {case}: expected indexed={indexed} for {schema_name:?} at {at:?}"
            );
            assert!(
                matches_every_keyword(schema, &keywords_of(""), at),
                "case {case}: a value carrying no keyword must report the schema"
            );
        }
    }
}
