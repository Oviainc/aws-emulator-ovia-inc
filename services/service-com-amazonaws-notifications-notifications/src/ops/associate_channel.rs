impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for AssociateChannel<Eng>
{
    type Input = AssociateChannelInput;
    type Output = AssociateChannelOutput;
    type Error = AssociateChannelError;

    const NAME: &'static str = "AssociateChannel";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::ASSOCIATE_CHANNEL_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::ASSOCIATE_CHANNEL_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 201u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;

        // The store is the only place an association exists; without it there is
        // nothing to associate in, which is a server fault, not a client error.
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            AssociateChannelErrorModeled::InternalServerException(InternalServerException {
                message: "the notifications store is unavailable".to_string(),
            })
        })?;
        let mut store = state.lock();

        // The channel is associated "with a particular NotificationConfiguration":
        // the arn must name one this account holds, or there is nothing to
        // associate it with. Both arns already satisfy their modelled patterns —
        // the boundary validator refused the request otherwise — so the only
        // thing left to establish is that the configuration exists.
        let Some(record) = store.configurations.get(&input.notification_configuration_arn) else {
            return Err(AssociateChannelErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: crate::state::not_found_message(
                        crate::state::CONFIGURATION_RESOURCE_LABEL,
                        crate::state::ARN_IDENTIFIER_LABEL,
                        &input.notification_configuration_arn,
                    ),
                    resource_id: input.notification_configuration_arn.clone(),
                },
            )
            .into());
        };

        let already_associated = record.channel_arns.contains_key(&input.arn);
        let associated_channels = record.channel_arns.len();

        // `@idempotent`: a repeat of an association this configuration already
        // carries succeeds and changes nothing — no second entry, no reordering
        // of the listing, and no quota consumed.
        if !already_associated {
            // The stored set is bounded: past its ceiling an association is
            // refused with the error the model declares for a quota, not served
            // by growing the record further.
            if associated_channels >= crate::state::MAX_CHANNELS_PER_CONFIGURATION {
                return Err(AssociateChannelErrorModeled::ServiceQuotaExceededException(
                    ServiceQuotaExceededException {
                        message: format!(
                            "this NotificationConfiguration is already associated with the maximum of {} Channels",
                            crate::state::MAX_CHANNELS_PER_CONFIGURATION
                        ),
                        resource_type: "Channel".to_string(),
                        resource_id: Some(input.notification_configuration_arn.clone()),
                        service_code: Some("notifications".to_string()),
                        quota_code: None,
                    },
                )
                .into());
            }
            store.associate_channel(&input.notification_configuration_arn, &input.arn);
        }

        // The association is what this operation persists; the modelled response
        // carries no members, so a caller reads it back through `ListChannels`.
        Ok(AssociateChannelOutput {})
    }
}
