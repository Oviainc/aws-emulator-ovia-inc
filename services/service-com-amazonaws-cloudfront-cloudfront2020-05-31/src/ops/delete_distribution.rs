    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(crate::state::store_unavailable());
        };
        let _ = ctx;
        let mut store = state.lock();
        store.settle(SystemTime::now());

        let Some(current) = store
            .distribution(&input.id)
            .map(|stored| (stored.etag.clone(), stored.deletable()))
        else {
            return Err(DeleteDistributionErrorModeled::NoSuchDistribution(
                crate::state::no_such_distribution(),
            )
            .into());
        };
        let (current_etag, deletable) = current;

        // The precondition is checked first, the way HTTP evaluates one: a caller
        // holding a version that is no longer current is told that before anything
        // about the distribution's own state.
        match crate::state::check_if_match(&current_etag, input.if_match.as_deref()) {
            IfMatch::Current => {}
            IfMatch::Invalid => {
                return Err(DeleteDistributionErrorModeled::InvalidIfMatchVersion(
                    crate::state::invalid_if_match_version(),
                )
                .into());
            }
            IfMatch::Stale => {
                return Err(DeleteDistributionErrorModeled::PreconditionFailed(
                    crate::state::precondition_failed(),
                )
                .into());
            }
        }

        // "The specified CloudFront distribution is not disabled. You must disable the
        // distribution before you can delete it." Disabling it is not enough on its own:
        // the disabled configuration has to have reached the edge locations, so a
        // distribution that is still `InProgress` — whether it was never disabled, was
        // just disabled, or was just reconfigured — is refused here and stays readable.
        if !deletable {
            return Err(DeleteDistributionErrorModeled::DistributionNotDisabled(
                DistributionNotDisabled {
                    message: Some(crate::state::DISTRIBUTION_NOT_DISABLED_MESSAGE.to_string()),
                },
            )
            .into());
        }

        // Gone means gone: the record, the caller reference it held and the listener its
        // edge was served on are all released, so a later create may reuse that reference,
        // no later read reports the distribution, and nothing answers at the domain name it
        // published.
        if let Some(removed) = store.distributions.remove(&input.id) {
            store
                .caller_references
                .remove(&removed.config.caller_reference);
        }
        store.edge_endpoints.remove(&input.id);

        Ok(DeleteDistributionOutput {})
    }
