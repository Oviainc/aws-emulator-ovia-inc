/// The filter names the `Filters` member doc publishes: "Valid filter names:
/// replication-task-arn | replication-task-id | migration-type | endpoint-arn |
/// replication-instance-arn".
const DOCUMENTED_FILTERS: &[&str] = &[
    "replication-task-arn",
    "replication-task-id",
    "migration-type",
    "endpoint-arn",
    "replication-instance-arn",
];

/// Refuse a filter name this operation does not document, rather than ignoring it and
/// answering with tasks the caller asked to exclude.
fn check_filter_names(filters: &[Filter]) -> Result<(), DescribeReplicationTasksError> {
    for filter in filters {
        if !DOCUMENTED_FILTERS.contains(&filter.name.as_str()) {
            return Err(crate::scaffolded::Scaffolded::validation(format!(
                "{} is not a supported filter name; the valid filter names are {}",
                filter.name,
                DOCUMENTED_FILTERS.join(" | ")
            )));
        }
    }
    Ok(())
}

/// Whether `record` satisfies every filter the request carries: each filter narrows the
/// answer to the tasks whose matching attribute is one of that filter's values.
fn matches_filters(record: &crate::state::ReplicationTaskRecord, filters: &[Filter]) -> bool {
    filters.iter().all(|filter| match filter.name.as_str() {
        "replication-task-arn" => filter.values.contains(&record.arn),
        "replication-task-id" => filter.values.contains(&record.identifier),
        "migration-type" => filter.values.contains(&record.migration_type),
        // A task has two endpoints, and either one answers an `endpoint-arn` filter.
        "endpoint-arn" => {
            filter.values.contains(&record.source_endpoint_arn)
                || filter.values.contains(&record.target_endpoint_arn)
        }
        "replication-instance-arn" => filter.values.contains(&record.replication_instance_arn),
        // `check_filter_names` has already refused every other name.
        _ => true,
    })
}
