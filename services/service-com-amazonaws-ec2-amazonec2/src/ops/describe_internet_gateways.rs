/// The filter names this operation documents, from
/// `DescribeInternetGatewaysRequest$Filters`:
///
/// ```text
/// smithy_query(query="doc",shape="DescribeInternetGatewaysRequest",member="Filters",model_path="services/service-com-amazonaws-ec2-amazonec2/smithy-model/com-amazonaws-ec2-amazonec2.json")
/// ```
///
/// `tag:<key>` is the one name with a variable part, so it is matched by prefix rather than
/// listed here. Every entry must be answered by [`filter_values`]. This operation's doc
/// publishes no alternative spelling for any of them.
const INTERNET_GATEWAY_FILTERS: [&str; 5] = [
    "attachment.state",
    "attachment.vpc-id",
    "internet-gateway-id",
    "owner-id",
    "tag-key",
];

/// Whether this operation documents the filter the request named.
///
/// The tag filter is the one name with a variable part — "use the tag key in the filter name
/// and the tag value as the filter value" (`DescribeInternetGatewaysRequest$Filters`) — so it
/// is matched by [`TAG_FILTER_PREFIX`], the one spelling every describe of this crate reads a
/// tag filter by, and the key must not be empty: a `tag:` with no key names no tag.
///
/// "Filter names are case-sensitive" (`Filter$Name`), so every other comparison is exact.
fn filter_name_is_documented(name: &str) -> bool {
    name.strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
        || INTERNET_GATEWAY_FILTERS.contains(&name)
}

/// The values the EC2 filter `name` compares against this internet gateway.
///
/// A filter naming an attribute no part of this gateway carries compares against NO values,
/// so it selects nothing — which is what "Present only if a VPC is attached"
/// (`DescribeInternetGatewaysRequest$Filters`, `attachment.state`) asks of a gateway attached
/// to nothing. An `attachment.…` filter compares against the values of EVERY attachment the
/// gateway holds, so the gateway is selected when any one of them matches. `name` is a name
/// the handler has already found documented.
///
/// The AND/OR evaluation of these values, and the budget that bounds it, live in
/// [`crate::state::matches_every_filter`], which every filtered describe of this crate
/// shares: "If you specify multiple filters, the filters are joined with an AND" (`Filter`),
/// and within one filter "if you specify multiple values for a filter, the values are joined
/// with an OR" (`Filter$Values`). So a filter carrying NO value matches nothing — one reading
/// of `Filter$Values`, shared with the sibling describes, rather than one this operation
/// invents for itself.
fn filter_values<'a>(internet_gateway: &'a InternetGateway, name: &str) -> Vec<Cow<'a, str>> {
    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return internet_gateway
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let attachments = || internet_gateway.attachments.iter().flatten();
    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "attachment.state" => attachments()
            .filter_map(|attachment| attachment.state.as_deref().map(Cow::Borrowed))
            .collect(),
        "attachment.vpc-id" => attachments()
            .filter_map(|attachment| attachment.vpc_id.as_deref().map(Cow::Borrowed))
            .collect(),
        "internet-gateway-id" => text(internet_gateway.internet_gateway_id.as_deref()),
        "owner-id" => text(internet_gateway.owner_id.as_deref()),
        "tag-key" => internet_gateway
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        // Unreachable: the handler has already refused every other name. An undefined name
        // compares against nothing, so it could never widen a result even if that check were
        // bypassed.
        _ => Vec::new(),
    }
}
