/// The filter names this operation documents, from `DescribeVpnGatewaysRequest$Filters`:
///
/// ```text
/// smithy_query(query="doc",shape="DescribeVpnGatewaysRequest",member="Filters",model_path="services/service-com-amazonaws-ec2-amazonec2/smithy-model/com-amazonaws-ec2-amazonec2.json")
/// ```
///
/// `tag:<key>` is the one name with a variable part, so it is matched by prefix rather than
/// listed here. Every entry must be answered by [`filter_values`].
const VPN_GATEWAY_FILTERS: [&str; 8] = [
    "amazon-side-asn",
    "attachment.state",
    "attachment.vpc-id",
    "availability-zone",
    "state",
    "tag-key",
    "type",
    "vpn-gateway-id",
];

/// The prefix of the tag filter: "Use the tag key in the filter name and the tag value as
/// the filter value" (`DescribeVpnGatewaysRequest$Filters`).
const TAG_FILTER_PREFIX: &str = "tag:";

/// Is `name` a filter this operation documents? "Filter names are case-sensitive"
/// (`Filter$Name`), so the comparison is exact — and a `tag:` prefix with no key names no
/// tag, so it is as undocumented as any other misspelling.
fn is_documented_filter(name: &str) -> bool {
    name.strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
        || VPN_GATEWAY_FILTERS.contains(&name)
}

/// The values the EC2 filter `name` compares against this virtual private gateway.
///
/// A filter naming an attribute this gateway does not carry compares against NO values, so
/// it selects nothing — which is the answer for `availability-zone` on a gateway created
/// without one, and for the two `attachment.` filters on a gateway attached to no VPC.
fn filter_values<'a>(record: &'a VpnGatewayRecord, name: &str) -> Vec<Cow<'a, str>> {
    let vpn_gateway = &record.view;
    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return vpn_gateway
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let attachments = || vpn_gateway.vpc_attachments.iter().flatten();
    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        // A numeric attribute is filtered on the value a client sends for it, which is how
        // the wire renders it: the ASN in decimal.
        "amazon-side-asn" => vpn_gateway
            .amazon_side_asn
            .map(|asn| Cow::Owned(asn.to_string()))
            .into_iter()
            .collect(),
        // "The current state of the attachment between the gateway and the VPC" and "The ID
        // of an attached VPC": a gateway may be attached to more than one VPC, so each
        // attachment contributes a value and the filter holds when ANY of them matches.
        "attachment.state" => attachments()
            .filter_map(|attachment| attachment.state.as_deref().map(Cow::Borrowed))
            .collect(),
        "attachment.vpc-id" => attachments()
            .filter_map(|attachment| attachment.vpc_id.as_deref().map(Cow::Borrowed))
            .collect(),
        "availability-zone" => text(vpn_gateway.availability_zone.as_deref()),
        "state" => text(vpn_gateway.state.as_deref()),
        "type" => text(vpn_gateway.r#type.as_deref()),
        "vpn-gateway-id" => text(vpn_gateway.vpn_gateway_id.as_deref()),
        "tag-key" => vpn_gateway
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        // Unreachable: `is_documented_filter` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even
        // if that check were bypassed.
        _ => Vec::new(),
    }
}
