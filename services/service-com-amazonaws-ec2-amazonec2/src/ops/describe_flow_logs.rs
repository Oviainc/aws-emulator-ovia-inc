/// `tag:<key>` is the one name with a variable part, so it is matched by prefix rather than
/// listed here. Every entry must be answered by [`filter_values`].
const FLOW_LOG_FILTERS: [&str; 7] = [
    "deliver-log-status",
    "log-destination-type",
    "flow-log-id",
    "log-group-name",
    "resource-id",
    "traffic-type",
    "tag-key",
];

/// The names a refusal reports as supported: [`FLOW_LOG_FILTERS`] plus the `tag:<key>`
/// family, which this operation accepts by prefix and so cannot be a member of the array
/// the matcher resolves against. A caller fixing a misspelled filter from the message has
/// to be told about it too.
const REPORTED_FLOW_LOG_FILTERS: [&str; 8] = [
    "deliver-log-status",
    "log-destination-type",
    "flow-log-id",
    "log-group-name",
    "resource-id",
    "traffic-type",
    "tag:<key>",
    "tag-key",
];

/// The prefix of the tag filter: "Use the tag key in the filter name and the tag value as
/// the filter value" (`DescribeFlowLogsRequest$Filter`).
const TAG_FILTER_PREFIX: &str = "tag:";

/// The name [`filter_values`] answers for the filter the request called `name`, or `None`
/// when this operation documents no such filter.
///
/// "Filter names are case-sensitive" (`Filter$Name`), so every comparison is exact — and a
/// `tag:` prefix with no key names no tag, so it is as undocumented as any other
/// misspelling. The `tag:<key>` family keeps its whole name, the key being part of what it
/// selects on.
fn canonical_filter_name(name: &str) -> Option<&str> {
    if name
        .strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
    {
        return Some(name);
    }
    FLOW_LOG_FILTERS.contains(&name).then_some(name)
}

/// The values the EC2 filter `name` compares against this flow log.
///
/// A filter naming an attribute this flow log does not carry compares against NO values, so
/// it selects nothing rather than everything. `name` is a name [`canonical_filter_name`]
/// resolved.
fn filter_values<'a>(flow_log: &'a FlowLog, name: &str) -> Vec<Cow<'a, str>> {
    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return flow_log
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        // "The status of the logs delivery (SUCCESS | FAILED)"
        // (`DescribeFlowLogsRequest$Filter`), compared against the member the stored flow
        // log reports it under.
        "deliver-log-status" => text(flow_log.deliver_logs_status.as_deref()),
        "log-destination-type" => text(flow_log.log_destination_type.as_deref()),
        "flow-log-id" => text(flow_log.flow_log_id.as_deref()),
        "log-group-name" => text(flow_log.log_group_name.as_deref()),
        "resource-id" => text(flow_log.resource_id.as_deref()),
        "traffic-type" => text(flow_log.traffic_type.as_deref()),
        "tag-key" => flow_log
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        // Unreachable: `canonical_filter_name` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even
        // if that check were bypassed.
        _ => Vec::new(),
    }
}
