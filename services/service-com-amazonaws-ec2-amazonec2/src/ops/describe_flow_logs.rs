/// The filter names this operation documents, from `DescribeFlowLogsRequest$Filter`:
///
/// ```text
/// smithy_query(query="doc",shape="DescribeFlowLogsRequest",member="Filter",model_path="services/service-com-amazonaws-ec2-amazonec2/smithy-model/com-amazonaws-ec2-amazonec2.json")
