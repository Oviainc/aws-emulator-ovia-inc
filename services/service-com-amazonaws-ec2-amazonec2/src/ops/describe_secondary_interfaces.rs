/// The prefix of the tag filter: "Use the tag key in the filter name and the tag value as
/// the filter value" (`DescribeSecondaryInterfacesRequest$Filters`).
const TAG_FILTER_PREFIX: &str = "tag:";

/// Does this operation document a filter called `name`?
///
/// "Filter names are case-sensitive" (`Filter$Name`), so every comparison is exact — and a
/// `tag:` prefix with no key names no tag, so it is as undocumented as any other
/// misspelling.
fn filter_name_documented(name: &str) -> bool {
    if name
        .strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
    {
        return true;
    }
    SECONDARY_INTERFACE_FILTERS.contains(&name)
}

/// The values the EC2 filter `name` compares against this secondary interface.
///
/// A filter naming an attribute this interface does not carry compares against NO values, so
/// it selects nothing — the same answer AWS gives for a tag key a resource does not have, and
/// what every `attachment.*` filter gets for an interface no instance holds. `name` is one
/// [`filter_name_documented`] accepted.
fn filter_values<'a>(
    secondary_interface: &'a SecondaryInterface,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return secondary_interface
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let attachment = secondary_interface.attachment.as_ref();
    let text =
        |value: Option<&'a str>| -> Vec<Cow<'a, str>> { value.map(Cow::Borrowed).into_iter().collect() };
    match name {
        "attachment.attachment-id" => {
            text(attachment.and_then(|attachment| attachment.attachment_id.as_deref()))
        }
        "attachment.instance-id" => {
            text(attachment.and_then(|attachment| attachment.instance_id.as_deref()))
        }
        "attachment.instance-owner-id" => {
            text(attachment.and_then(|attachment| attachment.instance_owner_id.as_deref()))
        }
        "attachment.status" => text(attachment.and_then(|attachment| attachment.status.as_deref())),
        "owner-id" => text(secondary_interface.owner_id.as_deref()),
        "private-ipv4-addresses.private-ip-address" => secondary_interface
            .private_ipv4_addresses
            .iter()
            .flatten()
            .filter_map(|address| address.private_ip_address.as_deref().map(Cow::Borrowed))
            .collect(),
        "secondary-interface-arn" => text(secondary_interface.secondary_interface_arn.as_deref()),
        "secondary-interface-id" => text(secondary_interface.secondary_interface_id.as_deref()),
        "secondary-interface-type" => text(secondary_interface.secondary_interface_type.as_deref()),
        "secondary-network-id" => text(secondary_interface.secondary_network_id.as_deref()),
        "secondary-network-type" => text(secondary_interface.secondary_network_type.as_deref()),
        "secondary-subnet-id" => text(secondary_interface.secondary_subnet_id.as_deref()),
        "status" => text(secondary_interface.status.as_deref()),
        "tag-key" => secondary_interface
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        // Unreachable: `filter_name_documented` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even
        // if that check were bypassed.
        _ => Vec::new(),
    }
}
