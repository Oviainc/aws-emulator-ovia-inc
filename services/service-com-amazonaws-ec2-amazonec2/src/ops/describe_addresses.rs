        let requested_ips = input.public_ips.clone().unwrap_or_default();
        for (member, named) in [
            ("AllocationIds", &requested_ids),
            ("PublicIps", &requested_ips),
        ] {
            if named.len() > MAX_RESOURCE_IDS {
                return Err(Scaffolded::invalid_parameter_value(format!(
                    "{member} carries {} entries, above the maximum of {MAX_RESOURCE_IDS}",
                    named.len()
                )));
            }
        }

        // Matching cost is filters x values x held values x stored addresses and the model
        // bounds none of them, so the request-controlled factors are capped here, and their
        // PRODUCT is charged to one [`MatchBudget`] below.
        let supplied_filters = input.filters.as_ref().map_or(0, Vec::len);
        if supplied_filters > MAX_FILTERS {
            return Err(Scaffolded::invalid_parameter_value(format!(
                "The request carries {supplied_filters} filters, above the maximum \
                 of {MAX_FILTERS}"
            )));
        }

        // A filter name this operation does not document is refused whether or not any
        // address would have matched it, so an unsupported filter can never read as "no
        // results".
