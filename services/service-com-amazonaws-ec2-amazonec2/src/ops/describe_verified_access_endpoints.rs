/// The filter names this operation answers.
///
/// The model documents no list of its own — "One or more filters. Filter names and values are
/// case-sensitive" (`DescribeVerifiedAccessEndpointsRequest$Filters`) — and `Filter` itself
/// says a filter matches resources "by specific criteria, such as tags, attributes, or IDs".
/// So the names here are EC2's spelling (hyphenated, lower case) of the reported shape's own
/// members — `smithy_query(query="shape",shape="VerifiedAccessEndpoint")` — plus `tag-key`,
/// the resource-wide tag filter EC2 documents for every taggable resource ("List and filter
/// using the CLI and API", linked from `Filter`). `security-group-id` names the values of the
/// endpoint's `SecurityGroupIds` list and `status-code` the `Code` of its `Status` block, the
/// two members that are not plain scalars. Every entry must be answered by [`filter_values`].
///
/// `tag:<key>` is the one name with a variable part, so it is matched by prefix rather than
/// listed here.
const VERIFIED_ACCESS_ENDPOINT_FILTERS: [&str; 16] = [
    "application-domain",
    "attachment-type",
    "creation-time",
    "deletion-time",
    "description",
    "device-validation-domain",
    "domain-certificate-arn",
    "endpoint-domain",
    "endpoint-type",
    "last-updated-time",
    "security-group-id",
    "status-code",
    "tag-key",
    "verified-access-endpoint-id",
    "verified-access-group-id",
    "verified-access-instance-id",
];

/// The name [`filter_values`] answers for the filter the request called `name`, or `None`
/// when this operation answers no such filter.
///
/// The `tag:<key>` prefix comes from the crate's one definition of it,
/// `crate::state::TAG_FILTER_PREFIX`, so that spelling cannot drift between the describes
/// that answer the tag filter.
///
/// "Filter names and values are case-sensitive"
/// (`DescribeVerifiedAccessEndpointsRequest$Filters`), so every comparison is exact — and a
/// `tag:` prefix with no key names no tag, so it is as undocumented as any other misspelling.
fn canonical_filter_name(name: &str) -> Option<&str> {
    if name
        .strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
    {
        return Some(name);
    }
    VERIFIED_ACCESS_ENDPOINT_FILTERS
        .contains(&name)
        .then_some(name)
}

/// The values the EC2 filter `name` compares against this endpoint.
///
/// A filter naming an attribute this endpoint does not carry compares against NO values, so
/// it selects nothing — which is the answer for `deletion-time` on an endpoint nothing has
/// deleted, and for `device-validation-domain` on one whose instance has no device trust
/// provider. `name` is a name [`canonical_filter_name`] resolved.
fn filter_values<'a>(
    endpoint: &'a VerifiedAccessEndpoint,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return endpoint
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "application-domain" => text(endpoint.application_domain.as_deref()),
        "attachment-type" => text(endpoint.attachment_type.as_deref()),
        "creation-time" => text(endpoint.creation_time.as_deref()),
        "deletion-time" => text(endpoint.deletion_time.as_deref()),
        "description" => text(endpoint.description.as_deref()),
        "device-validation-domain" => text(endpoint.device_validation_domain.as_deref()),
        "domain-certificate-arn" => text(endpoint.domain_certificate_arn.as_deref()),
        "endpoint-domain" => text(endpoint.endpoint_domain.as_deref()),
        "endpoint-type" => text(endpoint.endpoint_type.as_deref()),
        "last-updated-time" => text(endpoint.last_updated_time.as_deref()),
        "security-group-id" => endpoint
            .security_group_ids
            .iter()
            .flatten()
            .map(|group_id| Cow::Borrowed(group_id.as_str()))
            .collect(),
        "status-code" => text(
            endpoint
                .status
                .as_ref()
                .and_then(|status| status.code.as_deref()),
        ),
        "tag-key" => endpoint
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        "verified-access-endpoint-id" => text(endpoint.verified_access_endpoint_id.as_deref()),
        "verified-access-group-id" => text(endpoint.verified_access_group_id.as_deref()),
        "verified-access-instance-id" => text(endpoint.verified_access_instance_id.as_deref()),
        // Unreachable: `canonical_filter_name` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even if
        // that check were bypassed.
        _ => Vec::new(),
    }
}
