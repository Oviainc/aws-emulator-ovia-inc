/// "`ok` the accelerator interconnect is healthy"
/// (`CapacityBlockStatus$InterconnectStatus`): one member of the modelled
/// `CapacityBlockInterconnectStatus` enum
/// (`smithy_query(query="shape",shape="CapacityBlockInterconnectStatus")`, whose wire values
/// this crate also keeps in [`CAPACITY_BLOCK_INTERCONNECT_STATUS_VALUES`]).
const INTERCONNECT_STATUS_OK: &str = "ok";

/// "`impaired` - accelerator interconnect communication is impaired" (same member): that
/// enum's second value.
const INTERCONNECT_STATUS_IMPAIRED: &str = "impaired";

/// "`insufficient-data` - insufficient data to determine accelerator interconnect status"
/// (same member): that enum's third value.
const INTERCONNECT_STATUS_INSUFFICIENT_DATA: &str = "insufficient-data";

/// The availability of `record`'s capacity as of `now`.
///
/// A Capacity Block holds its capacity as Capacity Reservations, so the block's capacity IS
/// those reservations' capacity: each one contributes "the combined amount of `Available` and
/// `Unavailable` capacity" it reserves (`CapacityReservationStatus$TotalCapacity`), of which
/// the part that can still be launched into is available (`$TotalAvailableCapacity`) and the
/// rest is not (`$TotalUnavailableCapacity`); the block's three totals are the sums of its
/// reservations' (`CapacityBlockStatus$TotalCapacity`). Capacity of a reservation that is not
/// serving capacity at `now` — one whose payment has not settled, one held for a later date,
/// one that has expired or been cancelled — cannot be launched into, so none of it is
/// available.
///
/// Every number is derived from the stored block, the stored reservations and the clock, so
/// two calls a moment apart answer the same and neither writes anything.
fn capacity_block_status_at(
    store: &crate::state::ComAmazonawsEc2Amazonec2State,
    record: &crate::state::CapacityBlockRecord,
    now: ::std::time::SystemTime,
) -> CapacityBlockStatus {
    let named = record
        .block
        .capacity_reservation_ids
        .as_deref()
        .unwrap_or_default();
    let mut capacity_reservation_statuses: Vec<CapacityReservationStatus> =
        Vec::with_capacity(named.len());
    let mut serving = 0usize;
    for capacity_reservation_id in named {
        // A reservation this store no longer holds reports no capacity rather than a row of
        // zeroes: there is nothing to report the availability of.
        let Some(reservation) = store.capacity_reservations.get(capacity_reservation_id) else {
            continue;
        };
        let delivering =
            reservation.state_at(now) == crate::state::CAPACITY_RESERVATION_STATE_ACTIVE;
        if delivering {
            serving = serving.saturating_add(1);
        }
        let total = reservation
            .view
            .total_instance_count
            .unwrap_or_default()
            .max(0);
        // "The remaining capacity. Indicates the amount of resources that can be launched
        // into the Capacity Reservation" (`CapacityReservationStatus$TotalAvailableCapacity`)
        // — which is none of it while the reservation is not serving capacity.
        let available = if delivering {
            reservation.available_instance_count().clamp(0, total)
        } else {
            0
        };
        capacity_reservation_statuses.push(CapacityReservationStatus {
            capacity_reservation_id: Some(capacity_reservation_id.clone()),
            total_capacity: Some(total),
            total_available_capacity: Some(available),
            // The two parts of `TotalCapacity` are exhaustive, so what is not available is
            // unavailable — "the used capacity" of a reservation being served
            // (`$TotalUnavailableCapacity`), and all of it for one that is not.
            total_unavailable_capacity: Some(total.saturating_sub(available)),
        });
    }

    let sum = |of: fn(&CapacityReservationStatus) -> Option<i32>| -> i32 {
        capacity_reservation_statuses
            .iter()
            .fold(0i32, |total, status| {
                total.saturating_add(of(status).unwrap_or_default())
            })
    };

    CapacityBlockStatus {
        capacity_block_id: record.block.capacity_block_id.clone(),
        interconnect_status: Some(
            interconnect_status_at(record, named.len(), serving, now).to_string(),
        ),
        total_capacity: Some(sum(|status| status.total_capacity)),
        total_available_capacity: Some(sum(|status| status.total_available_capacity)),
        total_unavailable_capacity: Some(sum(|status| status.total_unavailable_capacity)),
        capacity_reservation_statuses: Some(capacity_reservation_statuses),
    }
}

/// The status of the accelerator interconnect of the block `record` holds, `serving` of whose
/// `named` Capacity Reservations are serving capacity at `now`.
///
/// The interconnect links the accelerators of capacity that is being served, so there is
/// something to measure only while the block's reserved window is open and the block holds
/// its capacity as reservations at all: a block the clock does not put inside that window —
/// scheduled, expired, cancelled, or waiting on its payment
/// ([`crate::state::CapacityBlockRecord::state_at`]) — and one naming no reservation report
/// `insufficient-data`. An open block whose every named reservation is serving capacity is
/// healthy; one missing some of it — a reservation not serving capacity, or one the account
/// no longer holds — is impaired.
fn interconnect_status_at(
    record: &crate::state::CapacityBlockRecord,
    named: usize,
    serving: usize,
    now: ::std::time::SystemTime,
) -> &'static str {
    if record.state_at(now) != crate::state::CAPACITY_BLOCK_STATE_ACTIVE || named == 0 {
        return INTERCONNECT_STATUS_INSUFFICIENT_DATA;
    }
    if serving == named {
        return INTERCONNECT_STATUS_OK;
    }
    INTERCONNECT_STATUS_IMPAIRED
}

