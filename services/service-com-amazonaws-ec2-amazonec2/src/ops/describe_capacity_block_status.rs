const CAPACITY_BLOCK_STATUS_FILTERS: [&str; 1] = ["interconnect-status"];

/// The name [`filter_values`] answers for the filter the request called `name`, or `None`
/// when this operation documents no such filter.
///
/// "Filter names are case-sensitive" (`Filter$Name`), so the comparison is exact.
fn canonical_filter_name(name: &str) -> Option<&str> {
    CAPACITY_BLOCK_STATUS_FILTERS
        .contains(&name)
        .then_some(name)
}

/// The values the EC2 filter `name` compares against this Capacity Block's status.
///
/// `name` is a name [`canonical_filter_name`] resolved.
fn filter_values<'a>(
    status: &'a CapacityBlockStatus,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    match name {
        "interconnect-status" => status
            .interconnect_status
            .as_deref()
            .map(Cow::Borrowed)
            .into_iter()
            .collect(),
        // Unreachable: `canonical_filter_name` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even if
        // that check were bypassed.
        _ => Vec::new(),
    }
}

/// Does `status` satisfy every filter?
///
/// The AND/OR evaluation, the wildcard matching and the budget charging all live in
/// [`crate::state::matches_every_filter`], so this operation only says WHERE a filter's
/// values come from.
fn matches_every_filter(
    status: &CapacityBlockStatus,
    selectors: &[crate::state::CompiledFilter],
    budget: &mut crate::state::MatchBudget,
) -> bool {
    crate::state::matches_every_filter(selectors, budget, &|name| filter_values(status, name))
}
