const DEFAULT_MAX_RESULTS: usize = 1000;

/// The filter names this operation documents, from `DescribeDhcpOptionsRequest$Filters`:
///
/// ```text
/// smithy_query(query="doc",shape="DescribeDhcpOptionsRequest",member="Filters",model_path="services/service-com-amazonaws-ec2-amazonec2/smithy-model/com-amazonaws-ec2-amazonec2.json")
/// ```
///
/// `tag:<key>` is the one name with a variable part, so it is matched by prefix rather than
/// listed here. Every entry must be answered by [`filter_values`].
const DHCP_OPTIONS_FILTERS: [&str; 5] = ["dhcp-options-id", "key", "owner-id", "tag-key", "value"];

/// The prefix of the tag filter: "Use the tag key in the filter name and the tag value as
/// the filter value" (`DescribeDhcpOptionsRequest$Filters`).
const TAG_FILTER_PREFIX: &str = crate::state::TAG_FILTER_PREFIX;

/// Is `name` a filter this operation documents? "Filter names are case-sensitive"
/// (`Filter$Name`), so the comparison is exact — and a `tag:` prefix with no key names no
/// tag, so it is as undocumented as any other misspelling.
fn is_documented_filter(name: &str) -> bool {
    name.strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
        || DHCP_OPTIONS_FILTERS.contains(&name)
}

/// The values the EC2 filter `name` compares against this option set.
///
/// A filter naming an attribute this set does not carry compares against NO values, so it
/// selects nothing. An undocumented name reaches here only if the check above were
/// bypassed, and answers nothing for the same reason.
fn filter_values<'a>(options: &'a DhcpOptions, name: &str) -> Vec<Cow<'a, str>> {
    let tags = || options.tags.iter().flatten();
    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return tags()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }
    let configurations = || options.dhcp_configurations.iter().flatten();
    match name {
        // "The ID of a DHCP options set."
        "dhcp-options-id" => options
            .dhcp_options_id
            .as_deref()
            .map(Cow::Borrowed)
            .into_iter()
            .collect(),
        // "The key for one of the options (for example, domain-name)" — every option of the
        // set, since a set that carries the key anywhere matches.
        "key" => configurations()
            .filter_map(|configuration| configuration.key.as_deref().map(Cow::Borrowed))
            .collect(),
        // "The ID of the Amazon Web Services account that owns the DHCP options set."
        "owner-id" => options
            .owner_id
            .as_deref()
            .map(Cow::Borrowed)
            .into_iter()
            .collect(),
        "tag-key" => tags()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        // "The value for one of the options" — one option may carry several values, and all
        // of them are the set's.
        "value" => configurations()
            .flat_map(|configuration| configuration.values.iter().flatten())
            .filter_map(|value| value.value.as_deref().map(Cow::Borrowed))
            .collect(),
        // Unreachable: `is_documented_filter` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even if
        // that check were bypassed.
        _ => Vec::new(),
    }
}
