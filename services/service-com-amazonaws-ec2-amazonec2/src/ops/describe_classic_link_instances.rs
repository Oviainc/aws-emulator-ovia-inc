/// The filter names this operation documents, from
/// `DescribeClassicLinkInstancesRequest$Filters`:
///
/// ```text
/// smithy_query(query="doc",shape="DescribeClassicLinkInstancesRequest",member="Filters",model_path="services/service-com-amazonaws-ec2-amazonec2/smithy-model/com-amazonaws-ec2-amazonec2.json")
/// ```
///
/// `tag:<key>` is the one name with a variable part — "Use the tag key in the filter name
/// and the tag value as the filter value" — so it is matched by prefix rather than listed
/// here. Every entry must be answered by [`filter_values`].
const CLASSIC_LINK_INSTANCE_FILTERS: [&str; 4] =
    ["group-id", "instance-id", "tag-key", "vpc-id"];

/// Is `name` a filter this operation documents? "Filter names are case-sensitive"
/// (`Filter$Name`), so the comparison is exact — and a `tag:` prefix with no key names no
/// tag, so it is as undocumented as any other misspelling.
fn is_documented_filter(name: &str) -> bool {
    name.strip_prefix(crate::state::TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
        || CLASSIC_LINK_INSTANCE_FILTERS.contains(&name)
}

/// The values the EC2 filter `name` compares against one linked instance — the
/// per-operation half of [`crate::state::matches_every_filter`], which holds the AND/OR
/// evaluation every filtered describe of this crate shares.
///
/// A filter naming an attribute this row does not carry compares against NO values, so it
/// selects nothing — the answer for `group-id` on an instance linked with no security
/// group, and for `tag:<key>` on an instance carrying no tag of that key. `name` is one of
/// [`CLASSIC_LINK_INSTANCE_FILTERS`] or a `tag:<key>`.
fn filter_values<'a>(
    instance: &'a ClassicLinkInstance,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    if let Some(key) = name.strip_prefix(crate::state::TAG_FILTER_PREFIX) {
        return instance
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        // "The ID of a VPC security group that's associated with the instance": an instance
        // may be linked with several, so each contributes a value and the filter holds when
        // ANY of them matches.
        "group-id" => instance
            .groups
            .iter()
            .flatten()
            .filter_map(|group| group.group_id.as_deref().map(Cow::Borrowed))
            .collect(),
        "instance-id" => text(instance.instance_id.as_deref()),
        "vpc-id" => text(instance.vpc_id.as_deref()),
        // "The key of a tag assigned to the resource ... regardless of the tag value."
        "tag-key" => instance
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        // Unreachable: `is_documented_filter` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even if
        // that check were bypassed.
        _ => Vec::new(),
    }
}
