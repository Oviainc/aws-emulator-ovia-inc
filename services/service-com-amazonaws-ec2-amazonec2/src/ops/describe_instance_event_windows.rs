/// The filter names this operation documents, from
/// `DescribeInstanceEventWindowsRequest$Filters`:
///
/// ```text
/// smithy_query(query="doc",shape="DescribeInstanceEventWindowsRequest",member="Filters",model_path="services/service-com-amazonaws-ec2-amazonec2/smithy-model/com-amazonaws-ec2-amazonec2.json")
/// ```
///
/// `tag:<key>` is the one name with a variable part, so it is matched by prefix rather than
/// listed here. The documented list names no filter for the window's own id — a caller that
/// wants named windows passes `InstanceEventWindowIds`. Every entry must be answered by
/// [`filter_values`].
const EVENT_WINDOW_FILTERS: [&str; 8] = [
    "dedicated-host-id",
    "event-window-name",
    "instance-id",
    "instance-tag",
    "instance-tag-key",
    "instance-tag-value",
    "tag-key",
    "tag-value",
];

/// The name [`filter_values`] answers for the filter the request called `name`, or `None`
/// when this operation documents no such filter.
///
/// "Filter names are case-sensitive" (`Filter$Name`), so every comparison is exact — and a
/// `tag:` prefix with no key names no tag, so it is as undocumented as any other
/// misspelling. The `tag:<key>` family keeps its whole name, the key being part of what it
/// selects on.
fn canonical_filter_name(name: &str) -> Option<&str> {
    if name
        .strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
    {
        return Some(name);
    }
    EVENT_WINDOW_FILTERS.contains(&name).then_some(name)
}

/// How the `instance-tag` filter names one tag of an associated target: "the specified tag
/// and value" (`DescribeInstanceEventWindowsRequest$Filters`), which EC2 spells
/// `<key>=<value>` — the same spelling its `instance-tag` filters take elsewhere.
///
/// Nothing can carry an association target until `AssociateInstanceEventWindow` is
/// implemented, so no stored window exercises this yet; the spelling is worth re-checking,
/// with a test over a tagged target, when that operation lands.
const INSTANCE_TAG_SEPARATOR: char = '=';

/// The values the EC2 filter `name` compares against this event window, as
/// [`crate::state::matches_every_filter`] — the ONE AND/OR evaluator every filtered describe
/// of this crate delegates to — asks for them.
///
/// A filter naming an attribute this window does not carry compares against NO values, so
/// it selects nothing — which is the answer for every `instance-*` and `dedicated-host-id`
/// filter on a window nothing is associated with, a freshly created window having no
/// association target. `name` is a name [`canonical_filter_name`] resolved.
fn filter_values<'a>(
    window: &'a InstanceEventWindow,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    let window_tags = || window.tags.iter().flatten();
    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return window_tags()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let target = || window.association_target.as_ref();
    let target_tags = || target().into_iter().flat_map(|target| target.tags.iter().flatten());
    match name {
        "dedicated-host-id" => target()
            .into_iter()
            .flat_map(|target| target.dedicated_host_ids.iter().flatten())
            .map(|host_id| Cow::Borrowed(host_id.as_str()))
            .collect(),
        "event-window-name" => window.name.as_deref().map(Cow::Borrowed).into_iter().collect(),
        "instance-id" => target()
            .into_iter()
            .flat_map(|target| target.instance_ids.iter().flatten())
            .map(|instance_id| Cow::Borrowed(instance_id.as_str()))
            .collect(),
        "instance-tag" => target_tags()
            .map(|tag| {
                Cow::Owned(format!(
                    "{key}{INSTANCE_TAG_SEPARATOR}{value}",
                    key = tag.key.as_deref().unwrap_or_default(),
                    value = tag.value.as_deref().unwrap_or_default(),
                ))
            })
            .collect(),
        "instance-tag-key" => target_tags()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        "instance-tag-value" => target_tags()
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect(),
        "tag-key" => window_tags()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        "tag-value" => window_tags()
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect(),
        // Unreachable: `canonical_filter_name` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even if
        // that check were bypassed.
        _ => Vec::new(),
    }
}
