/// The filter names this operation documents, from
/// `DescribeCarrierGatewaysRequest$Filters`:
///
/// ```text
/// smithy_query(query="doc",shape="DescribeCarrierGatewaysRequest",member="Filters",model_path="services/service-com-amazonaws-ec2-amazonec2/smithy-model/com-amazonaws-ec2-amazonec2.json")
/// ```
///
/// `tag:<key>` is the one name with a variable part, so it is matched by prefix rather than
/// listed here. Every entry must be answered by [`filter_values`].
const CARRIER_GATEWAY_FILTERS: [&str; 5] = [
    "carrier-gateway-id",
    "owner-id",
    "state",
    "tag-key",
    "vpc-id",
];

/// The prefix of the tag filter: "Use the tag key in the filter name and the tag value as
/// the filter value" (`DescribeCarrierGatewaysRequest$Filters`).
const TAG_FILTER_PREFIX: &str = "tag:";

/// The name [`filter_values`] answers for the filter the request called `name`, or `None`
/// when this operation documents no such filter.
///
/// "Filter names are case-sensitive" (`Filter$Name`), so every comparison is exact — and a
/// `tag:` prefix with no key names no tag, so it is as undocumented as any other
/// misspelling. The `tag:<key>` family keeps its whole name, the key being part of what it
/// selects on.
fn canonical_filter_name(name: &str) -> Option<&str> {
    if name
        .strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
    {
        return Some(name);
    }
    CARRIER_GATEWAY_FILTERS.contains(&name).then_some(name)
}

/// The values the EC2 filter `name` compares against this carrier gateway.
///
/// A filter naming an attribute this gateway does not carry compares against NO values, so
/// it selects nothing rather than everything. `name` is a name [`canonical_filter_name`]
/// resolved.
fn filter_values<'a>(carrier_gateway: &'a CarrierGateway, name: &str) -> Vec<Cow<'a, str>> {
    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return carrier_gateway
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "carrier-gateway-id" => text(carrier_gateway.carrier_gateway_id.as_deref()),
        "owner-id" => text(carrier_gateway.owner_id.as_deref()),
        "state" => text(carrier_gateway.state.as_deref()),
        "tag-key" => carrier_gateway
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        "vpc-id" => text(carrier_gateway.vpc_id.as_deref()),
        // Unreachable: `canonical_filter_name` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even
        // if that check were bypassed.
        _ => Vec::new(),
    }
}
