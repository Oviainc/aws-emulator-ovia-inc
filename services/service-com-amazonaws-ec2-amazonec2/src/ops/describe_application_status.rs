const MAX_INSTANCES_PER_PAGE: usize = 100;

/// The filter names this operation documents, from
/// `DescribeApplicationStatusRequest$Filters`:
///
/// ```text
/// smithy_query(query="doc",shape="DescribeApplicationStatusRequest",member="Filters",model_path="services/service-com-amazonaws-ec2-amazonec2/smithy-model/com-amazonaws-ec2-amazonec2.json")
/// ```
///
/// It documents these two and no `tag:` family, so a tag filter is as undocumented here as
/// any other name — unlike `DescribeInstances`, whose own doc lists one. Every entry must
/// be answered by [`filter_values`].
const APPLICATION_STATUS_FILTERS: [&str; 2] = ["availability-zone-id", "status"];

/// The values the EC2 filter `name` compares against one instance's application status —
/// the per-operation half of [`crate::state::matches_every_filter`], which holds the
/// AND/OR evaluation every filtered describe of this crate shares.
///
/// A filter naming an attribute this row does not carry compares against NO values, so it
/// selects nothing — the answer for `availability-zone-id` on an instance in a zone no
/// Region of that name has. `name` is one of [`APPLICATION_STATUS_FILTERS`].
fn filter_values<'a>(
    status: &'a InstanceApplicationStatus,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "availability-zone-id" => text(status.availability_zone_id.as_deref()),
        // "`status` - The instance-level application status. For valid values and their
        // meanings, see `ApplicationStatus`" — the aggregated status, not a check's own.
        "status" => text(
            status
                .application_status
                .as_ref()
                .and_then(|application_status| application_status.status.as_deref()),
        ),
        // Unreachable: the handler has already refused every other name. An undefined name
        // compares against nothing, so it could never widen a result even if that check
        // were bypassed.
        _ => Vec::new(),
    }
}
