/// The values the EC2 filter `name` compares against this address usage.
///
/// A filter naming an attribute this usage does not carry compares against NO values, so it
/// selects nothing — the same answer AWS gives for any absent attribute. The AND/OR
/// evaluation of these values, and the budget that bounds it, live in
/// [`crate::state::matches_every_filter`], which every filtered read of this crate shares:
/// "If you specify multiple filters, the filters are joined with an AND" (`Filter`), and
/// within one filter "if you specify multiple values for a filter, the values are joined with
/// an OR" (`Filter$Values`).
fn filter_values<'a>(usage: &'a CoipAddressUsage, name: &str) -> Vec<Cow<'a, str>> {
    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "coip-address-usage.allocation-id" => text(usage.allocation_id.as_deref()),
        "coip-address-usage.aws-account-id" => text(usage.aws_account_id.as_deref()),
        "coip-address-usage.aws-service" => text(usage.aws_service.as_deref()),
        "coip-address-usage.co-ip" => text(usage.co_ip.as_deref()),
        // Unreachable: the handler has already refused every other name. An undefined name
        // compares against nothing, so it could never widen a result even if that check were
        // bypassed.
        _ => Vec::new(),
    }
}
