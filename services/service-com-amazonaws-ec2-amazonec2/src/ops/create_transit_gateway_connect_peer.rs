/// The one IPv4 block size an inside CIDR block may have (see [`INSIDE_CIDR_IPV4_RANGE`]).
const INSIDE_CIDR_IPV4_PREFIX: u32 = 29;

/// The range an optional IPv6 inside CIDR block must come from: "You can also optionally
