const INSIDE_CIDR_IPV6_RANGE: &str = "fd00::/8";

/// The one IPv6 block size an inside CIDR block may have (see [`INSIDE_CIDR_IPV6_RANGE`]).
const INSIDE_CIDR_IPV6_PREFIX: u32 = 125;

