        let name = modelled_catalog_word(
            entry.resource_type.as_deref(),
            IMAGE_USAGE_RESOURCE_TYPE_NAMES,
            "resourceType",
            None,
        )?
        .ok_or_else(|| {
            Scaffolded::missing_parameter("Each resource type of the report must name a type")
        })?;
