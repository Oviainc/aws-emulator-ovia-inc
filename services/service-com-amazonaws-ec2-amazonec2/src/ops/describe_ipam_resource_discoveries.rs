/// The filter names this operation resolves.
///
/// `DescribeIpamResourceDiscoveriesRequest$Filters` documents no list of its own — "The
/// resource discovery filters" is all of it
/// (`smithy_query(query="doc",shape="DescribeIpamResourceDiscoveriesRequest",member="Filters")`)
/// — so the names are the ones EC2's filtering convention gives: each member of the resource
/// the operation reports, spelled in kebab-case. This list is therefore derived mechanically
/// from the `IpamResourceDiscovery` shape
/// (`smithy_query(query="shape",shape="IpamResourceDiscovery")`), one entry per member — a
/// list of single-member structures contributing the singular name of what it holds, the way
/// `operating-region` names one `OperatingRegions` entry for `DescribeIpams` — plus the
/// `tag-key` / `tag-value` / `tag:<key>` set every EC2 describe accepts. Every entry must be
/// answered by [`filter_values`].
const IPAM_RESOURCE_DISCOVERY_FILTERS: [&str; 11] = [
    "description",
    "ipam-resource-discovery-arn",
    "ipam-resource-discovery-id",
    "ipam-resource-discovery-region",
    "is-default",
    "operating-region",
    "organizational-unit-exclusion",
    "owner-id",
    "state",
    "tag-key",
    "tag-value",
];

/// The prefix of the tag filter: "Use the tag key in the filter name and the tag value as
/// the filter value" (`IpamResourceDiscovery$Tags`).
const TAG_FILTER_PREFIX: &str = "tag:";

/// Is `name` a filter this operation resolves? "Filter names are case-sensitive"
/// (`Filter$Name`), so the comparison is exact — and a `tag:` prefix with no key names no
/// tag, so it is as unresolvable as any other misspelling.
fn is_documented_filter(name: &str) -> bool {
    name.strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
        || IPAM_RESOURCE_DISCOVERY_FILTERS.contains(&name)
}

/// The values the EC2 filter `name` compares against this resource discovery.
///
/// A filter naming an attribute this discovery does not carry compares against NO values, so
/// it selects nothing — the same answer AWS gives for, say, `description` on a discovery
/// created without one. A boolean is compared as the wire spells it, which is how a client
/// would send the filter value, so it is the only value built here rather than borrowed from
/// the record.
fn filter_values<'a>(
    discovery: &'a IpamResourceDiscovery,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return discovery
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "description" => text(discovery.description.as_deref()),
        "ipam-resource-discovery-arn" => text(discovery.ipam_resource_discovery_arn.as_deref()),
        "ipam-resource-discovery-id" => text(discovery.ipam_resource_discovery_id.as_deref()),
        "ipam-resource-discovery-region" => {
            text(discovery.ipam_resource_discovery_region.as_deref())
        }
        "is-default" => discovery
            .is_default
            .map(|default| Cow::Borrowed(if default { "true" } else { "false" }))
            .into_iter()
            .collect(),
        "operating-region" => discovery
            .operating_regions
            .iter()
            .flatten()
            .filter_map(|operating| operating.region_name.as_deref().map(Cow::Borrowed))
            .collect(),
        "organizational-unit-exclusion" => discovery
            .organizational_unit_exclusions
            .iter()
            .flatten()
            .filter_map(|exclusion| {
                exclusion
                    .organizations_entity_path
                    .as_deref()
                    .map(Cow::Borrowed)
            })
            .collect(),
        "owner-id" => text(discovery.owner_id.as_deref()),
        "state" => text(discovery.state.as_deref()),
        "tag-key" => discovery
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        "tag-value" => discovery
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect(),
        // Unreachable: `is_documented_filter` has already refused every other name. An
        // unresolvable name compares against nothing, so it could never widen a result even
        // if that check were bypassed.
        _ => Vec::new(),
    }
}

// The AND/OR evaluation of the whole `Filters` member is
// `crate::state::matches_every_filter`, the one place this crate defines it: "if you
// specify multiple filters, the filters are joined with an AND" (`Filter`), and within one
// filter "if you specify multiple values for a filter, the values are joined with an OR"
// (`Filter$Values`), each value matched case-sensitively with EC2's `*`/`?` wildcards and
// every comparison charged to the call's one `crate::state::MatchBudget`. Only the
// per-operation lookup differs, which is `filter_values` above.
