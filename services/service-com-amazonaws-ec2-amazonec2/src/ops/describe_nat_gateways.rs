        // leave a paging client in a loop that never advances.
        let limit = input
            .max_results
            .and_then(|max_results| usize::try_from(max_results).ok())
            .unwrap_or(DEFAULT_MAX_RESULTS)
            .max(MIN_MAX_RESULTS);

        // The page and the token that follows it, through the one definition of EC2 paging
        // ([`crate::state::page_from_cursor`]): the cursor names the gateway this page ends
        // at, and "this value is null when there are no more items to return"
        // (`DescribeNatGatewaysResult$NextToken`) is a token only while a further gateway
        // follows the page.
