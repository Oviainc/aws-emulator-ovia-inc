/// The tag filter whose values are the KEYS a gateway carries, rather than one key's value:
/// "the key of a tag assigned to the resource … regardless of the tag value"
/// (`DescribeNatGatewaysRequest$Filter`).
const TAG_KEY_FILTER: &str = "tag-key";

/// The values the EC2 filter `name` compares against this NAT gateway.
///
/// The arms below ARE the catalog this operation documents — `nat-gateway-id`, `state`,
/// `subnet-id`, `vpc-id`, `tag:<key>` and `tag-key`, from
/// `DescribeNatGatewaysRequest$Filter`:
///
/// ```text
/// smithy_query(query="doc",shape="DescribeNatGatewaysRequest",member="Filter",model_path="services/service-com-amazonaws-ec2-amazonec2/smithy-model/com-amazonaws-ec2-amazonec2.json")
/// ```
///
/// "Filter names are case-sensitive" (`Filter$Name`), so every comparison is exact. A name
/// outside the catalog, and a documented name naming an attribute this gateway does not
/// carry, both compare against NO values and so select nothing — the answer `subnet-id`
/// gives for a gateway stored without one.
fn filter_values<'a>(gateway: &'a NatGateway, name: &str) -> Vec<Cow<'a, str>> {
    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return gateway
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "nat-gateway-id" => text(gateway.nat_gateway_id.as_deref()),
        "state" => text(gateway.state.as_deref()),
        "subnet-id" => text(gateway.subnet_id.as_deref()),
        "vpc-id" => text(gateway.vpc_id.as_deref()),
        TAG_KEY_FILTER => gateway
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        // A name this operation documents no filter for: it names nothing about a NAT
        // gateway, so it compares against no value and can only narrow a result, never
        // widen one.
        _ => Vec::new(),
    }
}
