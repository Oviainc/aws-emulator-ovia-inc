        // attribute of a NAT gateway, so it compares against no value and selects no gateway
        // — the answer a NAT gateway read was recorded giving a name outside its catalog,
        // which is also what the matcher already does for an attribute a gateway carries
        // nothing for (see [`filter_values`]). What is bounded here is only the SIZE of the
        // comparison the request asks for.
