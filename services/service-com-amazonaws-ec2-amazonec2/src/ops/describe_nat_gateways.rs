        // specific NAT gateway IDs or filter the results" (`DescribeNatGateways`): the ids
        // named narrow the store, and then every filter must hold ("If you specify multiple
        // filters, the filters are joined with an AND" — `Filter`). A set, so narrowing costs
        // one lookup per gateway rather than a scan of the asked-for list.
        //
        // Every comparison is charged to ONE budget, so the product of stored gateways,
        // filters, values and value length is bounded however the caller combines them —
        // which is also what bounds how long this holds the store's lock.
        let wanted: HashSet<&str> = requested.iter().map(String::as_str).collect();
