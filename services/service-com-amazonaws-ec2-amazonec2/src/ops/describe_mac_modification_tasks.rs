/// The prefix of the `tag:<key>` filter family, from the crate's one definition of it
/// ([`crate::state::TAG_FILTER_PREFIX`]), so that spelling cannot drift between the
/// describes that answer the tag filter.
const TAG_FILTER_PREFIX: &str = crate::state::TAG_FILTER_PREFIX;

/// The filter names this operation answers.
///
/// The model documents five of its own — "`instance-id` - The ID of the instance for which
/// the task was created", "`task-state` - The state of the task",
/// "`mac-system-integrity-protection-configuration.sip-status` - The overall SIP state
/// requested in the task", "`start-time` - The date and time the task was created" and
/// "`task-type` - The type of task" (`DescribeMacModificationTasksRequest$Filters`) — and
/// `tag-key` beside them, the resource-wide tag filter EC2 documents for every taggable
/// resource ("List and filter using the CLI and API", linked from `Filter`), a Mac
/// modification task being one
/// (`CreateMacSystemIntegrityProtectionModificationTaskRequest$TagSpecifications`). Every
/// entry must be answered by [`filter_values`].
///
/// `tag:<key>` is the one name with a variable part, so it is matched by prefix rather than
/// listed here.
const MAC_MODIFICATION_TASK_FILTERS: [&str; 6] = [
    "instance-id",
    "mac-system-integrity-protection-configuration.sip-status",
    "start-time",
    "tag-key",
    "task-state",
    "task-type",
];

/// The name [`filter_values`] answers for the filter the request called `name`, or `None`
/// when this operation answers no such filter.
///
/// The `tag:<key>` prefix comes from the crate's one definition of it,
/// [`TAG_FILTER_PREFIX`], so that spelling cannot drift between the describes that answer
/// the tag filter. "Filter names and values are case-sensitive" (`Filter`), so every
/// comparison is exact — and a `tag:` prefix with no key names no tag, so it is as
/// undocumented as any other misspelling.
fn canonical_filter_name(name: &str) -> Option<&str> {
    if name
        .strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
    {
        return Some(name);
    }
    MAC_MODIFICATION_TASK_FILTERS
        .contains(&name)
        .then_some(name)
}

/// The values the EC2 filter `name` compares against this task.
///
/// A filter naming an attribute this task does not carry compares against NO values, so it
/// selects nothing: a volume ownership delegation task carries no SIP configuration ("[SIP
/// modification tasks only]", `MacModificationTask$MacSystemIntegrityProtectionConfig`), so
/// it matches no `sip-status` value. `name` is a name [`canonical_filter_name`] resolved.
fn filter_values<'a>(
    task: &'a MacModificationTask,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return task
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let text =
        |value: Option<&'a str>| -> Vec<Cow<'a, str>> { value.map(Cow::Borrowed).into_iter().collect() };
    match name {
        "instance-id" => text(task.instance_id.as_deref()),
        "mac-system-integrity-protection-configuration.sip-status" => text(
            task.mac_system_integrity_protection_config
                .as_ref()
                .and_then(|configuration| configuration.status.as_deref()),
        ),
        // The wire rendering of the instant, which is what a caller was shown.
        "start-time" => crate::state::filter_timestamp_values(task.start_time),
        "tag-key" => task
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        "task-state" => text(task.task_state.as_deref()),
        "task-type" => text(task.task_type.as_deref()),
        // Unreachable: `canonical_filter_name` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even if
        // that check were bypassed.
        _ => Vec::new(),
    }
}

