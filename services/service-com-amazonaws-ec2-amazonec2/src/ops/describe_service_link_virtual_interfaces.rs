/// The values the EC2 filter `name` compares against this service link virtual interface.
///
/// ONE rule picks what each name compares against: a filter whose name is an attribute THIS
/// resource carries a member for compares against that member, and only a filter naming an
/// attribute no member of this shape carries is read across an association. That is what
/// settles `state`, whose line reads "The  state of the Outpost LAG" while the resource being
/// described carries a state of its own (`ServiceLinkVirtualInterface$ConfigurationState`, "The
/// current state of the service link virtual interface") and the doc list demonstrably names
/// the wrong resource elsewhere ("vlan - The ID of the address pool", for the member documented
/// as "The virtual local area network for the service link virtual interface"): a `Filters` doc
/// describes what to narrow the DESCRIBED resource by, so `state` is this interface's own
/// configuration state — which is also the state `DescribeOutpostLags` selects a LAG by through
/// its interfaces, so the two operations read one value.
///
/// A filter naming an attribute this interface holds no value for compares against NO values,
/// so it selects nothing — the same answer AWS gives for any attribute a resource holds no
/// value for. The VLAN compares as the decimal text EC2 reports it as, every EC2 filter value
/// being a string.
///
/// `local-gateway-virtual-interface-id` is the one name this shape carries no member for, as
/// that filter's own wording says ("The ID of the local gateway virtual interface"): what a
/// service link virtual interface shares with one is the Outpost LAG they both run over, so it
/// compares against the ids of the local gateway virtual interfaces associated with THIS
/// interface's LAG
/// ([`crate::state::local_gateway_virtual_interface_ids_over_outpost_lag`], read against
/// `outpost_lags`) — an interface is selected when one of them matches, which is the same OR
/// every EC2 filter makes over the values one candidate holds. It is the mirror of the way
/// `DescribeOutpostLags` selects a LAG on its interfaces' own attributes.
fn filter_values<'a>(
    interface: &'a ServiceLinkVirtualInterface,
    outpost_lags: &'a ::std::collections::BTreeMap<String, OutpostLag>,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    let number = |value: Option<i32>| -> Vec<Cow<'a, str>> {
        value
            .map(|value| Cow::Owned(value.to_string()))
            .into_iter()
            .collect()
    };
    match name {
        "local-gateway-virtual-interface-id" => {
            crate::state::local_gateway_virtual_interface_ids_over_outpost_lag(
                outpost_lags,
                interface.outpost_lag_id.as_deref(),
            )
            .iter()
            .map(|id| Cow::Borrowed(id.as_str()))
            .collect()
        }
        "outpost-arn" => text(interface.outpost_arn.as_deref()),
        "outpost-lag-id" => text(interface.outpost_lag_id.as_deref()),
        "owner-id" => text(interface.owner_id.as_deref()),
        "service-link-virtual-interface-id" => {
            text(interface.service_link_virtual_interface_id.as_deref())
        }
        "state" => text(interface.configuration_state.as_deref()),
        "vlan" => number(interface.vlan),
        // Unreachable: the handler has already refused every other name. An undefined name
        // compares against nothing, so it could never widen a result even if that check were
        // bypassed.
        _ => Vec::new(),
    }
}

/// Does `interface` satisfy every filter?
///
/// The AND/OR evaluation EC2 defines for every `Filters` member, through the crate's one
/// implementation of it ([`crate::state::matches_every_filter`]): "If you specify multiple
/// filters, the filters are joined with an AND" (`Filter`), and within one filter "if you
/// specify multiple values for a filter, the values are joined with an OR" (`Filter$Values`) —
/// each value matched case-sensitively, with EC2's own `*`/`?` wildcards, by the pattern the
/// value was compiled into. So a filter carrying no value at all matches nothing, there being
/// no value for the attribute to match.
///
/// Every comparison, and the candidate itself, is charged to `budget`, so one request's
/// filtering cannot cost more than the ceiling however it combines filters, values and value
/// length.
fn matches_every_filter(
    interface: &ServiceLinkVirtualInterface,
    outpost_lags: &::std::collections::BTreeMap<String, OutpostLag>,
    selectors: &[crate::state::CompiledFilter],
    budget: &mut crate::state::MatchBudget,
) -> bool {
    crate::state::matches_every_filter(selectors, budget, &|name| {
        filter_values(interface, outpost_lags, name)
    })
}
