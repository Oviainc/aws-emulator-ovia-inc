/// Whether this operation documents the filter the request named.
///
/// The tag filter is the one name with a variable part — "use the tag key in the filter name
/// and the tag value as the filter value" (`DescribeNetworkAclsRequest$Filters`) — so it is
/// matched by [`TAG_FILTER_PREFIX`], the one spelling every describe of this crate reads a
/// tag filter by, and the key must not be empty: a `tag:` with no key names no tag.
///
/// "Filter names are case-sensitive" (`Filter$Name`), so every other comparison is exact.
fn filter_name_is_documented(name: &str) -> bool {
    name.strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
        || NETWORK_ACL_FILTERS.contains(&name)
}

/// The protocol keywords the `entry.protocol` filter publishes beside a protocol number —
/// "the protocol specified in the entry (`tcp` | `udp` | `icmp` or a protocol number)"
/// (`DescribeNetworkAclsRequest$Filters`) — paired with the IANA protocol number an entry
/// stores for each of them (`NetworkAclEntry$Protocol`: "The protocol number").
///
/// So an entry is selected by `entry.protocol` under either spelling of its protocol, which
/// is what lets the documented keywords select at all: the entry itself holds the number.
const PROTOCOL_KEYWORDS: [(&str, &str); 3] = [("1", "icmp"), ("6", "tcp"), ("17", "udp")];

/// The values the EC2 filter `name` compares against this network ACL.
///
/// A filter naming an attribute no part of this ACL carries compares against NO values, so
/// it selects nothing — the same answer AWS gives for, say, `entry.ipv6-cidr` on an ACL
/// whose entries are all IPv4. An `entry.…` or `association.…` filter compares against the
/// values of EVERY entry or association the ACL holds, so the ACL is selected when any one
/// of them matches, which is what "the ICMP type specified in the entry" asks of an ACL made
/// of many entries. `name` is a name the handler has already found documented.
///
/// The AND/OR evaluation of these values, and the budget that bounds it, live in
/// [`crate::state::matches_every_filter`], which every filtered describe of this crate
/// shares: "If you specify multiple filters, the filters are joined with an AND" (`Filter`),
/// and within one filter "if you specify multiple values for a filter, the values are joined
/// with an OR" (`Filter$Values`). So a filter carrying NO value matches nothing — one
/// reading of `Filter$Values`, shared with the sibling describes, rather than one this
/// operation invents for itself.
fn filter_values<'a>(network_acl: &'a NetworkAcl, name: &str) -> Vec<Cow<'a, str>> {
    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return network_acl
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let associations = || network_acl.associations.iter().flatten();
    let entries = || network_acl.entries.iter().flatten();
    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "association.association-id" => associations()
            .filter_map(|association| {
                association
                    .network_acl_association_id
                    .as_deref()
                    .map(Cow::Borrowed)
            })
            .collect(),
        "association.network-acl-id" => associations()
            .filter_map(|association| association.network_acl_id.as_deref().map(Cow::Borrowed))
            .collect(),
        "association.subnet-id" => associations()
            .filter_map(|association| association.subnet_id.as_deref().map(Cow::Borrowed))
            .collect(),
        "default" => boolean_filter_values(network_acl.is_default),
        "entry.cidr" => entries()
            .filter_map(|entry| entry.cidr_block.as_deref().map(Cow::Borrowed))
            .collect(),
        "entry.egress" => entries()
            .flat_map(|entry| boolean_filter_values(entry.egress))
            .collect(),
        "entry.icmp.code" => entries()
            .flat_map(|entry| {
                integer_filter_values(entry.icmp_type_code.as_ref().and_then(|icmp| icmp.code))
            })
            .collect(),
        "entry.icmp.type" => entries()
            .flat_map(|entry| {
                integer_filter_values(entry.icmp_type_code.as_ref().and_then(|icmp| icmp.r#type))
            })
            .collect(),
        "entry.ipv6-cidr" => entries()
            .filter_map(|entry| entry.ipv6_cidr_block.as_deref().map(Cow::Borrowed))
            .collect(),
        "entry.port-range.from" => entries()
            .flat_map(|entry| {
                integer_filter_values(entry.port_range.as_ref().and_then(|range| range.from))
            })
            .collect(),
        "entry.port-range.to" => entries()
            .flat_map(|entry| {
                integer_filter_values(entry.port_range.as_ref().and_then(|range| range.to))
            })
            .collect(),
        "entry.protocol" => entries().flat_map(protocol_filter_values).collect(),
        "entry.rule-action" => entries()
            .filter_map(|entry| entry.rule_action.as_deref().map(Cow::Borrowed))
            .collect(),
        "entry.rule-number" => entries()
            .flat_map(|entry| integer_filter_values(entry.rule_number))
            .collect(),
        "network-acl-id" => text(network_acl.network_acl_id.as_deref()),
        "owner-id" => text(network_acl.owner_id.as_deref()),
        "tag-key" => network_acl
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        "vpc-id" => text(network_acl.vpc_id.as_deref()),
        // Unreachable: the handler has already refused every other name. An undefined name
        // compares against nothing, so it could never widen a result even if that check
        // were bypassed.
        _ => Vec::new(),
    }
}

/// The values the `entry.protocol` filter compares against one entry: the protocol number
/// the entry holds, and the keyword [`PROTOCOL_KEYWORDS`] pairs with that number when the
/// filter publishes one for it.
fn protocol_filter_values(entry: &NetworkAclEntry) -> Vec<Cow<'_, str>> {
    let Some(protocol) = entry.protocol.as_deref() else {
        return Vec::new();
    };
    let mut values = vec![Cow::Borrowed(protocol)];
    values.extend(
        PROTOCOL_KEYWORDS
            .iter()
            .filter(|(number, _)| *number == protocol)
            .map(|(_, keyword)| Cow::Borrowed(*keyword)),
    );
    values
}
