/// The filter names this operation documents, from
/// `DescribeTransitGatewayConnectsRequest$Filters`:
///
/// ```text
/// smithy_query(query="doc",shape="DescribeTransitGatewayConnectsRequest",member="Filters",model_path="services/service-com-amazonaws-ec2-amazonec2/smithy-model/com-amazonaws-ec2-amazonec2.json")
/// ```
///
/// That member documents these five and NO tag filter, so a `tag:` name is as undocumented
/// here as any other misspelling. Every entry must be answered by [`filter_values`].
const CONNECT_FILTERS: [&str; 5] = [
    "options.protocol",
    "state",
    "transit-gateway-attachment-id",
    "transit-gateway-id",
    "transport-transit-gateway-attachment-id",
];

/// The values the EC2 filter `name` compares against this Connect attachment.
///
/// A filter naming an attribute this attachment does not carry compares against NO values, so
/// it selects nothing.
fn filter_values<'a>(attachment: &'a TransitGatewayConnect, name: &str) -> Vec<Cow<'a, str>> {
    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "options.protocol" => text(
            attachment
                .options
                .as_ref()
                .and_then(|options| options.protocol.as_deref()),
        ),
        "state" => text(attachment.state.as_deref()),
        "transit-gateway-attachment-id" => {
            text(attachment.transit_gateway_attachment_id.as_deref())
        }
        "transit-gateway-id" => text(attachment.transit_gateway_id.as_deref()),
        "transport-transit-gateway-attachment-id" => {
            text(attachment.transport_transit_gateway_attachment_id.as_deref())
        }
        // Unreachable: the filter loop has already refused every other name. An undefined
        // name compares against nothing, so it could never widen a result even if that check
        // were bypassed.
        _ => Vec::new(),
    }
}
