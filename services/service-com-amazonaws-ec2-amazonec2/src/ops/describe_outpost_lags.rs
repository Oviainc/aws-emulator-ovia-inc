/// The values the EC2 filter `name` compares against this Outpost LAG.
///
/// A filter naming a fact of the LAG itself — its id, the Outpost's ARN, the Outpost id that
/// ARN names ([`crate::state::outpost_id_of_arn`], the LAG shape carrying no member of its own
/// for it) or the owning account — compares against the LAG's own value. A filter naming an
/// attribute of a service link virtual interface compares against the values held by EVERY
/// interface associated with this LAG ("The service link virtual interface IDs associated with
/// the Outpost LAG" — `OutpostLag$ServiceLinkVirtualInterfaceIds`), looked up in
/// `interfaces`: a LAG is selected when one of its interfaces matches, which is the same OR
/// every EC2 filter makes over the values one candidate holds.
///
/// A filter naming an attribute nothing this LAG holds carries a value for compares against NO
/// values, so it selects nothing — the same answer AWS gives for any attribute a resource holds
/// no value for. A numeric attribute (`vlan`, `peer-bgp-asn`) compares as the decimal text EC2
/// reports it as, every EC2 filter value being a string.
fn filter_values<'a>(
    outpost_lag: &'a OutpostLag,
    interfaces: &'a ::std::collections::BTreeMap<String, ServiceLinkVirtualInterface>,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    // The interfaces associated with this LAG, in the order it lists them; an id the LAG lists
    // that this store holds no interface for contributes nothing.
    let associated = || -> Vec<&'a ServiceLinkVirtualInterface> {
        outpost_lag
            .service_link_virtual_interface_ids
            .as_deref()
            .unwrap_or_default()
            .iter()
            .filter_map(|interface_id| interfaces.get(interface_id))
            .collect()
    };
    let interface_text =
        |value: &dyn Fn(&'a ServiceLinkVirtualInterface) -> Option<&'a str>| -> Vec<Cow<'a, str>> {
            associated().into_iter().filter_map(value).map(Cow::Borrowed).collect()
        };
    let interface_number =
        |value: &dyn Fn(&'a ServiceLinkVirtualInterface) -> Option<i64>| -> Vec<Cow<'a, str>> {
            associated()
                .into_iter()
                .filter_map(value)
                .map(|number| Cow::Owned(number.to_string()))
                .collect()
        };
    match name {
        "outpost-lag-id" => text(outpost_lag.outpost_lag_id.as_deref()),
        "outpost-arn" => text(outpost_lag.outpost_arn.as_deref()),
        "outpost-id" => outpost_lag
            .outpost_arn
            .as_deref()
            .and_then(crate::state::outpost_id_of_arn)
            .map(Cow::Borrowed)
            .into_iter()
            .collect(),
        "owner-id" => text(outpost_lag.owner_id.as_deref()),
        "service-link-virtual-interface-id" => {
            interface_text(&|interface| interface.service_link_virtual_interface_id.as_deref())
        }
        "service-link-virtual-interface-arn" => {
            interface_text(&|interface| interface.service_link_virtual_interface_arn.as_deref())
        }
        "configuration-state" => {
            interface_text(&|interface| interface.configuration_state.as_deref())
        }
        "local-address" => interface_text(&|interface| interface.local_address.as_deref()),
        "peer-address" => interface_text(&|interface| interface.peer_address.as_deref()),
        "peer-bgp-asn" => interface_number(&|interface| interface.peer_bgp_asn),
        "vlan" => interface_number(&|interface| interface.vlan.map(i64::from)),
        // Unreachable: the handler has already refused every other name. An undefined name
        // compares against nothing, so it could never widen a result even if that check were
        // bypassed.
        _ => Vec::new(),
    }
}

/// Does `outpost_lag` satisfy every filter?
///
/// The AND/OR evaluation EC2 defines for every `Filters` member, through the crate's one
/// implementation of it ([`crate::state::matches_every_filter`]): "If you specify multiple
/// filters, the filters are joined with an AND" (`Filter`), and within one filter "if you
/// specify multiple values for a filter, the values are joined with an OR" (`Filter$Values`) —
/// each value matched case-sensitively, with EC2's own `*`/`?` wildcards, by the pattern the
/// value was compiled into. So a filter carrying no value at all matches nothing, there being
/// no value for the attribute to match.
///
/// Every comparison, and the candidate itself, is charged to `budget`, so one request's
/// filtering cannot cost more than the ceiling however it combines filters, values and value
/// length.
fn matches_every_filter(
    outpost_lag: &OutpostLag,
    interfaces: &::std::collections::BTreeMap<String, ServiceLinkVirtualInterface>,
    selectors: &[crate::state::CompiledFilter],
    budget: &mut crate::state::MatchBudget,
) -> bool {
    crate::state::matches_every_filter(selectors, budget, &|name| {
        filter_values(outpost_lag, interfaces, name)
    })
}
