    type Output = DescribeInstanceTypesOutput;
    type Error = DescribeInstanceTypesError;

    const NAME: &'static str = "DescribeInstanceTypes";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_INSTANCE_TYPES_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_INSTANCE_TYPES_OUTPUT_SCHEMA;
