            let Ok(canonical) = state::canonical_ipv6_cidr(prefix) else {
                return Err(state::invalid_parameter_value(format!(
                    "Value ({prefix}) for parameter ipv6Prefixes is invalid. \
                     This is not a valid IPv6 CIDR block."
                )));
            };
