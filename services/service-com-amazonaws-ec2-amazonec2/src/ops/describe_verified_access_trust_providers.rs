/// The name [`filter_values`] answers for the filter the request called `name`, or `None`
/// when this operation answers no such filter.
///
/// The `tag:<key>` prefix comes from the crate's one definition of it,
/// `crate::state::TAG_FILTER_PREFIX`, so that spelling cannot drift between the describes
/// that answer the tag filter.
///
/// "Filter names and values are case-sensitive"
/// (`DescribeVerifiedAccessTrustProvidersRequest$Filters`), so every comparison is exact —
/// and a `tag:` prefix with no key names no tag, so it is as undocumented as any other
/// misspelling. The `tag:<key>` family keeps its whole name, the key being part of what it
/// selects on.
fn canonical_filter_name(name: &str) -> Option<&str> {
    if name
        .strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
    {
        return Some(name);
    }
    TRUST_PROVIDER_FILTERS.contains(&name).then_some(name)
}

/// The values the EC2 filter `name` compares against this trust provider.
///
/// A filter naming an attribute this trust provider does not carry compares against NO
/// values, so it selects nothing — which is the answer for `user-trust-provider-type` on a
/// device-based provider, and for `device-trust-provider-type` on a user-based one.
/// `name` is a name [`canonical_filter_name`] resolved.
fn filter_values<'a>(
    provider: &'a VerifiedAccessTrustProvider,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return provider
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "creation-time" => text(provider.creation_time.as_deref()),
        "description" => text(provider.description.as_deref()),
        "device-trust-provider-type" => text(provider.device_trust_provider_type.as_deref()),
        "last-updated-time" => text(provider.last_updated_time.as_deref()),
        "policy-reference-name" => text(provider.policy_reference_name.as_deref()),
        "tag-key" => provider
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        "trust-provider-type" => text(provider.trust_provider_type.as_deref()),
        "user-trust-provider-type" => text(provider.user_trust_provider_type.as_deref()),
        "verified-access-trust-provider-id" => {
            text(provider.verified_access_trust_provider_id.as_deref())
        }
        // Unreachable: `canonical_filter_name` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even if
        // that check were bypassed.
        _ => Vec::new(),
    }
}
