//! @op DeleteArchive
//! Deletes one archive: the events it holds and the managed rule that fed it go
//! with it, and the name becomes free again.
//!
//! "Deletes the specified archive" (this operation's documentation): the archive
//! the `ArchiveName` names is removed from the store, so `DescribeArchive` no
//! longer reads it back, `ListArchives` no longer lists it, `PutEvents` captures
//! nothing into it and a `StartReplay` naming its ARN is refused. An archive is
//! served by a MANAGED rule on its source bus ([`crate::state::archive_rule`]),
//! which exists only for the archive, so the delete removes that rule too —
//! otherwise the bus would be left carrying a rule whose one target is an archive
//! nobody holds, and the bus could never be deleted.
//!
//! A REPLAY of this archive is NOT a reason to refuse: a replay re-publishes the
//! events it selected when it started, so one already in flight is unaffected by
//! the archive going away, and only a replay STARTED afterwards is refused — by
//! the event source resolving to nothing. A name this store holds no archive for
//! is the modelled `ResourceNotFoundException`, in the words every reader of an
//! archive uses ([`crate::state::no_such_archive`]).
//!
