/// Why the submitted authorization parameters do not match the authorization
/// type, or `None` when they do.
///
/// "You must include only authorization parameters for the AuthorizationType you
/// specify" (`CreateConnection$AuthParameters`), and each type has exactly one
/// member of `CreateConnectionAuthRequestParameters` that carries its
/// credentials: `API_KEY` -> `ApiKeyAuthParameters`, `BASIC` ->
/// `BasicAuthParameters`, `OAUTH_CLIENT_CREDENTIALS` -> `OAuthParameters`. The
/// refusal names the member and what was expected of it, the way this service's
/// other request-derived refusals do.
fn auth_parameters_violation(
    authorization_type: &str,
    parameters: &CreateConnectionAuthRequestParameters,
) -> Option<String> {
    // (the type, the member that carries its credentials, whether it is present)
    let supplied = [
        (
            API_KEY_AUTHORIZATION,
            "ApiKeyAuthParameters",
            parameters.api_key_auth_parameters.is_some(),
        ),
        (
            BASIC_AUTHORIZATION,
            "BasicAuthParameters",
            parameters.basic_auth_parameters.is_some(),
        ),
        (
            OAUTH_AUTHORIZATION,
            "OAuthParameters",
            parameters.o_auth_parameters.is_some(),
        ),
    ];
    for (kind, member, present) in supplied {
        if kind == authorization_type && !present {
            return Some(format!(
                "Parameter AuthParameters is not valid. Reason: {member} is required for \
                 AuthorizationType {kind}."
            ));
        }
        if kind != authorization_type && present {
            return Some(format!(
                "Parameter AuthParameters is not valid. Reason: {member} may only be \
                 provided for AuthorizationType {kind}."
            ));
        }
    }
    None
}

/// `ConnectionAuthorizationType`'s values, named so the rule above reads as the
/// documentation states it (`CONNECTION_AUTHORIZATION_TYPE_VALUES` is the list
/// the model carries).
const API_KEY_AUTHORIZATION: &str = "API_KEY";
const BASIC_AUTHORIZATION: &str = "BASIC";
const OAUTH_AUTHORIZATION: &str = "OAUTH_CLIENT_CREDENTIALS";

/// The authorization parameters as a READ reports them.
///
/// The response shape carries exactly the non-secret half of each request shape:
/// `ConnectionBasicAuthResponseParameters` has a `Username` and no password,
/// `ConnectionApiKeyAuthResponseParameters` an `ApiKeyName` and no value, and
/// `ConnectionOAuthClientResponseParameters` a `ClientID` and no secret. The
/// projection happens ONCE, here, so no secret the request carried is ever
/// stored on the record a read serializes.
fn reported_auth_parameters(
    parameters: &CreateConnectionAuthRequestParameters,
) -> ConnectionAuthResponseParameters {
    ConnectionAuthResponseParameters {
        basic_auth_parameters: parameters.basic_auth_parameters.as_ref().map(|basic| {
            ConnectionBasicAuthResponseParameters {
                username: Some(basic.username.clone()),
            }
        }),
        o_auth_parameters: parameters.o_auth_parameters.as_ref().map(|oauth| {
            ConnectionOAuthResponseParameters {
                client_parameters: Some(ConnectionOAuthClientResponseParameters {
                    client_id: Some(oauth.client_parameters.client_id.clone()),
                }),
                authorization_endpoint: Some(oauth.authorization_endpoint.clone()),
                http_method: Some(oauth.http_method.clone()),
                // The HTTP parameters of the OAuth exchange are reported back as
                // they were given: each of their values carries its own
                // `IsValueSecret` flag, which is the request's own statement
                // about it.
                o_auth_http_parameters: oauth.o_auth_http_parameters.clone(),
            }
        }),
        api_key_auth_parameters: parameters.api_key_auth_parameters.as_ref().map(|key| {
            ConnectionApiKeyAuthResponseParameters {
                api_key_name: Some(key.api_key_name.clone()),
            }
        }),
        invocation_http_parameters: parameters.invocation_http_parameters.clone(),
        // The connectivity parameters a read reports carry the ARN of the
        // resource ASSOCIATION EventBridge made with the resource configuration,
        // beside the configuration's own ARN. This emulator makes no such
        // association, so there is none to name and none is reported — the
        // configuration the request named is kept on the record
        // (`ConnectionRecord::invocation_resource_configuration_arn`) for when
        // the private-connectivity path is implemented.
        connectivity_parameters: None,
    }
}
