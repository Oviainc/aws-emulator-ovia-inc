//! @op DeleteMatchingWorkflow
//! Removes the stored matching workflow, so a later `GetMatchingWorkflow` answers
//! `ResourceNotFoundException` and `ListMatchingWorkflows` no longer reaches it, and
//! the schema mappings it referenced report `hasWorkflows` false again.
//!
