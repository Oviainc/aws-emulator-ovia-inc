//! End-to-end cover for the ONE rule the whole recommendation surface obeys on
//! `createdAt`, driven over HTTP through the same `MultiServiceRouter` the
//! emulator serves with:
//!
//! * **a response member the model scopes to a recommendation created by
//!   Trusted Advisor Priority is reported only for a recommendation whose
//!   `type` is the prioritized one, and is absent for a recommendation the
//!   service produced automatically** — so `createdAt` is present exactly when
//!   `type` is `priority`, on the single read and on the listing alike, while
//!   `lastUpdatedAt`, which carries no such scoping, is reported for either
//!   type;
//! * the presence follows the recommendation's `type`, not the row: the same
//!   stored creation instant is reported or withheld as that type changes;
//! * every organization recommendation is a prioritized one, so the
//!   organization surface goes on reporting a creation instant for all of them.
//!
//! The model is the source of both halves —
//! `smithy_query(query="doc",shape="Recommendation",member="createdAt")`: "When
//! the Recommendation was created, if created by AWS Trusted Advisor Priority",
//! the same sentence on `RecommendationSummary$createdAt`,
//! `OrganizationRecommendation$createdAt` and
//! `OrganizationRecommendationSummary$createdAt`, against
//! `Recommendation$type`, "Whether the Recommendation was automated or
//! generated by AWS Trusted Advisor Priority". `lastUpdatedAt` is modelled
//! "When the Recommendation was last updated", with no condition on it.
//!
//! Every table below spans both values `RecommendationType` declares (their
//! source is `RECOMMENDATION_TYPE_VALUES` in `ops::types`) and several creation
//! instants, so the assertions are about the rule rather than about one stored
//! row.
//!
//! Every call is made as an account whose support plan includes the Trusted
//! Advisor API; the gate ahead of every handler is pinned in
//! `tests/all/support_level_gate.rs`.

use serde_json::Value;
use service_com_amazonaws_trustedadvisor_trustedadvisor::ops::types::RECOMMENDATION_TYPE_VALUES;
use service_com_amazonaws_trustedadvisor_trustedadvisor::state::{
    check_arn, service_state, LocalizedText, RecommendationEntry, SupportPlan, TextCatalog,
    RECOMMENDATION_TYPE_PRIORITY,
};
use smithy_server_runtime::MultiServiceRouter;

use crate::organization_recommendation_lifecycle::organization_recommendation_arn;
use crate::recommendation_loop::{
    call, emulator_on_plan, label, recommendation_arn, timestamp_secs, PRIORITIZED_CHECK_IDS,
    STANDARD_CHECK_IDS,
};

/// One recommendation this suite writes into the store: the id it is keyed by,
/// the `RecommendationType` it carries and the instant it was created at.
///
/// Trusted Advisor models no operation that creates a recommendation, so a
/// recommendation other than a seeded one can only arrive from outside the API —
/// written straight into the store the way the seed is.
struct Written {
    id: &'static str,
    kind: &'static str,
    created_at_millis: i64,
}

/// Recommendations spanning the class the rule generalises over: both values of
/// `RecommendationType` (`RECOMMENDATION_TYPE_VALUES`), each with creation
/// instants that differ in size and sign — the Unix epoch itself, an instant
/// before it, one with a non-zero millisecond part, and one far in the future —
/// and the SAME instant carried by one recommendation of each type, which is
/// the pair that shows the member's presence is decided by the type and not by
/// the value.
const WRITTEN: &[Written] = &[
    Written {
        id: "written-priority-at-the-epoch",
        kind: "priority",
        created_at_millis: 0,
    },
    Written {
        id: "written-standard-at-the-epoch",
        kind: "standard",
        created_at_millis: 0,
    },
    Written {
        id: "written-priority-before-the-epoch",
        kind: "priority",
        created_at_millis: -86_400_000,
    },
    Written {
        id: "written-standard-before-the-epoch",
        kind: "standard",
        created_at_millis: -86_400_000,
    },
    Written {
        id: "written-priority-with-millis",
        kind: "priority",
        created_at_millis: 1_735_689_600_123,
    },
    Written {
        id: "written-standard-with-millis",
        kind: "standard",
        created_at_millis: 1_735_689_600_123,
    },
    Written {
        id: "written-priority-far-in-the-future",
        kind: "priority",
        created_at_millis: 4_102_444_800_000,
    },
    Written {
        id: "written-standard-far-in-the-future",
        kind: "standard",
        created_at_millis: 4_102_444_800_000,
    },
];

/// `arn:aws:trustedadvisor::<account>:recommendation/<id>` — the ARN pattern
/// `AccountRecommendationArn` declares.
fn arn_of(recommendation_id: &str) -> String {
    format!(
        "arn:aws:trustedadvisor::{}:recommendation/{recommendation_id}",
        engine::EMULATOR_ACCOUNT_ID
    )
}

/// A mounted emulator on an entitled plan whose store also holds [`WRITTEN`],
/// together with the engine it was built on so a test can move a stored
/// recommendation's `type` the way something outside the API would (Trusted
/// Advisor models no operation that does).
fn emulator_and_engine() -> (MultiServiceRouter, std::sync::Arc<engine::InMemoryEngine>) {
    let (router, engine) = emulator_on_plan(SupportPlan::Business);
    {
        let state = service_state(&*engine).expect("the engine carries this service's state");
        let mut state = state.lock();
        for row in WRITTEN {
            let arn = arn_of(row.id);
            state.recommendations.insert(
                arn.clone(),
                RecommendationEntry {
                    id: row.id.to_string(),
                    arn,
                    text: TextCatalog::new(
                        LocalizedText {
                            name: format!("Finding {}", row.id),
                            description: format!("A {} recommendation of this account.", row.kind),
                        },
                        std::iter::empty(),
                    ),
                    check_arn: Some(check_arn(row.id)),
                    r#type: row.kind.to_string(),
                    status: "ok".to_string(),
                    lifecycle_stage: None,
                    pillars: vec!["cost_optimizing".to_string()],
                    source: "ta_check".to_string(),
                    aws_services: vec!["ec2".to_string()],
                    created_at_millis: row.created_at_millis,
                    // A stated instant of its own, so a row's `lastUpdatedAt`
                    // is never its `createdAt` by accident.
                    last_updated_at_millis: row.created_at_millis + 1_000,
                    resolved_at_millis: None,
                    update_reason: None,
                    update_reason_code: None,
                },
            );
        }
    }
    (router, engine)
}

/// A mounted emulator on an entitled plan whose store also holds [`WRITTEN`].
fn emulator() -> MultiServiceRouter {
    emulator_and_engine().0
}

/// Record `kind` as the `RecommendationType` of the stored recommendation `arn`,
/// leaving every other member of it — its creation instant in particular —
/// exactly as it was.
fn set_type(engine: &engine::InMemoryEngine, arn: &str, kind: &str) {
    let state = service_state(engine).expect("the engine carries this service's state");
    let mut state = state.lock();
    let entry = state
        .recommendations
        .get_mut(arn)
        .unwrap_or_else(|| panic!("the store holds the recommendation {arn}"));
    entry.r#type = kind.to_string();
}

/// Every recommendation the store holds for this suite, as (case name, ARN,
/// `RecommendationType`): the seeded prioritized and standard ones (their
/// source is the `SEED` table in `src/state.rs`, shared through
/// `PRIORITIZED_CHECK_IDS` / `STANDARD_CHECK_IDS`) and the written rows above.
fn cases() -> Vec<(String, String, &'static str)> {
    let seeded = PRIORITIZED_CHECK_IDS
        .iter()
        .map(|check| (*check, RECOMMENDATION_TYPE_PRIORITY))
        .chain(STANDARD_CHECK_IDS.iter().map(|check| (*check, "standard")))
        .map(|(check, kind)| (format!("seeded {check}"), recommendation_arn(check), kind));
    let written = WRITTEN
        .iter()
        .map(|row| (format!("written {}", row.id), arn_of(row.id), row.kind));
    seeded.chain(written).collect()
}

/// `GET /v1/recommendations/{identifier}`, asserting 200 and reporting the
/// `Recommendation` it answered with.
async fn get_recommendation(router: &MultiServiceRouter, case: &str, arn: &str) -> Value {
    let (status, body) = call(
        router,
        "GET",
        &format!("/v1/recommendations/{}", label(arn)),
        None,
    )
    .await;
    assert_eq!(
        status, 200,
        "case {case}: expected 200 from GetRecommendation, got {status} with {body}"
    );
    body["recommendation"].clone()
}

/// What this suite asserts about one reported recommendation or summary: a
/// creation instant exactly when its `type` is the prioritized one, and a
/// `lastUpdatedAt` either way.
fn assert_scoped(case: &str, reported: &Value, kind: &str) {
    let created = &reported["createdAt"];
    if kind == RECOMMENDATION_TYPE_PRIORITY {
        assert!(
            !created.is_null(),
            "case {case}: expected a createdAt on a {kind} recommendation, got {reported}"
        );
    } else {
        assert_eq!(
            *created,
            Value::Null,
            "case {case}: expected no createdAt on a {kind} recommendation, got {created:?}"
        );
    }
    assert!(
        !reported["lastUpdatedAt"].is_null(),
        "case {case}: expected a lastUpdatedAt on a {kind} recommendation, got {reported}"
    );
}

#[tokio::test]
async fn a_single_read_reports_a_creation_instant_only_for_a_prioritized_recommendation() {
    let router = emulator();

    for (case, arn, kind) in cases() {
        let reported = get_recommendation(&router, &case, &arn).await;
        assert_eq!(
            reported["type"].as_str(),
            Some(kind),
            "case {case}: expected type {kind}, got {:?}",
            reported["type"]
        );
        assert_scoped(&case, &reported, kind);
    }
}

#[tokio::test]
async fn the_reported_creation_instant_is_the_stored_one() {
    let router = emulator();

    // The rows that carry one: stated instants, so the reported value is
    // compared against a number this suite names rather than against the store
    // it came from.
    for row in WRITTEN
        .iter()
        .filter(|row| row.kind == RECOMMENDATION_TYPE_PRIORITY)
    {
        let case = row.id;
        let reported = get_recommendation(&router, case, &arn_of(row.id)).await;
        let expected = row.created_at_millis as f64 / 1_000.0;
        let got = timestamp_secs(&reported["createdAt"]);
        assert!(
            (got - expected).abs() < 0.001,
            "case {case}: expected createdAt {expected} seconds, got {got}"
        );
    }
}

#[tokio::test]
async fn the_listing_scopes_the_member_the_same_way_the_single_read_does() {
    let router = emulator();

    // Rows differ along the `type` filter: absent (every stored
    // recommendation), and each value `RecommendationType` declares.
    let mut queries: Vec<String> = vec![String::new()];
    queries.extend(
        RECOMMENDATION_TYPE_VALUES
            .iter()
            .map(|kind| format!("&type={kind}")),
    );

    for query in queries {
        let (status, body) = call(
            &router,
            "GET",
            &format!("/v1/recommendations?maxResults=200{query}"),
            None,
        )
        .await;
        assert_eq!(
            status, 200,
            "case {query:?}: expected 200 from ListRecommendations, got {status} with {body}"
        );
        let summaries = body["recommendationSummaries"]
            .as_array()
            .unwrap_or_else(|| panic!("case {query:?}: response has no summaries: {body}"))
            .clone();
        assert!(
            !summaries.is_empty(),
            "case {query:?}: expected the listing to report summaries, got {body}"
        );
        for summary in &summaries {
            let arn = summary["arn"].as_str().unwrap_or_default();
            let kind = summary["type"]
                .as_str()
                .unwrap_or_else(|| panic!("case {query:?}: summary has no type: {summary}"));
            let case = format!("summary {arn} ({kind}) of {query:?}");
            assert_scoped(&case, summary, kind);

            // The listing and the single read of one recommendation agree on
            // the member, so neither surface carries its own rule.
            let read = get_recommendation(&router, &case, arn).await;
            assert_eq!(
                read["createdAt"], summary["createdAt"],
                "case {case}: expected the single read's createdAt {:?} to equal the summary's \
                 {:?}",
                read["createdAt"], summary["createdAt"]
            );
        }
    }
}

#[tokio::test]
async fn the_members_presence_follows_the_type_and_not_the_stored_instant() {
    let (router, engine) = emulator_and_engine();

    // ONE recommendation, read once per `RecommendationType` value with its
    // stored creation instant untouched: the member appears and disappears with
    // the type alone.
    let arn = recommendation_arn(STANDARD_CHECK_IDS[0]);

    for kind in RECOMMENDATION_TYPE_VALUES {
        set_type(&engine, &arn, kind);
        let case = format!("{arn} as {kind}");
        let reported = get_recommendation(&router, &case, &arn).await;
        assert_eq!(
            reported["type"].as_str(),
            Some(*kind),
            "case {case}: expected type {kind}, got {:?}",
            reported["type"]
        );
        assert_scoped(&case, &reported, kind);
    }
}

#[tokio::test]
async fn every_organization_recommendation_reports_its_creation_instant() {
    let router = emulator();

    // The store holds an organization recommendation only for a prioritized
    // recommendation, so the rule withholds nothing on that surface: the single
    // read and the listing both report a creation instant for every one of
    // them.
    for check_id in PRIORITIZED_CHECK_IDS {
        let case = format!("organization recommendation of {check_id}");
        let arn = organization_recommendation_arn(check_id);
        let (status, body) = call(
            &router,
            "GET",
            &format!("/v1/organization-recommendations/{}", label(&arn)),
            None,
        )
        .await;
        assert_eq!(
            status, 200,
            "case {case}: expected 200, got {status} with {body}"
        );
        assert_scoped(
            &case,
            &body["organizationRecommendation"],
            RECOMMENDATION_TYPE_PRIORITY,
        );
    }

    let (status, body) = call(
        &router,
        "GET",
        "/v1/organization-recommendations?maxResults=200",
        None,
    )
    .await;
    assert_eq!(status, 200, "expected 200, got {status} with {body}");
    let summaries = body["organizationRecommendationSummaries"]
        .as_array()
        .unwrap_or_else(|| panic!("response has no organization summaries: {body}"))
        .clone();
    assert_eq!(
        summaries.len(),
        PRIORITIZED_CHECK_IDS.len(),
        "expected one summary per prioritized check, got {body}"
    );
    for summary in &summaries {
        let case = format!("organization summary {}", summary["arn"]);
        assert_scoped(&case, summary, RECOMMENDATION_TYPE_PRIORITY);
    }
}
