//! End-to-end cover for the ONE rule the whole ORGANIZATION surface of this
//! service obeys, driven over HTTP through the same `MultiServiceRouter` the
//! emulator serves with:
//!
//! * **an organization recommendation exists only for a PRIORITIZED
//!   recommendation, so every organization operation serves the prioritized
//!   recommendations and nothing else** — `ListOrganizationRecommendations`
//!   reports exactly those (and `?type=standard` selects none of them), and
//!   `GetOrganizationRecommendation`,
//!   `ListOrganizationRecommendationResources`,
//!   `ListOrganizationRecommendationAccounts` and
//!   `UpdateOrganizationRecommendationLifecycle` answer 404
//!   `ResourceNotFoundException` for the organization-recommendation identifier
//!   a non-prioritized check would have had;
//! * the rule is about the ORGANIZATION surface only: the account-level
//!   `GetRecommendation` and `ListRecommendations` go on serving the same
//!   checks' standard recommendations.
//!
//! Each of the five organization operations carries the same model sentence —
//! "This API only supports prioritized recommendations"
//! (`smithy_query(query="doc",shape="ListOrganizationRecommendations")` and the
//! same for `GetOrganizationRecommendation`,
//! `ListOrganizationRecommendationResources`,
//! `ListOrganizationRecommendationAccounts` and
//! `UpdateOrganizationRecommendationLifecycle`) — and
//! `OrganizationRecommendation$type` is documented "Whether the Recommendation
//! was automated or generated by AWS Trusted Advisor Priority", so a
//! recommendation the service produced automatically has no organization-level
//! resource at all. The statuses and error codes come from the same model:
//! those operations bind `ResourceNotFoundException` 404.
//!
//! The rows below are every seeded check with its recommendation's `type`,
//! written out by hand; their source is the `SEED` table in `src/state.rs`.
//!
//! Every call is made as an account whose support plan includes the Trusted
//! Advisor API; the gate ahead of every handler is pinned in
//! `tests/all/support_level_gate.rs`.

use serde_json::json;
use service_com_amazonaws_trustedadvisor_trustedadvisor::ops::types::UPDATE_RECOMMENDATION_LIFECYCLE_STAGE_VALUES;
use service_com_amazonaws_trustedadvisor_trustedadvisor::state::SupportPlan;
use smithy_server_runtime::MultiServiceRouter;

use crate::organization_recommendation_lifecycle::organization_recommendation_arn;
use crate::recommendation_loop::{
    call, check_arn, emulator_on_plan, error_code, field_of_each, label, recommendation_arn,
    CHECK_IDS, PRIORITIZED_CHECK_IDS, STANDARD_CHECK_IDS,
};

/// The `RecommendationType` value the organization surface is documented to
/// support, and the other value `RecommendationType` declares.
const PRIORITY: &str = "priority";
const STANDARD: &str = "standard";

/// An emulator whose account is entitled to the API.
fn emulator() -> MultiServiceRouter {
    emulator_on_plan(SupportPlan::Business).0
}

/// Every seeded check with the `type` of the recommendation it produced: the
/// rows differ along that type, which is what decides whether the check has an
/// organization recommendation at all.
fn rows() -> Vec<(&'static str, &'static str)> {
    let rows: Vec<(&str, &str)> = PRIORITIZED_CHECK_IDS
        .iter()
        .map(|check| (*check, PRIORITY))
        .chain(STANDARD_CHECK_IDS.iter().map(|check| (*check, STANDARD)))
        .collect();
    // The two halves together are the whole catalog, so no seeded check is left
    // out of the table.
    let mut covered: Vec<&str> = rows.iter().map(|(check, _)| *check).collect();
    covered.sort_unstable();
    assert_eq!(
        covered,
        CHECK_IDS.to_vec(),
        "the table must cover every seeded check, got {covered:?}"
    );
    rows
}

/// The organization-recommendation ARNs of the prioritized checks, in the ARN
/// order every organization list pages in.
fn prioritized_arns() -> Vec<String> {
    let mut arns: Vec<String> = PRIORITIZED_CHECK_IDS
        .iter()
        .map(|check| organization_recommendation_arn(check))
        .collect();
    arns.sort();
    arns
}

/// The ARNs `ListOrganizationRecommendations` reports for `query`, asserting
/// 200 first.
async fn list_arns(router: &MultiServiceRouter, query: &str) -> Vec<String> {
    let (status, body) = call(
        router,
        "GET",
        &format!("/v1/organization-recommendations{query}"),
        None,
    )
    .await;
    assert_eq!(
        status, 200,
        "case {query:?}: expected 200, got {status} with {body}"
    );
    field_of_each(&body, "organizationRecommendationSummaries", "arn")
}

#[tokio::test]
async fn the_organization_list_reports_the_prioritized_recommendations_only() {
    let router = emulator();
    let prioritized = prioritized_arns();

    // Rows differ along the `type` filter: absent (every stored entry), the
    // supported value, and the value no organization recommendation can carry.
    let cases: &[(&str, &[String])] = &[
        ("", &prioritized),
        ("?type=priority", &prioritized),
        ("?type=standard", &[]),
    ];
    for (query, expected) in cases {
        let arns = list_arns(&router, query).await;
        assert_eq!(
            arns,
            expected.to_vec(),
            "case {query:?}: expected {expected:?}, got {arns:?}"
        );
    }

    // Whatever the filters, every summary the list reports carries the one type
    // the organization surface supports.
    let (status, body) = call(
        &router,
        "GET",
        "/v1/organization-recommendations?maxResults=200",
        None,
    )
    .await;
    assert_eq!(status, 200, "expected 200, got {status} with {body}");
    let types = field_of_each(&body, "organizationRecommendationSummaries", "type");
    assert!(
        !types.is_empty() && types.iter().all(|kind| kind == PRIORITY),
        "case every summary: expected every reported type to be {PRIORITY}, got {types:?}"
    );

    // And `checkIdentifier` selects one organization recommendation for a
    // prioritized check and none for a check whose recommendation is standard.
    for (check_id, kind) in rows() {
        let query = format!("?checkIdentifier={}", label(&check_arn(check_id)));
        let arns = list_arns(&router, &query).await;
        let expected: Vec<String> = if kind == PRIORITY {
            vec![organization_recommendation_arn(check_id)]
        } else {
            Vec::new()
        };
        assert_eq!(
            arns, expected,
            "case checkIdentifier={check_id} ({kind}): expected {expected:?}, got {arns:?}"
        );
    }
}

#[tokio::test]
async fn every_organization_read_serves_a_prioritized_recommendation_and_no_other() {
    let router = emulator();

    // Every organization operation that takes an organization-recommendation
    // identifier: the single read, the two member lists, and the lifecycle
    // write, which is the one path that already enforced the rule.
    let operations: &[(&str, &str, &str)] = &[
        (
            "GetOrganizationRecommendation",
            "GET",
            "/v1/organization-recommendations/{}",
        ),
        (
            "ListOrganizationRecommendationAccounts",
            "GET",
            "/v1/organization-recommendations/{}/accounts",
        ),
        (
            "ListOrganizationRecommendationResources",
            "GET",
            "/v1/organization-recommendations/{}/resources",
        ),
        (
            "UpdateOrganizationRecommendationLifecycle",
            "PUT",
            "/v1/organization-recommendations/{}/lifecycle",
        ),
    ];
    let update = json!({
        "lifecycleStage": "in_progress",
        "updateReason": "working the finding across the organization",
        "updateReasonCode": "other",
    });

    for (check_id, kind) in rows() {
        let arn = organization_recommendation_arn(check_id);
        for (operation, method, template) in operations {
            let case = format!("{operation} on the {kind} {check_id}");
            let path = template.replace("{}", &label(&arn));
            let payload = (*method == "PUT").then(|| update.clone());
            let (status, body) = call(&router, method, &path, payload).await;

            if kind == PRIORITY {
                assert_eq!(
                    status, 200,
                    "case {case}: expected 200, got {status} with {body}"
                );
                continue;
            }

            assert_eq!(
                status, 404,
                "case {case}: expected 404 for an identifier no prioritized recommendation \
                 owns, got {status} with {body}"
            );
            assert_eq!(
                error_code(&body),
                "ResourceNotFoundException",
                "case {case}: expected ResourceNotFoundException, got {body}"
            );
            assert!(
                body["message"]
                    .as_str()
                    .is_some_and(|message| message.contains(&arn)),
                "case {case}: expected the message to name {arn}, got {body}"
            );
        }
    }
}

#[tokio::test]
async fn a_prioritized_organization_recommendation_reports_the_supported_type() {
    let router = emulator();

    for check_id in PRIORITIZED_CHECK_IDS {
        let case = *check_id;
        let (status, body) = call(
            &router,
            "GET",
            &format!(
                "/v1/organization-recommendations/{}",
                label(&organization_recommendation_arn(check_id))
            ),
            None,
        )
        .await;
        assert_eq!(
            status, 200,
            "case {case}: expected 200, got {status} with {body}"
        );
        let reported = body["organizationRecommendation"]["type"].as_str();
        assert_eq!(
            reported,
            Some(PRIORITY),
            "case {case}: expected type {PRIORITY}, got {reported:?}"
        );
    }
}

#[tokio::test]
async fn the_lifecycle_of_a_standard_check_cannot_be_moved_at_the_organization_level() {
    let router = emulator();

    // Rows differ along the requested stage — every
    // `UpdateRecommendationLifecycleStage` the model declares — so the refusal
    // is about the identifier naming no prioritized recommendation and not
    // about one stage.
    for check_id in STANDARD_CHECK_IDS {
        for stage in UPDATE_RECOMMENDATION_LIFECYCLE_STAGE_VALUES {
            let case = format!("{check_id}/{stage}");
            let (status, body) = call(
                &router,
                "PUT",
                &format!(
                    "/v1/organization-recommendations/{}/lifecycle",
                    label(&organization_recommendation_arn(check_id))
                ),
                Some(json!({
                    "lifecycleStage": stage,
                    "updateReason": "not a prioritized recommendation",
                    "updateReasonCode": "not_applicable",
                })),
            )
            .await;
            assert_eq!(
                status, 404,
                "case {case}: expected 404, got {status} with {body}"
            );
            assert_eq!(
                error_code(&body),
                "ResourceNotFoundException",
                "case {case}: expected ResourceNotFoundException, got {body}"
            );
        }
    }
}

#[tokio::test]
async fn the_account_level_surface_still_serves_the_standard_recommendations() {
    let router = emulator();

    // The rule is confined to the organization operations: the account-level
    // read of the same check reports its recommendation, with the `type` the
    // check produced.
    for (check_id, kind) in rows() {
        let case = format!("{check_id} ({kind})");
        let (status, body) = call(
            &router,
            "GET",
            &format!(
                "/v1/recommendations/{}",
                label(&recommendation_arn(check_id))
            ),
            None,
        )
        .await;
        assert_eq!(
            status, 200,
            "case {case}: expected 200 from GetRecommendation, got {status} with {body}"
        );
        assert_eq!(
            body["recommendation"]["type"].as_str(),
            Some(kind),
            "case {case}: expected type {kind}, got {:?}",
            body["recommendation"]["type"]
        );
    }

    // And the account-level list still cuts on `type`, both halves of it.
    for (kind, expected_checks) in [(PRIORITY, PRIORITIZED_CHECK_IDS), (STANDARD, STANDARD_CHECK_IDS)]
    {
        let (status, body) = call(
            &router,
            "GET",
            &format!("/v1/recommendations?type={kind}"),
            None,
        )
        .await;
        assert_eq!(
            status, 200,
            "case ?type={kind}: expected 200, got {status} with {body}"
        );
        let arns = field_of_each(&body, "recommendationSummaries", "arn");
        let mut expected: Vec<String> = expected_checks
            .iter()
            .map(|check| recommendation_arn(check))
            .collect();
        expected.sort();
        assert_eq!(
            arns, expected,
            "case ?type={kind}: expected {expected:?}, got {arns:?}"
        );
    }
}
