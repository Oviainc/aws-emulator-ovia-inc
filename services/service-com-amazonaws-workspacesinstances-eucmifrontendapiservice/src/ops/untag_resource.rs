    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UNTAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // A regional resource is mutable only through the Region it was created in,
        // which travels in the request's credential scope.
        let region = crate::state::request_region(ctx.parts());
        // A key in the reserved `aws:` namespace names a tag AWS generates, not one a
        // caller may set OR take away, so the request is refused BEFORE the store is
        // reached: the resource's tag set is left exactly as it was, including under
        // the ordinary keys the same request named.
        crate::state::reject_reserved_tag_keys("TagKeys", input.tag_keys.iter().map(String::as_str))
            .map_err(UntagResourceErrorModeled::ValidationException)?;

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(UntagResourceErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the WorkSpaces Instances store is unavailable".to_string(),
                    retry_after_seconds: None,
                },
            )
            .into());
        };
        let mut state = state.lock();

        // The same clock-due settle, and the same Region scope, every other
        // single-instance operation looks a record up through: an instance of another
        // Region, or one whose teardown retention has elapsed, is not here to untag.
        let Some(record) = state.settled_mut(
            &region,
            &input.workspace_instance_id,
            std::time::Instant::now(),
        ) else {
            return Err(crate::state::instance_not_found_error(
                &input.workspace_instance_id,
                UntagResourceErrorModeled::ResourceNotFoundException,
            ));
        };

        // Untagging is REMOVAL BY KEY from what is stored, so it is idempotent: a key
        // the resource does not carry is nothing to remove and leaves the rest of the
        // request's keys to go, and the value a key was stored with plays no part in
        // whether it goes. Every other tag the record holds stays put.
        for key in &input.tag_keys {
            record.tags.remove(key);
        }

        Ok(UntagResourceOutput {})
    }
