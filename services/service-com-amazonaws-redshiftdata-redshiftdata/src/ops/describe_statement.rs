impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeStatement<Eng>
{
    type Input = DescribeStatementInput;
    type Output = DescribeStatementOutput;
    type Error = DescribeStatementError;

    const NAME: &'static str = "DescribeStatement";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_STATEMENT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_STATEMENT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(DescribeStatementErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the Redshift Data API state store is unavailable".to_string(),
                },
            )
            .into());
        };

        let mut store = state.lock();
        store.materialise_due_transitions();
        let Some(statement) = store.statement(&input.id) else {
            return Err(no_such_query(&input.id));
        };

        Ok(DescribeStatementOutput {
            // The `Id` of the SUBMISSION, which for one statement of a batch is
            // the batch's: `SubStatementData.Id` documents the `:<n>` suffix
            // positionally, so it is the ADDRESS that reaches this statement
            // and not the identity its record reports. A client that walks a
            // batch's `SubStatements` and describes each one correlates the
            // record back to the batch through this member.
            id: statement.submission_id().to_string(),
            secret_arn: statement.secret_arn.clone(),
            db_user: statement.db_user.clone(),
            database: statement.database.clone(),
            cluster_identifier: statement.target.cluster_identifier(),
            duration: statement.duration_nanos(),
            error: statement.error(),
            status: Some(statement.status.as_str().to_string()),
            created_at: Some(to_timestamp(statement.created_at)),
            updated_at: Some(to_timestamp(statement.updated_at)),
            redshift_pid: statement.redshift_pid,
            has_result_set: statement.has_result_set(),
            query_string: statement.query_string(),
            result_rows: statement.result_rows(),
            result_size: statement.result_size(),
            redshift_query_id: statement.redshift_query_id,
            redshift_query_uuid: statement.query_uuid.clone(),
            // `SqlParametersList` is modelled with a minimum length of 1, so a
            // statement submitted without parameters reports the member absent
            // rather than as an empty list.
            query_parameters: (!statement.parameters.is_empty())
                .then(|| statement.parameters.clone()),
            // `SubStatements` describes "the SQL statements from a multiple
            // statement run", so it is reported for a batch submission and
            // only for one: a single `ExecuteStatement` ran exactly one
            // statement, which it reports as `QueryString`.
            sub_statements: statement.is_batch.then(|| {
                statement
                    .sub_statements
                    .iter()
                    .map(sub_statement_data)
                    .collect()
            }),
            workgroup_name: statement.target.workgroup_name(),
            result_format: Some(statement.reported_result_format()),
            session_id: statement.session_id.clone(),
            execution_mode: Some(statement.execution_mode().to_string()),
        })
    }
}

/// Refuse an `Id` this service holds no query for.
///
/// The missing-resource error the Data API carries this refusal in, in the fixed
/// words it states for every reader of a statement — no part of the id reaches
/// the message — served at the status the service answers this path with
/// ([`UNKNOWN_QUERY_STATUS`]) rather than at the shape's own `@httpError`.
fn no_such_query(id: &str) -> DescribeStatementError {
    crate::scaffolded::Scaffolded::modeled_with_status(
        DescribeStatementErrorModeled::ResourceNotFoundException(ResourceNotFoundException {
            message: UNKNOWN_QUERY_MESSAGE.to_string(),
            resource_id: id.to_string(),
        }),
        UNKNOWN_QUERY_STATUS,
    )
}

/// One entry of `SubStatements`: one statement of a batch, reported from what
/// that statement itself did.
fn sub_statement_data(sub_statement: &Statement) -> SubStatementData {
    SubStatementData {
        id: sub_statement.id.clone(),
        duration: sub_statement.duration_nanos(),
        error: sub_statement.error(),
        status: Some(sub_statement.status.as_str().to_string()),
        created_at: Some(to_timestamp(sub_statement.created_at)),
        updated_at: Some(to_timestamp(sub_statement.updated_at)),
        query_string: sub_statement.query_string(),
        result_rows: sub_statement.result_rows(),
        result_size: sub_statement.result_size(),
        redshift_query_id: sub_statement.redshift_query_id,
        redshift_query_uuid: sub_statement.query_uuid.clone(),
        has_result_set: sub_statement.has_result_set(),
    }
}
