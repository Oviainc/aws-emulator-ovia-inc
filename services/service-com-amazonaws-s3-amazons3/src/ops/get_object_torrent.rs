        // there is still no torrent for S3 to answer with: the service no longer delivers
        // objects over BitTorrent, so an object's torrent is a resource this method is not
        // allowed against. That holds whatever the object at `Key` is, and whether the
        // bucket holds that key at all, because the refusal is about the delivery mechanism
        // and not about the object — so nothing reads the object, and `Body` ("a Bencoded
        // dictionary as defined by the BitTorrent specification") is never answered, in
        // place of an empty one a client would read as a torrent with no peers.
