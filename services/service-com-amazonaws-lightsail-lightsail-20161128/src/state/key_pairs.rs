//! The stored SSH key pair: the public half this service holds for the account,
//! under the name an instance's key pair member names it by.

use super::*;

/// One stored SSH key pair: the PUBLIC half Lightsail holds for the account,
/// under the name an instance's `sshKeyName` names it by.
///
/// Lightsail holds only the public half — the modelled `DeleteKeyPair`
/// documentation deletes a key pair "by removing the public key from Amazon
/// Lightsail" — so that is all a record here holds beside what the service
/// assigned it. The private half is handed to the caller by the call that
/// created the pair and is never stored.
#[derive(Debug, Clone)]
pub struct StoredKeyPair {
    /// The key pair name the request named, kept verbatim — it is this record's
    /// store key and the `name` every read reports.
    pub name: String,
    pub arn: String,
    pub support_code: String,
    pub created_at_ms: i64,
    pub location: StoredLocation,
    pub tags: Vec<Tag>,
    /// The fingerprint of the public half: "The RSA fingerprint of the key pair"
    /// (`KeyPair$fingerprint`). It is what a delete's `expectedFingerprint`
    /// states it expects to be deleting.
    pub fingerprint: String,
}

impl StoredKeyPair {
    /// This record as the modelled `KeyPair`.
    pub fn view(&self) -> KeyPair {
        KeyPair {
            name: Some(self.name.clone()),
            arn: Some(self.arn.clone()),
            support_code: Some(self.support_code.clone()),
            created_at: Some(timestamp(self.created_at_ms)),
            location: Some(self.location.view()),
            resource_type: Some(RESOURCE_TYPE_KEY_PAIR.to_string()),
            tags: Some(self.tags.clone()),
            fingerprint: Some(self.fingerprint.clone()),
        }
    }

    /// Whether this is the account's Lightsail DEFAULT key pair — the one
    /// [`DEFAULT_SSH_KEY_NAME`] names, which an instance created without a key
    /// pair of its own is launched with.
    ///
    /// The record's NAME is what decides, because that name is how every
    /// Lightsail operation addresses the default pair.
    pub fn is_default(&self) -> bool {
        self.name == DEFAULT_SSH_KEY_NAME
    }
}

/// The SSH key material this service minted for one key pair: the two halves the
/// call that minted it answers, and the fingerprint the stored record keeps.
///
/// Real RSA key material, generated by the cryptography library this workspace
/// already generates RSA key pairs with, and encoded by the crates that
/// implement each published encoding — so nothing here is a string shaped like a
/// key. Only the private half's holder can use it: it is handed to the caller by
/// the call that minted it and never stored, exactly as the modelled `KeyPair`
/// carries no key material and keeps the fingerprint alone.
/// Not `Clone`: the private half is handed to the caller by the call that minted
/// it, so a second copy of it has no reason to exist.
pub struct MintedKeyPairMaterial {
    /// The public half as an OpenSSH public key line — `ssh-rsa <body>`, the
    /// type `CreateKeyPairResult$publicKeyBase64` documents ("A base64-encoded
    /// public key of the ssh-rsa type"), which is the form an
    /// `authorized_keys` file carries and the form `ImportKeyPair`'s own
    /// `publicKeyBase64` is given.
    pub public_key: String,
    /// The private half as an `RSA PRIVATE KEY` PEM — the PKCS#1 encoding
    /// `privateKeyBase64` documents ("A base64-encoded RSA private key"), which
    /// is what an SSH client reads from the file a caller saves it to.
    pub private_key: String,
    /// "The RSA fingerprint of the key pair" (`KeyPair$fingerprint`): the MD5
    /// digest of the DER-encoded PUBLIC half, in the colon-separated hex an AWS
    /// key pair fingerprint is published in — the digest `openssl rsa -pubout
    /// -outform DER | openssl md5 -c` prints for this key.
    ///
    /// Computed from the PUBLIC half alone, because that is all this service
    /// holds once the call returns: the fingerprint of a stored key pair has to
    /// be derivable from the record, whether the pair was minted here or
    /// imported with its public half alone.
    pub fingerprint: String,
}

/// Redacts the private half, for the reason [`TemporarySshKeys`]' own `Debug`
/// redacts the key it grants: a derived `Debug` would carry the minted private
/// key into any formatter, including a log line.
impl std::fmt::Debug for MintedKeyPairMaterial {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("MintedKeyPairMaterial")
            .field("public_key", &self.public_key)
            .field("fingerprint", &self.fingerprint)
            .finish_non_exhaustive()
    }
}

impl MintedKeyPairMaterial {
    /// Mint a fresh RSA key pair of [`KEY_PAIR_MODULUS_BITS`].
    ///
    /// `None` only when the key does not generate or does not encode, which a
    /// caller reports no key pair for rather than storing a record with no key
    /// behind it.
    pub fn mint() -> Option<Self> {
        use ::aws_lc_rs::encoding::AsDer;

        let generated = ::aws_lc_rs::rsa::PrivateDecryptingKey::generate(KEY_PAIR_MODULUS_BITS)
            .ok()?;
        // `openssl rsa -pubout -outform DER`: the SubjectPublicKeyInfo of the
        // public half, which is what the published fingerprint is the digest
        // of.
        let public_key_der = generated.public_key().as_der().ok()?.as_ref().to_vec();
        // The library hands the private half over as PKCS#8; the inner key of
        // that wrapper IS the PKCS#1 `RSAPrivateKey` an `RSA PRIVATE KEY` PEM
        // carries, and the crates implementing those two encodings are what
        // read and write them here.
        let pkcs8 = generated.as_der().ok()?;
        let pkcs1_der = ::pkcs8::PrivateKeyInfo::try_from(pkcs8.as_ref())
            .ok()?
            .private_key
            .to_vec();
        let parsed = <::pkcs1::RsaPrivateKey as ::der::Decode>::from_der(&pkcs1_der).ok()?;
        let public_key = openssh_rsa_public_key(&parsed)?;
        let private_key = ::der::Document::try_from(pkcs1_der.as_slice())
            .ok()?
            .to_pem(RSA_PRIVATE_KEY_PEM_LABEL, ::der::pem::LineEnding::LF)
            .ok()?;
        Some(Self {
            public_key,
            private_key,
            fingerprint: colon_hex(&::md5::Md5::digest(&public_key_der)),
        })
    }
}

/// The PEM label a PKCS#1 RSA private key is published under, from the textual
/// encodings RFC 7468 defines ("RSA PRIVATE KEY"): the header and footer an SSH
/// client recognises the private half by.
const RSA_PRIVATE_KEY_PEM_LABEL: &str = "RSA PRIVATE KEY";

/// The size of the RSA key pair a create mints.
///
/// 2048 bits is the size an SSH key pair is generated at by default and the
/// smallest an OpenSSH client accepts without complaint; the modelled output
/// documents the TYPE of the halves ("the ssh-rsa type", "an RSA private key")
/// and not their size, so this is the size this service generates rather than a
/// published one.
const KEY_PAIR_MODULUS_BITS: ::aws_lc_rs::rsa::KeySize = ::aws_lc_rs::rsa::KeySize::Rsa2048;

/// The OpenSSH public key line of the RSA key `private`'s public half:
/// `ssh-rsa <base64 body>`, built from the key's own modulus and public exponent
/// by the crate that implements the OpenSSH key formats.
///
/// No comment is attached: the line is the key material a caller saves, and
/// Lightsail reports no comment for it.
fn openssh_rsa_public_key(private: &::pkcs1::RsaPrivateKey<'_>) -> Option<String> {
    let key = ::ssh_key::public::KeyData::Rsa(::ssh_key::public::RsaPublicKey {
        e: ::ssh_key::Mpint::from_positive_bytes(private.public_exponent.as_bytes()).ok()?,
        n: ::ssh_key::Mpint::from_positive_bytes(private.modulus.as_bytes()).ok()?,
    });
    ::ssh_key::PublicKey::new(key, "").to_openssh().ok()
}
