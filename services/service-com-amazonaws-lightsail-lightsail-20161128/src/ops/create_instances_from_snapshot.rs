/// One block storage disk the attached-disk mapping asks this call to restore.
struct PlannedDisk {
    /// `DiskMap$originalDiskPath` — "The original disk path exposed to the
    /// instance" — which is both how the captured disk is addressed in the
    /// snapshot and the path the restored disk is attached at.
    original_disk_path: String,
    /// `DiskMap$newDiskName` — "The new disk name".
    new_disk_name: String,
    /// The captured disk's size in GB, filled in once the snapshot has been
    /// read: a restored disk is a copy of the volume the snapshot captured, so
    /// its size is that volume's and never a figure from the request.
    size_in_gb: i32,
}

/// What `input` asks this call to create, one entry per name in `instanceNames`
/// and in that order, or the refusal its members earn.
///
/// `attachedDiskMapping` is a map keyed by the name of an instance this request
/// creates, so a key naming anything else maps a disk onto nothing and is
/// refused. Its entries are read in `instanceNames` order rather than the map's,
/// so one request writes the same records whatever order a client serialized the
/// mapping in.
fn planned_instances(
    input: &CreateInstancesFromSnapshotInput,
) -> Result<Vec<PlannedInstance>, CreateInstancesFromSnapshotError> {
    let mapping = input.attached_disk_mapping.clone().unwrap_or_default();
    // The mapping is caller-sized, and nothing modelled bounds it, so it is
    // CLAMPED before any entry is looked at — the same way `instanceNames`,
    // `tags` and `addOns` are. A request cannot restore more disks than this
    // emulator holds, so that is the bound, applied to the whole mapping rather
    // than to one key's list: a request past it creates nothing however it
    // spread its entries across keys.
    let mapped_entries: usize = mapping.values().map(Vec::len).sum();
    if mapped_entries > crate::state::MAX_DISKS {
        return Err(invalid(format!(
            "attachedDiskMapping carries {mapped_entries} entries, more than the {} disks \
             this emulator holds",
            crate::state::MAX_DISKS
        )));
    }
    for key in mapping.keys() {
        if !input.instance_names.contains(key) {
            return Err(invalid(format!(
                "attachedDiskMapping maps disks onto '{key}', which this request does not \
                 create: every key must be one of the instanceNames"
            )));
        }
    }
    let add_on_requests = input.add_ons.clone().unwrap_or_default();
    let mut taken_disk_names: std::collections::HashSet<String> = std::collections::HashSet::new();
    let mut planned = Vec::with_capacity(input.instance_names.len());
    for name in &input.instance_names {
        let add_ons = crate::state::add_ons_from_requests(
            crate::state::ADD_ONS_LIST_MEMBER,
            name,
            &add_on_requests,
        )
        .map_err(invalid)?;
        let mut disks: Vec<PlannedDisk> = Vec::new();
        // Keyed, not scanned, so planning one instance's mapping costs time
        // linear in its (already bounded) entries.
        let mut taken_paths: std::collections::HashSet<String> = std::collections::HashSet::new();
        for entry in mapping.get(name).map(Vec::as_slice).unwrap_or_default() {
            // Both members are modelled optional, and a mapping entry that
            // names only one of them says either which disk to restore or what
            // to call it, never both — there is nothing to create from it.
            let (Some(original_disk_path), Some(new_disk_name)) =
                (entry.original_disk_path.clone(), entry.new_disk_name.clone())
            else {
                return Err(invalid(format!(
                    "attachedDiskMapping['{name}'] carries an entry without both \
                     originalDiskPath and newDiskName: a disk mapping names the path a disk \
                     was exposed at and the name to restore it under"
                )));
            };
            // A device path addresses one device on the instance, so two
            // restored disks cannot be exposed at the same one.
            if !taken_paths.insert(original_disk_path.clone()) {
                return Err(invalid(format!(
                    "attachedDiskMapping['{name}'] names originalDiskPath \
                     '{original_disk_path}' more than once: one device path exposes one disk"
                )));
            }
            // A disk name addresses one disk, so one request cannot restore two
            // disks under the same name.
            if !taken_disk_names.insert(new_disk_name.clone()) {
                return Err(invalid(format!(
                    "attachedDiskMapping names newDiskName '{new_disk_name}' more than once: \
                     a disk name addresses one disk"
                )));
            }
            disks.push(PlannedDisk {
                original_disk_path,
                new_disk_name,
                // Filled in from the snapshot once it has been read.
                size_in_gb: 0,
            });
        }
        planned.push(PlannedInstance {
            name: name.clone(),
            add_ons,
            disks,
        });
    }
    Ok(planned)
}

/// The snapshot the request asked to restore: exactly one of the two mutually
/// exclusive sources the modelled input admits, resolved against the store once
/// the request is known to name one.
///
/// The three operations of this service that can address an automatic snapshot
/// take the same pair of sources under their own member names, so which source a
/// request names is settled by the one owner they share
/// ([`crate::state::requested_snapshot_source`]) and its answer is what this
/// operation then resolves.
type RequestedSource = crate::state::RequestedSnapshotSource;

/// The source `input` names, or the refusal its combination of members earns.
///
/// The modelled documentation states each rule enforced here:
/// `instanceSnapshotName` and `sourceInstanceName` "are mutually exclusive";
/// `restoreDate` and `useLatestRestorableAutoSnapshot` "are mutually exclusive";
/// and both of the latter are to be defined "only when creating a new instance
/// from an automatic snapshot", which is what `sourceInstanceName` names the
/// source of. A restore of nothing is not a restore, so naming neither source is
/// refused too. All of that is the rule the shared owner answers, in this
/// operation's own words
/// ([`crate::state::INSTANCE_RESTORE_SOURCE_MEMBERS`]).
fn requested_source(
    input: &CreateInstancesFromSnapshotInput,
) -> Result<RequestedSource, CreateInstancesFromSnapshotError> {
    crate::state::requested_snapshot_source(
        crate::state::INSTANCE_RESTORE_SOURCE_MEMBERS,
        input.instance_snapshot_name.as_deref(),
        input.source_instance_name.as_deref(),
        input.restore_date.as_deref(),
        input.use_latest_restorable_auto_snapshot,
    )
    .map_err(invalid)
}

/// The snapshotted instance a restore makes its copies of, once the source the
/// request named is known to hold one this account can restore.
struct SnapshottedInstance {
    /// The image the snapshotted instance ran, which every instance restored
    /// from it runs: this input models no blueprint, so a snapshot of a
    /// since-retired image still restores.
    blueprint_id: String,
    /// The size of the system volume the snapshot captured, in GB: the floor
    /// under the SSD of the plan the instances are restored onto.
    size_in_gb: i32,
    /// The block storage disks the snapshot captured, whole — what
    /// `attachedDiskMapping` addresses by the device path each was exposed at.
    attached_disks: Vec<crate::state::StoredDisk>,
    /// How a refusal names the snapshot that captured all of that. A manual
    /// snapshot is a resource with a name of its own, while an automatic one
    /// has neither name nor ARN and is named by the instance it was taken of
    /// and the date it was taken on (`AutoSnapshotDetails$date`,
    /// `DeleteAutoSnapshot$date`).
    described: String,
}

/// The instance the ONE source `source` names captured, or the refusal that
/// source earns against this store's own state.
///
/// Both forms of source answer the same three questions — does this account hold
/// it, is it in the Region the new instances are being created in, and has the
/// service finished taking it — because a restore needs a complete copy of an
/// instance of this Region whichever way the request addressed it. What differs
/// is where each is held: a manual snapshot is a record of its own, and so the
/// source of truth for the image, the system volume and the captured disks it
/// holds, while an automatic snapshot is a copy held beside the schedule that
/// took it ([`crate::state::ComAmazonawsLightsailLightsail20161128State::auto_snapshot`]),
/// whose image and system volume are the source instance's own — this service
/// models no call that changes either — and whose captured disks are the ones
/// that copy itself recorded, which is the same resolution `CopySnapshot` makes
/// of the same source form.
fn snapshotted_instance(
    store: &crate::state::ComAmazonawsLightsailLightsail20161128State,
    source: &RequestedSource,
    region: &str,
    availability_zone: &str,
) -> Result<SnapshottedInstance, CreateInstancesFromSnapshotError> {
    match source {
        RequestedSource::Snapshot(requested) => {
            let snapshot = store.instance_snapshot(requested).ok_or_else(|| {
                not_found(crate::state::RESOURCE_TYPE_INSTANCE_SNAPSHOT, requested)
            })?;
            // A snapshot belongs to the region it was taken in, and only that
            // region's Lightsail endpoint can restore it: moving one between
            // regions is what `CopySnapshot` is for.
            if snapshot.location.region_name != region {
                return Err(invalid(format!(
                    "instanceSnapshotName '{}' is a snapshot of region {}, which cannot be \
                     restored into availabilityZone '{availability_zone}' of region {region}",
                    snapshot.name, snapshot.location.region_name
                )));
            }
            // A snapshot is restorable only once every block it captures is
            // captured: while Lightsail is still taking it the snapshot reports
            // `pending` (`InstanceSnapshot$state`), and there is nothing
            // complete to restore from yet. That is a well-formed request the
            // resources' state does not allow, which is what the modelled
            // `OperationFailureException` is for.
            if snapshot.state != crate::state::INSTANCE_SNAPSHOT_STATE_AVAILABLE {
                return Err(operation_failure(format!(
                    "The instance snapshot {} is {}: an instance can be restored only from a \
                     snapshot that is {}.",
                    snapshot.name,
                    snapshot.state,
                    crate::state::INSTANCE_SNAPSHOT_STATE_AVAILABLE
                )));
            }
            Ok(SnapshottedInstance {
                blueprint_id: snapshot.from_blueprint_id.clone(),
                size_in_gb: snapshot.size_in_gb,
                attached_disks: snapshot.from_attached_disks.clone(),
                described: format!("instance snapshot '{}'", snapshot.name),
            })
        }
        // An AUTOMATIC snapshot is one the `AutoSnapshot` add-on took of the
        // instance on the daily schedule that instance carries, addressed by
        // that instance plus the date the copy was taken on — or, where the
        // request asked for the latest restorable copy, by the instance alone.
        // The image and the system volume it captured are the instance's own,
        // while the block storage disks it captured are the ones attached when
        // the copy was taken.
        RequestedSource::AutoSnapshot {
            resource_name: instance_name,
            date,
        } => {
            let instance = store
                .instance(instance_name)
                .ok_or_else(|| not_found(crate::state::RESOURCE_TYPE_INSTANCE, instance_name))?;
            if instance.location.region_name != region {
                return Err(invalid(format!(
                    "sourceInstanceName '{}' names an instance of region {}, whose automatic \
                     snapshots cannot be restored into availabilityZone '{availability_zone}' \
                     of region {region}",
                    instance.name, instance.location.region_name
                )));
            }
            let copy = store
                .auto_snapshot(
                    crate::state::RESOURCE_TYPE_INSTANCE,
                    instance_name,
                    date.as_deref(),
                )
                .ok_or_else(|| auto_snapshot_not_found(instance_name, date.as_deref()))?;
            // The same rule the manual source is held to: a copy the service
            // has not finished taking holds no complete instance to restore
            // from. A request for the latest RESTORABLE copy never reaches
            // this, the lookup answering it with a copy that is finished.
            if copy.status != crate::state::AUTO_SNAPSHOT_STATUS_SUCCESS {
                return Err(operation_failure(format!(
                    "The automatic snapshot of the {} {instance_name} dated {} is {}: an \
                     instance can be restored only from a snapshot that is {}.",
                    crate::state::RESOURCE_TYPE_INSTANCE,
                    copy.date,
                    copy.status,
                    crate::state::AUTO_SNAPSHOT_STATUS_SUCCESS
                )));
            }
            Ok(SnapshottedInstance {
                blueprint_id: instance.blueprint_id.clone(),
                // The system volume is the instance plan's own SSD, the disk
                // `GetInstance` reports as the instance's system disk.
                size_in_gb: instance.bundle.disk_size_in_gb,
                attached_disks: copy.from_attached_disks.clone().unwrap_or_default(),
                described: format!(
                    "the automatic snapshot of the {} {instance_name} dated {}",
                    crate::state::RESOURCE_TYPE_INSTANCE,
                    copy.date
                ),
            })
        }
    }
}

/// Lightsail's refusal of a well-formed request its resources' state does not
/// allow: the modelled `OperationFailureException` — HTTP 400, "Lightsail throws
/// this exception when an operation fails to execute" — whose message names the
/// resource that is in the way and the state it is in.
