impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for SetSubnets<Eng>
{
    type Input = SetSubnetsInput;
    type Output = SetSubnetsOutput;
    type Error = SetSubnetsError;

    const NAME: &'static str = "SetSubnets";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::SET_SUBNETS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::SET_SUBNETS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            // Only reachable on an engine that is not the shared `InMemoryEngine`,
            // which this service has no store on — so nothing is implemented for it.
            crate::scaffolded::Scaffolded::not_implemented("SetSubnets")
        })?;
        let region = crate::state::request_region(ctx);

        // The model: "You must specify either subnets or subnet mappings" — and the
        // create's own documentation adds "but not both". Read from the request alone, so
        // it is checked before anything is looked up.
        let subnets = input.subnets.as_deref().unwrap_or_default();
        let subnet_mappings = input.subnet_mappings.as_deref().unwrap_or_default();
        if !subnets.is_empty() && !subnet_mappings.is_empty() {
            return Err(invalid_configuration(
                "Specify either Subnets or SubnetMappings, but not both".to_string(),
            ));
        }
        if subnets.is_empty() && subnet_mappings.is_empty() {
            return Err(invalid_configuration(
                "You must specify either Subnets or SubnetMappings".to_string(),
            ));
        }
        let requested_placements = subnets.len() + subnet_mappings.len();

        // What the load balancer is today, read under the lock and then released: the
        // subnets are resolved against EC2 next, and nothing is held across that call.
        let (family, scheme, carried_address_type, carried_vpc) = {
            let guard = state.lock();
            let Some(load_balancer) = guard.load_balancers.get(&input.load_balancer_arn) else {
                return Err(not_found(&input.load_balancer_arn));
            };
            (
                load_balancer.family(),
                load_balancer.scheme.clone(),
                load_balancer.ip_address_type.clone(),
                load_balancer.vpc_id.clone(),
            )
        };

        // How many PLACEMENTS the request asks for — one per `Subnets` entry and one per
        // `SubnetMappings` entry — judged before anything reads either list, because this
        // is the bound that has to dominate every per-entry step below: the zone records
        // this call persists on the load balancer and the addresses it resolves against
        // EC2. Both the ceiling ("you can specify only one subnet per Availability Zone")
        // and the Application family's floor are one reading in `crate::state`, the same
        // one `CreateLoadBalancer` applies to the subnets a load balancer STARTS in.
        if let Err(refusal) = crate::state::check_placement_count(family, requested_placements) {
            return Err(refuse(refusal));
        }
        // Each `SubnetMapping` member is documented for one family, and two of them for
        // one scheme of it, so an address pinned on a load balancer that could never carry
        // it is refused rather than stored.
        for mapping in subnet_mappings {
            if let Err(rule) = crate::state::check_subnet_mapping(family, &scheme, mapping) {
                return Err(invalid_configuration(rule));
            }
        }
        let requested_subnets: Vec<String> = subnets
            .iter()
            .cloned()
            .chain(
                subnet_mappings
                    .iter()
                    .filter_map(|mapping| mapping.subnet_id.clone()),
            )
            .collect();

        // The IP address type the load balancer will carry after this call: the one the
        // request names, else the one it already has. Judged by the same rules
        // `SetIpAddressType` applies, so one call cannot set a type the other refuses.
        let ip_address_type = input
            .ip_address_type
            .clone()
            .unwrap_or(carried_address_type);
        if let Err(refusal) = crate::state::check_ip_address_type(family, &ip_address_type) {
            return Err(refuse(refusal));
        }
        // `EnablePrefixForIpv6SourceNat`'s documented pairing with the address type, read
        // once in `crate::state` and applied by `CreateLoadBalancer` too.
        if let Err(refusal) = crate::state::check_source_nat_prefix(
            input.enable_prefix_for_ipv6_source_nat.as_deref(),
            &ip_address_type,
        ) {
            return Err(refuse(refusal));
        }

        // The subnets a load balancer is placed in are EC2's resources, and they are what
        // say which Availability Zone each one is in — so they are resolved against EC2
        // before anything is written. The store is locked only once the answer is in.
        let resolved_subnets =
            match crate::state::network::resolve_subnets(ctx, &region, &requested_subnets).await {
                // One the account does not hold is a placement EC2 itself refuses, so the
                // modelled `SubnetNotFound` states the code that refusal came under — the
                // same reading `CreateLoadBalancer` applies to the subnets a load balancer
                // STARTS in.
                crate::state::network::SubnetLookup::Absent(refusal) => {
                    return Err(SetSubnetsErrorModeled::SubnetNotFoundException(
                        SubnetNotFoundException {
                            message: Some(refusal.stated_message()),
                        },
                    )
                    .into())
                }
                crate::state::network::SubnetLookup::Resolved(subnets) => Some(subnets),
                crate::state::network::SubnetLookup::Unknown => None,
            };
        // An Elastic IP is EC2's resource too, and the allocation id is what names it.
        let allocation_ids: Vec<String> = subnet_mappings
            .iter()
            .filter_map(|mapping| mapping.allocation_id.clone())
            .collect();
        if let Some(refusal) =
            crate::state::network::absent_allocation_id(ctx, &region, &allocation_ids).await
        {
            return Err(
                SetSubnetsErrorModeled::AllocationIdNotFoundException(
                    AllocationIdNotFoundException {
                        message: Some(refusal.stated_message()),
                    },
                )
                .into(),
            );
        }
        // A load balancer's network interfaces live in the subnets it is placed in, and
        // each of them belongs to exactly one VPC: the subnets that replace the enabled
        // ones have to be the VPC's own, so a placement naming a subnet of ANOTHER VPC is
        // refused — before anything is written, so the zones the load balancer carries are
        // left as they were. The ONE reading of that rule, the same one
        // `CreateLoadBalancer` applies to the subnets a load balancer STARTS in.
        if let Err(rule) = crate::state::check_subnet_vpcs(
            carried_vpc.as_deref(),
            &requested_subnets,
            resolved_subnets.as_deref(),
        ) {
            return Err(invalid_configuration(rule));
        }
        // A load balancer carries IPv6 addresses out of the IPv6 ranges of the subnets it
        // is placed in, so a placement that asks for them needs subnets that have one —
        // the same reading `CreateLoadBalancer` and `SetIpAddressType` apply.
        if let Err(refusal) = crate::state::check_subnet_ipv6_cidrs(
            &ip_address_type,
            resolved_subnets.as_deref(),
        ) {
            return Err(refuse(refusal));
        }
        let zones = crate::state::availability_zone_records(
            subnets,
            subnet_mappings,
            &region,
            resolved_subnets.as_deref(),
        );

        let mut guard = state.lock();
        // Looked up again because the lock was released for the EC2 read: the load
        // balancer may have been deleted while it ran.
        let Some(load_balancer) = guard.load_balancers.get_mut(&input.load_balancer_arn) else {
            return Err(not_found(&input.load_balancer_arn));
        };
        load_balancer.availability_zones = zones;
        load_balancer.ip_address_type = ip_address_type;
        if let Some(prefix) = input.enable_prefix_for_ipv6_source_nat.clone() {
            load_balancer.enable_prefix_for_ipv6_source_nat = Some(prefix);
        }
        // A load balancer holds one interface per subnet it is attached to, so the subnets
        // this call left it with are the subnets its interfaces sit in: a subnet it still has
        // keeps the interface already there, one it has left gives its interface back, and
        // one it has just been given gets an interface of its own
        // ([`crate::state::service_interfaces`]).
        let held = ::std::mem::take(&mut load_balancer.network_interface_ids);
        let record = load_balancer.clone();
        let placed = crate::state::reconcile_load_balancer_interfaces(
            &*self.engine,
            &record,
            &held,
        );
        let Some(load_balancer) = guard.load_balancers.get_mut(&input.load_balancer_arn) else {
            return Err(not_found(&input.load_balancer_arn));
        };
        load_balancer.network_interface_ids = placed;

        Ok(SetSubnetsOutput {
            // Read back off the record rather than echoed from the request, so the answer
            // is what a later `DescribeLoadBalancers` reports.
            availability_zones: Some(
                load_balancer
                    .availability_zones
                    .iter()
                    .map(crate::state::AvailabilityZoneRecord::to_shape)
                    .collect(),
            ),
            ip_address_type: Some(load_balancer.ip_address_type.clone()),
            enable_prefix_for_ipv6_source_nat: load_balancer
                .enable_prefix_for_ipv6_source_nat
                .clone(),
        })
    }
}

