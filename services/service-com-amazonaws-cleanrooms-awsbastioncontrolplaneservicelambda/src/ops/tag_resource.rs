impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        _ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        use crate::state as st;

        let Some(state) = st::service_state(&*self.engine) else {
            return Err(TagResourceErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("cleanrooms state is unavailable".to_string()),
                },
            )
            .into());
        };

        // A well-formed Clean Rooms ARN whose resource segment names no kind of resource
        // addresses nothing, so the fault is in the member's value, not in a resource
        // that is missing. The model's pattern cannot express it, so it is refused here.
        let Some(resource_type) = st::resource_type_of_arn(&input.resource_arn) else {
            return Err(TagResourceErrorModeled::ValidationException(
                ValidationException {
                    message: Some(st::invalid_resource_arn_message(&input.resource_arn)),
                    reason: Some(st::VALIDATION_REASON_FIELD_VALIDATION_FAILED.to_string()),
                    field_list: Some(vec![ValidationExceptionField {
                        name: "resourceArn".to_string(),
                        message: st::invalid_resource_arn_message(&input.resource_arn),
                    }]),
                },
            )
            .into());
        };

        let mut store = state.lock();
        // Only an existing resource can be tagged, so the store is checked BEFORE it is
        // written: a refused call leaves no tags behind for an ARN nothing is stored
        // under, which a later create of that same ARN would otherwise inherit. The
        // tagging plane words this refusal itself: its wire code is `NotFoundException`,
        // not the `ResourceNotFoundException` the CRUD operations answer.
        if !store.holds_resource_at_arn(&input.resource_arn) {
            return Err(TagResourceError::not_found(
                &input.resource_arn,
                resource_type,
            ));
        }

        // A tag set past what a `TagMap` can hold could not be reported by
        // `ListTagsForResource` at all, so a call that would push the resource past the
        // limit is refused before anything is written.
        let would_carry = store.tag_count_after_adding(&input.resource_arn, &input.tags);
        if would_carry > st::MAX_TAGS_PER_RESOURCE {
            return Err(TagResourceErrorModeled::ValidationException(
                ValidationException {
                    message: Some(st::tag_limit_exceeded_message(
                        st::MAX_TAGS_PER_RESOURCE,
                        would_carry,
                    )),
                    reason: Some(st::VALIDATION_REASON_FIELD_VALIDATION_FAILED.to_string()),
                    field_list: Some(vec![ValidationExceptionField {
                        name: "tags".to_string(),
                        message: st::tag_limit_exceeded_message(
                            st::MAX_TAGS_PER_RESOURCE,
                            would_carry,
                        ),
                    }]),
                },
            )
            .into());
        }

        store.add_tags(&input.resource_arn, input.tags);
        Ok(TagResourceOutput {})
    }
}
