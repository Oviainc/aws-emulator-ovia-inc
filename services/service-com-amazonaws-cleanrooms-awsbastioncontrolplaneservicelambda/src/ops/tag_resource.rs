//! @op TagResource
//!
//! Adds the request's tags to the resource `resourceArn` addresses, persisting them in
//! the one tag store keyed by resource ARN (`crate::state::CleanRoomsState::tags`) that
//! `ListTagsForResource` reads and `UntagResource` removes from. A key the resource
//! already carries takes the new value and every other key stays where it is, so tagging
//! twice leaves the resource carrying both calls' keys. An ARN this service holds no
//! resource under is refused: there is nothing to tag. A call that would leave a resource
//! carrying more tags than a `TagMap` can hold is refused too, since such a set could not
//! be reported back.
//!
