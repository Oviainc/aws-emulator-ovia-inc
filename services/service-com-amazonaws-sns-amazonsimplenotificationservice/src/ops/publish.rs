/// One SQS queue a message is handed to, however it was addressed — as a subscription's
/// endpoint or as its dead-letter target.
#[derive(Debug, Clone)]
struct QueueLocation {
    /// The url the queue is reached at.
    queue_url: String,
    /// The queue's own ARN: the RESOURCE its policy is asked about before a message is
    /// handed to it.
    queue_arn: String,
    /// The Region the queue is in: the one its own ARN names.
    region: String,
}

impl QueueLocation {
    /// The queue `arn` names, or `None` when `arn` is not the ARN of a queue.
    fn of_queue_arn(arn: &str) -> Option<Self> {
        let parsed = ::service_common::arn::parse(arn)?;
        if parsed.vendor != SQS_ARN_NAMESPACE || parsed.resource.contains([':', '/']) {
            // A queue's ARN names the queue directly: a resource field carrying a type
            // separator addresses no queue.
            return None;
        }
        let region = ::service_common::arn::region_of(arn, SQS_ARN_NAMESPACE)?;
        Some(Self {
            queue_url: format!(
                "https://sqs.{region}.amazonaws.com/{}/{}",
                parsed.account, parsed.resource
            ),
            queue_arn: arn.to_string(),
            region: region.to_string(),
        })
    }

    /// Whether this is a FIFO queue: "the name of a FIFO queue must end with the .fifo
    /// suffix" (`CreateQueueInput$QueueName` doc), and the resource part of a queue's ARN
    /// is its name. A FIFO queue is the only kind that takes the ordering members of a
    /// published message.
    fn is_fifo(&self) -> bool {
        self.queue_arn.ends_with(crate::state::FIFO_SUFFIX)
    }
}

/// How many deliveries ONE publishing request may make, across every message it publishes
/// and every subscription of the topic.
///
/// The request's OWN bound, not a limit AWS publishes. Each factor of the fan-out is bounded
/// on its own — at most 10 entries per `PublishBatch` and
/// [`crate::state::MAX_RECORDS_PER_STORE`] subscriptions per store — but their PRODUCT is
/// not, so one request could otherwise dispatch 10,000 in-process calls. It is set far above
/// any realistic topic fan-out (a handful of subscribers), and a request that exhausts it
/// stops delivering and says so in the log rather than silently dispatching more.
const MAX_DELIVERIES_PER_REQUEST: usize = 100;

/// How many delivered bytes ONE publishing request may hand to the subscribed queues.
///
/// A second bound on the same fan-out, because a delivery count alone does not bound the
/// work: one message may be just under the topic's `MaximumMessageSize` (up to 1 MiB), so a
/// count-only cap would admit a hundred megabytes of message bodies from one request.
const MAX_DELIVERED_BYTES_PER_REQUEST: usize = 8 * 1024 * 1024;

/// What one publishing request has left to spend on delivering to subscribed queues.
///
/// ONE budget for the whole request, spent across every message and every subscription: that
/// is what caps the (messages x subscriptions x body bytes) PRODUCT rather than each factor
/// on its own.
#[derive(Debug)]
pub(crate) struct DeliveryBudget {
    deliveries: usize,
    bytes: usize,
}

impl DeliveryBudget {
    /// A fresh budget: [`MAX_DELIVERIES_PER_REQUEST`] deliveries and
    /// [`MAX_DELIVERED_BYTES_PER_REQUEST`] bytes.
    pub(crate) fn new() -> Self {
        Self {
            deliveries: 0,
            bytes: 0,
        }
    }

    /// Charge one delivery of `bytes`: `false` when it would pass either bound, in which case
    /// nothing is charged and nothing must be delivered.
    fn charge(&mut self, bytes: usize) -> bool {
        let deliveries = self.deliveries + 1;
        let total = self.bytes.saturating_add(bytes);
        if deliveries > MAX_DELIVERIES_PER_REQUEST || total > MAX_DELIVERED_BYTES_PER_REQUEST {
            return false;
        }
        self.deliveries = deliveries;
        self.bytes = total;
        true
    }
}

/// The body an SQS subscriber of `published` receives: the message as published, or —
/// when it was published with `MessageStructure` of `json` — the branch that document
/// names for the `sqs` protocol, falling back to its `default` branch.
///
/// The queues of one topic all deliver over the same protocol, so one publish selects
/// this body once.
fn protocol_body(published: &PublishedMessage) -> String {
    state::structured_message_body(
        &published.message,
        published.message_structure.as_deref(),
        SQS_PROTOCOL,
    )
}

/// The deliveries `published` owes to the SQS queues among `subscriptions`, within what
/// `budget` has left.
///
/// The RAW form of the body is rendered at most once and shared by every raw subscriber, so a
/// fan-out does not re-serialize it per subscriber; the ENVELOPED form is rendered per
/// subscription, because it carries that subscription's own unsubscribe link.
/// `pub(crate)` with [`deliver_to_queues`]: `PublishBatch` publishes the same messages to the
/// same subscriptions, so it goes through this one definition of the envelope and the fan-out
/// rather than a second copy, and shares one budget across its entries.
pub(crate) fn queue_deliveries(
    subscriptions: &[state::SubscriptionRecord],
    published: &PublishedMessage,
    budget: &mut DeliveryBudget,
) -> Vec<QueueDelivery> {
    // The body the subscribers of THIS protocol receive: the whole published message,
    // unless it was published with a per-protocol structure, in which case it is the
    // branch that structure names for the protocol. Every queue of a topic is subscribed
    // over the same protocol, so one fan-out selects it once — the envelope around it is
    // still rendered per subscription, because it carries that subscription's own
    // unsubscribe link.
    let body_lazily: ::std::cell::OnceCell<String> = ::std::cell::OnceCell::new();
    let mut raw_body: Option<::std::sync::Arc<str>> = None;
    let mut deliveries: Vec<QueueDelivery> = Vec::new();
    for subscription in subscriptions {
        let Some(target) = QueueTarget::of(subscription) else {
            continue;
        };
        let protocol_body = body_lazily.get_or_init(|| protocol_body(published));
        let body = if target.raw {
            raw_body
                .get_or_insert_with(|| ::std::sync::Arc::from(protocol_body.as_str()))
                .clone()
        } else {
            ::std::sync::Arc::from(notification_envelope(
                published,
                protocol_body,
                &subscription.arn,
            ))
        };
        if !budget.charge(body.len()) {
            ::tracing::warn!(
                subscription = %subscription.arn,
                deliveries = MAX_DELIVERIES_PER_REQUEST,
                bytes = MAX_DELIVERED_BYTES_PER_REQUEST,
                "this request reached the emulator's delivery budget; the remaining \
                 subscriptions of the topic are not delivered to"
            );
            return deliveries;
        }
        deliveries.push(QueueDelivery {
            subscription_arn: subscription.arn.clone(),
            target: target.location,
            topic_arn: published.topic_arn.clone(),
            body,
            attributes: if target.raw {
                published
                    .message_attributes
                    .iter()
                    .map(|(name, value)| (name.clone(), queue_attribute(value)))
                    .collect()
            } else {
                Vec::new()
            },
            message_group_id: published.message_group_id.clone(),
            message_deduplication_id: published.message_deduplication_id.clone(),
            dead_letter: target.dead_letter,
        });
    }
    deliveries
}

/// One published message attribute as the subscribed queue's OWN message attribute.
///
/// A raw delivery carries the published attributes as the queue's own, and the value of a
/// `Number` attribute is a NUMBER: the queue receives the number the publisher named, not the
/// way it spelled it (a leading `+`, a trailing `.0`). An attribute of any other type carries
/// its value verbatim — it is text or bytes, so the publisher's spelling of it is all there
/// is — and so does a `Number` whose value is not a number this service can read, which it
/// passes on rather than rewriting.
fn queue_attribute(value: &MessageAttributeValue) -> MessageAttributeValue {
    let is_number = value.data_type == NUMBER_DATA_TYPE
        || value
            .data_type
            .starts_with(&format!("{NUMBER_DATA_TYPE}{DATA_TYPE_LABEL_SEPARATOR}"));
    let Some(number) = value
        .string_value
        .as_deref()
        .filter(|_| is_number)
        .and_then(canonical_number)
    else {
        return value.clone();
    };
    MessageAttributeValue {
        string_value: Some(number),
        ..value.clone()
    }
}

/// The data type of a numeric message attribute: "Number – Numbers are positive or negative
/// integers or floating-point numbers" (`MessageAttributeValue$DataType` doc).
const NUMBER_DATA_TYPE: &str = "Number";

/// What separates a data type from the custom label a publisher may append to it
/// (`Number.int`): "You can also append custom labels" (`MessageAttributeValue$DataType`).
const DATA_TYPE_LABEL_SEPARATOR: char = '.';

/// `value` as the number it names, spelled canonically — or `None` when it names none.
///
/// The spelling is normalised in the DECIMAL TEXT the publisher sent: the redundant leading
/// `+`, the leading zeros of the integer part and the trailing zeros of the fraction are
/// dropped, and nothing else about the number changes. It is never round-tripped through a
/// binary float, which would respell an exponent and lose the digits a double cannot hold. A
/// value that is not a plain decimal number — one in exponent form, one that is not a number
/// at all — names no canonical spelling here and is passed on as the publisher sent it.
fn canonical_number(value: &str) -> Option<String> {
    let (sign, magnitude) = match value.strip_prefix(['+', '-']) {
        Some(magnitude) if value.starts_with('-') => ("-", magnitude),
        Some(magnitude) => ("", magnitude),
        None => ("", value),
    };
    let (whole, fraction) = match magnitude.split_once('.') {
        Some((whole, fraction)) => (whole, fraction),
        None => (magnitude, ""),
    };
    let is_decimal = |part: &str| part.bytes().all(|byte| byte.is_ascii_digit());
    if (whole.is_empty() && fraction.is_empty()) || !is_decimal(whole) || !is_decimal(fraction) {
        return None;
    }
    let whole = whole.trim_start_matches('0');
    let fraction = fraction.trim_end_matches('0');
    if whole.is_empty() && fraction.is_empty() {
        // Zero is zero, however many digits and whichever sign it was written with.
        return Some("0".to_string());
    }
    let whole = if whole.is_empty() { "0" } else { whole };
    if fraction.is_empty() {
        return Some(format!("{sign}{whole}"));
    }
    Some(format!("{sign}{whole}.{fraction}"))
}

/// Where one subscription's deliveries go, and in which form.
struct QueueTarget {
    /// The queue the subscription's endpoint ARN names.
    location: QueueLocation,
    /// Whether the subscription asked for RAW delivery.
    raw: bool,
    /// The dead-letter queue the subscription's `RedrivePolicy` names, if any.
    dead_letter: Option<QueueLocation>,
}

impl QueueTarget {
    /// The queue `subscription` addresses, or `None` when it is not one this operation
    /// delivers to.
    fn of(subscription: &state::SubscriptionRecord) -> Option<Self> {
        if subscription.protocol != SQS_PROTOCOL {
            // Every other protocol (`http`, `lambda`, `email`, `firehose`, …) needs its own
            // delivery path, which is not implemented here. The message is still RECORDED
            // against the subscription, so nothing claims a delivery that did not happen.
            return None;
        }
        let endpoint = subscription.endpoint.as_deref()?;
        let location = QueueLocation::of_queue_arn(endpoint)?;
        if subscription
            .attributes
            .contains_key(state::FILTER_POLICY_ATTRIBUTE)
        {
            // A filter policy decides WHICH messages the subscription receives, and applying
            // one is not implemented here. A subscriber that asked to be filtered must not be
            // handed every message instead — that would deliver what it filtered out — so the
            // delivery does not happen and says so.
            ::tracing::warn!(
                subscription = %subscription.arn,
                "a subscription carrying a FilterPolicy is not delivered to: message \
                 filtering is not implemented in this emulator"
            );
            return None;
        }
        Some(Self {
            location,
            // "RawMessageDelivery – When set to true, enables raw message delivery to Amazon
            // SQS […] endpoints. This eliminates the need for the endpoints to process JSON
            // formatting, which is otherwise created for Amazon SNS metadata."
            raw: subscription
                .attributes
                .get(state::RAW_MESSAGE_DELIVERY_ATTRIBUTE)
                .is_some_and(|value| value == state::RAW_MESSAGE_DELIVERY_ENABLED),
            // "RedrivePolicy – When specified, sends undeliverable messages to the specified
            // Amazon SQS dead-letter queue" — the queue a delivery this subscription cannot
            // receive is parked in.
            dead_letter: state::dead_letter_target_arn(&subscription.attributes)
                .as_deref()
                .and_then(QueueLocation::of_queue_arn),
        })
    }
}

/// Deliver each queued message to the queue its subscription names, and park the ones that
/// cannot be delivered in that subscription's dead-letter queue.
///
/// A queue is reached the way any emulated service reaches another: through the in-process
/// callback ([`smithy_server_runtime::OperationContext::callback`]), so this crate names no
/// other service crate. The delivery's outcome is not part of this operation's answer, so a
/// queue that cannot be reached is logged and changes nothing about what the caller is told.
///
/// A delivery is made only where the queue's OWN policy grants it: see
/// [`delivery_is_authorized`]. The queue's policy is read once per queue per request, because
/// one publish may owe several messages to the same queue — so the reads this adds are
/// bounded by the same [`MAX_DELIVERIES_PER_REQUEST`] the deliveries are, and so is the
/// per-request table they are remembered in.
///
/// A delivery that could NOT be made to a subscription carrying a `RedrivePolicy` is written
/// to the queue that policy names instead: "sends undeliverable messages to the specified
/// Amazon SQS dead-letter queue. Messages that can't be delivered due to client errors (for
/// example, when the subscribed endpoint is unreachable) […] are held in the dead-letter
/// queue for further analysis or reprocessing"
/// (`SetSubscriptionAttributesInput$AttributeName`). The copy is the body the subscription
/// itself would have received, in that subscription's own delivery format, because that is
/// the message that could not be delivered.
pub(crate) async fn deliver_to_queues(
    ctx: &smithy_server_runtime::OperationContext<'_>,
    deliveries: &[QueueDelivery],
) {
    let mut queues = Queues::new(ctx);
    for delivery in deliveries {
        if queues.hand_over(&delivery.target, delivery).await {
            continue;
        }
        let Some(dead_letter) = delivery.dead_letter.as_ref() else {
            continue;
        };
        if queues.hand_over(dead_letter, delivery).await {
            ::tracing::info!(
                subscription = %delivery.subscription_arn,
                queue = %dead_letter.queue_url,
                "the notification could not be delivered, so it was held in the \
                 subscription's dead-letter queue"
            );
        } else {
            ::tracing::warn!(
                subscription = %delivery.subscription_arn,
                queue = %dead_letter.queue_url,
                "the notification could not be delivered and its subscription's \
                 dead-letter queue could not be written to either"
            );
        }
    }
}

/// The SQS queues ONE publishing request hands its messages to.
///
/// It remembers what each queue of the fan-out answered — the client its Region is reached
/// through and the `Policy` the queue itself reports — so a request that owes several
/// messages to one queue reads that queue once. Both tables are bounded by the same
/// [`MAX_DELIVERIES_PER_REQUEST`] the deliveries are.
struct Queues<'ctx, 'op> {
    ctx: &'ctx smithy_server_runtime::OperationContext<'op>,
    /// One client per Region: every queue of one Region is reached through the same endpoint,
    /// and a publish rarely fans out across Regions.
    clients: Vec<(String, ::aws_sdk_sqs::Client)>,
    /// The `Policy` each queue answered with, keyed by its url.
    policies: Vec<(String, QueuePolicy)>,
}

/// What a queue answered when the `Policy` it carries was read.
#[derive(Debug, Clone)]
enum QueuePolicy {
    /// The queue answered: the policy document it carries, or `None` when it carries none.
    Stated(Option<String>),
    /// The queue did not answer at all — one that was deleted, or that never existed — so
    /// nothing can be handed to it.
    Unreachable,
}

impl<'ctx, 'op> Queues<'ctx, 'op> {
    fn new(ctx: &'ctx smithy_server_runtime::OperationContext<'op>) -> Self {
        Self {
            ctx,
            clients: Vec::new(),
            policies: Vec::new(),
        }
    }

    /// The client `region`'s queues are reached through, built on first use.
    ///
    /// Handed back by value: the client is a handle over the shared in-process transport, so
    /// a copy of it addresses the same endpoint.
    fn client(&mut self, region: &str) -> ::aws_sdk_sqs::Client {
        if let Some((_, client)) = self.clients.iter().find(|(held, _)| held == region) {
            return client.clone();
        }
        let fresh = sqs_client(self.ctx, region);
        self.clients.push((region.to_string(), fresh.clone()));
        fresh
    }

    /// The `Policy` the queue at `queue_url` reports, read at most once per request.
    async fn policy(&mut self, client: &::aws_sdk_sqs::Client, queue_url: &str) -> QueuePolicy {
        if let Some((_, policy)) = self.policies.iter().find(|(held, _)| held == queue_url) {
            return policy.clone();
        }
        let read = queue_policy(client, queue_url).await;
        self.policies.push((queue_url.to_string(), read.clone()));
        read
    }

    /// Hand `delivery`'s message to `queue`, and report whether the queue took it.
    ///
    /// `false` is every way the message did not reach the queue: a queue that does not
    /// answer, a queue whose own policy does not grant this service the send, and a send the
    /// queue refused — the client errors a redrive exists to make visible.
    async fn hand_over(&mut self, queue: &QueueLocation, delivery: &QueueDelivery) -> bool {
        let client = self.client(&queue.region);
        let policy = match self.policy(&client, &queue.queue_url).await {
            QueuePolicy::Stated(policy) => policy,
            QueuePolicy::Unreachable => {
                ::tracing::warn!(
                    subscription = %delivery.subscription_arn,
                    queue = %queue.queue_url,
                    "the subscribed queue does not answer, so the notification cannot be \
                     delivered to it"
                );
                return false;
            }
        };
        if !delivery_is_authorized(policy.as_deref(), &queue.queue_arn, &delivery.topic_arn) {
            ::tracing::warn!(
                subscription = %delivery.subscription_arn,
                queue = %queue.queue_url,
                "the subscribed queue's policy does not allow this service to send it a \
                 message, so the notification is withheld"
            );
            return false;
        }
        let mut request = client
            .send_message()
            .queue_url(&queue.queue_url)
            .message_body(&*delivery.body);
        // The ordering members of the published message, passed on to the queue: a FIFO
        // queue orders and deduplicates by them, and takes no message without a group.
        // A STANDARD queue takes a group ("In standard queues, using MessageGroupId
        // enables fair queues") but no deduplication token, which is a FIFO member.
        if let Some(group) = delivery.message_group_id.as_deref() {
            request = request.message_group_id(group);
        }
        if let Some(token) = delivery
            .message_deduplication_id
            .as_deref()
            .filter(|_| queue.is_fifo())
        {
            request = request.message_deduplication_id(token);
        }
        for (name, value) in &delivery.attributes {
            let mut attribute =
                ::aws_sdk_sqs::types::MessageAttributeValue::builder().data_type(&value.data_type);
            if let Some(string) = value.string_value.as_deref() {
                attribute = attribute.string_value(string);
            }
            if let Some(binary) = value.binary_value.as_ref() {
                attribute =
                    attribute.binary_value(::aws_smithy_types::Blob::new(binary.clone()));
            }
            match attribute.build() {
                Ok(attribute) => request = request.message_attributes(name, attribute),
                Err(error) => ::tracing::warn!(
                    subscription = %delivery.subscription_arn,
                    attribute = %name,
                    error = %error,
                    "a message attribute could not be carried to the subscribed queue"
                ),
            }
        }
        if let Err(error) = request.send().await {
            ::tracing::warn!(
                subscription = %delivery.subscription_arn,
                queue = %queue.queue_url,
                error = %::aws_smithy_types::error::display::DisplayErrorContext(&error),
                "a subscribed queue could not be delivered to"
            );
            return false;
        }
        true
    }
}

/// The service principal an SNS delivery performs its `SendMessage` as: the identity a
/// queue's own policy has to grant for a notification to reach it.
const SNS_SERVICE_PRINCIPAL: &str = "sns.amazonaws.com";

/// The IAM action a delivery to a subscribed queue performs on that queue.
const SEND_MESSAGE_ACTION: &str = "sqs:SendMessage";

/// The condition key naming the resource a cross-service request came FROM — the topic
/// published to — which is what a queue policy scopes its grant to.
const SOURCE_ARN_CONDITION_KEY: &str = "aws:SourceArn";

/// The condition key naming the ACCOUNT that resource belongs to.
const SOURCE_ACCOUNT_CONDITION_KEY: &str = "aws:SourceAccount";

/// The same account under the key SNS's own documented queue policy uses for it.
const SOURCE_OWNER_CONDITION_KEY: &str = "aws:SourceOwner";

/// Whether the queue's own policy allows this delivery.
///
/// A queue is a resource of another service, and SNS reaches it as the service principal
/// `sns.amazonaws.com` rather than as the queue's owner: "you must ensure that the Amazon SQS
/// queue policy allows the Amazon SNS topic to send messages to the queue" — so a queue whose
/// policy states no such grant receives nothing, and a client that repairs the policy sees
/// the next notification arrive. That is the ordinary IAM question — may this principal
/// perform this action on this resource? — so it is answered by the shared evaluation of
/// policy documents rather than by a reading of its own, over the queue's `Policy` attribute
/// as the queue reports it. The principal is a service, not an identity with policies of its
/// own, so the queue's resource policy is the only document in force: with none at all the
/// implicit deny stands.
///
/// The request carries the keys such a grant is scoped by — the topic's ARN and the account
/// it belongs to — so a policy conditioned on them is decided rather than left undecided.
fn delivery_is_authorized(policy: Option<&str>, queue_arn: &str, topic_arn: &str) -> bool {
    let Some(policy) = policy else {
        return false;
    };
    let principals = [SNS_SERVICE_PRINCIPAL.to_string()];
    let account = ::service_common::arn::parse(topic_arn)
        .map(|arn| arn.account.to_string())
        .unwrap_or_default();
    let context = [
        (SOURCE_ARN_CONDITION_KEY.to_string(), topic_arn.to_string()),
        (SOURCE_ACCOUNT_CONDITION_KEY.to_string(), account.clone()),
        (SOURCE_OWNER_CONDITION_KEY.to_string(), account),
    ];
    let request =
        ::service_common::iam_authorization::Request::new(
            SEND_MESSAGE_ACTION,
            queue_arn,
            &principals,
        )
        .with_context(&context);
    let stated = ::service_common::iam_authorization::resource_decision(policy, &request);
    ::service_common::iam_authorization::is_allowed(
        // SNS holds no identity-based policies: a service principal's permission to reach
        // another service's resource comes from that resource's own policy.
        ::service_common::iam_authorization::Decision::NotStated,
        stated,
    )
}

/// What the queue at `queue_url` answered when its `Policy` was read: the document it
/// carries, none, or nothing at all.
///
/// A queue that does not answer the read is one no message can be handed to either — it was
/// deleted, or never existed — which is told apart from a queue that answered and carries no
/// policy, because the first is an undeliverable endpoint and the second is a queue that has
/// granted nothing.
async fn queue_policy(client: &::aws_sdk_sqs::Client, queue_url: &str) -> QueuePolicy {
    let answered = client
        .get_queue_attributes()
        .queue_url(queue_url)
        .attribute_names(::aws_sdk_sqs::types::QueueAttributeName::Policy)
        .send()
        .await;
    match answered {
        Ok(answer) => QueuePolicy::Stated(
            answer
                .attributes()
                .and_then(|attributes| {
                    attributes.get(&::aws_sdk_sqs::types::QueueAttributeName::Policy)
                })
                .cloned(),
        ),
        Err(error) => {
            ::tracing::warn!(
                queue = %queue_url,
                error = %::aws_smithy_types::error::display::DisplayErrorContext(&error),
                "a subscribed queue's policy could not be read"
            );
            QueuePolicy::Unreachable
        }
    }
}

/// An SQS client over the in-process callback into this same emulator.
fn sqs_client(
    ctx: &smithy_server_runtime::OperationContext<'_>,
    region: &str,
) -> ::aws_sdk_sqs::Client {
    let config = ::aws_sdk_sqs::Config::builder()
        .behavior_version(::aws_sdk_sqs::config::BehaviorVersion::latest())
        .http_client(ctx.callback().http_client())
        .credentials_provider(ctx.callback().aws_credentials_provider())
        .region(::aws_sdk_sqs::config::Region::new(region.to_string()))
        .endpoint_url(format!("https://sqs.{region}.amazonaws.com"))
        // The transport is in-process: there is nothing to retry, time out or watch for a
        // stalled stream, and each of those would need a sleep implementation this client is
        // not given. The same goes for caching the identity: the credentials are handed over
        // directly.
        .retry_config(::aws_sdk_sqs::config::retry::RetryConfig::disabled())
        .timeout_config(::aws_sdk_sqs::config::timeout::TimeoutConfig::disabled())
        .identity_cache(::aws_sdk_sqs::config::IdentityCache::no_cache())
        .stalled_stream_protection(
            ::aws_sdk_sqs::config::StalledStreamProtectionConfig::disabled(),
        )
        .build();
    ::aws_sdk_sqs::Client::from_conf(config)
}

/// The JSON notification SNS wraps a message in for a subscriber that has not asked for raw
/// delivery: "This eliminates the need for the endpoints to process JSON formatting, which is
/// otherwise created for Amazon SNS metadata."
/// (`GetSubscriptionAttributesResponse$Attributes`, `RawMessageDelivery`).
///
/// The envelope carries the metadata the message was published with — its type, id, topic,
/// subject, body, attributes and the instant it was published — and the link that cancels THE
/// SUBSCRIPTION IT IS DELIVERED TO, so it is rendered per subscriber rather than once per
/// publish. The `body` it wraps is the message the SUBSCRIBER's protocol receives, which is
/// the whole published message unless it was published as a structure of per-protocol
/// branches. It carries NO signature members (`Signature`, `SigningCertURL`): nothing signs a
/// message in this emulator, and a member that looked like a signature would be one a
/// subscriber could not verify.
fn notification_envelope(
    published: &PublishedMessage,
    body: &str,
    subscription_arn: &str,
) -> String {
    let mut envelope = serde_json::Map::new();
    envelope.insert(
        "Type".to_string(),
        serde_json::Value::from("Notification"),
    );
    envelope.insert(
        "MessageId".to_string(),
        serde_json::Value::from(published.message_id.as_str()),
    );
    envelope.insert(
        "TopicArn".to_string(),
        serde_json::Value::from(published.topic_arn.as_str()),
    );
    if let Some(subject) = published.subject.as_deref() {
        envelope.insert("Subject".to_string(), serde_json::Value::from(subject));
    }
    envelope.insert("Message".to_string(), serde_json::Value::from(body));
    if let Some(timestamp) = state::rfc3339(published.published_at) {
        envelope.insert("Timestamp".to_string(), serde_json::Value::from(timestamp));
    }
    if let Some(sequence_number) = published.sequence_number.as_deref() {
        envelope.insert(
            "SequenceNumber".to_string(),
            serde_json::Value::from(sequence_number),
        );
    }
    if let Some(url) = unsubscribe_url(&published.topic_arn, subscription_arn) {
        envelope.insert("UnsubscribeURL".to_string(), serde_json::Value::from(url));
    }
    if !published.message_attributes.is_empty() {
        // "MessageAttributes": {"<name>": {"Type": "<data type>", "Value": "<value>"}} — the
        // form the envelope carries a published attribute in. A binary value is carried as the
        // base64 text the wire form of `BinaryValue` already is.
        let mut attributes: Vec<(&String, &MessageAttributeValue)> =
            published.message_attributes.iter().collect();
        attributes.sort_by(|left, right| left.0.cmp(right.0));
        let rendered: serde_json::Map<String, serde_json::Value> = attributes
            .into_iter()
            .map(|(name, value)| {
                let mut attribute = serde_json::Map::new();
                attribute.insert(
                    "Type".to_string(),
                    serde_json::Value::from(value.data_type.as_str()),
                );
                let text = value.string_value.clone().or_else(|| {
                    value
                        .binary_value
                        .as_ref()
                        .map(::aws_smithy_types::base64::encode)
                });
                if let Some(text) = text {
                    attribute.insert("Value".to_string(), serde_json::Value::from(text));
                }
                (name.clone(), serde_json::Value::Object(attribute))
            })
            .collect();
        envelope.insert(
            "MessageAttributes".to_string(),
            serde_json::Value::Object(rendered),
        );
    }
    serde_json::Value::Object(envelope).to_string()
}

/// The call that cancels ONE subscription, as the notification delivered to it carries it:
/// the `Unsubscribe` action of the Region the topic is in, naming that subscription.
///
/// Each subscriber of a topic is handed the link to ITS OWN subscription, never a sibling's,
/// because following it ends the subscription it was delivered to. `None` for a topic whose
/// ARN names no Region, which addresses no regional endpoint.
fn unsubscribe_url(topic_arn: &str, subscription_arn: &str) -> Option<String> {
    let region = ::service_common::arn::region_of(topic_arn, SNS_ARN_NAMESPACE)?;
    Some(format!(
        "https://sns.{region}.amazonaws.com/?Action=Unsubscribe&\
         SubscriptionArn={subscription_arn}"
    ))
}

/// The ARN namespace of this service, which its topics' and subscriptions' ARNs name.
const SNS_ARN_NAMESPACE: &str = "sns";
