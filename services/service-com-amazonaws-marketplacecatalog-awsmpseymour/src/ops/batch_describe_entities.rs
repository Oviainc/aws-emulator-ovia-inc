impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for BatchDescribeEntities<Eng>
{
    type Input = BatchDescribeEntitiesInput;
    type Output = BatchDescribeEntitiesOutput;
    type Error = BatchDescribeEntitiesError;

    const NAME: &'static str = "BatchDescribeEntities";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::BATCH_DESCRIBE_ENTITIES_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::BATCH_DESCRIBE_ENTITIES_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(BatchDescribeEntitiesErrorModeled::InternalServiceException(
                InternalServiceException {
                    message: Some("the marketplace catalog store is unavailable".to_string()),
                },
            )
            .into());
        };

        // `EntityRequest$Catalog` documents the same fixed value every other
        // operation's `Catalog` does, and it selects the STORE the whole call
        // reads rather than one entry's record, so an entry naming another
        // catalog is a bad request rather than a missing entity: it is refused
        // for the whole call, before any entity is read.
        for request in &input.entity_request_list {
            if let Err(fault) = crate::state::check_catalog(&request.catalog) {
                return Err(BatchDescribeEntitiesErrorModeled::ValidationException(fault).into());
            }
        }

        let now = ::std::time::SystemTime::now();
        let mut store = state.lock();
        // An entity exists once the change set that creates it has succeeded,
        // which is a change the clock owes rather than one a reader makes.
        store.settle(now);

        // BOTH members are reported, empty maps included: a request for entities
        // the catalog does not hold answers `EntityDetails {}` beside the
        // `Errors` that say why, and a request that resolves every entity
        // answers `Errors {}`.
        let mut entity_details: ::std::collections::HashMap<String, EntityDetail> =
            ::std::collections::HashMap::new();
        let mut errors: ::std::collections::HashMap<String, BatchDescribeErrorDetail> =
            ::std::collections::HashMap::new();
        for request in &input.entity_request_list {
            // An entry's `EntityId` is judged PER ENTRY, not at the boundary
            // (`skip_validation` on `EntityRequest`): a batch read reports what
            // went wrong with one entry under that entry's own id and still
            // serves the rest, so one malformed id neither fails the call nor
            // costs the caller the entities the other entries asked for. The
            // form is checked before the lookup, so a malformed id is reported
            // as a validation failure and only a well-formed one as missing —
            // the same two answers, under the same two codes, a single read of
            // that entity gives.
            //
            // The entry is keyed by the id that was ASKED FOR, whatever that id
            // is: this operation's recorded answers report a malformed entry
            // under the value the caller sent, which is also the only key a
            // caller could look its own entry up by.
            if !crate::state::is_entity_id(&request.entity_id) {
                errors.insert(
                    request.entity_id.clone(),
                    BatchDescribeErrorDetail {
                        error_code: Some(crate::state::BATCH_ERROR_VALIDATION.to_string()),
                        // The sentence quotes the submitted id cut to the room
                        // it leaves, so an entry of any length is reported
                        // inside `BatchDescribeErrorMessageContent`'s 2048.
                        error_message: Some(crate::state::invalid_entity_id_message(
                            &request.entity_id,
                        )),
                    },
                );
                continue;
            }
            match store.entities.get(&request.entity_id) {
                Some(entity) => {
                    entity_details.insert(
                        request.entity_id.clone(),
                        EntityDetail {
                            entity_type: Some(entity.entity_type.clone()),
                            entity_identifier: Some(entity.identifier()),
                            entity_arn: Some(entity.arn.clone()),
                            last_modified_date: Some(entity.last_modified_date.clone()),
                            // `EntityDetail` carries the details as a document
                            // only; `None` is unreachable, since nothing deeper
                            // than the stored bound was accepted.
                            details_document: crate::state::json_to_document(&entity.details),
                        },
                    );
                }
                None => {
                    // A missing entity is NOT a top-level failure here: this
                    // operation models none for it, and reports it per entity
                    // under the id that was asked for.
                    errors.insert(
                        request.entity_id.clone(),
                        BatchDescribeErrorDetail {
                            error_code: Some(
                                crate::state::BATCH_ERROR_RESOURCE_NOT_FOUND.to_string(),
                            ),
                            error_message: Some(crate::state::entity_missing_message(
                                &request.entity_id,
                            )),
                        },
                    );
                }
            }
        }

        Ok(BatchDescribeEntitiesOutput {
            entity_details: Some(entity_details),
            errors: Some(errors),
        })
    }
}
