                    return Err(StartChangeSetErrorModeled::ValidationException(
                        crate::state::cannot_parse(
                            "ChangeSet.Details",
                            format!(
                                "the details of a change nest no deeper than {} levels",
                                crate::state::MAX_DETAILS_DEPTH
                            ),
                        ),
                    )
                    .into());
