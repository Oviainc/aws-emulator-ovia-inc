        // value, and a key it does not carry keeps the one the resource has.
        // Bounded, so repeated calls cannot grow one record's tag map without
        // limit.
        let merged = tags
            .keys()
            .filter(|key| !input.tags.contains_key(*key))
            .count()
            + input.tags.len();
