impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeServer<Eng>
{
    type Input = DescribeServerInput;
    type Output = DescribeServerOutput;
    type Error = DescribeServerError;

    const NAME: &'static str = "DescribeServer";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_SERVER_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_SERVER_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        use crate::state as st;

        // WHO is asking is decided before anything is read: a caller whose identity
        // policy explicitly denies this action on this server is refused with
        // `AccessDeniedException` (HTTP 403). The gate reads the account's own IAM
        // store — see `crate::state::authorization`.
        let resource = st::server_arn(&st::request_region(ctx.parts()), &input.server_id);
        if let Some(message) = st::authorization::explicit_deny(
            &*self.engine,
            ctx.parts(),
            Self::NAME,
            Some(&resource),
        ) {
            return Err(DescribeServerErrorModeled::AccessDeniedException(
                AccessDeniedException {
                    message: Some(message),
                },
            )
            .into());
        }
        let state = st::service_state(&*self.engine).ok_or_else(|| {
            DescribeServerErrorModeled::InternalServiceError(InternalServiceError {
                message: "the transfer service state is unavailable".to_string(),
            })
        })?;

        let now = ::std::time::Instant::now();
        let mut guard = state.lock();

        // `UserCount` first, so the lookup below is the ONLY one and there is no
        // unreachable second 404 branch.
        let user_count = guard.user_count(&input.server_id);
        let Some(stored) = guard.servers.get_mut(&input.server_id) else {
            return Err(st::not_found(
                DescribeServerErrorModeled::ResourceNotFoundException(st::unknown_server(
                    &input.server_id,
                )),
            ));
        };

        // Settle ONLY the server being described — the single write this reporting
        // operation makes, and only for a change the clock already owed at `now`.
        // `ListServers` needs the bulk form; a single-resource read does not.
        stored.settle(now);

        let server = DescribedServer {
            arn: stored.arn.clone(),
            certificate: stored.certificate.clone(),
            protocol_details: Some(stored.protocol_details.clone()),
            domain: Some(stored.domain.clone()),
            endpoint_details: stored.endpoint_details.clone(),
            endpoint_type: Some(stored.endpoint_type.clone()),
            host_key_fingerprint: Some(stored.host_key_fingerprint.clone()),
            identity_provider_details: stored.identity_provider_details.clone(),
            identity_provider_type: Some(stored.identity_provider_type.clone()),
            // The logging members are reported ONLY when the server has them
            // configured: a server with a `LoggingRole` and no structured destination
            // publishes to the service-managed log group, and the ABSENCE of
            // `StructuredLogDestinations` is what tells the caller so. See
            // `state::configured_log_destinations`.
            logging_role: stored.logging_role.clone(),
            post_authentication_login_banner: stored.post_authentication_login_banner.clone(),
            pre_authentication_login_banner: stored.pre_authentication_login_banner.clone(),
            protocols: Some(stored.protocols.clone()),
            security_policy_name: Some(stored.security_policy_name.clone()),
            server_id: Some(stored.server_id.clone()),
            state: Some(stored.state.clone()),
            // The server's tag set, as a list — EMPTY when nothing is tagged, which is
            // what the service reports for an untagged server. `Tags`' modelled
            // `len 1..50` bounds what a caller may SEND on a tagging request, not what
            // a description of the server reports.
            tags: Some(stored.tags.clone()),
            user_count: Some(user_count),
            workflow_details: stored.workflow_details.clone(),
            structured_log_destinations: stored.structured_log_destinations.clone(),
            s3_storage_options: Some(stored.s3_storage_options.clone()),
            // Egress IPs are only meaningful for AS2 servers and the emulator runs no
            // AS2 transport, so there is nothing to report.
            as2_service_managed_egress_ip_addresses: None,
            ip_address_type: Some(stored.ip_address_type.clone()),
        };

        Ok(DescribeServerOutput { server })
    }
}
