//! End-to-end suite for the status changes this service makes on its OWN against a
//! budget action, and the history records they leave behind — driven over the wire
//! through the same `MultiServiceRouter` the production router serves from.
//!
//! The RULE these tables assert: an action's history is the audit log of its status
//! changes ("the status of action at the time of the event", `ActionHistory$Status`), so
//! a status change no caller made — the completion of `*_IN_PROGRESS` work — is recorded
//! too, as ONE record carrying the settled status, the action as that change left it,
//! and the `EventType` the model keeps for events "generated by the system" rather than
//! "triggered by the user". The newest history record therefore always reports the
//! status `DescribeBudgetAction` reports.
//!
//! Each table spans that class rather than one request: its rows differ along the status
//! the action starts in, the `ExecutionType` that is run and the settled status it
//! reaches — every settled status this state machine can leave an action in — and the
//! sequencing test runs several executions over one action in a row.
//!
//! The harness is the lifecycle suite's and the setup helpers are the execution and
//! history suites', so every suite in this target drives the service identically.

use serde_json::Value;
use std::time::Duration;

/// The `EventType` catalog is not re-typed here: this is the model-derived constant the
/// scaffold generated into `src/ops/types/shared_types.rs`, so a table built from it
/// cannot drift from the model.
use service_com_amazonaws_budgets_awsbudgetservicegateway::ops::types::EVENT_TYPE_VALUES;
use service_com_amazonaws_budgets_awsbudgetservicegateway::state::{
    ACTION_SETTLES_AFTER, ACTION_STATUS_EXECUTION_FAILURE, ACTION_STATUS_EXECUTION_IN_PROGRESS,
    ACTION_STATUS_EXECUTION_SUCCESS, ACTION_STATUS_PENDING, ACTION_STATUS_RESET_FAILURE,
    ACTION_STATUS_RESET_IN_PROGRESS, ACTION_STATUS_REVERSE_FAILURE,
    ACTION_STATUS_REVERSE_IN_PROGRESS, ACTION_STATUS_REVERSE_SUCCESS, ACTION_STATUS_STANDBY,
    EVENT_TYPE_CREATE_ACTION, EVENT_TYPE_EXECUTE_ACTION, EVENT_TYPE_SYSTEM, EXECUTION_TYPE_APPROVE,
    EXECUTION_TYPE_RESET, EXECUTION_TYPE_RETRY, EXECUTION_TYPE_REVERSE,
};

use super::budget_action_execution::{
    describe_action, execute_action, make_settle_due, read_status, seed_action, seed_budget,
    seed_pending_action, seed_status,
};
use super::budget_action_history::read_history;
use super::budget_lifecycle::{caller_account, router, router_with_engine, same};

/// One row of the settle table: the status the action starts in, the execution run from
/// it, the `*_IN_PROGRESS` status that execution takes immediately and the status the
/// service settles it to with no further call.
///
/// The rows are every (status, `ExecutionType`) pair this state machine accepts, which
/// is the set the execution suite asserts the status moves of — here each one is read
/// through its HISTORY. `ActionStatus` has no `RESET_SUCCESS`, so a completed reset
/// leaves the action in the armed status it started life in.
struct Row {
    case: &'static str,
    from: &'static str,
    execution_type: &'static str,
    in_progress: &'static str,
    settled: &'static str,
}

/// The settle table.
fn settle_rows() -> Vec<Row> {
    vec![
        Row {
            case: "approve an action waiting for its manual approval",
            from: ACTION_STATUS_PENDING,
            execution_type: EXECUTION_TYPE_APPROVE,
            in_progress: ACTION_STATUS_EXECUTION_IN_PROGRESS,
            settled: ACTION_STATUS_EXECUTION_SUCCESS,
        },
        Row {
            case: "reverse an applied action",
            from: ACTION_STATUS_EXECUTION_SUCCESS,
            execution_type: EXECUTION_TYPE_REVERSE,
            in_progress: ACTION_STATUS_REVERSE_IN_PROGRESS,
            settled: ACTION_STATUS_REVERSE_SUCCESS,
        },
        Row {
            case: "reset an applied action",
            from: ACTION_STATUS_EXECUTION_SUCCESS,
            execution_type: EXECUTION_TYPE_RESET,
            in_progress: ACTION_STATUS_RESET_IN_PROGRESS,
            settled: ACTION_STATUS_STANDBY,
        },
        Row {
            case: "reset a reversed action",
            from: ACTION_STATUS_REVERSE_SUCCESS,
            execution_type: EXECUTION_TYPE_RESET,
            in_progress: ACTION_STATUS_RESET_IN_PROGRESS,
            settled: ACTION_STATUS_STANDBY,
        },
        Row {
            case: "retry a failed execution",
            from: ACTION_STATUS_EXECUTION_FAILURE,
            execution_type: EXECUTION_TYPE_RETRY,
            in_progress: ACTION_STATUS_EXECUTION_IN_PROGRESS,
            settled: ACTION_STATUS_EXECUTION_SUCCESS,
        },
        Row {
            case: "retry a failed reversal",
            from: ACTION_STATUS_REVERSE_FAILURE,
            execution_type: EXECUTION_TYPE_RETRY,
            in_progress: ACTION_STATUS_REVERSE_IN_PROGRESS,
            settled: ACTION_STATUS_REVERSE_SUCCESS,
        },
        Row {
            case: "retry a failed reset",
            from: ACTION_STATUS_RESET_FAILURE,
            execution_type: EXECUTION_TYPE_RETRY,
            in_progress: ACTION_STATUS_RESET_IN_PROGRESS,
            settled: ACTION_STATUS_STANDBY,
        },
    ]
}

/// The `EventType` of one history record.
fn event_type(record: &Value) -> Option<&str> {
    record.get("EventType").and_then(Value::as_str)
}

/// The `Status` of one history record — "the status of action at the time of the event".
fn status_of(record: &Value) -> Option<&str> {
    record.get("Status").and_then(Value::as_str)
}

/// The `ActionHistoryDetails$Action` of one history record: the action as the event left
/// it.
fn recorded_action(record: &Value) -> Value {
    record
        .get("ActionHistoryDetails")
        .and_then(|details| details.get("Action"))
        .cloned()
        .unwrap_or(Value::Null)
}

/// The `Timestamp` of one history record, in epoch seconds.
fn timestamp(record: &Value) -> f64 {
    record
        .get("Timestamp")
        .and_then(Value::as_f64)
        .unwrap_or(-1.0)
}

/// RULE row 1: whatever execution settles, the settle appends exactly ONE record whose
/// `EventType` is the system value, whose `Status` is the settled status and whose
/// details carry the action as the settle left it — over every (status, `ExecutionType`)
/// pair the state machine accepts.
#[tokio::test]
async fn a_settle_appends_one_system_event_carrying_the_settled_status() {
    assert!(
        EVENT_TYPE_VALUES.contains(&EVENT_TYPE_SYSTEM),
        "setup: expected the modelled EventType catalog to carry {EVENT_TYPE_SYSTEM}, got \
         {EVENT_TYPE_VALUES:?}"
    );

    let (router, engine) = router_with_engine();
    let account_id = caller_account();
    for row in settle_rows() {
        let budget_name = format!("settle-{}", row.case.replace(' ', "-"));
        seed_budget(&router, &account_id, &budget_name).await;
        let action_id = seed_action(&router, &account_id, &budget_name).await;
        seed_status(&engine, &account_id, &budget_name, &action_id, row.from);

        let (http, body) = execute_action(
            &router,
            &account_id,
            &budget_name,
            &action_id,
            row.execution_type,
        )
        .await;
        assert_eq!(
            http, 200,
            "case {}: expected the execution to be accepted with 200, got {http} {body}",
            row.case
        );

        // Bring the owed settle forward rather than waiting it out; the clock making it
        // on its own is asserted in `the_clock_alone_appends_the_system_event`.
        make_settle_due(&engine, &account_id, &budget_name, &action_id);

        let records =
            read_history(&router, &account_id, &budget_name, &action_id, None, row.case).await;
        assert_eq!(
            records.len(),
            3,
            "case {}: expected the create, the execute and the settle event, got {records:?}",
            row.case
        );
        assert_eq!(
            event_type(&records[0]),
            Some(EVENT_TYPE_CREATE_ACTION),
            "case {}: expected the oldest record to stay the create event, got {}",
            row.case,
            records[0]
        );
        assert_eq!(
            event_type(&records[1]),
            Some(EVENT_TYPE_EXECUTE_ACTION),
            "case {}: expected the caller's execute event, got {}",
            row.case,
            records[1]
        );
        assert_eq!(
            status_of(&records[1]),
            Some(row.in_progress),
            "case {}: expected the execute event to keep the status it was recorded at, got {}",
            row.case,
            records[1]
        );

        let settle = &records[2];
        assert_eq!(
            event_type(settle),
            Some(EVENT_TYPE_SYSTEM),
            "case {}: expected the settle to be recorded as a system event, got {settle}",
            row.case
        );
        assert_eq!(
            status_of(settle),
            Some(row.settled),
            "case {}: expected the settle record to carry the settled status, got {settle}",
            row.case
        );
        let left_behind = recorded_action(settle);
        assert_eq!(
            left_behind.get("Status").and_then(Value::as_str),
            Some(row.settled),
            "case {}: expected the record to carry the action as the settle left it, got \
             {left_behind}",
            row.case
        );
        assert!(
            settle
                .get("ActionHistoryDetails")
                .and_then(|details| details.get("Message"))
                .and_then(Value::as_str)
                .is_some_and(|message| !message.is_empty()),
            "case {}: expected a Message describing the event, got {settle}",
            row.case
        );
        assert!(
            timestamp(settle) >= timestamp(&records[1]),
            "case {}: expected the settle to be recorded no earlier than the execute that \
             started it, got {:?}",
            row.case,
            records.iter().map(timestamp).collect::<Vec<f64>>()
        );

        // The two reads agree: the newest record is the status the action itself reports.
        let read = read_status(&router, &account_id, &budget_name, &action_id).await;
        assert_eq!(
            read, row.settled,
            "case {}: expected the action read to report the settled status, got {read:?}",
            row.case
        );
        let action = describe_action(&router, &account_id, &budget_name, &action_id)
            .await
            .1;
        assert!(
            same(&left_behind, &action["Action"]),
            "case {}: expected the newest record to carry the action the read reports {}, got \
             {left_behind}",
            row.case,
            action["Action"]
        );
    }
}

/// RULE row 2: the settle is owed to the CLOCK, so its record appears with no further
/// call — and it appears ONCE: a read that materialises it does not append a second one,
/// however often the history is read.
#[tokio::test]
async fn the_clock_alone_appends_the_system_event() {
    let router = router();
    let account_id = caller_account();
    let budget_name = "settles-on-the-clock";
    seed_budget(&router, &account_id, budget_name).await;
    let action_id = seed_pending_action(&router, &account_id, budget_name).await;

    let (http, body) = execute_action(
        &router,
        &account_id,
        budget_name,
        &action_id,
        EXECUTION_TYPE_APPROVE,
    )
    .await;
    assert_eq!(
        http, 200,
        "case clock: expected the approval to be accepted with 200, got {http} {body}"
    );

    // No call makes the move: the span passes and the record is there.
    tokio::time::sleep(ACTION_SETTLES_AFTER + Duration::from_millis(250)).await;
    let settled =
        read_history(&router, &account_id, budget_name, &action_id, None, "clock").await;
    assert_eq!(
        settled.len(),
        3,
        "case clock: expected the clock to add the settle event, got {settled:?}"
    );
    assert_eq!(
        event_type(&settled[2]),
        Some(EVENT_TYPE_SYSTEM),
        "case clock: expected the newest record to be the system settle, got {}",
        settled[2]
    );
    assert_eq!(
        status_of(&settled[2]),
        Some(ACTION_STATUS_EXECUTION_SUCCESS),
        "case clock: expected the settled status on the newest record, got {}",
        settled[2]
    );

    // And reading it again changes nothing a later caller sees: the settle is recorded
    // once, not once per read.
    for round in 0..3 {
        let case = format!("round-{round}");
        let again = read_history(
            &router,
            &account_id,
            budget_name,
            &action_id,
            Some(1),
            &case,
        )
        .await;
        assert!(
            same(
                &Value::Array(again.clone()),
                &Value::Array(settled.clone())
            ),
            "case {case}: expected the same history {settled:?}, got {again:?}"
        );
    }
}

/// RULE row 3, over a SEQUENCE: each execution and the settle that completes it appends
/// its own record, in the order they happened — so a history read oldest-first alternates
/// the caller's execute events with the system settles, and the newest record is always
/// the status the action carries.
#[tokio::test]
async fn each_execution_and_its_settle_are_recorded_in_order() {
    let (router, engine) = router_with_engine();
    let account_id = caller_account();
    let budget_name = "settle-sequence";
    seed_budget(&router, &account_id, budget_name).await;
    let action_id = seed_pending_action(&router, &account_id, budget_name).await;

    // One execution per settled status this state machine reaches, run back to back over
    // ONE action: approve it, reverse it, then re-arm it.
    let sequence = [
        (EXECUTION_TYPE_APPROVE, ACTION_STATUS_EXECUTION_SUCCESS),
        (EXECUTION_TYPE_REVERSE, ACTION_STATUS_REVERSE_SUCCESS),
        (EXECUTION_TYPE_RESET, ACTION_STATUS_STANDBY),
    ];
    let mut expected: Vec<(String, String)> = vec![(
        EVENT_TYPE_CREATE_ACTION.to_string(),
        ACTION_STATUS_PENDING.to_string(),
    )];
    for (execution_type, settled) in sequence {
        let case = format!("{execution_type} -> {settled}");
        let in_progress = read_status_after_execute(
            &router,
            &account_id,
            budget_name,
            &action_id,
            execution_type,
            &case,
        )
        .await;
        expected.push((EVENT_TYPE_EXECUTE_ACTION.to_string(), in_progress));
        make_settle_due(&engine, &account_id, budget_name, &action_id);
        expected.push((EVENT_TYPE_SYSTEM.to_string(), settled.to_string()));

        let records =
            read_history(&router, &account_id, budget_name, &action_id, Some(2), &case).await;
        let reported: Vec<(String, String)> = records
            .iter()
            .map(|record| {
                (
                    event_type(record).unwrap_or_default().to_string(),
                    status_of(record).unwrap_or_default().to_string(),
                )
            })
            .collect();
        assert_eq!(
            reported, expected,
            "case {case}: expected the history {expected:?} oldest first, got {reported:?}"
        );
        let timestamps: Vec<f64> = records.iter().map(timestamp).collect();
        assert!(
            timestamps.windows(2).all(|pair| pair[0] <= pair[1]),
            "case {case}: expected the history oldest first, got timestamps {timestamps:?}"
        );
        let read = read_status(&router, &account_id, budget_name, &action_id).await;
        assert_eq!(
            read,
            records
                .last()
                .and_then(status_of)
                .unwrap_or_default()
                .to_string(),
            "case {case}: expected the newest record to agree with the action read, got \
             {read:?} against {records:?}"
        );
    }
}

/// Run one execution and answer the `*_IN_PROGRESS` status it left the action in.
async fn read_status_after_execute(
    router: &smithy_server_runtime::MultiServiceRouter,
    account_id: &str,
    budget_name: &str,
    action_id: &str,
    execution_type: &str,
    case: &str,
) -> String {
    let (http, body) =
        execute_action(router, account_id, budget_name, action_id, execution_type).await;
    assert_eq!(
        http, 200,
        "case {case}: expected the execution to be accepted with 200, got {http} {body}"
    );
    read_status(router, account_id, budget_name, action_id).await
}
