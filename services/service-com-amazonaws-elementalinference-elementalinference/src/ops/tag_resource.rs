//! @op TagResource
//!
//! Associates tags with a feed or a dictionary: the tags are written onto the ONE
//! stored record every other handler of this service reads, so a tag added here is a
//! tag `GetFeed`/`GetDictionary` reports, and `DeleteFeed`/`DeleteDictionary` take the
//! resource's tags with it when the record goes ("When a resource is deleted, the tags
//! associated with that resource are also deleted").
//!
//! The write is a MERGE, not a replacement: each key the request carries is set to the
//! value it carries, and "if existing tags on a resource are not specified in the
//! request parameters, they are not changed". Setting a key the resource already holds
//! overwrites that key's value and leaves the rest alone, which is also why the
//! operation is `@idempotent` — the same request twice leaves the same tag set.
//!
