//! @op TagResource
//!
//! Adds the request's key-value pairs to the monitor or probe its `resourceArn`
//! names, overwriting the value of a key the resource already carries and
//! leaving every other stored key alone. The tags live in the resource's own
//! record ([`crate::state`]), so what this write stores is what `GetMonitor`
//! reports afterwards — for the monitor itself and for each probe it lists — and
//! an ARN no stored resource answers to is refused with the code AWS's tagging
//! facade answers rather than the modelled one: 404 `NotFoundException`
//! ([`crate::scaffolded::TAG_NOT_FOUND_CODE`]).
//!
//! A write that lands in a PROBE rewrites a record the monitor holds and every
//! read of the monitor reports, so it changed the monitor too and the monitor's
//! own `modifiedAt` moves with the probe's
//! ([`crate::state::Monitor::follow_probe_write`]), exactly as a create, update
//! or delete of a probe moves it.
//!
//! A resource whose teardown has already been accepted is not a target for this
//! write either: it is on its way out, so an ARN naming it is refused with the
//! same 404
//! ([`crate::state::ComAmazonawsNetworkmonitorNetworkmonitorState::resolve_tagged_resource_for_mutation`]),
//! exactly as `UpdateProbe` refuses an update of it, while the reads of the
//! service keep reporting it until the clock has carried its teardown through.
//!
//! A key AWS reserves for its own tags
//! ([`crate::state::RESERVED_TAG_KEY_PREFIX`]) is not a key a caller may assign,
//! so a request naming one is refused with the modelled 400
//! `ValidationException` ([`crate::state::check_tag_keys`]) and stores none of
//! the pairs it carried.
//!
