                    return Err(CreateAssetFilterErrorModeled::ValidationException(
                        ValidationException {
                            message: format!(
                                "rowFilter holds more than {MAX_ROW_FILTER_NODES} expressions and groups, which is the most this emulator evaluates"
                            ),
                        },
                    )
                    .into());
