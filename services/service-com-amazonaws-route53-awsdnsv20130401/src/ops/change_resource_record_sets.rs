/// An `InvalidChangeBatch` naming one problem per refused change.
///
/// The shape carries both a `messages` LIST — "This exception contains a list of
/// messages that might contain one or more error messages. Each error message
/// indicates one error in the change batch" — and the single `message` an SDK
/// surfaces, so both are filled from the same list: `messages` holds one entry
/// per refused change, and `message` is that list rendered as a list, in
/// brackets, so a caller that reads only the flat member still sees every entry
/// and can tell one from several.
fn invalid_change_batch(problems: Vec<String>) -> InvalidChangeBatch {
    InvalidChangeBatch {
        message: Some(format!("[{}]", problems.join(", "))),
        messages: Some(problems),
    }
}

/// Record one problem, up to [`MAX_REPORTED_CHANGE_PROBLEMS`]; past that only
/// count it, so a thousand-change batch cannot amplify the error body.
#[derive(Debug, Default)]
struct Problems {
    reported: Vec<String>,
    suppressed: usize,
}

impl Problems {
    fn push(&mut self, problem: String) {
        if self.reported.len() < MAX_REPORTED_CHANGE_PROBLEMS {
            self.reported.push(problem);
        } else {
            self.suppressed += 1;
        }
    }

    fn is_empty(&self) -> bool {
        self.reported.is_empty()
    }

    /// The messages to report, with a final line counting what was suppressed.
    fn into_messages(mut self) -> Vec<String> {
        if self.suppressed > 0 {
            self.reported.push(format!(
                "and {} further problems not reported",
                self.suppressed
            ));
        }
        self.reported
    }
}

/// How a change names the record set it was refused over: `[name='<name>',
/// type='<type>']`, and `set-identifier='<id>'` as well when the record set
/// carries one.
///
/// The record is named by what IDENTIFIES it — the name it answers for, its
/// record type and, for a member of a routing group, the identifier that tells
/// it from its siblings — so a caller with several changes in one batch can tell
/// which one was refused, and a caller whose group reuses an identifier can tell
/// a collision on one sibling from a collision on the whole name-and-type group.
/// Nothing internal to this handler goes in: the action is already stated by the
/// sentence the label sits in, and a member the request did not give is not
/// reported as a literal `null`.
fn change_label(record: &ResourceRecordSet) -> String {
    record_set_label(&record.name, &record.r#type, set_identifier_of(record))
}

/// The `SetIdentifier` a record set carries, if it carries one.
///
/// A member the request left out and a member it sent empty are the same thing
