impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ListGraphs<Eng>
{
    type Input = ListGraphsInput;
    type Output = ListGraphsOutput;
    type Error = ListGraphsError;

    const NAME: &'static str = "ListGraphs";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_GRAPHS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_GRAPHS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            ListGraphsErrorModeled::InternalServerException(InternalServerException {
                message: Some("the behavior graph store is unavailable".to_string()),
            })
        })?;

        // The page size is the server's own decision, clamped whatever the request
        // asked for, so no allocation below is sized by input.
        let page_size = crate::state::page_size(input.max_results);
        let start = input.next_token.as_deref().map(next_graph_arn).transpose()?;

        let store = state.lock();
        let mut remaining = match &start {
            Some(arn) => store.graphs.range(arn.clone()..),
            None => store.graphs.range::<String, _>(..),
        };

        // Reserve no more than the store can actually yield.
        let mut graph_list = Vec::with_capacity(page_size.min(store.graphs.len()));
        let mut next_token = None;
        for (arn, graph) in remaining.by_ref() {
            // The first graph that does not fit becomes the next page's start, and
            // only then is a `NextToken` emitted: the last page carries none.
            if graph_list.len() == page_size {
                next_token = Some(crate::state::encode_page_token(arn));
                break;
            }
            graph_list.push(graph.detail());
        }

        Ok(ListGraphsOutput {
            graph_list: Some(graph_list),
            next_token,
        })
    }
}
