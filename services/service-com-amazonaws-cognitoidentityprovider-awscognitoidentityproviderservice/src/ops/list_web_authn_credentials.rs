/// What separates the two parts of a [`listing_key`]: the unit separator, a
/// character no credential id carries, so the key splits nowhere else.
const LISTING_KEY_SEPARATOR: char = '\u{1f}';

/// The key one passkey credential takes in this listing's ascending order.
///
/// `WebAuthnCredentialDescription.CreatedAt` is "the date and time when the
/// item was created" (this service's model) and a completed registration
/// appends to what the user holds, so ordering the credentials by creation
/// instant is ordering them by registration. The instant is rendered as
/// fixed-width nanoseconds since the epoch so the keys compare in that order as
/// strings, and the credential id — which identifies ONE passkey — follows it,
/// so two credentials registered at the same instant still take a total order a
/// page token can index into.
fn listing_key(credential: &crate::state::WebAuthnCredential) -> String {
    let created_at = credential
        .created_at
        .duration_since(::std::time::UNIX_EPOCH)
        .map(|since| since.as_nanos())
        .unwrap_or_default();
    format!(
        "{created_at:020}{LISTING_KEY_SEPARATOR}{}",
        credential.credential_id
    )
}

