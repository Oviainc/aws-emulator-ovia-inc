/// The filter names this operation's `Filters` member documents: "`tenant-db-name`",
/// "`tenant-database-resource-id`" and "`dbi-resource-id`". RDS refuses any other name, and
/// so does this operation — with a 400, because quietly ignoring a filter would report
/// tenant databases the caller excluded.
const SUPPORTED_FILTER_NAMES: [&str; 3] = [
    "tenant-db-name",
    "tenant-database-resource-id",
    "dbi-resource-id",
];

/// Refuse a filter this operation does not support. "Filter names are case-sensitive."
fn check_filter_names(filters: &[Filter]) -> Result<(), String> {
    for filter in filters {
        if !SUPPORTED_FILTER_NAMES.contains(&filter.name.as_str()) {
            return Err(format!(
                "unrecognized filter name: {}; supported filters are {}",
                filter.name,
                SUPPORTED_FILTER_NAMES.join(", ")
            ));
        }
    }
    Ok(())
}

/// Whether `record` matches one filter: true when any of the filter's values matches the
/// member that filter names. "Filter values are case-sensitive."
fn matches_filter(record: &crate::state::TenantDatabaseRecord, filter: &Filter) -> bool {
    filter.values.iter().any(|wanted| match filter.name.as_str() {
        "tenant-db-name" => *wanted == record.tenant_db_name,
        "tenant-database-resource-id" => *wanted == record.resource_id,
        "dbi-resource-id" => *wanted == record.dbi_resource_id,
        // Unreachable: `check_filter_names` has already refused every name outside
        // `SUPPORTED_FILTER_NAMES`. A `&str` match needs the arm all the same.
        _ => false,
    })
}
