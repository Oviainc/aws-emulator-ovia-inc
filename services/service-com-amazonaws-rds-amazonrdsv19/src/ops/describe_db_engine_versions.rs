/// Whether `engine` is a CLUSTER engine — one whose instances are members of a DB
/// cluster, which owns their storage and their endpoints: the Aurora engines, and the
/// Amazon DocumentDB and Amazon Neptune engines this same front door serves
/// (`src/service.rs`).
///
/// `pub(crate)` because `DescribeOrderableDBInstanceOptions` reports on the same engines
/// and must not disagree with this report about which of them are cluster engines.
pub(crate) fn is_cluster_engine(engine: &str) -> bool {
    crate::state::is_aurora(engine) || serves_another_control_plane(engine)
}

/// Whether `engine` belongs to ANOTHER control plane this one front door serves: the
/// Amazon DocumentDB and Amazon Neptune engines, whose own APIs (`aws docdb …`,
/// `aws neptune …`) are served on this endpoint because all three models publish the same
/// wire identity (`src/service.rs`). Their names are the valid values documented on
/// `CreateDBClusterMessage$Engine` in those models, and are not values THIS model's
/// `Engine` member lists.
///
/// `pub(crate)` because `DescribeOrderableDBInstanceOptions` reports on the same engines.
pub(crate) fn serves_another_control_plane(engine: &str) -> bool {
    matches!(engine, "docdb" | "neptune")
}

/// Whether a DEFAULT engine version resolves for `engine` on this front door — what
/// `DefaultOnly` selects, and so what decides between a report and an
/// `InvalidParameterCombination` refusal.
///
/// An engine this door reports on behalf of ANOTHER control plane
/// ([`serves_another_control_plane`]), whose own API owns the engine version a cluster is
/// created with (`CreateDBClusterMessage$EngineVersion` in those models: "The
/// --engine-version will default to the latest major engine version"), publishes NO
/// default version here: the default-version registry this report reads is the RDS DB
/// instance engines' own. Recorded behaviour on the DocumentDB engine is this refusal, not
/// an answer naming a version. The versions themselves are still reported; only the
/// DEFAULT of them is not a thing this door resolves.
fn resolves_a_default_version(engine: &str) -> bool {
    !serves_another_control_plane(engine)
}

/// The engine facts of `engine`, or `None` for an engine this service reports no
/// versions for (the `custom-oracle-*` engines, and any value that is not an engine).
pub(crate) fn engine_facts(engine: &str) -> Option<&'static EngineFacts> {
    ENGINES.iter().find(|facts| facts.engine == engine)
}

/// The catalogue version this service would PROVISION for `engine` when a create or
/// modify request names `requested`, or `Err` with the message to refuse the request
/// with.
///
/// `DBInstance$EngineVersion` is "the version of the database engine" an instance RUNS,
/// not the string a request carried: a request names a version to provision and the
/// service answers with the version it provisioned, which is one of the versions it
/// publishes as available. The resolution, against [`CATALOG`]:
///
/// * no value — the engine's own default version, which is what RDS provisions when a
///   request names none;
/// * a value naming an available version of that engine (case-insensitively) — that
///   version;
/// * a value naming a published MAJOR version (`8.0`, `16`) — that major version's
///   default available version, which is what serves a request naming only the major
///   version;
/// * any other value — `Err`: it names no version this service can provision.
///
/// `Ok(None)` means the catalogue publishes no AVAILABLE version for `engine` at all
/// (a `custom-*` engine, whose versions a customer creates, or a value that is not an
/// engine): there is nothing to resolve against, so the caller keeps what the request
/// named rather than moving it to another engine's version.
pub(crate) fn resolve_version(
    engine: &str,
    requested: Option<&str>,
) -> Result<Option<&'static CatalogVersion>, String> {
    let available: Vec<&'static CatalogVersion> = CATALOG
        .iter()
        .filter(|entry| {
            entry.engine.eq_ignore_ascii_case(engine) && entry.status == STATUS_AVAILABLE
        })
        .collect();
    if available.is_empty() {
        return Ok(None);
    }
    let Some(requested) = requested else {
        return Ok(Some(default_version_of(&available)));
    };
    if let Some(exact) = available
        .iter()
        .find(|entry| entry.engine_version.eq_ignore_ascii_case(requested))
    {
        return Ok(Some(exact));
    }
    // A value that names a MAJOR version this service publishes resolves to that major
    // version's default: naming only the major version (`8.0`, `16`) is what RDS lets a
    // request do. A value that is neither an available version NOR a published major
    // version names no version this service can provision — `8.0.99` is not `8.0` — so
    // it is refused rather than quietly moved onto a version the caller did not ask
    // for, which is what the real service answers for it.
    let within: Vec<&'static CatalogVersion> = available
        .iter()
        .copied()
        .filter(|entry| entry.major_engine_version.eq_ignore_ascii_case(requested))
        .collect();
    if !within.is_empty() {
        return Ok(Some(default_version_of(&within)));
    }
    Err(format!("Cannot find version {requested} for {engine}"))
}

/// The version `entries` resolves to: the engine's own default, else the default of the
/// major version, else the last of them — [`CATALOG`] lists an engine's rows in
/// ascending version order, so that is its latest.
fn default_version_of(entries: &[&'static CatalogVersion]) -> &'static CatalogVersion {
    entries
        .iter()
        .copied()
        .find(|entry| entry.default_level.is_engine_default())
        .or_else(|| {
            entries
                .iter()
                .copied()
                .find(|entry| entry.default_level.is_major_default())
        })
        .or_else(|| entries.iter().copied().next_back())
        .expect("entries is never empty: the caller checks")
}

/// Every catalogue entry with its index and its engine's facts.
///
/// A row naming an engine absent from [`ENGINES`] could not be projected onto the wire
/// shape — there would be nothing to report for `DBEngineDescription` and the log,
/// character-set and time-zone members — so it is skipped rather than half-reported. The
/// two tables are written together and no row does this today, which makes the skip a
/// guard rather than a behaviour.
pub(crate) fn catalogue() -> impl Iterator<Item = (usize, &'static CatalogVersion, &'static EngineFacts)>
{
    CATALOG
        .iter()
        .enumerate()
        .filter_map(|(index, entry)| engine_facts(entry.engine).map(|facts| (index, entry, facts)))
}

/// Whether the catalogue carries `major_engine_version` for `engine`, at the
/// major-version granularity the option group operations take
/// (`CreateOptionGroup$MajorEngineVersion`).
///
/// `pub(crate)` because an operation that takes a `MajorEngineVersion` must resolve it
/// against the SAME catalogue this operation reports: a major version no entry of that
/// engine carries is one this service publishes no version for, so an option group
/// cannot be associated with it. Engine names are matched case-insensitively, the way
/// the describe operations match them.
pub(crate) fn offers_major_engine_version(engine: &str, major_engine_version: &str) -> bool {
    CATALOG.iter().any(|entry| {
        entry.engine.eq_ignore_ascii_case(engine)
            && entry
                .major_engine_version
                .eq_ignore_ascii_case(major_engine_version)
    })
}

/// Whether `entry` is in the report this request asks for.
fn matches_request(
    entry: &CatalogVersion,
    input: &DescribeDBEngineVersionsInput,
    filters: &[Filter],
) -> bool {
    // `IncludeAll`: "Specifies whether to also list the engine versions that aren't
    // available. The default is to list only available engine versions."
    if input.include_all != Some(true) && entry.status != STATUS_AVAILABLE {
        return false;
    }
    // `Engine`: "The database engine to return version details for."
    if let Some(engine) = &input.engine {
        if !entry.engine.eq_ignore_ascii_case(engine) {
            return false;
        }
    }
    // `EngineVersion`: "A specific database engine version to return details for" —
    // matched either exactly or by the major version it belongs to, the "engine and
    // major version combination" `DefaultOnly` names.
    if let Some(version) = &input.engine_version {
        if !entry.engine_version.eq_ignore_ascii_case(version)
            && !entry.major_engine_version.eq_ignore_ascii_case(version)
        {
            return false;
        }
    }
    // `DBParameterGroupFamily`: "The name of a specific DB parameter group family to
    // return details for."
    if let Some(family) = &input.db_parameter_group_family {
        if !entry.parameter_group_family.eq_ignore_ascii_case(family) {
            return false;
        }
    }
    // `DefaultOnly`: "Specifies whether to return only the default version of the
    // specified engine or the engine and major version combination." A request that
    // narrows to one major version family — by `EngineVersion` or by
    // `DBParameterGroupFamily` — asks for that family's default; otherwise the engine's.
    if input.default_only == Some(true) {
        let narrowed_to_a_major_version =
            input.engine_version.is_some() || input.db_parameter_group_family.is_some();
        let keep = resolves_a_default_version(entry.engine)
            && if narrowed_to_a_major_version {
                entry.default_level.is_major_default()
            } else {
                entry.default_level.is_engine_default()
            };
        if !keep {
            return false;
        }
    }
    filters.iter().all(|filter| matches_filter(entry, filter))
}

/// Whether `entry` matches one filter: true when any of the filter's values matches the
/// member that filter names. Filter values are case-sensitive.
fn matches_filter(entry: &CatalogVersion, filter: &Filter) -> bool {
    filter
        .values
        .iter()
        .any(|wanted| match filter.name.as_str() {
            "db-parameter-group-family" => wanted == entry.parameter_group_family,
            "engine" => wanted == entry.engine,
            // The modes of THIS version, which is what the entry reports.
            "engine-mode" => entry.profile.engine_modes.contains(&wanted.as_str()),
            "engine-version" => wanted == entry.engine_version,
            "status" => wanted == entry.status,
            _ => false,
        })
}

/// One `(name, description)` pair as the modelled `CharacterSet`.
fn character_set((name, description): &(&str, &str)) -> CharacterSet {
    CharacterSet {
        character_set_name: Some((*name).to_string()),
        character_set_description: Some((*description).to_string()),
    }
}

/// The modelled list of a `&[&str]` reference-data column.
fn strings(values: &[&str]) -> Vec<String> {
    values.iter().map(|value| (*value).to_string()).collect()
}

/// The versions `entry` can be upgraded to: the LATER versions of the same engine, which
/// are the catalogue rows after it (each engine's rows ascend by version).
///
/// Every capability a target reports is the TARGET's own, read from its profile: a caller
/// decides whether to take an upgrade by what it would be running afterwards.
fn valid_upgrade_targets(
    entry: &CatalogVersion,
    facts: &EngineFacts,
    index: usize,
) -> Vec<UpgradeTarget> {
    CATALOG
        .iter()
        .skip(index.saturating_add(1))
        .filter(|target| target.engine == entry.engine)
        .map(|target| {
            let within_one_major = target.major_engine_version == entry.major_engine_version;
            UpgradeTarget {
                engine: Some(target.engine.to_string()),
                engine_version: Some(target.engine_version.to_string()),
                description: Some(format!("{} {}", facts.product, target.engine_version)),
                // An automatic MINOR upgrade only ever moves within one major version,
                // and only onto that major version's default.
                auto_upgrade: Some(within_one_major && target.default_level.is_major_default()),
                is_major_version_upgrade: Some(!within_one_major),
                supported_engine_modes: Some(strings(target.profile.engine_modes)),
                supports_parallel_query: Some(target.profile.supports_parallel_query),
                supports_global_databases: Some(target.profile.supports_global_databases),
                supports_babelfish: Some(target.profile.supports_babelfish),
                supports_limitless_database: Some(target.profile.supports_limitless_database),
                supports_local_write_forwarding: Some(
                    target.profile.supports_local_write_forwarding,
                ),
                supports_integrations: Some(target.profile.supports_integrations),
            }
        })
        .collect()
}

/// Project one catalogue entry onto the modelled `DBEngineVersion` wire shape.
///
/// `SupportedCharacterSets` and `SupportedTimezones` are reported only when the request
/// asks for them: "Specifies whether to list the supported character sets for each
/// engine version" / "… the supported time zones for each engine version", and only for
/// an engine that has them. Every other member the catalogue knows is reported on every
/// entry, because a client reads them to choose a version and gate on its capabilities.
fn to_wire(
    entry: &CatalogVersion,
    facts: &EngineFacts,
    index: usize,
    input: &DescribeDBEngineVersionsInput,
    certificates: &[String],
) -> CreateCustomDBEngineVersionOutput {
    let profile = entry.profile;
    let supported_character_sets = (input.list_supported_character_sets == Some(true)
        && !facts.character_sets.is_empty())
    .then(|| facts.character_sets.iter().map(character_set).collect());
    let supported_timezones = (input.list_supported_timezones == Some(true)
        && !facts.timezones.is_empty())
    .then(|| {
        facts
            .timezones
            .iter()
            .map(|name| Timezone {
                timezone_name: Some((*name).to_string()),
            })
            .collect()
    });
    CreateCustomDBEngineVersionOutput {
        engine: Some(entry.engine.to_string()),
        engine_version: Some(entry.engine_version.to_string()),
        major_engine_version: Some(entry.major_engine_version.to_string()),
        db_parameter_group_family: Some(entry.parameter_group_family.to_string()),
        db_engine_description: Some(facts.description.to_string()),
        db_engine_version_description: Some(format!(
            "{} {}",
            facts.product, entry.engine_version
        )),
        status: Some(entry.status.to_string()),
        supported_engine_modes: Some(strings(profile.engine_modes)),
        supported_feature_names: Some(strings(profile.feature_names)),
        // `SupportedCACertificateIdentifiers`: the CA certificates an instance of this
        // version can be given through `CreateDBInstance`'s `CACertificateIdentifier`. The
        // member's documentation points at "Using SSL/TLS to encrypt a connection to a DB
        // instance", and the certificate authorities that page publishes are the ones THIS
        // service already reports through `DescribeCertificates` — so the list is read from
        // that ONE catalogue (`crate::state::CA_CERTIFICATES`) rather than restated here,
        // and the two reports cannot name different certificates. An entry whose
        // `ValidTill` has passed is left out: an expired certificate is not one a new
        // instance can be launched with.
        supported_ca_certificate_identifiers: Some(certificates.to_vec()),
        exportable_log_types: Some(strings(facts.exportable_log_types)),
        supports_log_exports_to_cloudwatch_logs: Some(!facts.exportable_log_types.is_empty()),
        supports_read_replica: Some(profile.supports_read_replica),
        supports_global_databases: Some(profile.supports_global_databases),
        supports_parallel_query: Some(profile.supports_parallel_query),
        supports_babelfish: Some(profile.supports_babelfish),
        supports_limitless_database: Some(profile.supports_limitless_database),
        supports_local_write_forwarding: Some(profile.supports_local_write_forwarding),
        supports_integrations: Some(profile.supports_integrations),
        supports_certificate_rotation_without_restart: Some(
            profile.supports_certificate_rotation_without_restart,
        ),
        // "Specifies any Aurora Serverless v2 properties or limits that differ between
        // Aurora engine versions": reported for a version that runs Serverless v2, and
        // absent — rather than zeroed — for one that does not.
        serverless_v2_features_support: profile.serverless_v2_capacity.map(|(min, max)| {
            ServerlessV2FeaturesSupport {
                min_capacity: Some(min),
                max_capacity: Some(max),
            }
        }),
        default_character_set: facts.character_sets.first().map(character_set),
        supported_character_sets,
        supported_timezones,
        valid_upgrade_target: Some(valid_upgrade_targets(entry, facts, index)),
        // The members a CUSTOM engine version carries — `DBEngineVersionArn`,
        // `CreateTime`, `KMSKeyId`, `Image`, the installation-file members and
        // `CustomDBEngineVersionManifest` — belong to a record
        // `CreateCustomDBEngineVersion` stores, and this service stores none yet, so no
        // catalogue entry invents them.
        ..Default::default()
    }
}

