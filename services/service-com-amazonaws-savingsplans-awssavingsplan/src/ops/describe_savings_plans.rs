/// Whether every filter the request supplied admits `plan`.
fn admits(input: &DescribeSavingsPlansInput, plan: &crate::state::SavingsPlanRecord) -> bool {
    use crate::state::filter_admits;

    if !filter_admits(input.savings_plan_ids.as_ref(), &plan.savings_plan_id)
        || !filter_admits(input.savings_plan_arns.as_ref(), &plan.savings_plan_arn)
        || !filter_admits(input.states.as_ref(), &plan.state)
    {
        return false;
    }
    input.filters.iter().flatten().all(|filter| {
        filter
            .name
            .as_deref()
            .is_none_or(|name| plan.matches_filter(name, filter.values.as_ref()))
    })
}

