/// Whether `entity` is in the list the single accepted filter selects. With no
/// filter every entity of the workspace is.
///
/// Both component filters — `componentTypeId` ("the ID of the component type in
/// the entities in the list") and `externalId` ("the external-Id property of a
/// component") — are answered over every component the entity HOLDS
/// ([`crate::state::Entity::components_at_every_path`]): a composite component
/// is a component of the entity too, instantiating a component type and
/// carrying properties of its own, and `GetEntity` and `ListComponents` both
/// report it as one, so a filter that skipped it would contradict every reader
/// of the same entity.
///
/// `workspace` is the entity's own workspace, which the `externalId` filter
/// needs: which property of a component is its external id is declared on a
/// component TYPE, so the filter is answered against the workspace's component
/// types rather than off the entity alone
/// ([`crate::state::Workspace::component_external_ids`], which reads
/// `isExternalId` off the EFFECTIVE definition of each property rather than off
/// an entity-local one).
fn matches_filter(
    workspace: &crate::state::Workspace,
    entity: &crate::state::Entity,
    filter: Option<&ListEntitiesFilter>,
) -> bool {
    match filter {
        None => true,
        Some(ListEntitiesFilter::parentEntityId(parent_entity_id)) => {
            entity.parent_entity_id == *parent_entity_id
        }
        Some(ListEntitiesFilter::componentTypeId(component_type_id)) => entity
            .components_at_every_path()
            .any(|component| component.component_type_id() == Some(component_type_id.as_str())),
        Some(ListEntitiesFilter::externalId(external_id)) => {
            entity.components_at_every_path().any(|component| {
                workspace
                    .component_external_ids(component.component_type_id(), component.properties())
                    .contains(external_id)
            })
        }
    }
}

/// The envelope a `nextToken` of this service carries, so a token minted
/// elsewhere — for another workspace, or by hand — is recognisably not one of
/// ours. The token itself is the shape every paginated operation of this service
/// mints ([`crate::state::encode_page_token`]), scoped to the Region and the
/// workspace whose page it is and to the filter that selected it.
const NEXT_TOKEN_PREFIX: &str = "iottwinmaker:entities:1:";

/// What the single accepted filter binds a token to: the member it filters on
/// and the value it selects, under the one rule every filtered listing of this
/// service binds its filters by ([`crate::state::filters_token_scope`]).
///
/// The filter is what decides which entities are in the listing at all
/// ([`matches_filter`]), so a page resumed under a different one would skip
/// every entity the new filter selects that sorts before the resume key. A
/// request naming no filter has its own scope, distinct from any filtered one:
/// the unfiltered sequence is a different sequence.
fn filters_token_scope(filter: Option<&ListEntitiesFilter>) -> String {
    crate::state::filters_token_scope(filter.map(|filter| match filter {
        ListEntitiesFilter::parentEntityId(parent_entity_id) => (
            "parentEntityId",
            ::serde_json::Value::from(parent_entity_id.as_str()),
        ),
        ListEntitiesFilter::componentTypeId(component_type_id) => (
            "componentTypeId",
            ::serde_json::Value::from(component_type_id.as_str()),
        ),
        ListEntitiesFilter::externalId(external_id) => (
            "externalId",
            ::serde_json::Value::from(external_id.as_str()),
        ),
    }))
}

/// The opaque `nextToken` for a page of `region`'s `workspace_id` taken under
/// `filters_scope`, starting at `entity_id`.
fn encode_next_token(
    region: &str,
    workspace_id: &str,
    filters_scope: &str,
    entity_id: &str,
) -> String {
    crate::state::encode_page_token(
        NEXT_TOKEN_PREFIX,
        region,
        &[workspace_id, filters_scope],
        entity_id,
    )
}

/// The entity id inside a `nextToken` minted in `region` for `workspace_id`
/// under `filters_scope`, or `None` when the token is not one this service
/// minted for that Region's workspace and that filter.
fn decode_next_token(
    token: &str,
    region: &str,
    workspace_id: &str,
    filters_scope: &str,
) -> Option<String> {
    crate::state::decode_page_token(
        NEXT_TOKEN_PREFIX,
        region,
        &[workspace_id, filters_scope],
        token,
    )
}
