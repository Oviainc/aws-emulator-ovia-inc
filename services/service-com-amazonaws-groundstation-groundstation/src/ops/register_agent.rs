impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for RegisterAgent<Eng>
{
    type Input = RegisterAgentInput;
    type Output = RegisterAgentOutput;
    type Error = RegisterAgentError;

    const NAME: &'static str = "RegisterAgent";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REGISTER_AGENT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REGISTER_AGENT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            RegisterAgentErrorModeled::DependencyException(DependencyException {
                message: Some("this service's state store is unavailable".to_string()),
                parameter_name: None,
            })
        })?;

        // A `tags` map is checked before anything else about the request, the same gate
        // every other operation of this service that accepts one goes through: `TagsMap`
        // carries no constraint in the model, so the boundary validator passed it, and the
        // platform's tagging rules are the only thing that refuses a reserved `aws:` key,
        // an out-of-bounds key or value, or more tags than a resource may carry. Refused
        // HERE, before an id and an ARN are minted, so a caller never holds an agent AWS
        // would not have tagged that way.
        crate::state::validate_tags(input.tags.as_ref())
            .map_err(RegisterAgentErrorModeled::InvalidParameterException)?;

        // `AgentDetails` offers TWO members for the CPU cores an agent runs on, one
        // superseding the other: `reservedCpuCores` ("This field should not be used. Use
        // agentCpuCores instead.") and `agentCpuCores`, both optional
        // `AgentCpuCoresList`s (`smithy_query(query="shape", shape="AgentDetails")`). The
        // model marks neither `@required` on its own, because supplying EITHER satisfies the
        // service, and the service requires one of the pair: an agent reports its core
        // assignment through the superseded member or through the current one, and a
        // registration that supplies neither reports none at all. Refused before an id and
        // an ARN are minted, so no agent is registered on a configuration that describes no
        // cores — and checked on `agentDetails`, the input's first member, before the
        // `discoveryData` below it. It comes AFTER the tagging gate above for the reason
        // that gate states: a `tags` map is judged before anything else about the request,
        // in every operation of this service that accepts one, so a caller never holds a
        // resource AWS would not have tagged that way.
        if input.agent_details.reserved_cpu_cores.is_none()
            && input.agent_details.agent_cpu_cores.is_none()
        {
            return Err(RegisterAgentErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    message: Some(CPU_CORES_UNSPECIFIED.to_string()),
                    parameter_name: None,
                },
            )
            .into());
        }

        // The discovery data's addresses are IPv4 addresses (`IpAddressList`'s member is
        // `IpV4Address` — `smithy_query(query="shape", shape="IpAddressList")`), and that
        // shape's pattern only holds them to four dot-separated runs of up to three
        // digits: `256.0.0.1` satisfies the pattern the boundary validator applies and is
        // still not an address the agent can be reached on, so the value is parsed
        // (`crate::state::is_ipv4_address`, which every member this service types as an
        // `IpV4Address` is held to).
        for (member, addresses) in [
            (
                "discoveryData.publicIpAddresses",
                &input.discovery_data.public_ip_addresses,
            ),
            (
                "discoveryData.privateIpAddresses",
                &input.discovery_data.private_ip_addresses,
            ),
        ] {
            if let Some(address) = addresses
                .iter()
                .find(|address| !crate::state::is_ipv4_address(address))
            {
                return Err(invalid_parameter(
                    member,
                    format!(
                        "{address} is not an IPv4 address; each of the four octets of an \
                         IPv4 address is between 0 and 255"
                    ),
                ));
            }
        }

        let region = crate::state::request_region(ctx.parts());
        let agent_id = crate::state::new_uuid();
        let agent_arn = ::engine::emulator_arn(
            crate::state::ARN_SERVICE,
            &region,
            &format!("agent/{agent_id}"),
        );
        let registered = crate::state::now_timestamp();

        let mut guard = state.lock();

        // The store this emulator keeps is bounded, so a caller cannot grow it without
        // limit; past the bound a create is refused the way the service refuses one that
        // runs past an account limit. Checked after the request itself, so what the caller
        // hears is what is wrong with the request.
        if guard.agents.len() >= crate::state::MAX_RECORDS_PER_STORE {
            return Err(RegisterAgentErrorModeled::ResourceLimitExceededException(
                ResourceLimitExceededException {
                    message: Some(format!(
                        "this account already holds the maximum of {} registered agents",
                        crate::state::MAX_RECORDS_PER_STORE
                    )),
                    parameter_name: None,
                },
            )
            .into());
        }

        // A registered agent has reported no status yet: `AgentStatus` is what the AGENT
        // reports through `UpdateAgentStatus`, so the service holds the new agent inactive,
        // with no component status and no task, until the first report arrives.
        //
        // The `discoveryData` stored here is also what ASSOCIATES this agent with the
        // capabilities it manages, so the dataflow endpoints those capabilities address
        // carry this agent's status from now on (`crate::state::agent_for_capability`).
        let stored = crate::state::Agent {
            agent_id: agent_id.clone(),
            agent_arn: agent_arn.clone(),
            agent_details: input.agent_details,
            discovery_data: input.discovery_data,
            tags: input.tags.unwrap_or_default(),
            aggregate_status: AggregateStatus {
                status: crate::state::AGENT_INACTIVE.to_string(),
                signature_map: None,
            },
            component_statuses: Vec::new(),
            task_id: None,
            log_uploads: ::std::collections::HashMap::new(),
            tasking_document: None,
            registered,
            last_updated: registered,
        };

        guard.arn_index.insert(
            agent_arn,
            crate::state::ResourceRef::Agent {
                agent_id: agent_id.clone(),
            },
        );
        guard.agents.insert(agent_id.clone(), stored);

        Ok(RegisterAgentOutput {
            agent_id: Some(agent_id),
        })
    }
}

