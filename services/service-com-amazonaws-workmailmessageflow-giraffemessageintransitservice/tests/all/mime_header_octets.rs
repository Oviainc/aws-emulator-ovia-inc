//! The header criteria `PutRawMessageContent` decides are decided over the
//! message's OCTETS.
//!
//! A message's MIME content is an arbitrary octet stream: the model's
//! `RawMessageContent` documentation (`smithy_query(query="doc",
//! shape="RawMessageContent")`) only *recommends* encoding "content that is
//! outside of the 7-bit ASCII character range", and this service stores and serves
//! whatever bytes it is given (`crate::raw_message_content` round-trips every byte
//! value). So "the value of immutable headers must remain unchanged" holds of the
//! bytes of a header field, not of text decoded out of them: two values that
//! differ in any octet are different values, and two field names are the same
//! field only when their names are the same octets up to ASCII case.
//!
//! Each test is a TABLE whose axis is WHERE in the octets the two sides differ —
//! which immutable header, one byte or several, a byte replaced, transposed,
//! appended or re-encoded, a name or a value — with a generated sweep over the
//! byte values that no text encoding distinguishes. Every row goes over the wire
//! through the harness in [`crate::raw_message_content`], and reuses the
//! seed-update-read helper in [`crate::mime_header_criteria`].

use crate::mime_header_criteria::{assert_rejected, update};
use crate::raw_message_content::DATE;

/// How many rows the generated byte sweep drives. Bounded: these are integration
/// tests, each row standing a whole emulator up.
const SWEPT_BYTES: usize = 16;

/// A message whose header block is `fields` — (field name, value) octets in the
/// order the message carries them — with `body` after the empty line that ends the
/// block.
fn message(fields: &[(&[u8], &[u8])], body: &[u8]) -> Vec<u8> {
    let mut content: Vec<u8> = Vec::new();
    for (name, value) in fields {
        content.extend_from_slice(name);
        content.extend_from_slice(b": ");
        content.extend_from_slice(value);
        content.extend_from_slice(b"\r\n");
    }
    content.extend_from_slice(b"\r\n");
    content.extend_from_slice(body);
    content
}

/// A message carrying the `Received` trace and `Message-ID` given, then the two
/// required fields and a subject, with `body` as its body.
fn with_immutable(
    received: &[&[u8]],
    message_id: &[u8],
    subject: &[u8],
    body: &[u8],
) -> Vec<u8> {
    let mut fields: Vec<(&[u8], &[u8])> = Vec::new();
    for value in received {
        fields.push((b"Received", *value));
    }
    fields.push((b"Message-ID", message_id));
    fields.push((b"Date", DATE.as_bytes()));
    fields.push((b"From", b"sender@example.com"));
    fields.push((b"Subject", subject));
    message(&fields, body)
}

/// A message in transit carrying one `Message-ID` of the octets given and one
/// `Received` line, with everything else fixed.
fn by_message_id(message_id: &[u8]) -> Vec<u8> {
    with_immutable(
        &[b"by relay-one with SMTP"],
        message_id,
        b"original",
        b"the original body\r\n",
    )
}

/// A message in transit carrying the `Received` trace of the octets given and one
/// fixed `Message-ID`, with everything else fixed.
fn by_received(received: &[&[u8]]) -> Vec<u8> {
    with_immutable(
        received,
        b"<00000001@example.com>",
        b"original",
        b"the original body\r\n",
    )
}

/// Every byte value a header field may carry, in order, minus the two that end a
/// line: CR and LF delimit header fields (RFC 5322 §2.2), everything else is just
/// an octet of the field.
fn every_header_byte() -> Vec<u8> {
    (0u8..=255)
        .filter(|byte| *byte != b'\r' && *byte != b'\n')
        .collect()
}

/// Render a case's octets for an assertion message without pretending they are
/// text.
pub(crate) fn shown(octets: &[u8]) -> String {
    octets
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect::<Vec<String>>()
        .join(" ")
}

/// `content` with `octets` inserted where `after` first ends.
fn insert_after(content: &[u8], after: &[u8], octets: &[u8]) -> Vec<u8> {
    let at = content
        .windows(after.len())
        .position(|window| window == after)
        .unwrap_or_else(|| panic!("the message carries {}", shown(after)))
        + after.len();
    let mut content = content.to_vec();
    content.splice(at..at, octets.iter().copied());
    content
}

// ---------------------------------------------------------------------------
// "The value of immutable headers must remain unchanged" — over the octets.
// ---------------------------------------------------------------------------

/// An update whose immutable header value differs from the one in transit only in
/// octets no text decoding keeps apart — a byte replaced, two transposed, a
/// truncated multi-byte sequence swapped for a single byte, whitespace that is not
/// RFC 5322's space or horizontal tab added — changes that value, so it is refused
/// and installs nothing.
#[tokio::test]
async fn an_update_that_changes_immutable_header_octets_is_rejected() {
    let refused: Vec<(&str, Vec<u8>, Vec<u8>, &str)> = vec![
        (
            "one invalid byte of the Message-ID replaced by another",
            by_message_id(b"<\xff@example.com>"),
            by_message_id(b"<\xfe@example.com>"),
            "message-id",
        ),
        (
            "two invalid bytes of the Message-ID transposed",
            by_message_id(b"<\xff\xfe@example.com>"),
            by_message_id(b"<\xfe\xff@example.com>"),
            "message-id",
        ),
        (
            "a truncated multi-byte sequence in the Message-ID replaced by one invalid byte",
            by_message_id(b"<\xe2\x82@example.com>"),
            by_message_id(b"<\xff@example.com>"),
            "message-id",
        ),
        (
            "a non-ASCII whitespace octet pair appended to the Message-ID",
            by_message_id(b"<a@example.com>"),
            by_message_id(b"<a@example.com>\xc2\xa0"),
            "message-id",
        ),
        (
            "a non-ASCII whitespace octet pair before the Message-ID value",
            by_message_id(b"<a@example.com>"),
            insert_after(&by_message_id(b"<a@example.com>"), b"Message-ID: ", b"\xc2\xa0"),
            "message-id",
        ),
        (
            "a form feed appended to the Message-ID value",
            by_message_id(b"<a@example.com>"),
            by_message_id(b"<a@example.com>\x0c"),
            "message-id",
        ),
        (
            "a bare CR left in the Message-ID value by a doubled line ending",
            by_message_id(b"<a@example.com>"),
            insert_after(&by_message_id(b"<a@example.com>"), b"<a@example.com>", b"\r"),
            "message-id",
        ),
        (
            "one invalid byte of a Received line replaced by another",
            by_received(&[b"by relay-two \xff", b"by relay-one with SMTP"]),
            by_received(&[b"by relay-two \xfe", b"by relay-one with SMTP"]),
            "received",
        ),
        (
            "the invalid bytes of the Received trace swapped between its lines",
            by_received(&[b"by relay-two \xff", b"by relay-one \xfe"]),
            by_received(&[b"by relay-two \xfe", b"by relay-one \xff"]),
            "received",
        ),
        (
            "a non-ASCII whitespace octet pair appended to a Received line",
            by_received(&[b"by relay-two with SMTP", b"by relay-one with SMTP"]),
            by_received(&[b"by relay-two with SMTP\xc2\xa0", b"by relay-one with SMTP"]),
            "received",
        ),
        (
            "an invalid byte appended to a Received line",
            by_received(&[b"by relay-two with SMTP", b"by relay-one with SMTP"]),
            by_received(&[b"by relay-two with SMTP", b"by relay-one with SMTP\xff"]),
            "received",
        ),
    ];

    for (case, original, content, header) in refused {
        let (reply, after) = update(&original, &content).await;
        assert_rejected(case, &reply);
        let reported = reply.error_message().to_ascii_lowercase();
        assert!(
            reported.contains(header),
            "case {case:?}: expected the rejection to name the {header} header, got {:?}",
            reply.error_message()
        );
        assert_eq!(
            after, original,
            "case {case:?}: the rejected update changed the content in transit to {}",
            shown(&after[..after.len().min(120)])
        );
    }
}

/// The same rule swept over the byte values a text decoding collapses together:
/// for a spread of high bytes, a `Message-ID` carrying one of them and a
/// `Message-ID` carrying the next are different values, and the update is refused.
#[tokio::test]
async fn an_update_that_swaps_one_high_byte_of_an_immutable_value_is_rejected() {
    // 0x80..=0xff is the range in which no byte stands for itself in UTF-8, so a
    // decoding that is not injective maps every row's two values onto one string.
    // Computed arithmetically, so every run drives exactly the same rows.
    for row in 0..SWEPT_BYTES {
        let before = 0x80u8 + (row as u8) * 8;
        let after_byte = before + 1;
        let case = format!("the Message-ID's {before:02x} replaced by {after_byte:02x}");
        let original = by_message_id(&[b'<', before, b'@', b'x', b'>']);
        let content = by_message_id(&[b'<', after_byte, b'@', b'x', b'>']);
        let (reply, after) = update(&original, &content).await;
        assert_rejected(&case, &reply);
        assert_eq!(
            after, original,
            "case {case:?}: the rejected update changed the content in transit to {}",
            shown(&after[..after.len().min(120)])
        );
    }
}

/// An update that carries every immutable header's octets exactly as the message
/// in transit has them is accepted, however arbitrary those octets are and
/// however much else the update rewrites.
#[tokio::test]
async fn an_update_that_preserves_immutable_header_octets_is_accepted() {
    let id: Vec<u8> = {
        let mut value = b"<".to_vec();
        value.extend_from_slice(&every_header_byte());
        value.extend_from_slice(b"@example.com>");
        value
    };
    let trace: Vec<u8> = {
        let mut value = b"by relay-one ".to_vec();
        value.extend_from_slice(&every_header_byte());
        value
    };

    let accepted: Vec<(&str, Vec<u8>, Vec<u8>)> = vec![
        (
            "a Message-ID of every header byte, kept while the subject is rewritten",
            with_immutable(&[], &id, b"original", b"the original body\r\n"),
            with_immutable(&[], &id, b"rewritten by the message flow", b"the original body\r\n"),
        ),
        (
            "a Received trace of every header byte, kept while the body is rewritten",
            with_immutable(
                &[&trace],
                b"<00000001@example.com>",
                b"original",
                b"the original body\r\n",
            ),
            with_immutable(
                &[&trace],
                b"<00000001@example.com>",
                b"original",
                b"a body the rule says nothing about\r\n",
            ),
        ),
        (
            "the immutable field names in a different ASCII case, values byte for byte",
            by_message_id(b"<\xff\xfe@example.com>"),
            message(
                &[
                    (b"RECEIVED", b"by relay-one with SMTP"),
                    (b"message-id", b"<\xff\xfe@example.com>"),
                    (b"Date", DATE.as_bytes()),
                    (b"From", b"rewritten@example.com"),
                    (b"Subject", b"rewritten"),
                ],
                b"a different body\r\n",
            ),
        ),
        (
            "an invalid byte in a header the rule does not protect",
            by_message_id(b"<a@example.com>"),
            with_immutable(
                &[b"by relay-one with SMTP"],
                b"<a@example.com>",
                b"rewritten \xff\xfe",
                b"a body of \xff bytes\r\n",
            ),
        ),
    ];

    for (case, original, content) in accepted {
        let (reply, after) = update(&original, &content).await;
        assert_eq!(
            reply.status, 200,
            "case {case:?}: expected HTTP 200, got {} ({})",
            reply.status,
            reply.summary()
        );
        assert_eq!(
            after, content,
            "case {case:?}: expected the accepted content in transit, got {}",
            shown(&after[..after.len().min(120)])
        );
    }
}

// ---------------------------------------------------------------------------
// A field is the field its NAME's octets say it is.
// ---------------------------------------------------------------------------

/// Which field a header line is, is decided by the octets of its name up to ASCII
/// case: a required field is present only when a line's name is exactly its
/// octets, and RFC 5322 §3.6.8 admits only printable US-ASCII in a field name,
/// with the space and the horizontal tab as the only whitespace a value or a fold
/// may be padded with (§2.2.3). So a name carrying a non-ASCII octet is a
/// different field, and a message whose only `Date`-like line is one of those
/// carries no `Date` field at all.
#[tokio::test]
async fn a_header_field_is_the_field_its_name_octets_name() {
    let from: (&[u8], &[u8]) = (b"From", b"sender@example.com");

    let refused: Vec<(&str, Vec<u8>, &str)> = vec![
        (
            "a Date name preceded by a non-ASCII whitespace octet pair",
            message(&[from, (b"\xc2\xa0Date", DATE.as_bytes())], b"body\r\n"),
            "date",
        ),
        (
            "a Date name followed by a non-ASCII whitespace octet pair",
            message(&[from, (b"Date\xc2\xa0", DATE.as_bytes())], b"body\r\n"),
            "date",
        ),
        (
            "a Date name carrying an invalid byte",
            message(&[from, (b"Dat\xffe", DATE.as_bytes())], b"body\r\n"),
            "date",
        ),
        (
            "a Date name followed by a form feed",
            message(&[from, (b"Date\x0c", DATE.as_bytes())], b"body\r\n"),
            "date",
        ),
        (
            "a From name carrying an invalid byte",
            message(
                &[(b"Date", DATE.as_bytes()), (b"Fro\xffm", b"sender@example.com")],
                b"body\r\n",
            ),
            "from",
        ),
    ];

    for (case, content, missing) in refused {
        let original = message(
            &[(b"Date", DATE.as_bytes()), from, (b"Subject", b"original")],
            b"body\r\n",
        );
        let (reply, after) = update(&original, &content).await;
        assert_rejected(case, &reply);
        let reported = reply.error_message().to_ascii_lowercase();
        assert!(
            reported.contains(missing),
            "case {case:?}: expected the rejection to name the missing {missing} field, got {:?}",
            reply.error_message()
        );
        assert_eq!(
            after, original,
            "case {case:?}: the rejected update changed the content in transit to {}",
            shown(&after[..after.len().min(120)])
        );
    }

    // A field whose name is the required octets is that field whatever its value
    // carries, and a name padded with ASCII whitespace — which the obsolete field
    // syntax of RFC 5322 §4.5.8 admits before the colon — is still that field.
    let accepted: Vec<(&str, Vec<u8>)> = vec![
        (
            "required fields whose values carry every header byte",
            message(
                &[
                    (b"Date", &every_header_byte()),
                    (b"From", &every_header_byte()),
                ],
                b"body\r\n",
            ),
        ),
        (
            "required field names padded with a tab and a space",
            message(
                &[
                    (b"Subject", b"a first line whose name needs no padding"),
                    (b"Date\t", DATE.as_bytes()),
                    (b"From ", b"a@example.com"),
                ],
                b"body\r\n",
            ),
        ),
        (
            "a folded value whose continuation carries invalid bytes",
            {
                let mut content = format!("Date: {DATE}\r\n").into_bytes();
                content.extend_from_slice(b" (the fold continues \xff\xfe)\r\n");
                content.extend_from_slice(b"From: sender@example.com\r\n\r\nbody\r\n");
                content
            },
        ),
    ];

    for (case, content) in accepted {
        let original = message(
            &[(b"Date", DATE.as_bytes()), from, (b"Subject", b"original")],
            b"body\r\n",
        );
        let (reply, after) = update(&original, &content).await;
        assert_eq!(
            reply.status, 200,
            "case {case:?}: expected HTTP 200, got {} ({})",
            reply.status,
            reply.summary()
        );
        assert_eq!(
            after, content,
            "case {case:?}: expected the accepted content in transit, got {}",
            shown(&after[..after.len().min(120)])
        );
    }
}

/// A header a message may carry only once is counted by its name's octets too: two
/// lines whose names are the same octets up to ASCII case are the same field
/// twice, however arbitrary their values, and the update is refused.
#[tokio::test]
async fn a_unique_header_is_counted_by_its_name_octets() {
    let refused: Vec<(&str, Vec<u8>, &str)> = vec![
        (
            "two Message-ID lines whose values carry invalid bytes",
            message(
                &[
                    (b"Message-ID", b"<\xff@example.com>"),
                    (b"Message-ID", b"<\xfe@example.com>"),
                    (b"Date", DATE.as_bytes()),
                    (b"From", b"sender@example.com"),
                ],
                b"body\r\n",
            ),
            "message-id",
        ),
        (
            "two Subject lines differing in ASCII case of the name",
            message(
                &[
                    (b"Date", DATE.as_bytes()),
                    (b"From", b"sender@example.com"),
                    (b"Subject", b"one \xff"),
                    (b"SUBJECT", b"another \xfe"),
                ],
                b"body\r\n",
            ),
            "subject",
        ),
    ];

    for (case, content, duplicated) in refused {
        let original = message(
            &[(b"Date", DATE.as_bytes()), (b"From", b"sender@example.com")],
            b"body\r\n",
        );
        let (reply, after) = update(&original, &content).await;
        assert_rejected(case, &reply);
        let reported = reply.error_message().to_ascii_lowercase();
        assert!(
            reported.contains(duplicated),
            "case {case:?}: expected the rejection to name the repeated {duplicated} header, \
             got {:?}",
            reply.error_message()
        );
        assert_eq!(
            after, original,
            "case {case:?}: the rejected update changed the content in transit to {}",
            shown(&after[..after.len().min(120)])
        );
    }
}
