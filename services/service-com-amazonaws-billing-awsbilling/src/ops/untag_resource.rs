impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UntagResource<Eng>
{
    type Input = UntagResourceInput;
    type Output = UntagResourceOutput;
    type Error = UntagResourceError;

    const NAME: &'static str = "UntagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UNTAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UNTAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // The modeled constraints (`resourceArn` pattern, `resourceTagKeys`
        // 0..200 and each key's own length) are refused by the boundary validator
        // before this runs.
        let _ = ctx;
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            UntagResourceErrorModeled::InternalServerException(InternalServerException {
                message: "the billing view store is unavailable".to_string(),
            })
        })?;
        let mut state = state.lock();

        // The same two refusals the other tagging operations answer, for the same
        // reason: a managed view's tags are the service's own, not the customer's
        // to remove. Decided before the request's keys are looked at, so neither
        // refusal depends on the other.
        if state
            .billing_views
            .get(&input.resource_arn)
            .is_some_and(crate::state::BillingView::is_managed)
        {
            return Err(invalid_field(
                "resourceArn",
                crate::state::MANAGED_VIEW_NOT_TAGGABLE,
            ));
        }

        let Some(view) = state.billing_views.get_mut(&input.resource_arn) else {
            return Err(UntagResourceErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    // The fixed sentence the tagging APIs answer: the ARN the
                    // request carried is reported in `resourceId`, the member the
                    // model has for it, and not echoed into the message.
                    message: crate::state::RESOURCE_NOT_FOUND_MESSAGE.to_string(),
                    resource_id: input.resource_arn.clone(),
                    resource_type: crate::state::BILLING_VIEW_RESOURCE_TYPE.to_string(),
                },
            )
            .into());
        };

        // A request names keys, not values, and removal shrinks the set — so,
        // unlike attaching a value, which `TagResource` refuses to decide by
        // arrival order, a key named twice in one request and a key the resource
        // never carried both leave the same stored set: every key the request did
        // not name, with the value it already had.
        for key in &input.resource_tag_keys {
            view.tags.remove(key);
        }

        Ok(UntagResourceOutput {})
    }
}
