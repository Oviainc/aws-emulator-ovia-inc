/// The `CheckSummary` of ONE check: the check as this emulator publishes it
/// ([`crate::state::TrustedAdvisorCheck`]), the best practice it is associated to, and what
/// that check reports across the accounts related to the workload
/// ([`crate::state::check_account_summary`]).
///
/// `UpdatedAt` is "the date and time when the check summary was last updated", which
/// describes a check RESULT, and the statuses this emulator can report are the two that say
/// there is no result for an account — so it is not reported rather than being filled with
/// an instant nothing produced.
fn check_summary(
    check: &crate::state::TrustedAdvisorCheck,
    summary: Option<&crate::state::CheckAccountSummary>,
    lens_arn: &str,
    pillar_id: &str,
    question_id: &str,
    choice_id: &str,
) -> CheckSummary {
    CheckSummary {
        id: Some(check.id.to_string()),
        name: Some(check.name.to_string()),
        description: Some(check.description.to_string()),
        provider: Some(crate::state::CHECK_PROVIDER_TRUSTED_ADVISOR.to_string()),
        lens_arn: Some(lens_arn.to_string()),
        pillar_id: Some(pillar_id.to_string()),
        question_id: Some(question_id.to_string()),
        choice_id: Some(choice_id.to_string()),
        status: summary.map(|summary| summary.status.to_string()),
        account_summary: summary.map(|summary| summary.accounts_by_status.clone()),
        updated_at: None,
    }
}

