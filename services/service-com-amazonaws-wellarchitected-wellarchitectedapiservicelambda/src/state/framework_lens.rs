use super::*;

/// The AWS Well-Architected Framework lens's question set: the content of the lens
/// [`FRAMEWORK_LENS_ALIAS`] names, in pillar order and then in the framework's question
/// order. It is that lens's entry in the AWS-official lens catalog
/// ([`official_lenses::OFFICIAL_LENS_CATALOG`]), which carries one question set per lens.
///
/// Every identifier here is the framework lens's OWN published identifier, because a lens
/// addresses its content by them and a client drives a review with them: the `question_id`
/// is the `QuestionId` the framework lens asks that question under (`cost` 1 is
/// `cloud-financial-management`), and each choice carries the `ChoiceId` the lens names
/// that best practice by (`cost_cloud_financial_management_function`) beside its
/// `Choice$Title` and the prose the lens publishes for it. They are what `QuestionId` and
/// `ChoiceId` mean everywhere in this crate — `ListAnswers` reports them, an answer is
/// stored under them and `UpdateAnswer$SelectedChoices` names them.
///
/// SOURCE: the AWS Well-Architected Framework's own lens content, published as the
/// framework's pillars, questions and best practices
/// (<https://docs.aws.amazon.com/wellarchitected/latest/framework/welcome.html>) — the
/// pillars and the number of questions each asks are its published numbering (OPS 1-11,
/// SEC 1-11, REL 1-13, PERF 1-5, COST 1-11, SUS 1-6 — 57 questions), and each `title` is
/// that published question. The Smithy model cannot supply it: it bounds a `QuestionId`
/// and a `ChoiceId` only by length (`smithy_query(query="shape",
/// shape="QuestionId,ChoiceId")`), so the content is written out here, the same way
/// [`super::AWS_OFFICIAL_LENS_ALIASES`] writes out the published lens library.
