impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = TAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(internal_server_error());
        };

        // `Arn`'s modelled pattern is only `^arn:.+$`, so an ARN naming another
        // service's resource reaches this handler. That is a bad request rather than
        // a missing resource: no Aurora DSQL resource can carry such an ARN. Same
        // refusal, in the same words, as `ListTagsForResource`.
        let Some(resource) = crate::state::parse_resource_arn(&input.resource_arn) else {
            return Err(TagResourceErrorModeled::ValidationException(
                crate::state::invalid_resource_arn("resourceArn", &input.resource_arn),
            )
            .into());
        };

        // A tag key under the AWS-reserved prefix is not the caller's to write: the
        // whole request is refused, before any resource is resolved or any pair
        // applied, so the addressed resource's tags are left exactly as they were.
        // `TagKey`'s pattern admits the `:` such a key needs, so the boundary
        // validator passes it through and the check belongs here.
        if let Err(invalid) = crate::state::validate_tag_keys(
            crate::state::TAGS_MEMBER,
            input.tags.keys().map(String::as_str),
        ) {
            return Err(TagResourceErrorModeled::ValidationException(invalid).into());
        }

        let region = crate::state::request_region(ctx);
        let mut state = state.lock();
        // Materialise what the clock already owes before the lookup, so a cluster
        // whose deletion came due is not found here either.
        state.settle(std::time::SystemTime::now());

        // The identity the modelled quota refusal below reports for the addressed
        // resource: its own type segment and its own identifier, so a stream of a
        // cluster is named as a stream rather than as the cluster segment the ARN read
        // split at.
        let identity = state.addressed_identity(&resource);

        // The one resolution of a tagging ARN, shared with `ListTagsForResource` and
        // `UntagResource`: it walks every tagged resource of this service — a cluster,
        // and a stream of a cluster addressed by its nested ARN
        // `cluster/{cluster}/stream/{stream}` (`crate::state::stream_arn`) — to that
        // resource's own tag map, within the scope the request reached. A well-formed
        // ARN naming nothing this store holds is the tagging surface's own not-found,
        // whichever of the two it named — and an ARN of another region, account or
        // partition names a resource this endpoint neither reads nor writes, so it is
        // absent here too.
        let Some(held) = state.resource_tags_mut(&resource, &region) else {
            return Err(crate::state::tagging_resource_not_found());
        };

        // The write is all-or-nothing: a request that would leave the resource
        // holding more tags than `TagMap` admits is refused in full, before any pair
        // is applied, so a refused call changes nothing. Only the keys the resource
        // does not already hold grow it.
        let added = input
            .tags
            .keys()
            .filter(|key| !held.contains_key(*key))
            .count();
        let merged = held.len() + added;
        if merged > crate::state::MAX_TAGS_PER_RESOURCE {
            return Err(TagResourceErrorModeled::ServiceQuotaExceededException(
                identity.quota_exceeded(
                    format!(
                        "The request would leave the resource with {merged} tags, which exceeds \
                         the maximum of {} tags per resource.",
                        crate::state::MAX_TAGS_PER_RESOURCE
                    ),
                    QUOTA_CODE_TAGS_PER_RESOURCE,
                ),
            )
            .into());
        }

        for (key, value) in input.tags {
            held.insert(key, value);
        }

        // `@idempotent`: the merge is a set of assignments, so repeating the same
        // call leaves the resource in the same state and answers the same way.
        Ok(TagResourceOutput)
    }
}

/// The `quotaCode` the refusal at a resource's tag ceiling carries: the quota
/// bounds how many tags ONE resource holds.
const QUOTA_CODE_TAGS_PER_RESOURCE: &str = "tags-per-resource";

