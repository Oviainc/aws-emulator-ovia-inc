        let (mut store, now) = crate::state::locked_store_now(&state);
        // Reporting only (`@readonly`): the sole write is materialising the CREATING ->
        // AVAILABLE transitions the clock already made due.
        store.settle_all(now);

        // `graphIdentifier` is optional: absent, the listing spans every snapshot of
        // the Region; present, it narrows the listing to the snapshots taken from that
        // one graph. A snapshot is a resource in its own right and keeps the id of the
        // graph it was taken from, so it stays listed under that graph after the graph
        // itself is reclaimed: the identifier is resolved against everything the Region
        // still holds under it (`crate::state::listable_graph_id`), and only an
        // identifier it holds nothing under is the failed lookup this listing reports
        // rather than an empty page.
        let of_graph = match input.graph_identifier.as_deref() {
            Some(identifier) => {
                let Some(graph_id) = store.listable_graph_id(identifier, &region, now) else {
                    return Err(ListGraphSnapshotsErrorModeled::ResourceNotFoundException(
                        crate::state::graph_not_found(identifier),
                    )
                    .into());
                };
                Some(graph_id)
            }
            None => None,
        };

        // `snapshots` is a BTreeMap, so one stable total order underlies every page and
        // a token can name a position in it.
