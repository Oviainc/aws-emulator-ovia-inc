#[cfg(test)]
mod tests {
    use super::{decode_page_token, encode_page_token, PageScope, PagedListing, SCOPE};

    /// A token round-trips to the id it was minted from, and a token this listing
    /// never issued is rejected rather than silently treated as the first page.
    #[test]
    fn page_tokens_round_trip_and_reject_foreign_tokens() {
        for id in ["g-0000000000", "g-abcdefghij", "g-zz99zz99zz"] {
            let token = encode_page_token(SCOPE, id);
            let decoded = decode_page_token(&token);
            assert_eq!(
                decoded.as_deref(),
                Some(id),
                "case {id:?}: token {token:?} did not round-trip, got {decoded:?}"
            );
        }
        for foreign in [
            "not-a-token",
            "zz",
            "abc",
            // Decodes cleanly, but names no position in the graph-id space.
            &hex::encode("not-a-graph-id"),
            &hex::encode("g-short"),
            &hex::encode("gs-0123456789"),
            // A bare position, in this listing's own id space, carrying no listing: not
            // a value this listing ever handed out.
            &hex::encode("g-0123456789"),
            // Carries the bytes of a graph id, but in a spelling the minting half never
            // emits, so it is not a token this service issued.
            &encode_page_token(SCOPE, "g-0123456789").to_ascii_uppercase(),
            // Every OTHER listing's token for a position in its own id space.
            &encode_page_token(
                PageScope::whole_listing(PagedListing::GraphSnapshots),
                "gs-0123456789",
            ),
            &encode_page_token(
                PageScope::whole_listing(PagedListing::ImportTasks),
                "t-0123456789",
            ),
            &encode_page_token(
                PageScope::whole_listing(PagedListing::ExportTasks),
                "t-0123456789",
            ),
            // The endpoint listing's token for a position in its own id space, under the
            // graph whose endpoints it pages.
            &encode_page_token(
                PageScope::listing_in(PagedListing::PrivateGraphEndpoints, "g-0123456789"),
                "vpc-0a1b2c3d",
            ),
        ] {
            let decoded = decode_page_token(foreign);
            assert!(
                decoded.is_none(),
                "case {foreign:?}: expected rejection, got {decoded:?}"
            );
        }
    }
}

