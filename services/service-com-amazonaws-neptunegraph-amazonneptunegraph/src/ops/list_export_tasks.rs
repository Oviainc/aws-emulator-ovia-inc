impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ListExportTasks<Eng>
{
    type Input = ListExportTasksInput;
    type Output = ListExportTasksOutput;
    type Error = ListExportTasksError;

    const NAME: &'static str = "ListExportTasks";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_EXPORT_TASKS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_EXPORT_TASKS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(ListExportTasksErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the neptune-graph store is not mounted on this engine".to_string(),
                },
            )
            .into());
        };

        // A token this service did not issue names no page, so it is refused rather
        // than treated as the start of the listing. The refusal is the service's own
        // modelled 400, worded and classified once in `crate::state`.
        let start_after = match input.next_token.as_deref() {
            Some(token) => Some(decode_page_token(token).ok_or_else(|| {
                ListExportTasksErrorModeled::ValidationException(unissued_page_token(token))
            })?),
            None => None,
        };
        let page_size = resolve_page_size(input.max_results);

        // An export task lives in exactly one Region, so this listing reports the tasks
        // of the Region the request was signed for and no others.
        let region = crate::state::request_region(ctx);
        let (mut store, now) = crate::state::locked_store_now(&state);
        // Reporting only (`@readonly`): the sole write is materialising the terminal
        // transitions the clock already made due.
        store.settle_all(now);

        // `graphIdentifier` is optional: absent, the listing spans every export task of
        // the Region; present, it narrows the listing to the tasks that read that one
        // graph. A task is read by its own id and keeps the id of the graph it read, so
        // it stays listed under that graph after the graph itself is reclaimed: the
        // identifier is resolved against everything the Region still holds under it
        // (`crate::state::listable_graph_id`), and only an identifier it holds nothing
        // under is the failed lookup this listing reports rather than an empty page.
        let of_graph = match input.graph_identifier.as_deref() {
            Some(identifier) => {
                let Some(graph_id) = store.listable_graph_id(identifier, &region, now) else {
                    return Err(ListExportTasksErrorModeled::ResourceNotFoundException(
                        crate::state::graph_not_found(identifier),
                    )
                    .into());
                };
                Some(graph_id)
            }
            None => None,
        };

        // `export_tasks` is a BTreeMap, so one stable total order underlies every page
        // and a token can name a position in it.
        let mut remaining = store
            .export_tasks_in(&region, of_graph.as_deref(), start_after.as_deref())
            .map(ExportTaskSummary::from);
        let (tasks, next_token) = take_page(&mut remaining, page_size, SCOPE, |summary| {
            &summary.task_id
        });

        Ok(Self::Output { tasks, next_token })
    }
}

/// Which listing of this service the tokens this file mints and takes back belong to.
///
/// An export task and an import task share one modelled id pattern while living in two
/// independently keyed collections, so the listing — not the pattern — is what binds a
/// token to the order it names a position in.
const LISTING: PagedListing = PagedListing::ExportTasks;

/// The scope a token of this listing belongs to: the listing alone, because it pages ONE
/// order — `export_tasks` keyed by task id, with any `graphIdentifier` restriction
/// applied as a filter after the range — so a position names the same cut point in it
/// whichever graph the listing was restricted to.
const SCOPE: PageScope<'static> = PageScope::whole_listing(LISTING);

/// The export-task id a token resumes after, or `None` when the token is not one
/// [`crate::state::encode_page_token`] produced for THIS listing.
///
/// Only the scope is this file's own: the wire format, and the decision to refuse a
/// value that names no position in that scope's order rather than treat it as the
/// start of the list, are [`crate::state::decode_page_token`]'s.
fn decode_page_token(token: &str) -> Option<String> {
    crate::state::decode_page_token(token, SCOPE)
}

#[cfg(test)]
mod tests {
    use super::{decode_page_token, encode_page_token, PageScope, PagedListing, SCOPE};

    /// A token round-trips to the id it was minted from, and a token this listing never
    /// issued is rejected rather than silently treated as the first page.
    #[test]
    fn page_tokens_round_trip_and_reject_foreign_tokens() {
        for id in ["t-0000000000", "t-abcdefghij", "t-zz99zz99zz"] {
            let token = encode_page_token(SCOPE, id);
            let decoded = decode_page_token(&token);
            assert_eq!(
                decoded.as_deref(),
                Some(id),
                "case {id:?}: token {token:?} did not round-trip, got {decoded:?}"
            );
        }
        for foreign in [
            "not-a-token",
            "zz",
            "abc",
            // Decodes cleanly, but names no position in the task-id space.
            &hex::encode("not-a-task-id"),
            &hex::encode("t-short"),
            // A bare position, in this listing's own id space, carrying no listing: not
            // a value this listing ever handed out.
            &hex::encode("t-0123456789"),
            // A graph id and a snapshot id are positions in OTHER id spaces.
            &hex::encode("g-0123456789"),
            &hex::encode("gs-0123456789"),
            // The token the SIBLING task listing mints for a position in the one task-id
            // space both are keyed by: a cut point in the other collection's order.
            &encode_page_token(
                PageScope::whole_listing(PagedListing::ImportTasks),
                "t-0123456789",
            ),
            // And every other listing's token for a position in its own id space.
            &encode_page_token(
                PageScope::whole_listing(PagedListing::Graphs),
                "g-0123456789",
            ),
            &encode_page_token(
                PageScope::whole_listing(PagedListing::GraphSnapshots),
                "gs-0123456789",
            ),
            // The endpoint listing's token for a position in its own id space, under the
            // graph whose endpoints it pages.
            &encode_page_token(
                PageScope::listing_in(PagedListing::PrivateGraphEndpoints, "g-0123456789"),
                "vpc-0a1b2c3d",
            ),
        ] {
            let decoded = decode_page_token(foreign);
            assert!(
                decoded.is_none(),
                "case {foreign:?}: expected rejection, got {decoded:?}"
            );
        }
    }
}
