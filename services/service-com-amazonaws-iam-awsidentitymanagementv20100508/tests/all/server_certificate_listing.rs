//! `ListServerCertificates`, end to end over the awsQuery wire, cross-read through
//! `GetServerCertificate`.
//!
//! Every assertion drives a `MultiServiceRouter` holding this service over one shared
//! `InMemoryEngine`, exactly as the production router does, so what is under test is the
//! HTTP behaviour (status, awsQuery error code, XML members) of certificates that were
//! PERSISTED by `UploadServerCertificate`, never a handler called directly. The awsQuery
//! harness is the one `tests/all/user_lifecycle.rs` owns and the other suites in this
//! crate share, and the certificate material is generated by the `rcgen` fixture
//! `tests/all/server_certificates.rs` owns, so nothing here is built by the code under
//! test.
//!
//! The rules under test are that a resource-listing operation enumerates the persisted
//! resources in the store's one total key order, reporting for each the record a
//! single-resource read reports; that `PathPrefix` selects exactly those whose path
//! begins with it and defaults to a slash; that `MaxItems` is a real page size whose
//! `Marker` resumes without repeating or skipping; and that a token this collection did
//! not issue names no position in it.
//!
//! Each suite is a TABLE whose rows differ along what those rules generalise over: the
//! page size, the path prefix depth, the name alphabet and case, the number of persisted
//! certificates and the tag count. No single request is the specification.

use smithy_server_runtime::MultiServiceRouter;

use crate::role_lifecycle::{borrowed, param};
use crate::server_certificates::material;
use crate::user_lifecycle::{account_id, call, element, elements, error_code, router};

/// One fixture certificate: the name it is uploaded under, the `Path` the request names
/// (`None` for a request that omits it, which "defaults to a slash (/)"), and the tags it
/// carries.
struct Fixture {
    name: &'static str,
    path: Option<&'static str>,
    tags: &'static [(&'static str, &'static str)],
}

/// The fixture certificate set: names spanning the whole `^[\w+=,.@-]+$` alphabet and
/// both cases (`smithy_query(query="operation", operation="UploadServerCertificate")` for
/// `ServerCertificateName`), and paths spanning an omitted `Path`, the root given
/// explicitly, a one-segment path and a nested path, so a rule about paths is exercised at
/// more than one depth; tag counts from none to two, because the listing's documented
/// subset is about tags.
const FIXTURES: &[Fixture] = &[
    Fixture {
        name: "web-server",
        path: Some("/edge/east/"),
        tags: &[("env", "prod"), ("owner", "platform")],
    },
    Fixture {
        name: "CloudFront_Cert.1",
        path: Some("/cloudfront/"),
        tags: &[],
    },
    Fixture {
        name: "edge+east=1",
        path: None,
        tags: &[("team", "edge")],
    },
    Fixture {
        name: "LEGACY-cert_9",
        path: Some("/edge/"),
        tags: &[],
    },
    Fixture {
        name: "svc.team@2",
        path: Some("/"),
        tags: &[],
    },
    Fixture {
        name: "Alpha",
        path: Some("/edge/west/"),
        tags: &[("env", "test")],
    },
];

impl Fixture {
    /// The path this certificate ends up under: the one the request named, or the slash an
    /// omitted `Path` defaults to.
    fn expected_path(&self) -> &'static str {
        self.path.unwrap_or("/")
    }
}

/// The fixture names in the order the service enumerates them: ascending by the
/// case-folded name, which is the key the store is ordered on — IAM entity names "are not
/// distinguished by case" (`UploadServerCertificate$ServerCertificateName`).
fn names_in_store_order() -> Vec<&'static str> {
    let mut names: Vec<&'static str> = FIXTURES.iter().map(|fixture| fixture.name).collect();
    names.sort_by_key(|name| name.to_ascii_lowercase());
    names
}

/// Upload one fixture certificate, asserting the fixture upload succeeded.
async fn upload(router: &MultiServiceRouter, fixture: &Fixture) {
    // Ed25519 for every row: the key algorithm is what
    // `tests/all/server_certificates.rs` is the table for, and this suite is about the
    // enumeration, so the cheapest generated pair is used here.
    let leaf = material(&rcgen::PKCS_ED25519, (2024, 2044), "server.example.com");
    let mut params = vec![
        param("ServerCertificateName", fixture.name),
        param("CertificateBody", &leaf.certificate),
        param("PrivateKey", &leaf.private_key),
    ];
    if let Some(path) = fixture.path {
        params.push(param("Path", path));
    }
    for (position, (key, value)) in fixture.tags.iter().enumerate() {
        let index = position + 1;
        params.push(param(&format!("Tags.member.{index}.Key"), key));
        params.push(param(&format!("Tags.member.{index}.Value"), value));
    }
    let (status, body) = call(router, "UploadServerCertificate", &borrowed(&params)).await;
    assert_eq!(
        status, 200,
        "case {:?}: the fixture UploadServerCertificate must succeed, got {status}: {body}",
        fixture.name
    );
}

/// Upload every fixture certificate, answering the router they were uploaded to.
async fn with_fixtures() -> MultiServiceRouter {
    let router = router();
    for fixture in FIXTURES {
        upload(&router, fixture).await;
    }
    router
}

/// One server certificate as a `ListServerCertificates` page reports it, read off the
/// members of the `ServerCertificateMetadata` shape — `Path`, `ServerCertificateName`,
/// `ServerCertificateId`, `Arn`, `UploadDate` and `Expiration` — each of which every
/// member of the list carries exactly once, so position identifies the certificate.
#[derive(Debug, PartialEq, Eq)]
struct ListedCertificate {
    server_certificate_name: String,
    path: String,
    server_certificate_id: String,
    arn: String,
    upload_date: String,
    expiration: String,
}

/// The certificates a `ListServerCertificates` (or `GetServerCertificate`) response
/// reports, in document order.
fn listed_certificates(body: &str) -> Vec<ListedCertificate> {
    let names = elements(body, "ServerCertificateName");
    let paths = elements(body, "Path");
    let ids = elements(body, "ServerCertificateId");
    let arns = elements(body, "Arn");
    let uploaded = elements(body, "UploadDate");
    let expirations = elements(body, "Expiration");
    for (label, found) in [
        ("Path", paths.len()),
        ("ServerCertificateId", ids.len()),
        ("Arn", arns.len()),
        ("UploadDate", uploaded.len()),
        ("Expiration", expirations.len()),
    ] {
        assert_eq!(
            found,
            names.len(),
            "every listed certificate must carry one <{label}>: got {found} for {} \
             certificates: {body}",
            names.len()
        );
    }
    names
        .into_iter()
        .zip(paths)
        .zip(ids)
        .zip(arns)
        .zip(uploaded)
        .zip(expirations)
        .map(
            |(((((server_certificate_name, path), server_certificate_id), arn), upload_date), expiration)| {
                ListedCertificate {
                    server_certificate_name,
                    path,
                    server_certificate_id,
                    arn,
                    upload_date,
                    expiration,
                }
            },
        )
        .collect()
}

/// The certificate names a `ListServerCertificates` response reports, in document order.
fn listed_names(body: &str) -> Vec<String> {
    elements(body, "ServerCertificateName")
}

/// RULE: a resource-listing operation enumerates the persisted resources, reporting for
/// each the record the account holds — the same identifiers a single-resource read of it
/// returns, never a value recomputed from the listing request.
#[tokio::test]
async fn list_server_certificates_reports_the_stored_record_of_every_certificate() {
    let router = with_fixtures().await;

    let (status, body) = call(&router, "ListServerCertificates", &[]).await;
    assert_eq!(status, 200, "expected 200, got {status}: {body}");
    let listed = listed_certificates(&body);
    let names: Vec<String> = listed
        .iter()
        .map(|certificate| certificate.server_certificate_name.clone())
        .collect();
    assert_eq!(
        names,
        names_in_store_order()
            .into_iter()
            .map(str::to_string)
            .collect::<Vec<_>>(),
        "expected every persisted certificate once, in store order, got {names:?}"
    );

    // Each row of this table is one persisted certificate: what the listing says about it
    // must be what its own read says.
    for certificate in &listed {
        let case = &certificate.server_certificate_name;
        let (status, fetched) = call(
            &router,
            "GetServerCertificate",
            &[("ServerCertificateName", case.as_str())],
        )
        .await;
        assert_eq!(
            status, 200,
            "case {case:?}: GetServerCertificate must find the certificate, got {status}: \
             {fetched}"
        );
        let stored = listed_certificates(&fetched);
        assert_eq!(
            stored.len(),
            1,
            "case {case:?}: expected the read to report one certificate, got {stored:?}"
        );
        assert_eq!(
            certificate, &stored[0],
            "case {case:?}: expected the listing to report the stored record, got \
             {certificate:?}"
        );
        let fixture = FIXTURES
            .iter()
            .find(|fixture| fixture.name == case)
            .expect("a fixture certificate");
        assert_eq!(
            certificate.path,
            fixture.expected_path(),
            "case {case:?}: expected path {:?}, got {:?}",
            fixture.expected_path(),
            certificate.path
        );
        // A server certificate ARN is `arn:aws:iam::<account>:server-certificate<path><name>`
        // — IAM is global, so the region segment is EMPTY.
        assert_eq!(
            certificate.arn,
            format!(
                "arn:aws:iam::{}:server-certificate{}{}",
                account_id(),
                certificate.path,
                certificate.server_certificate_name
            ),
            "case {case:?}: expected the stored server certificate ARN, got {:?}",
            certificate.arn
        );
    }
}

/// RULE: an IAM resource-listing operation reports a SUBSET of the resource's attributes —
/// the ones its documentation names are withheld from the listing and available only from
/// the single-resource read — while every other stored attribute is reported.
///
/// `ListServerCertificates`: "this operation does not return tags, even though they are an
/// attribute of the returned object. To view all of the information for a
/// servercertificate, see GetServerCertificate."
#[tokio::test]
async fn a_listing_withholds_the_attributes_its_documentation_names() {
    let router = with_fixtures().await;

    let (status, body) = call(&router, "ListServerCertificates", &[]).await;
    assert_eq!(status, 200, "expected 200, got {status}: {body}");
    assert!(
        !body.contains("<Tags>"),
        "the listing must carry no Tags member at all, got {body}"
    );
    // Rows: every fixture tag key and value, including the keys two of the fixtures share.
    for fixture in FIXTURES {
        for (key, value) in fixture.tags {
            assert!(
                !elements(&body, "Key").contains(&(*key).to_string()),
                "case {:?}: the listing must not report tag key {key:?}, got {body}",
                fixture.name
            );
            assert!(
                !elements(&body, "Value").contains(&(*value).to_string()),
                "case {:?}: the listing must not report tag value {value:?}, got {body}",
                fixture.name
            );
        }
    }
    // The PEM material is a `GetServerCertificate` attribute too, and is not a member of
    // the metadata shape the listing reports.
    for withheld in ["CertificateBody", "CertificateChain"] {
        assert_eq!(
            elements(&body, withheld),
            Vec::<String>::new(),
            "the listing must not report <{withheld}>, got {body}"
        );
    }
    // Every tag IS still readable from the single-resource read, which is where the
    // documentation points.
    for fixture in FIXTURES.iter().filter(|fixture| !fixture.tags.is_empty()) {
        let (status, fetched) = call(
            &router,
            "GetServerCertificate",
            &[("ServerCertificateName", fixture.name)],
        )
        .await;
        assert_eq!(
            status, 200,
            "case {:?}: expected 200, got {status}: {fetched}",
            fixture.name
        );
        for (key, _) in fixture.tags {
            assert!(
                elements(&fetched, "Key").contains(&(*key).to_string()),
                "case {:?}: the read must still report tag {key:?}, got {fetched}",
                fixture.name
            );
        }
    }
}

