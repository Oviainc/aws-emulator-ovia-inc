/// RULE: a list operation enumerates the persisted entities in one total order, honours
/// `MaxItems` as a real page size, and hands out a `Marker` a follow-up call resumes from
/// without repeating or skipping an entity.
#[tokio::test]
async fn list_server_certificates_pages_through_every_certificate_exactly_once() {
    let router = with_fixtures().await;
    let expected: Vec<String> = names_in_store_order()
        .into_iter()
        .map(str::to_string)
        .collect();

    // Rows span the page size: the published minimum, sizes that do and do not divide the
    // set, a size equal to the set, the published maximum, and the absent-parameter
    // default. `maxItemsType` is range 1..1000
    // (`smithy_query(query="operation", operation="ListServerCertificates")`).
    let page_sizes: &[Option<i32>] = &[
        Some(1),
        Some(2),
        Some(4),
        Some(expected.len() as i32),
        Some(1000),
        None,
    ];

    for page_size in page_sizes {
        let case = format!("MaxItems={page_size:?}");
        let mut seen: Vec<String> = Vec::new();
        let mut marker: Option<String> = None;
        let mut pages = 0;

        loop {
            let mut params: Vec<(String, String)> = Vec::new();
            if let Some(size) = page_size {
                params.push(param("MaxItems", &size.to_string()));
            }
            if let Some(token) = &marker {
                params.push(param("Marker", token));
            }
            let (status, body) =
                call(&router, "ListServerCertificates", &borrowed(&params)).await;
            assert_eq!(
                status, 200,
                "case {case:?}: expected 200, got {status}: {body}"
            );

            let page = listed_names(&body);
            if let Some(size) = page_size {
                assert!(
                    page.len() <= *size as usize,
                    "case {case:?}: expected at most {size} certificates on a page, got {}",
                    page.len()
                );
            }
            seen.extend(page);
            pages += 1;
            assert!(
                pages <= expected.len() + 1,
                "case {case:?}: the pagination never ended, saw {seen:?}"
            );

            if element(&body, "IsTruncated") == "true" {
                marker = Some(element(&body, "Marker"));
            } else {
                assert_eq!(
                    elements(&body, "Marker"),
                    Vec::<String>::new(),
                    "case {case:?}: the last page must carry no Marker, got {:?}",
                    elements(&body, "Marker")
                );
                break;
            }
        }

        assert_eq!(
            seen, expected,
            "case {case:?}: expected every certificate exactly once in store order, got \
             {seen:?}"
        );
    }
}

/// RULE: `MaxItems` outside its published range is refused before the operation runs, so a
/// page size the model forbids never reaches the store; the refusal is HTTP 400
/// `ValidationError` and its message names the member and the bound it broke.
#[tokio::test]
async fn a_page_size_outside_the_published_range_is_refused() {
    let router = with_fixtures().await;
    // One past each published bound of `maxItemsType` (range 1..1000), with the bound
    // clause each one breaks.
    for (out_of_range, requirement) in [
        ("0", "Member must have value greater than or equal to 1"),
        ("-1", "Member must have value greater than or equal to 1"),
        ("1001", "Member must have value less than or equal to 1000"),
    ] {
        let (status, body) =
            call(&router, "ListServerCertificates", &[("MaxItems", out_of_range)]).await;
        assert_eq!(
            status, 400,
            "case {out_of_range:?}: expected 400, got {status}: {body}"
        );
        assert_eq!(
            error_code(&body),
            "ValidationError",
            "case {out_of_range:?}: expected the query protocol's bound refusal code, got \
             {body}"
        );
        let expected = format!(
            "1 validation error detected: Value at 'maxItems' failed to satisfy constraint: \
             {requirement}"
        );
        assert_eq!(
            element(&body, "Message"),
            expected,
            "case {out_of_range:?}: expected {expected:?}, got {:?}",
            element(&body, "Message")
        );
        assert_eq!(
            listed_names(&body),
            Vec::<String>::new(),
            "case {out_of_range:?}: a refused listing reports no certificate, got {body}"
        );
    }
    // And each bound itself is accepted.
    for in_range in ["1", "1000"] {
        let (status, body) =
            call(&router, "ListServerCertificates", &[("MaxItems", in_range)]).await;
        assert_eq!(
            status, 200,
            "case {in_range:?}: expected 200, got {status}: {body}"
        );
    }
}

/// RULE: a `Marker` this service did not issue for this collection names no position in
/// it, so the call is refused rather than silently answered from the beginning; a token
/// that does decode names a POSITION, which stays usable even when the entity it was cut
/// at is gone.
#[tokio::test]
async fn a_marker_this_collection_did_not_issue_is_refused() {
    let router = with_fixtures().await;

    // Rows: a token that is not base64 at all, and two that decode to bytes carrying none
    // of this service's marker structure.
    for marker in ["not-a-marker", "zz", "0g"] {
        let (status, body) =
            call(&router, "ListServerCertificates", &[("Marker", marker)]).await;
        assert_eq!(
            status, 400,
            "case {marker:?}: expected a foreign marker to be refused, got {status}: {body}"
        );
        assert_eq!(
            error_code(&body),
            "ValidationError",
            "case {marker:?}: expected the marker to be refused as invalid, got {:?}",
            error_code(&body)
        );
    }

    // A marker issued while paging ANOTHER collection is not a position in this one, and
    // vice versa.
    for user in ["one", "two"] {
        let (status, body) = call(&router, "CreateUser", &[("UserName", user)]).await;
        assert_eq!(
            status, 200,
            "case {user:?}: the fixture CreateUser must succeed: {body}"
        );
    }
    let (status, body) = call(&router, "ListUsers", &[("MaxItems", "1")]).await;
    assert_eq!(
        status, 200,
        "expected a truncated user page, got {status}: {body}"
    );
    let user_marker = element(&body, "Marker");
    let (status, body) = call(
        &router,
        "ListServerCertificates",
        &[("Marker", user_marker.as_str())],
    )
    .await;
    assert_eq!(
        status, 400,
        "expected a user marker to be refused by ListServerCertificates, got {status}: {body}"
    );
    assert_eq!(
        error_code(&body),
        "ValidationError",
        "expected ValidationError, got {:?}",
        error_code(&body)
    );

    let (status, body) = call(&router, "ListServerCertificates", &[("MaxItems", "1")]).await;
    assert_eq!(
        status, 200,
        "expected a truncated certificate page, got {status}: {body}"
    );
    let certificate_marker = element(&body, "Marker");
    let first = element(&body, "ServerCertificateName");
    let (status, body) = call(
        &router,
        "ListUsers",
        &[("Marker", certificate_marker.as_str())],
    )
    .await;
    assert_eq!(
        status, 400,
        "expected a certificate marker to be refused by ListUsers, got {status}: {body}"
    );

    // A marker cut at a certificate that is then deleted still resumes from that position:
    // the rest of the order follows it, minus the deleted certificate.
    let (status, body) = call(
        &router,
        "DeleteServerCertificate",
        &[("ServerCertificateName", first.as_str())],
    )
    .await;
    assert_eq!(
        status, 200,
        "expected the first certificate to be deleted, got {status}: {body}"
    );
    let (status, body) = call(
        &router,
        "ListServerCertificates",
        &[("Marker", certificate_marker.as_str())],
    )
    .await;
    assert_eq!(
        status, 200,
        "expected a stale marker to still resume, got {status}: {body}"
    );
    let expected: Vec<String> = names_in_store_order()
        .into_iter()
        .filter(|name| *name != first)
        .map(str::to_string)
        .collect();
    assert_eq!(
        listed_names(&body),
        expected,
        "expected the order after the marker's position, got {:?}",
        listed_names(&body)
    );
}

/// RULE: `PathPrefix` selects exactly the resources whose path begins with it, and an
/// absent `PathPrefix` "defaults to a slash (/), listing all server certificates".
#[tokio::test]
async fn list_server_certificates_filters_by_path_prefix() {
    let router = with_fixtures().await;

    // Rows span the prefix depth: the root, a one-segment prefix, two nested prefixes, a
    // prefix that selects exactly one certificate, a partial segment that still matches by
    // prefix, and one that selects none.
    let cases: &[(&str, &[&str])] = &[
        (
            "/",
            &[
                "Alpha",
                "CloudFront_Cert.1",
                "edge+east=1",
                "LEGACY-cert_9",
                "svc.team@2",
                "web-server",
            ],
        ),
        ("/edge/", &["Alpha", "LEGACY-cert_9", "web-server"]),
        ("/edge/east/", &["web-server"]),
        ("/edge/west/", &["Alpha"]),
        ("/cloudfront/", &["CloudFront_Cert.1"]),
        ("/cl", &["CloudFront_Cert.1"]),
        ("/nobody/", &[]),
    ];

    for (prefix, expected) in cases {
        let (status, body) =
            call(&router, "ListServerCertificates", &[("PathPrefix", prefix)]).await;
        assert_eq!(
            status, 200,
            "case {prefix:?}: expected 200, got {status}: {body}"
        );
        let expected: Vec<String> = expected.iter().map(|name| (*name).to_string()).collect();
        assert_eq!(
            listed_names(&body),
            expected,
            "case {prefix:?}: expected {expected:?}, got {:?}",
            listed_names(&body)
        );
    }

    // The default prefix lists every certificate, exactly as "/" does.
    let (_, defaulted) = call(&router, "ListServerCertificates", &[]).await;
    let (_, rooted) =
        call(&router, "ListServerCertificates", &[("PathPrefix", "/")]).await;
    assert_eq!(
        listed_names(&defaulted),
        listed_names(&rooted),
        "expected an absent PathPrefix to default to \"/\", got {:?}",
        listed_names(&defaulted)
    );
}

/// RULE: `PathPrefix` and `MaxItems` compose — a filtered enumeration pages through
/// exactly the matching resources, once each.
#[tokio::test]
async fn a_filtered_listing_pages_through_only_the_matching_certificates() {
    let router = with_fixtures().await;

    // Rows: one prefix depth per row, each paged at every size that splits it.
    let cases: &[(&str, &[&str])] = &[
        ("/edge/", &["Alpha", "LEGACY-cert_9", "web-server"]),
        ("/edge/east/", &["web-server"]),
        ("/", &[
            "Alpha",
            "CloudFront_Cert.1",
            "edge+east=1",
            "LEGACY-cert_9",
            "svc.team@2",
            "web-server",
        ]),
    ];

    for (prefix, expected) in cases {
        for page_size in [1, 2, 3] {
            let case = format!("{prefix} with MaxItems={page_size}");
            let mut seen: Vec<String> = Vec::new();
            let mut marker: Option<String> = None;
            loop {
                let mut params = vec![
                    param("PathPrefix", prefix),
                    param("MaxItems", &page_size.to_string()),
                ];
                if let Some(token) = &marker {
                    params.push(param("Marker", token));
                }
                let (status, body) =
                    call(&router, "ListServerCertificates", &borrowed(&params)).await;
                assert_eq!(
                    status, 200,
                    "case {case:?}: expected 200, got {status}: {body}"
                );
                seen.extend(listed_names(&body));
                if element(&body, "IsTruncated") == "true" {
                    marker = Some(element(&body, "Marker"));
                } else {
                    break;
                }
            }
            let expected: Vec<String> =
                expected.iter().map(|name| (*name).to_string()).collect();
            assert_eq!(
                seen, expected,
                "case {case:?}: expected {expected:?}, got {seen:?}"
            );
        }
    }
}

/// RULE: a reporting operation does not change what a later caller sees — two identical
/// listings of an unchanged account report the same page, and a listing leaves every
/// single-resource read as it was.
#[tokio::test]
async fn listing_server_certificates_changes_nothing() {
    let router = with_fixtures().await;

    // Rows span the request forms a caller may repeat.
    let cases: &[&[(&str, &str)]] = &[
        &[],
        &[("MaxItems", "2")],
        &[("PathPrefix", "/edge/")],
        &[("PathPrefix", "/edge/"), ("MaxItems", "1")],
    ];
    for params in cases {
        let (status, first) = call(&router, "ListServerCertificates", params).await;
        assert_eq!(
            status, 200,
            "case {params:?}: expected 200, got {status}: {first}"
        );
        let (status, second) = call(&router, "ListServerCertificates", params).await;
        assert_eq!(
            status, 200,
            "case {params:?}: expected 200, got {status}: {second}"
        );
        assert_eq!(
            listed_certificates(&first),
            listed_certificates(&second),
            "case {params:?}: a repeated listing must report the same page, got \
             {second:?} after {first:?}"
        );
    }

    // And every certificate still reads back identically to what the listing reports.
    let (_, body) = call(&router, "ListServerCertificates", &[]).await;
    for certificate in listed_certificates(&body) {
        let case = certificate.server_certificate_name.clone();
        let (status, fetched) = call(
            &router,
            "GetServerCertificate",
            &[("ServerCertificateName", case.as_str())],
        )
        .await;
        assert_eq!(
            status, 200,
            "case {case:?}: expected 200, got {status}: {fetched}"
        );
        assert_eq!(
            listed_certificates(&fetched),
            vec![certificate],
            "case {case:?}: the read must report what the listing did, got {fetched}"
        );
    }
}
