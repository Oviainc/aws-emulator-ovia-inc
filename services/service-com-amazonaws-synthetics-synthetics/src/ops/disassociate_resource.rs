impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DisassociateResource<Eng>
{
    type Input = DisassociateResourceInput;
    type Output = DisassociateResourceOutput;
    type Error = DisassociateResourceError;

    const NAME: &'static str = "DisassociateResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DISASSOCIATE_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DISASSOCIATE_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(internal_error)?;
        let now = SystemTime::now();
        let region = crate::state::request_region(&ctx.parts().headers);

        let mut guard = state.lock();
        // Only what the clock already owed on the canary records (a canary that finished
        // provisioning, a run whose outcome came due); removing the membership is this
        // call's own write.
        guard.settle(now);

        // Both sides of the membership have to exist, exactly as they must for the paired
        // write that creates one. The group is "a global resource", so it is resolved by
        // name, ARN or id with no Region in play; the canary is resolved by the exact ARN
        // the request names, which carries the Region it lives in — that is how "You must
        // run this operation in the Region where the canary exists" holds here.
        let Some(group_key) = guard.group_key(&input.group_identifier) else {
            drop(guard);
            audit(ctx, &region, "rejected_group_not_found");
            return Err(not_found(group_not_found(&input.group_identifier)));
        };
        if guard.canary_by_arn(&input.resource_arn).is_none() {
            drop(guard);
            audit(ctx, &region, "rejected_canary_not_found");
            return Err(not_found(canary_not_found(&input.resource_arn)));
        }

        let group = guard.groups.get_mut(&group_key).ok_or_else(internal_error)?;
        // Membership is a set, so removing a canary that is not in the group succeeds and
        // changes nothing — including the timestamp below, which only a membership that
        // actually moved may advance. `Group$LastModifiedTime` is "the date and time that
        // the group was most recently updated", and a call that removed nothing did not
        // update it.
        let removed = group.resources.remove(&input.resource_arn);
        if removed {
            group.last_modified = now;
        }
        // The membership set is written and nothing below needs the store, so the critical
        // section covers the state change only.
        drop(guard);
        audit(
            ctx,
            &region,
            if removed { "removed" } else { "no_change" },
        );
        Ok(DisassociateResourceOutput {})
    }
}

