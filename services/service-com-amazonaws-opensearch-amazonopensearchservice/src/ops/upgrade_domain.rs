//! @op UpgradeDomain
//!
//! Starts a service-managed engine version upgrade of a domain — or, when the request
//! asks for a check only, an upgrade eligibility check, which performs no upgrade.
//!
//! The run is recorded on the domain as a [`crate::state::UpgradeRun`], the ONE record
//! `GetUpgradeHistory` reports; the version a domain can be upgraded to is
//! [`crate::state::compatible_target_versions`]'s answer, the same relation
//! `GetCompatibleVersions` publishes, so a target that table does not offer is refused
//! rather than started — on the service's generic error envelope, and before anything
//! about what the domain is busy with, because the eligibility of a target is decided
//! from the request and the version the domain runs alone.
//!
//! A check performs nothing, so performing it again records nothing: the domain holds
//! at most one eligibility-check run per engine version it runs, and a repeat check
//! reports that run ([`crate::state::Domain::eligibility_check`]) rather than growing
//! the history.
//!
//! An upgrade is a configuration change of the domain: it goes
//! `UpgradingEngineVersion` with its `EngineVersion` option `Processing`, and reports
//! the version it was upgraded to only once the clock makes the run due. It is also
//! work the domain has to be free to take on, so a domain with work in flight
//! ([`crate::state::Domain::work_in_flight`]) is refused with the modelled
//! `BaseException` rather than having a run queued behind that work.
//!
