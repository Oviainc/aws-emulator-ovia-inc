impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> DeletePackageVersions<Eng> {
    /// Remove the versions this request names, and RECORD the state change each removal
    /// made — the whole of this operation's work on the store.
    ///
    /// Separate from the handler, and not `async`, because the announcement the handler
    /// makes is an await: this is the critical section, and its end is where the store's
    /// guard is released.
    fn remove_versions(
        &self,
        input: DeletePackageVersionsInput,
    ) -> Result<DeletePackageVersionsOutput, DeletePackageVersionsError> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(DeletePackageVersionsErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the CodeArtifact store is unavailable".to_string(),
                },
            )
            .into());
        };

        // `expectedStatus` is modelled as the whole `PackageVersionStatus` enum, so the
        // boundary validator admits every value a RESPONSE can report. A precondition
        // naming a state no stored version carries can never hold, so it is a bad request
        // rather than a per-version mismatch — refused from the shared input/report split.
        if let Some(expected) = input.expected_status.as_deref() {
            if let Some(refusal) = crate::state::input_package_version_status_refusal(expected) {
                return Err(
                    DeletePackageVersionsErrorModeled::ValidationException(refusal).into(),
                );
            }
        }

        let mut store = state.lock();
        let Some(domain) = store.domain_mut(&input.domain, input.domain_owner.as_deref()) else {
            return Err(not_found(
                crate::state::domain_not_found_message(
                    &input.domain,
                    input.domain_owner.as_deref(),
                ),
                &input.domain,
                "domain",
            ));
        };
        let Some(repository) = domain.repositories.get_mut(&input.repository) else {
            return Err(not_found(
                crate::state::repository_not_found_message(
                    &input.domain,
                    input.domain_owner.as_deref(),
                    &input.repository,
                ),
                &input.repository,
                "repository",
            ));
        };

        // A package is addressed by its whole (format, namespace, name) triple, the same
        // key `DescribePackage` resolves: a request naming the right package name under a
        // different format or namespace addresses a DIFFERENT package, and that one is
        // not found — in the sentence the VERSION-addressing operations state for a package
        // absent from the addressed repository.
        //
        // The repository's own id is read out before the package is taken mutably out of
        // the same record: it is what a per-version `NOT_FOUND` names the repository the
        // version was looked for in.
        let repository_id = repository.id();
        let key =
            crate::state::package_key(&input.format, input.namespace.as_deref(), &input.package);
        let Some(package) = repository.packages.get_mut(&key) else {
            return Err(not_found(
                crate::state::package_coordinate_not_found_message(
                    &input.format,
                    input.namespace.as_deref(),
                    &input.package,
                    &input.repository,
                ),
                &input.package,
                "package",
            ));
        };

        let mut successful: ::std::collections::HashMap<String, SuccessfulPackageVersionInfo> =
            ::std::collections::HashMap::new();
        let mut failed: ::std::collections::HashMap<String, PackageVersionError> =
            ::std::collections::HashMap::new();
        // The records this call removed, kept so the state change each removal announces
        // can be built from the version as it last stood.
        let mut removed: Vec<crate::state::PackageVersion> = Vec::new();

        for version in &input.versions {
            // Both answers are MAPS keyed by version, so a list that repeats a version
            // carries one outcome for it: the first decision stands, and the repeat is not
            // re-decided against the store the first one already changed.
            if successful.contains_key(version) || failed.contains_key(version) {
                continue;
            }

            let Some(stored) = package.versions.get(version) else {
                failed.insert(
                    version.clone(),
                    version_error(
                        PACKAGE_VERSION_ERROR_NOT_FOUND,
                        crate::state::package_version_not_found_message(
                            &repository_id,
                            &input.format,
                            input.namespace.as_deref(),
                            &input.package,
                            version,
                        ),
                    ),
                );
                continue;
            };

            // `expectedStatus` is the caller's precondition on the version they are
            // deleting: a version in another status is left exactly as it was and reported
            // as the mismatch, not deleted.
            if let Some(expected) = &input.expected_status {
                if &stored.status != expected {
                    failed.insert(
                        version.clone(),
                        version_error(
                            PACKAGE_VERSION_ERROR_MISMATCHED_STATUS,
                            format!(
                                "Package version {} {} is {}, not the expected status {}.",
                                input.package, version, stored.status, expected
                            ),
                        ),
                    );
                    continue;
                }
            }

            // Read off the record BEFORE it goes: the revision the version last had is
            // what identifies the content this call removed.
            let Some(record) = package.versions.remove(version) else {
                continue;
            };
            successful.insert(
                version.clone(),
                SuccessfulPackageVersionInfo {
                    revision: Some(record.revision()),
                    status: Some(crate::state::PACKAGE_VERSION_STATUS_DELETED.to_string()),
                },
            );
            removed.push(record);
        }

        // The package record stays, however many versions this call removed: a package is
        // a resource of its own, carrying the origin configuration that decides what may
        // enter it, and the operation that deletes it is `DeletePackage` ("Deletes a
        // package and all associated package versions … To delete one or more package
        // versions, use the DeletePackageVersions API"). Pruning it here would make this
        // operation the other one for its last version, and would lose the configuration a
        // caller set on the package.

        let output = DeletePackageVersionsOutput {
            successful_versions: Some(successful),
            failed_versions: Some(failed),
        };

        // A removal is a state change of the version it removed: the repository no longer
        // holds it, so the event announces the record as it last stood, in the state a
        // version that is gone is in.
        let mut changes: Vec<crate::state::package_version_events::VersionChange> = Vec::new();
        if let Some(repository) = store
            .domain(&input.domain, input.domain_owner.as_deref())
            .and_then(|domain| domain.repositories.get(&input.repository))
        {
            if let Some(held) = repository.packages.get(&key) {
                for record in &removed {
                    changes.push(crate::state::package_version_events::VersionChange::deleted(
                        repository,
                        held,
                        record,
                        ::std::time::SystemTime::now(),
                    ));
                }
            }
        }
        for change in changes {
            store.record_version_change(change);
        }

        Ok(output)
    }
}

