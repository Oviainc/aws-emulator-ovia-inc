//! @op UpdateRepository
//!
//! Updates the properties of one repository and COMMITS them to the stored record, so the
//! answer this call gives and every later read of the same repository are the same
//! projection of one record:
//!
//! * the addressed domain and repository are resolved first; one this caller does not hold
