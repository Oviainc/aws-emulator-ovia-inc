//!   members are documented as what to change ("An updated repository description"), so
//!   this is a partial update, not a whole-record replacement. An `upstreams` sent as an
//!   EMPTY list is carried, not omitted, so it clears the repository's upstreams;
//! * `upstreams` is stored as the ORDERED sequence the caller submitted, because "the order
//!   of the upstream repositories in the list determines their priority order when
