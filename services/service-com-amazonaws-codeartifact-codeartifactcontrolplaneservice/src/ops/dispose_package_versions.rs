impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> DisposePackageVersions<Eng> {
    /// Dispose the versions this request names, and RECORD the state change each disposal
    /// made — the whole of this operation's work on the store.
    ///
    /// Separate from the handler, and not `async`, because the announcement the handler
    /// makes is an await: this is the critical section, and its end is where the store's
    /// guard is released.
    fn dispose_versions(
        &self,
        input: DisposePackageVersionsInput,
    ) -> Result<DisposePackageVersionsOutput, DisposePackageVersionsError> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(DisposePackageVersionsErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the CodeArtifact store is unavailable".to_string(),
                },
            )
            .into());
        };

        // `expectedStatus` is modelled as the whole `PackageVersionStatus` enum, so the
        // boundary validator admits every value a RESPONSE can report. A precondition
        // naming a state no stored version carries can never hold, so it is a bad request
        // rather than a per-version mismatch — refused from the shared input/report split.
        if let Some(expected) = input.expected_status.as_deref() {
            if let Some(refusal) = crate::state::input_package_version_status_refusal(expected) {
                return Err(
                    DisposePackageVersionsErrorModeled::ValidationException(refusal).into(),
                );
            }
        }

        let mut store = state.lock();
        let Some(domain) = store.domain_mut(&input.domain, input.domain_owner.as_deref()) else {
            return Err(not_found(
                crate::state::domain_not_found_message(
                    &input.domain,
                    input.domain_owner.as_deref(),
                ),
                &input.domain,
                "domain",
            ));
        };
        let Some(repository) = domain.repositories.get_mut(&input.repository) else {
            return Err(not_found(
                crate::state::repository_not_found_message(
                    &input.domain,
                    input.domain_owner.as_deref(),
                    &input.repository,
                ),
                &input.repository,
                "repository",
            ));
        };

        // A package is addressed by its whole (format, namespace, name) triple, the same
        // key `DescribePackage` resolves — refused in the sentence the VERSION-addressing
        // operations state for a package absent from the addressed repository.
        let key =
            crate::state::package_key(&input.format, input.namespace.as_deref(), &input.package);
        let Some(package) = repository.packages.get_mut(&key) else {
            return Err(not_found(
                crate::state::package_coordinate_not_found_message(
                    &input.format,
                    input.namespace.as_deref(),
                    &input.package,
                    &input.repository,
                ),
                &input.package,
                "package",
            ));
        };

        let mut successful: ::std::collections::HashMap<String, SuccessfulPackageVersionInfo> =
            ::std::collections::HashMap::new();
        let mut failed: ::std::collections::HashMap<String, PackageVersionError> =
            ::std::collections::HashMap::new();
        // The versions this call disposed — the state change each disposal announces.
        let mut disposed: Vec<String> = Vec::new();

        let revisions = input.version_revisions.unwrap_or_default();

        for version in &input.versions {
            // Both answers are MAPS keyed by version, so a list that repeats a version
            // carries one outcome for it: the first decision stands, and the repeat is not
            // re-decided against the store the first one already changed.
            if successful.contains_key(version) || failed.contains_key(version) {
                continue;
            }

            let Some(stored) = package.versions.get_mut(version) else {
                failed.insert(
                    version.clone(),
                    version_error(
                        PACKAGE_VERSION_ERROR_NOT_FOUND,
                        crate::state::package_version_not_found_message(
                            &input.package,
                            version,
                            &input.repository,
                        ),
                    ),
                );
                continue;
            };

            // `expectedStatus` is the caller's precondition on the version they are
            // disposing: a version in another status is left exactly as it was and reported
            // as the mismatch, assets included.
            if let Some(expected) = &input.expected_status {
                if &stored.status != expected {
                    failed.insert(
                        version.clone(),
                        version_error(
                            PACKAGE_VERSION_ERROR_MISMATCHED_STATUS,
                            format!(
                                "Package version {} {} is {}, not the expected status {}.",
                                input.package, version, stored.status, expected
                            ),
                        ),
                    );
                    continue;
                }
            }

            // `versionRevisions` is the same kind of precondition on the version's
            // CONTENT: an entry for this version pins the revision the caller last saw.
            if let Some(expected) = revisions.get(version) {
                let held = stored.revision();
                if &held != expected {
                    failed.insert(
                        version.clone(),
                        version_error(
                            PACKAGE_VERSION_ERROR_MISMATCHED_REVISION,
                            format!(
                                "Package version {} {} is at revision {}, not the expected revision {}.",
                                input.package, version, held, expected
                            ),
                        ),
                    );
                    continue;
                }
            }

            // The write: the status moves, and it is COMMITTED to the stored version, so
            // `DescribePackageVersion` reports a disposed version from here on. The ASSET
            // records stay: the deletion disposal documents is asynchronous work the
            // service does out of band, not part of answering this call, so a caller
            // reading the version's assets straight after a disposal is still served the
            // bytes it published.
            let status_changed = stored.status != crate::state::PACKAGE_VERSION_STATUS_DISPOSED;
            stored.status = crate::state::PACKAGE_VERSION_STATUS_DISPOSED.to_string();
            if status_changed {
                stored.advance_sequence();
                disposed.push(version.clone());
            }
            successful.insert(
                version.clone(),
                SuccessfulPackageVersionInfo {
                    // A version's revision identifies its CONTENT, which this call leaves
                    // as it is: the status it moved is not part of it.
                    revision: Some(stored.revision()),
                    status: Some(stored.status.clone()),
                },
            );
        }

        let output = DisposePackageVersionsOutput {
            successful_versions: Some(successful),
            failed_versions: Some(failed),
        };

        // A disposal is a state change of the version it disposed: its status moved, which
        // is what the event's `changes` states. No asset left the version in this call, so
        // none is announced as removed. Read back off the stored records, so the revision
        // announced is the one the disposal left.
        let mut changes: Vec<crate::state::package_version_events::VersionChange> = Vec::new();
        if let Some(repository) = store
            .domain(&input.domain, input.domain_owner.as_deref())
            .and_then(|domain| domain.repositories.get(&input.repository))
        {
            if let Some(held) = repository.packages.get(&key) {
                for version in disposed {
                    if let Some(stored) = held.versions.get(&version) {
                        changes.push(crate::state::package_version_events::VersionChange::of(
                            repository,
                            held,
                            stored,
                            crate::state::package_version_events::OPERATION_UPDATED,
                            crate::state::package_version_events::VersionChanges {
                                status_changed: true,
                                ..crate::state::package_version_events::VersionChanges::default()
                            },
                            ::std::time::SystemTime::now(),
                        ));
                    }
                }
            }
        }
        for change in changes {
            store.record_version_change(change);
        }

        Ok(output)
    }
}

