    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(ListMicrovmsErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("the MicroVM store is unavailable".to_string()),
                    retry_after_seconds: None,
                },
            )
            .into());
        };
        let region = crate::state::request_region(ctx);

        let mut store = state.lock();
        store.materialize_due(::std::time::Instant::now());

        // `imageIdentifier` is a FILTER ("Optional filter to list only MicroVMs running
        // the specified image"), not the resource this call addresses, so it SELECTS: it
        // resolves to the `imageArn` the stored MicroVMs carry, and an identifier that
        // selects no MicroVM yields an empty page rather than a refusal.
        //
        // Both forms `MicrovmImageIdentifier` documents ("The ARN or ID of the
        // MicroVmImage") select: an identifier that names a stored image selects that
        // image's ARN, and an identifier that names none is still matched against the
        // `imageArn` on each MicroVM — so an ARN whose image record has since been
        // deleted keeps selecting the MicroVMs that run it.
        let image_arn_filter = input.image_identifier.as_deref().map(|identifier| {
            store
                .image(&region, identifier)
                .map_or_else(|| identifier.to_string(), |image| image.image_arn.clone())
        });

        let after = match input.next_token.as_deref() {
            Some(token) => Some(decode_token(token)?),
            None => None,
        };
        // `maxResults` carries `@range(min: 1, max: 50)`, which the boundary validator
        // has already enforced; the clamp is a second line of defence, so a page size
        // can never be zero or unbounded however the value arrived.
        let page_size = input
            .max_results
            .and_then(|n| usize::try_from(n).ok())
            .unwrap_or(crate::state::MAX_LIST_PAGE)
            .clamp(1, crate::state::MAX_LIST_PAGE);

        // The MicroVMs listed are the ones of the REGION the request was signed for: a
        // MicroVM run through another region's endpoint belongs to that endpoint's
        // listing and to no other.
        let matching = store.microvms_in(&region).filter(|vm| {
            image_arn_filter
                .as_deref()
                .is_none_or(|arn| vm.image_arn == arn)
                && input
                    .image_version
                    .as_deref()
                    .is_none_or(|version| vm.image_version == version)
        });
        // `microvmId`s sort in creation order, so "after this id" is a stable cursor
        // even when MicroVMs are added between pages.
        let mut remaining = matching.filter(|vm| match after.as_deref() {
            Some(cursor) => vm.microvm_id.as_str() > cursor,
            None => true,
        });

        let items: Vec<MicrovmItem> = remaining
            .by_ref()
            .take(page_size)
            .map(|vm| MicrovmItem {
                microvm_id: vm.microvm_id.clone(),
                state: vm.state.clone(),
                image_arn: vm.image_arn.clone(),
                image_version: vm.image_version.clone(),
                started_at: vm.started_at,
            })
            .collect();

        // A `nextToken` is returned only when the page did not exhaust the matches.
        let next_token = match (items.last(), remaining.next()) {
            (Some(last), Some(_)) => Some(encode_token(&last.microvm_id)),
            _ => None,
        };

        Ok(ListMicrovmsOutput { next_token, items })
    }
