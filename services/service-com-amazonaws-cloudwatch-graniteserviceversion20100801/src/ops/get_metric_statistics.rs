/// Whether `datapoint` reports any statistic at all.
///
/// A `Datapoint` carries its instant and the unit of the observations it aggregated beside the
/// statistics themselves, so neither of those is a measurement: a datapoint that states no
/// statistic states nothing the caller asked for.
fn reports_a_statistic(datapoint: &Datapoint) -> bool {
    datapoint.sample_count.is_some()
        || datapoint.average.is_some()
        || datapoint.sum.is_some()
        || datapoint.minimum.is_some()
        || datapoint.maximum.is_some()
        || datapoint.extended_statistics.is_some()
}

/// Aggregate one window's datapoints, emitting ONLY the statistics the caller asked for.
///
/// `unit` is the unit the window's datapoints were published with — the window is keyed by it
/// ([`crate::state::windows_by_unit`]), so a datapoint reports the unit its own observations
/// carry whether or not the request filtered on one, and reports the value the enumerated type
/// declares for a measurement with no unit where its publisher named none.
fn aggregate(
    window_start: f64,
    data: &[&crate::state::StoredDatum],
    statistics: &[&str],
    extended: &[&str],
    unit: &str,
) -> Datapoint {
    let folded = crate::state::BasicStatistics::of(data.iter().copied());
    let (sample_count, sum) = (folded.sample_count, folded.sum);
    let minimum = folded.minimum;
    let maximum = folded.maximum;

    let mut extended_statistics = std::collections::HashMap::new();
    for name in extended {
        if let Some(value) = crate::state::extended_statistic_value(data, name) {
            extended_statistics.insert((*name).to_string(), value);
        }
    }

    Datapoint {
        timestamp: Some(crate::state::to_timestamp(window_start)),
        sample_count: statistics.contains(&"SampleCount").then_some(sample_count),
        average: statistics
            .contains(&"Average")
            .then(|| folded.average())
            .flatten(),
        sum: statistics.contains(&"Sum").then_some(sum),
        minimum: statistics
            .contains(&"Minimum")
            .then_some(minimum)
            .filter(|value: &f64| value.is_finite()),
        maximum: statistics
            .contains(&"Maximum")
            .then_some(maximum)
            .filter(|value: &f64| value.is_finite()),
        unit: Some(unit.to_string()),
        extended_statistics: (!extended_statistics.is_empty()).then_some(extended_statistics),
    }
}

