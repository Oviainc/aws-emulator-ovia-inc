/// The scope a `ListTypes` resume point is qualified by, which names the collection the
/// page came from: the types of ONE keyspace, named by that keyspace's ARN, which carries
/// the Region the keyspace is a resource of. A token this listing issued therefore resumes
/// only a listing of the same keyspace of the same Region — the same `keyspaceName` names a
/// different keyspace, holding a different set of types, in another Region — and the
/// `types` half keeps it apart from the `ListTables` token over the same keyspace, whose
/// item names have the same shape; [`crate::state::decode_page_token`] refuses either
/// foreign token rather than resuming at a point that would silently skip items.
fn page_token_scope(region: &str, keyspace_name: &str) -> String {
    crate::state::listing_scope("types", &crate::state::keyspace_arn(region, keyspace_name))
}

