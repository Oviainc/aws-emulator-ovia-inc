impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            TagResourceErrorModeled::InternalServerException(InternalServerException {
                message: Some(
                    "Amazon Keyspaces could not reach its state store for this request."
                        .to_string(),
                ),
            })
        })?;

        // Whether a key carries the reserved `aws:` prefix is a property of the REQUEST
        // alone ("Amazon Web Services-assigned tag names ... the user cannot assign",
        // `Tag`), so it is decided here — before the Region, before `settle` and before
        // the ARN is resolved — exactly as `UntagResource` decides it. A key the caller
        // may not name is refused the same way whether or not the ARN names a resource
        // this store holds, and nothing is stored for a refused call.
        //
        // It is decided before the service-managed check below, which is request-only
        // too: of two faults in one request, the one that is wrong about the TAGS the
        // request carries is the one the caller has to fix first — the resource it
        // addresses would take no tag with that key either. `UntagResource` grades the
        // two in the same order, so one request shape never gets two different messages
        // depending on which sibling served it.
        crate::state::reject_reserved_tag_keys(&input.tags).map_err(|rejection| {
            TagResourceErrorModeled::ValidationException(ValidationException {
                message: Some(rejection.message()),
            })
        })?;

        let region = crate::state::request_region(ctx);
        let mut store = state.lock();
        // The status transitions the clock already owed at this instant, so a table whose
        // deletion has completed is no longer a resource this call can tag.
        store.settle(::std::time::SystemTime::now());

        // A service-managed keyspace and its system tables are the SERVICE's resources:
        // a client cannot change them, tags included, and Cassandra refuses a change to a
        // system keyspace as an invalid query ("system keyspace is not user-modifiable") —
        // this operation's `ValidationException`.
        if let Some(keyspace_name) = crate::state::arn_keyspace_name(&input.resource_arn) {
            if crate::state::is_service_managed_keyspace(&keyspace_name) {
                return Err(TagResourceErrorModeled::ValidationException(ValidationException {
                    message: Some(crate::state::service_managed_rejection(&keyspace_name)),
                })
                .into());
            }
        }

        // A resource whose deletion is already in progress takes no further change until
        // that deletion completes — the rule `CreateTable`, `CreateType`, `RestoreTable`
        // and `DeleteKeyspace` already refuse by, applied to the resource the ARN names
        // and to the keyspace that owns it. Within the span between the delete being
        // accepted and `settle` dropping the record, a tag written here would be thrown
        // away with that record, so a 200 would report a change the caller can never read
        // back. That is the modelled conflict — "you try to perform an action and the same
        // or a different action is already in progress" — and nothing is written for it.
        if let Some(rejection) =
            store.deletion_in_progress_rejection(&region, &input.resource_arn)
        {
            return Err(TagResourceErrorModeled::ConflictException(ConflictException {
                message: Some(rejection),
            })
            .into());
        }

        // Tags attach to the resource the ARN names, so the ARN — not a name — is what is
        // resolved, in the Region the request was signed for: an ARN that names no resource
        // of THAT Region is the 404 the model declares, whatever another Region holds.
        let Some(tags) = store.resource_tags_mut(&region, &input.resource_arn) else {
            return Err(TagResourceErrorModeled::ResourceNotFoundException(
                crate::state::arn_not_found(&input.resource_arn),
            )
            .into());
        };

        // `merge_tags` upserts by key and refuses BEFORE storing anything, so a refused
        // call leaves the resource's tags exactly as they were. The reserved-key refusal
        // was already decided above, on the request alone; what is left here is the
        // per-resource tag count, which counts the tags the resource already holds and so
        // cannot be decided before it is resolved — nor expressed in the model.
        //
        // A request asking for more tags than a resource may hold is a request the caller
        // has to make smaller, so it is refused as a malformed request (400
        // `ValidationException`) and not as the service-quota failure a client would read
        // as "ask for more quota, then retry".
        crate::state::merge_tags(tags, &input.tags).map_err(|rejection| {
            TagResourceErrorModeled::ValidationException(ValidationException {
                message: Some(rejection.message()),
            })
        })?;

        Ok(TagResourceOutput {})
    }
}
