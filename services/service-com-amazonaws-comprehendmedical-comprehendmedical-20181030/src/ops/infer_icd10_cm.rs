/// Confidence of a condition mention named by a ONE-token lexicon entry.
///
/// A longer written form is a more specific mention of the same concept ("diabetes"
/// names several ICD-10-CM chapters, "type 2 diabetes mellitus" names one), so the
/// confidence of a mention rises with the number of tokens its lexicon entry spans and
/// stops rising at [`TERM_TOKENS_AT_FULL_CONFIDENCE`].
const WEIGHT_TERM_ONE_TOKEN: f32 = 0.84;

/// How much each further token of the matched written form adds to that confidence.
const WEIGHT_TERM_PER_TOKEN: f32 = 0.04;

/// The token count past which a longer written form adds no more confidence.
const TERM_TOKENS_AT_FULL_CONFIDENCE: usize = 4;

/// Confidence of a span a closed-form pattern placed — a time expression, a measured
/// value — whose own characters are the whole of the evidence, so nothing but the form
/// can be wrong.
pub(crate) const WEIGHT_PATTERN: f32 = 0.95;

/// Confidence of a trait a context cue licensed (a negation, a family reference): the
/// cue is a single word standing next to the mention, which is weaker evidence than the
/// mention's own written form.
pub(crate) const WEIGHT_CUE: f32 = 0.90;

/// Confidence of an attribute a one-word modifier lexicon placed.
pub(crate) const WEIGHT_MODIFIER: f32 = 0.90;

/// Confidence that a modifier STANDING NEXT to the mention modifies it, which is what
/// the modelled `RelationshipScore` reports.
pub(crate) const WEIGHT_RELATIONSHIP: f32 = 0.95;

/// How much each token between the modifier and the mention lowers that relationship
/// confidence: a modifier further from the mention is less likely to belong to it.
pub(crate) const RELATIONSHIP_DISTANCE_PENALTY: f32 = 0.08;

/// How much of the previous candidate's share of a mention the next candidate keeps.
///
/// The candidates of one mention are ordered most-likely-first and every modelled
/// ontology concept's `Score` reports "the likelihood of the match", so the candidates
/// divide the mention's confidence between them in this ratio — see
/// [`candidate_scores`].
pub(crate) const CONCEPT_RANK_DECAY: f32 = 0.5;

/// The most ontology candidates one entity reports.
pub(crate) const CONCEPT_CANDIDATE_LIMIT: usize = 5;

/// How far from a mention, in tokens, a modifier or a time expression is still read as
/// belonging to it. A clause boundary stops the search whatever this allows.
pub(crate) const ATTRIBUTE_WINDOW_TOKENS: usize = 4;

/// How far BEFORE a mention, in tokens, a negation, hypothetical or low-confidence cue
/// is still read as scoping it. A family reference scopes its whole clause instead, so
/// it is searched for without this window.
pub(crate) const CUE_WINDOW_TOKENS: usize = 6;

/// The first `Id` a response mints.
///
/// Every modelled `Id` member is "a monotonically increasing id unique within this
/// response rather than a global unique identifier", and the service numbers the spans of
/// one document from one, in the order they are WRITTEN, entities and their attributes
/// sharing the single sequence (see [`span_ids`]) — so a client that cross-references an
/// attribute's `Id` against an entity's reads the same numbering the service produced.
pub(crate) const FIRST_ID: i32 = 1;

/// How high the confidence of any one detection of this crate's passes can be carried by
/// the written form it placed: a rule-and-lexicon pass establishes a mention, never
/// certainty about it.
pub(crate) const CONFIDENCE_CEILING: f32 = 0.99;

/// The share of the distance to [`CONFIDENCE_CEILING`] that each further written group of
/// a placed span closes.
pub(crate) const CONFIDENCE_GROUP_SHARE: f32 = 0.4;

/// The classifier words a record writes a condition's SUBTYPE with, each followed by the
/// numeral that picks the subtype out ("type 2 diabetes mellitus", "stage 3 chronic
/// kidney disease").
///
/// Source: the modelled `QUALITY` attribute type, which reports a qualifier OF the
/// condition an entity names rather than part of the condition's own name.
pub(crate) const SUBTYPE_CLASSIFIERS: &[&str] = &["type", "stage", "grade", "class"];

/// The numerals a subtype is written with: digits, or the roman numerals a record writes
/// a disease type with.
pub(crate) const SUBTYPE_NUMERALS: &[&str] = &["i", "ii", "iii", "iv", "v"];

/// The words a cue is written with in front of the mention it introduces.
pub(crate) const CUE_FUNCTION_WORDS: &[&str] = &["of", "for", "with", "on", "a", "an", "the"];

/// The alphanumeric groups `matched` is written in — the parts of a written form, as the
/// text itself separates them.
pub(crate) fn written_groups(matched: &str) -> usize {
    matched
        .split(|character: char| !character.is_alphanumeric())
        .filter(|group| !group.is_empty())
        .count()
}

/// The confidence of ONE detection whose evidence class weighs `base` and whose placed
/// text is `matched`.
///
/// A confidence reports what THIS detection established, so it is read off the text the
/// detection placed rather than fixed per evidence class: every written group beyond the
/// first is one more part of the class's written form that the text actually spells out,
/// and each closes [`CONFIDENCE_GROUP_SHARE`] of what is left between the class weight
/// and [`CONFIDENCE_CEILING`] — so a more fully written mention is reported with more
/// confidence and no detection reports certainty.
pub(crate) fn span_confidence(base: f32, matched: &str) -> f32 {
    let base = base.clamp(0.0, CONFIDENCE_CEILING);
    let groups = written_groups(matched);
    let remaining = (1.0 - CONFIDENCE_GROUP_SHARE)
        .powi(i32::try_from(groups.saturating_sub(1)).unwrap_or(i32::MAX));
    (CONFIDENCE_CEILING - (CONFIDENCE_CEILING - base) * remaining).clamp(0.0, CONFIDENCE_CEILING)
}

/// `confidence` raised by ONE more piece of evidence for the same detection: the
/// detection closes [`CONFIDENCE_GROUP_SHARE`] of what was left between what it had and
/// [`CONFIDENCE_CEILING`], so corroborated evidence is reported with more confidence than
/// the same single piece of evidence alone and nothing reports certainty.
pub(crate) fn raised(confidence: f32) -> f32 {
    let confidence = confidence.clamp(0.0, CONFIDENCE_CEILING);
    (confidence + (CONFIDENCE_CEILING - confidence) * CONFIDENCE_GROUP_SHARE)
        .clamp(0.0, CONFIDENCE_CEILING)
}

/// The score each of the `count` ontology candidates of one mention reports, in rank
/// order, for a mention whose own confidence is `confidence`.
///
/// Every modelled ontology concept's `Score` reports "the likelihood of the match", so a
/// candidate's score answers how likely it is that the mention refers to THAT concept
/// rather than to one of the others it could refer to: the mention's confidence is
/// divided between its candidates, each successive one keeping [`CONCEPT_RANK_DECAY`] of
/// the share in front of it. The list is therefore strictly descending, the whole list
/// adds up to the mention's own confidence, and the leading candidate of a long list
/// scores well below a mention the ontology leaves no choice about.
pub(crate) fn candidate_scores(confidence: f32, count: usize) -> Vec<f32> {
    let shares: Vec<f32> = (0..count)
        .map(|rank| CONCEPT_RANK_DECAY.powi(i32::try_from(rank).unwrap_or(i32::MAX)))
        .collect();
    let total: f32 = shares.iter().sum();
    if total <= 0.0 {
        return vec![0.0; count];
    }
    shares
        .into_iter()
        .map(|share| confidence * share / total)
        .collect()
}

/// How many LEADING tokens of the normalized written form `term` are a subtype qualifier
/// of the condition the rest of it names, or 0 when it carries none.
///
/// A qualifier is a classifier word and its numeral, and it qualifies a condition NAME,
/// so a written form that is NOTHING but a qualifier carries none: there would be no name
/// left for the entity to span.
pub(crate) fn subtype_qualifier_tokens(term: &str) -> usize {
    let words: Vec<&str> = term.split(' ').collect();
    if words.len() < 3 || !SUBTYPE_CLASSIFIERS.contains(&words[0]) {
        return 0;
    }
    let numeral = words[1];
    let numbered = !numeral.is_empty()
        && (numeral.chars().all(|character| character.is_ascii_digit())
            || SUBTYPE_NUMERALS.contains(&numeral));
    if numbered {
        2
    } else {
        0
    }
}

/// `span` split after its first `leading` tokens: the stretch of text the REST of it
/// covers, then the stretch those leading tokens cover. `None` when there is nothing to
/// split off, or nothing left after it.
pub(crate) fn split_leading(tokens: &[Token], span: &Span, leading: usize) -> Option<(Span, Span)> {
    let boundary = span.tokens.start + leading;
    (leading > 0 && boundary < span.tokens.end).then(|| {
        (
            Span::of(tokens, boundary..span.tokens.end),
            Span::of(tokens, span.tokens.start..boundary),
        )
    })
}

