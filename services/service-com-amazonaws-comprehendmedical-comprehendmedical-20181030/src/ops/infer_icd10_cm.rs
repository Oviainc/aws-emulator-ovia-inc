/// The lexicon, indexed by written form, with the longest form it holds.
struct Lexicon {
    terms: HashMap<&'static str, &'static Condition>,
    max_tokens: usize,
}

/// The lexicon, built once per process rather than per request.
fn lexicon() -> &'static Lexicon {
    static LEXICON: OnceLock<Lexicon> = OnceLock::new();
    LEXICON.get_or_init(|| {
        let mut terms = HashMap::with_capacity(CONDITIONS.len());
        let mut max_tokens = 1;
        for condition in CONDITIONS {
            max_tokens = max_tokens.max(condition.term.split(' ').count());
            terms.insert(condition.term, condition);
        }
        Lexicon { terms, max_tokens }
    })
}

/// One token of the submitted text: where it is written, how it compares, and which
/// clause it belongs to.
#[derive(Debug)]
pub(crate) struct Token {
    /// Byte offset of the token's first character in the submitted text.
    pub(crate) start: usize,
    /// Byte offset one past the token's last character.
    pub(crate) end: usize,
    /// The token lowercased, which is what every table above is matched against.
    pub(crate) lower: String,
    /// Which clause of the text the token is in. A cue only scopes the mentions of its
    /// own clause, so a sentence boundary stops every context rule below.
    pub(crate) clause: usize,
}

/// The submitted text as tokens: each maximal run of alphanumeric characters is one
/// token, and every other character separates tokens — so case, hyphenation and
/// punctuation do not change what is matched. The clause number advances at sentence
/// and clause punctuation.
///
/// A period standing BETWEEN two digits is a decimal point rather than a sentence end,
/// so a written number is one token in one clause ("7.2", not "7" and a new clause
/// holding "2").
pub(crate) fn tokenize(text: &str) -> Vec<Token> {
    let mut tokens: Vec<Token> = Vec::new();
    let mut clause = 0usize;
    let mut run: Option<(usize, usize)> = None;
    let mut previous: Option<char> = None;
    let mut characters = text.char_indices().peekable();
    while let Some((index, character)) = characters.next() {
        let decimal_point = character == '.'
            && run.is_some()
            && previous.is_some_and(|before| before.is_ascii_digit())
            && characters
                .peek()
                .is_some_and(|&(_, next)| next.is_ascii_digit());
        if character.is_alphanumeric() || decimal_point {
            match run {
                Some((_, ref mut end)) => *end = index + character.len_utf8(),
                None => run = Some((index, index + character.len_utf8())),
            }
        } else {
            if let Some((start, end)) = run.take() {
                tokens.push(Token {
                    start,
                    end,
                    lower: text[start..end].to_lowercase(),
                    clause,
                });
            }
            if matches!(character, '.' | '!' | '?' | ';' | ':' | '\n' | '\r') {
                clause += 1;
            }
        }
        previous = Some(character);
    }
    if let Some((start, end)) = run {
        tokens.push(Token {
            start,
            end,
            lower: text[start..end].to_lowercase(),
            clause,
        });
    }
    tokens
}

/// A stretch of the submitted text the pass placed, in TOKEN indices and in BYTE
/// offsets into that text.
#[derive(Debug, Clone)]
pub(crate) struct Span {
    pub(crate) tokens: Range<usize>,
    pub(crate) start: usize,
    pub(crate) end: usize,
}

impl Span {
    /// The span covering `tokens[range]`.
    pub(crate) fn of(tokens: &[Token], range: Range<usize>) -> Self {
        Self {
            start: tokens[range.start].start,
            end: tokens[range.end - 1].end,
            tokens: range,
        }
    }
}

/// The 0-based CHARACTER offset of every character of `text`, as its BYTE offset.
///
/// The passes work in byte offsets; both modelled offset members report character
/// offsets, so the two are converted through this table once per request.
pub(crate) fn character_starts(text: &str) -> Vec<usize> {
    text.char_indices().map(|(index, _)| index).collect()
}

/// The 0-based CHARACTER offset of the position `byte` bytes into the text whose
/// character starts are `starts`.
pub(crate) fn character_offset(starts: &[usize], byte: usize) -> i32 {
    i32::try_from(starts.partition_point(|&start| start < byte)).unwrap_or(i32::MAX)
}

/// One attribute of a condition mention: a stretch of text beside the mention that says
/// something about it, and which modelled attribute type it reports.
#[derive(Debug)]
struct Attribute {
    span: Span,
    attribute_type: &'static str,
    category: &'static str,
    relationship_type: &'static str,
    /// Tokens between the attribute and the mention, which is what the relationship
    /// confidence falls off with.
    distance: usize,
}

/// What the pass placed at one stretch of text.
#[derive(Debug)]
enum Placed {
    /// A medical-condition mention, with the attributes read as belonging to it.
    Condition {
        span: Span,
        condition: &'static Condition,
        attributes: Vec<Attribute>,
    },
    /// A time expression that belongs to no single mention.
    Time { span: Span },
}

impl Placed {
    fn span(&self) -> &Span {
        match self {
            Self::Condition { span, .. } | Self::Time { span } => span,
        }
    }
}

/// Whether `token` counts a quantity: a written number (a run of digits, with at most
/// one decimal point), or a counting word.
pub(crate) fn is_count(token: &Token) -> bool {
    let word = token.lower.as_str();
    let number = word.chars().any(|character| character.is_ascii_digit())
        && word
            .chars()
            .all(|character| character.is_ascii_digit() || character == '.')
        && word.chars().filter(|&character| character == '.').count() <= 1;
    number || NUMBER_WORDS.contains(&word)
}

/// The confidence of a mention its lexicon entry spans `term_tokens` tokens of.
pub(crate) fn term_confidence(term_tokens: usize) -> f32 {
    let extra = term_tokens.clamp(1, TERM_TOKENS_AT_FULL_CONFIDENCE) - 1;
    (WEIGHT_TERM_ONE_TOKEN + WEIGHT_TERM_PER_TOKEN * extra as f32).clamp(0.0, 1.0)
}

/// Every maximal lexicon match in `tokens`, left to right, longest written form first.
///
/// `max_tokens` is the longest written form the lexicon holds, and `is_term` answers
/// whether a phrase — the tokens lowercased and joined by single spaces, which is how
/// every lexicon in this crate spells its entries — is one of them. The tokens of a
/// match are marked covered, so a match never overlaps another and the scan resumes past
/// it; the caller maps the phrase it gets back onto its own lexicon entry.
pub(crate) fn lexicon_matches(
    tokens: &[Token],
    covered: &mut [bool],
    max_tokens: usize,
    is_term: impl Fn(&str) -> bool,
) -> Vec<(Span, String)> {
    let mut placed = Vec::new();
    let mut index = 0usize;
    while index < tokens.len() {
        if covered[index] {
            index += 1;
            continue;
        }
        let longest = max_tokens.min(tokens.len() - index);
        let mut matched = None;
        for length in (1..=longest).rev() {
            let range = index..index + length;
            // A written form is never read across a clause boundary, and never over a
            // token something else already placed.
            if tokens[range.clone()]
                .iter()
                .any(|token| token.clause != tokens[index].clause)
                || covered[range.clone()].iter().any(|taken| *taken)
            {
                continue;
            }
            let phrase = tokens[range.clone()]
                .iter()
                .map(|token| token.lower.as_str())
                .collect::<Vec<_>>()
                .join(" ");
            if is_term(phrase.as_str()) {
                matched = Some((range, phrase));
                break;
            }
        }
        match matched {
            Some((range, phrase)) => {
                for token in &mut covered[range.clone()] {
                    *token = true;
                }
                index = range.end;
                placed.push((Span::of(tokens, range), phrase));
            }
            None => index += 1,
        }
    }
    placed
}

/// Every condition mention in `tokens`, longest written form first, left to right.
///
/// A mention never overlaps another: the tokens of a placed mention are marked covered,
/// so the longest written form that starts at a token is the one reported and the scan
/// resumes past it.
fn condition_mentions(
    tokens: &[Token],
    covered: &mut [bool],
) -> Vec<(Span, &'static Condition)> {
    let lexicon = lexicon();
    lexicon_matches(tokens, covered, lexicon.max_tokens, |phrase| {
        lexicon.terms.contains_key(phrase)
    })
    .into_iter()
    .filter_map(|(span, phrase)| {
        lexicon
            .terms
            .get(phrase.as_str())
            .map(|condition| (span, *condition))
    })
    .collect()
}

/// Every age written in the text, as the spans this pass places for them, with the
/// tokens they cover marked placed.
///
/// An age counts how old the PERSON is: it is the `AGE` identifier class of this crate's
/// protected-health-information pass (`crate::ops::detect_phi`, which states the written
/// forms of that class and places them), not the time course of a medical condition, so
/// an analysis whose entity vocabulary is medical reports no entity for it. The span is
/// still PLACED: the tokens it covers are not read as the time of a condition or as a
/// quantity of one, and the response-wide id sequence counts it like every other span the
/// pass placed.
pub(crate) fn age_spans(text: &str, tokens: &[Token], covered: &mut [bool]) -> Vec<Span> {
    let mut placed = Vec::new();
    for (start, _) in crate::ops::detect_phi::age_spans(text, tokens) {
        let Some(index) = tokens.iter().position(|token| token.start == start) else {
            continue;
        };
        if covered[index] {
            continue;
        }
        // The unit the age is counted in, where the text writes one after the number, is
        // part of the age expression rather than a time expression of its own.
        let unit = index + 1;
        let end = if unit < tokens.len()
            && !covered[unit]
            && tokens[unit].clause == tokens[index].clause
            && TIME_UNITS.contains(&tokens[unit].lower.as_str())
        {
            unit + 1
        } else {
            index + 1
        };
        for token in &mut covered[index..end] {
            *token = true;
        }
        placed.push(Span::of(tokens, index..end));
    }
    placed
}

/// The `Id` every span of one response carries, keyed by the span's byte start.
///
/// Every modelled `Id` member is "a monotonically increasing id unique within this
/// response rather than a global unique identifier", and the analysis numbers the spans
/// of ONE document in the order they are WRITTEN: an attribute written in front of the
/// entity it belongs to therefore carries the LOWER id, and a span the pass placed but
/// this operation's entity vocabulary does not report still takes its place in the
/// sequence, which is why the id of a reported entity can skip.
pub(crate) fn span_ids(starts: impl IntoIterator<Item = usize>) -> HashMap<usize, i32> {
    let mut starts: Vec<usize> = starts.into_iter().collect();
    starts.sort_unstable();
    starts.dedup();
    starts
        .into_iter()
        .enumerate()
        .map(|(rank, start)| {
            (
                start,
                i32::try_from(rank)
                    .unwrap_or(i32::MAX)
                    .saturating_add(FIRST_ID),
            )
        })
        .collect()
}

/// Every time expression in the tokens no mention covers: a count followed by a unit
/// ("3 days", "two weeks", optionally "… ago"), a qualifier in front of a unit ("last
/// year"), or a word that names a time on its own ("yesterday").
fn time_expressions(tokens: &[Token], covered: &mut [bool]) -> Vec<Span> {
    let mut placed = Vec::new();
    let mut index = 0usize;
    while index < tokens.len() {
        if covered[index] {
            index += 1;
            continue;
        }
        let clause = tokens[index].clause;
        // Whether the token at `next` is still available and still in this clause.
        let open = |next: usize, covered: &[bool]| {
            next < tokens.len() && !covered[next] && tokens[next].clause == clause
        };
        let counted_unit = (is_count(&tokens[index])
            || RELATIVE_QUALIFIERS.contains(&tokens[index].lower.as_str()))
            && open(index + 1, covered)
            && TIME_UNITS.contains(&tokens[index + 1].lower.as_str());
        let mut end = if counted_unit {
            index + 2
        } else if RELATIVE_DAY_WORDS.contains(&tokens[index].lower.as_str()) {
            index + 1
        } else {
            index += 1;
            continue;
        };
        // "three days ago" is one time expression, not a time expression and a word.
        if open(end, covered) && tokens[end].lower == "ago" {
            end += 1;
        }
        let range = index..end;
        for token in &mut covered[range.clone()] {
            *token = true;
        }
        placed.push(Span::of(tokens, range));
        index = end;
    }
    placed
}

/// The modelled attribute type a one-word modifier reports, or `None` when the word
/// modifies nothing.
fn modifier_type(token: &Token) -> Option<&'static str> {
    let word = token.lower.as_str();
    if ACUITY_MODIFIERS.contains(&word) {
        return Some(ATTRIBUTE_ACUITY);
    }
    if DIRECTION_MODIFIERS.contains(&word) {
        return Some(ATTRIBUTE_DIRECTION);
    }
    if QUALITY_MODIFIERS.contains(&word) {
        return Some(ATTRIBUTE_QUALITY);
    }
    if SYSTEM_ORGAN_SITE_MODIFIERS.contains(&word) {
        return Some(ATTRIBUTE_SYSTEM_ORGAN_SITE);
    }
    if is_count(token) {
        return Some(ATTRIBUTE_QUANTITY);
    }
    None
}

/// How the entity and an attribute of that type are related, as the modelled
/// `ICD10CMRelationshipType` names it: a body system or site relates to the condition as
/// the site of it, a quality as the quality of it, and anything else overlaps the
/// mention in the text.
fn relationship_type(attribute_type: &str) -> &'static str {
    match attribute_type {
        ATTRIBUTE_SYSTEM_ORGAN_SITE => RELATIONSHIP_SYSTEM_ORGAN_SITE,
        ATTRIBUTE_QUALITY => RELATIONSHIP_QUALITY,
        _ => RELATIONSHIP_OVERLAP,
    }
}

/// Where the FIRST family reference of each clause is written, by clause.
///
/// One pass over the text, so the family rule costs the same whether the text carries
/// one mention or hundreds.
pub(crate) fn first_family_cues(tokens: &[Token]) -> HashMap<usize, usize> {
    let mut first: HashMap<usize, usize> = HashMap::new();
    for (index, token) in tokens.iter().enumerate() {
        if FAMILY_CUES.contains(&token.lower.as_str()) {
            first.entry(token.clause).or_insert(index);
        }
    }
    first
}

/// Whether one of `cues` stands in the [`CUE_WINDOW_TOKENS`] tokens BEFORE `span`, in
/// the span's own clause — the window a cue that scopes what follows it reaches over.
pub(crate) fn cue_precedes(tokens: &[Token], span: &Span, cues: &[&str]) -> bool {
    let clause = tokens[span.tokens.start].clause;
    let window_start = span.tokens.start.saturating_sub(CUE_WINDOW_TOKENS);
    tokens[window_start..span.tokens.start]
        .iter()
        .filter(|token| token.clause == clause)
        .any(|token| cues.contains(&token.lower.as_str()))
}

/// Whether one of `cues` DIRECTLY governs `span`: the cue stands in the span's own
/// clause and nothing but the words a cue is written with stands between the two.
///
/// A cue that asserts something about the mention ITSELF — when it happened — reaches
/// only the mention it introduces, so any other word written between the two ends its
/// reach. A hedge over the whole clause reaches further, which is what [`cue_precedes`]
/// answers for.
pub(crate) fn cue_governs(tokens: &[Token], span: &Span, cues: &[&str]) -> bool {
    let clause = tokens[span.tokens.start].clause;
    let mut index = span.tokens.start;
    while index > 0 {
        index -= 1;
        if tokens[index].clause != clause {
            return false;
        }
        let word = tokens[index].lower.as_str();
        if cues.contains(&word) {
            return true;
        }
        if !CUE_FUNCTION_WORDS.contains(&word) {
            return false;
        }
    }
    false
}

/// The names of the traits the words around `span` license, beside the one its lexicon
/// entry carries. Every name is a member of both ontologies' trait enums, so each
/// operation maps them onto its own modelled trait shape.
///
/// A negation, hedge or hypothetical cue scopes the mentions that follow it within
/// [`CUE_WINDOW_TOKENS`] tokens of the same clause; a family reference scopes the rest of
/// its clause, because it names whose record the rest of the clause is about.
pub(crate) fn cue_trait_names(
    tokens: &[Token],
    span: &Span,
    first_family_cues: &HashMap<usize, usize>,
) -> Vec<&'static str> {
    let clause = tokens[span.tokens.start].clause;
    let family = first_family_cues
        .get(&clause)
        .is_some_and(|&cue| cue < span.tokens.start);
    let mut names = Vec::new();
    for (licensed, name) in [
        (cue_precedes(tokens, span, NEGATION_CUES), TRAIT_NEGATION),
        (family, TRAIT_PERTAINS_TO_FAMILY),
        (
            cue_precedes(tokens, span, HYPOTHETICAL_CUES),
            TRAIT_HYPOTHETICAL,
        ),
        (
            cue_precedes(tokens, span, LOW_CONFIDENCE_CUES),
            TRAIT_LOW_CONFIDENCE,
        ),
    ] {
        if licensed {
            names.push(name);
        }
    }
    names
}

/// The traits the words around `span` license, as the modelled ICD-10-CM trait shape.
fn cue_traits(
    tokens: &[Token],
    span: &Span,
    first_family_cues: &HashMap<usize, usize>,
) -> Vec<ICD10CMTrait> {
    cue_trait_names(tokens, span, first_family_cues)
        .into_iter()
        .map(|name| ICD10CMTrait {
            name: Some(name.to_string()),
            score: Some(WEIGHT_CUE),
        })
        .collect()
}

/// The attributes of the mention at `span`: the modifiers standing within
/// [`ATTRIBUTE_WINDOW_TOKENS`] tokens of it, in its own clause, that no other span has
/// taken. Mentions are served in document order, so a modifier between two mentions
/// belongs to the first that reaches it.
fn modifier_attributes(tokens: &[Token], span: &Span, covered: &mut [bool]) -> Vec<Attribute> {
    let clause = tokens[span.tokens.start].clause;
    let before = span.tokens.start.saturating_sub(ATTRIBUTE_WINDOW_TOKENS)..span.tokens.start;
    let after = span.tokens.end..(span.tokens.end + ATTRIBUTE_WINDOW_TOKENS).min(tokens.len());
    let mut attributes = Vec::new();
    for index in before.chain(after) {
        if covered[index] || tokens[index].clause != clause {
            continue;
        }
        let Some(attribute_type) = modifier_type(&tokens[index]) else {
            continue;
        };
        let distance = if index < span.tokens.start {
            span.tokens.start - index - 1
        } else {
            index - span.tokens.end
        };
        covered[index] = true;
        attributes.push(Attribute {
            span: Span::of(tokens, index..index + 1),
            attribute_type,
            category: TYPE_DX_NAME,
            relationship_type: relationship_type(attribute_type),
            distance,
        });
    }
    attributes
}

/// The ICD-10-CM entities the submitted text carries.
///
/// The answer is a function of `text` alone: the mentions are placed from the text's own
/// characters, so the same text always yields the same entities and no value from any
/// other request can appear. `BeginOffset`/`EndOffset` are 0-based CHARACTER offsets, as
/// the modelled members document, so an entity's `Text` is exactly the characters they
/// delimit.
pub fn infer_icd10_cm(text: &str) -> Vec<ICD10CMEntity> {
    let tokens = tokenize(text);
    let mut covered = vec![false; tokens.len()];
    let family_cues = first_family_cues(&tokens);

    // Every condition mention, with the subtype qualifier its written form carries split
    // off: a qualifier modifies the condition the rest of the form names, so the entity
    // spans the condition NAME and the qualifier is reported as that entity's own
    // `QUALITY` attribute. The concepts stay the ones the WHOLE written form names — the
    // qualifier is what tells the subtype's codes from the unspecified ones.
    let mentions: Vec<(Span, Option<Span>, &'static Condition)> =
        condition_mentions(&tokens, &mut covered)
            .into_iter()
            .map(|(span, condition)| {
                match split_leading(&tokens, &span, subtype_qualifier_tokens(condition.term)) {
                    Some((name, qualifier)) => (name, Some(qualifier), condition),
                    None => (span, None, condition),
                }
            })
            .collect();
    // The ages are placed before the time pass: an age counts how old the person is, so
    // the tokens it covers are not read as the time course of a condition.
    let ages = age_spans(text, &tokens, &mut covered);
    let times = time_expressions(&tokens, &mut covered);

    // A time expression is reported only in a clause that also carries a condition
    // mention: it is the time of a condition, which is what makes it part of an
    // ICD-10-CM analysis. One standing within the attribute window of a mention is an
    // attribute of that mention (the modelled `TIME_TO_DX_NAME`); one further away in the
    // same clause is its own `TIME_EXPRESSION` entity.
    let mut placed: Vec<Placed> = mentions
        .iter()
        .map(|(span, qualifier, condition)| Placed::Condition {
            span: span.clone(),
            condition,
            attributes: qualifier
                .iter()
                .map(|qualifier| Attribute {
                    span: qualifier.clone(),
                    attribute_type: ATTRIBUTE_QUALITY,
                    category: TYPE_DX_NAME,
                    relationship_type: relationship_type(ATTRIBUTE_QUALITY),
                    // The qualifier is written immediately in front of the name it
                    // qualifies, so nothing stands between the two.
                    distance: 0,
                })
                .collect(),
        })
        .collect();
    let mut loose_times: Vec<Span> = Vec::new();
    for time in times {
        let clause = tokens[time.tokens.start].clause;
        let nearest = mentions
            .iter()
            .filter(|(span, _, _)| tokens[span.tokens.start].clause == clause)
            .map(|(span, _, _)| {
                let distance = if span.tokens.end <= time.tokens.start {
                    time.tokens.start - span.tokens.end
                } else {
                    // The spans overlap only when a time expression IS the mention's
                    // neighbour-less self, which cannot happen: a covered token is never
                    // placed twice. The saturating form keeps that impossible case at
                    // distance 0 rather than wrapping.
                    span.tokens.start.saturating_sub(time.tokens.end)
                };
                (distance, span.start)
            })
            .min();
        match nearest {
            Some((distance, mention_start)) if distance <= ATTRIBUTE_WINDOW_TOKENS => {
                if let Some(Placed::Condition { attributes, .. }) =
                    placed.iter_mut().find(|entry| match entry {
                        Placed::Condition { span, .. } => span.start == mention_start,
                        Placed::Time { .. } => false,
                    })
                {
                    attributes.push(Attribute {
                        span: time,
                        attribute_type: ATTRIBUTE_TIME_TO_DX_NAME,
                        category: TYPE_TIME_EXPRESSION,
                        relationship_type: RELATIONSHIP_OVERLAP,
                        distance,
                    });
                }
            }
            Some(_) => loose_times.push(time),
            // No mention in the clause: nothing an ICD-10-CM analysis would date.
            None => {}
        }
    }
    for time in loose_times {
        placed.push(Placed::Time { span: time });
    }

    // The modifiers come last, so a token a mention or a time expression already covers
    // is never read as a modifier too.
    let mention_spans: Vec<Span> = mentions.into_iter().map(|(span, _, _)| span).collect();
    for span in &mention_spans {
        let found = modifier_attributes(&tokens, span, &mut covered);
        if let Some(Placed::Condition { attributes, .. }) =
            placed.iter_mut().find(|entry| match entry {
                Placed::Condition { span: placed, .. } => placed.start == span.start,
                Placed::Time { .. } => false,
            })
        {
            attributes.extend(found);
        }
    }

    placed.sort_by_key(|entry| entry.span().start);

    // Character offsets, as both modelled offset members document, from the byte offsets
    // the pass works in.
    let character_starts = character_starts(text);
    let character_offset = |byte: usize| character_offset(&character_starts, byte);

    // `Id` is "a monotonically increasing id unique within this response": the spans this
    // pass placed are numbered in the order they are WRITTEN — entities, their attributes
    // and the spans this operation reports no entity for sharing the one sequence (see
    // [`span_ids`]) — so an attribute written in front of its entity carries the lower id.
    let ids = span_ids(
        placed
            .iter()
            .flat_map(|entry| match entry {
                Placed::Condition {
                    span, attributes, ..
                } => std::iter::once(span.start)
                    .chain(attributes.iter().map(|attribute| attribute.span.start))
                    .collect::<Vec<_>>(),
                Placed::Time { span } => vec![span.start],
            })
            .chain(ages.iter().map(|age| age.start)),
    );
    let id_of = |start: usize| ids.get(&start).copied().unwrap_or(FIRST_ID);
    let mut entities = Vec::with_capacity(placed.len());
    for entry in placed {
        match entry {
            Placed::Condition {
                span,
                condition,
                mut attributes,
            } => {
                let written = &text[span.start..span.end];
                let score = span_confidence(
                    term_confidence(condition.term.split(' ').count()),
                    written,
                );
                let id = id_of(span.start);
                let mut traits = vec![ICD10CMTrait {
                    name: Some(condition.base_trait.to_string()),
                    score: Some(score),
                }];
                traits.extend(cue_traits(&tokens, &span, &family_cues));
                attributes.sort_by_key(|attribute| attribute.span.start);
                let attributes = attributes
                    .into_iter()
                    .map(|attribute| {
                        let attribute_id = id_of(attribute.span.start);
                        let relationship_score = (WEIGHT_RELATIONSHIP
                            - RELATIONSHIP_DISTANCE_PENALTY * attribute.distance as f32)
                            .clamp(0.0, 1.0);
                        let written = &text[attribute.span.start..attribute.span.end];
                        let base = if attribute.attribute_type == ATTRIBUTE_TIME_TO_DX_NAME {
                            WEIGHT_PATTERN
                        } else {
                            WEIGHT_MODIFIER
                        };
                        ICD10CMAttribute {
                            r#type: Some(attribute.attribute_type.to_string()),
                            score: Some(span_confidence(base, written)),
                            relationship_score: Some(relationship_score),
                            relationship_type: Some(attribute.relationship_type.to_string()),
                            id: Some(attribute_id),
                            begin_offset: Some(character_offset(attribute.span.start)),
                            end_offset: Some(character_offset(attribute.span.end)),
                            text: Some(written.to_string()),
                            traits: Some(cue_traits(&tokens, &attribute.span, &family_cues)),
                            category: Some(attribute.category.to_string()),
                        }
                    })
                    .collect();
                // The candidates the mention could refer to, most likely first and cut at
                // the candidate limit, each carrying its own share of the mention's
                // confidence.
                let candidates: Vec<&Concept> = condition
                    .concepts
                    .iter()
                    .take(CONCEPT_CANDIDATE_LIMIT)
                    .collect();
                let concepts = candidates
                    .iter()
                    .zip(candidate_scores(score, candidates.len()))
                    .map(|(concept, candidate_score)| ICD10CMConcept {
                        code: Some(concept.code.to_string()),
                        description: Some(concept.description.to_string()),
                        score: Some(candidate_score),
                    })
                    .collect();
                entities.push(ICD10CMEntity {
                    id: Some(id),
                    text: Some(written.to_string()),
                    category: Some(CATEGORY_MEDICAL_CONDITION.to_string()),
                    r#type: Some(TYPE_DX_NAME.to_string()),
                    score: Some(score),
                    begin_offset: Some(character_offset(span.start)),
                    end_offset: Some(character_offset(span.end)),
                    attributes: Some(attributes),
                    traits: Some(traits),
                    icd10_cm_concepts: Some(concepts),
                });
            }
            Placed::Time { span } => {
                let id = id_of(span.start);
                let written = &text[span.start..span.end];
                entities.push(ICD10CMEntity {
                    id: Some(id),
                    text: Some(written.to_string()),
                    category: Some(CATEGORY_MEDICAL_CONDITION.to_string()),
                    r#type: Some(TYPE_TIME_EXPRESSION.to_string()),
                    score: Some(span_confidence(WEIGHT_PATTERN, written)),
                    begin_offset: Some(character_offset(span.start)),
                    end_offset: Some(character_offset(span.end)),
                    attributes: Some(Vec::new()),
                    traits: Some(cue_traits(&tokens, &span, &family_cues)),
                    // A time expression names no medical condition, so there is no
                    // ICD-10-CM concept for it to be linked to.
                    icd10_cm_concepts: None,
                });
            }
        }
    }
    entities
}

