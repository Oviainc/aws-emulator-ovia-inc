//! @op ReimportApi
//! IMPLEMENTED: PUTS the api resource the OpenAPI definition in `Body` describes over the
//! api `ApiId` names, so the api keeps its identity — its `ApiId`, its `ApiEndpoint`, its
//! `CreatedDate`, its tags, and the stages, deployments and authorizers it holds — while
//! the configuration a definition carries is REPLACED by the one just read: the name,
//! description and version from `info`, the CORS and endpoint-configuration extensions,
//! and exactly the [`crate::state::Route`]s and [`crate::state::Integration`]s the
//! document's `paths` declare. This is the ONLY file to touch for this operation.
//!
//! That replacement is what makes a reimported document change what the api's deployed
//! stages serve: the routes the previous document declared are gone, so the data plane
//! ([`crate::service`]) matches a request against the new document's route keys alone.
//!
//! The definition is read by the ONE reader `ImportApi` reads it with
//! (`super::import_api::parse_definition`, which that operation makes `pub` for exactly
//! this reason), under the same `Basepath` interpretation and the same refusals, so the
//! same body imports and reimports identically. "Supported only for HTTP APIs"
//! (`ReimportApi$Body`), so an api of the other protocol type is refused rather than
//! having an HTTP-only definition written over it.
//!
//! ## Shape of an operation
//!
//! Each operation is a struct that owns the shared engine and implements
//! [`smithy_server_runtime::Operation`]. The framework constructs one per service via
//! `ReimportApi::new(engine)` and drives it through the centralized request walk:
//! deserialize → validate → `handle` → serialize. You write ONLY the `handle` body.
//!
//! ## Reaching this service's state
//!
//! The engine is held on `self` (constructor-injected), NOT passed per request — so
//! engine access is guaranteed by the time any request runs. Reach the store through
//! [`crate::state::service_state`] and read and write it through the guard it hands back:
//!
//! ```ignore
//!     let state = crate::state::service_state(&*self.engine)
//!         .ok_or(/* a modelled server error */)?;
//!     state.lock().your_field = /* ... */;
//! ```
//!
//! `ctx` ([`smithy_server_runtime::OperationContext`]) carries request metadata only —
//! headers, URI, method, and anything middleware placed in `ctx.parts().extensions`.
//! The engine is NOT reached through `ctx`.
//!
//! @generated by the emulator core scaffold op-stub generator.
//! Shared types live in `super::types`; the error channel in `crate::scaffolded`.
//!
//! ---
//!
//! # Modeled contract for `ReimportApi`
//!
//! What AWS documents for this operation, from this service's Smithy model. HTML is
//! stripped and long entries are clipped at ` …`. For the FULL text of any one item,
//! ask the model rather than reading the raw JSON:
//!
//! ```text
//! smithy_query(query="doc",shape="<Shape>",member="<Member>",model_path="services/service-com-amazonaws-apigatewayv2-apigatewayv2/smithy-model/com-amazonaws-apigatewayv2-apigatewayv2.json")
//! ```
//!
//! Puts an Api resource.
//!
//! ## Input
//!
//! * `ApiId` (__string) **required** — The API identifier.
//! * `Basepath` (__string) — Specifies how to interpret the base path of the API during
//!   import. Valid values are ignore, prepend, and split. The default value is ignore. To
//!   learn more, see Set the OpenAPI basePath Property. Supported only for HTTP APIs.
//! * `Body` (__string) **required** — The OpenAPI definition. Supported only for HTTP APIs.
//! * `FailOnWarnings` (__boolean) — Specifies whether to rollback the API creation when a
//!   warning is encountered. By default, API creation continues if a warning is encountered.
//!
//! ## Output
//!
//! * `ApiEndpoint` (__string) — The URI of the API, of the form
//!   {api-id}.execute-api.{region}.amazonaws.com. The stage name is typically appended to
//!   this URI to form a complete path to a deployed API stage.
//! * `ApiGatewayManaged` (__boolean) — Specifies whether an API is managed by API Gateway.
//!   You can't update or delete a managed API by using API Gateway. A managed API can be
//!   deleted only through the tooling or service that created it.
//! * `ApiId` (Id) — The API ID.
//! * `ApiKeySelectionExpression` (SelectionExpression) — An API key selection expression.
//!   Supported only for WebSocket APIs. See API Key Selection Expressions.
//! * `CorsConfiguration` (Cors) — A CORS configuration. Supported only for HTTP APIs.
//! * `CreatedDate` (__timestampIso8601) — The timestamp when the API was created.
//! * `Description` (StringWithLengthBetween0And1024) — The description of the API.
//! * `DisableExecuteApiEndpoint` (__boolean) — Specifies whether clients can invoke your API
//!   by using the default execute-api endpoint. By default, clients can invoke your API with
//!   the default https://{api_id}.execute-api.{region}.amazonaws.com endpoint. To require
//!   that clients use a custom domain name to invoke your API, disable the default endpoint.
//! * `DisableSchemaValidation` (__boolean) — Avoid validating models when creating a
//!   deployment. Supported only for WebSocket APIs.
//! * `ImportInfo` (__listOf__string) — The validation information during API import. This may
//!   include particular properties of your OpenAPI definition which are ignored during
//!   import. Supported only for HTTP APIs.
//! * `IpAddressType` (IpAddressType, one of: dualstack | ipv4) — The IP address types that
//!   can invoke the API.
//! * `Name` (StringWithLengthBetween1And128) — The name of the API.
//! * `ProtocolType` (ProtocolType, one of: HTTP | WEBSOCKET) — The API protocol.
//! * `RouteSelectionExpression` (SelectionExpression) — The route selection expression for
//!   the API. For HTTP APIs, the routeSelectionExpression must be ${request.method}
//!   ${request.path}. If not provided, this will be the default for HTTP APIs. This property
//!   is required for WebSocket APIs.
//! * `Tags` (Tags) — A collection of tags associated with the API.
//! * `Version` (StringWithLengthBetween1And64) — A version identifier for the API.
//! * `Warnings` (__listOf__string) — The warning messages reported when failonwarnings is
//!   turned on during API import.
//!
//! ## Errors
//!
//! * `BadRequestException` (HTTP 400) — The request is not valid, for example, the input is
//!   incomplete or incorrect. See the accompanying error message for details.
//! * `ConflictException` (HTTP 409) — The requested operation would cause a conflict with the
