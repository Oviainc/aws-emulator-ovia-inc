impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CompleteRollout<Eng>
{
    type Input = CompleteRolloutInput;
    type Output = CompleteRolloutOutput;
    type Error = CompleteRolloutError;

    const NAME: &'static str = "CompleteRollout";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::COMPLETE_ROLLOUT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::COMPLETE_ROLLOUT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // IAM decides authorization before the trajectory is resolved, under this
        // operation's own IAM action ([`crate::service::authorization`]).
        crate::service::authorization::authorize(&*self.engine, ctx, Self::NAME, &input.job_arn)
            .map_err(CompleteRolloutErrorModeled::AccessDeniedException)?;

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(CompleteRolloutErrorModeled::InternalServiceError(
                InternalServiceError {
                    message: "the AgenticRFT runtime emulator has no state store".to_string(),
                },
            )
            .into());
        };

        // `Status` targets the `CompletionStatus` enum, so only the two values the
        // model declares can seal a trajectory.
        let requested = match input.status.as_deref() {
            None => DEFAULT_COMPLETION_STATUS,
            Some(value) => match crate::state::CompletionStatus::from_wire(value) {
                Some(status) => status,
                None => return Err(enum_violation(value)),
            },
        };

        // The `(JobArn, TrajectoryId)` pair is resolved through the ONE resolution both
        // rollout-lifecycle operations serve a call by, so this operation cannot disagree
        // with `UpdateReward` about which pairs are refused, in which order, or with which
        // sentence; what is this operation's own is the error it reports that sentence
        // through, and what it does to the trajectory it is handed.
        crate::state::serve_rollout_trajectory(
            &*self.engine,
            &state,
            &input.job_arn,
            &input.trajectory_id,
            |trajectory, now| match trajectory.completion_status {
                // Not sealed yet: seal it, recording the terminal status and the
                // `ClientToken` the sealing call carried.
                None => {
                    trajectory.status = crate::state::TrajectoryStatus::Complete;
                    trajectory.completion_status = Some(requested);
                    trajectory.complete_rollout_token = input.client_token.clone();
                    trajectory.updated_at = now;
                    Ok(CompleteRolloutOutput {})
                }
                // `@idempotent`: asking again for the status it is already sealed with
                // changes nothing and succeeds.
                Some(sealed) if sealed == requested => Ok(CompleteRolloutOutput {}),
                // Anything that would CHANGE the sealed terminal status conflicts with
                // the trajectory's current state.
                Some(sealed) => Err(conflict(format!(
                    "Trajectory {} is already completed with Status {}; it cannot be completed \
                     with Status {}.",
                    input.trajectory_id,
                    sealed.as_str(),
                    requested.as_str()
                ))),
            },
        )
        .map_err(not_found)?
    }
}

#[cfg(test)]
mod tests {
    use super::{enum_violation, COMPLETION_STATUS_SET};
    use crate::ops::types::COMPLETION_STATUS_VALUES;
    use crate::service::LARGEST_QUOTED_VALUE_BYTES;

    /// The value the refusal's message quotes, read by stripping the clause's fixed halves
    /// (never by splitting on a quote, so a value carrying the delimiter is read whole).
    fn quoted_value(refusal: &super::CompleteRolloutError) -> String {
        let crate::scaffolded::Scaffolded::Modeled(
            super::CompleteRolloutErrorModeled::ValidationException(error),
        ) = refusal
        else {
            panic!("expected the modelled ValidationException, got {refusal:?}");
        };
        let head = "1 validation error detected: Value '";
        let tail = format!(
            "' at 'status' failed to satisfy constraint: Member must satisfy enum value set: \
             [{}]",
            COMPLETION_STATUS_SET.join(", ")
        );
        error
            .message
            .strip_prefix(head)
            .and_then(|rest| rest.strip_suffix(tail.as_str()))
            .unwrap_or_else(|| {
                panic!(
                    "expected the enum clause, got a {} byte message",
                    error.message.len()
                )
            })
            .to_string()
    }

    /// The order-carrying set this operation states a refusal with must hold EXACTLY the
    /// values the generated model data carries, so neither copy can drift from the model.
    #[test]
    fn completion_status_set_holds_every_modelled_value() {
        let mut stated: Vec<&str> = COMPLETION_STATUS_SET.to_vec();
        stated.sort_unstable();
        let mut modelled: Vec<&str> = COMPLETION_STATUS_VALUES.to_vec();
        modelled.sort_unstable();
        assert_eq!(
            stated, modelled,
            "the stated CompletionStatus set must be the modelled one: expected {modelled:?}, \
             got {stated:?}"
        );
    }

    /// Every value the model declares must resolve to a status, which is what makes the
    /// refusal above reachable only for a value the model does NOT declare.
    #[test]
    fn every_modelled_completion_status_resolves() {
        for value in COMPLETION_STATUS_VALUES {
            assert!(
                crate::state::CompletionStatus::from_wire(value).is_some(),
                "case {value:?}: expected a modelled CompletionStatus to resolve"
            );
        }
    }

    /// RULE: the clause this operation words itself quotes the submitted value up to the
    /// ceiling this service states from its model — the declared maximum of the member a
    /// refusal is carried in, less what the clause states around the value — and no
    /// further, so the refusal fits the member that has to hold it.
    ///
    /// Rows differ along the value's size (within, exactly at, and past the ceiling) and
    /// its encoding (ASCII, and a three-byte character so the ceiling falls inside one).
    #[test]
    fn a_refused_status_is_quoted_up_to_the_ceiling() {
        for (case, value) in [
            ("a value no ceiling touches", "bogus-status".to_string()),
            ("a quarter of the ceiling", "s".repeat(LARGEST_QUOTED_VALUE_BYTES / 4)),
            (
                "exactly at the ceiling",
                "s".repeat(LARGEST_QUOTED_VALUE_BYTES),
            ),
            (
                "multibyte characters just under the ceiling",
                // 255 * 3 = 765 bytes, three short of the 768 byte ceiling.
                "€".repeat((LARGEST_QUOTED_VALUE_BYTES / 3) - 1),
            ),
        ] {
            let quoted = quoted_value(&enum_violation(&value));
            assert_eq!(
                quoted, value,
                "case {case:?}: expected the submitted value quoted byte for byte, got {} \
                 bytes",
                quoted.len()
            );
        }

        for (case, value) in [
            (
                "one byte past the ceiling",
                "s".repeat(LARGEST_QUOTED_VALUE_BYTES + 1),
            ),
            ("a megabyte", "s".repeat(1024 * 1024)),
            (
                // One ASCII byte then three-byte characters, so the ceiling falls INSIDE a
                // character and the prefix must step back to a boundary.
                "multibyte characters past the ceiling",
                format!("x{}", "€".repeat(LARGEST_QUOTED_VALUE_BYTES)),
            ),
        ] {
            let quoted = quoted_value(&enum_violation(&value));
            let marker = format!("... [{} bytes]", value.len());
            let prefix = quoted.strip_suffix(marker.as_str()).unwrap_or_else(|| {
                panic!(
                    "case {case:?}: expected the clause to name the submitted {} bytes with \
                     {marker:?}, got {} quoted bytes",
                    value.len(),
                    quoted.len()
                )
            });
            assert!(
                value.starts_with(prefix),
                "case {case:?}: expected the quoted {} bytes to be a prefix of the submitted \
                 value",
                prefix.len()
            );
            // At the ceiling, less only what a character boundary forces back (at most two
            // bytes for UTF-8): the fidelity the echo exists for still lands, and the
            // clause cannot grow with the request.
            assert!(
                prefix.len() <= LARGEST_QUOTED_VALUE_BYTES
                    && prefix.len() + 3 > LARGEST_QUOTED_VALUE_BYTES,
                "case {case:?}: expected a prefix at the {LARGEST_QUOTED_VALUE_BYTES} byte \
                 ceiling, got {} bytes",
                prefix.len()
            );
        }
    }
}
