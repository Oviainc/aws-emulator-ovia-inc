/// The `CompleteRollout` operation.
///
/// Owns the shared engine (the constructor seam) and implements
/// [`smithy_server_runtime::Operation`]. Generic over the engine type `Eng`, so this
/// crate names no concrete engine type: a migrated service that needs state picks a
/// concrete engine where it mounts the service, not here.
/// The status an absent `Status` member means.
///
/// `Status` is optional in the model, and the operation's own documentation
/// describes exactly one outcome — the trajectory is "sealed and eligible for
/// reward submission via the UpdateReward operation" — which is the sentence the
/// `ready` enum value carries ("Trajectory completed successfully; sealed and
/// eligible for reward submission"), where `failed` is "a terminal state, no
/// further processing". So an unspecified `Status` seals the trajectory `ready`.
const DEFAULT_COMPLETION_STATUS: crate::state::CompletionStatus =
    crate::state::CompletionStatus::Ready;

/// This operation's own modelled 400 `ValidationException`.
fn validation(message: String) -> CompleteRolloutError {
    CompleteRolloutErrorModeled::ValidationException(ValidationException { message }).into()
}

/// The wire values `CompletionStatus` declares, in the order the model declares them
/// (`smithy_query(query="shape",shape="CompletionStatus")`: members `READY` then
/// `FAILED`).
///
/// The generated `COMPLETION_STATUS_VALUES` carries the same two values SORTED, which is
/// what a lookup needs; a refusal states the set in the model's own declaration order,
/// the way a service's validation message does, which is the one thing that list cannot
/// give. `completion_status_set_holds_every_modelled_value` below pins the two against
/// each other, so a value added to or renamed in the model fails loudly here rather than
/// leaving this order-carrying copy to drift.
const COMPLETION_STATUS_SET: [&str; 2] = ["ready", "failed"];

/// The refusal for a `Status` outside the modelled `CompletionStatus` enum.
///
/// The clause is built by the framework's own constraint renderer, reached through the ONE
/// wording this service states a refusal with (`crate::service::refusal_message`), so an
/// enum value the model declines is worded exactly as every other constraint violation this
/// emulator refuses — `1 validation error detected: Value '<value>' at 'status' failed
/// to satisfy constraint: Member must satisfy enum value set: [...]` — and is held to the
/// same bound: the maximum the model declares for the member a refusal is CARRIED in
/// (`Message` on every error shape of this service, targeting `FailureReason`, `@length` max
/// 1024).
///
/// The echo is quoted to the same per-value ceiling the collected violations carry
/// (`crate::service::LARGEST_QUOTED_VALUE_BYTES`): `Status` targets an enum and declares no
/// `@length`, so the value a caller can put here is unbounded, and a clause that
/// interpolated it whole would answer a message the model's own error shape cannot hold. The
/// CHECK below is still made against the value as submitted; only the quoting is bounded.
///
/// This is the operation's OWN enforcement of the value set: a request whose `Status` the
/// model does not declare is refused by the validating walk over the input schema before
/// any handler runs, and this clause is what words the same refusal when the handler is
/// the one that reaches it — so neither wording can be the one that is sized by a request.
fn enum_violation(value: &str) -> CompleteRolloutError {
    let violation = ::aws_smithy_schema_server::Violation {
        path: "status".to_string(),
        kind: ::aws_smithy_schema_server::ViolationKind::EnumValue(
            COMPLETION_STATUS_SET.iter().map(|v| (*v).to_string()).collect(),
        ),
        value: Some(
            service_common::validation::quoted_echo_up_to(
                value,
                crate::service::LARGEST_QUOTED_VALUE_BYTES,
            )
            .into_owned(),
        ),
        sensitive: false,
    };
    let message = crate::service::refusal_message(std::slice::from_ref(&violation))
        .unwrap_or_else(|| violation.message());
    validation(message)
}

