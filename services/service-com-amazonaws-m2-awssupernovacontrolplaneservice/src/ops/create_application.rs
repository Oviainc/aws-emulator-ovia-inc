/// Whether a retried `CreateApplication` carries the same application as the one the
/// client token already created — the test an `@idempotencyToken` replay turns on.
fn same_application(
    stored: &Application,
    stored_tags: &HashMap<String, String>,
    input: &CreateApplicationInput,
    definition: &str,
) -> bool {
    let requested_tags = input.tags.clone().unwrap_or_default();
    stored.name == input.name
        && stored.engine_type == input.engine_type
        && stored.description == input.description
        && stored.kms_key_id == input.kms_key_id
        && stored.role_arn == input.role_arn
        && *stored_tags == requested_tags
        && stored
            .version(1)
            .is_some_and(|first| first.definition_content == definition)
}

