            let home_region = match &arn {
                crate::state::TaggableArn::Trail { region, .. }
                | crate::state::TaggableArn::Dashboard { region, .. }
                | crate::state::TaggableArn::EventDataStore { region, .. }
                | crate::state::TaggableArn::Channel { region, .. } => region,
            };
