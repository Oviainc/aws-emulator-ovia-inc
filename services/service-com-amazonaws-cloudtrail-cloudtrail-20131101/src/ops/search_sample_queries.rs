    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::SEARCH_SAMPLE_QUERIES_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::SEARCH_SAMPLE_QUERIES_OUTPUT_SCHEMA;
