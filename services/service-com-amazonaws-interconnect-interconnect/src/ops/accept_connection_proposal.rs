/// Judge everything the REQUEST ITSELF carries, before anything the request NAMES is
/// resolved.
///
/// An `activationKey` whose text is not the encoding the member is written in, a tag set
/// outside what this service stores, and a value outside the constraints the
/// model puts on the `AttachPoint` member that carries it, are faults in the INPUT
/// whatever the `activationKey` names — so judging them here is what keeps a verdict
/// about a resource (a key that resolves to no proposal, a proposal whose acceptance has
/// already been made, a connection an acceptance can no longer be made on) from masking
/// them, and a caller branching on the error code can tell "the key I pasted is not a
/// key at all", "I sent something that is not an attach-point identifier" or "I sent a
/// tag key I may not write" from "this proposal does not exist" or "this proposal was
/// already accepted". The same ordering both
/// sibling tag writers of this crate (`TagResource`, `UntagResource`) and the sibling
/// reader of this union (`ListConnections`) apply, through the same three rules
/// (`crate::state::activation_key_encoding_violation`,
/// `crate::state::tag_write_violation`, `crate::state::judge_attach_point_value`).
///
/// Nothing is written and nothing is resolved here, so a refused acceptance leaves the
/// proposal exactly as it was. What the acceptance would LEAVE on the connection — the
/// merged tag set — and the resource the attach point names are judged against the store
/// in [`judge_against_store`], once the proposal has been resolved.
fn judge_request(
    input: &AcceptConnectionProposalInput,
) -> Result<(), AcceptConnectionProposalError> {
    // The `activationKey`'s own well-formedness, by the one rule both operations that
    // take the member apply to it
    // (`crate::state::activation_key_encoding_violation`): the member carries the
    // partner portal's encoded capture of what a creation request chose, so text that is
    // not base64 carries no capture and could never name a proposal of any account.
    // Judged HERE, ahead of every resolution below, so the probe a client runs first
    // (`DescribeConnectionProposal`) and the acceptance that follows it answer the same
    // text identically; the key is `@sensitive`, so the refusal reproduces nothing of
    // it.
    if let Some(message) = crate::state::activation_key_encoding_violation(&input.activation_key) {
        return Err(
            AcceptConnectionProposalErrorModeled::InterconnectValidationException(
                InterconnectValidationException { message },
            )
            .into(),
        );
    }

    // The entries the request carries, each inside the lengths the model gives `TagKey`
    // and `TagValue` and none of them in the namespace AWS reserves for its own system
    // tags. (The boundary validator holds a LIST's members to their target's
    // constraints but not a MAP's keys, so a tag map is checked here.)
    if let Some(message) = input
        .tags
        .as_ref()
        .and_then(|tags| crate::state::tag_write_violation(None, tags))
    {
        return Err(
            AcceptConnectionProposalErrorModeled::InterconnectValidationException(
                InterconnectValidationException { message },
            )
            .into(),
        );
    }

    // The value the union carries, against its own member's modelled `@length` and
    // `@pattern`, which nothing before the handler holds it to: the constraint sits on a
    // union member one level down, and the boundary validator reaches only the top-level
    // member.
    crate::state::judge_attach_point_value::<AcceptConnectionProposalError>(&input.attach_point)
}

/// What this service's own store says about an `AcceptConnectionProposal` request.
enum StoreVerdict {
    /// The proposal the `activationKey` names has not been accepted yet: this is the
    /// connection the acceptance is made on, and the Environment it is placed upon,
    /// which is what an attach-point refusal is worded from.
    Accept {
        connection_id: String,
        environment_id: String,
    },
    /// The proposal has already been accepted and the request asks for exactly what
    /// the connection it made already holds, so that connection is reported again
    /// rather than accepted a second time. Boxed because a `Connection` is far larger
    /// than the two identifiers above.
    AlreadyAccepted(Box<Connection>),
}

/// Judge a request against everything this service's OWN store answers: the proposal
/// the `activationKey` resolves to, whether that proposal has already been accepted,
/// the tag set the acceptance would leave on it, and the `arn` attach point.
///
/// `region` is the Region the request addressed, which is the scope the proposal is
/// resolved in: a connection belongs to the Region it was created in, so neither an
/// activation key nor an attach-point ARN of another Region resolves here.
///
/// Called under the lock BOTH before the cross-service attach-point resolution and
/// again at the instant the acceptance is applied, so a verdict is never acted on
/// from a store that has since moved: check and write happen under one lock.
fn judge_against_store(
    store: &crate::state::ComAmazonawsInterconnectInterconnectState,
    input: &AcceptConnectionProposalInput,
    region: &str,
) -> Result<StoreVerdict, AcceptConnectionProposalError> {
    // The `activationKey` is the proposal's only handle. The store's
    // `activationKey` -> connection-id index resolves it, and the connection it names
    // is then resolved in the Region the request was signed for, so a key minted
    // through another Region's endpoint resolves to nothing here. A key that resolves
    // to no proposal is the modelled 404, worded without the key itself, which
    // `ActivationKey` marks `@sensitive`. Unlike the proposal READ
    // (`crate::state::proposal_in`), which serves nothing once a `DeleteConnection`
    // has been made on the connection, the record is resolved here whatever state it
    // is in: the state is what refuses the acceptance below, and the refusal reports
    // it.
    let stored = store
        .activation_keys
        .get(&input.activation_key)
        .and_then(|connection_id| store.connection_in(region, connection_id));
    let Some(stored) = stored else {
        return Err(
            AcceptConnectionProposalErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(crate::state::proposal_not_retrievable_message()),
                },
            )
            .into(),
        );
    };
    let connection = &stored.connection;

    // The tag set the accepted connection would be LEFT holding, judged once the
    // proposal is resolved by the one rule every writer of a connection's tags uses:
    // each entry inside the lengths the model gives `TagKey` and `TagValue`, no key in
    // the namespace AWS reserves for its own system tags, and no more entries than a
    // resource holds once the write is merged. What the REQUEST itself carries was
    // judged ahead of the lookup above ([`judge_request`]), so the entry-count bound on
    // the merged set is what this adds. Judged BEFORE anything is written, so a refused
    // acceptance leaves the proposal exactly as it was.
    if let Some(message) = input
        .tags
        .as_ref()
        .and_then(|tags| crate::state::tag_write_violation(connection.tags.as_ref(), tags))
    {
        return Err(
            AcceptConnectionProposalErrorModeled::InterconnectValidationException(
                InterconnectValidationException { message },
            )
            .into(),
        );
    }

    // An acceptance is made on a connection that still EXISTS: one being deleted,
    // deleted or failed has no connectivity an acceptance could bring up, so there is
    // nothing left to accept on it at all
    // (`crate::state::acceptance_possible_in`). Every other state is a connection an
    // acceptance can still be made on — including the states the clock carries a new
    // connection into on its own, because the clock stands in for the time
    // provisioning takes and accepts nothing.
    if !crate::state::acceptance_possible_in(&connection.state) {
        return Err(
            AcceptConnectionProposalErrorModeled::InterconnectClientException(
                InterconnectClientException {
                    message: crate::state::proposal_not_acceptable_message(
                        &connection.id,
                        &connection.state,
                    ),
                },
            )
            .into(),
        );
    }

    // A proposal is accepted ONCE, and what records that it HAS been is the
    // acceptance itself (`StoredConnection::proposal_accepted`), never the state the
    // connection reports: the clock carries a connection out of the state it was
    // created in whether or not anybody has accepted it, so judging the acceptance by
    // the state would refuse the very call the model says selects the attach point.
    // Once the acceptance HAS been made, a request asking for exactly what that
    // connection already holds is the SAME acceptance reported again — the operation
    // is `@idempotent` — while one asking for anything else would re-associate a
    // connection whose attach point that acceptance already settled, which is this
    // service's own client fault.
    if stored.proposal_accepted {
        if crate::state::acceptance_already_applied(
            connection,
            &input.attach_point,
            input.description.as_ref(),
            input.tags.as_ref(),
        ) {
            return Ok(StoreVerdict::AlreadyAccepted(Box::new(connection.clone())));
        }
        return Err(
            AcceptConnectionProposalErrorModeled::InterconnectClientException(
                InterconnectClientException {
                    message: crate::state::proposal_already_accepted_message(&connection.id),
                },
            )
            .into(),
        );
    }

    // The attach point the acceptance selected, judged by the one rule both writers of
    // a connection's attach point apply to it
    // (`crate::state::judge_attach_point_in_store`): first the value against the union
    // member's OWN modelled length and pattern, which nothing before the handler holds
    // it to, so a value that is not an identifier of its kind is refused as invalid
    // INPUT rather than resolved and then reported as a resource the account does not
    // hold; then, for `AttachPoint$arn` — which "identifies an attach point by full
    // ARN", and whose pattern is an Interconnect CONNECTION ARN — the connection it
    // names, resolved in full, so one whose Region or account is not the stored one
    // names no resource this account holds, inside the scope the request addressed, so
    // a connection created through another Region's endpoint is one this endpoint holds
    // nothing for, and with the connectivity behind it actually there, so a connection
    // that is not fully provisioned — one still being brought up as much as one whose
    // teardown has been called — is no longer an attach point. An ARN that
    // resolves to nothing has no attach point behind it, so there is nothing to make
    // the connection onto. The same rule the create path applies, so what a Connection
    // may be attached to does not depend on how it came to exist.
    crate::state::judge_attach_point_in_store::<AcceptConnectionProposalError>(
        store,
        region,
        &input.attach_point,
        &connection.environment_id,
    )?;

    Ok(StoreVerdict::Accept {
        connection_id: connection.id.clone(),
        environment_id: connection.environment_id.clone(),
    })
}

