            return Err(ContinueDeploymentErrorModeled::InvalidDeploymentIdException(
                InvalidDeploymentIdException {
                    message: Some(crate::state::malformed_deployment_id_message(
                        &deployment_id,
                    )),
                },
            )
            .into());
