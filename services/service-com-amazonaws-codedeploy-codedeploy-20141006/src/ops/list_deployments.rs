/// The request's `createTimeRange` as a pair of epoch-millisecond bounds.
///
/// A bound that cannot be read as an instant, and a start after its end, both
/// describe no span of time, which is what `InvalidTimeRangeException` states —
/// reported rather than silently turned into a filter that matches nothing.
fn creation_window(
    range: Option<&TimeRange>,
) -> Result<(Option<i64>, Option<i64>), ListDeploymentsError> {
    let refuse = |detail: &str| -> ListDeploymentsError {
        ListDeploymentsErrorModeled::InvalidTimeRangeException(InvalidTimeRangeException {
            message: Some(format!("The specified time range was invalid: {detail}")),
        })
        .into()
    };
    let Some(range) = range else {
        return Ok((None, None));
    };
    let bound = |value: &Option<::aws_smithy_types::DateTime>| match value {
        Some(value) => crate::state::timestamp_millis(value)
            .map(Some)
            .ok_or_else(|| refuse("a bound is not a usable instant")),
        None => Ok(None),
    };
    let start = bound(&range.start)?;
    let end = bound(&range.end)?;
    if let (Some(start), Some(end)) = (start, end) {
        if start > end {
            return Err(refuse("the start time is after the end time"));
        }
    }
    Ok((start, end))
}
