impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for StopExecution<Eng>
{
    type Input = StopExecutionInput;
    type Output = StopExecutionOutput;
    type Error = StopExecutionError;

    const NAME: &'static str = "StopExecution";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::STOP_EXECUTION_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::STOP_EXECUTION_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::STORE_UNAVAILABLE,
            ));
        };

        // The ARN is validated BEFORE the lookup: a malformed ARN, an ARN of another
        // service and an ARN of another region are defects in the REQUEST, which
        // `InvalidArn` reports, not an execution that is absent here.
        let endpoint_region = crate::state::request_region(ctx.parts());
        if let Err(message) =
            crate::state::read_execution_arn(&input.execution_arn, &endpoint_region)
        {
            return Err(StopExecutionErrorModeled::InvalidArn(InvalidArn {
                message: Some(message),
            })
            .into());
        }

        let now = crate::state::now();
        // "For an execution with encryption enabled, Step Functions will encrypt the
        // error and cause fields using the KMS key for the execution role", and "a
        // caller can stop an execution without using any KMS permissions in the
        // execution role if the caller provides a null value for both error and cause
        // fields because no data needs to be encrypted": a stop that carries either
        // field has that field SEALED under the execution's customer managed key, so
        // KMS decides whether this caller may have the key used for it before the
        // execution is stopped. The decision is made with no store of this service
        // locked.
        if input.error.is_some() || input.cause.is_some() {
            if let Some(refusal) = crate::state::encryption::execution_write_denied(
                &*self.engine,
                ctx,
                &endpoint_region,
                &input.execution_arn,
            ) {
                return Err(crate::kms_key_refusal!(StopExecutionErrorModeled, refusal).into());
            }
        }
        // The store is held for THIS block alone: the stop itself is one state-level
        // step, and the cross-service call below must not hold the store while it is
        // in flight.
        let stopped = {
            let mut store = state.lock();
            // Settle first, so an execution whose own terminal status the clock already
            // owed is not reported as stopped by this call.
            store.settle(now);

            let express = store
                .executions
                .get(&input.execution_arn)
                .and_then(|execution| store.state_machines.get(&execution.state_machine_arn))
                .is_some_and(|machine| machine.sm_type == crate::state::STATE_MACHINE_TYPE_EXPRESS);
            // "This API action is not supported by EXPRESS state machines": the ARN
            // names an execution this action is not for, which is a defect in the
            // REQUEST rather than an execution that is absent or a combination of
            // members that cannot hold together — so it is the ARN error every
            // execution reader of this service refuses an ARN it does not serve with
            // (`crate::state::read_execution_arn` answers the same `InvalidArn` for
            // the `express` resource type a synchronous Express execution ARN
            // carries), worded through the one ARN envelope.
            if express {
                return Err(StopExecutionErrorModeled::InvalidArn(InvalidArn {
                    message: Some(crate::state::invalid_arn_message(format!(
                        "StopExecution is not supported by {} state machines: {}",
                        crate::state::STATE_MACHINE_TYPE_EXPRESS, input.execution_arn
                    ))),
                })
                .into());
            }

            // One state-level step does the whole stop: it moves a running execution
            // to ABORTED with the caller's error and cause, discards the outcome the
            // interpreter had computed along with its place in the settle queue, and
            // reports the `stopDate` the execution carries — its own when it had
            // already reached a terminal status. It also hands back the job a
            // run-a-job (`.sync`) task of this execution had started, which is work of
            // ANOTHER service and so is stopped below rather than in the store.
            match store.stop_execution(&input.execution_arn, now, input.error, input.cause) {
                Some(stopped) => stopped,
                None => {
                    return Err(StopExecutionErrorModeled::ExecutionDoesNotExist(
                        ExecutionDoesNotExist {
                            message: Some(crate::state::resource_error_message(
                                crate::state::EXECUTION_DOES_NOT_EXIST,
                                &input.execution_arn,
                            )),
                        },
                    )
                    .into())
                }
            }
        };

        // "Stops an execution": an execution parked inside a run-a-job task is
        // running the job that task started, so stopping the execution stops that
        // job too — through the stopping call its own integration names, in the
        // Region the starting call was made in. The abort therefore crosses the
        // service boundary exactly as the start did, and the job is not left running
        // behind an execution nothing will resume. What that service answers changes
        // nothing here: this execution is already ABORTED, and the stop it reports is
        // the stop of the execution.
        if let Some(parked) = stopped.parked {
            let (call, request) = crate::state::integration::stopping(
                parked.api,
                parked.job,
                &parked.job_id,
                &parked.naming,
            );
            let _answered = crate::state::integration::call_api(
                ctx.callback(),
                &parked.region,
                &call,
                &request,
            )
            .await;
        }

        // What the stop published about this execution: the series an aborted
        // execution is counted in, and the history events its logging configuration
        // delivers. The store guard was released with the block above.
        crate::state::observability::publish(&*self.engine);

        Ok(StopExecutionOutput {
            stop_date: crate::state::to_date_time(stopped.stop_date),
        })
    }
}
