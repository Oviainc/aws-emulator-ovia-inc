/// One record as it is stored: `CommonAttributes` merged in and the modelled defaults
/// applied.
///
/// A value the record itself declares wins over the common one; a value it omits is
/// taken from `CommonAttributes`; the dimension list is the union of the two, common
/// dimensions first. `MeasureValueType`, `TimeUnit` and `Version` then fall back to the
/// defaults the model documents.
fn merge_common_attributes(
    record: &Record,
    common: Option<&Record>,
) -> crate::state::StoredRecord {
    let from_common = |pick: &dyn Fn(&Record) -> Option<String>| -> Option<String> {
        pick(record).or_else(|| common.and_then(pick))
    };

    let mut dimensions: Vec<Dimension> = common
        .and_then(|c| c.dimensions.clone())
        .unwrap_or_default();
    dimensions.extend(record.dimensions.clone().unwrap_or_default());

    let measure_values = record
        .measure_values
        .clone()
        .or_else(|| common.and_then(|c| c.measure_values.clone()))
        .unwrap_or_default();

    crate::state::StoredRecord {
        dimensions,
        measure_name: from_common(&|r| r.measure_name.clone()),
        measure_value: from_common(&|r| r.measure_value.clone()),
        measure_value_type: from_common(&|r| r.measure_value_type.clone())
            .unwrap_or_else(|| crate::state::DEFAULT_MEASURE_VALUE_TYPE.to_string()),
        measure_values,
        time: from_common(&|r| r.time.clone()),
        time_unit: from_common(&|r| r.time_unit.clone())
            .unwrap_or_else(|| crate::state::DEFAULT_TIME_UNIT.to_string()),
        version: record
            .version
            .or_else(|| common.and_then(|c| c.version))
            .unwrap_or(crate::state::DEFAULT_RECORD_VERSION),
        ingested_at: ::std::time::SystemTime::now(),
    }
}
