        // cannot express a cross-member rule, so it is checked here — before the
        // tunnel is resolved, because the request is unanswerable whatever the
        // store holds, and so nothing is mutated.
        if input.destination_config.is_some() && !rotate_destination {
            return Err(crate::scaffolded::Scaffolded::validation(format!(
                "DestinationConfig is not allowed with clientMode {}",
                input.client_mode
            )));
        }

        // A tunnel carries at most `MAX_SERVICES_PER_TUNNEL` service names,
        // whichever call writes the field, so an oversized list is refused here
        // — before the tunnel is resolved, so a refused rotate mints no token
        // and leaves the stored record exactly as it was.
        let destination_config = input
            .destination_config
            .as_ref()
            .map(|config| crate::state::stored_destination_config("destinationConfig", config))
            .transpose()
            .map_err(crate::scaffolded::Scaffolded::validation)?;

        // Tokens are rotated through the endpoint of the tunnel's own Region and
        // no other: a tunnel of another Region is not a resource this one holds.
        let region = crate::state::request_region(ctx);
        // The instant this call reasons with is the instant at which it holds the
        // store, so a tunnel whose lifetime ran out while this request waited for
        // the lock is already closed by the clock here — and is refused below
        // instead of being handed fresh tokens.
        let (mut store, now) = crate::state::lock_and_settle(&state);

        let Some(tunnel) = store.tunnel_mut(&region, &input.tunnel_id) else {
            return Err(RotateTunnelAccessTokenErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(crate::state::tunnel_not_found_message(&input.tunnel_id)),
                },
            )
            .into());
        };

        // Credentials are only reissued for a tunnel that is still live: a closed
        // tunnel can never be connected to, so AWS refuses to mint a client access
        // token for one. The record is still describable, so this is the
        // request-time `ValidationException` refusal and NOT the modelled
        // not-found error, which says the endpoint holds no such tunnel; the check
        // runs before any token is minted or stored, so a refused call leaves the
        // record exactly as it was.
