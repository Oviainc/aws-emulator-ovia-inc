impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for OpenTunnel<Eng>
{
    type Input = OpenTunnelInput;
    type Output = OpenTunnelOutput;
    type Error = OpenTunnelError;

    const NAME: &'static str = "OpenTunnel";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::OPEN_TUNNEL_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::OPEN_TUNNEL_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // The shared store. `None` means this service was mounted on an engine it
        // cannot reach, so the operation cannot be served at all — never a fresh
        // engine, whose writes would be dropped when this request returns.
        let state = crate::state::service_state(&*self.engine)
            .ok_or_else(|| crate::scaffolded::Scaffolded::not_implemented("OpenTunnel"))?;

        let region = crate::state::request_region(ctx);

        // An absent `timeoutConfig`, or an absent member within it, takes the
        // modelled default of 720 minutes.
        let max_lifetime_timeout_minutes = input
            .timeout_config
            .as_ref()
            .and_then(|config| config.max_lifetime_timeout_minutes)
            .unwrap_or(crate::state::DEFAULT_MAX_LIFETIME_TIMEOUT_MINUTES);

        // A tunnel carries at most `MAX_SERVICES_PER_TUNNEL` service names, the
        // rule shared with the other writer of this field, so a longer list is
        // refused here — before anything is minted, stored or handed out —
        // rather than persisted as a tunnel the service could never run.
        let destination_config = input
            .destination_config
            .as_ref()
            .map(|config| crate::state::stored_destination_config("destinationConfig", config))
            .transpose()
            .map_err(crate::scaffolded::Scaffolded::validation)?;

        // A tunnel whose lifetime has run out is CLOSED as of the instant the
        // transition came due, whether or not anybody called, so its slot is
        // already free before this open is counted against the quota. The instant
        // this call reasons with — the one its own expiry is computed from below —
        // comes from inside the critical section, so it is the instant at which
        // this call holds the store and not an earlier one it sampled while
        // waiting for the lock.
        let (mut store, now) = crate::state::lock_and_settle(&state);

        // The quota is on the tunnels this account holds OPEN in this Region
        // (`MAX_CONCURRENT_TUNNELS`), which is what the modelled
        // `LimitExceededException` ("Thrown when a tunnel limit is exceeded")
        // exists to report: a closed tunnel holds no slot, so closing
        // one — with or without `delete` — makes room for this open. Refused
        // before anything is minted, so a refused open neither stores a record
        // nor hands out a token.
        let open_tunnels = store.open_tunnel_count(&region);
        if open_tunnels >= crate::state::MAX_CONCURRENT_TUNNELS {
            return Err(OpenTunnelErrorModeled::LimitExceededException(
                LimitExceededException {
                    message: Some(crate::state::tunnel_limit_message(open_tunnels)),
                },
            )
            .into());
        }

        // A tag key in the reserved `aws:` namespace is AWS's own to set, so a
        // caller-supplied one is refused wherever tags enter this service —
        // here as well as in `TagResource`, in the same words, and before
        // anything is minted or stored.
        if let Some(key) = input.tags.as_deref().and_then(|tags| {
            crate::state::first_reserved_tag_key(tags.iter().map(|tag| tag.key.as_str()))
        }) {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::reserved_tag_key_message("tags", key),
            ));
        }

        // The tunnel's identity, computed before the tag check below so that
        // check can ask the store how many distinct keys this resource would end
        // up carrying. Minting an id and formatting an ARN store nothing, so a
        // request refused below still writes no record and hands out no token.
        let tunnel_id = crate::state::mint_tunnel_id();
        let tunnel_arn = crate::state::tunnel_arn(&region, &tunnel_id);

        // A tunnel carries at most `MAX_TAGS_PER_TUNNEL` tags, and the two tagging
        // entry points agree because both apply the rule through the one state
        // helper `state::tag_limit_refusal`: refused here as well as in
        // `TagResource`, at the same count and in the same words, before
        // anything is stored. The modelled `TagList` length bounds one request's
        // list; this bounds what one tunnel accumulates, and an exhausted limit
        // is reported with the same modelled `LimitExceededException`
        // as the tunnel count above, which this handler wraps the message in.
        if let Some(message) =
            store.tag_limit_refusal(&tunnel_arn, input.tags.as_deref().unwrap_or(&[]))
        {
            return Err(OpenTunnelErrorModeled::LimitExceededException(
                LimitExceededException {
                    message: Some(message),
                },
            )
            .into());
        }

        // The instant this tunnel's lifetime runs out. Computed with checked
        // arithmetic: `SystemTime`'s `+` PANICS on an instant it cannot
        // represent, and the summand comes from the request, so the sum is
        // refused rather than taken on an addition that cannot be represented.
        let Some(expires_at) =
            now.checked_add(crate::state::max_lifetime(max_lifetime_timeout_minutes))
        else {
            return Err(crate::scaffolded::Scaffolded::validation(
                crate::state::unrepresentable_expiry_message(
                    "timeoutConfig.maxLifetimeTimeoutMinutes",
                    max_lifetime_timeout_minutes,
                ),
            ));
        };

        // The store keeps at most `MAX_RETAINED_TUNNELS` records across every
        // Region — the Region a record belongs to comes from the request, so the
        // bound is on the store and not on one Region's share of it — and this
        // is the one site the store grows at, so the bound is applied here,
        // under the same lock the insert below holds: the records closed longest
        // ago are evicted to make room, and when every record is open, so
        // nothing can be evicted, there is no room for this tunnel and the
        // request is refused with the same modelled error rather than stored.
        // An open tunnel is never evicted. Last of the refusals, so a request
        // the checks above turn away reclaims nothing either.
        if !store.make_room_for_tunnel() {
            return Err(OpenTunnelErrorModeled::LimitExceededException(
                LimitExceededException {
                    message: Some(crate::state::tunnel_record_limit_message()),
                },
            )
            .into());
        }

        // Two independently minted tokens: the source and destination proxies each
        // authenticate with their own.
        let source_access_token = crate::state::mint_access_token();
        let destination_access_token = crate::state::mint_access_token();

        let creation_seq = store.next_creation_seq();
        let tunnel = crate::state::StoredTunnel {
            tunnel_id: tunnel_id.clone(),
            tunnel_arn: tunnel_arn.clone(),
            status: crate::state::TunnelStatus::Open,
            description: input.description.clone(),
            destination_config,
            max_lifetime_timeout_minutes,
            // No local proxy has connected at either end yet.
            source_connection_state: crate::state::StoredConnectionState::disconnected(now),
            destination_connection_state: crate::state::StoredConnectionState::disconnected(now),
            source_access_token: source_access_token.clone(),
            destination_access_token: destination_access_token.clone(),
            created_at: now,
            last_updated_at: now,
            // The tunnel is OPEN, so there is no close instant to record yet;
            // the close transition writes it.
            closed_at: None,
            expires_at,
            creation_seq,
        };

        // Tags supplied at open time go into the one authoritative tag store, so
        // `ListTagsForResource` and `DescribeTunnel` report exactly what was set here.
        // The "did this change the set" answer is of no use on this path: the record
        // below is new and already carries `last_updated_at: now`, so there is no
        // earlier stamp for these tags to update.
        store.put_tags(&tunnel_arn, input.tags.as_deref().unwrap_or(&[]));
        // The record is a resource of the Region whose endpoint opened it, so it
        // is stored under that Region and is reachable through no other.
        store.insert_tunnel(&region, tunnel);
        // Tell the expiry sweep when this tunnel's lifetime runs out, so it can
        // skip the store entirely until something is due.
        store.note_open_expiry(expires_at);
        drop(store);

        Ok(OpenTunnelOutput {
            tunnel_id: Some(tunnel_id),
            tunnel_arn: Some(tunnel_arn),
            source_access_token: Some(source_access_token),
            destination_access_token: Some(destination_access_token),
        })
    }
}
