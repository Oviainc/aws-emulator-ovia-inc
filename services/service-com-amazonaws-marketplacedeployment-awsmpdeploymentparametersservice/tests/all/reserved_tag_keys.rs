//! The tag-key namespace AWS owns.
//!
//! The rule under test: a request that would create, change or remove a tag key
//! inside the namespace AWS reserves for its own generated tags (keys beginning
//! `aws:`) is refused as invalid input — HTTP 400 `ValidationException`, naming the
//! member that carried the key — and the stored tag map is left exactly as it was.
//! The reservation is a NAMESPACE rule, not a character-class one: the modelled
//! `TagKey` `@pattern` (`^[a-zA-Z0-9/_+=.:@-]+$`,
//! `smithy_query(query="shape",shape="TagKey")`) admits `:`, so such a key passes
//! the modelled constraint walk and only this judgement can refuse it. Equally, it
//! is a PREFIX rule on the key as written, so a key that merely resembles the
//! prefix — `aws` with no colon, a different case, `aws:` somewhere other than the
//! start — is a key of the caller's own and must round-trip.
//!
//! It holds for every input of this service that names tag keys:
//! `PutDeploymentParameter$tags` (on the create path and on the update path, where
//! the member documents that `tags` is ignored), `TagResource$tags` and
//! `UntagResource$tagKeys`.
//!
//! Every case drives the real wire path through the harness the
//! `deployment_parameters` suite owns.

use std::collections::BTreeMap;

use serde_json::{json, Value};
use service_com_amazonaws_marketplacedeployment_awsmpdeploymentparametersservice::state::{
    RESERVED_TAG_KEY_PREFIX, TAG_KEY_MAX_LEN,
};

use crate::deployment_parameters::{
    emulator, error_code, field_name, list_tags, message, provision, put, tag, tag_map, tags_of,
    untag, CATALOG,
};

/// Tag keys inside the reserved namespace, spanning what the rule generalises
/// over: the prefix alone, the AWS-generated keys real accounts carry, a key using
/// every other character the modelled `TagKey` pattern admits, and a key at the
/// modelled `TagKey` maximum length. Each one satisfies `TagKey`'s own
/// `length 1..128` and `@pattern`, so a refusal can only come from the namespace
/// rule. None is the key the report cited except the first.
fn reserved_keys() -> Vec<(&'static str, String)> {
    vec![
        (
            "a service-generated key",
            "aws:cloudformation:stack-name".to_string(),
        ),
        (
            "a key generated by the service this parameter materialises into",
            "aws:secretsmanager:owning-service".to_string(),
        ),
        ("the reserved prefix alone", "aws:".to_string()),
        (
            "the prefix followed by every other character the pattern admits",
            "aws:a0/_+=.:@-".to_string(),
        ),
        (
            "a reserved key at the modelled TagKey maximum",
            format!(
                "{RESERVED_TAG_KEY_PREFIX}{}",
                "k".repeat(TAG_KEY_MAX_LEN - RESERVED_TAG_KEY_PREFIX.len())
            ),
        ),
    ]
}

/// Tag keys OUTSIDE the reserved namespace that resemble it, so the rule is a
/// prefix test on the key as written and not a substring or case-folded one.
fn unreserved_lookalikes() -> Vec<(&'static str, String)> {
    vec![
        ("the prefix without its colon", "aws".to_string()),
        ("the prefix as a word prefix", "awsome".to_string()),
        ("the prefix with another separator", "aws/region".to_string()),
        (
            "the prefix in another case (tag keys are case-sensitive)",
            "AWS:region".to_string(),
        ),
        ("the prefix not at the start", "notaws:region".to_string()),
        ("the prefix inside the key", "env:aws:region".to_string()),
    ]
}

/// A `PutDeploymentParameter` body for `name` under `agreement_id`, carrying
/// `tags` — built as a map rather than a literal, so a row's key can be any
/// string.
fn put_body(
    agreement_id: &str,
    name: &str,
    secret: &str,
    tags: &BTreeMap<String, String>,
) -> Value {
    json!({
        "agreementId": agreement_id,
        "deploymentParameter": { "name": name, "secretString": secret },
        "tags": tags
            .iter()
            .map(|(key, value)| (key.clone(), json!(value)))
            .collect::<serde_json::Map<String, Value>>(),
    })
}

/// Assert `answer` is the modelled refusal for `key` on member `field`.
fn assert_reserved_refusal(case: &str, status: u16, answer: &Value, key: &str, field: &str) {
    assert_eq!(
        status, 400,
        "case {case:?} (key {key:?}): expected a 400 refusal, got {status} {answer:?}"
    );
    assert_eq!(
        error_code(answer),
        "ValidationException",
        "case {case:?} (key {key:?}): expected ValidationException, got {answer:?}"
    );
    assert_eq!(
        field_name(answer),
        field,
        "case {case:?} (key {key:?}): expected fieldName {field:?}, got {answer:?}"
    );
    let stated = message(answer);
    assert!(
        stated.contains(key),
        "case {case:?}: the refusal must name the key it refused, got {stated:?}"
    );
}

#[tokio::test]
async fn a_put_naming_a_reserved_tag_key_is_refused_and_creates_nothing() {
    let (router, engine) = emulator();
    provision(&engine, CATALOG, "agmt-reserved", &["prod-reserved"]);

    for (index, (case, key)) in reserved_keys().into_iter().enumerate() {
        // A fresh identity per row, so what the row proves about storage is about
        // its own create and nothing else.
        let name = format!("Reserved{index}");
        let mut carried = tag_map(&[("env", "dev")]);
        carried.insert(key.clone(), "mystack".to_string());
        let (status, answer) = put(
            &router,
            CATALOG,
            "prod-reserved",
            &put_body("agmt-reserved", &name, "s", &carried),
        )
        .await;
        assert_reserved_refusal(case, status, &answer, &key, "tags");

        // Nothing was created: the identity is still free, so the next Put for it
        // is a CREATE and its `tags` are applied (an update would ignore them and
        // report whatever the refused call had left behind).
        let (status, created) = put(
            &router,
            CATALOG,
            "prod-reserved",
            &put_body("agmt-reserved", &name, "s", &tag_map(&[("env", "prod")])),
        )
        .await;
        assert_eq!(
            status, 200,
            "case {case:?}: the following legal create must succeed, got {status} {created:?}"
        );
        assert_eq!(
            tags_of(&created),
            tag_map(&[("env", "prod")]),
            "case {case:?}: the refused create must have stored nothing, got {created:?}"
        );
        let arn = created
            .get("resourceArn")
            .and_then(Value::as_str)
            .expect("a minted resourceArn")
            .to_string();
        let (_, listed) = list_tags(&router, &arn).await;
        assert_eq!(
            tags_of(&listed),
            tag_map(&[("env", "prod")]),
            "case {case:?}: no reserved key may be listed, got {listed:?}"
        );
    }
}

#[tokio::test]
async fn a_tag_or_untag_naming_a_reserved_tag_key_is_refused_and_changes_nothing() {
    let (router, engine) = emulator();
    provision(&engine, CATALOG, "agmt-tagged", &["prod-tagged"]);

    let (status, created) = put(
        &router,
        CATALOG,
        "prod-tagged",
        &json!({
            "agreementId": "agmt-tagged",
            "deploymentParameter": { "name": "Tagged", "secretString": "s" },
            "tags": { "env": "dev" },
        }),
    )
    .await;
    assert_eq!(status, 200, "the setup Put must succeed, got {created:?}");
    let arn = created
        .get("resourceArn")
        .and_then(Value::as_str)
        .expect("a minted resourceArn")
        .to_string();
    let expected = tag_map(&[("env", "dev")]);

    for (case, key) in reserved_keys() {
        // TagResource: a reserved key may not be created or changed.
        let mut tags = tag_map(&[("team", "payments")]);
        tags.insert(key.clone(), "mystack".to_string());
        let (status, answer) = tag(&router, &arn, &tags).await;
        assert_reserved_refusal(case, status, &answer, &key, "tags");

        // UntagResource: nor removed — the reservation covers removal too.
        let (status, answer) = untag(&router, &arn, &[key.clone(), "env".to_string()]).await;
        assert_reserved_refusal(case, status, &answer, &key, "tagKeys");

        // PutDeploymentParameter on the UPDATE path: the member documents that
        // `tags` is ignored once the resource exists, and the key is still refused
        // as input rather than quietly dropped.
        let only_reserved: BTreeMap<String, String> =
            [(key.clone(), "mystack".to_string())].into_iter().collect();
        let (status, answer) = put(
            &router,
            CATALOG,
            "prod-tagged",
            &put_body("agmt-tagged", "Tagged", "s2", &only_reserved),
        )
        .await;
        assert_reserved_refusal(case, status, &answer, &key, "tags");

        let (status, listed) = list_tags(&router, &arn).await;
        assert_eq!(
            status, 200,
            "case {case:?}: ListTagsForResource must succeed, got {status} {listed:?}"
        );
        assert_eq!(
            tags_of(&listed),
            expected,
            "case {case:?}: a refused tag write or removal must change nothing, got {listed:?}"
        );
    }
}

#[tokio::test]
async fn a_key_that_only_resembles_the_reserved_prefix_round_trips() {
    let (router, engine) = emulator();
    provision(&engine, CATALOG, "agmt-lookalike", &["prod-lookalike"]);

    let (status, created) = put(
        &router,
        CATALOG,
        "prod-lookalike",
        &json!({
            "agreementId": "agmt-lookalike",
            "deploymentParameter": { "name": "Lookalike", "secretString": "s" },
            "tags": { "aws": "no-colon" },
        }),
    )
    .await;
    assert_eq!(
        status, 200,
        "a create carrying an unreserved lookalike key must succeed, got {status} {created:?}"
    );
    assert_eq!(
        tags_of(&created),
        tag_map(&[("aws", "no-colon")]),
        "the create must report the key it stored, got {created:?}"
    );
    let arn = created
        .get("resourceArn")
        .and_then(Value::as_str)
        .expect("a minted resourceArn")
        .to_string();

    let mut expected: BTreeMap<String, String> = tag_map(&[("aws", "no-colon")]);
    for (case, key) in unreserved_lookalikes() {
        let writes: BTreeMap<String, String> =
            [(key.clone(), "value-1".to_string())].into_iter().collect();
        let (status, answer) = tag(&router, &arn, &writes).await;
        assert_eq!(
            status, 204,
            "case {case:?} (key {key:?}): an unreserved key must be accepted, got {status} {answer:?}"
        );
        expected.insert(key.clone(), "value-1".to_string());
        let (_, listed) = list_tags(&router, &arn).await;
        assert_eq!(
            tags_of(&listed),
            expected,
            "case {case:?} (key {key:?}): the stored map must carry it, got {listed:?}"
        );

        // And it can be removed again: only the reserved namespace is protected.
        let (status, answer) = untag(&router, &arn, std::slice::from_ref(&key)).await;
        assert_eq!(
            status, 204,
            "case {case:?} (key {key:?}): an unreserved key must be removable, got {status} {answer:?}"
        );
        expected.remove(&key);
        let (_, listed) = list_tags(&router, &arn).await;
        assert_eq!(
            tags_of(&listed),
            expected,
            "case {case:?} (key {key:?}): the removal must take effect, got {listed:?}"
        );
    }
}
