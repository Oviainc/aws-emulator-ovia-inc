impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for Rescore<Eng>
{
    type Input = RescoreInput;
    type Output = RescoreOutput;
    type Error = RescoreError;

    const NAME: &'static str = "Rescore";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::RESCORE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::RESCORE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `RescoreExecutionPlanId`'s length and pattern, `SearchQuery`'s length, a
        // non-empty `Documents` list and each document's required `Id` / in-range
        // `OriginalScore` are modelled, so a request violating one of THOSE is already
        // refused with a 400 `ValidationException` before this handler runs. The model
        // puts no UPPER bound on `Documents`, so that one is enforced below.
        let region = crate::state::request_region(ctx.parts());
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(RescoreErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some(
                        "the rescore execution plan store is unavailable on this engine".to_string(),
                    ),
                },
            )
            .into());
        };

        // `Documents` is modelled with a minimum of 1 and NO maximum, so the batch size
        // is caller-chosen: refuse a batch past this emulator's ceiling with the modelled
        // 400 before any scoring runs, so one request cannot multiply work without bound.
        if input.documents.len() > crate::state::MAX_DOCUMENTS_PER_RESCORE {
            return Err(RescoreErrorModeled::ValidationException(ValidationException {
                message: Some(crate::state::constraint_report(
                    DOCUMENTS_MEMBER,
                    ::smithy_server_runtime::ViolationKind::MaxLength(
                        crate::state::MAX_DOCUMENTS_PER_RESCORE as i64,
                    ),
                )),
            })
            .into());
        }

        // Two rules on each submitted document, both documented on `Document`'s
        // members and neither expressible in the model, so both are refused here with
        // the modelled `ValidationException`:
        //
        // * the document's body text must be there, in exactly ONE of its two forms
        //   ("You must choose to provide Body or TokenizedBody. You cannot provide
        //   both." — `Document$TokenizedBody`);
        // * its title, which is optional, may be given in at most one form ("You must
        //   choose to provide Title or TokenizedTitle. You cannot provide both." —
        //   `Document$TokenizedTitle`).
        //
        // The REQUIREMENT on the body is evaluated before the title's exclusivity, so a
        // document failing both is told what it is MISSING rather than what it
        // duplicates: a caller that dropped the duplicate title would otherwise be
        // refused a second time for the defect it was never told about. The documents
        // are walked in request order, and the first document that fails a rule is the
        // one reported.
        //
        // All three refusals are worded under the ONE policy this crate states for a
        // refusal of a handler-enforced constraint (see `crate::state`): the sentence
        // names where the offending value was and what it had to satisfy, and renders
        // nothing of the caller's values — here the model member names of the pair the
        // document had to choose between, never the document's own `Id`.
        for document in &input.documents {
            if document.body.is_none() && document.tokenized_body.is_none() {
                return Err(RescoreErrorModeled::ValidationException(ValidationException {
                    message: Some(crate::state::DOCUMENT_BODY_REQUIRED_MESSAGE.to_string()),
                })
                .into());
            }
            if document.body.is_some() && document.tokenized_body.is_some() {
                return Err(RescoreErrorModeled::ValidationException(
                    crate::state::document_member_choice(BODY_MEMBER, TOKENIZED_BODY_MEMBER),
                )
                .into());
            }
            if document.title.is_some() && document.tokenized_title.is_some() {
                return Err(RescoreErrorModeled::ValidationException(
                    crate::state::document_member_choice(TITLE_MEMBER, TOKENIZED_TITLE_MEMBER),
                )
                .into());
            }
        }

        // The store is consulted only to answer whether the plan exists, whether it is
        // ready to serve, and to mint this ranking's identifier; the guard is dropped
        // before any caller-sized scoring, so one request's batch never runs under the
        // shared-state lock.
        enum PlanState {
            Missing,
            NotActive,
            Ready(String),
        }
        let plan_state = {
            let mut store = state.lock();
            let now = crate::state::now_millis();
            // A teardown the clock has already finished is materialised first, so an id
            // whose plan is gone is not found rather than refused as not ready.
            store.complete_due_teardowns(now);
            // A transition the clock already owes is reported as due, so a plan whose
            // transient span has passed serves this call even if nobody polled it. The
            // plan is resolved in THIS request's region only: a plan created in another
            // region names nothing here.
            match store.plan(&region, &input.rescore_execution_plan_id) {
                None => PlanState::Missing,
                Some(plan) if plan.status_at(now) != crate::state::STATUS_ACTIVE => {
                    PlanState::NotActive
                }
                Some(_) => PlanState::Ready(store.next_id(now)),
            }
        };
        let rescore_id = match plan_state {
            // A plan the store does not hold: the resource-not-found error, with this
            // service's constant not-found message.
            PlanState::Missing => {
                return Err(RescoreErrorModeled::ResourceNotFoundException(
                    crate::state::plan_not_found(),
                )
                .into())
            }
            // The plan exists but has not reached ACTIVE, so it cannot serve the data
            // plane yet ("When the value is ACTIVE, the rescore execution plan is ready
            // for use."): the modelled 400, not a served ranking.
            PlanState::NotActive => {
                return Err(
                    RescoreErrorModeled::ValidationException(crate::state::plan_not_active()).into(),
                )
            }
            PlanState::Ready(rescore_id) => rescore_id,
        };

        let query_terms = query_content_terms(&input.search_query);
        let units = scoring_units(&input.documents);
        // The scale this request's scores are on, which the relevance component is
        // expressed on too. See [`relevance_scale`].
        let scale = relevance_scale(&units);
        // One score per scoring unit, so a group of documents is ranked as the one
        // document it is processed as, and each of its members reports that score.
        let mut ranked: Vec<(f32, Vec<String>)> = units
            .into_iter()
            .map(|mut unit| {
                let score = unit_score(&query_terms, &unit, scale);
                // Inside one unit the members are listed by document id, the same
                // tie-break the ordering below applies between units.
                unit.member_ids.sort();
                (score, unit.member_ids)
            })
            .collect();
        // "The results are in descending order." Ties fall back to the unit's lowest
        // document id, so one request's ranking is one total order rather than an
        // input-order accident, and a unit of one document keeps ordering by its id.
        ranked.sort_by(|(left_score, left_ids), (right_score, right_ids)| {
            right_score
                .total_cmp(left_score)
                .then_with(|| left_ids.first().cmp(&right_ids.first()))
        });

        Ok(RescoreOutput {
            // The identifier of this ranking, minted by the store above. Nothing in this
            // service's surface reads a ranking back by it, so none is retained.
            rescore_id: Some(rescore_id),
            result_items: Some(
                ranked
                    .into_iter()
                    // A unit's members stay together: the group holds ONE position in
                    // the ordering, with one result item naming each document the
                    // request submitted under it.
                    .flat_map(|(score, member_ids)| {
                        member_ids
                            .into_iter()
                            .map(move |document_id| RescoreResultItem {
                                document_id: Some(document_id),
                                score: Some(score),
                            })
                    })
                    .collect(),
            ),
        })
    }
}

/// The validation-path name of the `Documents` input member: a validation report names
/// a member in lowerCamel, which is the report's casing convention applied to the
/// Smithy member name, not a fact of the model.
const DOCUMENTS_MEMBER: &str = "documents";

/// The model member names of the two forms a submitted document's body text may be
/// given in (`Document$Body` / `Document$TokenizedBody`). A refusal of the rule that
/// binds them names the members, so it names them as the model spells them.
const BODY_MEMBER: &str = "Body";
/// See [`BODY_MEMBER`].
const TOKENIZED_BODY_MEMBER: &str = "TokenizedBody";
/// The model member names of the two forms a submitted document's title may be given in
/// (`Document$Title` / `Document$TokenizedTitle`), like [`BODY_MEMBER`].
const TITLE_MEMBER: &str = "Title";
/// See [`TITLE_MEMBER`].
const TOKENIZED_TITLE_MEMBER: &str = "TokenizedTitle";

/// How much of the blended score the document's own original score contributes: the
/// SMALLER share, so a document the search service under-scored is not held down by it.
/// Emulator-chosen magnitude, serving the direction this module's documentation states.
const ORIGINAL_SCORE_WEIGHT: f32 = 0.4;
/// How much of the blended score the query/document term overlap contributes: the LARGER
/// share, because what the operation answers is a NEW relevancy score. Emulator-chosen
/// magnitude, like [`ORIGINAL_SCORE_WEIGHT`].
const RELEVANCE_WEIGHT: f32 = 0.6;
/// Share of the overlap measured against the document's title. Emulator-chosen.
const TITLE_WEIGHT: f32 = 0.7;
/// Share of the overlap measured against the document's body. Emulator-chosen.
const BODY_WEIGHT: f32 = 0.3;
/// The range `RescoreResultItem$Score` models (`Float`, range -100000..100000).
const SCORE_MIN: f32 = -100_000.0;
/// See [`SCORE_MIN`].
const SCORE_MAX: f32 = 100_000.0;

/// What this operation scores: one submitted document, or every submitted document that
/// carries the same `GroupId` pooled into the single document the service processes them
/// as.
#[derive(Debug)]
struct ScoringUnit {
    /// The ids of the documents this unit was built from, in the order they joined it;
    /// the ranking re-orders them by id before they reach the answer. Never empty: a
    /// unit exists because a document joined it.
    member_ids: Vec<String>,
    /// The unit's title terms: the union of its members' title terms.
    title_terms: BTreeSet<String>,
    /// The unit's body terms: the union of its members' body terms.
    body_terms: BTreeSet<String>,
    /// The original score the unit is blended with: the highest its members carry.
    /// Which member's score stands for a group is EMULATOR-chosen, like the weights in
    /// [`unit_score`]; taking the highest keeps a unit of one document scored exactly as
    /// that document's own `OriginalScore` and keeps the unit inside the range the model
    /// gives `OriginalScore`.
    original_score: f32,
}

/// The scoring units of one request's documents, in the order each unit's FIRST member
/// was submitted.
///
/// `Document$GroupId` is "the optional group identifier of the document from the search
/// service. Documents with the same group identifier are grouped together and processed
/// as one document within the service", so documents sharing a group identifier pool
/// into one unit — their title and body text joins one unit's text — while a document
/// that carries no group identifier is a unit holding only itself. Grouping is by the
/// identifier's exact value and spans only the documents of this one request.
fn scoring_units(documents: &[Document]) -> Vec<ScoringUnit> {
    let mut units: Vec<ScoringUnit> = Vec::new();
    let mut unit_of_group: BTreeMap<&str, usize> = BTreeMap::new();
    for document in documents {
        let title_terms = field_terms(
            document.title.as_deref(),
            document.tokenized_title.as_deref(),
        );
        let body_terms = field_terms(document.body.as_deref(), document.tokenized_body.as_deref());
        // The unit this document joins: the one its group already opened, or a new one
        // (which a later document carrying the same group identifier then joins).
        let joined = match document.group_id.as_deref() {
            Some(group_id) => match unit_of_group.entry(group_id) {
                std::collections::btree_map::Entry::Occupied(opened) => Some(*opened.get()),
                std::collections::btree_map::Entry::Vacant(unopened) => {
                    unopened.insert(units.len());
                    None
                }
            },
            None => None,
        };
        match joined {
            Some(index) => {
                let unit = &mut units[index];
                unit.member_ids.push(document.id.clone());
                unit.title_terms.extend(title_terms);
                unit.body_terms.extend(body_terms);
                unit.original_score = unit.original_score.max(document.original_score);
            }
            None => units.push(ScoringUnit {
                member_ids: vec![document.id.clone()],
                title_terms,
                body_terms,
                original_score: document.original_score,
            }),
        }
    }
    units
}

/// The score this service gives one scoring unit for a query carrying `query_terms`.
///
/// It blends the unit's `OriginalScore` with the share of the query's CONTENT-bearing
/// terms the unit's text carries, weighting the title above the body, taking the
/// relevance share on `scale` (the scale this request's scores are on, see
/// [`relevance_scale`]), and stays inside the range the model gives `Score`.
///
/// The weights are the EMULATOR's, not the service's: Amazon Kendra Intelligent Ranking
/// re-ranks with a semantic model, which this emulator cannot run, so this is a
/// deterministic lexical stand-in. Its guarantees are ordinal and directional, not
/// absolute — a unit whose text carries more of the query outranks one that carries
/// less at the same original score, a unit whose text carries the query's content terms
/// is scored materially above the original score it arrived with, and the same input
/// always yields the same ranking.
fn unit_score(query_terms: &[String], unit: &ScoringUnit, scale: f32) -> f32 {
    let relevance = TITLE_WEIGHT * coverage(query_terms, &unit.title_terms)
        + BODY_WEIGHT * coverage(query_terms, &unit.body_terms);
    (ORIGINAL_SCORE_WEIGHT * unit.original_score + RELEVANCE_WEIGHT * relevance * scale)
        .clamp(SCORE_MIN, SCORE_MAX)
}

/// The scale one request's scores are on: the largest magnitude its scoring units carry,
/// and never less than one.
///
/// A search service's scores have no fixed scale — `OriginalScore` is modelled over
/// -100000..100000, and a lexical search engine's scores commonly run in the tens —
/// while the share of a query a document's text carries is a fraction of one. Blending
/// the two as if they were one scale would let any batch whose scores are not already on
/// the unit scale swamp the relevance share and hand the submitted order straight back,
/// which is the opposite of re-ranking. So the relevance share is taken on the scale of
/// the scores the request itself carries, which is the only evidence of the caller's
/// scale a request holds, with a floor of one so a batch already on the unit scale is
/// left where it is.
fn relevance_scale(units: &[ScoringUnit]) -> f32 {
    units
        .iter()
        .map(|unit| unit.original_score.abs())
        .fold(1.0, f32::max)
}

/// The English function words, lowercased: the published ISO list the `stop-words` crate
/// carries, rather than a list written out here. Built once and shared.
fn function_words() -> &'static BTreeSet<String> {
    static FUNCTION_WORDS: ::std::sync::OnceLock<BTreeSet<String>> = ::std::sync::OnceLock::new();
    FUNCTION_WORDS.get_or_init(|| {
        ::stop_words::get(::stop_words::LANGUAGE::English)
            .into_iter()
            .map(|word| word.to_lowercase())
            .collect()
    })
}

/// The terms of one document field, from its text form or its pre-tokenized form
/// (`Title`/`TokenizedTitle`, `Body`/`TokenizedBody`): exactly one of the two is set.
fn field_terms(text: Option<&str>, tokens: Option<&[String]>) -> BTreeSet<String> {
    match (text, tokens) {
        (_, Some(tokens)) => tokens.iter().flat_map(|token| terms_of(token)).collect(),
        (Some(text), None) => terms_of(text).into_iter().collect(),
        (None, None) => BTreeSet::new(),
    }
}

/// The share of `query_terms` that `document_terms` carries, in `0.0..=1.0`. A query
/// with no terms, or a document field with none, covers nothing.
fn coverage(query_terms: &[String], document_terms: &BTreeSet<String>) -> f32 {
    if query_terms.is_empty() || document_terms.is_empty() {
        return 0.0;
    }
    let matched = query_terms
        .iter()
        .filter(|term| document_terms.contains(*term))
        .count();
    matched as f32 / query_terms.len() as f32
}

/// The query's CONTENT-bearing terms, without repeats and in first-seen order.
///
/// What the answer carries is a relevancy score, so the measure of relevance is taken
/// over the words the query ASKS ABOUT. A query's function words ask about nothing —
/// they are carried by no document's text in particular — so counting them would only
/// shrink the share of the query any document can ever cover, however completely the
/// document answers it. A query made of nothing BUT function words keeps them all, so it
/// still ranks its documents by the words it has rather than by none.
fn query_content_terms(search_query: &str) -> Vec<String> {
    let function_words = function_words();
    let words = words_of(search_query);
    let content: Vec<&String> = words
        .iter()
        .filter(|word| !function_words.contains(*word))
        .collect();
    let kept: Vec<&String> = if content.is_empty() {
        // A query of nothing BUT function words: keep them, so it ranks its documents
        // by the words it has.
        words.iter().collect()
    } else {
        content
    };
    let mut seen = BTreeSet::new();
    stems_of(kept.into_iter())
        .into_iter()
        .filter(|term| seen.insert(term.clone()))
        .collect()
}

/// Fold text into comparable terms: lowercase runs of alphanumeric characters, each
/// folded to its stem.
fn terms_of(text: &str) -> Vec<String> {
    stems_of(words_of(text).iter())
}

/// Split text into words: lowercase runs of alphanumeric characters, unstemmed, because
/// a function word is named in the published list by the word itself.
fn words_of(text: &str) -> Vec<String> {
    text.split(|c: char| !c.is_alphanumeric())
        .filter(|word| !word.is_empty())
        .map(str::to_lowercase)
        .collect()
}

/// The stems of already-lowercased `words`, under the Snowball English stemmer.
///
/// A term is compared by its stem on BOTH sides, query and document, so a query term
/// matches whichever inflected form a document spells it in — a document about
/// "batteries" answers a query about a "battery" — which is what a measure of relevance
/// over a document's words has to do to mean anything.
fn stems_of<'words>(words: impl Iterator<Item = &'words String>) -> Vec<String> {
    let stemmer = stemmer();
    words.map(|word| stemmer.stem(word).into_owned()).collect()
}

/// The Snowball English stemmer, built once and shared like [`function_words`].
fn stemmer() -> &'static ::rust_stemmers::Stemmer {
    static STEMMER: ::std::sync::OnceLock<::rust_stemmers::Stemmer> =
        ::std::sync::OnceLock::new();
    STEMMER.get_or_init(|| ::rust_stemmers::Stemmer::create(::rust_stemmers::Algorithm::English))
}
