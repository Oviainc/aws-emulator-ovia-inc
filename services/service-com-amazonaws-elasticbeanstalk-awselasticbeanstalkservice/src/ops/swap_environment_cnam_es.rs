            return Err(SwapEnvironmentCNAMEsError::missing_required_parameter(
                "Must specify SourceEnvironmentId with DestinationEnvironmentId, \
                 or SourceEnvironmentName with DestinationEnvironmentName."
                    .to_string(),
            ));
