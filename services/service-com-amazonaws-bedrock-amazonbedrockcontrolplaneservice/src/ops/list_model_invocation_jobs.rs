/// Whether every filter `input` carries holds for `record`.
///
/// The time bounds are STRICT, as the members word them: jobs "that were submitted after
/// the time you specify" and "before the time you specify".
fn matches(
    input: &ListModelInvocationJobsInput,
    record: &crate::state::ModelInvocationJobRecord,
) -> bool {
    let submitted = crate::state::epoch_seconds(record.submit_time);
    if let Some(after) = input.submit_time_after.as_ref() {
        if submitted <= after.as_secs_f64() {
            return false;
        }
    }
    if let Some(before) = input.submit_time_before.as_ref() {
        if submitted >= before.as_secs_f64() {
            return false;
        }
    }
    if input
        .status_equals
        .as_deref()
        .is_some_and(|status| status != record.status)
    {
        return false;
    }
    if input
        .name_contains
        .as_deref()
        .is_some_and(|fragment| !record.name.contains(fragment))
    {
        return false;
    }
    true
}

