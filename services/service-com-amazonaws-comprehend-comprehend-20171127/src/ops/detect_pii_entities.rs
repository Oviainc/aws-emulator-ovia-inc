//! @op DetectPiiEntities
//!
//! Answers the PII entities the submitted document carries: one `PiiEntity` per
//! entity the service's recognizer placed in the text, with the modelled
//! `PiiEntityType` it is, the confidence the recognizer's evidence carries and the
//! zero-based CHARACTER offsets of the span.
//!
//! ## How the document is analysed
//!
//! Through [`crate::ops::contains_pii_entities::detect_pii_spans`], the ONE PII
//! recognizer of Comprehend's PII family: it matches the published FORM of each
//! entity type and, where the defining standard gives the value a check digit,
//! verifies it. This operation PROJECTS the spans it returns into `PiiEntity` values
//! and `ContainsPiiEntities` projects the same spans into the distinct set of types,
//! so the two operations cannot disagree about what a document carries. Nothing is
//! matched out of the request's shape and no entity is guessed: a document with no
//! recognisable PII answers an empty `Entities` list rather than a detection nothing
//! found.
//!
//! ## Shape of an operation
//!
//! Each operation is a struct that owns the shared engine and implements
//! [`smithy_server_runtime::Operation`]. The framework constructs one per service via
//! `DetectPiiEntities::new(engine)` and drives it through the centralized request walk:
//! deserialize → validate → `handle` → serialize. You write ONLY the `handle` body.
//!
//! This operation holds NO state: its answer is a function of `Text` alone, so
//! repeating a call returns the same entities and nothing a later caller reads is
//! changed by one. The recognizer is synchronous, CPU-bound work, so
//! [`crate::ops::contains_pii_entities::recognize_pii`] runs it OFF the async worker
//! under a wall-clock budget, exactly as `ContainsPiiEntities` does.
//!
