/// The largest `Text` this operation accepts, in UTF-8 bytes: the real-time quota
/// Comprehend publishes for PII analysis, stated once for the whole family in
/// [`crate::state::PII_TEXT_QUOTA_BYTES`], whose documentation carries this
/// operation's own modelled member prose ("The maximum string size is 100 KB").
/// Anything larger is refused with the `TextSizeLimitExceededException` the operation
/// declares.
const MAX_TEXT_BYTES: usize = PII_TEXT_QUOTA_BYTES;

/// The recognizer's spans as the modelled `PiiEntity` values this operation answers,
/// in the document order [`crate::ops::contains_pii_entities::detect_pii_spans`]
/// returns them in.
///
/// `BeginOffset`/`EndOffset` are the span's zero-based CHARACTER offsets, `EndOffset`
/// one past its last character — the scale the modelled members are documented on,
/// and the scale the recognizer already works in. A document is bounded by
/// [`MAX_TEXT_BYTES`], so every offset of an accepted document fits the modelled
/// `Integer`; a span that somehow did not is reported without the offset it cannot
/// represent rather than with a wrapped one.
fn entities_of(spans: Vec<PiiSpan>) -> Vec<PiiEntity> {
    spans
        .into_iter()
        .map(|span| PiiEntity {
            score: Some(span.score),
            r#type: Some(span.entity_type.to_string()),
            begin_offset: i32::try_from(span.begin).ok(),
            end_offset: i32::try_from(span.end).ok(),
        })
        .collect()
}

