use lingua::{Language, LanguageDetector, LanguageDetectorBuilder};

/// Comprehend's `LanguageCode` values (`super::types::LANGUAGE_CODE_VALUES`) paired
/// with the language the identification engine recognises for each.
///
/// `zh-TW` has no entry: the engine identifies Chinese without distinguishing the
/// traditional-script variant, so it is never the answer — a language the engine
/// cannot tell apart is not reported rather than guessed at.
const DETECTABLE_LANGUAGES: &[(Language, &str)] = &[
    (Language::Arabic, "ar"),
    (Language::German, "de"),
    (Language::English, "en"),
    (Language::Spanish, "es"),
    (Language::French, "fr"),
    (Language::Hindi, "hi"),
    (Language::Japanese, "ja"),
    (Language::Korean, "ko"),
    (Language::Italian, "it"),
    (Language::Portuguese, "pt"),
    (Language::Chinese, "zh"),
];

/// The largest `Text` this operation accepts, in UTF-8 bytes: the real-time quota
/// Comprehend publishes for `DetectDominantLanguage`, stated once for every
/// real-time inference operation beside its siblings in
/// [`crate::state::DOMINANT_LANGUAGE_TEXT_QUOTA_BYTES`]. Anything larger is refused
/// with the `TextSizeLimitExceededException` the operation declares.
const MAX_TEXT_BYTES: usize = crate::state::DOMINANT_LANGUAGE_TEXT_QUOTA_BYTES;

/// How much of the document the identification engine is given, in characters.
///
/// The bound in-process execution must carry: the engine's n-gram pass costs more
/// than linearly in the length of a single token, so an unbounded document lets one
/// request hold the whole emulator for minutes. A language's n-gram profile
/// saturates after a few thousand characters — two orders of magnitude above the 20
/// characters this operation's documentation asks for — so the engine reads the
/// document's leading characters up to this budget. The answer is still the
/// engine's own, over text the caller submitted.
///
/// Contract consequence a caller should know: a document whose leading characters
/// are one language and whose tail is another is identified from that leading
/// sample alone.
const IDENTIFICATION_SAMPLE_CHARS: usize = 4096;

/// How long one identification may take before the caller is answered with the
/// operation's own server error instead of being left waiting.
///
/// Two orders of magnitude above what identifying an
/// [`IDENTIFICATION_SAMPLE_CHARS`]-character sample costs, so it never fires for a
/// request the engine is simply working through.
///
/// What it does and does not do: it bounds what the CALLER waits for. A blocking
/// task cannot be cancelled from outside, so when the budget fires the engine keeps
/// running to its natural end and releases its blocking-pool slot then; the budget
/// does not reclaim that slot early. What bounds the POOL is the work itself being
/// bounded — the byte quota refuses an oversized document before any inference, and
/// [`IDENTIFICATION_SAMPLE_CHARS`] caps what the engine reads of the rest.
const IDENTIFICATION_TIME_BUDGET: Duration = Duration::from_secs(5);

/// The shared language-identification engine, restricted to the languages
/// Comprehend's `LanguageCode` enum names.
///
/// Built once: the engine is immutable, so every request observes the same
/// deterministic model set and the language models are assembled a single time.
/// The engine's full-accuracy mode is what this operation needs, and not an
/// optimisation: its reduced mode scores only trigrams and collapses onto a single
/// candidate at confidence 1, which reports neither the runner-up candidates the
/// modelled `Languages` list carries nor a usable confidence for the dominant one.
///
/// What that costs, and why it is bounded: the model set is FIXED at the eleven
/// languages above — nothing a request says can widen it — and the engine
/// materialises each language's n-gram models at most once per process, on the first
/// request that needs them, so the residency is a constant of the emulator rather
/// than something a caller can grow. Per-request work is bounded by
/// [`IDENTIFICATION_SAMPLE_CHARS`], and every caller runs the engine through
/// [`identify_languages`], off the async worker and under
/// [`IDENTIFICATION_TIME_BUDGET`].
fn detector() -> &'static LanguageDetector {
    static DETECTOR: OnceLock<LanguageDetector> = OnceLock::new();
    DETECTOR.get_or_init(|| {
        let languages: Vec<Language> =
            DETECTABLE_LANGUAGES.iter().map(|(lang, _)| *lang).collect();
        LanguageDetectorBuilder::from_languages(&languages).build()
    })
}

/// How much contrast the reported distribution carries over the engine's own
/// relative confidence metric.
///
/// Why a calibration step exists at all: the identification engine documents its
/// per-language values as a RELATIVE metric — they rank the candidates and sum to 1,
/// but they are length-normalised, so a document that carries one language's clause
/// beside short material in others comes back with its mass split almost evenly
/// across the leading Latin-script candidates. The modelled `Languages` member
/// describes a different quantity: "the level of confidence that Amazon Comprehend
/// has in the accuracy of its inference" for a document whose "dominant language is
/// always the first element", which a caller gates on with a decision threshold.
/// Reporting a relative rank as a confidence makes an identification the engine is
/// clear about read as ambiguous.
///
/// What this is: each candidate's relative value raised to this exponent, then
/// renormalised over every candidate the engine placed. The transform is strictly
/// monotone, so it changes NO ranking — the dominant language, the runner-up order
/// and the set of candidates are exactly the engine's — and it introduces no number
/// of its own: every score is still a function of the engine's values over the
/// submitted text.
///
/// The value is the ONE contrast constant of this projection, applied identically to
/// every candidate of every document, so no request can select it. It is 2 because
/// that is where both halves of a confidence hold: a document with one predominating
/// language clears the decision threshold a caller gates on, while the score still
/// FOLLOWS the margin the engine gave it, so two documents the engine is differently
/// sure about are reported differently. Higher exponents lose the second half — by 4,
/// the engine's margin is squeezed past the float width and every clear document comes
/// back carrying the same rounded confidence, which tells a caller nothing.
const SCORE_CONTRAST_EXPONENT: i32 = 2;

/// The confidence the reported distribution keeps for a language outside the set the
/// identification engine was built with.
///
/// The engine's per-language values sum to 1 over [`DETECTABLE_LANGUAGES`] alone, so
/// they are a distribution CONDITIONAL on the document being written in one of those
/// languages — a document in a language Comprehend's `LanguageCode` enum does not
/// name, or in the traditional-script Chinese the engine cannot tell apart, still has
/// its whole mass spread over them. An identification is therefore never certain, and
/// this is the mass the response withholds from the candidates to say so: every
/// reported `Score` is the engine's own confidence scaled by `1 - ` this value, which
/// is strictly monotone and so changes no ranking, and which keeps the dominant
/// language's confidence strictly below 1 however clear the document is.
const UNMODELLED_LANGUAGE_MASS: f64 = 1e-3;

/// How far below the dominant language a candidate may be scored and still be
/// reported as a runner-up.
///
/// The engine scores EVERY language it was built with, so a document written plainly
/// in one of them still comes back with ten runner-ups carrying the rounding of a
/// rejected hypothesis. The modelled `Languages` member describes an "array of
/// languages that Amazon Comprehend detected in the input text", each with "the level
/// of confidence that Amazon Comprehend has in the accuracy of its inference": a
/// hypothesis the engine has all but rejected is not a language it detected, and a
/// caller reading `Languages[1]` as the second-best candidate must not be handed one.
///
/// The bound is RELATIVE to the leading candidate rather than an absolute confidence,
/// so it says the same thing about a long document the engine is sure about and a
/// two-word one it is not: a candidate the engine prefers the dominant language over
/// by more than an order of magnitude is a rejected hypothesis, while a document the
/// engine cannot decide between two or more languages keeps every one of them, since
/// they sit within an order of magnitude of each other.
const CANDIDATE_RELATIVE_FLOOR: f64 = 0.1;

/// The engine's answer for `text`, as the modelled `DominantLanguage` list: every
/// language the engine places material confidence in, each carrying that confidence
/// as its `Score`, "sorted in descending order of the score (the dominant language is
/// always the first element in the array)" as the modelled `Languages` member
/// documents. Nothing here is invented: the engine computes one confidence per
/// language it was built with over the submitted text, and this reports them.
///
/// Three things the projection does, and nothing else. Every candidate's relative
/// value is raised to [`SCORE_CONTRAST_EXPONENT`] and renormalised over the set, so
/// the score is a confidence rather than a relative rank; a candidate scored more
/// than [`CANDIDATE_RELATIVE_FLOOR`] below the dominant one is DROPPED rather than
/// reported as a runner-up the engine did not detect; and every reported confidence
/// is scaled by the mass [`UNMODELLED_LANGUAGE_MASS`] withholds for a language
/// outside the engine's set. All three are strictly monotone over the engine's
/// values, so the dominant language and the order of the runner-ups are exactly the
/// engine's; the scores stay a distribution, summing to at most 1, and the dominant
/// language's score stays strictly below 1.
///
/// Equal confidences are ordered by language code, so the list is a total order and
/// two identical requests return byte-identical arrays.
///
/// A document the engine can place nowhere — one carrying no letters at all — gets an
/// EMPTY list, which is why the modelled `Languages` member is optional in the first
/// place.
///
/// `pub(crate)` because every other caller identifies a document with the SAME
/// engine, through this one function: `BatchDetectDominantLanguage`, documented as
/// this same inference over a batch of documents, and the asynchronous
/// `StartDominantLanguageDetectionJob`, which analyses each of its input documents.
/// Synchronous, batch and asynchronous identification of a document must never be
/// implementations that can disagree.
pub(crate) fn detect_languages(text: &str) -> Vec<DominantLanguage> {
    let sample: String = text.chars().take(IDENTIFICATION_SAMPLE_CHARS).collect();
    // Every candidate the engine placed, with its relative confidence raised to the
    // contrast exponent and renormalised over the whole set: a confidence rather
    // than a relative rank, over exactly the candidates the engine scored.
    let weighted: Vec<(&'static str, f64)> = detector()
        .compute_language_confidence_values(&sample)
        .into_iter()
        .filter(|(_, confidence)| *confidence > 0.0)
        .filter_map(|(lang, confidence)| {
            DETECTABLE_LANGUAGES
                .iter()
                .find(|(candidate, _)| *candidate == lang)
                .map(|(_, code)| (*code, confidence.powi(SCORE_CONTRAST_EXPONENT)))
        })
        .collect();
    let total: f64 = weighted.iter().map(|(_, weight)| weight).sum();
    if total <= 0.0 {
        return Vec::new();
    }
    // What the dominant language is scored. Every other candidate is measured
    // against it, so the reporting bound is the engine's own preference for the
    // leader rather than a confidence this emulator fixed.
    let leading = weighted
        .iter()
        .map(|(_, weight)| *weight)
        .fold(0.0f64, f64::max);
    let mut candidates: Vec<DominantLanguage> = weighted
        .into_iter()
        // A candidate the engine all but rejected is not a language it detected.
        .filter(|(_, weight)| *weight >= leading * CANDIDATE_RELATIVE_FLOOR)
        .filter_map(|(code, weight)| {
            let score = (weight / total * (1.0 - UNMODELLED_LANGUAGE_MASS)) as f32;
            // A score that renders as zero at the modelled float width would claim
            // a candidate with no confidence at all.
            (score > 0.0).then(|| DominantLanguage {
                language_code: Some(code.to_string()),
                score: Some(score),
            })
        })
        .collect();
    candidates.sort_by(|left, right| {
        right
            .score
            .unwrap_or_default()
            .total_cmp(&left.score.unwrap_or_default())
            .then_with(|| left.language_code.cmp(&right.language_code))
    });
    candidates
}

/// [`detect_languages`] run OFF the async worker: identification is synchronous,
/// CPU-bound work with no await of its own, so it goes to the blocking pool and the
/// worker serving this request is released while the engine runs. The
/// `spawn_blocking(..).await` is a real await point, so a request waiting on an
/// identification can be cancelled or timed out, and a burst of concurrent
/// inference cannot starve the operations sharing the runtime.
///
/// `Err` carries the sentence the caller puts in its OWN modelled server error: the
/// engine either did not answer inside [`IDENTIFICATION_TIME_BUDGET`] — the budget
/// bounds the caller's wait, not the blocking task, which runs to its natural end —
/// or did not run at all, and in both cases nothing was computed, so no answer may
/// be fabricated for it. Every request-time caller goes through here;
/// [`detect_languages`] itself stays available for a pass that already yields
/// between documents of its own accord.
pub(crate) async fn identify_languages(text: String) -> Result<Vec<DominantLanguage>, String> {
    match ::tokio::time::timeout(
        IDENTIFICATION_TIME_BUDGET,
        ::tokio::task::spawn_blocking(move || detect_languages(&text)),
    )
    .await
    {
        Ok(Ok(languages)) => Ok(languages),
        Ok(Err(error)) => Err(format!(
            "the language identification did not complete: {error}"
        )),
        Err(_) => Err(format!(
            "the language identification did not complete within {} seconds",
            IDENTIFICATION_TIME_BUDGET.as_secs()
        )),
    }
}

