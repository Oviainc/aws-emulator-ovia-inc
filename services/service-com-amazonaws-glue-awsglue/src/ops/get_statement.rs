impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for GetStatement<Eng>
{
    type Input = GetStatementInput;
    type Output = GetStatementOutput;
    type Error = GetStatementError;

    const NAME: &'static str = "GetStatement";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_STATEMENT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_STATEMENT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            // This operation models a server fault, so an unreachable store is reported
            // as that rather than as a client error the caller could act on.
            return Err(GetStatementErrorModeled::InternalServiceException(
                InternalServiceException {
                    message: Some("the Glue session store is unavailable".into()),
                },
            )
            .into());
        };

        // "The origin of the request" names who is asking, not which statement is asked
        // for, so it changes nothing about this read.
        let _ = &input.request_origin;
        // A session is served only through the endpoint that created it, so the Region,
        // the session id and the statement id together are the whole address this read
        // resolves.
        let region = crate::state::request_region(ctx.parts());
        let now = ::std::time::SystemTime::now();
        let mut store = state.lock();
        let Some(session) = store.session_mut(&region, &input.session_id) else {
            return Err(GetStatementErrorModeled::EntityNotFoundException(
                EntityNotFoundException {
                    message: Some(crate::state::messages::session_id_not_found(
                        &input.session_id,
                    )),
                    from_federation_source: None,
                },
            )
            .into());
        };
        // The only write a read makes: the state changes the clock had already made due.
        session.settle_due_statements(now);

        let Some(statement) = session.statement(input.id) else {
            return Err(GetStatementErrorModeled::EntityNotFoundException(
                EntityNotFoundException {
                    // The refusal names the pair that resolved to nothing.
                    message: Some(crate::state::messages::statement_not_found(
                        &input.session_id,
                        input.id,
                    )),
                    from_federation_source: None,
                },
            )
            .into());
        };

        // "Returns the statement" — rebuilt from the stored record, so this read reports
        // what the run wrote and what the clock has since owed it.
        Ok(GetStatementOutput {
            statement: Some(statement.to_statement()),
        })
    }
}
