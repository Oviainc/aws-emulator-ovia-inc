            if !DELETION_PROTECTION_VALUES.contains(&value) {
                return Err(UpdateCollectionErrorModeled::ValidationException(
                    ValidationException {
                        message: Some(format!(
                            "deletionProtection must be one of [{}], got {value:?}",
                            DELETION_PROTECTION_VALUES.join(", ")
                        )),
                    },
                )
                .into());
            }
