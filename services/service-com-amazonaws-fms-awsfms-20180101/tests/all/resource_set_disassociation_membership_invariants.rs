//! End-to-end invariant tests for what `BatchDisassociateResource` does to a
//! resource set: which resources the set holds afterwards, and the
//! `LastUpdateTime` every reader of the set then reports.
//!
//! Every test drives the service the way a client does: an awsJson1_1 `POST /`
//! through [`smithy_server_runtime::MultiServiceRouter::dispatch`], with the
//! `X-Amz-Target` header and a SigV4 credential scope, so the whole
//! deserialize → handle → serialize walk runs and the assertions are about the
//! WIRE response.
//!
//! The rule asserted here is one sentence: which resources a set holds is part of
//! the set, so a disassociation leaves the set holding exactly the members it held
//! minus the items it named, and records the instant it ran as the set's last
//! update for every reader exactly when that membership changed — a call naming
//! only items the set does not hold, only items that could never be members, or
//! no items at all removed nothing, so the timestamp stays where it was.
//!
//! This is the INVARIANT form of that rule, where the hand-written table in
//! [`crate::resource_set_membership_last_update_time`] is its example form: the
//! cases are GENERATED by walking every subset of a candidate membership against
//! every subset of the URIs a call may name, each combination also carrying one of
//! the kinds of item that can never be a member, so both outcomes of the rule
//! (moved, unmoved) and the set-difference it leaves are reached from every
//! direction rather than from the few rows a table lists. Each case also repeats
//! its own call, which is where the idempotence the rule implies is asserted: the
//! second call has nothing left to remove, so it must leave the timestamp alone.
//!
//! The wire harness and the two readers of the stored instant are the sibling
//! suite's, so the two suites cannot drift in how a request is signed or a
//! timestamp is read.

use std::time::SystemTime;

use serde_json::json;

use crate::administrator_gated_operations::associate_admin;
use crate::policy_lifecycle::{call, emulator_with_engine, ACCOUNT, REGION};
use crate::resource_set_membership_last_update_time::{
    backdate, create_set_with_members, epoch_seconds, firewall, instance,
    reported_last_update_time, reported_membership, summarized_last_update_time,
};

/// The resource types every generated set declares. Two of them, so the generated
/// memberships span more than one type: `ResourceSet$ResourceTypeList`
/// "determines the resources that can be associated to the resource set", so the
/// candidate URIs below are resources of exactly these types.
const RESOURCE_TYPES: [&str; 2] = ["AWS::EC2::Instance", "AWS::NetworkFirewall::Firewall"];

/// A second Region, for an item whose ARN names another Region than the request.
const OTHER_REGION: &str = "eu-central-1";

/// The URIs a generated set may hold: every subset of these is a membership the
/// case walk seeds.
fn member_candidates() -> Vec<String> {
    vec![instance(0), instance(1), firewall("edge")]
}

/// The URIs a generated call may name: the three members, plus one resource the
/// set COULD hold but never held — so a call that names nothing removable is
/// generated as often as one that empties the set.
fn item_candidates() -> Vec<String> {
    let mut candidates = member_candidates();
    candidates.push(instance(9));
    candidates
}

/// The kinds of item that can never be a member of a generated set, each with the
/// reason the service must report it under, and `None` for a call that carries no
/// such item at all.
///
/// The reasons are values of the model's `FailedItemReason`
/// (`smithy_query(query="shape", shape="com.amazonaws.fms#FailedItemReason")`:
/// `NOT_VALID_ARN`, `NOT_VALID_PARTITION`, `NOT_VALID_REGION`,
/// `NOT_VALID_SERVICE`, `NOT_VALID_RESOURCE_TYPE`, `NOT_VALID_ACCOUNT_ID`), one
/// per ARN field a generated set can disagree with: a URI that is no ARN at all, a
/// resource of another Region than the request addresses, and a resource whose
/// type no entry of [`RESOURCE_TYPES`] names.
fn unassociable_variants() -> Vec<Option<(String, &'static str)>> {
    vec![
        None,
        Some(("not-an-arn-at-all".to_string(), "NOT_VALID_ARN")),
        Some((
            format!("arn:aws:ec2:{OTHER_REGION}:{ACCOUNT}:instance/i-{:017x}", 3),
            "NOT_VALID_REGION",
        )),
        Some((
            format!("arn:aws:ec2:{REGION}:{ACCOUNT}:vpc/vpc-{:017x}", 4),
            "NOT_VALID_RESOURCE_TYPE",
        )),
    ]
}

/// The subset of `candidates` `mask` selects, one bit per candidate.
fn subset(mask: usize, candidates: &[String]) -> Vec<String> {
    candidates
        .iter()
        .enumerate()
        .filter(|(index, _)| mask & (1 << index) != 0)
        .map(|(_, uri)| uri.clone())
        .collect()
}

/// `uris` in the ascending order [`reported_membership`] reports a membership in.
fn sorted(mut uris: Vec<String>) -> Vec<String> {
    uris.sort();
    uris
}

/// The `(URI, Reason)` pairs one `BatchDisassociateResource` response reports in
/// `FailedItems`.
fn failed_items(body: &serde_json::Value, case: &str) -> Vec<(String, String)> {
    body["FailedItems"]
        .as_array()
        .unwrap_or_else(|| panic!("case {case:?}: no FailedItems array in {body}"))
        .iter()
        .map(|item| {
            (
                item["URI"].as_str().unwrap_or_default().to_string(),
                item["Reason"].as_str().unwrap_or_default().to_string(),
            )
        })
        .collect()
}

/// For every membership and every set of items a call may name: the set afterwards
/// holds exactly what it held minus what the call named, the items that could
/// never be members are reported in `FailedItems`, and the set's `LastUpdateTime`
/// is the instant of the call when the membership changed and untouched when it
/// did not — with a repeat of the same call removing nothing and moving nothing.
#[tokio::test]
async fn a_disassociation_removes_exactly_the_members_it_names_and_dates_the_set_when_it_does() {
    let members = member_candidates();
    let items = item_candidates();
    let variants = unassociable_variants();
    let item_subsets = 1usize << items.len();

    for held_mask in 0..(1usize << members.len()) {
        for items_mask in 0..item_subsets {
            let held = subset(held_mask, &members);
            let named = subset(items_mask, &items);
            // Every combination also carries one kind of never-a-member item, so
            // the per-item failures are generated across the whole walk rather
            // than doubling it.
            let variant = &variants[(held_mask * item_subsets + items_mask) % variants.len()];
            let case = format!(
                "holding {held:?}, disassociating {named:?} beside {:?}",
                variant.as_ref().map(|(uri, _)| uri.as_str())
            );

            // The name the set is created under is derived from the masks rather
            // than from the case label: `ResourceSet$Name` is constrained to a
            // pattern the label's punctuation does not satisfy.
            let set_name = format!("disassociation-{held_mask}-{items_mask}");

            let (router, engine) = emulator_with_engine();
            associate_admin(&router).await;
            let id = create_set_with_members(&router, &set_name, &RESOURCE_TYPES, &held).await;
            // Dated back before the call, so the instant the call records is
            // separated from the document write by more than any timestamp
            // precision can blur.
            backdate(&engine, &case, &id);

            let before_time = reported_last_update_time(&router, &case, &id).await;
            let before_membership = reported_membership(&router, &case, &id).await;
            assert_eq!(
                before_membership,
                sorted(held.clone()),
                "case {case:?}: the seeded membership must be the set's own, got \
                 {before_membership:?}"
            );

            let mut request_items = named.clone();
            if let Some((uri, _)) = variant {
                request_items.push(uri.clone());
            }

            // The window the call ran in, floored and ceiled so the assertion
            // holds whatever precision the wire timestamp carries.
            let started = epoch_seconds(SystemTime::now()).floor();
            let (status, body) = call(
                &router,
                "BatchDisassociateResource",
                &json!({ "ResourceSetIdentifier": id, "Items": request_items }),
            )
            .await;
            let finished = epoch_seconds(SystemTime::now()).ceil();
            assert_eq!(
                status, 200,
                "case {case:?}: expected BatchDisassociateResource to answer 200, got {status} \
                 with {body}"
            );
            assert_eq!(
                body["ResourceSetIdentifier"].as_str(),
                Some(id.as_str()),
                "case {case:?}: the response must name the resource set it changed, got {body}"
            );
            let expected_failed: Vec<(String, String)> = variant
                .iter()
                .map(|(uri, reason)| (uri.clone(), (*reason).to_string()))
                .collect();
            assert_eq!(
                failed_items(&body, &case),
                expected_failed,
                "case {case:?}: only an item that could never be a member may be reported in \
                 FailedItems, got {body}"
            );

            let expected_membership = sorted(
                held.iter()
                    .filter(|uri| !named.contains(uri))
                    .cloned()
                    .collect(),
            );
            let after_membership = reported_membership(&router, &case, &id).await;
            assert_eq!(
                after_membership, expected_membership,
                "case {case:?}: the set must hold what it held minus what the call named, got \
                 {after_membership:?}"
            );

            let after_time = reported_last_update_time(&router, &case, &id).await;
            if expected_membership == before_membership {
                assert_eq!(
                    after_time, before_time,
                    "case {case:?}: a call that removed nothing must leave LastUpdateTime at \
                     {before_time}, got {after_time}"
                );
            } else {
                assert!(
                    after_time > before_time,
                    "case {case:?}: a removal must move LastUpdateTime on from {before_time}, got \
                     {after_time}"
                );
                assert!(
                    (started..=finished).contains(&after_time),
                    "case {case:?}: LastUpdateTime must be the instant the membership changed, in \
                     {started}..={finished}, got {after_time}"
                );
            }
            let summarized = summarized_last_update_time(&router, &case, &id).await;
            assert_eq!(
                summarized, after_time,
                "case {case:?}: the ListResourceSets summary must report the same LastUpdateTime \
                 as GetResourceSet ({after_time}), got {summarized}"
            );

            // The same call again: the membership is a SET, so there is nothing
            // left to remove and nothing about the set changed.
            backdate(&engine, &case, &id);
            let dated_back = reported_last_update_time(&router, &case, &id).await;
            let (status, body) = call(
                &router,
                "BatchDisassociateResource",
                &json!({ "ResourceSetIdentifier": id, "Items": request_items }),
            )
            .await;
            assert_eq!(
                status, 200,
                "case {case:?}: expected the repeated BatchDisassociateResource to answer 200, got \
                 {status} with {body}"
            );
            assert_eq!(
                failed_items(&body, &case),
                expected_failed,
                "case {case:?}: the repeated call must classify its items the same way, got {body}"
            );
            let repeated_membership = reported_membership(&router, &case, &id).await;
            assert_eq!(
                repeated_membership, expected_membership,
                "case {case:?}: the repeated call must leave the membership as it was, got \
                 {repeated_membership:?}"
            );
            let repeated_time = reported_last_update_time(&router, &case, &id).await;
            assert_eq!(
                repeated_time, dated_back,
                "case {case:?}: the repeated call removed nothing, so LastUpdateTime must stay at \
                 {dated_back}, got {repeated_time}"
            );
        }
    }
}
