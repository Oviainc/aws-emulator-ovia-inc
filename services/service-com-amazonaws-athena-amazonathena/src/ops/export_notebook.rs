impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ExportNotebook<Eng>
{
    type Input = ExportNotebookInput;
    type Output = ExportNotebookOutput;
    type Error = ExportNotebookError;

    const NAME: &'static str = "ExportNotebook";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::EXPORT_NOTEBOOK_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::EXPORT_NOTEBOOK_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        _ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(ExportNotebookErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("Athena state is not reachable on this engine".to_string()),
                },
            )
            .into());
        };
        // A read: the store is never written below, so what the next caller sees is
        // exactly what it saw before this call.
        let store = state.lock();

        let Some(record) = store.notebooks.notebook(&input.notebook_id) else {
            // Athena models no not-found error for this operation; naming a notebook that
            // does not exist is "something wrong with the input to the request", which is
            // what `InvalidRequestException` (HTTP 400) reports, under the code for a
            // refusal the request itself caused.
            return Err(ExportNotebookError::invalid_request(
                crate::state::ERROR_CODE_INVALID_INPUT,
                crate::state::notebook_not_found(&input.notebook_id),
            ));
        };

        // "The content of the exported notebook" is the content that was stored, handed
        // back unchanged: an export of what an import wrote is byte for byte that file.
        Ok(ExportNotebookOutput {
            notebook_metadata: Some(record.to_notebook_metadata()),
            payload: Some(record.payload.clone()),
        })
    }
}
