            return Err(UpdateThingShadowErrorModeled::RequestEntityTooLargeException(
                RequestEntityTooLargeException::new(crate::state::json_document_too_large(
                    document_state_bytes,
                    crate::state::MAX_SHADOW_DOCUMENT_BYTES,
                )),
            )
            .into());
