//! @op PutSupplementalTaxRegistration
//!
//! Adds or updates one supplemental tax registration (a supplemental TRN) of the
//! account and reports the `authorityId` it is stored under together with the
//! status its validation starts in.
//!
//! `SupplementalTaxRegistrationEntry` carries no `authorityId`, so the TRN
//! itself — its `registrationType` and `registrationId` — is the identity a
//! write addresses: writing the same TRN again UPDATES that record under the
//! `authorityId` it already has, and a TRN the account does not hold yet gets a
//! freshly minted one. The same TRN means the same NUMBER, not the same
//! spelling of it: the separators its authority prints it with and the padding
//! the member's non-blank pattern admits are no part of the number, so a write
//! that re-spells one the account holds still addresses that one record
//! ([`crate::state::ComAmazonawsTaxsettingsTaxsettingsState::find_supplemental_authority`]).
//!
//! WHICH JURISDICTIONS may hold a supplemental TRN is a rule of its own, and it
//! is applied here: supplemental registration is supported in a bounded set of
//! jurisdictions ([`crate::state::SUPPLEMENTAL_TRN_COUNTRIES`]), and an entry
//! whose `address.countryCode` is not one of them is refused with the modelled
//! `ValidationException` before anything is stored. The model names no
//! jurisdiction, so the boundary is read off OBSERVED behaviour instead — an
//! entry for a country outside the set takes a 400 while one inside it clears
//! country validation; see that constant for the observations, and why the
//! model's silence is not permission to report a stored registration for a
//! jurisdiction the service refuses. The only country code refused for its
//! SHAPE rather than its jurisdiction (not two letters, or absent) is refused
//! by the request walk before this handler runs.
