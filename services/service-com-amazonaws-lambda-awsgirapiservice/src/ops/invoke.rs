//! @op Invoke
//!
//! Resolves the function and version to invoke out of [`crate::state`], refuses a
//! request the service itself would refuse, and answers the two invocation types whose
//! answer does not depend on the run: `DryRun`, which as the model documents runs no
//! function code at all ("Validate parameter values and verify that the user or role
//! has permission to invoke the function"), and `Event`, whose answer is the QUEUEING
//! receipt — "Event – Invoke the function asynchronously […] The API response only
//! includes a status code" — so the event is queued against the resolved version
//! exactly as `InvokeAsync` queues one, and the accepted status is answered. The queued
//! event is then DELIVERED to the function off the response path: the handler runs with
//! it, through the same in-process engine a synchronous invocation runs through, so
//! whatever the handler itself performs becomes observable shortly after the accepting
//! call, and a delivery whose handler errored is attempted again up to the attempts
//! Lambda documents (`crate::state::async_invocation`).
//!
//! An accepted `Event` invocation of a DURABLE function — one whose resolved
//! configuration carries a `DurableConfig` — or one that names a `DurableExecutionName`
//! also STARTS a durable execution in the function's own durable-execution state, and
//! answers the ARN that execution is addressed by: "The ARN of the durable execution that
//! was started. This is returned when invoking a durable function and provides a unique
//! identifier for tracking the execution." `ListDurableExecutionsByFunction` reports the
//! execution from that moment on, a repeat of a live name carrying the same payload
//! answers the execution already started rather than a duplicate, and one carrying a
//! different payload is the modelled `DurableExecutionAlreadyStartedException`.
//!
//! Whether the invocation happens AT ALL is decided before any of that, by Lambda's
//! recursive-loop guardrail: an invocation that arrives as part of a request chain which
//! has already come back round into this function is one Lambda "stops […] being invoked"
//! when the function's recursive loop detection configuration is `Terminate`, and serves
//! untouched when it is `Allow`. A stopped synchronous invocation is the modelled
//! `RecursiveInvocationException`, a stopped asynchronous one is accepted and never
//! delivered, and each is metered as one `RecursiveInvocationsDropped` datapoint for the
//! function (`crate::state::recursion`).
//!
//! Every invocation the guardrail does NOT stop is one Lambda admits to the function, and
//! each is metered as one `Invocations` datapoint of the function and of the resource the
//! call addressed (`crate::state::metrics`), which is what a client reads to learn that a
//! function is being invoked at all. The dry run is metered by neither series, because it
//! invokes nothing.
//!
//! A `RequestResponse` invocation RUNS the function: the deployment package the store
//! holds for the resolved version is read, its handler is imported and called with the
//! event and the context, and what the handler produced is the answer — its returned value
//! as the response payload, or the error document and the `Unhandled` function-error signal
//! for an exception it raised, with the log tail when `LogType=Tail` asked for one. The run
//! happens in this process, in the interpreter `crate::state::execution` builds for the
//! function's runtime, bounded and contained there; a package this emulator embeds no
//! engine for is the modelled failure for it rather than a payload no function produced.
//!
//! ## Shape of an operation
//!
//! Each operation is a struct that owns the shared engine and implements
//! [`smithy_server_runtime::Operation`]. The framework constructs one per service via
//! `Invoke::new(engine)` and drives it through the centralized request walk:
//! deserialize → validate → `handle` → serialize. You write ONLY the `handle` body.
//!
//! ## Reaching this service's state
//!
//! The engine is held on `self` (constructor-injected), NOT passed per request — so
//! engine access is guaranteed by the time any request runs. Reach the store through
//! [`crate::state::service_state`] and read and write it through the guard it hands back:
//!
//! ```ignore
//!     let state = crate::state::service_state(&*self.engine)
//!         .ok_or(/* a modelled server error */)?;
//!     state.lock().your_field = /* ... */;
//! ```
//!
//! `ctx` ([`smithy_server_runtime::OperationContext`]) carries request metadata only —
//! headers, URI, method, and anything middleware placed in `ctx.parts().extensions`.
//! The engine is NOT reached through `ctx`.
//!
