/// Which listing this operation's `NextToken` belongs to, so a token issued by another
/// paginated operation is refused rather than misread.
const CURSOR_KIND: &str = "shared-directories";

/// How this operation's filter is recorded in a cursor: the `OwnerDirectoryId` and the
/// `SharedDirectoryIds` as the request listed them, through the one shared
/// [`crate::state::cursor_filter`] encoding. A later page must be asked for with the same
/// filter, so a token cannot silently resume a different listing.
fn cursor_filter(owner_directory_id: &str, shared_directory_ids: Option<&Vec<String>>) -> String {
    let shares = shared_directory_ids
        .map(|requested| requested.join(","))
        .unwrap_or_default();
    crate::state::cursor_filter(&[owner_directory_id, &shares])
}

