impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdatePipeline<Eng>
{
    type Input = UpdatePipelineInput;
    type Output = UpdatePipelineOutput;
    type Error = UpdatePipelineError;

    const NAME: &'static str = "UpdatePipeline";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_PIPELINE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_PIPELINE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        _ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            UpdatePipelineError::Modeled(UpdatePipelineErrorModeled::InternalFailureException(
                InternalFailureException {
                    message: "the IoT SiteWise store is unavailable".to_string(),
                },
            ))
        })?;
        let now = ::std::time::SystemTime::now();

        let key = crate::state::pipeline_key(&input.workspace_name, &input.pipeline_name);
        let mut store = state.lock();
        let record = store
            .pipelines
            .get_mut(&key)
            .ok_or_else(|| not_found(&input.pipeline_name))?;

        // "Only the fields provided in the request are updated; fields not included in
        // the request are preserved unchanged": an absent member keeps the value the
        // version this update builds on carried, and a present one replaces it.
        let description = input
            .description
            .clone()
            .or_else(|| record.current.description.clone());
        let environment_variables = input
            .environment_variables
            .clone()
            .or_else(|| record.current.environment_variables.clone());
        let computations = input
            .computations
            .clone()
            .unwrap_or_else(|| record.current.computations.clone());

        // The DAG rules hold for the list this update leaves the pipeline with, and are
        // checked BEFORE anything is written, so a refused update neither changes the
        // stored pipeline nor bumps its version.
        crate::state::check_compute_nodes(&computations).map_err(invalid_request)?;

        // The accepted configuration becomes a NEW version — `version` is "The new
        // version of the pipeline created by this update" — and the one it replaces is
        // kept, so a later read naming it still answers from it.
        record.record_update(description, environment_variables, computations, now);

        Ok(UpdatePipelineOutput {
            version: record.version_label(),
            status: record.status(now),
        })
    }
}

