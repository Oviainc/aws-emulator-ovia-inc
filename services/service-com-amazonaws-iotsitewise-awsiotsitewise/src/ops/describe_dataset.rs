impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeDataset<Eng>
{
    type Input = DescribeDatasetInput;
    type Output = DescribeDatasetOutput;
    type Error = DescribeDatasetError;

    const NAME: &'static str = "DescribeDataset";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_DATASET_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_DATASET_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            DescribeDatasetError::Modeled(DescribeDatasetErrorModeled::InternalFailureException(
                InternalFailureException {
                    message: "the IoT SiteWise store is unavailable".to_string(),
                },
            ))
        })?;
        let _ = ctx;
        let now = ::std::time::SystemTime::now();

        let store = state.lock();

        // A `workspaceName` the request names is resolved FIRST, as every
        // workspace-scoped entry point in this crate resolves the resource its
        // request names before the one nested in it: a request that is wrong in both
        // ways reports the resource that is absent. The workspace registry is the one
        // place that says which workspaces exist, and a create that puts a dataset in
        // a workspace resolves it there too, so no dataset can be stored under a
        // workspace the registry does not hold.
        if let Some(workspace) = input.workspace_name.as_deref() {
            if !store.workspaces.contains_key(workspace) {
                return Err(not_found(crate::state::RESOURCE_WORKSPACE, workspace));
            }
        }

        let dataset = store
            .datasets
            .get(&input.dataset_id)
            .filter(|dataset| {
                // `workspaceName` names the workspace that contains the dataset, so a
                // request that names one scopes the lookup: a dataset held by another
                // workspace, or by none, is not the dataset this request addresses.
                input.workspace_name.is_none() || input.workspace_name == dataset.workspace_name
            })
            // `datasetVersion` asks for ONE version of the dataset. This store keeps
            // only the version its last accepted write produced, so a request for any
            // other version names something it does not hold.
            .filter(|dataset| {
                input
                    .dataset_version
                    .as_ref()
                    .is_none_or(|version| *version == dataset.version_label())
            })
            .ok_or_else(|| not_found(crate::state::RESOURCE_DATASET, &input.dataset_id))?;

        Ok(DescribeDatasetOutput {
            dataset_id: dataset.id.clone(),
            dataset_arn: dataset.arn.clone(),
            dataset_name: dataset.name.clone(),
            // The model makes this member required while every member that writes it
            // is optional, so a dataset nobody described reports the empty string
            // rather than a description it was never given.
            dataset_description: dataset.description.clone().unwrap_or_default(),
            dataset_type: dataset.dataset_type.clone(),
            dataset_config: dataset.config.clone(),
            workspace_name: dataset.workspace_name.clone(),
            // A dataset carrying no metadata reports none, rather than an empty map it
            // was not given.
            metadata: (!dataset.metadata.is_empty()).then(|| dataset.metadata.clone()),
            dataset_source: dataset.source.clone(),
            dataset_status: dataset.status(now),
            dataset_creation_date: crate::state::to_date_time(dataset.creation_date),
            dataset_last_update_date: crate::state::to_date_time(dataset.last_update_date),
            dataset_version: Some(dataset.version_label()),
            // The enrichment the store knows about for this dataset, derived
            // from the enrichment jobs that name it the same way an enrichment
            // job's own reads derive its status and completion instant from the
            // record `CreateEnrichmentJob` persisted. A dataset no job names has
            // no enrichment to report, so this member stays absent for it.
            enrichment_status: store.dataset_enrichment(&dataset.id, now),
        })
    }
}

