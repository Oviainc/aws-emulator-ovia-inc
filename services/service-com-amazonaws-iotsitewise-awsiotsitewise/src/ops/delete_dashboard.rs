        // The dashboard goes, ARN and tags with it: the record owns its own tag set,
        // so dropping it is what makes the tagging operations stop resolving its ARN,
        // and what `DescribeDashboard` and the project's listing stop finding. Nothing
        // else in the store points AT a dashboard — a dashboard names the project it
        // was created in, never the other way round, and an access policy is a
        // resource of its own, addressed by its own id — so this one removal is the
        // whole deletion. The project the dashboard lived in stays: removing one of a
        // project's dashboards is no change to the project.
        //
