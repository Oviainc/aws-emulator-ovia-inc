impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CreateDashboard<Eng>
{
    type Input = CreateDashboardInput;
    type Output = CreateDashboardOutput;
    type Error = CreateDashboardError;

    const NAME: &'static str = "CreateDashboard";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_DASHBOARD_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_DASHBOARD_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 201u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            CreateDashboardError::Modeled(CreateDashboardErrorModeled::InternalFailureException(
                InternalFailureException {
                    message: "the IoT SiteWise store is unavailable".to_string(),
                },
            ))
        })?;
        let region = crate::state::request_region(ctx.parts());
        let now = ::std::time::SystemTime::now();

        // `TagMap`'s KEYS target `TagKey` (@length 1..128), which the framework's
        // constraint walk does not reach — it validates a map's values only — so the
        // bound is enforced here, in the same wording `TagResource` uses, and as the
        // client-input error this operation MODELS: its error list declares no
        // `ValidationException`, so a malformed request can only be
        // `InvalidRequestException` (400).
        for tag_key in input.tags.iter().flatten().map(|(tag_key, _)| tag_key) {
            crate::state::check_tag_key(tag_key).map_err(invalid_request)?;
        }

        // "The dashboard definition specified in a JSON literal": a body that is
        // not a JSON document states no definition, and storing it would let a
        // later read answer with one no IoT SiteWise Monitor client could render.
        // The modelled length bounds and pattern are enforced before this handler
        // runs and neither can express the JSON form, so this — like the write of
        // this crate's other member whose documentation names the JSON form — is
        // the member's own documented form, checked here.
        crate::state::check_json_document("dashboardDefinition", &input.dashboard_definition)
            .map_err(invalid_request)?;

        let mut store = state.lock();

        // `clientToken` makes this create idempotent, as the member documents: "A
        // unique case-sensitive identifier that you can provide to ensure the
        // idempotency of the request." A RETRY carries the token of the call it
        // repeats AND repeats that call's request, so it answers from the dashboard
        // THAT call minted and writes nothing. It is the FIRST thing decided,
        // because the call it repeats was already served — a replay stays the
        // answer the first call gave, whatever has changed since.
        //
        // A token already spent on a DIFFERENT request repeats no call, and this
        // create's answer carries nothing but the dashboard it minted: answering
        // from the earlier call would hand this caller a dashboard it never asked
        // for — under another name, with another definition, in whatever project
        // that call named — and mint nothing for the request it actually sent. Such
        // a request is therefore served as the fresh create it is, and the token's
        // record moves to the dashboard it mints: the token stops a repeat from
        // creating a second dashboard, it never turns another request into a
        // success that created nothing. The same rule every other create in this
        // crate applies, and the one `UpdateDashboard` applies to this resource.
        let fingerprint = crate::state::request_fingerprint(
            &[
                &input.project_id,
                &input.dashboard_name,
                &input.dashboard_description,
                &input.dashboard_definition,
            ],
            input.tags.as_ref(),
        );
        match store.idempotent_verdict(Self::NAME, input.client_token.as_deref(), &fingerprint) {
            crate::state::TokenVerdict::Replay(replayed) => {
                // One deleted since leaves the retry nothing to answer from, so that
                // retry is served as the fresh create it now is.
                if let Some(existing) = store.dashboards.get(&replayed) {
                    return Ok(CreateDashboardOutput {
                        dashboard_id: existing.id.clone(),
                        dashboard_arn: existing.arn.clone(),
                    });
                }
            }
            // A request that differs from the call its token was spent on is a
            // different create, served below exactly like one carrying no token.
            crate::state::TokenVerdict::Spent(_) | crate::state::TokenVerdict::Serve => {}
        }

        // A dashboard is created IN a project, so a `projectId` that resolves to no
        // stored project names no container for the dashboard to live in — the
        // absence this operation's modelled 404 states, in the one wording every
        // not-found refusal in this service carries. The same check `CreateProject`
        // makes of the portal it is given.
        if !store.projects.contains_key(&input.project_id) {
            return Err(CreateDashboardError::Modeled(
                CreateDashboardErrorModeled::ResourceNotFoundException(ResourceNotFoundException {
                    message: crate::state::not_found_message(
                        crate::state::RESOURCE_PROJECT,
                        &input.project_id,
                    ),
                }),
            ));
        }

        // The store is bounded: a create is the only thing that adds a dashboard and
        // only `DeleteDashboard` removes one, so past the cap this is a quota refusal.
        if store.dashboards.len() >= crate::state::MAX_DASHBOARDS {
            return Err(CreateDashboardError::Modeled(
                CreateDashboardErrorModeled::LimitExceededException(LimitExceededException {
                    message: format!(
                        "This emulator holds at most {} dashboards.",
                        crate::state::MAX_DASHBOARDS
                    ),
                }),
            ));
        }

        let dashboard_id = loop {
            let candidate = crate::state::new_id();
            if !store.dashboards.contains_key(&candidate) {
                break candidate;
            }
        };

        // The project the dashboard belongs to is held on the record, which is what
        // every read of the dashboard reports, and is not an update's to change.
        //
        // The caller-owned members are MOVED out of the request rather than cloned:
        // a definition literal runs to 204800 characters, so a copy of it would be
        // the largest allocation this handler makes and nothing reads `input` again.
        let record = crate::state::DashboardRecord {
            id: dashboard_id.clone(),
            arn: crate::state::dashboard_arn(&region, &dashboard_id),
            project_id: input.project_id,
            name: input.dashboard_name,
            description: input.dashboard_description,
            definition: input.dashboard_definition,
            creation_date: now,
            last_update_date: now,
            // The token this create carried, recorded as part of what it asked for.
            client_token: input.client_token.clone(),
            tags: input.tags.unwrap_or_default(),
        };

        let output = CreateDashboardOutput {
            dashboard_id: record.id.clone(),
            dashboard_arn: record.arn.clone(),
        };

        store.dashboards.insert(record.id.clone(), record);
        // The token is spent only now that the create has succeeded: a refused
        // request created nothing, so the caller may send its token again.
        store.record_idempotent_call(
            Self::NAME,
            input.client_token.as_deref(),
            fingerprint,
            &dashboard_id,
            now,
        );

        Ok(output)
    }
}

