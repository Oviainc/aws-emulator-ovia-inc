impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DeletePipeline<Eng>
{
    type Input = DeletePipelineInput;
    type Output = DeletePipelineOutput;
    type Error = DeletePipelineError;

    const NAME: &'static str = "DeletePipeline";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DELETE_PIPELINE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DELETE_PIPELINE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        _ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            DeletePipelineError::Modeled(DeletePipelineErrorModeled::InternalFailureException(
                InternalFailureException {
                    message: "the IoT SiteWise store is unavailable".to_string(),
                },
            ))
        })?;

        let key = crate::state::pipeline_key(&input.workspace_name, &input.pipeline_name);
        let mut store = state.lock();
        // A pipeline is identified by its workspace and its own name, so the lookup is
        // scoped to the workspace the request names and an absence there is the
        // modelled 404 — including for a workspace that holds no pipeline of that name.
        let record = store
            .pipelines
            .get(&key)
            .ok_or_else(|| not_found(&input.pipeline_name))?;
        let (name, workspace, arn) = (
            record.name.clone(),
            record.workspace_name.clone(),
            record.arn.clone(),
        );

        // "A pipeline cannot be deleted if it has any active executions. Wait for all
        // executions to complete before attempting to delete the pipeline, or use
        // CancelPipelineExecution to stop a running execution." An execution is active
        // until it reaches a state it stays in, so one that has not begun blocks the
        // delete as surely as one that is running. The precondition is evaluated
        // BEFORE anything is removed, so a refused delete leaves the pipeline, its
        // versions and its executions exactly as they were.
        let active = store.active_pipeline_execution_count(&workspace, &name);
        if active > 0 {
            return Err(DeletePipelineError::Modeled(
                DeletePipelineErrorModeled::ConflictingOperationException(
                    ConflictingOperationException {
                        message: format!(
                            "The pipeline {name} in the workspace {workspace} has {active} \
                             execution(s) that have not completed. Wait for them to complete, \
                             or cancel them, before deleting it."
                        ),
                        resource_id: name,
                        resource_arn: arn,
                    },
                ),
            ));
        }

        // The pipeline and everything keyed off it go away, so no later read can still
        // see it: a describe of the pipeline, or of an execution it ran, resolves to
        // nothing.
        store.forget_pipeline(&workspace, &input.pipeline_name);

        Ok(DeletePipelineOutput {
            // The lifecycle state of a resource this call has removed, as this
            // service's other deletes report it.
            status: ResourceStatus {
                state: Some(crate::state::STATE_DELETING.to_string()),
                error: None,
            },
        })
    }
}

