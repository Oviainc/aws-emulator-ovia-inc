/// Decode a `nextToken` back into the asset model id it resumes from.
fn decode_token(token: &str) -> Result<String, ListAssetModelsError> {
    ::hex::decode(token)
        .ok()
        .and_then(|bytes| String::from_utf8(bytes).ok())
        .ok_or_else(invalid_token)
}

