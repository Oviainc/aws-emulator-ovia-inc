/// Decode a `nextToken` back into the asset id it resumes from.
fn decode_token(token: &str) -> Result<String, ListAssetsError> {
    ::hex::decode(token)
        .ok()
        .and_then(|bytes| String::from_utf8(bytes).ok())
        .ok_or_else(invalid_token)
}

