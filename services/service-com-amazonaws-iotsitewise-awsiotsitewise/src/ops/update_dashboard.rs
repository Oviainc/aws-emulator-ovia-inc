impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateDashboard<Eng>
{
    type Input = UpdateDashboardInput;
    type Output = UpdateDashboardOutput;
    type Error = UpdateDashboardError;

    const NAME: &'static str = "UpdateDashboard";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_DASHBOARD_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_DASHBOARD_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        _ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            UpdateDashboardError::Modeled(UpdateDashboardErrorModeled::InternalFailureException(
                InternalFailureException {
                    message: "the IoT SiteWise store is unavailable".to_string(),
                },
            ))
        })?;
        let now = ::std::time::SystemTime::now();

        // "The new dashboard definition, as specified in a JSON literal": a body
        // that is not a JSON document states no definition, and installing it on
        // the dashboard would let a later read answer with one no IoT SiteWise
        // Monitor client could render. The same check the create of this member
        // makes, so neither write path can store a definition the other would
        // refuse — and made before the request is resolved against the store,
        // because a malformed request is refused whatever the store holds.
        crate::state::check_json_document("dashboardDefinition", &input.dashboard_definition)
            .map_err(invalid_request)?;

        // `clientToken` makes this update idempotent, as the member documents: "A
        // unique case-sensitive identifier that you can provide to ensure the
        // idempotency of the request." A RETRY carries the token of the call it
        // repeats AND repeats that call's request, so it succeeds and writes nothing —
        // it does not write the dashboard a second time. It is the FIRST thing
        // decided, because the call it repeats was already served.
        //
        // A token already spent on a DIFFERENT request names no answer this operation
        // could replay: its output carries no member of that earlier call, so the 200
        // it would give states only that THIS request was applied. Such a request is
        // therefore served as the fresh update it is, and the token's record moves to
        // it — the token stops a repeat from being applied twice, it never turns
        // another request into a success that wrote nothing.
        let mut store = state.lock();

        let fingerprint = crate::state::request_fingerprint(
            &[
                &input.dashboard_id,
                &input.dashboard_name,
                &input.dashboard_description,
                &input.dashboard_definition,
            ],
            None,
        );
        match store.idempotent_verdict(Self::NAME, input.client_token.as_deref(), &fingerprint) {
            crate::state::TokenVerdict::Replay(replayed) => {
                // A dashboard deleted since leaves the retry nothing to answer from,
                // so that retry is served as the fresh update it now is — which is the
                // not-found refusal below.
                if store.dashboards.contains_key(&replayed) {
                    return Ok(UpdateDashboardOutput {});
                }
            }
            // A request that differs from the call its token was spent on is a
            // different update, served below exactly like one carrying no token.
            crate::state::TokenVerdict::Spent(_) | crate::state::TokenVerdict::Serve => {}
        }

        let dashboard = store
            .dashboards
            .get_mut(&input.dashboard_id)
            .ok_or_else(|| not_found(&input.dashboard_id))?;
        // The request describes the dashboard's NEW state: its name and definition
        // are required and its description is the one optional member, so an omitted
        // description clears the stored one rather than keeping it. What the request
        // does not carry — the dashboard's id, ARN, project, tags and creation date —
        // is not this call's to change.
        dashboard.apply_update(
            input.dashboard_name,
            input.dashboard_description,
            input.dashboard_definition,
            now,
        );

        // The token is spent only now that the update has succeeded: a refused
        // request changed nothing, so the caller may send its token again.
        store.record_idempotent_call(
            Self::NAME,
            input.client_token.as_deref(),
            fingerprint,
            &input.dashboard_id,
            now,
        );

        Ok(UpdateDashboardOutput {})
    }
}

