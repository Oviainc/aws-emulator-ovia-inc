/// Whether `arn` is an entitlement ARN this service could have minted: the prefix
/// [`has_mintable_arn_prefix`] describes for the `entitlement` resource type, then the
/// entitlement id [`entitlement_resource_fragment`] mints and a non-empty name.
///
/// The model puts no pattern on `Entitlement$EntitlementArn`
/// (`smithy_query(query="shape",shape="Entitlement",member="EntitlementArn")`: it targets
/// `String`), and no operation constrains an entitlement's name either, so the name is
/// only required to carry something: a name that itself holds the ARN segment separator
/// still yields an ARN this function accepts, which is why the trailing segments are
/// walked rather than counted.
///
/// ListEntitlements' `NextToken` is the entitlement ARN its next page resumes at, so a
/// token the service never minted is a semantic error in the request rather than a key to
/// page from. The entitlement it names need NOT still exist: paging must survive a revoke
/// between pages.
pub fn is_mintable_entitlement_arn(arn: &str) -> bool {
    let segments: Vec<&str> = arn.split(':').collect();
    if segments.len() < 8 || !has_mintable_arn_prefix(&segments, "entitlement") {
        return false;
    }
    let entitlement_id = segments[6];
    !entitlement_id.is_empty()
        && entitlement_id
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-')
        && segments[7..].iter().any(|segment| !segment.is_empty())
}

/// Whether `arn` is a flow ARN this service could have minted.
///
/// This function is the crate's ONE encoding of the modelled `FlowArn` constraint
/// (`smithy_query(query="shape",shape="FlowArn")`:
/// `^arn:(aws[a-zA-Z-]*):mediaconnect:[a-z0-9-]+:[0-9]{12}:flow:[a-zA-Z0-9-]+:[a-zA-Z0-9_-]+$`),
/// checked segment by segment: the `arn` prefix, an `aws*` partition, this service's
/// namespace, a region token, a 12-digit account id, the `flow` resource type, the flow
/// id and the flow name. The integration test asserts minted ARNs through this same
/// function, so there is no second spelling that can drift from it.
///
/// ListFlows' `NextToken` is the ARN its next page resumes at, so a token the service
/// never minted is a semantic error in the request rather than a key to page from. The
/// flow it names need NOT still exist: paging must survive a delete between pages.
pub fn is_mintable_flow_arn(arn: &str) -> bool {
    let segments: Vec<&str> = arn.split(':').collect();
    let [.., flow_id, flow_name] = segments.as_slice() else {
        return false;
    };
    segments.len() == 8
        && has_mintable_arn_prefix(&segments, "flow")
        && !flow_id.is_empty()
        && flow_id
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-')
        && is_valid_flow_name(flow_name)
}

/// Whether `label` satisfies the `@pattern` the flow operations' own `{FlowArn}` label
/// declares, `^arn:.+:mediaconnect.+:flow:.+$`
/// (`smithy_query(query="shape",shape="DescribeFlowRequest")` — every flow operation's
/// `FlowArn` member declares that same wider pattern in place of the narrow one the
/// `FlowArn` SHAPE carries; see the note on `DescribeFlowInput` in `crate::ops::types`).
///
/// This is the judgement on the LABEL, not on the store: a label that satisfies it names a
/// flow ARN whether or not this service holds that flow, and one that does not satisfy it
/// names no flow at all. Checked the way the pattern reads — the `arn:` prefix, then at
/// least one character before `:mediaconnect`, then at least one character before `:flow:`,
/// then a non-empty remainder — rather than by counting fields, because the pattern
/// constrains neither the partition, the Region nor the account field.
///
/// TOTAL for every `label` a request can carry: the walk is over byte offsets this crate
/// obtained from `match_indices` and `find` on `label` itself, with no slicing at an offset
/// of its own making, no `unwrap`/`expect` and no arithmetic on caller input beyond adding
/// the length of a literal to a match offset.
pub fn satisfies_flow_arn_label_pattern(label: &str) -> bool {
    const SERVICE_FIELD: &str = ":mediaconnect";
    const FLOW_FIELD: &str = ":flow:";
    let Some(after_prefix) = label.strip_prefix("arn:") else {
        return false;
    };
    after_prefix
        .match_indices(SERVICE_FIELD)
        // `.+` before `:mediaconnect`: at least one character of the partition field.
        .filter(|(index, _)| *index > 0)
        .any(|(index, matched)| {
            let after_service = &after_prefix[index + matched.len()..];
            after_service
                .match_indices(FLOW_FIELD)
                // `.+` before `:flow:`, then `.+` after it.
                .any(|(flow_at, matched)| {
                    flow_at > 0 && after_service.len() > flow_at + matched.len()
                })
        })
}

/// The reason phrase a request that resolved nothing before reaching a resource lookup is
/// reported as not found by.
///
/// A `{FlowArn}` label that is not a flow ARN at all addresses no flow and so reaches no
/// lookup: there is no resource for the message to name, and the request's own label is
/// not one — it is caller-supplied text that this service's refusal does not echo. The
/// 404 therefore carries this generic reason inside the service's not-found envelope
/// ([`not_found_message`]), which is the whole of that message.
pub const UNRESOLVED_PATH_NOT_FOUND_REASON: &str = "404 Not Found";

/// MediaConnect's `NotFoundException` message for a request whose `{FlowArn}` label
/// resolved no flow.
///
/// The ONE wording of that refusal, shared by every operation that takes a flow ARN as a
/// path label, so DescribeFlow and its siblings cannot word one refusal two ways:
///
/// * a label that IS a flow ARN ([`satisfies_flow_arn_label_pattern`]) but names no stored
///   flow reached the lookup and resolved nothing, so the message names the ARN that
///   resolved nothing ([`not_found_message`]);
/// * a label that is not a flow ARN never got that far, so the message carries
///   [`UNRESOLVED_PATH_NOT_FOUND_REASON`] instead of the label.
pub fn flow_not_found_message(flow_arn: &str) -> String {
    if satisfies_flow_arn_label_pattern(flow_arn) {
        not_found_message(flow_arn)
    } else {
        not_found_message(UNRESOLVED_PATH_NOT_FOUND_REASON)
    }
}

