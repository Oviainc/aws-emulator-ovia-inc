/// The values `filter` names — the list the union member carries, whichever member it is.
fn filter_values(filter: &RouterOutputFilter) -> &[String] {
    match filter {
        RouterOutputFilter::RegionNames(values)
        | RouterOutputFilter::NetworkInterfaceArns(values)
        | RouterOutputFilter::RoutingScopes(values)
        | RouterOutputFilter::OutputTypes(values)
        | RouterOutputFilter::RoutedInputArns(values)
        | RouterOutputFilter::NameContains(values) => values,
    }
}

