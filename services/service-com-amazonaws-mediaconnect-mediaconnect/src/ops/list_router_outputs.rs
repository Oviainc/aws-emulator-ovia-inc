/// Whether `router_output` satisfies ONE filter of the request.
///
/// A `RouterOutputFilter` is a union whose member names the ATTRIBUTE of a router output to
/// select on and whose value is the list of values accepted for it, so an output satisfies
/// the filter exactly when its own value for that attribute is one the list names — and an
/// attribute the output does not carry (no interface for a configuration that egresses into
/// another AWS resource, no routed input while nothing is routed) is not among them. The
/// `NameContains` member selects on CONTAINMENT instead of equality, so there it is enough
/// that the output's name contains one of the fragments.
fn satisfies_filter(router_output: &StoredRouterOutput, filter: &RouterOutputFilter) -> bool {
    match filter {
        RouterOutputFilter::RegionNames(region_names) => region_names
            .iter()
            .any(|region| region.as_str() == router_output.region_name),
        RouterOutputFilter::NetworkInterfaceArns(interface_arns) => {
            crate::state::router_output_network_interface_arn(&router_output.configuration)
                .is_some_and(|interface_arn| {
                    interface_arns
                        .iter()
                        .any(|candidate| candidate.as_str() == interface_arn)
                })
        }
        RouterOutputFilter::RoutingScopes(routing_scopes) => routing_scopes
            .iter()
            .any(|scope| scope.as_str() == router_output.routing_scope),
        RouterOutputFilter::OutputTypes(output_types) => output_types
            .iter()
            .any(|output_type| output_type.as_str() == router_output.output_type()),
        RouterOutputFilter::RoutedInputArns(routed_input_arns) => router_output
            .routed_input_arn
            .as_deref()
            .is_some_and(|routed_input_arn| {
                routed_input_arns
                    .iter()
                    .any(|candidate| candidate.as_str() == routed_input_arn)
            }),
        RouterOutputFilter::NameContains(fragments) => fragments
            .iter()
            .any(|fragment| router_output.name.contains(fragment.as_str())),
    }
}

