impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeFlow<Eng>
{
    type Input = DescribeFlowInput;
    type Output = DescribeFlowOutput;
    type Error = DescribeFlowError;

    const NAME: &'static str = "DescribeFlow";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_FLOW_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_FLOW_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(DescribeFlowErrorModeled::InternalServerErrorException(
                InternalServerErrorException {
                    message: "the mediaconnect flow store is unavailable".to_string(),
                },
            )
            .into());
        };

        let mut store = state.lock();
        // The ONLY write this reporting operation makes: a status change the clock
        // already made due (see `crate::state::TRANSITION_SPAN`) was owed at that
        // instant whether or not anybody called, so it is materialised before reporting.
        store.settle_due_transitions(::std::time::SystemTime::now());

        // The `{FlowArn}` label is an IDENTIFIER, so the store resolves it: a label this
        // store does not hold (one never minted, one whose flow was deleted, or one that
        // is not an ARN at all) addresses no flow and is refused `NotFoundException`
        // rather than judged against the `FlowArn` shape's pattern. See the note on
        // `DescribeFlowInput` in `super::types` (`describe_flow_types.rs`). The refusal is
        // worded by `crate::state::flow_not_found_message`, which names the ARN that
        // resolved nothing only when the label was a flow ARN at all.
        let Some(flow) = store.flows.get(&input.flow_arn) else {
            return Err(DescribeFlowErrorModeled::NotFoundException(NotFoundException {
                message: crate::state::flow_not_found_message(&input.flow_arn),
            })
            .into());
        };

        Ok(DescribeFlowOutput {
            flow: Some(flow.to_flow()),
            // `Messages`: "Any errors that apply currently to the flow. If there are no
            // errors, MediaConnect will not include this field in the response." A flow
            // this emulator serves carries no errors, so the member stays absent.
            messages: None,
        })
    }
}
