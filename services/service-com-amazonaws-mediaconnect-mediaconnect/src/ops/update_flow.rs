impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateFlow<Eng>
{
    type Input = UpdateFlowInput;
    type Output = UpdateFlowResponse;
    type Error = UpdateFlowError;

    const NAME: &'static str = "UpdateFlow";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_FLOW_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_FLOW_RESPONSE_SCHEMA;
    const SUCCESS_STATUS: u16 = 202u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(UpdateFlowErrorModeled::InternalServerErrorException(
                InternalServerErrorException {
                    message: "the mediaconnect flow store is unavailable".to_string(),
                },
            )
            .into());
        };

        let now = ::std::time::SystemTime::now();
        let mut store = state.lock();
        // The only write this operation owes beyond the request: a status change the
        // clock already made due is materialised before the flow is read or written.
        store.settle_due_transitions(now);

        let Some(flow) = store.flows.get_mut(&input.flow_arn) else {
            return Err(not_found(&input.flow_arn));
        };

        // What each setting becomes once this request is applied: the request's value
        // where it carries one, the stored value where it does not.
        let flow_size = input.flow_size.clone().or_else(|| flow.flow_size.clone());
        let maintenance = match input.maintenance.as_ref() {
            Some(update) => Some(merged_maintenance(flow.maintenance.as_ref(), update)),
            None => flow.maintenance.clone(),
        };
        let source_failover_config = match input.source_failover_config.as_ref() {
            Some(update) => Some(crate::state::merged_failover_config(
                flow.source_failover_config.as_ref(),
                update,
            )),
            None => flow.source_failover_config.clone(),
        };
        let source_monitoring_config = input
            .source_monitoring_config
            .clone()
            .or_else(|| flow.source_monitoring_config.clone());
        let ndi_config = input
            .ndi_config
            .clone()
            .or_else(|| flow.ndi_config.clone());
        let encoding_config = input
            .encoding_config
            .clone()
            .or_else(|| flow.encoding_config.clone());

        // The maintenance window the request asks for has to be expressible as one: the
        // two members the request shape leaves free-form carry documented formats, checked
        // through the one function in `crate::state` every path that writes a window checks
        // them with (CreateFlow checks the create shape there too).
        if let Some(update) = input.maintenance.as_ref() {
            if let Some(rejection) = crate::state::maintenance_window_rejection(
                update.maintenance_start_hour.as_deref(),
                update.maintenance_scheduled_date.as_deref(),
            ) {
                return Err(bad_request(rejection));
            }
        }

        // Every refusal below reads the members THIS request carries, not the merged
        // result: a request that does not touch a setting may not be refused for a stored
        // value it did not introduce.
        //
        // NDI needs the larger flow: "if you have a MEDIUM flow and you want to change the
        // flow source to NDI: first, use the UpdateFlow operation to upgrade the flow size
        // to LARGE" (this operation's own documentation). Both the request that enables NDI
        // and the one that changes the size are checked, against the size and NDI state the
        // flow ends up with, because either member alone can break the pair.
        if input.ndi_config.is_some() || input.flow_size.is_some() {
            // What uses NDI on the flow this request leaves behind, worded for the refusal
            // `crate::state::ndi_flow_size_rejection` states — the same markers CreateFlow
            // and the add paths read.
            let ndi_feature = if crate::state::ndi_is_enabled(ndi_config.as_ref()) {
                Some(format!("NdiConfig.NdiState {STATE_ENABLED}"))
            } else if input.flow_size.is_some() {
                // What the flow already HOLDS is the other half of the same pair: "if
                // you're switching from an NDI source to a transport stream (TS) source and
                // want to downgrade the flow size: first, use the UpdateFlowSource
                // operation to change the flow source type" (this operation's own
                // documentation). A stored source OR a stored output on the NDI transport
                // makes the flow one that includes NDI, exactly as it does on the create
                // and add sides, so both are read here. Only a request that changes the
                // size is refused for them.
                flow.sources
                    .iter()
                    .find(|source| crate::state::stored_source_uses_ndi(source))
                    .map(|source| format!("The NDI source {:?}", source.name))
                    .or_else(|| {
                        flow.outputs
                            .iter()
                            .find(|output| crate::state::stored_output_uses_ndi(output))
                            .map(|output| format!("The NDI output {:?}", output.name))
                    })
            } else {
                None
            };
            if let Some(rejection) = ndi_feature.as_deref().and_then(|feature| {
                crate::state::ndi_flow_size_rejection(feature, flow_size.as_deref())
            }) {
                return Err(bad_request(rejection));
            }
        }

        // The `NdiConfig` a request REPLACES the stored one with is kept verbatim on the
        // flow record, so the discovery servers it declares are bounded before they are
        // stored — the count the model publishes, read from the one place this crate words
        // it, so a config this update stores is one CreateFlow would also have stored (see
        // `crate::state::MAX_NDI_DISCOVERY_SERVERS`). Only a request that carries the member
        // is checked: one that does not touch it may not be refused for a stored value it
        // did not introduce.
        if let Some(rejection) =
            crate::state::ndi_discovery_servers_rejection("NdiConfig", input.ndi_config.as_ref())
        {
            return Err(bad_request(rejection));
        }

        let requested_failover = input.source_failover_config.as_ref();

        // "If the state is inactive, the flow can have only one source. If the state is
        // active, the flow can have one or two sources." (`UpdateFailoverConfig$State`).
        // The request moves the bound rather than the source count, so it is checked
        // against the failover config the flow ENDS UP with, under the sources it already
        // holds — through the one function the create and add paths read the bound from
        // (`crate::state::max_flow_sources`).
        // A request that does not touch the failover setting is never refused for the
        // source count already in the store.
        let bound_rejection = requested_failover.and_then(|_| {
            crate::state::flow_source_bound_rejection(
                source_failover_config.as_ref(),
                flow.sources.len(),
                0,
            )
        });
        if let Some(rejection) = bound_rejection {
            return Err(bad_request(rejection));
        }

        // `SourcePriority$PrimarySource` is "the name of the source you choose as the
        // primary source for this flow", so it has to name a source the flow has —
        // resolved through the one function every path that writes a source priority
        // resolves it with (CreateFlow resolves the create shape there too).
        if let Some(rejection) = crate::state::flow_primary_source_rejection(
            requested_failover.and_then(|config| config.source_priority.as_ref()),
            flow.sources.iter().map(|source| source.name.as_str()),
        ) {
            return Err(bad_request(rejection));
        }

        flow.flow_size = flow_size;
        flow.maintenance = maintenance;
        flow.source_failover_config = source_failover_config;
        flow.source_monitoring_config = source_monitoring_config;
        flow.ndi_config = ndi_config;
        flow.encoding_config = encoding_config;

        // The response is the STORED record — `flow` is the record in the store, so this
        // reads back exactly what was just written, never the request.
        Ok(UpdateFlowResponse {
            flow: Some(flow.to_flow()),
        })
    }
}
