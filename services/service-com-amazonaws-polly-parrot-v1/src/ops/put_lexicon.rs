//! @op PutLexicon
//!
//! Stores a PLS pronunciation lexicon under its name, deriving the attributes
//! `GetLexicon` and `ListLexicons` report from the document itself.
//!
//! The PLS document is parsed with a real XML reader (`quick-xml`), never scanned as
//! text: `Alphabet` is the `<lexicon>` element's `alphabet` attribute, `LanguageCode`
//! its `xml:lang`, and `LexemesCount` the number of `<lexeme>` elements. A store is an
//! INSERT-OR-REPLACE keyed by name, so re-putting a name overwrites the entry and
//! moves its `LastModified` forward rather than adding a second one.
//!
//! The error channel is the model's: a document that is not a PLS lexicon is
//! `InvalidLexiconException`, an `alphabet` outside the set the model's
//! `UnsupportedPlsAlphabetException` documentation lists is
//! `UnsupportedPlsAlphabetException`, and an `xml:lang` naming no language this
//! service's `LanguageCode` enum carries is `UnsupportedPlsLanguageException`.
//!
//! Two of Amazon Polly's published lexicon quotas are enforced here, and they are
//! also what bounds the store a caller can grow: [`MAX_LEXICON_CHARACTERS`] per
//! lexicon (`LexiconSizeExceededException`) and [`MAX_LEXICONS`] entries
//! (`MaxLexiconsNumberExceededException`).
//!
//! @generated by the emulator core scaffold op-stub generator (header), implemented
//! by hand below. Shared types live in `super::types`; the error channel in
//! `crate::scaffolded`.
//!
//! ---
