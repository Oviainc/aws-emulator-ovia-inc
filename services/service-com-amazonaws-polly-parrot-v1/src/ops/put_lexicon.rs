impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for PutLexicon<Eng>
{
    type Input = PutLexiconInput;
    type Output = PutLexiconOutput;
    type Error = PutLexiconError;

    const NAME: &'static str = "PutLexicon";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::PUT_LEXICON_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::PUT_LEXICON_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // The size cap comes first: it bounds the work done on the request as well as
        // what the store keeps, so an oversized document is refused before it is
        // parsed.
        let characters = input.content.chars().count();
        if characters > MAX_LEXICON_CHARACTERS {
            return Err(PutLexiconErrorModeled::LexiconSizeExceededException(
                LexiconSizeExceededException {
                    message: Some(format!(
                        "the maximum size of the specified lexicon would be exceeded by this \
                         operation: {characters} characters, maximum {MAX_LEXICON_CHARACTERS}"
                    )),
                },
            )
            .into());
        }

        let parsed = parse_pls(&input.content)?;

        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            PutLexiconErrorModeled::ServiceFailureException(ServiceFailureException {
                message: Some("the Amazon Polly lexicon store is unavailable".to_string()),
            })
        })?;

        let region = crate::state::request_region(ctx.parts());
        let stored = crate::state::StoredLexicon {
            lexicon_arn: ::engine::emulator_arn(
                "polly",
                &region,
                &format!("lexicon/{}", input.name),
            ),
            alphabet: parsed.alphabet,
            language_code: parsed.language_code,
            lexemes_count: parsed.lexemes_count,
            // `LexiconAttributes$Size` is documented as "Total size of the lexicon,
            // in characters", so it counts characters of `Content`, not bytes.
            size: i32::try_from(characters).unwrap_or(i32::MAX),
            last_modified: ::std::time::SystemTime::now(),
            name: input.name.clone(),
            content: input.content,
        };

        let mut guard = state.lock();
        // The count cap is checked against the store under the same lock that
        // inserts, so concurrent puts cannot both pass it. Replacing a name already
        // stored adds no entry, so it is never refused here.
        if !guard.lexicons.contains_key(&input.name) && guard.lexicons.len() >= MAX_LEXICONS {
            return Err(PutLexiconErrorModeled::MaxLexiconsNumberExceededException(
                MaxLexiconsNumberExceededException {
                    message: Some(format!(
                        "the maximum number of lexicons would be exceeded by this operation: \
                         {MAX_LEXICONS} lexicons are already stored"
                    )),
                },
            )
            .into());
        }
        // INSERT-OR-REPLACE: the operation is documented as "If a lexicon with the
        // same name already exists in the region, it is overwritten by the new
        // lexicon", so the name is the whole key.
        guard.lexicons.insert(input.name, stored);

        Ok(PutLexiconOutput {})
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const IPA_LEXICON: &str = r#"<?xml version="1.0" encoding="UTF-8"?>
<lexicon version="1.0"
      xmlns="http://www.w3.org/2005/01/pronunciation-lexicon"
      xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
      alphabet="ipa" xml:lang="en-US">
  <lexeme><grapheme>W3C</grapheme><alias>World Wide Web Consortium</alias></lexeme>
  <lexeme><grapheme>PLS</grapheme><phoneme>ˈplɪs</phoneme></lexeme>
</lexicon>"#;

    #[test]
    fn attributes_are_read_from_the_document() {
        let parsed = parse_pls(IPA_LEXICON).expect("a valid PLS lexicon parses");
        assert_eq!(
            parsed,
            ParsedLexicon {
                alphabet: Some("ipa".to_string()),
                language_code: Some("en-US".to_string()),
                lexemes_count: 2,
            },
            "the attributes must come from the document"
        );
    }

    #[test]
    fn a_document_that_is_not_a_lexicon_is_rejected() {
        for (case, content) in [
            ("not xml", "this is not xml at all <"),
            ("other root", "<speak>hello</speak>"),
            ("empty", ""),
        ] {
            let outcome = parse_pls(content);
            assert!(
                matches!(outcome, Err(PlsRejection::NotALexicon(_))),
                "case {case:?}: expected NotALexicon, got {outcome:?}"
            );
        }
    }

    #[test]
    fn alphabet_and_language_are_checked_against_the_model() {
        for alphabet in SUPPORTED_PLS_ALPHABETS {
            let content =
                format!(r#"<lexicon version="1.0" alphabet="{alphabet}" xml:lang="en-US"/>"#);
            let parsed = parse_pls(&content);
            assert!(
                parsed.is_ok(),
                "alphabet {alphabet:?}: expected acceptance, got {parsed:?}"
            );
        }
        let bogus = parse_pls(r#"<lexicon version="1.0" alphabet="x-klingon" xml:lang="en-US"/>"#);
        assert!(
            matches!(bogus, Err(PlsRejection::UnsupportedAlphabet(ref a)) if a == "x-klingon"),
            "expected UnsupportedAlphabet, got {bogus:?}"
        );
        let bad_language = parse_pls(r#"<lexicon version="1.0" alphabet="ipa" xml:lang="xx-ZZ"/>"#);
        assert!(
            matches!(bad_language, Err(PlsRejection::UnsupportedLanguage(ref l)) if l == "xx-ZZ"),
            "expected UnsupportedLanguage, got {bad_language:?}"
        );
    }

    #[test]
    fn a_primary_language_subtag_is_a_supported_language() {
        for language in ["en", "en-GB", "arb", "cmn-CN", "yue-CN"] {
            assert!(
                language_is_supported(language),
                "language {language:?}: expected supported"
            );
        }
        for language in ["xx", "klingon", ""] {
            assert!(
                !language_is_supported(language),
                "language {language:?}: expected unsupported"
            );
        }
    }
}
