//! @op PutLexicon
//!
//! Stores a PLS pronunciation lexicon under its name, deriving the attributes
//! `GetLexicon` and `ListLexicons` report from the document itself.
//!
//! The PLS document is parsed with a real XML reader (`quick-xml`), never scanned as
//! text: `Alphabet` is the `<lexicon>` element's `alphabet` attribute, `LanguageCode`
//! its `xml:lang`, and `LexemesCount` the number of `<lexeme>` elements. A store is an
//! INSERT-OR-REPLACE keyed by name, so re-putting a name overwrites the entry and
//! moves its `LastModified` forward rather than adding a second one.
//!
//! The error channel is the model's: a document that is not a PLS lexicon — including
//! one declaring an `alphabet` Amazon Polly does not support — is
//! `InvalidLexiconException`, an `xml:lang` naming no language this service's
//! `LanguageCode` enum carries is `UnsupportedPlsLanguageException`, and a `<lexeme>`
//! whose replacement is longer than [`MAX_LEXEME_CHARACTERS`] is
//! `MaxLexemeLengthExceededException`.
//!
//! Three of Amazon Polly's published lexicon quotas are enforced here, and two of them
//! are also what bounds the store a caller can grow: [`MAX_LEXICON_CHARACTERS`] per
//! lexicon (`LexiconSizeExceededException`), [`MAX_LEXICONS`] entries
//! (`MaxLexiconsNumberExceededException`) and [`MAX_LEXEME_CHARACTERS`] per lexeme
//! replacement (`MaxLexemeLengthExceededException`).
//!
//! @generated by the emulator core scaffold op-stub generator (header), implemented
//! by hand below. Shared types live in `super::types`; the error channel in
//! `crate::scaffolded`.
//!
//! ---
//!
//! # Modeled contract for `PutLexicon`
//!
//! What AWS documents for this operation, from this service's Smithy model. HTML is
//! stripped and long entries are clipped at ` …`. For the FULL text of any one item,
//! ask the model rather than reading the raw JSON:
//!
