//! @op PutLexicon
//!
//! Stores a PLS pronunciation lexicon under its name in the Region the call was
//! signed for, deriving the attributes `GetLexicon` and `ListLexicons` report from the
//! document itself.
//!
//! The PLS document is parsed with a real namespace-aware XML reader (`quick-xml`),
//! never scanned as text: `Alphabet` is the `<lexicon>` element's `alphabet`
//! attribute, `LanguageCode` the language its `xml:lang` names — in the spelling the
//! model's own `LanguageCode` enum uses for it, because that enum is what the reported
//! member targets — and `LexemesCount` the number of `<lexeme>` elements. A store is an INSERT-OR-REPLACE keyed by the REGION and the
//! name, so re-putting a name in that Region overwrites the entry and moves its
//! `LastModified` forward rather than adding a second one, while a lexicon of another
//! Region is neither read nor replaced.
//!
//! A document element that does not DECLARE itself a PLS 1.0 lexicon — `<lexicon>` in
//! the [`PLS_NAMESPACE`] carrying `version="`[`PLS_VERSION`]`"` and an `xml:lang` — is
//! not a lexicon this service can store, so nothing about it is stored; that is what
//! makes `LanguageCode` a value every stored lexicon has rather than an optional one.
//!
//! The error channel is the model's: a document that is not a PLS lexicon — including
//! one declaring, ANYWHERE PLS admits the attribute, an `alphabet` Amazon Polly does
//! not support — is `InvalidLexiconException`, an `xml:lang` naming no language this service's
//! `LanguageCode` enum carries is `UnsupportedPlsLanguageException`, and a `<lexeme>`
//! whose replacement is longer than [`MAX_LEXEME_CHARACTERS`] is
//! `MaxLexemeLengthExceededException`.
//!
//! Three of Amazon Polly's published lexicon quotas are enforced here, and two of them
//! are also what bounds the store a caller can grow: [`MAX_LEXICON_CHARACTERS`] per
//! lexicon (`LexiconSizeExceededException`), [`MAX_LEXICONS`] entries per Region
//! (`MaxLexiconsNumberExceededException`) and [`MAX_LEXEME_CHARACTERS`] per lexeme
//! replacement (`MaxLexemeLengthExceededException`). Because the Region is the
//! caller's own choice of credential scope, [`MAX_STORED_LEXICONS`] bounds the store
//! across every Region as well.
//!
//! @generated by the emulator core scaffold op-stub generator (header), implemented
//! by hand below. Shared types live in `super::types`; the error channel in
//! `crate::scaffolded`.
//!
//! ---
