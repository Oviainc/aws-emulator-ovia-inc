/// The largest lexicon this service stores, in characters.
///
/// Amazon Polly's published service quotas for lexicons ("Quotas in Amazon Polly"):
/// a lexicon is at most 4,000 characters. It is also THE MEMORY BOUND on a single
/// stored entry: `Content` carries no modeled length constraint, so without this cap
/// a caller decides how much of the emulator's heap one lexicon occupies.
pub const MAX_LEXICON_CHARACTERS: usize = 4_000;

/// The largest number of lexicons this service stores in ONE Region.
///
/// The same published quotas: 100 lexicons per Region. A lexicon is a regional
/// resource, so the count this bounds is the storing Region's own and a Region at the
/// cap does not stop a put in another one.
/// Replacing an existing name is not a new entry and is never refused by this cap.
pub const MAX_LEXICONS: usize = 100;

/// The largest number of lexicons this service stores across EVERY Region.
///
/// An emulator resource guard rather than a published quota, and the second half of
/// what bounds the store's memory: [`MAX_LEXICONS`] bounds one Region, the Region
/// comes from the caller's own credential scope and `Name` matches
/// `^[0-9A-Za-z]{1,20}$`, so the per-Region cap alone would let a caller grow the
/// store without limit by signing for another Region. Together with
/// [`MAX_LEXICON_CHARACTERS`] this caps the whole store. It is refused with the
/// modelled count error, which is the only count refusal `PutLexicon` declares.
pub const MAX_STORED_LEXICONS: usize = 1_000;

/// The longest replacement a single `<lexeme>` may carry, in characters.
///
/// Amazon Polly's published service quotas for lexicons ("Quotas in Amazon Polly")
/// cap a lexeme at 100 characters, which is the quota
/// `MaxLexemeLengthExceededException` reports (the model documents that shape as "The
/// maximum size of the lexeme would be exceeded by this operation"; the sentence the
/// service puts on the wire for the code is
/// [`crate::service::errors::MAX_LEXEME_LENGTH_EXCEEDED`]).
/// It applies to the REPLACEMENT a lexeme defines —
/// its `<alias>` or `<phoneme>` — which is the part Amazon Polly substitutes while
/// speaking; the `<grapheme>` being matched is bounded by
/// [`MAX_LEXICON_CHARACTERS`] along with the rest of the document.
pub const MAX_LEXEME_CHARACTERS: usize = 100;

/// The XML namespace a PLS lexicon's elements are bound to.
///
/// `PutLexicon` documents `Content` as a PLS document, and PLS 1.0 (the W3C
/// Pronunciation Lexicon Specification) declares its vocabulary — `lexicon`,
/// `lexeme`, `grapheme`, `phoneme`, `alias` — in this namespace. Every lexicon in
/// Amazon Polly's own lexicon documentation declares it on the document element.
pub const PLS_NAMESPACE: &str = "http://www.w3.org/2005/01/pronunciation-lexicon";

/// The `version` a PLS lexicon's document element declares.
///
/// PLS 1.0 makes `version` a required attribute of the `lexicon` element and fixes
/// its value at the version of the specification, so a document element declaring no
/// version — or another one — is not a PLS 1.0 lexicon.
pub const PLS_VERSION: &str = "1.0";

/// The phonetic alphabets a PLS lexicon may declare.
///
/// Quoted from this operation's `UnsupportedPlsAlphabetException` documentation in
