impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UploadArchive<Eng>
{
    type Input = UploadArchiveInput;
    type Output = UploadArchiveOutput;
    type Error = UploadArchiveError;

    const NAME: &'static str = "UploadArchive";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPLOAD_ARCHIVE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPLOAD_ARCHIVE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 201u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        use crate::state;

        let Some(store) = state::service_state(&*self.engine) else {
            return Err(UploadArchiveErrorModeled::ServiceUnavailableException(
                state::service_unavailable(state::NO_STORE_MESSAGE),
            )
            .into());
        };

        let region = state::request_region(ctx);
        let account_id = match state::resolve_account(&input.account_id) {
            Ok(account_id) => account_id,
            Err(refusal) => {
                return Err(UploadArchiveErrorModeled::InvalidParameterValueException(refusal).into())
            }
        };
        let vault_name = input.vault_name;

        // The checksum is computed over the bytes this request carried, never echoed
        // from the request header: the header is the client's CLAIM about the content,
        // and "the SHA256 tree hash of the data being uploaded" is what the service
        // verifies it against. Hashing happens HERE, before the store is locked, and the
        // per-chunk leaves are kept with the archive so no later request has to hash
        // archive bytes while holding it.
        let chunk_leaves = state::chunk_leaves(&input.body);
        let sha256_tree_hash = state::tree_hash_from_leaves(&chunk_leaves);
        if let Some(claimed) = input.checksum.as_deref().map(str::trim) {
            if !claimed.eq_ignore_ascii_case(&sha256_tree_hash) {
                return Err(UploadArchiveErrorModeled::InvalidParameterValueException(
                    state::invalid_parameter_value(format!(
                        "Checksum mismatch: the x-amz-sha256-tree-hash header claims {claimed} \
                         but the SHA256 tree hash of the uploaded content is {sha256_tree_hash}"
                    )),
                )
                .into());
            }
        }

        let mut store = store.lock();
        let Some(vault) = store.vaults.get(&(account_id.clone(), vault_name.clone())) else {
            return Err(UploadArchiveErrorModeled::ResourceNotFoundException(
                state::vault_not_found(&region, &vault_name),
            )
            .into());
        };

        // This emulator holds every archive in memory, so a vault has a capacity: past
        // it the service really cannot complete the request, and nothing about the
        // request is wrong. Real Glacier has no such limit; see the constants.
        let size_in_bytes = i64::try_from(input.body.len()).unwrap_or(i64::MAX);
        if vault.archives.len() >= state::MAX_ARCHIVES_PER_VAULT
            || vault.size_in_bytes().saturating_add(size_in_bytes) > state::MAX_VAULT_BYTES
        {
            return Err(UploadArchiveErrorModeled::ServiceUnavailableException(
                state::service_unavailable(format!(
                    "Vault {} has reached this emulator's capacity of {} archives or {} bytes",
                    vault.vault_arn,
                    state::MAX_ARCHIVES_PER_VAULT,
                    state::MAX_VAULT_BYTES
                )),
            )
            .into());
        }

        let (sequence, archive_id) = store.mint_id("archive");
        let archive = state::Archive {
            archive_id: archive_id.clone(),
            body: ::bytes::Bytes::from(input.body),
            size_in_bytes,
            chunk_leaves,
            sha256_tree_hash: sha256_tree_hash.clone(),
            description: input.archive_description,
            creation_date: state::now_iso8601(),
            sequence,
        };
        // Inserted under exactly the id that was minted and is about to be returned.
        store
            .vaults
            .get_mut(&(account_id.clone(), vault_name.clone()))
            .expect("the vault was present under this key a moment ago")
            .archives
            .insert(archive_id.clone(), archive);

        Ok(UploadArchiveOutput {
            location: Some(format!(
                "/{account_id}/vaults/{vault_name}/archives/{archive_id}"
            )),
            checksum: Some(sha256_tree_hash),
            archive_id: Some(archive_id),
        })
    }
}
