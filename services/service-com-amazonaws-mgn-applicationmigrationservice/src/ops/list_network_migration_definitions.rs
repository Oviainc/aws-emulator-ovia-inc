/// definition configured with none.
fn summary(
    definition: &crate::state::NetworkMigrationDefinition,
) -> NetworkMigrationDefinitionSummary {
    NetworkMigrationDefinitionSummary {
        network_migration_definition_id: Some(definition.network_migration_definition_id.clone()),
        name: Some(definition.configuration.name.clone()),
        source_environment: definition
            .configuration
            .source_configurations
            .first()
            .map(|configuration| configuration.source_environment.clone()),
        arn: Some(definition.arn.clone()),
        tags: definition.tags_shape(),
        scope_tags: definition.scope_tags_shape(),
    }
}

/// Whether `definition` satisfies every filter the request set. An absent filter, and a
/// present-but-empty id list, select everything.
fn matches_filters(
    definition: &crate::state::NetworkMigrationDefinition,
    filters: Option<&ListNetworkMigrationDefinitionsRequestFilters>,
) -> bool {
    let Some(filters) = filters else {
        return true;
    };
    if let Some(ids) = filters.network_migration_definition_i_ds.as_ref() {
        if !ids.is_empty() && !ids.contains(&definition.network_migration_definition_id) {
            return false;
        }
    }
    true
}
