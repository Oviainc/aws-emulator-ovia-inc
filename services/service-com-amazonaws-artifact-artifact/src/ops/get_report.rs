//! @op GetReport
//! Serves the report document for one report version. A report is served ONLY under a term
//! grant this service issued for the TERM governing it: the request's `termToken` is checked
//! against the grants [`crate::state`] holds, so a token nobody was ever given and a token
//! accepted under another term are both refused with the modelled `ValidationException`.
//! The member is `@required` and is documented as the "Unique download token provided by
//! GetTermForReport API", so a value no acceptance minted is no token on any report,
//! whatever that report's `AcceptanceType` says: the acceptance type tells a client whether
//! it has to put the term document in front of a person before asking for the receipt, and
//! it decides nothing about which receipts this service issued.
//! The grant is not consumed — this handler only READS.
//!
//! A `reportId` the catalog does not hold is refused by the front door's 401
//! `UnauthorizedException`, because AWS Artifact authorises the report resource before
//! looking it up; `ResourceNotFoundException` is left for a VERSION a reachable report
//! never published.
//!
//! The acceptance rule is the ONLY authorisation this handler applies. The emulator verifies every
//! request signature before a handler runs, but it models no IAM, so the modelled
//! `AccessDeniedException` is never raised here: a call the real service would refuse for
//! lack of `artifact:GetReport` succeeds against this emulator, and a pass here is not a
//! statement about an AWS-side authorisation decision.
//!
//! The report catalog IS the account's entitlement, though: AWS Artifact is served
//! through a gateway that authorizes the report the request targets before the service
//! is reached, so a `reportId` the catalog does not publish is answered with the front
//! door's 401 `UnauthorizedException` (`crate::scaffolded::FrontDoorRefusal`) and never
//! with the modelled 404 — before the term token is looked at at all.
//!
