impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for GetReport<Eng>
{
    type Input = GetReportInput;
    type Output = GetReportOutput;
    type Error = GetReportError;

    const NAME: &'static str = "GetReport";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_REPORT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_REPORT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(GetReportErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the artifact report catalog is unavailable".to_string(),
                    retry_after_seconds: None,
                },
            )
            .into());
        };

        // The URL announced below names the endpoint the CALLER reached this emulator
        // on, because this emulator serves the document it points at.
        let host = crate::state::document_url_host(ctx.parts());
        let store = state.lock();

        // Which of the two refusals a request that resolves no report version gets is the
        // service's one rule, decided in `crate::state`; this handler only lifts it into
        // its own modelled not-found variant.
        let (report, version) = store
            .report_version(&input.report_id, input.report_version)
            .map_err(|refusal| refusal.lift(GetReportErrorModeled::ResourceNotFoundException))?;

        // The term token is the receipt `GetTermForReport` mints, and it is bound to the
        // TERM governing the report: a token that was never issued is not a token at all,
        // and one accepted under a different term document does not authorise this
        // download. Either way no URL is served, and the refusal names neither the token nor
        // the term it covers.
        if !store.download_authorised(&input.term_token, report) {
            ::tracing::info!(
                operation = "GetReport",
                report_id = %input.report_id,
                report_version = version.version,
                outcome = "denied",
                reason = "termToken does not cover this report's term",
                "refused a report download"
            );
            return Err(GetReportErrorModeled::ValidationException(
                // The service's own fixed invalid-token text, not the check that refused
                // it: which internal lookup missed is a fact about the SERVER, and the
                // caller's token is not echoed back either — the request carried it. The
                // reason this refusal happened is on the log line above, where an
                // operator reads it; the modelled `reason` tells a client it was a token.
                crate::state::invalid_token(),
            )
            .into());
        }

        ::tracing::info!(
            operation = "GetReport",
            report_id = %input.report_id,
            report_version = version.version,
            outcome = "served",
            "served a report document"
        );

        Ok(GetReportOutput {
            document_presigned_url: Some(crate::state::report_document_url(
                &host,
                report,
                version,
                &input.term_token,
            )),
        })
    }
}
