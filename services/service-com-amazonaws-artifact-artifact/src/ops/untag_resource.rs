//! @op UntagResource
//! Removes the named tag keys from the resource its `resourceArn` names, writing the
//! remaining tag set back onto the record [`crate::state`] holds for that resource.
//!
//! A MUTATING operation, and `@idempotent`: a key the resource does not carry is not an
//! error — the request states the keys that must be gone afterwards, so the same request
//! twice leaves the same tag set, and keys it does not name are left alone.
//!
//! A key in the reserved `aws:` namespace ([`crate::state::RESERVED_TAG_KEY_PREFIX`]) names
//! a tag Amazon Web Services owns, which a caller may no more remove than create: such a
//! request is refused with the modelled 400 `ValidationException` and removes nothing.
//!
//! The removal changes persisted state, so it is ATTRIBUTABLE on the same terms as the tag
//! write ([`crate::ops::tag_resource`]): exactly one structured record naming the caller,
//! the resource whose tag set it changed, which keys the request named and the outcome, on
//! the refusal paths as much as on the success one.
//!
//! A removal that takes a key off the resource MODIFIES that resource, so it moves the
//! record's last-modified instant to the instant of the removal
//! ([`crate::state::ComplianceInquiry::record_modification`]) — the tag set is persisted on
//! the inquiry record, so a reader of that record cannot report an instant before a change
//! `ListTagsForResource` reports back. A request naming only keys the resource does not
//! carry changes nothing, so it leaves that instant where it was.
//!
//! A `resourceArn` that is not a well-formed ARN is refused with the front door's own 400
//! `BadRequestException` request shape
//! ([`crate::scaffolded::Scaffolded::invalid_resource_arn`]) before anything resolves a
//! target, and an ARN this surface can read that names no resource this account holds is
//! answered HTTP 401 `UnauthorizedException`, as every resource lookup in this service is —
//! see [`crate::ops::tag_resource`].
//!
