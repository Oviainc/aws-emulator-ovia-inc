//! @op TagResource
//! Adds tags to the resource its `resourceArn` names, writing them onto the record
//! [`crate::state`] holds for that resource, so `ListTagsForResource` and
//! `GetComplianceInquiryMetadata` report back what this call persisted.
//!
//! A MUTATING operation: "Add tags to a resource." The write is ABSOLUTE PER KEY — a key
//! the resource already carries takes the request's value and a key it does not carry is
//! added, so repeating one request changes nothing the second time, and keys the request
//! does not name are left alone (removing one is `UntagResource`'s job).
//!
//! The `aws:` tag-key namespace is Amazon Web Services' own
//! ([`crate::state::RESERVED_TAG_KEY_PREFIX`]): a request naming a key under it is refused
//! with the modelled 400 `ValidationException` and writes nothing, so a caller-created tag
//! set never carries one.
//!
//! A write that would leave the resource holding more tags than
//! [`crate::state::TAGS_PER_RESOURCE_LIMIT`] is refused the same way
//! ([`crate::state::too_many_tags`]) and writes nothing: both refusals this handler states
//! are field-validation failures, so both are worded in the one validation envelope this
//! service states such a refusal in.
//!
//! The write changes persisted state, so it is ATTRIBUTABLE: this handler leaves exactly
//! one structured record naming the caller (the access-key id and the credential-scope
//! region the request presented), the resource whose tag set it changed, which keys it
//! wrote and the outcome — on the refusal paths as much as on the success one, since a
//! state-changing call that changed nothing is still attributable. Never a tag VALUE, and
//! never the inquiry's `@sensitive` name or content.
//!
//! A write that changes the resource's tag set MODIFIES that resource, so it moves the
//! record's last-modified instant to the instant of the write
//! ([`crate::state::ComplianceInquiry::record_modification`]) — the tag set is persisted on
//! the inquiry record, so a reader of that record cannot report an instant before a change
//! `ListTagsForResource` reports back. A request writing the values the resource already
//! carries changes nothing, so it leaves that instant where it was.
//!
//! The resource is named by its ARN, which this handler READS as an ARN before it resolves
//! anything: the model gives that member no identifier syntax, so a value that is not a
//! well-formed ARN names no resource to authorize and is refused with the front door's own
//! 400 `BadRequestException` request shape
//! ([`crate::scaffolded::Scaffolded::invalid_resource_arn`]) — the same refusal the other
//! two tagging operations state for the same value. The only resource an account owns
//! in this service is a compliance inquiry — see
//! [`crate::state::ComAmazonawsArtifactArtifactState::tagged_resource`] — so an ARN this
//! surface CAN read and that names no such resource is answered the way the front door
//! answers a target it cannot authorize (HTTP 401 `UnauthorizedException`), as every
//! resource lookup in this service does: whether the account holds the resource is not
//! information this API discloses.
//!
