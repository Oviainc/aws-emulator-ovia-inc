//! @op GetTermForReport
//! Serves the term document attached to one report version, and MINTS the `termToken`
//! that document is served under — "a unique token representing this request event", as
//! the model puts it, and the acceptance receipt `GetReport` requires. The grant is
//! persisted in [`crate::state`] so `GetReport` can check a token against the TERM it
//! covers; minting it is what this operation DOES, not a side effect of reading, and no
//! earlier grant is altered or consumed.
//!
//! A `reportId` the catalog does not hold is refused by the front door's 401
//! `UnauthorizedException`, because AWS Artifact authorises the report resource before
//! looking it up; `ResourceNotFoundException` is left for a VERSION a reachable report
//! never published.
//!
//! The grant store is bounded (`crate::state::TERM_GRANT_CAPACITY`), oldest released
//! first, so repeated acceptance cannot grow the state without end. The id that KEYS a
//! grant is drawn from that bound's counter, but the `termToken` answered here is not: it
//! is the receipt of this acceptance and the only thing that authorises a download of a
//! report requiring it, so it is minted per call from a random source and a caller that
//! accepted nothing can derive none. The emulator models
//! no IAM, so the modelled `AccessDeniedException` is never raised here, and the grant
//! records the term it covers rather than a principal: a pass is not a statement about
//! an AWS-side authorisation decision.
//!
//! The report catalog IS the account's entitlement, though: AWS Artifact is served
//! through a gateway that authorizes the report the request targets before the service
//! is reached, so a `reportId` the catalog does not publish is answered with the front
//! door's 401 `UnauthorizedException` (`crate::scaffolded::FrontDoorRefusal`) and never
//! with the modelled 404 — and, as before, leaves no grant behind.
//!
//! Minting that grant persists a resource, so the call is ATTRIBUTABLE on the same terms as
//! this crate's other state changes: this handler leaves exactly one structured record naming
//! the caller (the access-key id and the credential-scope region the request presented), what
//! the call addressed and the outcome — on the refusal paths as much as on the success one,
//! since a state-changing call that changed nothing is still attributable. Never the
//! `termToken` itself, nor the URL that carries it: the token is the receipt of this one
//! acceptance.
//!
