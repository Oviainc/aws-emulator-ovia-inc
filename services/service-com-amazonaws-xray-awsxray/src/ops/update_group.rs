//! @op UpdateGroup
//!
//! Updates a stored group in place: the group is selected by EXACTLY ONE of
//! `GroupName` or `GroupARN`, each member the request SUPPLIES replaces the
//! stored one, each member it OMITS is left as it is, and the group's name, its
//! ARN and its tags are untouched, so the response — and every later `GetGroup`
//! / `GetGroups` — is read back out of `crate::state::GroupRecord` rather than
//! echoed from this request. A request that names no group, that names a group
//! this emulator does not hold, or that supplies BOTH selectors (two identities
//! at once) is refused with the modelled `InvalidRequestException` (HTTP 400)
//! before anything is written.
//!
//! A supplied `FilterExpression` is PARSED first
//! ([`crate::state::filter_expression`]): an expression X-Ray would refuse is
//! answered with `InvalidRequestException` and the group keeps the expression it
//! had. The reserved `Default` group is updatable like any other — it is derived
//! until the first update stores it, with the ARN it already reads with.
//!
//! Supplying both selectors is refused whatever they name, which is also what
//! settles a CONFLICTING pair: two selectors that name different stored groups
//! can never be acted on, so no update mutates a group the caller did not name
//! on its own.
//!
//! The one other refusal this handler owns is the configuration the
//! documentation forbids: `NotificationsEnabled` true where `InsightsEnabled` is
//! not explicitly true.
