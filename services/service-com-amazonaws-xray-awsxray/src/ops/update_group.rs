impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateGroup<Eng>
{
    type Input = UpdateGroupInput;
    type Output = UpdateGroupOutput;
    type Error = UpdateGroupError;

    const NAME: &'static str = "UpdateGroup";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_GROUP_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_GROUP_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(UpdateGroupErrorModeled::ThrottledException(ThrottledException {
                message: Some(
                    "the X-Ray group store is unavailable on this emulator engine".to_string(),
                ),
            })
            .into());
        };

        // The filter expression is parsed BEFORE anything is written, so a
        // refused update leaves the stored expression exactly as it was.
        if let Some(expression) = input.filter_expression.as_deref() {
            if let Err(failure) = crate::state::filter_expression::validate(expression) {
                return Err(refuse(failure.message()));
            }
            // And a comparison whose operands cannot be compared at all is
            // refused HERE too, not only where the expression is evaluated
            // (`crate::state::filter`): an expression that can never be true
            // for any trace is a mistake in the request, and a group may not
            // store one.
            if let Err(error) = crate::state::filter::operand_check(expression) {
                return Err(refuse(error.message));
            }
        }

        // "Notifications can only be enabled on a group with InsightsEnabled set
        // to true" (`InsightsConfiguration` on this operation's input). Decided
        // against the RESULTING record: a submitted `InsightsConfiguration`
        // REPLACES the stored one whole, so the configuration in the request is
        // the one the group ends up with — notifications on without insights
        // explicitly on is the state the documentation forbids, whether
        // `InsightsEnabled` is false or absent.
        if let Some(configuration) = input.insights_configuration.as_ref() {
            if configuration.notifications_enabled == Some(true)
                && configuration.insights_enabled != Some(true)
            {
                return Err(refuse(
                    "InsightsConfiguration.NotificationsEnabled can only be true on a group whose InsightsEnabled is true".to_string(),
                ));
            }
        }

        // Both selectors are optional in the model, so what is left to refuse
        // here is a request that names no group at all, one that supplies both
        // selectors, and one that names a group this emulator does not hold;
        // `GroupName`'s and `GroupARN`'s length bounds are modelled and already
        // refused before this handler. Every refusal happens before any write,
        // so a refused update leaves every stored group as it was.
        //
        // Supplying BOTH selectors is refused in `resolve_group_name` itself,
        // which is also what settles a CONFLICTING pair: two selectors that name
        // different stored groups can never be acted on, so no update can mutate
        // a group the caller did not name on its own.
        let mut store = state.lock();
        let region = crate::state::request_region(ctx.parts());
        let group = store
            .find_group(
                &region,
                input.group_name.as_deref(),
                input.group_arn.as_deref(),
            )
            .map_err(|failure| {
                UpdateGroupErrorModeled::InvalidRequestException(InvalidRequestException {
                    message: Some(failure.message().to_string()),
                })
            })?;

        let update = crate::state::GroupUpdate {
            filter_expression: input.filter_expression,
            insights_configuration: input
                .insights_configuration
                .as_ref()
                .map(InsightsConfigurationRecord::from_configuration),
        };
        // The reserved `Default` group is derived rather than stored, so the
        // first update of it materialises its record — carrying the ARN it is
        // already read with. The only way that can fail is a store already
        // holding its maximum of groups.
        let Some(group) = store
            .apply_group_update(group, update)
            .map(GroupRecord::to_group)
        else {
            return Err(UpdateGroupErrorModeled::InvalidRequestException(
                InvalidRequestException {
                    message: Some(format!(
                        "this emulator holds the maximum of {} groups",
                        crate::state::MAX_GROUPS
                    )),
                },
            )
            .into());
        };

        Ok(UpdateGroupOutput { group: Some(group) })
    }
}

/// Refuse the request with the error this operation models for an invalid one.
fn refuse(message: String) -> UpdateGroupError {
    UpdateGroupErrorModeled::InvalidRequestException(InvalidRequestException {
        message: Some(message),
    })
    .into()
}
