/// The epoch second the `period`-wide aggregation period containing `seconds`
/// starts at.
///
/// Periods are aligned to multiples of `period` since the epoch, not to the
/// requested `StartTime`, so the same instant falls in the same period whatever
/// window asks about it — two overlapping windows report one request under one
/// `Timestamp`.
///
/// Total for any finite `seconds` and any accepted `period`: the float-to-int
/// cast saturates rather than wrapping, and the alignment multiply is checked,
/// so an absurd stored `start_time` lands in the first or last representable
/// period instead of panicking or wrapping into another period's counts.
fn period_start(seconds: f64, period: i64) -> i64 {
    #[allow(clippy::cast_possible_truncation)]
    let whole = seconds.floor() as i64;
    whole
        .div_euclid(period)
        .checked_mul(period)
        .unwrap_or(if whole < 0 { i64::MIN } else { i64::MAX })
}

/// One aggregation period's counts, built up from the stored segments.
///
/// A completed segment is one request, classified by the status it recorded:
/// `ErrorStatistics` counts the 4xx ones (429 as its `ThrottleCount`, every
/// other 4xx as `OtherCount`) and `FaultStatistics` the 5xx ones, so `OkCount`
/// — "the number of requests that completed with a 2xx Success status code" —
/// takes every other completed request: a segment that recorded no status at
/// all, or one outside those two series, has no other count to go to and is one
/// more request its service completed without error or fault.
#[derive(Debug, Default)]
struct Aggregate {
    /// Requests that completed with neither an error, a fault nor a throttle.
    ///
    /// The model's wording for `OkCount` is "completed with a 2xx Success
    /// status code"; it is DELIBERATELY widened here to "completed without
    /// error or fault", because a 3xx response and a segment that recorded no
    /// status at all are both completed requests the other two counts exclude,
    /// and `TotalCount` is "the total number of completed requests".
    ok_count: i64,
    /// Requests that recorded a 429 throttle.
    throttle_count: i64,
    /// Requests that recorded a 400-series error other than a throttle.
    error_other_count: i64,
    /// Requests that recorded a 500-series fault.
    fault_count: i64,
    /// The aggregate response time of the counted requests, in seconds.
    total_response_time: f64,
    /// Response time in whole milliseconds -> how many requests took it, which
    /// is the `ResponseTimeHistogram`'s (value, prevalence) pairs.
    histogram: std::collections::BTreeMap<i64, i32>,
}

impl Aggregate {
    /// Count one completed segment, whose request took `response_time` seconds.
    fn record(&mut self, segment: &crate::state::SegmentRecord, response_time: f64) {
        // A 429 is both a throttle and a 400-series error, and `ErrorStatistics`
        // SPLITS the two counts (`$ThrottleCount` beside `$OtherCount`, with
        // `$TotalCount` their sum), so a throttled request is counted under the
        // throttle count and not also under the other-error count. That split is
        // exactly the exclusive `crate::state::Classification` every counter of
        // this state uses, read here rather than recomputed; the trace's
        // `HasError` flag is a different question and a different rule (see
        // `crate::state::recorded_error`), because the flags are not exclusive.
        match segment.classification() {
            crate::state::Classification::Fault => self.fault_count += 1,
            crate::state::Classification::Throttle => self.throttle_count += 1,
            crate::state::Classification::Error => self.error_other_count += 1,
            crate::state::Classification::Ok => self.ok_count += 1,
        }
        self.total_response_time += response_time;
        #[allow(clippy::cast_possible_truncation)]
        let millis = (response_time * 1_000.0).round() as i64;
        let count = self.histogram.entry(millis).or_insert(0);
        *count = count.saturating_add(1);
    }

    /// "The total number of completed requests."
    fn total_count(&self) -> i64 {
        self.ok_count + self.error_total_count() + self.fault_count
    }

    /// "The total number of requests that failed with a 4xx Client Error status
    /// code" — throttles included.
    fn error_total_count(&self) -> i64 {
        self.throttle_count + self.error_other_count
    }

    /// This period as one `TimeSeriesServiceStatistics`.
    ///
    /// WHICH summary carries the counts follows what the request selected. "If
    /// no selector expression is specified, edge statistics are returned", and
    /// every counted request arrived at its service over one inbound edge, so an
    /// unselected aggregate and an edge-selected one are aggregates of edges. A
    /// selector naming a SERVICE asks about that service's own requests, which
    /// `ServiceSummaryStatistics` reports — and those requests are exactly the
    /// calls its inbound edges carried, so the same counts stand under both
    /// summaries rather than one of the two being left for the caller to
    /// recompute. `ServiceForecastStatistics` stays absent — a forecast request
    /// is refused rather than answered with numbers nothing computed.
    fn to_statistics(
        &self,
        period_start: i64,
        selector: Option<&crate::state::filter_expression::EntitySelector>,
    ) -> TimeSeriesServiceStatistics {
        let of_service = matches!(
            selector,
            Some(crate::state::filter_expression::EntitySelector::Service(_))
        );
        let error_statistics = || ErrorStatistics {
            throttle_count: Some(self.throttle_count),
            other_count: Some(self.error_other_count),
            total_count: Some(self.error_total_count()),
        };
        let fault_statistics = || FaultStatistics {
            // Nothing here categorises a 5xx further, so every counted
            // fault is an untracked one.
            other_count: Some(self.fault_count),
            total_count: Some(self.fault_count),
        };
        TimeSeriesServiceStatistics {
            timestamp: Some(::aws_smithy_types::DateTime::from_secs(period_start)),
            edge_summary_statistics: Some(EdgeStatistics {
                ok_count: Some(self.ok_count),
                error_statistics: Some(error_statistics()),
                fault_statistics: Some(fault_statistics()),
                total_count: Some(self.total_count()),
                total_response_time: Some(self.total_response_time),
            }),
            service_summary_statistics: of_service.then(|| ServiceStatistics {
                ok_count: Some(self.ok_count),
                error_statistics: Some(error_statistics()),
                fault_statistics: Some(fault_statistics()),
                total_count: Some(self.total_count()),
                total_response_time: Some(self.total_response_time),
            }),
            service_forecast_statistics: None,
            response_time_histogram: Some(
                self.histogram
                    .iter()
                    .map(|(millis, count)| HistogramEntry {
                        #[allow(clippy::cast_precision_loss)]
                        value: *millis as f64 / 1_000.0,
                        count: *count,
                    })
                    .collect(),
            ),
        }
    }
}

/// Whether one stored segment is an entity the selector names.
///
/// A `service(id(…))` / `id(…)` selector names the segments of the service its
/// members match; an `edge(id(…), id(…))` names the segments of the second
/// entity that were reached from the first, which is the call the edge carried —
/// resolved through `owners`, the trace's entity index.
fn selects_entity(
    selector: &crate::state::filter_expression::EntitySelector,
    trace: &crate::state::TraceRecord,
    segment: &crate::state::SegmentRecord,
    owners: Option<&std::collections::BTreeMap<&str, usize>>,
) -> bool {
    use crate::state::filter_expression::EntitySelector;

    match selector {
        EntitySelector::Service(entity) => names_entity(entity, segment),
        EntitySelector::Edge {
            source,
            destination,
        } => {
            names_entity(destination, segment)
                && segment.parent_id.as_deref().is_some_and(|parent_id| {
                    owners
                        .and_then(|owners| owners.get(parent_id))
                        .and_then(|at| trace.segments.get(*at))
                        .is_some_and(|holder| names_entity(source, holder))
                })
        }
    }
}

/// Whether a segment is the entity one `id(…)` names: every member the selector
/// labelled has to match, and one it omitted narrows nothing.
fn names_entity(
    entity: &crate::state::filter_expression::EntityId,
    segment: &crate::state::SegmentRecord,
) -> bool {
    entity
        .name
        .as_ref()
        .is_none_or(|name| &segment.name == name)
        && entity
            .r#type
            .as_ref()
            .is_none_or(|wanted| segment.origin.as_ref() == Some(wanted))
        && entity
            .account_id
            .as_ref()
            .is_none_or(|wanted| segment.account_id.as_ref() == Some(wanted))
}
