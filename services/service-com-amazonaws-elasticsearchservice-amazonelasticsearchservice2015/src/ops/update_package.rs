    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_PACKAGE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine)
            .ok_or_else(crate::state::state_unavailable)?;

        let now = ::std::time::SystemTime::now();
        // A package is held by the control plane of the Region its create was
        // signed for, so that is the scope this id is resolved in.
        let region = crate::state::request_region(&ctx.parts().headers);

        let mut store = state.lock();
        let Some(package) = store
            .packages
            .get_mut(&crate::state::package_key(&region, &input.package_id))
        else {
            // The resource named is not there: HTTP 404
            // (`crate::scaffolded::RESOURCE_NOT_FOUND_STATUS`), not the
            // `@httpError(409)` the model annotates on the shape.
            return Err(crate::scaffolded::Scaffolded::not_found(
                UpdatePackageErrorModeled::ResourceNotFoundException(
                    ResourceNotFoundException {
                        message: Some(format!("Package not found: {}", input.package_id)),
                    },
                ),
            ));
        };

        // The emulator's bound on the one growth site inside a package record.
        // Checked before the revision, so a refused update changes nothing.
        if package.versions.len() >= MAX_PACKAGE_VERSIONS {
            return Err(UpdatePackageErrorModeled::LimitExceededException(
                LimitExceededException {
                    message: Some(format!(
                        "Version limit of {MAX_PACKAGE_VERSIONS} versions per package has been \
                         reached for package {package}",
                        package = input.package_id
                    )),
                },
            )
            .into());
        }

        package.revise(
            input.package_source,
            input.package_description,
            input.commit_message,
            now,
        );

        // The response is the details of the record just written — the same
        // value the next DescribePackages reads back — so the two cannot
        // disagree.
        Ok(UpdatePackageOutput {
            package_details: Some(package.to_details(now)),
        })
    }
