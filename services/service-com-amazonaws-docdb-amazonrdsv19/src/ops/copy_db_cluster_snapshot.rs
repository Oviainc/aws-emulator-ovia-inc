            return Err(
                CopyDBClusterSnapshotErrorModeled::DBClusterSnapshotAlreadyExistsFault(
                    DBClusterSnapshotAlreadyExistsFault {
                        message: Some(format!(
                            "DB cluster snapshot already exists: {target_key}"
                        )),
                    },
                )
                .into(),
            );
