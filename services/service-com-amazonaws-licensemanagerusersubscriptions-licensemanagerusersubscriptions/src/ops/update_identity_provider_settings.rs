//! @op UpdateIdentityProviderSettings
//!
//! Updates a registration's product configuration settings in [`crate::state`], so
//! `ListIdentityProviders` and every later read report the updated settings.
//!
//! `Product` is checked before any of that: it is modelled as a plain `String`, so the
//! boundary validator cannot enforce the values its documentation lists, and whether a
//! product name is one this service serves does not depend on what is registered — a
//! request naming a product outside [`crate::state::PRODUCTS`] is refused naming the
//! value, exactly as every other operation with a `Product` member refuses it.
//!
//! The identity provider is RESOLVED BEFORE the `UpdateSettings` payload is looked at:
//! a reference that resolves to no registration is refused with the modelled
//! `ValidationException` and [`crate::state::IDENTITY_PROVIDER_NOT_VALID`], whatever the
//! payload says
//! — so a request with an unresolvable reference is answered the same way whether or not
//! its payload would also have been refused. This operation models no
//! `ResourceNotFoundException` at all (`smithy_query(query="operation",
//! operation="UpdateIdentityProviderSettings")` lists AccessDeniedException,
//! ThrottlingException and ValidationException), so an unresolvable reference IS a
//! validation failure here.
//!
//! Only then is the payload applied, by [`crate::state::apply_update_settings`]: a
//! subnet in both `AddSubnets` and `RemoveSubnets`, or a payload that takes away the last
//! subnet the registration carries, is refused as invalid rather than half-applied. A
//! registration stored with no subnet (`Settings` is optional on registration) is not
//! taken below the minimum by a payload that removes nothing, so a security-group-only
//! update of one is applied, and a payload naming nothing is the no-op the operation's
//! `@idempotent` trait asks for.
//!
//! The settings that payload WOULD store are then resolved against what the account has,
//! asked of the service that owns those resources
//! ([`crate::state::ec2_fleet::resolve_settings_network`]), because License Manager creates
//! the activation-server VPC endpoints in those subnets with that security group: a payload
//! that would leave the registration naming a subnet or a security group the account does
//! not have, or resources of two different VPCs, is refused instead of stored.
//! `RemoveSubnets` needs no resolution of its own — what it names leaves the settings
//! rather than being provisioned, so removing a subnet the account no longer has is exactly
//! the no-op the operation's `@idempotent` trait asks for.
//!
//! That resolution is a HOP, so this handler's store is released across it and taken again
//! to write. Nothing read before the hop is carried over as still true: the registration is
//! resolved by the same liveness rule a second time, and the write is CONDITIONAL on the
//! settings the resolution was made against still being the settings the store holds
//! ([`crate::state::ComAmazonawsLicensemanagerusersubscriptionsLicensemanagerusersubscriptionsState::update_live_settings`]).
//! So a registration deregistered while the resolution was in flight is refused rather than
//! mutated, and an update accepted in that window does not compose with this one into a
//! configuration nothing resolved: the write reports that the settings moved, and this
//! handler folds the payload onto the moved-on settings and resolves THAT whole
//! configuration before trying the write again, for at most
//! [`SETTINGS_WRITE_ATTEMPTS`] attempts. So an update accepted in the window is added to
//! rather than overwritten, while the configuration left in the store is always one the
//! account's network carries.
