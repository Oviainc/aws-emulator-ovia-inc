/// Marker that prefixes a token's plaintext, so a token minted for some other
/// list cannot be mistaken for one of these. The plaintext is encoded with the
/// one page-token codec of this service ([`crate::state::encode_page_token`]).
const NEXT_TOKEN_PREFIX: &str = "kafka:scram-secrets:";

/// Separates the cluster ARN a token was minted for from the secret ARN the page
/// stopped at. Neither an MSK cluster ARN nor a Secrets Manager secret ARN can
/// contain it, so the plaintext splits back into exactly two fields.
const NEXT_TOKEN_SEPARATOR: char = '#';

/// Encode the cluster and the secret ARN a page stopped at as a token.
fn encode_next_token(cluster_arn: &str, last_secret: &str) -> String {
    crate::state::encode_page_token(
        NEXT_TOKEN_PREFIX,
        &format!("{cluster_arn}{NEXT_TOKEN_SEPARATOR}{last_secret}"),
    )
}

/// The secret ARN a token resumes after, or `None` when the token is not one
/// this operation minted FOR THIS CLUSTER: a token carries the list it was
/// minted from, so one cluster's page token cannot resume another cluster's
/// listing.
fn decode_next_token(token: &str, cluster_arn: &str) -> Option<String> {
    let plaintext = crate::state::decode_page_token(NEXT_TOKEN_PREFIX, token)?;
    let (arn, last_secret) = plaintext.split_once(NEXT_TOKEN_SEPARATOR)?;
    (arn == cluster_arn).then(|| last_secret.to_string())
}

