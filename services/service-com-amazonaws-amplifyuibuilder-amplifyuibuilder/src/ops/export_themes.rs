impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ExportThemes<Eng>
{
    type Input = ExportThemesInput;
    type Output = ExportThemesOutput;
    type Error = ExportThemesError;

    const NAME: &'static str = "ExportThemes";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::EXPORT_THEMES_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::EXPORT_THEMES_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(ExportThemesErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("the amplifyuibuilder theme store is unavailable".to_string()),
                },
            )
            .into());
        };

        let key = (input.app_id.clone(), input.environment_name.clone());
        let store = state.lock();

        // One page of this app environment's themes, through the service's one
        // page walk (`crate::state::page_of`), projected to the FULL `Theme`
        // record rather than to a summary and bounded by this export's own page
        // limit. A malformed token, one issued for another app environment, one
        // issued over another collection of this app environment, or one whose
        // cursor is not among those handed out names no page of this export, so
        // it is refused rather than served as a page. With no token at all the
        // export starts at the first cursor the service ever hands out, i.e. at
        // the head of the list.
        let page = crate::state::page_of(
            store.themes_in(&input.app_id, &input.environment_name),
            &key,
            store.cursor_seq,
            input.next_token.as_deref(),
            crate::state::EXPORT_PAGE_LIMIT,
            crate::state::StoredTheme::to_theme,
        )
        .map_err(|unknown| {
            ExportThemesErrorModeled::InvalidParameterException(InvalidParameterException {
                message: Some(unknown.message(Self::NAME)),
            })
        })?;

        Ok(ExportThemesOutput {
            entities: page.entities,
            next_token: page.next_token,
        })
    }
}
