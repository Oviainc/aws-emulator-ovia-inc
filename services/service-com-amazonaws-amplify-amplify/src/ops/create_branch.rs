impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CreateBranch<Eng>
{
    type Input = CreateBranchInput;
    type Output = CreateBranchOutput;
    type Error = CreateBranchError;

    const NAME: &'static str = "CreateBranch";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_BRANCH_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_BRANCH_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        _ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            CreateBranchErrorModeled::InternalFailureException(InternalFailureException {
                message: Some("the Amplify emulator has no state store attached".to_string()),
            })
        })?;

        let created = crate::state::now();

        // A branch name is drawn from a character set the model's `@pattern ^(?s).+$`
        // does not express, so the boundary validator passes a name this service
        // refuses: it is checked HERE, before the app is looked up and before the branch
        // is built or stored, because a name outside the set would become a default
        // domain prefix no visitor could address. See
        // [`crate::state::is_branch_name`].
        if !crate::state::is_branch_name(&input.branch_name) {
            return Err(CreateBranchErrorModeled::BadRequestException(BadRequestException {
                message: Some(crate::state::branch_name_not_supported_message(
                    &input.branch_name,
                )),
            })
            .into());
        }

        let mut store = state.lock();

        // A branch only exists as part of an app, so an unknown `appId` is a 404
        // rather than an app created on the way.
        let app = store.apps.get_mut(&input.app_id).ok_or_else(|| {
            CreateBranchErrorModeled::NotFoundException(NotFoundException {
                message: Some(crate::state::not_found_message(
                    crate::state::APP_ENTITY,
                    &input.app_id,
                )),
            })
        })?;

        // `branchName` identifies a branch within its app, so a second create under
        // the same name is refused rather than silently replacing the first branch.
        // The refusal's message is built from the request's own members through the
        // one formatter every duplicate-name refusal in this crate shares, because
        // callers substring-match it to tell this conflict from the other conditions
        // Amplify also reports as a bare `BadRequestException`.
        if app.branches.contains_key(&input.branch_name) {
            return Err(CreateBranchErrorModeled::BadRequestException(BadRequestException {
                message: Some(crate::state::already_exists_message(
                    crate::state::BRANCH_ENTITY,
                    &input.branch_name,
                    &input.app_id,
                )),
            })
            .into());
        }

        // The quota is enforced BEFORE the branch is built or stored, so a refused
        // create leaves the app exactly as it was and one app's branch map cannot
        // grow without limit.
        if app.branches.len() >= MAX_BRANCHES_PER_APP {
            return Err(CreateBranchErrorModeled::LimitExceededException(
                LimitExceededException {
                    message: Some(format!(
                        "Number of branches exceeds the limit of {MAX_BRANCHES_PER_APP} for app {}",
                        input.app_id
                    )),
                },
            )
            .into());
        }

        // The basic-authorization credentials the request configured are INGESTED rather
        // than stored: what is kept is the verifier the hosting edge checks a visitor's
        // credentials against, and what the record reports is the reference every reader
        // is answered with — never the credentials the request sent
        // (`BasicAuthCredentials` is `@sensitive`). See `crate::state::basic_auth`.
        let mut kept_credentials = None;
        let reported_credentials =
            crate::state::ingest_basic_auth(&mut kept_credentials, input.basic_auth_credentials);

        let branch = Branch {
            branch_arn: format!("{}/branches/{}", app.app.app_arn, input.branch_name),
            // `displayName` "is used as the default domain prefix", and a branch's
            // default domain prefix is its own name.
            display_name: input.display_name.unwrap_or_else(|| input.branch_name.clone()),
            branch_name: input.branch_name,
            // The @required members below have no value in a request that omits them.
            // The record holds the empty value of the member's type, which is what
            // `BranchProjection` reports as JSON `null`.
            description: input.description.unwrap_or_default(),
            // `tags` is echoed exactly as the request set it; a later read reports
            // the branch's tag map (see `BranchProjection::reported`).
            tags: input.tags,
            stage: input.stage.unwrap_or_else(|| DEFAULT_STAGE.to_string()),
            enable_notification: input.enable_notification.unwrap_or(false),
            create_time: created,
            update_time: created,
            environment_variables: input.environment_variables.unwrap_or_default(),
            enable_auto_build: input.enable_auto_build.unwrap_or(DEFAULT_ENABLE_AUTO_BUILD),
            enable_skew_protection: input.enable_skew_protection,
            // A branch carries a custom domain once a domain association assigns it
            // one; a new branch has none.
            custom_domains: Vec::new(),
            framework: input.framework.unwrap_or_default(),
            // Jobs are what build a branch, and a new branch has never been built:
            // no active job, and none in its history.
            active_job_id: String::new(),
            total_number_of_jobs: "0".to_string(),
            enable_basic_auth: input.enable_basic_auth.unwrap_or(false),
            // Performance mode is OFF on a branch created without it, and a branch
            // Amplify created has a definite answer for it: `false`, not nothing.
            enable_performance_mode: Some(input.enable_performance_mode.unwrap_or(false)),
            // The thumbnail is a screenshot of a deployed branch.
            thumbnail_url: None,
            basic_auth_credentials: reported_credentials,
            build_spec: input.build_spec,
            ttl: input.ttl.unwrap_or_else(|| DEFAULT_TTL_SECONDS.to_string()),
            associated_resources: None,
            enable_pull_request_preview: input.enable_pull_request_preview.unwrap_or(false),
            pull_request_environment_name: input.pull_request_environment_name,
            // Both are set only on a branch Amplify created FOR a pull request.
            destination_branch: None,
            source_branch: None,
            backend_environment_arn: input.backend_environment_arn,
            // Every branch has a backend; its `stackArn` is set once a Gen 2
            // deployment provisions the CloudFormation stack, which creating a
            // branch does not do.
            backend: Some(input.backend.unwrap_or_default()),
            compute_role_arn: input.compute_role_arn,
        };

        app.branches.insert(
            branch.branch_name.clone(),
            crate::state::AmplifyBranch::created(branch.clone(), kept_credentials),
        );

        Ok(CreateBranchOutput {
            branch: BranchProjection::written(branch),
        })
    }
}

/// The stage a branch created without one carries.
///
/// `Stage` is modelled `BETA | DEVELOPMENT | EXPERIMENTAL | PRODUCTION | PULL_REQUEST`
/// (`smithy_query(query="shape",shape="Stage")`) and `Branch$stage` is @required, but
/// none of those five is what a branch created without a stage carries: recorded
/// behaviour shows such a branch reporting `NONE`, the value that says the branch has
/// been assigned no stage at all, so the recording overrides the model's value list.
/// A request that names a stage still decides it.
const DEFAULT_STAGE: &str = "NONE";

/// Whether a branch created without `enableAutoBuild` auto-builds on push.
///
/// `EnableAutoBuild` is modelled as a plain boolean with no `@default`
/// (`smithy_query(query="shape",shape="Branch,EnableAutoBuild")`), so the default is
/// the service's, not the Rust type's: Amplify connects a branch WITH continuous
/// deployment on, and a recorded `CreateBranch` whose request omits the member comes
/// back with `enableAutoBuild: true`. A request that carries the member still decides
/// it, in either direction.
const DEFAULT_ENABLE_AUTO_BUILD: bool = true;

/// The content TTL, in seconds, a branch created without one carries.
///
/// CHOSEN, not documented: `TTL` is modelled `length 0..32, pattern ^\d*$` with no
/// default, so this emulator picks the shortest useful cache lifetime rather than
/// leaving the @required member empty.
const DEFAULT_TTL_SECONDS: u32 = 5;

/// How many branches one app may hold at once, past which `CreateBranch` answers the
/// modelled `LimitExceededException` (HTTP 429, "A resource could not be created
/// because service quotas were exceeded").
///
/// AWS Amplify's published service quotas give "Branches per app" a default of 50 (an
/// adjustable quota), which is also the page bound `ListBranches` models, so that is
/// the bound this emulator enforces: one app's branch map cannot grow without limit,
/// and the refusal is the one a real account past its quota gets.
const MAX_BRANCHES_PER_APP: usize = 50;
