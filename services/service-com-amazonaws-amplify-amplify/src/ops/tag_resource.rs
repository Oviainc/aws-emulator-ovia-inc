impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_OUTPUT_SCHEMA;
    // `TagResourceResponse` declares no members either, but this half of the tagging
    // pair is bound to `POST` and leaves the resource carrying what it wrote, so it
    // keeps the 200 the protocol gives it; its sibling `UntagResource` is the DELETE
    // that answers No Content (see [`crate::state::NO_CONTENT_SUCCESS_STATUS`]).
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        _ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            TagResourceErrorModeled::InternalFailureException(InternalFailureException {
                message: Some("the Amplify emulator has no state store attached".to_string()),
            })
        })?;

        // `resourceArn`'s bounds and pattern, and the size of the map this one request
        // carries, are refused at the boundary BEFORE this handler runs.
        let mut store = state.lock();
        let tags = store
            .resource_tags_mut(&input.resource_arn)
            .map_err(|message| {
                TagResourceErrorModeled::ResourceNotFoundException(ResourceNotFoundException {
                    code: crate::state::RESOURCE_NOT_FOUND_CODE.to_string(),
                    message,
                })
            })?;

        // The bound is on the map the resource is LEFT carrying, so only a key it does
        // not already hold grows it: re-tagging a key the resource has can never exceed
        // the limit. It is checked before anything is written, so a refused call stores
        // none of the pairs it carried.
        let merged = tags.len()
            + input
                .tags
                .keys()
                .filter(|key| !tags.contains_key(*key))
                .count();
        if merged > crate::state::MAX_TAGS_PER_RESOURCE {
            return Err(TagResourceErrorModeled::BadRequestException(BadRequestException {
                message: Some(crate::state::tag_limit_message(&input.resource_arn, merged)),
            })
            .into());
        }

        // Add or overwrite exactly the keys the request names, leaving every other key
        // the resource carries as it was: that is what makes two tag writes of
        // different keys converge on the union of both, and a key written twice end at
        // the value the later write gave it.
        for (key, value) in input.tags {
            tags.insert(key, value);
        }

        Ok(TagResourceOutput {})
    }
}
