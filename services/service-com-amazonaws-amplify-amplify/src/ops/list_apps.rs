/// The largest page `ListApps` serves, and the page it serves a caller that set no
/// bound: `maxResults` is modelled `range 0..100`
/// (`smithy_query(query="operation",operation="ListApps")`).
const MAX_RESULTS: usize = 100;

/// Does `value` satisfy `AppId`'s modelled `length 1..20` and `pattern ^d[a-z0-9]+$`
/// (`smithy_query(query="shape",shape="App")`)?
///
/// A token naming an app that has since been DELETED still satisfies this and is
/// still honoured — the scan resumes at the next id — so a page boundary survives a
/// concurrent delete, which is the behaviour a paging client depends on.
fn is_app_id(value: &str) -> bool {
    let mut rest = value.chars();
    rest.next() == Some('d')
        && value.len() >= 2
        && value.len() <= 20
        && rest.all(|ch| ch.is_ascii_lowercase() || ch.is_ascii_digit())
}
