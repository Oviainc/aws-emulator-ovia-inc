//! @op GetExperiment
//! Reports the persisted experiment `id` names: its current `state.status`,
//! `experimentTemplateId`, the targets, actions and stop conditions copied from its
//! template, and its timestamps. An id naming no record answers
//! `ResourceNotFoundException` (HTTP 404).
//!
