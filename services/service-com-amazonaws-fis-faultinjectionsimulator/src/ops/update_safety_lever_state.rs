impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateSafetyLeverState<Eng>
{
    type Input = UpdateSafetyLeverStateInput;
    type Output = UpdateSafetyLeverStateOutput;
    type Error = UpdateSafetyLeverStateError;

    const NAME: &'static str = "UpdateSafetyLeverState";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_SAFETY_LEVER_STATE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_SAFETY_LEVER_STATE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(crate::scaffolded::Scaffolded::internal_failure(
                crate::state::STORE_UNAVAILABLE,
            ));
        };

        // `state.status` is enum-typed and is persisted on the lever, so a value
        // `SafetyLeverStatusInput` does not admit is refused here rather than stored —
        // worded the way FIS words it, the same sentence the boundary validator's refusal
        // of the same value is reworded to ([`crate::state::safety_lever_status_refusal`]).
        // `engaging` is among the values it refuses: that is a status the SERVICE reaches,
        // never one a request may ask for.
        if let Some(refusal) = crate::state::safety_lever_status_refusal(input.state.status.as_str())
        {
            return Err(UpdateSafetyLeverStateErrorModeled::ValidationException(refusal).into());
        }

        // The lever this account HAS: an id naming anything else names no lever, which is
        // decided before the store is touched so a miss persists nothing.
        if input.id != crate::state::safety_lever_id() {
            return Err(UpdateSafetyLeverStateErrorModeled::ResourceNotFoundException(
                crate::state::safety_lever_not_found(),
            )
            .into());
        }

        let region = crate::state::request_region(ctx.parts());
        let now = ::std::time::SystemTime::now();

        let engaging = input.state.status == crate::state::SafetyLeverStatusKind::Engaged.as_wire();
        // Engaging settles every experiment before it stops the running ones, so it
        // materialises the end of every run that elapsed — and with it the report generation
        // that end makes due, written to the Amazon S3 output each experiment's
        // configuration names. It takes the store lock itself, holding it across no call, so
        // it runs before this handler takes the lock. A disengage settles nothing and so
        // owes nothing.
        if engaging {
            crate::state::materialise_experiment_reports(&*self.engine, ctx, &region, now).await;
        }

        // The guard is taken, spent and RELEASED inside this block: the log records the
        // stops below produced are written after it, so nothing is delivered while the
        // store is locked.
        let (safety_lever, deliveries) = {
            let mut store = state.lock();

            // Engaging the lever stops the experiments that are running. Done before the
            // lever's own state is written, and on the same clock a `StopExperiment` puts an
            // experiment on, so the lever reports `engaging` exactly while the experiments it
            // stopped are on their way to `stopped`.
            if engaging {
                store.stop_experiments_for_safety_lever(now);
            }
            let record = store.settled_safety_lever(now);
            if engaging {
                record.engage(&input.state.reason, now);
            } else {
                record.disengage(&input.state.reason);
            }
            let safety_lever = record.to_safety_lever(&input.id, &region);
            let deliveries = store.take_pending_log_deliveries();
            (safety_lever, deliveries)
        };

        // A stop the lever performed is a move of the stopped experiment's OWN lifecycle,
        // so it is delivered to the destination that experiment's template configured,
        // exactly as a `StopExperiment` of the same experiment would be. Best effort, and
        // never the caller's problem: see [`crate::state::experiment_logs`].
        crate::state::experiment_logs::deliver(ctx, &region, deliveries).await;

        Ok(UpdateSafetyLeverStateOutput {
            safety_lever: Some(safety_lever),
        })
    }
}
