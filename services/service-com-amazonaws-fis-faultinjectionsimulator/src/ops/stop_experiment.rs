//! @op StopExperiment
//! Stops the persisted experiment `id` names: moves its `state.status` to `stopping`
//! with a `state.reason`, and returns the updated record.
//!
//! The move on to `stopped` — and with it `endTime`, "the time that the experiment ended"
//! — is owed to the clock (see [`crate::state::ExperimentRecord::settle`]), so a caller
//! reading the experiment immediately still sees it stopping and a later
//! `GetExperiment` sees it stopped. Stopping an experiment that is already stopping
//! changes nothing, so `endTime` never moves once it is set; stopping one already in a
//! FINAL state is refused with `ValidationException` (HTTP 400) and leaves the record
//! untouched. An id naming no record answers `ResourceNotFoundException` (HTTP 404).
//!
//! Stopping SETTLES the experiment first, so the stop lands on the status the clock
//! already owed — which can be the END of a run that elapsed, the event that makes the
//! experiment's report generation due. That generation
//! ([`crate::state::materialise_experiment_report`]) was due at this instant whether or
//! not anybody called, so it is materialised here as well, including on the path where
//! this handler then REFUSES the stop for the run the settle ended: a caller that reads
//! the experiment afterwards sees the same report state whichever operation observed the
//! end. The run's log records are owed on the same terms — the settle that ends a run
//! produces that run's terminal record, so this call drains the outbox and delivers what
//! it drained whatever it answers the caller (see [`crate::state::experiment_logs`]).
//!
