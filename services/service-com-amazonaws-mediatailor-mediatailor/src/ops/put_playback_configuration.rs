    /// `https://mediatailor.{region}.{dualStackDnsSuffix}`, whose suffix is
    /// `api.aws`). The paths are the documented session (`/v1/session/..`), HLS
    /// (`/v1/master/..`) and DASH (`/v1/dash/..`) prefixes.
