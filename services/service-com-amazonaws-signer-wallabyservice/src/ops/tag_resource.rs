impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_OUTPUT_SCHEMA;
    // `TagResourceResponse` declares no members, so a successful tag write has
    // nothing to report: the answer is the no-content one every such reply of
    // this service carries, not the protocol default the route resolves to.
    const SUCCESS_STATUS: u16 = crate::service::NO_CONTENT_STATUS;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // The ARN the caller supplies carries the region and account the profile
        // lives in, and it is matched against the ARN this service stored for
        // that profile; the request's own region is what says which region's
        // endpoint is answering, and only that region's resources are there to
        // tag.
        let region = crate::state::request_region(ctx.parts());
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(TagResourceErrorModeled::InternalServiceErrorException(
                InternalServiceErrorException {
                    message: Some("the signer profile store is unavailable".to_string()),
                    code: Some(crate::state::ERROR_CODE_INTERNAL_SERVICE_ERROR.to_string()),
                },
            )
            .into());
        };

        // Every key this request carries is held to the modelled `TagKey` shape —
        // its length bounds, AWS's reserved `aws:` namespace and the alphabet its
        // pattern admits — before anything is written, so one key the model does
        // not admit refuses the whole write. The judgement lives in
        // `crate::state` because the framework's boundary validator checks
        // neither: a map KEY is not a constrained leaf there, and `TagKey`'s
        // pattern is a negative lookahead its regex engine cannot compile.
        if let Some((key, problem)) =
            crate::state::invalid_tag_key(input.tags.keys().map(String::as_str))
        {
            return Err(bad_request(
                crate::state::invalid_tag_key_message(key, problem),
                crate::state::ERROR_CODE_BAD_REQUEST.to_string(),
            ));
        }

        // A `resourceArn` that reaches no signing profile is refused by the one
        // mapping all three tagging operations expand (`tagging_arn_refusal!`,
        // stated beside `crate::state::TaggingArnProblem`): the two conditions
        // answer different modelled shapes and statuses, and each carries the
        // `code` naming the condition.
        let mut store = state.lock();
        let profile = store
            .profile_for_tagging_mut(&region, &input.resource_arn)
            .map_err(|problem| -> TagResourceError {
                crate::tagging_arn_refusal!(
                    TagResourceErrorModeled,
                    problem,
                    &input.resource_arn
                )
            })?;

        // A canceled profile is the one status the modelled bad request names, and
        // the gate reads the status the store holds NOW.
        if let Some((message, code)) = profile.tagging_refusal() {
            return Err(bad_request(message, code));
        }

        // What the merge would LEAVE on the profile is what the modelled bound
        // limits, so it is computed before anything is written: a request that
        // would carry the profile past it changes nothing. Re-tagging a key the
        // profile already holds never grows the map.
        let resulting = profile
            .tags
            .keys()
            .map(String::as_str)
            .chain(input.tags.keys().map(String::as_str))
            .collect::<::std::collections::BTreeSet<_>>()
            .len();
        if resulting > crate::state::MAX_TAGS_PER_PROFILE {
            return Err(bad_request(
                crate::state::too_many_tags_message(resulting),
                crate::state::ERROR_CODE_BAD_REQUEST.to_string(),
            ));
        }

        // The write itself: a MERGE, not a replacement. Nothing else on the
        // profile moves — tagging is not a new version of it, so the version, the
        // status and the creation time are left alone.
        for (key, value) in &input.tags {
            profile.tags.insert(key.clone(), value.clone());
        }

        Ok(TagResourceOutput {})
    }
}
