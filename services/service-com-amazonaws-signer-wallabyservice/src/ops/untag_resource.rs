//! @op UntagResource
//!
//! Implemented: removes the named keys from the tags the signing profile
//! `resourceArn` names holds, leaving every key the request does not name — the
//! same map `TagResource` writes and `ListTagsForResource` reports. Removing a key
//! the profile does not hold removes nothing and still succeeds.
//!
//! A label that is not a signing-profile ARN is refused 400 `BadRequestException`;
//! a well-formed ARN naming no stored profile is refused 404 `NotFoundException`;
//! a request naming a key the modelled `TagKey` shape does not admit — one
//! outside its length bounds, one inside AWS's reserved namespace or one
//! carrying a character outside the alphabet its pattern states — is refused 400
//! `BadRequestException`;
//! and a CANCELED profile is refused 400 `BadRequestException` — the shape
//! documents that it "also occurs when you call a tagging API on a cancelled
//! signing profile". A refused call removes nothing.
//!
//! Implemented alongside `ListTagsForResource` (issue
//! `20261023T031331Z-signer-listtagsforresource-stub`): it is the same persisted
//! tag map, and the removal half of the rule that map follows.
