//! `EvaluateCode`, end to end over HTTP: the APPSYNC_JS code a call carries is RUN, and
//! the response is what that run produced.
//!
//! The rules asserted here are stated over CLASSES of input rather than over the one
//! request that exposed the defect:
//!
//! 1. "Evaluates the given code and returns the response … For APPSYNC_JS runtimes, the
//!    code defines the request and response functions": the `evaluationResult` is the JSON
//!    of whatever the named function RETURNED, over a table spanning the value's shape
//!    (object, list, scalar, string, nothing), both `function` values, the default when the
//!    call names none, and the context members the code reads;
//! 2. `logs` is "a list of logs that were generated by calls to util.log.info and
//!    util.log.error in the evaluated code" — and by `console`, which an APPSYNC_JS
//!    resolver logs with too — in the order the code wrote them;
//! 3. the `stash` "lives through a single resolver run", so the response reports it as the
//!    run left it, and `outErrors` reports the errors the run appended without ending it;
//! 4. code that RAISES is a served call whose `error` carries the error's own message, and
//!    no `evaluationResult`;
//! 5. code that defines nothing the call could run — it does not compile, it exports no
//!    function of the requested name, or it imports a module the runtime does not provide —
//!    is a 400 `BadRequestException` whose `reason` is `CODE_ERROR` and whose `detail`
//!    carries one `CodeError` per fault;
//! 6. a member this operation cannot run with (`runtimeVersion` other than the one allowed
//!    version, a `function` outside the two valid values, a `context` that is not a map) is
//!    a 400 `BadRequestException` naming that member;
//! 7. the run is CONTAINED and BOUNDED: no host surface is reachable from the code, nothing
//!    of one call is reachable from the next, and code that does not end is stopped and
//!    reported as stopped rather than holding the call open.
//!
//! Every assertion goes through the router the production emulator mounts, so these
//! exercise routing, restJson1 (de)serialization, the handler and the embedded engine
//! together.

use std::time::{SystemTime, UNIX_EPOCH};

use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

// The router and the request helper are the crate's shared test harness, reused rather
// than copied.
use super::error_contract::{call, router, Answer};

/// The operation's own path: `POST /v1/dataplane-evaluatecode`
/// (`smithy_query(query="operation", operation="EvaluateCode")`).
const PATH: &str = "/v1/dataplane-evaluatecode";

/// The only runtime AppSync supports, as `AppSyncRuntime` requires both its members:
/// `name` "the only allowed value is APPSYNC_JS" and `runtimeVersion` "the only allowed
/// version is 1.0.0".
const RUNTIME: (&str, &str) = ("APPSYNC_JS", "1.0.0");

/// The module an APPSYNC_JS resolver imports `util` from.
const UTILS: &str = "@aws-appsync/utils";

/// One `EvaluateCode` request body.
fn body(code: &str, context: &str, function: Option<&str>) -> Value {
    let mut request = json!({
        "runtime": {"name": RUNTIME.0, "runtimeVersion": RUNTIME.1},
        "code": code,
        "context": context,
    });
    if let Some(function) = function {
        request["function"] = json!(function);
    }
    request
}

/// Evaluate `code` over `context` and return what the emulator answered.
async fn evaluate(
    router: &MultiServiceRouter,
    code: &str,
    context: &str,
    function: Option<&str>,
) -> Answer {
    call(router, "POST", PATH, Some(body(code, context, function))).await
}

/// The `logs` of an answer, as the strings the response carries.
fn logs(answer: &Answer) -> Vec<String> {
    answer.body["logs"]
        .as_array()
        .map(|entries| {
            entries
                .iter()
                .map(|entry| entry.as_str().unwrap_or_default().to_string())
                .collect()
        })
        .unwrap_or_default()
}

/// Rule 1: the `evaluationResult` is the JSON of what the evaluated function returned.
#[tokio::test]
async fn the_evaluation_result_is_what_the_evaluated_function_returned() {
    let router = router();

    // The rows differ along what the rule generalises over: the shape of the returned
    // value, which of the two functions is evaluated, whether the call names one at all,
    // and which context members the code reads.
    let both_functions = "export function request(ctx) { return {from: 'request'} }\n\
                          export function response(ctx) { return {from: 'response'} }\n";
    let cases: &[(&str, &str, &str, Option<&str>, &str)] = &[
        (
            "a request function building a data-source operation",
            "export function request(ctx) { return {operation: 'GetItem', key: {id: ctx.args.id}} }",
            r#"{"args":{"id":"7"}}"#,
            Some("request"),
            r#"{"operation":"GetItem","key":{"id":"7"}}"#,
        ),
        (
            "a response function passing the data source result through",
            "export function request(ctx) { return {} }\n\
             export function response(ctx) { return ctx.result }\n",
            r#"{"result":{"id":"7","name":"a name"}}"#,
            Some("response"),
            r#"{"id":"7","name":"a name"}"#,
        ),
        (
            "the request function when the call names no function",
            both_functions,
            r#"{"args":{}}"#,
            None,
            r#"{"from":"request"}"#,
        ),
        (
            "the response function of the same code",
            both_functions,
            r#"{"args":{}}"#,
            Some("response"),
            r#"{"from":"response"}"#,
        ),
        (
            "a list filtered out of the context",
            "export function request(ctx) { return ctx.args.items.filter(i => i.keep) }",
            r#"{"args":{"items":[{"id":1,"keep":true},{"id":2,"keep":false}]}}"#,
            Some("request"),
            r#"[{"id":1,"keep":true}]"#,
        ),
        (
            "a number computed from the context",
            "export function request(ctx) { return ctx.args.n * 2 }",
            r#"{"args":{"n":21}}"#,
            Some("request"),
            "42",
        ),
        (
            "a string built from the context",
            "export function request(ctx) { return 'hello ' + ctx.args.who }",
            r#"{"args":{"who":"world"}}"#,
            Some("request"),
            r#""hello world""#,
        ),
        (
            "a boolean",
            "export function request(ctx) { return ctx.args.flag === true }",
            r#"{"args":{"flag":true}}"#,
            Some("request"),
            "true",
        ),
        (
            "a function that returns nothing",
            "export function request(ctx) { }",
            "{}",
            Some("request"),
            "null",
        ),
        (
            "a function that returns null",
            "export function request(ctx) { return null }",
            "{}",
            Some("request"),
            "null",
        ),
        (
            "a response function reading a result the context does not carry",
            "export function response(ctx) { return ctx.result }",
            "{}",
            Some("response"),
            "null",
        ),
        (
            "an early return through the util module",
            &format!(
                "import {{ runtime }} from '{UTILS}';\n\
                 export function request(ctx) {{ runtime.earlyReturn({{done: true}}); \
                 return {{done: false}} }}\n"
            ),
            "{}",
            Some("request"),
            r#"{"done":true}"#,
        ),
    ];

    for (case, code, context, function, expected) in cases {
        let answer = evaluate(&router, code, context, *function).await;
        assert_eq!(
            answer.status, 200,
            "case {case:?}: expected status 200, got {answer:?}"
        );
        assert_eq!(
            answer.body["evaluationResult"].as_str(),
            Some(*expected),
            "case {case:?}: expected the evaluated function's own answer, got {answer:?}"
        );
        assert!(
            answer.body.get("error").is_none(),
            "case {case:?}: expected no error payload, got {answer:?}"
        );
    }
}

/// Rule 2: `logs` carries the lines the code wrote, in order.
#[tokio::test]
async fn the_logs_are_the_lines_the_code_wrote() {
    let router = router();

    // The rows differ along which logger the code used and what it was handed.
    let cases: &[(&str, String, Vec<&str>)] = &[
        (
            "util.log.info and util.log.error, in order",
            format!(
                "import {{ util }} from '{UTILS}';\n\
                 export function request(ctx) {{ util.log.info('one'); \
                 util.log.error('two'); return {{}} }}\n"
            ),
            vec!["INFO - one", "ERROR - two"],
        ),
        (
            "util.log.info over several arguments",
            format!(
                "import {{ util }} from '{UTILS}';\n\
                 export function request(ctx) {{ util.log.info('a', 'b'); return {{}} }}\n"
            ),
            vec!["INFO - a b"],
        ),
        (
            "util.log.info over a document",
            format!(
                "import {{ util }} from '{UTILS}';\n\
                 export function request(ctx) {{ util.log.info(ctx.args); return {{}} }}\n"
            ),
            vec![r#"INFO - {"n":1}"#],
        ),
        (
            "console.log and console.error",
            "export function request(ctx) { console.log('out'); console.error('bad'); \
             return {} }"
                .to_string(),
            vec!["INFO - out", "ERROR - bad"],
        ),
        (
            "code that logs nothing",
            "export function request(ctx) { return {} }".to_string(),
            vec![],
        ),
    ];

    for (case, code, expected) in cases {
        let answer = evaluate(&router, code, r#"{"args":{"n":1}}"#, Some("request")).await;
        assert_eq!(
            answer.status, 200,
            "case {case:?}: expected status 200, got {answer:?}"
        );
        assert_eq!(
            logs(&answer),
            *expected,
            "case {case:?}: expected the lines the code wrote, got {answer:?}"
        );
    }
}

/// Rule 3: the stash is reported as the run left it, and the appended errors as a list,
/// without either ending the run.
#[tokio::test]
async fn the_stash_and_the_appended_errors_are_what_the_run_left() {
    let router = router();

    let wrote_stash = evaluate(
        &router,
        "export function request(ctx) { ctx.stash.seen = ctx.args.n; return {ok: true} }",
        r#"{"args":{"n":3}}"#,
        Some("request"),
    )
    .await;
    assert_eq!(
        wrote_stash.body["evaluationResult"].as_str(),
        Some(r#"{"ok":true}"#),
        "case a run that writes to the stash: expected its own answer, got {wrote_stash:?}"
    );
    assert_eq!(
        wrote_stash.body["stash"].as_str(),
        Some(r#"{"seen":3}"#),
        "case a run that writes to the stash: expected the stash it left, got {wrote_stash:?}"
    );

    // A run that writes nothing to the stash leaves nothing to report.
    let untouched = evaluate(
        &router,
        "export function request(ctx) { return {ok: true} }",
        "{}",
        Some("request"),
    )
    .await;
    assert!(
        untouched.body.get("stash").is_none(),
        "case a run that leaves the stash empty: expected no stash member, got {untouched:?}"
    );

    // A stash the CALLER put in the context is carried into the run and read back.
    let carried = evaluate(
        &router,
        "export function request(ctx) { ctx.stash.added = true; return ctx.stash.given }",
        r#"{"stash":{"given":"from the caller"}}"#,
        Some("request"),
    )
    .await;
    assert_eq!(
        carried.body["evaluationResult"].as_str(),
        Some(r#""from the caller""#),
        "case a stash the caller supplied: expected the code to read it, got {carried:?}"
    );
    assert_eq!(
        carried.body["stash"].as_str(),
        Some(r#"{"given":"from the caller","added":true}"#),
        "case a stash the caller supplied: expected both members, got {carried:?}"
    );

    // `util.appendError` "adds an error to the response" and the run goes on.
    let appended = evaluate(
        &router,
        &format!(
            "import {{ util }} from '{UTILS}';\n\
             export function request(ctx) {{ util.appendError('first', 'FirstType'); \
             util.appendError('second'); return {{ok: true}} }}\n"
        ),
        "{}",
        Some("request"),
    )
    .await;
    assert_eq!(
        appended.body["evaluationResult"].as_str(),
        Some(r#"{"ok":true}"#),
        "case appended errors: expected the run to go on, got {appended:?}"
    );
    let out_errors: Value = serde_json::from_str(
        appended.body["outErrors"]
            .as_str()
            .unwrap_or_else(|| panic!("case appended errors: expected outErrors, got {appended:?}")),
    )
    .expect("case appended errors: outErrors is a JSON document");
    assert_eq!(
        out_errors,
        json!([
            {"message": "first", "errorType": "FirstType", "data": null, "errorInfo": null},
            {"message": "second", "errorType": null, "data": null, "errorInfo": null},
        ]),
        "case appended errors: expected both errors in order, got {appended:?}"
    );

    // A run that appends none reports no list at all.
    assert!(
        untouched.body.get("outErrors").is_none(),
        "case a run that appends no error: expected no outErrors member, got {untouched:?}"
    );
}

/// Rule 4: code that raises is a served call carrying the error's own message.
#[tokio::test]
async fn code_that_raises_is_reported_as_the_response_error() {
    let router = router();

    // The rows differ along HOW the run failed: a thrown error, the util module's own
    // raise, a type error the code made, a module body that raises, and a name the
    // sandbox does not define.
    let cases: &[(&str, String, &str)] = &[
        (
            "a thrown error",
            "export function request(ctx) { throw new Error('boom') }".to_string(),
            "boom",
        ),
        (
            "util.error",
            format!(
                "import {{ util }} from '{UTILS}';\n\
                 export function request(ctx) {{ util.error('no', 'Refused') }}\n"
            ),
            "no",
        ),
        (
            "util.unauthorized",
            format!(
                "import {{ util }} from '{UTILS}';\n\
                 export function request(ctx) {{ util.unauthorized() }}\n"
            ),
            "Unauthorized",
        ),
        (
            "a module body that raises",
            "throw new Error('at load');\nexport function request(ctx) { return {} }\n".to_string(),
            "at load",
        ),
    ];

    for (case, code, expected) in cases {
        let answer = evaluate(&router, code, "{}", Some("request")).await;
        assert_eq!(
            answer.status, 200,
            "case {case:?}: expected the call itself to be served, got {answer:?}"
        );
        assert_eq!(
            answer.body["error"]["message"].as_str(),
            Some(*expected),
            "case {case:?}: expected the error's own message, got {answer:?}"
        );
        assert!(
            answer.body.get("evaluationResult").is_none(),
            "case {case:?}: expected no evaluation result, got {answer:?}"
        );
    }

    // A failure the code itself made still names what went wrong, without this emulator
    // choosing the words: the engine's own message is reported.
    for (case, code, named) in [
        (
            "a member read off nothing",
            "export function request(ctx) { return ctx.args.missing.deep }",
            "deep",
        ),
        (
            "a name the sandbox does not define",
            "export function request(ctx) { return process.env.AWS_REGION }",
            "process",
        ),
    ] {
        let answer = evaluate(&router, code, r#"{"args":{}}"#, Some("request")).await;
        let message = answer.body["error"]["message"]
            .as_str()
            .unwrap_or_default()
            .to_string();
        assert_eq!(
            answer.status, 200,
            "case {case:?}: expected the call itself to be served, got {answer:?}"
        );
        assert!(
            message.contains(named),
            "case {case:?}: expected the engine's message to name {named:?}, got {answer:?}"
        );
    }
}

/// Rule 5: code that defines nothing the call could run is a bad request carrying the
/// `CODE_ERROR` detail.
#[tokio::test]
async fn code_that_defines_nothing_runnable_is_a_code_error_bad_request() {
    let router = router();

    // The rows differ along the kind of fault and the `errorType` it is reported under.
    let cases: &[(&str, String, Option<&str>, &str, &str)] = &[
        (
            "code that does not compile",
            "export function request(ctx) { return (((( }".to_string(),
            Some("request"),
            "PARSER_ERROR",
            "",
        ),
        (
            "code that is not a module at all",
            "this is not javascript at all".to_string(),
            Some("request"),
            "PARSER_ERROR",
            "",
        ),
        (
            "code that exports no function of the requested name",
            "export function request(ctx) { return {} }".to_string(),
            Some("response"),
            "LINT_ERROR",
            "response",
        ),
        (
            "code whose only export is not a function",
            "export const request = 42;".to_string(),
            Some("request"),
            "LINT_ERROR",
            "request",
        ),
        (
            "code that imports a module the runtime does not provide",
            "import fs from 'node:fs';\nexport function request(ctx) { return {} }\n".to_string(),
            Some("request"),
            "PARSER_ERROR",
            "node:fs",
        ),
    ];

    for (case, code, function, error_type, named) in cases {
        let answer = evaluate(&router, code, "{}", *function).await;
        assert_eq!(
            answer.status, 400,
            "case {case:?}: expected status 400, got {answer:?}"
        );
        assert_eq!(
            answer.error_type, "BadRequestException",
            "case {case:?}: expected error type BadRequestException, got {answer:?}"
        );
        assert_eq!(
            answer.message, "Invalid code given.",
            "case {case:?}: expected the refusal to name the code member, got {answer:?}"
        );
        assert_eq!(
            answer.body["reason"].as_str(),
            Some("CODE_ERROR"),
            "case {case:?}: expected the CODE_ERROR reason, got {answer:?}"
        );
        let faults = answer.body["detail"]["codeErrors"]
            .as_array()
            .cloned()
            .unwrap_or_default();
        assert_eq!(
            faults.len(),
            1,
            "case {case:?}: expected one code error, got {answer:?}"
        );
        assert_eq!(
            faults[0]["errorType"].as_str(),
            Some(*error_type),
            "case {case:?}: expected the {error_type} type, got {answer:?}"
        );
        let value = faults[0]["value"].as_str().unwrap_or_default();
        assert!(
            !value.is_empty() && value.contains(named),
            "case {case:?}: expected a presentable error naming {named:?}, got {answer:?}"
        );
        // "The line number in the code. Defaults to 0 if unknown"; "The span/length of the
        // error. Defaults to -1 if unknown" (`CodeErrorLocation`).
        assert_eq!(
            faults[0]["location"],
            json!({"line": 0, "column": 0, "span": -1}),
            "case {case:?}: expected the documented unknown location, got {answer:?}"
        );
    }
}

/// Rule 6: a member this operation cannot run with is a bad request naming it.
#[tokio::test]
async fn a_member_the_operation_cannot_run_with_is_named_by_the_refusal() {
    let router = router();
    let code = "export function request(ctx) { return {} }";

    // One row per member, each at several values of the class the rule refuses.
    for version in ["1.0.1", "2.0.0", "1.0", ""] {
        let case = format!("runtimeVersion {version:?}");
        let mut request = body(code, "{}", Some("request"));
        request["runtime"]["runtimeVersion"] = json!(version);
        let answer = call(&router, "POST", PATH, Some(request)).await;
        assert_eq!(
            answer.status, 400,
            "case {case:?}: expected status 400, got {answer:?}"
        );
        assert_eq!(
            answer.message, "Invalid runtimeVersion given.",
            "case {case:?}: expected the refusal to name runtimeVersion, got {answer:?}"
        );
    }

    for function in ["handler", "Request", "RESPONSE", "onPublish", ""] {
        let case = format!("function {function:?}");
        let answer = evaluate(&router, code, "{}", Some(function)).await;
        assert_eq!(
            answer.status, 400,
            "case {case:?}: expected status 400, got {answer:?}"
        );
        assert_eq!(
            answer.message, r#"Function must be "request", or "response""#,
            "case {case:?}: expected AppSync's fixed text listing the two values, \
             got {answer:?}"
        );
    }

    // A context that is not a map carries no member the code could read. Every row is at
    // least the two characters `Context`'s `@length` requires, so the boundary validator
    // passes it through to the handler.
    for context in ["not json", "[]", "[1]", r#""text""#, "12", "null", "true"] {
        let case = format!("context {context:?}");
        let answer = evaluate(&router, code, context, Some("request")).await;
        assert_eq!(
            answer.status, 400,
            "case {case:?}: expected status 400, got {answer:?}"
        );
        assert_eq!(
            answer.message, "Invalid context given.",
            "case {case:?}: expected the refusal to name context, got {answer:?}"
        );
    }
}

/// Rule 7: the run is contained — no host surface is reachable from the evaluated code.
#[tokio::test]
async fn no_host_surface_is_reachable_from_the_evaluated_code() {
    let router = router();

    // The names a resolver might reach a host through on another JavaScript runtime: a
    // process, a module loader, a network client, a timer, and the modules QuickJS's own
    // host library would have registered. None of them is defined in this sandbox.
    let names = [
        "process",
        "require",
        "module",
        "exports",
        "fetch",
        "XMLHttpRequest",
        "WebSocket",
        "setTimeout",
        "setInterval",
        "setImmediate",
        "std",
        "os",
        "Deno",
        "Buffer",
        "__dirname",
        "importScripts",
    ];
    for name in names {
        let answer = evaluate(
            &router,
            &format!("export function request(ctx) {{ return typeof {name} }}"),
            "{}",
            Some("request"),
        )
        .await;
        assert_eq!(
            answer.status, 200,
            "case the name {name:?}: expected status 200, got {answer:?}"
        );
        assert_eq!(
            answer.body["evaluationResult"].as_str(),
            Some(r#""undefined""#),
            "case the name {name:?}: expected it to be undefined in the sandbox, got {answer:?}"
        );
    }

    // Nothing of one evaluation is reachable from the next: each call gets a fresh engine.
    let first = evaluate(
        &router,
        "export function request(ctx) { globalThis.leaked = 'yes'; return 'set' }",
        "{}",
        Some("request"),
    )
    .await;
    assert_eq!(
        first.body["evaluationResult"].as_str(),
        Some(r#""set""#),
        "case a call that writes a global: expected it to be served, got {first:?}"
    );
    let second = evaluate(
        &router,
        "export function request(ctx) { return typeof globalThis.leaked }",
        "{}",
        Some("request"),
    )
    .await;
    assert_eq!(
        second.body["evaluationResult"].as_str(),
        Some(r#""undefined""#),
        "case the next call: expected no global of the previous one, got {second:?}"
    );
}

/// Rule 7: the run is bounded — code that does not end is stopped, and the stop is
/// reported rather than the answer the code then gives.
#[tokio::test]
async fn code_that_does_not_end_is_stopped_and_reported_as_stopped() {
    let router = router();

    // The rows differ along how the code refuses to end: a loop that makes no progress,
    // the same loop catching what the engine raises in it, and a recursion with no base
    // case (which the engine's own stack ceiling ends).
    let cases: &[(&str, &str, bool)] = &[
        (
            "a loop that makes no progress",
            "export function request(ctx) { while (true) {} }",
            true,
        ),
        (
            "a loop that catches what the engine raises",
            "export function request(ctx) { while (true) { try { } catch (error) { } } }",
            true,
        ),
        (
            "a loop that returns a value after catching",
            "export function request(ctx) { while (true) { try { } catch (error) { \
             return {escaped: true} } } }",
            true,
        ),
        (
            "a recursion with no base case",
            "export function request(ctx) { function down(n) { return down(n + 1) } \
             return down(0) }",
            false,
        ),
    ];

    for (case, code, stopped) in cases {
        let answer = evaluate(&router, code, "{}", Some("request")).await;
        assert_eq!(
            answer.status, 200,
            "case {case:?}: expected the call itself to be served, got {answer:?}"
        );
        let message = answer.body["error"]["message"]
            .as_str()
            .unwrap_or_default()
            .to_string();
        assert!(
            !message.is_empty(),
            "case {case:?}: expected the failure to be reported, got {answer:?}"
        );
        assert!(
            answer.body.get("evaluationResult").is_none(),
            "case {case:?}: expected no evaluation result, got {answer:?}"
        );
        if *stopped {
            assert!(
                message.contains("stopped"),
                "case {case:?}: expected the run to be reported as stopped, got {answer:?}"
            );
        }
    }
}

/// The answer, the log and the appended-error list are each CAPPED, so a small request
/// cannot make an unbounded response.
#[tokio::test]
async fn the_answer_the_log_and_the_error_list_are_capped() {
    let router = router();

    // `EvaluationResult` is modelled `@length 0..65536`, so a result past that is not one
    // the response can carry: the run is reported as stopped instead.
    let oversized = evaluate(
        &router,
        "export function request(ctx) { return 'x'.repeat(200000) }",
        "{}",
        Some("request"),
    )
    .await;
    assert_eq!(
        oversized.status, 200,
        "case a result past the modelled length: expected the call to be served, \
         got {oversized:?}"
    );
    assert!(
        oversized.body["error"]["message"]
            .as_str()
            .unwrap_or_default()
            .contains("more than"),
        "case a result past the modelled length: expected the ceiling to be reported, \
         got {oversized:?}"
    );
    assert!(
        oversized.body.get("evaluationResult").is_none(),
        "case a result past the modelled length: expected no evaluation result, \
         got {oversized:?}"
    );

    // One run cannot write an unbounded log, however many lines it asks for.
    let many_lines = evaluate(
        &router,
        "export function request(ctx) { for (let i = 0; i < 500; i++) { console.log(i) } \
         return {} }",
        "{}",
        Some("request"),
    )
    .await;
    let written = logs(&many_lines);
    assert!(
        !written.is_empty() && written.len() <= 100,
        "case a run that logs 500 lines: expected the line count to be capped, \
         got {} lines",
        written.len()
    );

    // Nor an unbounded list of appended errors.
    let many_errors = evaluate(
        &router,
        &format!(
            "import {{ util }} from '{UTILS}';\n\
             export function request(ctx) {{ for (let i = 0; i < 500; i++) \
             {{ util.appendError('e' + i) }} return {{}} }}\n"
        ),
        "{}",
        Some("request"),
    )
    .await;
    let appended: Value = serde_json::from_str(
        many_errors.body["outErrors"]
            .as_str()
            .unwrap_or_else(|| panic!("case 500 appended errors: expected outErrors, \
                 got {many_errors:?}")),
    )
    .expect("case 500 appended errors: outErrors is a JSON document");
    let count = appended.as_array().map(Vec::len).unwrap_or_default();
    assert!(
        count > 0 && count <= 100,
        "case 500 appended errors: expected the list to be capped, got {count} errors"
    );
}

/// The `util` helpers that answer with a value rather than with control flow compute it
/// here: `util.autoId` mints a fresh identifier and `util.time` reads this process's clock.
#[tokio::test]
async fn the_util_helpers_that_compute_a_value_compute_it_in_the_run() {
    let router = router();
    let code = format!(
        "import {{ util }} from '{UTILS}';\n\
         export function request(ctx) {{ return {{id: util.autoId(), \
         millis: util.time.nowEpochMilliSeconds(), seconds: util.time.nowEpochSeconds(), \
         at: util.time.nowISO8601()}} }}\n"
    );

    let mut minted = Vec::new();
    for turn in 0..3 {
        let case = format!("turn {turn}");
        let answer = evaluate(&router, &code, "{}", Some("request")).await;
        assert_eq!(
            answer.status, 200,
            "case {case:?}: expected status 200, got {answer:?}"
        );
        let result: Value = serde_json::from_str(
            answer.body["evaluationResult"]
                .as_str()
                .unwrap_or_else(|| panic!("case {case:?}: expected a result, got {answer:?}")),
        )
        .expect("the evaluation result is a JSON document");

        let id = result["id"].as_str().unwrap_or_default().to_string();
        let parsed = uuid::Uuid::parse_str(&id)
            .unwrap_or_else(|error| panic!("case {case:?}: expected a UUID, got {id:?}: {error}"));
        assert_eq!(
            parsed.get_version_num(),
            4,
            "case {case:?}: expected a version 4 id, got {id:?}"
        );
        assert!(
            !minted.contains(&id),
            "case {case:?}: expected a fresh id, got {id:?} again"
        );
        minted.push(id);

        let now_millis = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .expect("the clock is after the epoch")
            .as_millis() as i64;
        let millis = result["millis"].as_i64().unwrap_or_default();
        let seconds = result["seconds"].as_i64().unwrap_or_default();
        assert!(
            (millis - now_millis).abs() < 60_000,
            "case {case:?}: expected the clock this process reads, got {millis} against \
             {now_millis}"
        );
        assert_eq!(
            seconds,
            millis / 1_000,
            "case {case:?}: expected the seconds to be the same instant, got {result:?}"
        );
        let at = result["at"].as_str().unwrap_or_default();
        assert!(
            at.len() == 24 && at.ends_with('Z'),
            "case {case:?}: expected an ISO 8601 instant, got {at:?}"
        );
    }
}
