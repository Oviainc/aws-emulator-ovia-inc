//!   rule is expressible in the model, so both are refused here with the operation's own
//!   modelled `ValidationException` (HTTP 400);
//! * the group must exist, or the operation answers its modelled
//!   `ResourceNotFoundException` (HTTP 404);
//! * `profilingGroupName` comes from the STORED group record, and
//!   `profileStartTime`/`profileEndTime` from the receipt times of the AGGREGATED agent
//!   profiles that group retains inside the requested window — the profiles the analysis
//!   is about. A profile the service has received but whose aggregation is not due yet is
//!   part of no aggregated profile, so it is part of no analysed span either, exactly as
//!   `GetProfile` and `ListProfileTimes` do not report it. A window the group retains no
//!   such profile in covers nothing, so the requested bounds are reported back as the
//!   (empty) analysed span.
//!
//! `recommendations` holds NO findings, and `anomalies` holds only what was recorded
//! against the group. This emulator stores an agent profile as the opaque payload
//! `PostAgentProfile` uploaded (`GetProfile` hands the same bytes back byte-identical) and
//! runs no anti-pattern matcher or anomaly detector over it: nothing here parses a profile,
//! so there is no match and no anomaly for an analysis of its own to report. Inventing
//! `Recommendation`/`Anomaly` entries would be output synthesised to look computed, so
