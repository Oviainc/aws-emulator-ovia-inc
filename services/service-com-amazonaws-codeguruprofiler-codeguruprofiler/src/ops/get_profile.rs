/// The representations this service serves an aggregated profile in, as the model's
/// `GetProfile$accept` doc names them: "application/json — standard JSON format" and
/// "application/x-amzn-ion — the Amazon Ion data format".
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Representation {
    Json,
    Ion,
}

impl Representation {
    /// Every representation. The order breaks a tie between two the request accepts
    /// equally and that the stored profile is in neither of, so one request has one
    /// answer.
    const ALL: [Self; 2] = [Self::Json, Self::Ion];

    /// The representation a served profile is announced under when nothing about it names
    /// one of them, as the model's `GetProfileResponse$contentType` doc names it: "The
    /// content type of the profile in the payload. It is either application/json or the
    /// default application/x-amzn-ion."
    const DEFAULT: Self = Self::Ion;

    /// The media type this representation is announced and requested under: its media
    /// TYPE and SUBTYPE, which are also what a media range in an `Accept` header matches
    /// against.
    fn type_and_subtype(self) -> (&'static str, &'static str) {
        match self {
            Self::Json => ("application", "json"),
            Self::Ion => ("application", "x-amzn-ion"),
        }
    }

    /// This representation's media type, as `contentType` announces it.
    fn media_type(self) -> &'static str {
        match self {
            Self::Json => "application/json",
            Self::Ion => "application/x-amzn-ion",
        }
    }

    /// The representation `media_type` names, or `None` for a media type that is neither
    /// of them (including one that is no media type at all). The parse and the comparison
    /// are the `mime` crate's, so the media-type grammar decides what names what: the
    /// comparison is on the type and subtype, which are case-insensitive and carry no
    /// parameter — `application/json; charset=utf-8` and `APPLICATION/JSON` both name
    /// JSON.
    fn of(media_type: &str) -> Option<Self> {
        let parsed: ::mime::Mime = media_type.parse().ok()?;
        Self::ALL.into_iter().find(|representation| {
            let (media_type, subtype) = representation.type_and_subtype();
            parsed.type_() == media_type && parsed.subtype() == subtype
        })
    }

    /// The representation the stored media type `media_type` announces, out of the ones
    /// this service serves: the one it names ([`Self::of`]), and [`Self::DEFAULT`] where
    /// it names neither — a media type of some other format, or no media type at all.
    ///
    /// The media type an upload was announced under is a caller's string, and never what a
    /// response reports: the media types this service announces a profile under are the
    /// two it reads and writes, so an announcement outside them names no representation to
    /// report and leaves the default.
    fn announced(media_type: &str) -> Self {
        Self::of(media_type).unwrap_or(Self::DEFAULT)
    }

    /// Whether the media range `range` allows this representation: a range allows it when
    /// it names its type and subtype, that type's wildcard (`application/*`) or the
    /// wildcard that allows anything (`*/*`).
    fn allowed_by(self, range: &::mime::Mime) -> bool {
        let (media_type, subtype) = self.type_and_subtype();
        (range.type_() == ::mime::STAR || range.type_() == media_type)
            && (range.subtype() == ::mime::STAR || range.subtype() == subtype)
    }
}

/// The representation an `Accept` header asks for, out of the ones this service serves,
/// or `None` when it asks for none of them.
///
/// `Accept` is a comma-separated list of media ranges, each with an optional quality: the
/// representation to serve is the one the header gives the highest quality, and a quality
/// of zero is how a caller says a representation is NOT acceptable. A tie goes to the
/// representation the profile is already stored in (`stored`), which is the one the
/// service can serve without re-encoding it.
fn negotiated(accept: &str, stored: Option<Representation>) -> Option<Representation> {
    let mut best: Option<(Representation, f32)> = None;
    for representation in Representation::ALL {
        let Some(quality) = quality_of(accept, representation) else {
            continue;
        };
        let better = match best {
            None => true,
            Some((chosen, best_quality)) => match quality.total_cmp(&best_quality) {
                Ordering::Greater => true,
                Ordering::Equal => {
                    Some(representation) == stored && Some(chosen) != stored
                }
                Ordering::Less => false,
            },
        };
        if better {
            best = Some((representation, quality));
        }
    }
    best.map(|(representation, _)| representation)
}

/// The quality the `Accept` header `accept` gives `representation`: the highest quality
/// of any media range in it that allows that representation, or `None` when no range
/// does.
///
/// A range that is not a media range at all names nothing and is skipped; a range whose
/// quality is zero (or is not a number) allows nothing, so it is skipped too.
fn quality_of(accept: &str, representation: Representation) -> Option<f32> {
    accept
        .split(',')
        .filter_map(|range| range.trim().parse::<::mime::Mime>().ok())
        .filter(|range| representation.allowed_by(range))
        .filter_map(|range| match range.get_param("q") {
            None => Some(1.0),
            Some(quality) => quality.as_str().parse::<f32>().ok(),
        })
        .filter(|quality| *quality > 0.0)
        .max_by(|left, right| left.total_cmp(right))
}

/// How many container levels deep this operation reads a profile document.
///
/// A profile is a document a caller posted, so its nesting is caller-controlled: the read
/// that re-encodes or depth-bounds one DESCENDS into it, one frame per level, so the
/// descent is bounded here rather than by the request — in BOTH representations, the JSON
/// one by the limit `serde_json` applies to its own parse and the Ion one by
/// [`ion_document`], which drives the reader level by level so nothing recurses on a
/// caller-chosen depth. The number is `serde_json`'s own default, so neither
/// representation is read deeper than the other. A document nested deeper than this is
/// not one this operation re-encodes — it is served exactly as it is stored, announced
/// under one of the two media types this service serves.
const DOCUMENT_NESTING_LIMIT: u32 = 128;

/// The bytes to serve and the media type to announce them under, for `profile` read with
/// the request's `accept` and `max_depth`.
///
/// The two inputs are what the caller asks the service to do with the aggregated profile:
/// serve it in a representation the caller understands (`accept`), and leave out the
/// frames below a depth (`maxDepth`, whose doc: "if the maxDepth is set to 2, then the
/// aggregated profile contains representations of methods A and B"). Neither is a
/// constraint on the request, so neither can refuse one: a profile the caller accepts in
/// the representation its bytes already are a document in and asks for no depth bound on
/// is served byte for byte, and anything else is the stored document re-encoded. The
/// representation a stored profile is read in is the one its bytes are a document in
/// ([`stored_document`]), never the one they were announced under, so both members are
/// honoured for every stored profile this service can read at all. `contentType` reports
/// the representation the served bytes are announced in, which is always one of the two
/// this service serves ([`Representation::media_type`]) and never a media type carried
/// over from an upload: bytes that are a document in NEITHER representation hold no frames
/// this service can see — there is nothing in them to re-encode or to bound — so they are
/// served as stored, announced under the representation their stored media type names, or
/// under the default ([`Representation::announced`]) when it names neither.
fn served_profile(
    profile: &crate::state::AgentProfile,
    accept: Option<&str>,
    max_depth: Option<i32>,
) -> (Vec<u8>, String) {
    let Some((stored, document)) = stored_document(profile) else {
        // Bytes that are a document in neither representation: served as stored, and
        // announced under the representation this service serves that their stored media
        // type names — the default where it names neither, since a media type this service
        // does not serve is not one `contentType` can report.
        return (
            profile.bytes.clone(),
            Representation::announced(&profile.content_type)
                .media_type()
                .to_string(),
        );
    };
    // The stored bytes, announced under the representation they ARE a document in: the
    // answer whenever the document itself is not to be changed, and the one left when a
    // document that was read cannot be written back out.
    let as_read = || (profile.bytes.clone(), stored.media_type().to_string());

    // The caller accepts the representation the profile already is a document in and asks
    // for no depth bound: nothing is to be done to the document, so the stored bytes
    // themselves are the answer.
    if kept_depth(max_depth).is_none() && wanted_representation(stored, accept) == stored {
        return as_read();
    }
    written(&document, stored, accept, max_depth).unwrap_or_else(as_read)
}

/// The call-stack depth a request bounds the served profile to, as a count of container
/// levels, or `None` when it bounds none.
///
/// The modelled range is 1..10000, so the boundary validator has already refused anything
/// else; a value outside it bounds nothing rather than panicking here.
fn kept_depth(max_depth: Option<i32>) -> Option<u32> {
    max_depth.and_then(|depth| u32::try_from(depth).ok())
}

/// The representation a profile already a document in `stored` is served in for a request
/// whose `Accept` is `accept`: the one that header asks for, and `stored` where it asks
/// for neither of the two this service serves (including when there is no header at all).
fn wanted_representation(stored: Representation, accept: Option<&str>) -> Representation {
    accept
        .and_then(|accept| negotiated(accept, Some(stored)))
        .unwrap_or(stored)
}

/// `document` written out for a request that accepts `accept` and bounds the call-stack
/// depth to `max_depth`, with the media type the written bytes are announced under — or
/// `None` when the document cannot be bounded or written out at all.
///
/// `stored` is the representation the document is already a document in, which is the one
/// it is written in where the request accepts it. This is the one place the two members
/// saying what to DO with an aggregated profile are applied, so a single stored profile
/// ([`served_profile`]) and a combination of several ([`served_aggregate`]) honour them
/// identically.
fn written(
    document: &Element,
    stored: Representation,
    accept: Option<&str>,
    max_depth: Option<i32>,
) -> Option<(Vec<u8>, String)> {
    let wanted = wanted_representation(stored, accept);
    // No `maxDepth` bounds no depth, so the whole document is kept — up to the nesting
    // this operation reads at all.
    let keep = kept_depth(max_depth).unwrap_or(u32::MAX);
    let document = bounded(document, keep, DOCUMENT_NESTING_LIMIT)?;
    Some((
        encoded(&document, wanted)?,
        wanted.media_type().to_string(),
    ))
}

