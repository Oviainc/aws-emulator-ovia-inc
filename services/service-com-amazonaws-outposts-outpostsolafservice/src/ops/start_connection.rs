impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for StartConnection<Eng>
{
    type Input = StartConnectionInput;
    type Output = StartConnectionOutput;
    type Error = StartConnectionError;

    const NAME: &'static str = "StartConnection";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::START_CONNECTION_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::START_CONNECTION_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            StartConnectionErrorModeled::InternalServerException(InternalServerException {
                message: Some("the Outposts store is unavailable".to_string()),
            })
        })?;
        // The region this request is addressed to: the hardware a connection is
        // started for belongs to an Outpost of its own region, and the connection
        // the start mints belongs to that same region.
        let region = crate::state::request_region(ctx.parts());

        let mut store = state.lock();
        // An Outpost's hardware is installed when an order placed on it has delivered
        // some, so the installation the clock has already made due is materialised
        // before the `AssetId` is resolved against it: the asset ids a caller read out
        // of `ListAssets` are the ones it can start a connection for.
        store.settle_outposts();
        // A connection installs one Outpost SERVER, named by the `AssetId` of that
        // unit of hardware, so the asset is resolved against the hardware the store
        // holds and WHAT that unit is decides whether there is a server to install:
        //
        // * an asset no Outpost of this store holds has no connection to start: the
        //   not-found error this call models, worded as every refusal about an asset
        //   this service holds none of is;
        // * one this store does hold that is not a server is hardware this call does
        //   not install, so the request naming it is the bad request this call models
        //   — the asset resolved, so it is not the not-found error — and no tunnel is
        //   minted for it.
        let installs_a_server = match store.asset_in_region(&region, &input.asset_id) {
            Some(asset) => crate::state::is_outpost_server(asset),
            None => {
                return Err(StartConnectionErrorModeled::NotFoundException(NotFoundException {
                    message: Some(crate::state::asset_not_found(&input.asset_id)),
                })
                .into())
            }
        };
        if !installs_a_server {
            return Err(StartConnectionErrorModeled::ValidationException(ValidationException {
                message: Some(crate::state::connection_asset_report()),
            })
            .into());
        }
        // See `MAX_RESOURCES`: a connection is never released while the Outpost whose
        // hardware it installs is held (`GetConnection` must still answer what this
        // start minted), so the store this insert grows needs a maximum entry count.
        // `StartConnection` models no quota error, so past the cap the request is
        // refused as what it is from the caller's side — one this service will not
        // accept (400 `ValidationException`) — exactly as `CreateQuote` and
        // `CreateRenewal` report their own ceilings, and never as a server fault a
        // client would retry a call that can only fail again.
        if store.connections.len() >= crate::state::MAX_RESOURCES {
            return Err(StartConnectionErrorModeled::ValidationException(
                ValidationException {
                    message: Some(crate::state::store_full("connections")),
                },
            )
            .into());
        }

        let (connection_id, sequence) = store.mint_connection_id();
        let server_public_key = store.server_public_key();
        // The client end's key is the caller's own, stored as sent, so every read of
        // the connection answers the key this call was started with.
        let details = crate::state::connection_details(
            sequence,
            input.client_public_key,
            server_public_key,
        );
        let underlay_ip_address = crate::state::underlay_ip_address(sequence);
        // Nothing in this API models a second start as a conflict, and a device that
        // re-registers brings a new client key, so each call mints its OWN
        // connection: the earlier one stays readable under the id it was given.
        store.connections.insert(
            connection_id.clone(),
            crate::state::ConnectionRecord {
                sequence,
                region,
                connection_id: connection_id.clone(),
                asset_id: input.asset_id,
                device_serial_number: crate::state::non_empty(input.device_serial_number),
                network_interface_device_index: input.network_interface_device_index,
                underlay_ip_address: underlay_ip_address.clone(),
                details,
            },
        );

        Ok(StartConnectionOutput {
            connection_id: Some(connection_id),
            underlay_ip_address: Some(underlay_ip_address),
        })
    }
}
